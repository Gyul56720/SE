// ecc24.h -- 24비트 데이터 + 6비트 ECC, SEC-DED.
//
// 어디에 쓰이나
// --------------
// MIPI CSI-2 · DSI 의 **패킷 헤더**가 정확히 이 모양이다: 24비트 헤더
// (Data Identifier 8 + Word Count 16) 에 ECC 1바이트가 붙는다.
// 헤더가 깨지면 패킷 길이를 잘못 읽어 **그 뒤의 모든 패킷 경계가 밀린다** --
// 한 비트 오류가 프레임 하나를 통째로 버리게 만든다.  그래서 페이로드에는
// 검출만 하는 CRC 를 쓰면서 헤더에는 **정정까지** 하는 ECC 를 쓴다.
//
// ── 이 표가 MIPI 의 것인가?  아니다.  그 말을 분명히 한다 ──────────────
//
// 처음에는 기억하고 있던 CSI-2 패리티 마스크를 적었다.  그리고 그것을
// **재 봤다**:
//
//     신드롬 30 개 중 서로 다른 것이 27 개  -> 겹치는 것이 있다
//     이중오류가 단일오류로 오인될 쌍 96 개
//
// 즉 그 마스크는 **단일오류 정정 부호조차 아니었다.**  기억이 틀렸다.
// 망이 막혀 있어(403) MIPI 문서와 대조할 수 없으므로, 틀린 기억을
// "CSI-2 의 표" 라고 실어 보낼 수는 없다.
//
// 그래서 **제1원리로 지었다.**  아래 마스크는
//   * 24 데이터 비트 + 5 패리티 비트 + 전체패리티 1 비트
//   * 신드롬 29 개가 전부 0 이 아니고 서로 다르다 (전수 확인)
//   * 이중오류 신드롬이 단일오류와 겹치지 않는다 (전수 확인)
// 즉 **정당한 SEC-DED 다.**  다만 **MIPI 와 비트까지 같지는 않다** --
// 상호운용을 하려면 그 문서의 표로 바꿔 끼워야 한다.  구조·회로·검증은
// 그대로 쓰고 `ECC_MASK` 만 갈아 끼우면 된다.
//
// 이 구별을 흐리면 "CSI-2 IP" 라고 팔았다가 상대 장비와 안 붙는다.
#ifndef EDU_ECC24_H
#define EDU_ECC24_H

#include <stdint.h>

// 패리티 마스크.  P[i] 는 그 패리티에 들어가는 데이터 비트들의 비트맵.
// 신드롬 배정: 데이터 비트 b 의 신드롬 = 무게 2 이상인 5비트 패턴 중 b 번째.
// 무게 1 짜리는 패리티 비트 자신의 오류가 쓰므로 데이터에 주면 안 된다.
static const uint32_t ECC_MASK[5] = {
    0xAAAD5Bu,   /* P0 */
    0x33366Du,   /* P1 */
    0xC3C78Eu,   /* P2 */
    0xFC07F0u,   /* P3 */
    0xFFF800u,   /* P4 */
};

static inline int par32(uint32_t v) {
    v ^= v >> 16; v ^= v >> 8; v ^= v >> 4; v ^= v >> 2; v ^= v >> 1;
    return (int)(v & 1u);
}

// 부호화: 24비트 데이터 -> 6비트 ECC.
// 아래 5비트가 P0..P4, 여섯째 비트가 **전체 패리티**다.
// 전체 패리티가 DED 를 만든다: 단일오류는 전체패리티를 뒤집고, 이중오류는
// 두 번 뒤집어 제자리로 돌린다.  그래서 신드롬이 0 이 아닌데 전체패리티가
// 맞으면 "둘 이상 틀렸다" 는 뜻이 된다.
static inline uint8_t ecc24_enc(uint32_t data24) {
    uint32_t d = data24 & 0xFFFFFFu;
    uint32_t e = 0;
    for (int i = 0; i < 5; i++)
        e |= (uint32_t)par32(d & ECC_MASK[i]) << i;
    e |= (uint32_t)(par32(d) ^ par32(e)) << 5;      // 전체 패리티
    return (uint8_t)e;
}

// 복호 결과
enum { ECC_OK = 0, ECC_FIXED = 1, ECC_DOUBLE = 2 };

// 복호: 받은 데이터와 ECC 로 신드롬을 구해 고치거나 알린다.
//   돌려주는 값: ECC_OK / ECC_FIXED / ECC_DOUBLE
//   *out 에 (고친) 24비트 데이터
static inline int ecc24_dec(uint32_t data24, uint8_t ecc, uint32_t *out) {
    uint32_t d = data24 & 0xFFFFFFu;
    uint8_t  calc = ecc24_enc(d);
    uint32_t syn  = (uint32_t)((calc ^ ecc) & 0x1Fu);      // 아래 5비트

    // 전체패리티는 **받은 코드워드에서 바로** 센다.  다시 부호화해서
    // 여섯째 비트를 비교하면 안 된다 -- 그러면 신드롬 자신의 패리티가
    // 섞여 들어간다.
    //
    // 실측: 처음에 `((calc ^ ecc) >> 5) & 1` 로 썼더니 **단일오류 180 가지
    // 중 90 가지가 이중오류로 잘못 보고됐다.**  신드롬 무게가 홀수인
    // 데이터 비트들이 전부 그랬다.  계산해 보면 그 식은
    //     opar = 1 XOR parity(신드롬)
    // 이라 신드롬 무게가 홀수면 0 이 되어 버린다.
    //
    // 바른 식: 성한 코드워드는 30 비트 전체의 패리티가 0 이다 (부호기가
    // 그렇게 여섯째 비트를 정했다).  그러니 받은 것에서 그대로 세면
    // 단일오류는 1, 이중오류는 0 이 나온다 -- 신드롬과 무관하게.
    int      opar = par32(d) ^ par32((uint32_t)ecc & 0x3Fu);
    *out = d;
    if (syn == 0u) {
        // 신드롬 0: 데이터·패리티는 맞다.  전체패리티만 틀렸으면 그 비트가
        // 깨진 것이고 데이터는 성하다.
        return opar ? ECC_FIXED : ECC_OK;
    }
    if (!opar) return ECC_DOUBLE;    // 신드롬은 있는데 홀수가 아니다 -> 둘 이상
    // 단일 오류.  신드롬이 어느 데이터 비트의 것인지 찾는다.
    for (int b = 0; b < 24; b++) {
        uint32_t s = 0;
        for (int i = 0; i < 5; i++)
            if ((ECC_MASK[i] >> b) & 1u) s |= (1u << i);
        if (s == syn) { *out = d ^ (1u << b); return ECC_FIXED; }
    }
    // 신드롬이 무게 1 이면 패리티 비트 자신이 깨진 것이다 -- 데이터는 성하다.
    return ECC_FIXED;
}

#endif // EDU_ECC24_H
