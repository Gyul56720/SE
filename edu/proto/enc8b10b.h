// enc8b10b.h -- 8b/10b 부호기·복호기.
//
// 어디에 쓰이나
// --------------
//   PCIe Gen1 (2.5 GT/s) · Gen2 (5 GT/s)      물리층 부호
//   1000BASE-X (기가비트 이더넷 PCS)           IEEE 802.3 Clause 36
//   SATA · DisplayPort · Fibre Channel · USB3 Gen1
//
// 한 블록이 **두 시장**에 걸친다.  1인 디자인 하우스에서 이것은 큰 뜻이다 --
// 같은 IP 를 PCIe 하는 곳에도, 이더넷 하는 곳에도 팔 수 있다.
//
// 무엇을 하는 부호인가 -- 네 가지를 동시에 준다
// -----------------------------------------------
//   1. **DC 균형**.  0 과 1 의 개수를 맞춰 준다.  AC 결합된 링크(커패시터가
//      직렬로 들어간 링크)는 DC 를 못 지나가므로, 0 이 길게 이어지면 기준선이
//      흘러간다(baseline wander).  running disparity 를 +-1 안에 가둬 막는다.
//   2. **전이 보장**.  연속된 같은 비트가 5개를 못 넘는다.  CDR(클럭 복원)이
//      전이를 보고 위상을 잡으므로, 전이가 없으면 클럭을 잃는다.
//   3. **제어 부호**.  데이터로는 못 나오는 코드워드(K 코드)를 따로 둔다.
//      그래서 프레임 경계를 데이터와 헷갈리지 않고 표시할 수 있다.
//   4. **오류 검출**.  1024 개 코드워드 중 유효한 것은 일부뿐이라, 비트가
//      뒤집히면 대개 무효 코드워드가 되어 바로 잡힌다.
//
// 대가는 **20 % 대역폭**이다.  8비트를 10비트로 보내므로 PCIe Gen1 의
// 2.5 GT/s 가 실제로는 2.0 Gb/s 다.  Gen3 이 128b/130b 로 바꾼 이유가
// 이것이고, 그 이야기는 Z23 에 있다.
//
// ── 이 파일의 표를 어디까지 믿을 수 있나 ──────────────────────────────
// **정규 표는 IEEE 802.3 Clause 36 Table 36-1/36-2 에 있고, 이 컨테이너는
// 망이 막혀 있어 대조하지 못했다.**  그래서 두 가지를 갈라 말한다.
//
//   (a) **여기서 증명한 것** -- `proto_check.cpp` 가 전수로 확인한다:
//       전단사 · running disparity 가 +-1 을 안 벗어남 · 연속 비트 5 이하 ·
//       콤마의 유일성.  이것들은 이 부호의 **설계 목표 그 자체**이므로,
//       표에 오타가 있으면 거의 반드시 하나가 깨진다.
//   (b) **여기서 증명하지 못한 것** -- 정규 표와 **바이트까지 같은가**.
//       (a)를 다 통과해도 표준과 다른 (그러나 자기모순 없는) 부호일 수 있다.
//       상호운용을 말하려면 표준 문서나 상대 구현과 대조해야 한다.
//
// 이 구별을 흐리지 않는 것이 이 저장소의 규율이다.  `출처.jsonl` 에
// 확인수준을 적어 두었다.
#ifndef EDU_ENC8B10B_H
#define EDU_ENC8B10B_H

#include <stdint.h>

// ---------------------------------------------------------------------------
// 표를 **절반만** 적는다 -- 오타가 날 자리를 절반으로 줄인다
// ---------------------------------------------------------------------------
// 각 코드워드의 불균형(disparity)은 (1의 개수) - (0의 개수) 다.
//   6비트 코드: 불균형이 -2 · 0 · +2 중 하나
//   4비트 코드: 같음
//
// 불균형이 0 이면 코드워드가 **하나**다 (RD 가 어느 쪽이든 같은 것을 쓴다).
// 불균형이 +-2 이면 **짝**이 있고, 둘은 서로의 보수(complement)다.
//
// 그래서 RD = -1 일 때 쓰는 코드워드만 적고, RD = +1 쪽은 **계산한다**:
//   불균형 0  -> 같은 것
//   불균형 +2 -> 보수 (그래야 RD 가 다시 -1 로 돌아온다)
//
// 표를 두 벌 적으면 한쪽만 고치는 사고가 난다.  한 벌만 적고 나머지를
// 규칙으로 만들면 **그 사고가 불가능해진다.**

// 5b/6b: RD=-1 에서 쓰는 6비트 코드워드.  비트 순서는 abcdei (a 가 MSB).
// 6비트 쪽도 **두 벌을 적는다.**  대부분은 "불균형 0 이면 같은 것, 아니면
// 보수" 규칙대로인데 **D.07 하나가 예외다**: 111000 / 000111 로, 둘 다
// 불균형 0 인데 서로 다르다.
//
// 이것도 짐작이 아니라 검사가 짚었다.  D.07 을 한 벌로 두었더니
// D7.7 이 RD=+1 에서 111000|0001 = 1110000001 -- **0 이 여섯 개**가 되어
// P3 이 556 군데에서 깨졌다.  000111|0001 이면 최장 3 이다.
static const uint8_t T5B6B_M[32] = {   /* RD = -1 에서 */
    /* D.00 */ 0x27,  /* D.01 */ 0x1D,  /* D.02 */ 0x2D,  /* D.03 */ 0x31,
    /* D.04 */ 0x35,  /* D.05 */ 0x29,  /* D.06 */ 0x19,  /* D.07 */ 0x38,
    /* D.08 */ 0x39,  /* D.09 */ 0x25,  /* D.10 */ 0x15,  /* D.11 */ 0x34,
    /* D.12 */ 0x0D,  /* D.13 */ 0x2C,  /* D.14 */ 0x1C,  /* D.15 */ 0x17,
    /* D.16 */ 0x1B,  /* D.17 */ 0x23,  /* D.18 */ 0x13,  /* D.19 */ 0x32,
    /* D.20 */ 0x0B,  /* D.21 */ 0x2A,  /* D.22 */ 0x1A,  /* D.23 */ 0x3A,
    /* D.24 */ 0x33,  /* D.25 */ 0x26,  /* D.26 */ 0x16,  /* D.27 */ 0x36,
    /* D.28 */ 0x0E,  /* D.29 */ 0x2E,  /* D.30 */ 0x1E,  /* D.31 */ 0x2B,
};
static const uint8_t T5B6B_P[32] = {   /* RD = +1 에서 */
    /* D.00 */ 0x18,  /* D.01 */ 0x22,  /* D.02 */ 0x12,  /* D.03 */ 0x31,
    /* D.04 */ 0x0A,  /* D.05 */ 0x29,  /* D.06 */ 0x19,  /* D.07 */ 0x07,
    /* D.08 */ 0x06,  /* D.09 */ 0x25,  /* D.10 */ 0x15,  /* D.11 */ 0x34,
    /* D.12 */ 0x0D,  /* D.13 */ 0x2C,  /* D.14 */ 0x1C,  /* D.15 */ 0x28,
    /* D.16 */ 0x24,  /* D.17 */ 0x23,  /* D.18 */ 0x13,  /* D.19 */ 0x32,
    /* D.20 */ 0x0B,  /* D.21 */ 0x2A,  /* D.22 */ 0x1A,  /* D.23 */ 0x05,
    /* D.24 */ 0x0C,  /* D.25 */ 0x26,  /* D.26 */ 0x16,  /* D.27 */ 0x09,
    /* D.28 */ 0x0E,  /* D.29 */ 0x11,  /* D.30 */ 0x21,  /* D.31 */ 0x14,
};

// ── 3b/4b 는 **두 벌을 다 적는다.**  압축하면 틀린다 ──────────────────
//
// 처음에는 여기도 한 벌만 적고 "불균형이 0 이면 같은 코드, 아니면 보수"
// 라는 규칙으로 나머지를 만들었다.  **틀렸다.**  4비트 쪽에는 불균형이
// 둘 다 0 인데 **서로 다른** 짝이 있다:
//
//     D.x.1   1001 / 0110      둘 다 불균형 0 인데 다르다
//     D.x.2   0101 / 1010
//     D.x.3   1100 / 0011
//     D.x.5   1010 / 0101
//     D.x.6   0110 / 1001
//
// 불균형이 같은데 왜 갈라 쓰나 -- **연속 비트 때문이다.**  앞의 6비트
// 코드가 1111 로 끝나는데 뒤에 1100 이 붙으면 1 이 여섯 개 이어진다.
// 0011 을 쓰면 안 그렇다.  즉 이 선택은 DC 균형이 아니라 **CDR 를 위한
// 전이 보장**이 정한다.
//
// 이것을 짐작으로 안 것이 아니다.  압축한 판으로 `proto_check.cpp` 를
// 돌렸더니 **P3(연속 5 이하)가 1082 군데에서, P4(콤마 유일)가 2048 번
// 깨졌다.**  예로 D0.0 다음에 K28.3 이 오면 0011111100 -- 1 이 여섯이다.
//
// 교훈: **표를 압축하는 규칙은 그 자체가 가설이다.**  검사 없이 압축하면
// 오타를 줄이는 대신 더 나쁜 것(틀린 구조)을 얻는다.
static const uint8_t T3B4B_M[8] = {   /* RD = -1 에서 */
    /* D.x.0 */ 0x0B, /* D.x.1 */ 0x09, /* D.x.2 */ 0x05, /* D.x.3 */ 0x0C,
    /* D.x.4 */ 0x0D, /* D.x.5 */ 0x0A, /* D.x.6 */ 0x06, /* D.x.7 */ 0x0E,
};
static const uint8_t T3B4B_P[8] = {   /* RD = +1 에서 */
    /* D.x.0 */ 0x04, /* D.x.1 */ 0x06, /* D.x.2 */ 0x0A, /* D.x.3 */ 0x03,
    /* D.x.4 */ 0x02, /* D.x.5 */ 0x05, /* D.x.6 */ 0x09, /* D.x.7 */ 0x01,
};

// D.x.A7 -- **대체** 3b/4b 부호.  주 부호(D.x.7)를 쓰면 연속 비트가
// 5 를 넘는 자리에서만 이것으로 바꾼다.
static const uint8_t T3B4B_ALT7_M = 0x07;  /* 0111, RD=-1 */
static const uint8_t T3B4B_ALT7_P = 0x08;  /* 1000, RD=+1 */

// K.28 의 5b/6b: 001111 (RD-) / 110000 (RD+).  불균형 +-2 라 보수 관계다.
// 여기에 콤마(0011111 / 1100000)가 들어 있고, 그 무늬는 어떤 데이터
// 코드워드 이음에도 안 나타난다 -- 그래서 바이트 정렬의 기준이 된다.
static const uint8_t K28_5B6B = 0x0F;      /* 001111 */

// K 코드의 3b/4b.  데이터용과 **다르다**.  여기도 두 벌을 다 적는다.
static const uint8_t T3B4B_K_M[8] = {  /* RD = -1 에서 */
    /* K.x.0 */ 0x0B, /* K.x.1 */ 0x06, /* K.x.2 */ 0x0A, /* K.x.3 */ 0x0C,
    /* K.x.4 */ 0x0D, /* K.x.5 */ 0x05, /* K.x.6 */ 0x09, /* K.x.7 */ 0x07,
};
static const uint8_t T3B4B_K_P[8] = {  /* RD = +1 에서 */
    /* K.x.0 */ 0x04, /* K.x.1 */ 0x09, /* K.x.2 */ 0x05, /* K.x.3 */ 0x03,
    /* K.x.4 */ 0x02, /* K.x.5 */ 0x0A, /* K.x.6 */ 0x06, /* K.x.7 */ 0x08,
};

// ---------------------------------------------------------------------------
// 작은 도구들
// ---------------------------------------------------------------------------
static inline int popcnt(uint32_t v) {
    int n = 0;
    while (v) { n += (int)(v & 1u); v >>= 1; }
    return n;
}

// n비트 코드워드의 불균형.  (1의 개수) - (0의 개수).
static inline int disp_of(uint32_t code, int n) {
    return 2 * popcnt(code) - n;
}

// n비트 안에서 보수를 취한다.
static inline uint32_t compl_n(uint32_t code, int n) {
    return (~code) & ((1u << n) - 1u);
}

// 6비트 쪽도 표를 그대로 고른다.  4비트 쪽과 같은 이유다.
static inline uint32_t pick6(uint32_t em, uint32_t ep, int rd, int *rd_out) {
    uint32_t c = (rd < 0) ? em : ep;
    *rd_out = rd + disp_of(c, 6);
    return c;
}

// 4비트 쪽: **표를 그대로 고른다.**  보수로 만들지 않는다 (위 설명 참고).
static inline uint32_t pick4(uint32_t em, uint32_t ep, int rd, int *rd_out) {
    uint32_t c = (rd < 0) ? em : ep;
    *rd_out = rd + disp_of(c, 4);
    return c;
}

// ---------------------------------------------------------------------------
// 부호기
// ---------------------------------------------------------------------------
// 입력: 8비트 데이터 + K 표시 + 현재 RD (-1 또는 +1)
// 출력: 10비트 코드워드, 그리고 새 RD
//
// 비트 배치: abcdei fghj  (a 가 먼저 전송된다)
// 우리는 [9:0] 에서 a 를 bit9 에 둔다.  **전송 순서는 RTL 의 시프트
// 방향에서 정해지고, 여기서 정하는 것은 값뿐이다.**
//
// 돌려주는 값은 **성공 여부(1/0)** 이고 새 RD 는 `rd_out` 으로 나간다.
//
// 첫 판은 "새 RD 를 돌려주고 오류면 -1" 이었다.  그런데 **새 RD 가
// 정당하게 -1 일 수 있다.**  그래서 부르는 쪽이 성한 결과를 오류로 읽고
// 코드워드 절반(528 중 264)을 버렸다 -- 그리고 그 절반만 가지고 잰
// 연속비트·콤마 결과가 빨간불로 나왔다.  `proto_check.cpp` 가 첫 실행에서
// 이것을 잡았다.
//
// **정당한 값을 오류 코드로 쓰면 안 된다.**  이 저장소가 `pr_merged.sh`
// 에서 '모르겠다' 를 따로 둔 것과 같은 이유다.
static inline int enc8b10b(uint8_t data, int is_k, int rd_in,
                           uint32_t *code_out, int *rd_out) {
    uint32_t lo5 = data & 0x1Fu;          // EDCBA
    uint32_t hi3 = (data >> 5) & 0x07u;   // HGF
    int rd = rd_in;
    uint32_t six, four;

    if (is_k) {
        // 이 모델이 다루는 K 코드는 K.28.x 뿐이다.
        // K.23.7 · K.27.7 · K.29.7 · K.30.7 은 5b/6b 를 데이터 표에서
        // 가져오는데, 그 넷은 이 블록의 쓰임(정렬·프레임 표시)에 필요
        // 없으므로 **일부러 뺐다.**  빠진 것을 빠졌다고 적는다.
        if (lo5 != 28u) return 0;          // K.28.x 가 아니다
        six = pick6(K28_5B6B, 0x30u, rd, &rd);   /* 001111 / 110000 */
        four = pick4(T3B4B_K_M[hi3], T3B4B_K_P[hi3], rd, &rd);
    } else {
        six = pick6(T5B6B_M[lo5], T5B6B_P[lo5], rd, &rd);
        // 대체 부호 규칙.  D.x.7 에서만, 그리고 연속 비트가 5를 넘을
        // 자리에서만 0111 을 쓴다.
        //   RD 가 -1 로 들어와 6비트가 끝나고도 -1 이면서 lo5 가 17·18·20
        //   RD 가 +1 로 들어와 6비트가 끝나고도 +1 이면서 lo5 가 11·13·14
        // 이 조건이 왜 이 다섯 값인지는 Z23 에서 **재서** 보인다.
        uint32_t m = T3B4B_M[hi3], pp = T3B4B_P[hi3];
        if (hi3 == 7u) {
            int use_alt = 0;
            if (rd < 0 && (lo5 == 17u || lo5 == 18u || lo5 == 20u)) use_alt = 1;
            if (rd > 0 && (lo5 == 11u || lo5 == 13u || lo5 == 14u)) use_alt = 1;
            if (use_alt) { m = T3B4B_ALT7_M; pp = T3B4B_ALT7_P; }
        }
        four = pick4(m, pp, rd, &rd);
    }
    *code_out = (six << 4) | four;
    *rd_out = rd;
    return 1;
}

#endif // EDU_ENC8B10B_H
