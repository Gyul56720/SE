"""스트리밍 CRC-32 블록.  골든모델은 파이썬 zlib 이다.

이 블록이 앞의 조합 블록들과 다른 점:
  * **순차**다 -- 클럭·리셋·핸드셰이크가 있다
  * 비교가 **트랜잭션 수준**이다.  테스트벤치가 무작위 back-pressure 를 걸므로
    사이클 타이밍은 매번 다르지만, 나오는 CRC 의 **순서와 값**은 같아야 한다.
    실제 DV 가 이렇게 한다 -- 사이클 정확 비교는 타이밍을 바꿀 수 없게 만든다.
  * 자극이 **패킷 길이를 섞는다**.  길이 1 (한 바이트에 last) 과 긴 패킷이
    같은 시험에 들어가야 경계 논리가 걸린다.
"""
import os, random, zlib

여기 = os.path.dirname(os.path.abspath(__file__))
이름 = "crc32_stream"
톱 = "tb"

# 합성·lint 는 **DUT 만** 본다.  테스트벤치를 같이 넣으면 $fopen 때문에
# yosys 가 실패하고 verilator 가 경고를 쏟는다 -- 그것은 블록의 품질이 아니다.
합성톱 = "crc32_stream"


def 소스들():
    """[0] 이 DUT 다 -- 수리와 변이는 이 파일만 건드린다.

    파일 이름이 모듈 이름과 같다.  `verilator -Wall` 의
    DECLFILENAME 이 이것을 요구하고, 그것이 업계 관례다 --
    한 파일에 한 모듈, 파일 이름은 모듈 이름.
    """
    return [os.path.join(여기, "crc32_stream.v"), os.path.join(여기, "tb.v")]


def 자극(시행, 씨앗):
    """시행 = 대략적인 바이트 수.  패킷으로 잘라서 낸다."""
    r = random.Random(씨앗)
    줄들 = [str(r.randrange(1, 1 << 31))]      # 첫 줄은 back-pressure 씨앗
    골든 = []
    남은 = max(8, 시행)
    # 경계 길이를 먼저 넣는다 -- 무작위는 길이 1 을 거의 안 낸다
    길이들 = [1, 1, 2, 3, 4, 8, 64]
    while sum(길이들) < 남은:
        길이들.append(r.choice([1, 2, 3, 4, 5, 16, 64, 128]))
    for L in 길이들:
        payload = bytes(r.randrange(256) for _ in range(L))
        for i, b in enumerate(payload):
            줄들.append(f"{b:02x} {1 if i == L - 1 else 0}")
        골든.append(zlib.crc32(payload) & 0xFFFFFFFF)
    return 줄들, 골든


def 성능한계(입력줄수):
    """이 블록이 허용하는 최대 사이클 수.

    값만 보는 회귀는 **느려지는 결함을 못 잡는다**.  실측 2026-09-19: 변이 점수가
    `s_ready = ~(m_valid & ~m_ready)` 를 `|` 로 바꾼 변이를 **못 잡았다** --
    나오는 CRC 는 전부 맞고 처리량만 떨어진다.  그래서 처리량도 잰다.

    **한계는 재서 정했다.**  테스트벤치가 무작위로 입력 공백과 출력 back-pressure
    를 넣으므로 이상적인 바이트당 1 사이클은 나올 수 없다.  씨앗 1 · 7 · 99 에서:

        성한 것   2.18 · 2.16 · 2.18  사이클/바이트
        변이      3.16 · 3.14 · 3.20  사이클/바이트  (1.45 배)

    성한 쪽 흩어짐이 1 % 안쪽이므로 **2.6 사이클/바이트** 로 둔다 -- 성한 것에
    20 % 여유를 주고 변이는 걸린다.  한계를 어림으로 5 로 잡았을 때는 변이가
    그대로 통과했다(그래서 재서 다시 정했다).

    고정 항 200 은 리셋·배수·마지막 배출에 드는 사이클이다.
    """
    바이트 = max(1, 입력줄수 - 1)          # 첫 줄은 back-pressure 씨앗이다
    return int(바이트 * 2.6) + 200


