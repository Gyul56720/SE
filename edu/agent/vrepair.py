def _디유티구역(원문):
    """테스트벤치가 아닌 줄의 인덱스 집합.

    실측 2026-09-19: 변이 점수를 처음 돌렸더니 **테스트벤치의 LFSR** 과 **주석**
    까지 변이시키고 있었다.  둘 다 영원히 안 잡히므로 점수를 끌어내리고, 사람이
    봐야 할 진짜 탈출을 그 속에 묻는다.

      * 테스트벤치를 고치는 것은 수리가 아니다 -- 검사를 고쳐 초록을 만드는 것이다
      * 주석을 바꾼 변이는 **정의상 등가**다

    `module tb` 부터 그 `endmodule` 까지를 뺀다.  이름이 tb 가 아닌 테스트벤치는
    블록이 `디유티모듈` 로 알려 줄 수 있다.
    """
    줄들 = 원문.split("\n")
    쓸것 = set(range(len(줄들)))
    깊이 = 0
    tb중 = False
    for i, l in enumerate(줄들):
        s = l.strip()
        if _re.match(r"^module\s+tb\b", s):
            tb중 = True
        if tb중:
            쓸것.discard(i)
            if _re.match(r"^endmodule\b", s):
                tb중 = False
    return 쓸것


def 후보들(원문, 최대=400, 디유티만=True):
    """한 곳만 바꾼 편집들을 낸다.  두 곳 이상은 내지 않는다 -- 탐색이 터지고,
    실제 버그도 대개 한 곳이다.

    주석 안과 테스트벤치 안은 건드리지 않는다 (`_디유티구역` 설명 참고).
    """
    낸것 = []
    줄들 = 원문.split("\n")
    구역 = _디유티구역(원문) if 디유티만 else set(range(len(줄들)))
    for 이름, pat, rep, 왜 in 규칙:
        for li, 줄 in enumerate(줄들):
            if li not in 구역:
                continue
            if 줄.strip().startswith("//"):
                continue
            # 줄 끝 주석은 변이 대상에서 뺀다 (문자열 리터럴 안의 // 는 이 저장소의
            # Verilog 에 없으므로 단순 절단으로 충분하다)
            끝 = 줄.find("//")
            코드끝 = len(줄) if 끝 < 0 else 끝
            for m in _re.finditer(pat, 줄[:코드끝]):
                새줄 = 줄[:m.start()] + rep + 줄[m.end():]
                if 새줄 == 줄:
                    continue
                새 = list(줄들)
                새[li] = 새줄
                낸것.append({
                    "규칙": 이름, "왜": 왜, "줄번호": li + 1,
                    "전": 줄.strip(), "후": 새줄.strip(),
                    "원문": "\n".join(새)})
                if len(낸것) >= 최대:
                    return 낸것
    return 낸것


class 임시블록:
    """블록 모듈을 감싸, 소스들() 이 수정된 파일을 가리키게 한다."""

    def __init__(self, 블록, 파일, 새내용):
        self.블록, self.파일 = 블록, 파일
        self.이름, self.톱 = 블록.이름, 블록.톱
        self.자극 = 블록.자극
        self.디렉 = tempfile.mkdtemp(prefix="rep_")
        self.새경로 = os.path.join(self.디렉, os.path.basename(파일))
        open(self.새경로, "w", encoding="utf-8").write(새내용)
        self._소스 = [self.새경로 if p == 파일 else p for p in 블록.소스들()]

    def 소스들(self):
        return list(self._소스)

    def __getattr__(self, 이름):
        """감싼 블록의 나머지 속성을 그대로 넘긴다.

        실측 2026-09-19: 처음에는 이름·톱·자극만 베껴 왔는데, 블록이 나중에
        `성능한계` 를 추가하자 **변이에는 그것이 안 붙어서 성능 검사가 조용히
        꺼졌다** -- 느려지는 변이가 통과했고 원인이 보이지 않았다.  명시적으로
        베끼는 방식은 이렇게 조용히 낡는다.
        """
        return getattr(self.블록, 이름)

    def 닫기(self):
        shutil.rmtree(self.디렉, ignore_errors=True)


def 고쳐보기(블록, harness, 씨앗, 검증씨앗, 시행=600, 최대후보=400,
            후보시간제한=10, 기록=None):
    """수리를 시도한다.  돌려주는 것은 **받아들인 편집** 또는 None.

    부작용은 없다 -- 파일을 쓰지 않는다.  적용은 부르는 쪽이 결정한다.
    """
    파일 = 블록.소스들()[0]
    원문 = open(파일, encoding="utf-8").read()
    cands = 후보들(원문, 최대후보)
    본것 = 0
    셈 = {"컴파일실패": 0, "여전히틀림": 0, "자극이무의미": 0,
          "과적합거부": 0, "하니스가안뭄": 0, "멈추지않음": 0}
    for c in cands:
        본것 += 1
        tb = 임시블록(블록, 파일, c["원문"])
        try:
            # 1) 싼 관문부터: 원래 씨앗에서 초록인가
            # 후보에는 **짧은 시간제한**을 준다.  편집 하나가 for 문의 증가를
            # 감소로 바꾸면 시뮬레이션이 영원히 돈다 -- 실측으로 한 후보가
            # 120 초를 먹었다.  고칠 수 있는 편집은 빨리 끝난다.
            r1 = harness.잰다(tb, 시행=시행, 씨앗=씨앗, 시간제한=후보시간제한)
            if r1.오류:
                셈["멈추지않음" if "시간초과" in r1.오류 else "컴파일실패"] += 1
                continue
            if not r1.쓸모있나:
                셈["자극이무의미"] += 1
                continue
            if r1.틀림:
                셈["여전히틀림"] += 1
                continue
            # 2) 과적합 관문: 한 번도 안 쓴 씨앗
            r2 = harness.잰다(tb, 시행=시행, 씨앗=검증씨앗, 시간제한=후보시간제한)
            if r2.오류 or not r2.쓸모있나 or r2.틀림:
                셈["과적합거부"] += 1
                continue
            # 3) 비교가 아직 무는가 -- 초록불을 믿기 전에 검사기를 검사한다
            ok, 왜 = harness.자해검사(tb, 시행=120, 씨앗=4242,
                                     시간제한=후보시간제한)
            if not ok:
                셈["하니스가안뭄"] += 1
                continue
            return dict({"규칙": c["규칙"], "왜": c["왜"], "줄번호": c["줄번호"],
                         "전": c["전"], "후": c["후"], "원문": c["원문"],
                         "본후보": 본것, "전체후보": len(cands)}, **셈)
        finally:
            tb.닫기()
    return dict({"실패": True, "본후보": 본것, "전체후보": len(cands)}, **셈)
