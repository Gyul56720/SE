"""Verilog 자동 수리 -- 후보를 **만들고, 돌려 보고, 과적합을 검사해서** 고른다.

## 왜 '고쳤다' 를 두 번 검사하나

자동 수리의 고전적 실패는 **실패한 그 자극만 통과하게 만드는 것**이다.  거기에
맞춘 편집은 회귀 전체로 보면 더 나쁠 수 있다.  그래서 후보 하나를 받으려면
세 관문을 다 통과해야 한다.

    1. 자해검사      비교가 아직 물고 있나 (골든을 망치면 걸리나)
    2. 원래 씨앗     실패하던 회귀가 초록인가
    3. **다른 씨앗** 한 번도 안 쓴 자극에서도 초록인가  <- 과적합 관문

3번이 없으면 "실패 사례를 특수처리하는 편집" 이 통과한다.  실측으로 그런 편집이
후보에 실제로 나온다 (상수를 실패한 입력값으로 박는 것).

## 무엇을 편집하나

문법을 아는 파서를 쓰지 않는다.  대신 **RTL 에서 실제로 틀리는 자리**의 목록을
가지고 그 자리만 건드린다.  목록은 이 저장소가 겪은 것과 표준적인 RTL 실수에서
왔고, 각 항목은 '왜 이것이 흔한가' 를 달고 있다.
"""
