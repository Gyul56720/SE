# 완성된 CMOS 회로 -- 장마다 손으로 배선하지 않게 여기서 한 번만 맞춘다
# ---------------------------------------------------------------------------
# 손으로 배선하면 전원선을 빠뜨린다.  실측: 이 파일을 처음 시험할 때 그린
# 인버터가 VDD 와 PMOS 소스가 **안 이어져 있었다**.  그림은 그럴듯했다.
# 회로도의 오류는 코드의 오류보다 알아채기 어렵다 -- 돌려볼 수가 없으므로.
# 그래서 배선을 함수 안에 가두고, 장에서는 부르기만 한다.

def 씨모스인버터():
    """CMOS 인버터 한 개.  풀업(PMOS) 하나 + 풀다운(NMOS) 하나.

    이것이 모든 CMOS 논리의 원형이다:
      * 입력이 0 이면  PMOS 가 켜지고 NMOS 가 꺼진다 -> 출력이 VDD 로 **당겨 올려진다**
      * 입력이 1 이면  PMOS 가 꺼지고 NMOS 가 켜진다 -> 출력이 GND 로 **당겨 내려진다**
    둘이 동시에 켜지는 일이 없으므로 **정상상태에서 전류가 흐르지 않는다.**
    CMOS 가 이겨서 살아남은 이유가 이 한 줄이다.

    좌표를 함수 안에 못박은 이유: 손으로 배선하면 전원선을 빠뜨린다.
    실측 -- 이 그림의 첫 판은 VDD 와 PMOS 소스가 **안 이어져 있었다.**
    그럴듯해 보였고, 회로도는 돌려볼 수가 없어서 눈으로만 걸린다.
    """
    기둥 = 176                      # PMOS·NMOS 의 드레인/소스가 서 있는 세로선
    o  = 전원(기둥, 30)
    o += 모스("PMOS", 150, 80)
    o += 모스("NMOS", 150, 170)
    o += 선((기둥, 38), (기둥, 62))          # VDD -> PMOS 소스
    o += 선((기둥, 98), (기둥, 152))         # PMOS 드레인 -> NMOS 드레인 (= 출력 마디)
    o += 선((기둥, 188), (기둥, 215))        # NMOS 소스 -> 접지
    o += 접지(기둥, 215)
    o += 선((150, 80), (110, 80), (110, 170), (150, 170))   # 게이트 둘을 묶는다
    o += 선((110, 125), (62, 125)) + 점(110, 125)
    o += 글(56, 129, "A", 맞춤="end", 굵게=True)
    o += 선((기둥, 125), (268, 125)) + 점(기둥, 125)
    o += 글(274, 129, "Y = NOT A", 굵게=True)
    o += 글(196, 84, "PMOS = 풀업", 크기=9.5, 색=빨)
    o += 글(196, 174, "NMOS = 풀다운", 크기=9.5, 색=초)
    o += 글(58, 252, "입력이 0 -> 위(PMOS)가 켜짐 -> Y 를 VDD 로 당겨 올린다", 크기=9.5, 색=회)
    o += 글(58, 265, "입력이 1 -> 아래(NMOS)가 켜짐 -> Y 를 GND 로 당겨 내린다", 크기=9.5, 색=회)
    o += 글(58, 278, "둘이 동시에 켜지지 않는다 -> 정상상태 전류가 0 이다", 크기=9.5, 색=회)
    return svg(420, 292, o, 뷰="40 8 380 284")


def 씨모스낸드():
    """2입력 CMOS NAND.  **풀업은 병렬, 풀다운은 직렬.**

    왜 그런가 -- 이것이 CMOS 논리의 전부다:
      * 풀다운(NMOS)은 출력을 0 으로 끌어내린다.  NAND 가 0 이 되는 조건은
        **A 와 B 가 둘 다 1** 이므로, NMOS 둘을 **직렬**로 놓는다 (둘 다
        켜져야 길이 이어진다 = AND).
      * 풀업(PMOS)은 그 여집합이어야 한다.  드모르간으로
        not(A and B) = (not A) or (not B) 이므로 PMOS 둘을 **병렬**로 놓는다.
    풀업 그물과 풀다운 그물은 언제나 서로의 **쌍대(dual)** 다.
    """
    PL, PR = 230, 350               # 두 PMOS 의 드레인/소스 기둥
    출 = 290                        # 출력 마디의 기둥
