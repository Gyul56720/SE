def 모스(종류, x, y, 라벨=""):
    """NMOS·PMOS 하나.  (x,y) 는 게이트 단자가 붙는 왼쪽 점이다.

    단자 좌표: 게이트=(x,y), 위=(x+26,y-18), 아래=(x+26,y+18)
      * NMOS 는 위가 드레인, 아래가 소스(접지 쪽)다
      * PMOS 는 위가 소스(전원 쪽), 아래가 드레인이고 게이트에 버블이 붙는다
    """
    p = 종류.upper() == "PMOS"
    o = 선((x, y), (x + 14 if not p else x + 10, y))
    if p:
        o += _버블(x + 14, y, 3.5)
    # 게이트 판
    o += 선((x + 18, y - 13), (x + 18, y + 13), 굵기=2.0)
    # 채널
    o += 선((x + 23, y - 13), (x + 23, y + 13), 굵기=2.0)
    # 드레인·소스 단자
    o += 선((x + 23, y - 11), (x + 26, y - 11), (x + 26, y - 18))
    o += 선((x + 23, y + 11), (x + 26, y + 11), (x + 26, y + 18))
    if 라벨:
        o += 글(x + 32, y + 4, 라벨, 크기=10, 색=회)
    return o


def 전원(x, y, 이름="VDD"):
    return (선((x, y), (x, y + 8), 색=빨) + 선((x - 9, y), (x + 9, y), 색=빨, 굵기=2.2)
            + 글(x, y - 5, 이름, 색=빨, 크기=10, 맞춤="middle"))


def 접지(x, y):
    o = 선((x, y), (x, y + 6), 색=초)
    for i, ww in enumerate((10, 6.5, 3)):
        o += 선((x - ww, y + 6 + i * 4), (x + ww, y + 6 + i * 4), 색=초, 굵기=2.0)
    return o


def 저항(x, y, h=30, 라벨=""):    # 라벨은 평문만 (위 _깨는태그 참고)
    """세로 저항.  (x,y) 가 위 단자, (x,y+h) 가 아래 단자다."""
    s, e = y + h * 0.2, y + h * 0.8
    zz = [(x, y), (x, s)]
    n, amp = 6, 6
    for i in range(n + 1):
        zz.append((x + (amp if i % 2 == 0 else -amp), s + (e - s) * i / n))
    zz += [(x, e), (x, y + h)]
    o = 선(*zz)
    if 라벨:
        o += 글(x + 12, y + h / 2 + 4, 라벨, 크기=10, 색=회)
    return o


