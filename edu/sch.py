"""sch.py -- 회로도·블록도·타이밍도를 SVG 로 그린다.

왜 이 파일이 있나
------------------
글로만 적은 회로는 읽는 사람 머릿속에서 저마다 다른 그림이 된다.  `edu/` 의
장들은 `bookE.fig()` 로 **날 SVG** 를 받으므로, 여기서 게이트·트랜지스터·
파형·블록을 그려 넣으면 책에 진짜 그림이 들어간다.

좌표 규약
---------
  * 화면 좌표다.  x 는 오른쪽, **y 는 아래쪽**이 크다 (수학과 반대).
  * 신호는 **왼쪽에서 오른쪽으로** 흐른다.  전원은 위, 접지는 아래.
  * 격자 단위는 10 px 로 잡았다.  게이트 하나가 대략 40x30 이다.

색 규약 -- 흑백 인쇄에서도 읽히게
----------------------------------
색으로만 구분하지 않는다.  선 굵기와 점선으로도 갈라 둔다.  색맹이거나
흑백으로 뽑아 보는 사람이 있고, 회로도는 그런 데서 더 많이 읽힌다.
"""

먹 = "#111"        # 본선
회 = "#888"        # 보조선·격자
빨 = "#c0392b"     # 전원 · 강조
파 = "#1f6feb"     # 클럭
초 = "#137333"     # 접지


def svg(w, h, 속, 뷰=None):
    """SVG 한 장을 감싼다.  `뷰` 를 주면 viewBox 를 따로 쓴다."""
    vb = 뷰 or f"0 0 {w} {h}"
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="{vb}" '
            f'width="100%" style="max-width:{w}px;height:auto" '
            f'font-family="ui-monospace,monospace" font-size="11">{속}</svg>')


def 선(*pts, 색=먹, 굵기=1.6, 점선=None):
    """꺾은선.  pts 는 (x,y) 쌍들."""
    d = " ".join(f"{'M' if i == 0 else 'L'}{x},{y}" for i, (x, y) in enumerate(pts))
    dash = f' stroke-dasharray="{점선}"' if 점선 else ""
    return f'<path d="{d}" fill="none" stroke="{색}" stroke-width="{굵기}"{dash}/>'


# HTML 파서가 SVG 안에서 보면 **SVG 를 끝내 버리는** 태그들.
# HTML5 명세의 "foreign content breakout" 목록이다.  <sub> 하나가 들어가면
# 그 뒤의 회로가 통째로 HTML 글자로 쏟아진다.
#
# 실측 2026-09-19: 저항 라벨에 "R<sub>pu</sub>" 라고 적었더니 그림의 **VDD 와
# 저항만 그려지고 트랜지스터·배선·나머지 라벨이 전부 사라졌다.**  브라우저가
# <sub> 에서 SVG 를 닫고 나머지를 본문 글자로 흘려 보냈기 때문이다.
# 오류도 경고도 없었다 -- 그림이 조용히 반쪽이 되었다.
_깨는태그 = ("b", "big", "blockquote", "body", "br", "center", "code", "dd", "div",
            "dl", "dt", "em", "embed", "h1", "h2", "h3", "h4", "h5", "h6", "head",
            "hr", "i", "img", "li", "listing", "menu", "meta", "nobr", "ol", "p",
            "pre", "ruby", "s", "small", "span", "strong", "strike", "sub", "sup",
            "table", "tt", "u", "ul", "var")


def 글(x, y, t, 색=먹, 크기=11, 맞춤="start", 굵게=False):
    import re as _re
    for _태그 in _깨는태그:
        if _re.search(rf"</?{_태그}[ />]", str(t)):
            raise ValueError(
                f"sch.글(): SVG 글자 안에 <{_태그}> 를 쓸 수 없다 -- HTML 파서가 "
                f"거기서 SVG 를 끝내고 뒤의 그림을 통째로 버린다.  글자 {t!r}. "
                f"아래첨자는 'R_pu' 처럼 평문으로 쓰거나 <tspan> 을 쓴다.")
    w = ' font-weight="bold"' if 굵게 else ""
    return (f'<text x="{x}" y="{y}" fill="{색}" font-size="{크기}" '
            f'text-anchor="{맞춤}"{w}>{t}</text>')


def 점(x, y, r=2.6, 색=먹):
    """접속점.  선이 만나는데 점이 없으면 **교차**이고, 점이 있으면 **연결**이다.
    이 구별을 빠뜨린 회로도는 읽을 수 없다."""
    return f'<circle cx="{x}" cy="{y}" r="{r}" fill="{색}"/>'


def 상자(x, y, w, h, 글자="", 색=먹, 채움="#fff", 점선=None):
    dash = f' stroke-dasharray="{점선}"' if 점선 else ""
    o = (f'<rect x="{x}" y="{y}" width="{w}" height="{h}" fill="{채움}" '
         f'stroke="{색}" stroke-width="1.6" rx="3"{dash}/>')
    if 글자:
        for i, ln in enumerate(글자.split("\n")):
            o += 글(x + w / 2, y + h / 2 + 4 + (i - (글자.count("\n")) / 2) * 13,
                    ln, 맞춤="middle")
    return o


