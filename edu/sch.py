def 파형(신호들, 폭=44, 높이=26, 간격=16, x0=70, y0=16, 눈금=True):
    """신호들 = [(이름, 패턴), ...].

    패턴 글자:  '_' 낮음 · '^' 높음 · 'x' 모름(엇갈림) · '=' 값 유지
    클럭은 이름에 'clk' 가 들어가면 파란색으로 그린다.
    """
    n = max(len(p) for _, p in 신호들)
    W = x0 + n * 폭 + 20
    H = y0 + len(신호들) * (높이 + 간격) + 10
    o = ""
    if 눈금:
        for i in range(n + 1):
            o += 선((x0 + i * 폭, y0 - 6), (x0 + i * 폭, H - 6), 색="#e3e3e3",
                    굵기=1, 점선="3,3")
    for r, (이름, 패턴) in enumerate(신호들):
        top = y0 + r * (높이 + 간격)
        bot = top + 높이
        색 = 파 if "clk" in 이름.lower() else 먹
        o += 글(x0 - 8, top + 높이 / 2 + 4, 이름, 맞춤="end", 크기=11)
        앞 = None
        for i, c in enumerate(패턴):
            x = x0 + i * 폭
            y = top if c == "^" else bot
            if c == "x":
                o += 선((x, top), (x + 폭, bot), 색=색, 굵기=1.3)
                o += 선((x, bot), (x + 폭, top), 색=색, 굵기=1.3)
                앞 = None
                continue
            if 앞 is not None and 앞 != y:
                o += 선((x, 앞), (x, y), 색=색)      # 모서리 (전이)
            o += 선((x, y), (x + 폭, y), 색=색)
            앞 = y
    return svg(W, H, o)


def 블록도(줄들, 칸=120, 높이=46, 간격=34, x0=10, y0=14, 설명=None):
    """가로로 이어지는 블록 사슬.  줄들 = [[이름, ...], ...] 이고 같은 줄은
    화살표로 이어진다.  `설명` 은 {이름: 아래에 적을 작은 글자}."""
    설명 = 설명 or {}
    n = max(len(r) for r in 줄들)
    W = x0 + n * (칸 + 간격) + 10
    H = y0 + len(줄들) * (높이 + 46) + 10
    o = ""
    for r, 줄 in enumerate(줄들):
        y = y0 + r * (높이 + 46)
        for i, 이름 in enumerate(줄):
            x = x0 + i * (칸 + 간격)
            o += 상자(x, y, 칸, 높이, 이름)
            note = 설명.get(이름)
            if note:
                for j, ln in enumerate(note.split("\n")):
                    o += 글(x + 칸 / 2, y + 높이 + 13 + j * 12, ln,
                            맞춤="middle", 크기=9.5, 색=회)
            if i + 1 < len(줄):
                xa, xb = x + 칸, x + 칸 + 간격
                o += 선((xa, y + 높이 / 2), (xb - 6, y + 높이 / 2))
                o += (f'<path d="M{xb-6},{y+높이/2-4} L{xb},{y+높이/2} '
                      f'L{xb-6},{y+높이/2+4} Z" fill="{먹}"/>')
    return svg(W, H, o)


