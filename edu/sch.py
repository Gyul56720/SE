def _버블(x, y, r=4):
    return f'<circle cx="{x}" cy="{y}" r="{r}" fill="#fff" stroke="{먹}" stroke-width="1.6"/>'


def 게이트(종류, x, y, w=34, h=28, 라벨=None):
    """AND·OR·NAND·NOR·XOR·XNOR·INV 를 (x,y) 왼쪽위 기준으로 그린다.

    입력 핀은 왼쪽 1/3·2/3 높이, 출력 핀은 오른쪽 가운데다.
    `핀()` 으로 그 좌표를 받아 선을 잇는다.
    """
    k = 종류.upper()
    cy = y + h / 2
    o = ""
    부정 = k in ("NAND", "NOR", "XNOR", "INV", "NOT")
    바탕 = {"NAND": "AND", "NOR": "OR", "XNOR": "XOR", "NOT": "INV"}.get(k, k)

    if 바탕 == "AND":
        # 왼쪽은 직선, 오른쪽은 반원
        o += (f'<path d="M{x},{y} L{x+w*0.45},{y} A{h/2},{h/2} 0 0 1 {x+w*0.45},{y+h} '
              f'L{x},{y+h} Z" fill="#fff" stroke="{먹}" stroke-width="1.6"/>')
    elif 바탕 == "OR":
        o += (f'<path d="M{x},{y} Q{x+w*0.55},{y} {x+w*0.95},{cy} '
              f'Q{x+w*0.55},{y+h} {x},{y+h} Q{x+w*0.22},{cy} {x},{y} Z" '
              f'fill="#fff" stroke="{먹}" stroke-width="1.6"/>')
    elif 바탕 == "XOR":
        o += (f'<path d="M{x+6},{y} Q{x+w*0.6},{y} {x+w},{cy} '
              f'Q{x+w*0.6},{y+h} {x+6},{y+h} Q{x+w*0.28},{cy} {x+6},{y} Z" '
              f'fill="#fff" stroke="{먹}" stroke-width="1.6"/>')
        o += (f'<path d="M{x},{y} Q{x+w*0.22},{cy} {x},{y+h}" fill="none" '
              f'stroke="{먹}" stroke-width="1.6"/>')
    else:   # INV -- 삼각형
        o += (f'<path d="M{x},{y+3} L{x+w*0.8},{cy} L{x},{y+h-3} Z" '
              f'fill="#fff" stroke="{먹}" stroke-width="1.6"/>')

    끝 = x + (w * 0.8 if 바탕 == "INV" else (w * 0.95 if 바탕 in ("AND", "OR") else w))
    if 바탕 == "AND":
        끝 = x + w * 0.45 + h / 2
    if 부정:
        o += _버블(끝 + 4, cy)
    if 라벨:
        o += 글(x + w / 2, y - 5, 라벨, 맞춤="middle", 크기=10, 색=회)
    return o


def 핀(종류, x, y, w=34, h=28):
    """게이트의 입력 두 개와 출력 좌표를 돌려준다: (입력1, 입력2, 출력)."""
    k = 종류.upper()
    바탕 = {"NAND": "AND", "NOR": "OR", "XNOR": "XOR", "NOT": "INV"}.get(k, k)
    cy = y + h / 2
    if 바탕 == "INV":
        끝 = x + w * 0.8 + 8
        return (x, cy), (x, cy), (끝, cy)
    if 바탕 == "AND":
        끝 = x + w * 0.45 + h / 2
    else:
        끝 = x + (w * 0.95 if 바탕 == "OR" else w)
    if k in ("NAND", "NOR", "XNOR"):
        끝 += 8
    return (x, y + h * 0.28), (x, y + h * 0.72), (끝, cy)


