"""한국어 이론서의 뼈대 -- 그리고 **논리 점프를 기계가 막는 장치**.

## 이 파일이 있는 이유

"고졸이 읽어도 이해되게, 논리 점프 없이" 는 좋은 목표인데, **사람이
지키려고 하면 반드시 샌다.**  쓰다 보면 앞에서 설명 안 한 말을 쓰게 되고,
쓴 사람은 자기가 아니까 그것을 못 알아챈다.

그래서 규칙이 아니라 **장치**로 만든다.  각 장이 두 가지를 선언한다.

    쓰는것   : 이 장이 **이미 안다고 전제하는** 개념들
    내놓는것 : 이 장이 **처음 정의하는** 개념들

그리고 `tests/test_사다리.py` 가 장을 순서대로 훑으면서,
**아직 안 나온 개념을 쓰는 장이 있으면 빨간불을 낸다.**

밑바닥(`고교`)은 고등학교에서 배우는 것으로 둔다.  그 위로는 전부
이 책 안에서 정의돼야 한다.

## 왜 이것이 진짜 검사인가

"앞에서 설명했다" 는 기억이고, 기억은 틀린다.  **개념 하나하나가 어느
장에서 처음 나왔는지를 기계가 들고 있으면** 순서가 어긋나는 순간 걸린다.
이 저장소의 규율 -- *검사하지 않은 초록불이 검사한 빨간불보다 나쁘다* --
를 교재에 옮긴 것이다.
"""
