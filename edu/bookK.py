def 사다리검사(목록=None):
    """장을 순서대로 훑으며 **아직 안 나온 개념을 쓰는 곳**을 찾는다.

    돌려주는 것: (어긴목록, 개념이처음나온장)
    """
    목록 = 목록 if 목록 is not None else 장들
    가진것 = set(고교)
    처음 = {c: "고교" for c in 고교}
    어김 = []
    for ch in 목록:
        모자람 = [c for c in ch.쓰는것 if c not in 가진것]
        if 모자람:
            어김.append((ch.번호, 모자람))
        for c in ch.내놓는것:
            if c in 처음:
                어김.append((ch.번호, [f"{c} (이미 {처음[c]} 에서 나왔다)"]))
            else:
                처음[c] = ch.번호
                가진것.add(c)
    return 어김, 처음


# ---------------------------------------------------------------------------
# 개념 하나를 다섯 칸으로 -- 이 책의 기본 단위
# ---------------------------------------------------------------------------
# 사용자 지시: "이론을 설명하고 그 뒤에는 어디에 이 개념을 쓸건지, 언제
# 쓸건지, 어떻게 쓸건지, 실제 산업 코드는 어떤지."
#
# 그래서 개념 하나가 나올 때마다 **다섯 칸을 다 채운다.**  다섯 칸을 못
# 채우는 개념은 **이 책에 안 넣는다** -- 쓰는 자리를 못 대면 그것은
# 이 책의 목적(개발과 특허)에 필요 없는 개념이다.
def 개념(이름, 이론, 어디에, 언제, 어떻게, 산업코드=None, 주의=None):
    """개념 하나를 다섯 칸으로 낸다.

    이름     : 개념의 이름
    이론     : 무엇이고 왜 그런가 (HTML)
    어디에   : 어느 블록·어느 자리에서 쓰나
    언제     : 어떤 상황이 되면 이것을 꺼내 쓰나
    어떻게   : 실제로 어떻게 적용하나 (절차·식·판정)
    산업코드 : 진짜 코드가 어떻게 생겼나 (문자열, <pre> 로 감싼다)
    주의     : 여기서 틀린다
    """
    o = [f'<div class="개념"><div class="개념머리">{_이름(이름)}</div>']
    o.append(f'<div class="개념이론">{이론}</div>')
    o.append('<table class="개념표"><tbody>')
    o.append(f'<tr><th>{말("어디에")}</th><td>{어디에}</td></tr>')
    o.append(f'<tr><th>{말("언제")}</th><td>{언제}</td></tr>')
    o.append(f'<tr><th>{말("어떻게")}</th><td>{어떻게}</td></tr>')
    o.append('</tbody></table>')
    if 산업코드:
        o.append(f'<div class="개념코드머리">{말("코드머리")}</div>')
        o.append('<pre><code>' + 안전(산업코드) + '</code></pre>')
    if 주의:
        o.append(f'<div class="개념주의"><b>{말("주의")}</b> {주의}</div>')
    o.append('</div>')
    return "\n".join(o)


def 쓰는자리(줄들):
    """'이 장에서 배운 것을 어디에 쓰나' 를 장 끝에 표로."""
    # 첫 칸은 개념 이름이라 영어판에서는 같이 옮긴다.  한 칸에 여러 개를
    # `·` 로 늘어놓은 줄이 있으므로 쪼개서 옮긴다(안 쪼개면 통째로 안 맞아
    # 한국어가 그대로 남는다 -- 실측 2026-09-20).
