class 장:
    """장 하나.  선언이 곧 등록이다."""

    def __init__(self, 번호, 제목, 한줄, 쓰는것, 내놓는것, 특허=None):
        self.번호, self.제목, self.한줄 = 번호, 제목, 한줄
        self.쓰는것 = list(쓰는것)
        self.내놓는것 = list(내놓는것)
        self.특허 = 특허            # 이 주제에서 발명이 일어나는 자리
        self.조각 = []
        장들.append(self)

    # -- 본문 쌓기 ---------------------------------------------------------
    def 글(self, t):
        self.조각.append(f"<p>{t}</p>")
        return self

    def 절(self, t):
        self.조각.append(f"<h2>{t}</h2>")
        return self

    def 소절(self, t):
        self.조각.append(f"<h3>{t}</h3>")
        return self

    def 날것(self, t):
        self.조각.append(t)
        return self

    def 코드(self, t):
        self.조각.append("<pre><code>" + 안전(t) + "</code></pre>")
        return self

    def 완성(self):
        머리 = [f'<h1 id="{self.번호}">{self.번호}. {self.제목}</h1>']
        머리.append(f'<p class="한줄">{self.한줄}</p>')
        머리.append(_알아야(self.쓰는것, self.내놓는것))
        꼬리 = []
        if self.특허:
            꼬리.append(특허칸(self.특허))
        return "\n".join(머리 + self.조각 + 꼬리)


def _알아야(쓰는것, 내놓는것):
    """장 첫머리의 '읽기 전에 / 읽고 나면' 상자."""
    a = " · ".join(쓰는것) if 쓰는것 else "없다 (여기서 시작한다)"
    b = " · ".join(내놓는것)
    return (
        '<div class="사다리">'
        f'<div class="사다리앞"><b>읽기 전에 알아야 하는 것</b><br>{a}</div>'
        f'<div class="사다리뒤"><b>이 장에서 새로 나오는 것</b><br>{b}</div>'
        '</div>')


def 특허칸(t):
    return ('<div class="특허"><div class="특허머리">특허로 가는 길 '
            '&mdash; 이 주제에서 발명이 일어나는 자리</div>'
            f'<div class="특허속">{t}</div></div>')


