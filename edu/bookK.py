def 수(x, 유효=4, 단위=""):
    """수를 읽기 좋게.  **계산해서 나온 수만 쓴다.**"""
    if isinstance(x, int):
        s = f"{x:,}"
    else:
        ax = abs(x)
        if ax != 0 and (ax >= 1e5 or ax < 1e-3):
            m, e = f"{x:.{유효-1}e}".split("e")
            s = f"{m}×10<sup>{int(e)}</sup>"
        else:
            s = f"{x:,.{max(0, 유효 - len(str(int(ax))) )}f}".rstrip("0").rstrip(".")
    return s + (f"&nbsp;{단위}" if 단위 else "")


