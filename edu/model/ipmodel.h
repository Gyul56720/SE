// ipmodel.h -- 한 벌의 C++ 모델이 **골든모델이자 HLS 입력**이다.
//
// 왜 이 파일이 있나
// ------------------
// 1인 디자인 하우스에서 같은 알고리즘을 세 벌 적으면 세 벌이 서로 어긋난다
// (파이썬 모델 · HLS 소스 · 손으로 쓴 RTL).  어긋나면 어느 것이 옳은지
// 아무도 모른다.  그래서 **C++ 한 벌**만 적고 그것을 두 군데로 보낸다:
//
//     ipmodel.h ──┬── g++ 로 컴파일 ──> 골든 벡터 (검증의 정답)
//                 └── bambu 로 합성 ──> Verilog (파는 물건)
//
// 두 길이 **같은 소스**에서 나오므로 "모델과 RTL 이 어긋났다" 가 구조적으로
// 불가능해진다.  손으로 쓴 RTL 도 같은 골든 벡터로 잰다.
//
// 이 파일에 벤더 타입이 없는 이유 -- 실측으로 정했다
// --------------------------------------------------
// survey/synth/합성결과.md 의 1변수 대조 네 개가 이렇게 나왔다:
//
//     순수 C                            rc=0, Verilog 나옴
//     + `#pragma HLS PIPELINE II=1`     rc=11  Loop pipelining pragma not supported
//     C++ 템플릿 (프라그마 없음)         rc=0, Verilog 나옴
//     ap_uint 만                        rc=0, 119~147 MHz
//     hls::stream 만                    rc=1   FixStructsPassedByValue 크래시
//     ap_fixed 복소 8x8 Cholesky        rc=124 프론트엔드에서 40분 타임아웃
//
// 그래서 **프라그마도 hls::stream 도 ap_fixed 도 쓰지 않는다.**  남는 것은
// `int32_t` · `int64_t` 와 손으로 적은 고정소수점인데, 그것이 오히려 이식성이
// 높다 -- 이 헤더는 Bambu · Vitis HLS · g++ 셋 다에서 같은 뜻이다.
//
// 벤더 타입을 안 쓰는 대가도 적는다: 비트폭을 도구가 자동으로 못 좁힌다.
// `ap_uint<10>` 이면 10비트로 합성될 것이 `int32_t` 면 32비트로 간다.
// 그래서 **폭이 중요한 자리는 마스크로 직접 좁힌다** (아래 `sat`·`mask`).
#ifndef IPMODEL_H
#define IPMODEL_H

#include <stdint.h>

// ---------------------------------------------------------------------------
// 고정소수점 규약
// ---------------------------------------------------------------------------
// Q(I.F): 부호 1비트 + 정수 I비트 + 소수 F비트.  값 v 는 정수 round(v * 2^F)
// 로 담긴다.  하드웨어는 소수점을 모른다 -- 소수점은 **우리 머릿속에만** 있고,
// 비트는 그냥 정수다.  그래서 모델도 정수 연산만 쓴다.  float 을 쓰면 모델과
// RTL 이 마지막 비트에서 갈라지고, 그 갈라짐은 회귀에서 "가끔 1 틀림" 으로
// 나타나 몇 주를 먹는다.
//
// 이 IP 가 쓰는 폭: 표본 Q1.7 (8비트), 계수 Q1.7 (8비트), 누산 Q3.14 (18비트).
enum {
    SAMP_F = 7,          // 표본의 소수 비트 수
    COEF_F = 7,          // 계수의 소수 비트 수
    ACC_F  = SAMP_F + COEF_F,   // 곱하면 소수 비트가 더해진다 = 14
    NTAP   = 4           // 탭 수.  RTL 의 generate 개수와 **같아야** 한다
};

// 아래로 폭 좁히기.  산술 시프트라 부호가 보존된다.
// C++ 에서 음수 우시프트는 C++20 이전에는 구현정의지만, gcc·clang 은
// 산술 시프트로 하고 Bambu 도 같다 -- 그래도 기대는 것이 싫어서
// **나눗셈으로 적지 않는다**: 나눗셈은 0 쪽으로 자르고 시프트는 -무한 쪽으로
// 자른다.  둘이 음수에서 다르다.  RTL 은 시프트를 하므로 모델도 시프트다.
static inline int32_t asr(int32_t v, int n) {
    return (v < 0) ? ~((~v) >> n) : (v >> n);   // 부호와 무관하게 floor 시프트
}

// n비트 부호있는 범위로 포화.  자르지(wrap) 않고 **포화**하는 이유:
// 링크 등화기에서 wrap 은 큰 양수를 큰 음수로 뒤집어 슬라이서를 정반대로
// 틀리게 만든다.  포화는 틀려도 같은 부호 쪽으로 틀린다.
static inline int32_t sat(int32_t v, int n) {
    const int32_t hi = (int32_t)((1u << (n - 1)) - 1);
    const int32_t lo = -hi - 1;
    return v > hi ? hi : (v < lo ? lo : v);
}

// 아래 n비트만 남긴다 (부호 없음).  RTL 의 `[n-1:0]` 과 같다.
static inline uint32_t mask(uint32_t v, int n) {
    return n >= 32 ? v : (v & ((1u << n) - 1));
}

#endif // IPMODEL_H
