// fir.h -- 링크 수신단 4탭 FIR 등화기.  **같은 함수를 세 가지 구조로 적었다.**
//
// 셋은 출력이 **비트까지 같다** -- 짐작이 아니라 `equiv.cpp` 가 8비트 입력
// 네 개의 **전체 공간 256^4 = 4,294,967,296 가지를 전수로** 확인한다.
// 이것이 이 파일의 요점이다: C++ 한 줄을 고치면 *아키텍처*가 바뀐다.
// 손으로 쓴 RTL 에서 같은 일을 하려면 데이터패스를 다시 그려야 한다.
//
//   FIR_VARIANT=0  naive     곱셈기 4개.  교과서에 적힌 그대로
//   FIR_VARIANT=1  narrow    naive 와 같은 구조인데 **폭을 손으로 좁혔다**
//   FIR_VARIANT=2  folded    대칭 계수를 접었다.  곱셈기 2개
//
// 왜 셋을 다 남겨 두나 -- 쓸기를 보이려고
// ----------------------------------------
// 이 저장소의 규율은 *가장 유리한 구석에서 나온 수를 표제로 쓰지 않는다* 이다.
// HLS 가 손RTL 을 이긴다고 말하려면 **셋 다 재서 나란히 보여야** 한다.
// 하나만 재서 "HLS 가 이겼다" 고 적으면 그것은 측정이 아니라 광고다.
//
// 계수가 상수인 이유 -- 이것이 QoR 의 첫 번째 지렛대다
// ------------------------------------------------------
// 계수를 `static const` 로 두면 합성기가 곱셈을 **시프트-덧셈으로 푼다**.
// 계수가 런타임 포트면 못 푼다 -- 진짜 곱셈기가 박힌다.  손으로 쓴 RTL 은
// 보통 계수를 포트로 두고(나중에 바꾸고 싶어서) 범용 곱셈기를 인스턴스한다.
// **그 한 결정이 면적의 대부분을 정한다.**  HLS 는 상수로 두는 순간 공짜로
// 얻는다.  뒤에서 yosys 로 실제 셀 수를 세어 이 말을 검사한다.
// 인클루드 가드가 `EDU_FIR_H` 인 이유 -- 실측으로 물렸다
// 처음에는 가드도 `FIR_H` 였다.  계수 배열 이름도 `FIR_H` 였다.  그러면
// 전처리기가 배열 이름을 **지운다**:
//     static const int32_t [NTAP] = { -18, 111, 111, -18 };
// gcc 는 이것을 구조적 바인딩으로 읽고 엉뚱한 데를 가리킨다
// ("structured binding declaration cannot have type const int32_t").
// **가드 이름은 그 파일 안의 어떤 식별자와도 겹치면 안 된다.**
#ifndef EDU_FIR_H
#define EDU_FIR_H

#include "ipmodel.h"

#ifndef FIR_VARIANT
#define FIR_VARIANT 0
#endif

// 대칭 계수 (선형위상).  h[0]==h[3], h[1]==h[2] -- folded 변형이 이것에 기댄다.
// Q1.7 이므로 정수 값을 2^7 로 나눈 것이 실제 계수다: {-0.1406, 0.8672, 0.8672, -0.1406}
static const int32_t FIR_H[NTAP] = { -18, 111, 111, -18 };

// 출력 폭.  누산은 Q3.14 인데 밖으로는 Q1.7 로 내보낸다.
// **이 두 줄이 폭 좁히기의 전부다** -- 그런데 면적의 절반이 여기서 갈린다.
enum { OUT_W = 8, ACC_W = 18 };

// ---------------------------------------------------------------------------
// 변형 0: naive -- 교과서 그대로
// ---------------------------------------------------------------------------
// 곱셈 4번, 덧셈 3번.  중간값을 `int32_t` 로 둔다 -- 도구가 폭을 좁힐 근거가
// 없으므로 32비트 데이터패스가 나온다.  **이것이 HLS 가 손RTL 에 지는
// 전형적인 이유다**: C 의 정수 승격 규칙이 전부 int 로 끌어올린다.
static inline int32_t fir_naive(const int32_t *x) {
    int32_t acc = 0;
    for (int i = 0; i < NTAP; i++)
        acc += x[i] * FIR_H[i];
    // 밖으로 나가는 포트는 8비트다.  세 변형이 **같은 함수**이려면 여기서도
    // 포화해야 한다.  처음에는 이 줄이 없었고, 그래서 변형 0 만 255 를 내고
    // 변형 1·2 는 127 을 냈다 -- 입력이 클 때만.  아래 `equiv.cpp` 가
    // 입력공간 전체를 훑어서 그것을 잡았다(표본이 아니라 전수다).
    return sat(asr(acc, COEF_F), OUT_W);
}

// ---------------------------------------------------------------------------
// 변형 1: narrow -- 같은 구조, 폭만 손으로 좁혔다
// ---------------------------------------------------------------------------
// 구조는 naive 와 **완전히 같다**.  곱셈 4번, 덧셈 3번, 같은 순서.
// 바꾼 것은 `sat(..., ACC_W)` 한 줄 -- 누산을 18비트로 못박는다.
// 그러면 합성기가 32비트 캐리체인 대신 18비트를 짓는다.
//
// 1변수 대조다: **변형 0 과 이것의 면적 차이는 전부 폭 때문이다.**
static inline int32_t fir_narrow(const int32_t *x) {
    int32_t acc = 0;
    for (int i = 0; i < NTAP; i++) {
        int32_t xi = sat(x[i], 8);           // 입력은 Q1.7 = 8비트다
        acc = sat(acc + xi * FIR_H[i], ACC_W);
    }
    return sat(asr(acc, COEF_F), OUT_W);
}

// ---------------------------------------------------------------------------
// 변형 2: folded -- 대칭을 접는다.  곱셈기 4개 -> 2개
// ---------------------------------------------------------------------------
// h[0]==h[3] 이고 h[1]==h[2] 이므로
//
//     y = h0*x0 + h1*x1 + h2*x2 + h3*x3
//       = h0*(x0 + x3) + h1*(x1 + x2)
//
// **곱셈 4번이 2번이 된다.**  덧셈은 3번에서 3번으로 그대로다 (앞에 2번,
// 뒤에 1번).  곱셈기가 덧셈기보다 훨씬 비싸므로 순이익이다.
//
// 이 변환이 "HLS 가 손RTL 을 이기는" 자리다 -- 어렵기 때문이 아니라
// **유지보수가 어렵기 때문이다.**  탭 수를 8·16·32 로 바꿀 때마다 손RTL
// 에서는 접는 구조를 다시 그려야 하고, 대칭이 깨지면 조용히 틀린다.
// C++ 에서는 계수 배열만 바꾸면 되고, 아래 `assert` 가 대칭이 깨지는 순간
// 컴파일 타임에 잡는다.
//
// 앞 덧셈이 9비트인 이유: 8비트 둘을 더하면 9비트가 필요하다.  이것을
// 8비트로 자르면 **조용히 틀린다** -- x0+x3 가 넘칠 때만, 자극의 몇 %에서만.
// 그런 결함이 회귀를 몇 주 먹는다.
static inline int32_t fir_folded(const int32_t *x) {
    int32_t a0 = sat(x[0], 8) + sat(x[3], 8);      // 9비트
    int32_t a1 = sat(x[1], 8) + sat(x[2], 8);      // 9비트
    int32_t acc = sat(a0 * FIR_H[0] + a1 * FIR_H[1], ACC_W);
    return sat(asr(acc, COEF_F), OUT_W);
}

// 고른 변형 하나를 `fir_tap` 이라는 한 이름으로 낸다.
// 하니스도 HLS 도 이 이름만 본다 -- 변형을 바꿔도 배선이 안 바뀐다.
static inline int32_t fir_tap(const int32_t *x) {
#if   FIR_VARIANT == 0
    return fir_naive(x);
#elif FIR_VARIANT == 1
    return fir_narrow(x);
#elif FIR_VARIANT == 2
    return fir_folded(x);
#else
#error "FIR_VARIANT 는 0·1·2 중 하나여야 한다"
#endif
}

#endif // EDU_FIR_H
