// fir_top_tuned.cpp -- **HLS 로 손RTL 을 이기려면 무엇을 바꿔야 하는가.**
//
// `fir_top.cpp` 와 알고리즘이 똑같다.  출력도 비트까지 같다.
// 바꾼 것은 **타입 세 줄**뿐인데 하드웨어가 통째로 달라진다.
//
//   fir_top.cpp        int  x0..x3  ->  int        포트 32비트, 32비트 데이터패스
//   fir_top_tuned.cpp  int8_t       ->  int8_t     포트 8비트,  좁은 데이터패스
//
// 왜 이것이 "HLS 를 정확하게 이해한다" 의 실체인가
// ------------------------------------------------
// HLS 는 **C 의 타입을 그대로 믿는다.**  C 의 정수 승격 규칙은 `char`·`short`
// 를 전부 `int` 로 끌어올리므로, 아무 생각 없이 적으면 8비트 신호를 32비트
// 데이터패스로 만든다.  손으로 RTL 을 쓰는 사람은 `[7:0]` 이라고 적을 자리라
// 이 실수를 아예 할 수 없다 -- **HLS 가 손RTL 에 지는 이유의 대부분이 이것이다.**
//
// 거꾸로, 타입을 정확히 적으면 HLS 는 손RTL 이 놓치는 것을 잡는다:
//   * 상수 계수를 시프트-덧셈으로 푼다 (손RTL 은 보통 범용 곱셈기를 인스턴스한다)
//   * 대칭 접기를 탭 수가 바뀌어도 자동으로 유지한다
//   * 클럭 주기를 바꾸면 **파이프라인을 다시 짠다** (손RTL 은 사람이 다시 그려야 한다)
//
// 승부는 "HLS 냐 손RTL 이냐" 가 아니라 **"폭을 적었느냐"** 에서 갈린다.
#include "ipmodel.h"

// 계수는 `fir.h` 와 같은 값이다.  상수여야 시프트-덧셈으로 풀린다.
static const int16_t TH[NTAP] = { -18, 111, 111, -18 };

// 접은 구조.  중간 폭을 **하나하나 적는다** -- 이것이 이 파일의 전부다.
//
//   x       int8_t    8비트   (Q1.7)
//   a0,a1   int16_t   9비트면 되지만 C 에 9비트 타입이 없다.  16으로 두고
//                     합성기가 위 7비트가 안 쓰이는 것을 스스로 지우게 한다
//   acc     int32_t   9+8=17비트.  32로 두면 위 15비트가 죽은 논리가 되는데,
//                     **상수 계수라 합성기가 그것을 지운다** -- 실측으로 확인한다
extern "C" signed char fir_top_tuned(signed char x0, signed char x1,
                                     signed char x2, signed char x3) {
    int16_t a0 = (int16_t)x0 + (int16_t)x3;
    int16_t a1 = (int16_t)x1 + (int16_t)x2;
    int32_t acc = (int32_t)a0 * TH[0] + (int32_t)a1 * TH[1];
    int32_t y = asr(acc, COEF_F);
    // 포화.  `sat()` 과 같은 일을 하는데 8비트로 못박아 적었다.
    if (y >  127) y =  127;
    if (y < -128) y = -128;
    return (signed char)y;
}
