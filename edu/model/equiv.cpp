// equiv.cpp -- 세 변형이 같은 함수인지 **전수로** 확인한다.
//
// 왜 표본이 아니라 전수인가
// --------------------------
// 이 IP 의 입력은 8비트 표본 네 개다.  그러면 입력공간 전체가
// 256^4 = 4,294,967,296 가지뿐이다.  4.3 G 는 C++ 에서 **분 단위**로 훑린다.
// 훑을 수 있는데 표본을 뽑는 것은 게으름이다.
//
// 그리고 이것이 이 장의 요점이다 -- **검증 시간은 C++ 에서 줄인다.**
// 같은 4.3 G 를 RTL 시뮬레이터로 돌리면 몇 달이 걸린다(뒤에서 실측으로
// 비율을 잰다).  그래서 순서를 이렇게 둔다:
//
//     C++ 에서 전수/대량으로 알고리즘을 못박는다   <- 여기서 결함의 대부분이 죽는다
//     RTL 에서는 **배선**만 본다 (적은 벡터로 충분)
//
// 알고리즘 결함을 RTL 시뮬레이션으로 찾는 것은, 찾을 수는 있지만
// **1000 배 비싼 자리에서 찾는 것**이다.
#include <stdio.h>
#include <stdlib.h>
#include <time.h>

#define FIR_VARIANT 0
#include "ipmodel.h"

// 세 변형을 한 번역단위에서 다 부르려면 매크로 분기를 피해야 한다.
// 그래서 `fir.h` 의 개별 함수를 직접 부른다 -- `fir_tap` 은 안 쓴다.
#include "fir.h"

int main(int argc, char **argv) {
    // 기본은 전수.  `equiv 빠름` 이면 상위 바이트를 건너뛰며 훑는다
    // (검사 스위트가 6분을 쓰면 안 되므로).
    long step = (argc > 1) ? atol(argv[1]) : 1;
    if (step < 1) step = 1;

    clock_t t0 = clock();
    long long 본것 = 0, 다름01 = 0, 다름02 = 0;
    int 첫다름[4] = {0, 0, 0, 0};
    int 서로다른출력[512];
    for (int i = 0; i < 512; i++) 서로다른출력[i] = 0;

    for (int a = -128; a < 128; a += (int)step)
    for (int b = -128; b < 128; b++)
    for (int c = -128; c < 128; c++)
    for (int d = -128; d < 128; d++) {
        int32_t x[4] = { a, b, c, d };
        int32_t y0 = fir_naive(x);
        int32_t y1 = fir_narrow(x);
        int32_t y2 = fir_folded(x);
        본것++;
        서로다른출력[y0 + 256] = 1;
        if (y0 != y1) { if (!다름01) { 첫다름[0]=a; 첫다름[1]=b; 첫다름[2]=c; 첫다름[3]=d; } 다름01++; }
        if (y0 != y2) { if (!다름02 && !다름01) { 첫다름[0]=a; 첫다름[1]=b; 첫다름[2]=c; 첫다름[3]=d; } 다름02++; }
    }

    int 값가지수 = 0;
    for (int i = 0; i < 512; i++) 값가지수 += 서로다른출력[i];
    double 초 = (double)(clock() - t0) / CLOCKS_PER_SEC;

    printf("본것 %lld\n", 본것);
    printf("걸음 %ld\n", step);
    printf("초 %.3f\n", 초);
    printf("초당 %.0f\n", 본것 / (초 > 0 ? 초 : 1e-9));
    printf("다름01 %lld\n", 다름01);
    printf("다름02 %lld\n", 다름02);
    printf("출력값가지수 %d\n", 값가지수);
    if (다름01 || 다름02)
        printf("첫다름 %d %d %d %d\n", 첫다름[0], 첫다름[1], 첫다름[2], 첫다름[3]);
    // 출력이 한 가지뿐이면 이 확인은 아무것도 안 본 것이다 -- 하니스의
    // `쓸모있나` 와 같은 관문을 여기에도 둔다.
    if (값가지수 < 2) { printf("쓸모없음 출력이 %d 가지뿐이다\n", 값가지수); return 2; }
    return (다름01 || 다름02) ? 1 : 0;
}
