// vectors.cpp -- C++ 골든모델이 **검증의 정답을 파일로 낸다.**
//
//     ./vectors <개수> <씨앗>  >  vec.txt
//
// 각 줄: x0 x1 x2 x3 y   (전부 10진 부호있는 정수)
// 테스트벤치가 앞 넷을 DUT 에 넣고 다섯째와 비교한다.
//
// 왜 파일로 내나 -- 골든모델의 **독립성**
// ----------------------------------------
// 골든모델이 RTL 에서 나오면 비교는 아무것도 안 본다 (자기 자신과 비교한다).
// 여기서는 골든이 C++ 에서 나오고 RTL 은 그 C++ 을 HLS 로 돌린 것이라
// 한 다리 건넜을 뿐이다 -- **그래서 손RTL 도 같은 벡터로 잰다.**
// 손RTL 은 C++ 을 안 보고 사람이 쓴 것이므로, 손RTL 이 통과하면
// 그 벡터가 진짜로 알고리즘을 못박고 있다는 뜻이다.
//
// 자극을 어떻게 고르나 -- 무작위만으로는 모자라다
// ------------------------------------------------
// 무작위 8비트 넷은 포화 경계를 거의 안 밟는다.  그래서 **경계를 먼저 넣는다**:
// 전부 최대 · 전부 최소 · 부호가 엇갈리는 조합.  실측: 경계를 안 넣으면
// 포화 논리를 지워도 회귀가 초록이었다 (포화가 한 번도 안 일어나므로).
#include <stdio.h>
#include <stdlib.h>
#include "fir.h"

int main(int argc, char **argv) {
    int n    = (argc > 1) ? atoi(argv[1]) : 256;
    unsigned seed = (argc > 2) ? (unsigned)atoi(argv[2]) : 1u;

    // 경계부터.  포화가 실제로 일어나는 자리를 손으로 골랐다.
    static const int corner[][4] = {
        {  127,  127,  127,  127 },   // 최대 -- 양의 포화
        { -128, -128, -128, -128 },   // 최소 -- 음의 포화
        {  127, -128,  127, -128 },   // 엇갈림
        { -128,  127, -128,  127 },
        {    0,    0,    0,    0 },   // 영
        {  127,    0,    0,  127 },   // 접는 덧셈 a0 가 넘치는 자리
        { -128,    0,    0, -128 },
        {    0,  127,  127,    0 },   // a1 가 넘치는 자리
        {    0, -128, -128,    0 },
        {    1,   -1,    1,   -1 },
    };
    const int nc = (int)(sizeof(corner) / sizeof(corner[0]));

    unsigned s = seed ? seed : 1u;
    for (int k = 0; k < n; k++) {
        int32_t x[NTAP];
        if (k < nc) {
            for (int i = 0; i < NTAP; i++) x[i] = corner[k][i];
        } else {
            // xorshift32.  rand() 를 안 쓰는 이유: libc 마다 수열이 달라서
            // **다른 기계에서 같은 벡터가 안 나온다.**  회귀는 재현돼야 한다.
            for (int i = 0; i < NTAP; i++) {
                s ^= s << 13; s ^= s >> 17; s ^= s << 5;
                x[i] = (int32_t)(int8_t)(s & 0xFF);
            }
        }
        printf("%d %d %d %d %d\n", x[0], x[1], x[2], x[3], fir_tap(x));
    }
    return 0;
}
