"""
G023 -- 논문이 **표제와 초록에서 내세우는 수치**가 측정 원장에 있고, 그 행이
독립 대조 · 사소한 설명 · 무효화 조건을 달고 있는가.

사용자(2026-09-18): "반복되는 잘못되는 측정, 논리적 결함 ... 그리고 너무나도 큰 과장."

이 저장소에서 잰 것이 틀린 방식은 늘 같았다 -- **그 수가 사소하게 나올 수 있는 길을 막지
않고 보고했다.** 실측 넷:

  1. 지터 민감도를 **펄스 정점**에서 쟀다. 정점의 기울기는 정의상 0이다. 0이 나온 것이
     발견처럼 보고됐다
  2. 잔차 분해를 σ≈신호진폭(BER 0.49)인 **망가진 동작점**에서 쟀다
  3. `yosys ltp` 가 고리경로가 아니라 **넷리스트 전체**의 최장경로를 쟀다. 재려던 것이
     아닌 것을 쟀는데 수는 멀쩡해 보였다
  4. "게이트 7개, 불일치 0%" -- 그런데 그 동작점의 DFE 탭이 |c|<=0.041 이었다. **고리가
     놀고 있었다.** 정답은 맨 슬라이서였다. 사소한 설명을 안 죽여서 발견으로 보고할 뻔했다

그리고 `ff31763` 의 표제는 "1/59 the Standard-Cell Area" 인데, 같은 원고 안에 **실제
동작점(30 dB)에서는 W(1e-3)>16 이라 제거형이 크게 진다**는 사실이 있었다. 1/59 는 쓸기의
가장 유리한 구석에서 나온 수다. 그것이 표제가 됐다 -- 이것이 사용자가 과장이라 부른 것이다.

## 무엇을 위반으로 보는가

`paper/*.html` 의 `<h1 class="title">` 과 `<div class="abs">` 에 나오는 **모든 수치 토막**에
대해 `paper/측정.jsonl` 에 행이 있어야 한다. 행의 `종류` 에 따라 요구가 다르다.

  · `종류: "측정"` -- `재현`(그 수를 다시 내는 명령), `독립대조`(같은 수를 **다른 길로**
    한 번 더 구한 것과 그 차이), `사소한설명`(이 수가 시시하게 나올 수 있는 길과, 그것을
    재서 죽인 결과), `무효화`(이 주장이 깨지는 조건) 가 전부 비어 있지 않아야 한다
  · `종류: "규격"` 또는 `"인용"` -- `출처` 가 비어 있지 않아야 한다 (448G, 802.3 같은 수)

`무효화` 가 필수인 것이 이 게이트의 핵심이다. **주장이 깨지는 조건을 적을 수 없으면 그것은
주장이 아니라 광고다.** 1/59 는 무효화 조건("W(1e-3)>16 이면 진다")을 적는 순간 표제가
될 수 없었다.

## 무엇을 안 잡는가 -- 그리고 왜

  · `attic/` 은 안 본다 -- 폐기한 원고의 무덤이고, 거기 남은 것이 RED 증명의 근거다
  · 본문 속 수치는 안 본다. 표제와 초록만 본다 -- **과장이 사는 자리**가 거기이고,
    문서 전체의 수를 다 물리면 원장이 잡일이 되어 아무나 아무 글자나 채우게 된다
  · 원장에 적힌 독립대조가 **그 자체로 틀린** 경우는 못 잡는다. 기계는 두 계산이 서로
    독립인지 모른다. 이 게이트가 강제하는 것은 두 번째 길을 **실제로 걸었다는 기록**뿐이다
  · 수가 옳은지도, 그 주장이 새로운지도 안 본다 (새로움은 G024 가 본다)
"""
from __future__ import annotations

import json
import re

RULE_ID = "G023"
TITLE = "논문 표제와 초록의 수치가 측정 원장에 있고 무효화 조건을 달고 있는가"
ORIGIN = "ff31763 (표제 '1/59 면적' -- 쓸기의 가장 유리한 구석에서 나온 수였다)"
EVIDENCE = "attic/폐기논문/README.md"

_원장이름 = "paper/측정.jsonl"
_측정필수 = ("재현", "독립대조", "사소한설명", "무효화")
_인용필수 = ("출처",)

_표제 = re.compile(r'<h1[^>]*class="[^"]*\btitle\b[^"]*"[^>]*>(.*?)</h1>', re.S)
_초록 = re.compile(r'<div[^>]*class="[^"]*\babs\b[^"]*"[^>]*>(.*?)</div>', re.S)
_태그 = re.compile(r"<[^>]+>")
_실체 = re.compile(r"&[a-zA-Z]+;|&#\d+;")
# 긴 꼴부터: 지수 -> 분수 -> 보통 수. 그래야 1/59 가 1 과 59 로 쪼개지지 않는다.
_수 = re.compile(r"\d+(?:\.\d+)?\s*[eE][-+]?\d+|\d+(?:\.\d+)?\s*/\s*\d+(?:\.\d+)?|\d+(?:\.\d+)?")


def _논문들(ctx):
    자리 = ctx.repo / "paper"
    return sorted(p for p in 자리.glob("*.html") if p.is_file()) if 자리.is_dir() else []


def _내세운글(글: str) -> str:
    조각 = [m.group(1) for m in (_표제.search(글), _초록.search(글)) if m]
    본 = " ".join(조각)
    본 = _태그.sub(" ", 본)
    return _실체.sub(" ", 본)


def _수들(본: str) -> "list[str]":
    """나온 차례대로, 중복 없이. 공백은 지워서 '2.2 e-4' 와 '2.2e-4' 를 같게 본다."""
    본것, 차례 = set(), []
    for m in _수.finditer(본):
        값 = re.sub(r"\s+", "", m.group(0))
        if 값 not in 본것:
            본것.add(값)
            차례.append(값)
    return 차례


def _원장(ctx) -> "tuple[dict, str | None]":
    p = ctx.repo / _원장이름
    if not p.is_file():
        return {}, None
    표 = {}
    for n, 줄 in enumerate(p.read_text(encoding="utf-8", errors="replace").splitlines(), 1):
        줄 = 줄.strip()
        if not 줄 or 줄.startswith("#"):
            continue
        try:
            행 = json.loads(줄)
        except ValueError as e:
            return {}, f"{_원장이름}:{n}: JSON 이 깨졌다 ({e}) -- 원장이 읽히지 않으면 게이트가 무력하다."
        논문, 값 = str(행.get("논문", "")), re.sub(r"\s+", "", str(행.get("값", "")))
        if not 논문 or not 값:
            return {}, f"{_원장이름}:{n}: '논문' 또는 '값' 이 비어 있다."
        표[(논문, 값)] = 행
    return 표, None


def check(ctx) -> "list[str]":
    논문들 = _논문들(ctx)
    if not 논문들:
        return []
    표, 깨짐 = _원장(ctx)
    if 깨짐:
        return [깨짐]

    위반 = []
    for path in 논문들:
        이름 = path.name
        try:
            글 = path.read_text(encoding="utf-8", errors="replace")
        except OSError:
            continue
        for 값 in _수들(_내세운글(글)):
            행 = 표.get((이름, 값))
            if 행 is None:
                위반.append(
                    f"{이름} 표제/초록의 '{값}': {_원장이름} 에 행이 없다 -- 어떻게 재서 나온 "
                    f"수이고, 이 수가 사소하게 나올 길을 무엇으로 죽였고, 언제 깨지는지가 없다. "
                    f'{{"논문":"{이름}","값":"{값}","종류":"측정","재현":"…","독립대조":"…",'
                    f'"사소한설명":"…","무효화":"…"}} 를 넣어라 '
                    f'(규격·인용 숫자면 {{"종류":"규격","출처":"…"}}).')
                continue
            종류 = str(행.get("종류", "")).strip()
            if 종류 == "측정":
                필수 = _측정필수
            elif 종류 in ("규격", "인용"):
                필수 = _인용필수
            else:
                위반.append(f"{이름} '{값}': 종류 '{종류}' 는 측정|규격|인용 중 하나여야 한다.")
                continue
            빈칸 = [k for k in 필수 if not str(행.get(k, "")).strip()]
            if 빈칸:
                위반.append(
                    f"{이름} 표제/초록의 '{값}': {_원장이름} 의 행에 {', '.join(빈칸)} 이(가) 비어 있다"
                    + (" -- 깨지는 조건을 못 적는 수는 주장이 아니라 광고다." if "무효화" in 빈칸 else "."))
    return 위반
