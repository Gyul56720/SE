"""밖의 자 -- **읽은 것을 세어 보여 주는가**가 이 검사의 본체다.

OCR 은 깨진다. 깨진 채로 조용히 반쯤 읽으면 그 뒤의 정답률도 위반 수도 전부 거짓이
된다. 그래서 파서는 몇 문항을 읽었는지, 선택지를 못 읽은 것이 몇 개인지 말해야 한다.

그리고 **네트워크를 안 탄다** -- 가짜 물음이를 주면 가짜로만 돈다.
"""
from __future__ import annotations

import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from law import corpus as CP                                          # noqa: E402
from law import exam as EX                                            # noqa: E402

FIXTURE = ROOT / "tests" / "fixtures" / "law_corpus"
CORPUS = CP.load(FIXTURE)
fails = []


def ok(cond, msg):
    print(("  OK   " if cond else "  실패 ") + msg)
    if not cond:
        fails.append(msg)


# 휴대폰으로 viewer.moj.go.kr 을 찍은 화면이라 문제와 상관없는 줄이 섞인다.
시험지 = """11:26
LTE
viewer.moj.go.kr
3쪽
문 5.
 법률행위의 무효와 취소에 관한 설명 중 옳지 않은 것을 모두 고른 것은? (각 지문은
 독립적이며, 다툼이 있는 경우 판례에 의함)
ㄱ. 甲이 그 소유 X 토지를 乙과 통정하여 허위로 매도하고 소유권이전등기를 마쳐 준 후
   그 사실을 과실로 알지 못한 丙이 乙로부터 X 토지를 매수하여 등기를 마친 경우
ㄴ. 甲이 乙로부터 매수한 목적물의 하자가 계약 내용의 중요 부분에 해당하여 甲이
   하자담보책임을 물어 계약을 해제할 수 있는 경우
① ㄱ, ㄴ ② ㄱ, ㄹ
③ ㄴ, ㄷ ④ ㄴ, ㄹ
⑤ ㄷ, ㄹ
4쪽
문 6.
 소멸시효에 관한 설명 중 옳은 것을 모두 고른 것은? (다툼이 있는 경우 판례에 의함)
ㄱ. 동일한 채권자와 채무자 사이에 아직 소멸시효가 완성되지 않은 다수의 금전채권이
   존재하는 경우
① ㄱ ② ㄴ ③ ㄷ ④ ㄹ ⑤ ㄱ, ㄴ
"""

print("[읽기] **읽은 것을 세어 보여 준다** -- 깨진 채로 반쯤 읽으면 뒤가 전부 거짓이다")
qs = EX.parse(시험지)
ok(len(qs) == 2, f"문항 둘을 읽는다 (얻은 값 {len(qs)})")
ok([q.번호 for q in qs] == [5, 6], f"번호를 읽는다 (얻은 값 {[q.번호 for q in qs]})")
ok(qs[0].물음.startswith("법률행위의 무효와 취소"),
   f"여러 줄로 접힌 물음을 이어 붙인다 (얻은 값 {qs[0].물음[:20]}...)")
ok(len(qs[0].보기) == 2 and qs[0].보기[0][0] == "ㄱ",
   f"보기를 ㄱ/ㄴ 으로 가른다 (얻은 값 {[b[0] for b in qs[0].보기]})")
ok("등기를 마친 경우" in qs[0].보기[0][1],
   "이어지는 줄은 앞 보기에 붙인다 -- 한 보기가 여러 줄에 걸린다")
ok(len(qs[0].선택지) == 5,
   f"한 줄에 둘씩 온 선택지도 다섯으로 가른다 (얻은 값 {len(qs[0].선택지)})")

print()
print("[껍데기] 화면에 같이 찍힌 것은 문제가 아니다")
줄 = EX.clean(시험지)
ok(not any("viewer.moj.go.kr" in l or l.strip() == "LTE" or l.strip() == "11:26"
           for l in 줄), "시각·통신사·주소창·쪽번호를 걷어낸다")
ok(any("문 5." in l for l in 줄), "문제 줄은 그대로 둔다 -- 닫힌 목록으로만 지운다")

print()
print("[관문을 모른다] **알려 주면 답안이 관문을 통과하는 쪽으로 균질해진다**")
P = EX.prompt(qs[0])
샘 = [w for w in ("관문", "게이트", "위반", "기각", "심판", "돌연변이",
                 "L001", "L004", "W001", "W004", "hard", "soft") if w in P]
ok(not 샘, f"푸는 쪽 프롬프트에 관문 낱말이 없다 (샌 것 {샘})")
ok("법령명과 번호로" in P and "낱말을 그대로" in P,
   "근거를 조문으로 적으라고는 시킨다 -- 그래야 심판이 볼 것이 생긴다")

print()
print("[답 읽기] **못 읽은 것을 조용히 0점으로 넘기지 않는다**")
ok(EX.read_reply("답: 3\n근거: 민법 제109조에 따른다.") == (3, "민법 제109조에 따른다."),
   "답과 근거를 가른다")
ok(EX.read_reply("답: ④\n근거: 판례 법리다.")[0] == 4, "①~⑤ 로 와도 읽는다")
# RED: 프롬프트가 `답: <번호>` 를 시켜도 모델은 늘 그 꼴로 쓰지 않는다. 좁게 받으면
# 그 답들이 전부 **못 읽음**이 되고, 못 읽음이 틀림과 섞이면 정답률 0/70 이 찍힌다.
# 관문이 아니라 파서가 틀린 것인데 답안이 틀린 것처럼 보인다.
for _꼴, _몇 in [("④\n근거: 민법 제126조", 4), ("답은 ④입니다.", 4),
               ("정답은 ③입니다.", 3), ("**답: ②**", 2), ("답: 4번", 4)]:
    ok(EX.read_reply(_꼴)[0] == _몇,
       f"{_꼴.splitlines()[0]!r} 을 {_몇} 로 읽는다 (얻은 값 {EX.read_reply(_꼴)[0]})")

ok(EX.read_reply("모르겠습니다")[0] == 0,
   "못 읽으면 0 이다 -- 0 은 '틀림' 이 아니라 '못 읽음' 이고 보고가 그것을 센다")

print()
print("[심판] **답안의 근거를 원장과 대조한다. LLM 이 아니다**")
_틀림 = EX.judge("가상시험법 제20조에 따라 행정청은 시정을 명하여야 한다.", CORPUS)
ok(_틀림["어긋남"] == ["서법:기속"],
   f"조문은 재량인데 근거가 기속이면 어긋남 (얻은 값 {_틀림['어긋남']})")
_맞음 = EX.judge("가상시험법 제20조에 따라 행정청은 시정을 명할 수 있다.", CORPUS)
ok(not _맞음["어긋남"] and _맞음["맞음"], "조문대로 적으면 어긋나지 않는다")
_없음 = EX.judge("형법 제356조에 따른다.", CORPUS)
ok(_없음["미검증"] == 1, "원장이 안 담은 법령은 미검증으로 따로 센다")
ok(EX.judge("판례 법리에 따른다.", CORPUS)["인용"] == 0,
   "조문을 안 부른 답안은 인용 0 -- 관문이 볼 것이 없는 자리다")

print()
print("[진짜 시험지] **지어낸 문자열이 아니라 실제 2026 변호사시험 앞 네 문항이다**")
# 파서를 지어낸 예시로만 재면, 실제 시험지가 다르게 생겼을 때 그 사실이 안 드러난다.
# PDF 원본을 눈으로 읽어 옮긴 앞 네 문항을 그대로 넣어 둔다.
_진짜 = EX.parse((ROOT / "law" / "exam" / "2026_민사법_선택형_손옮김.txt")
                .read_text(encoding="utf-8"))
# **수를 못 박지 않는다** -- 옮겨 적은 문항이 늘어날 때마다 깨지면 그건 자가 아니라 덫이다.
# 보는 것은 "번호가 1부터 빠짐없이 이어지는가" 와 "선택지를 다 읽었는가" 다.
ok(_진짜 and [q.번호 for q in _진짜] == list(range(1, len(_진짜) + 1)),
   f"번호가 1부터 빠짐없이 이어진다 -- 빠지면 옮겨 적다 흘린 것이다 "
   f"(얻은 값 {len(_진짜)}개, {[q.번호 for q in _진짜][:8]}...)")
_빈 = [q.번호 for q in _진짜 if len(q.선택지) != 5]
ok(not _빈, f"모든 문항이 선택지 다섯을 갖는다 (못 읽은 문항 {_빈})")
# 문 2 는 보기(ㄱ~) 없이 선택지가 곧 지문인 꼴이다 -- 이 꼴도 읽어야 한다.
ok(not _진짜[1].보기 and len(_진짜[1].선택지) == 5,
   "보기 없이 선택지가 곧 지문인 문항도 읽는다")
# 시험지가 조문을 부르는 자리가 실제로 있다 -- 여기가 우리 관문이 닿는 자리다.
ok(CP.find_citations(_진짜[0].보기[0][1])[0].statute == "민법",
   "「민법」제126조 꼴 인용을 읽는다 -- 시험지에도 관문이 댈 자리가 있다")

print()
print("[정답표] 여러 꼴을 받는다")
_k = Path(tempfile.mkdtemp()) / "답.txt"
_k.write_text("5: 3\n6 ④\n7,1\n엉뚱한 줄\n", encoding="utf-8")
ok(EX.load_key(_k) == {5: 3, 6: 4, 7: 1},
   f"`5: 3` · `6 ④` · `7,1` 을 다 읽는다 (얻은 값 {EX.load_key(_k)})")

print()
print("[보고] **못 읽은 것을 틀린 것과 섞지 않는다** -- 섞으면 파서 탓이 답안 탓이 된다")
_행 = [{"번호": n, "고름": (4 if n <= 6 else 0), "근거": "", "인용": 0, "미검증": 0, "어긋남": []}
       for n in range(1, 11)]
import io as _io                                                       # noqa: E402
import contextlib as _cl                                               # noqa: E402
_buf = _io.StringIO()
with _cl.redirect_stdout(_buf):
    EX.report(_행, {n: 4 for n in range(1, 11)})
_찍힘 = _buf.getvalue()
ok("정답률   6/6" in _찍힘,
   f"못 읽은 문항은 정답률의 분모에서 뺀다 (얻은 값: {[l for l in _찍힘.splitlines() if '정답률' in l]})")
ok("답을 못 읽은 문항 4개" in _찍힘,
   f"몇 개를 못 읽었는지 따로 적는다 (얻은 값: {[l for l in _찍힘.splitlines() if '못 읽' in l]})")

print()
print("[읽기점검] **조용히 반쯤 읽은 것**을 시험지 혼자서 되짚는다")
# 실측: 선택지 겹침이 손옮김의 문 8 ④ 를 잡았다 -- ③ 과 글자까지 똑같이 적혀 있었다.
# 실제 시험지에 똑같은 선택지 둘이 있을 리 없으니 읽기가 깨진 자리다. OCR 과 견주기
# 전에, 원본 없이, 시험지 하나만으로 잡히는 자리가 있다.
_겹 = EX.parse("문 8.\n혼동에 관한 설명 중 옳은 것은?\n"
               "③ ㄱ(×), ㄴ(○)\n④ ㄱ(×), ㄴ(○)\n")
_말 = " ".join(EX.읽기점검(_겹))
ok("선택지가 서로 같은" in _말, f"똑같은 선택지 둘을 잡는다 (얻은 값 {_말!r})")

_빠짐 = EX.parse("문 5.\n등기에 관한 설명\n① ㄱ\n문 7.\n혼동에 관한 설명\n① ㄴ\n")
_말 = " ".join(EX.읽기점검(_빠짐))
ok("번호가 빠진 자리" in _말 and "6" in _말,
   f"안 읽힌 문항을 잡는다 -- 없는 문항은 틀린 문항으로도 안 세어진다 (얻은 값 {_말!r})")

_중복 = EX.parse("문 5.\n등기에 관한 설명\n① ㄱ\n문 5.\n이어지는 조각\n② ㄴ\n")
_말 = " ".join(EX.읽기점검(_중복))
ok("번호가 두 번" in _말, f"쪽 경계에서 갈린 문항을 잡는다 (얻은 값 {_말!r})")

_성함 = EX.parse("문 5.\n등기에 관한 설명\n① ㄱ\n② ㄴ\n")
ok(EX.읽기점검(_성함) == [],
   f"멀쩡한 시험지에는 아무 말도 안 한다 (얻은 값 {EX.읽기점검(_성함)!r})")

print()
if fails:
    print(f"밖의 자: {len(fails)}개 실패 -- {fails}")
    sys.exit(1)
print("밖의 자: 읽기 · 껍데기 · 관문 무지 · 답 읽기 · 심판 · 정답표 · 읽기점검 -- RED/GREEN 통과")
