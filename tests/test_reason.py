def ok(cond, msg):
    print(("  OK   " if cond else "  실패 ") + msg)
    if not cond:
        fails.append(msg)


def 스(요건, 입장, 물음="검사", 세="찬성", 다="반대"):
    return SC.읽기({"물음": 물음, "세우는쪽": 세, "다투는쪽": 다,
                    "요건": 요건, "입장": 입장})


def run(argv):
    buf = io.StringIO()
    with contextlib.redirect_stdout(buf):
        code = A.main(argv)
    return code, buf.getvalue()


