"""`serdes.py` -- 와이어라인 링크. **닫힌 꼴로 교정하고, 물리로 붙든다.**

사용자(2026-09-15)가 고른 주제: "경량화 신경망 기반 wireline SerDes 등화기의 FPGA
실시간 구현". 그 방법론 1~2 단계(채널·CTLE+DFE 기준선·BER)와 4 단계(비트폭 대비 BER)
가 이 모듈이다.

## 시뮬레이터는 **교정해야 한다**

BER 을 내는 코드는 아무 숫자나 낼 수 있고, 그 숫자가 틀렸는지 눈으로는 모른다.
그래서 손실 0 · 등화 없음일 때 닫힌 꼴

    BER = Q(10^(SNRdB/20))

과 나란히 놓는다. 이것이 맞아야 SNR 정의 · 잡음 · 슬라이서가 다 맞는 것이다.

## 첫 판이 낸 것들 -- 실측 2026-09-15, 전부 고쳤다

    정렬을 안 밀었다      -> 모든 BER 이 0.5 (동전 던지기)였다. 등화기가 나쁜 줄 알았다
    틀을 원형으로 굴렸다  -> 한 심볼 끝을 제 앞머리에 이어 붙여 t=0 에 가짜 이음매
    너비를 "높이>0 인 위상 수" 로 -> 20dB 로 닫힌 눈이 **1.00 UI** 로 나왔다
    평평 판정이 헐거웠다  -> 1e-5 짜리 실눈을 이상적 NRZ 로 보아 틀이 안 돌아갔다

## 물리로 붙드는 자리

**잰 눈높이는 peak distortion 한계보다 작을 수 없다.** 무작위 데이터는 최악 패턴을
잘 안 만들기 때문이다. 이 부등식이 깨지면 커서 분해든 아이 측정이든 하나가 틀린
것이다 -- 손계산 없이도 걸린다.
"""
from __future__ import annotations

import math
import sys
from pathlib import Path

import numpy as np

뿌리 = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(뿌리))

import serdes

FAIL_목록 = []


def ok(참, 말):
    print(("  통과 " if 참 else "  실패 ") + 말)
    if not 참:
        FAIL_목록.append(말)


print("[교정 -- 닫힌 꼴 BER = Q(10^(SNR/20)) 과 나란히]")
for snr in (6.0, 8.0, 10.0):
    r = serdes.링크(비트수=200000, 손실dB=0.0, SNRdB=snr, sps=4, 학습비율=0.0, 씨=1)
    이론 = serdes.Q(10 ** (snr / 20.0))
    막대 = 3.0 / math.sqrt(max(r["오류수"], 1))          # 3시그마 상대폭
    어긋남 = abs(r["BER"] - 이론) / 이론
    ok(어긋남 < max(막대, 0.05),
       f"SNR {snr:.0f}dB: 잰 {r['BER']:.3e} vs 이론 {이론:.3e} "
       f"(어긋남 {100 * 어긋남:.1f}%, 3시그마 {100 * 막대:.1f}%)")

print("\n[오류 0 은 BER 0 이 아니다]")
말 = serdes.BER말(0, 10000)
ok("3의 규칙" in 말 and "3.00e-04" in 말, f"3의 규칙으로 위쪽 한계를 말한다: {말[:70]}")
ok("BER 0" in 말, "**오류 0 을 BER 0 이라 부르지 않는다**")
ok("±" in serdes.BER말(9, 10000), "오류가 있으면 상대오차를 같이 말한다")
ok("잰 비트가 없다" in serdes.BER말(0, 0), "안 잰 것은 측정이 아니다")

print("\n[아이 -- 이상적 NRZ 는 2.000 V · 1.00 UI]")
rng = np.random.default_rng(1)
sps = 16
b = rng.integers(0, 2, 4000) * 2 - 1
깨끗 = np.repeat(b, sps).astype(float)
r = serdes.아이재기(깨끗, sps)
ok(abs(r["눈높이"] - 2.0) < 1e-9, f"이상적 눈높이 = 2.000 V (±1 레일): {r['눈높이']}")
ok(abs(r["눈너비UI"] - 1.0) < 1e-9,
   f"**이상적 눈너비 = 1.00 UI** (첫 판은 0.50 이었다): {r['눈너비UI']}")
ok(abs(r["최적표본위상UI"]) < 1e-9,
   f"평평하면 최적 표본점이 한가운데다: {r['최적표본위상UI']}")
ok(serdes.눈한가운데(np.array([0.5] * 8)) == 4, "평평한 높이 -> 틀 한가운데")
ok(serdes.눈한가운데(np.array([0.1, 0.9, 0.2, 0.05])) == 1, "안 평평하면 제일 높은 위상")
ok(serdes.눈한가운데(np.array([1e-5] * 3 + [0.9] + [1e-5] * 4)) == 3,
   "**1e-5 짜리 실눈을 평평한 것으로 보지 않는다** -- 첫 판이 여기서 틀렸다")

print("\n[물리 -- 잰 눈은 peak distortion 한계보다 작을 수 없다]")
앞눈, 앞너비 = float("inf"), float("inf")
for 손실 in (3.0, 6.0, 9.0, 12.0, 20.0):
    h = serdes.채널(손실, sps, 64)
    y = np.convolve(깨끗, h, mode="full")[:len(깨끗)]
    잰것 = serdes.아이재기(y, sps)
    c = serdes.커서들(h, sps)
    ok(잰것["눈높이"] >= c["아이높이_ISI"] - 1e-9,
       f"{손실:.0f}dB: 잰 눈 {잰것['눈높이']:.4f} >= peak distortion "
       f"{c['아이높이_ISI']:+.4f}")
    # **세로로 닫힌 눈은 가로로도 닫혀 있어야 한다.** 첫 판은 "높이>0 인 위상의 수" 로
    # 너비를 세어서 0.001 V 까지 닫힌 눈을 1.00 UI 로 냈다(실측 2026-09-15).
    if 잰것["눈높이"] < 0.05:
        ok(잰것["눈너비UI"] == 0.0,
           f"{손실:.0f}dB: 눈높이 {잰것['눈높이']:.4f} 인데 너비가 "
           f"{잰것['눈너비UI']:.2f} UI -- **닫힌 눈은 너비 0 이다**")
    ok(잰것["눈높이"] < 앞눈, f"{손실:.0f}dB: 손실이 커지면 눈이 작아진다")
    앞눈 = 잰것["눈높이"]
    ok(sum(abs(x) for x in c["후행"]) > sum(abs(x) for x in c["선행"]),
       f"{손실:.0f}dB: **후행 커서가 선행보다 크다** -- 최소위상 채널이다(DFE 가 뜻이 있다)")

print("\n[양자화·프루닝 -- 연구 기여 2번이 여기 선다]")
탭 = np.array([1.0, -0.5, 0.25, -0.125, 0.0625])
ok(np.allclose(serdes.양자화(탭, 12), 탭, atol=1e-3), "12비트면 거의 그대로")
ok(np.array_equal(np.sign(serdes.양자화(탭, 1)), np.sign(탭)),
   "1비트는 부호만 남는다")
ok(abs(np.max(np.abs(serdes.양자화(탭, 4)))) == 1.0, "최댓값 스케일이 보존된다")
q = serdes.양자화(탭, 3)
ok(np.max(np.abs(q - 탭)) > 1e-3, "**3비트는 실제로 값을 바꾼다** -- 안 바꾸면 쓸기가 헛돈다")
ok(int(np.sum(serdes.프루닝(탭, 0.4) != 0)) == 2, "프루닝이 남길 수를 지킨다")
ok(np.array_equal(serdes.프루닝(탭, 1.0), 탭), "다 남기면 그대로")
ok(serdes.프루닝(탭, 0.0)[np.argmax(np.abs(탭))] != 0, "적어도 제일 큰 탭 하나는 남는다")

print("\n[구별되나 -- 오차막대 안의 차이를 '같다'고 말하지 않는다]")
다름, 말 = serdes.구별되나(709, 105000, 8, 105000)
ok(다름, f"709 대 8 오류는 구별된다: {말[:50]}")
같음, 말2 = serdes.구별되나(11, 105000, 8, 105000)
ok(not 같음, f"**11 대 8 오류는 구별 안 된다**: {말2[:60]}")
ok("구별 안 된다" in 말2 and "비트를 더 세라" in 말2,
   "구별 안 되면 그렇게 말하고 어떻게 해야 하는지도 말한다")

print("\n[ADC -- 분해능과 풀스케일은 따로 못 고른다]")
# 3비트 -> 단계수 4, 눈금 0.25, 코드 범위 [-4, +3].
# **2의 보수는 안 대칭이다** -- 양수 쪽이 한 눈금 먼저 잘린다. 0.9 는 코드 3.6 -> 4 인데
# 위 끝이 3 이라 잘리고, -0.9 는 코드 -3.6 -> -4 로 아래 끝에 딱 맞아 안 잘린다.
x = np.array([0.0, 0.4, 0.9, 1.4, -1.4, -0.9])
q, 클립 = serdes.ADC(x, 3, 1.0)
ok(np.allclose(q, [0.0, 0.5, 0.75, 0.75, -1.0, -1.0]),
   f"양자화하고 풀스케일 밖은 자른다: {list(np.round(q, 3))}")
ok(abs(클립 - 3 / 6) < 1e-9,
   f"**잘린 비율을 센다**: {클립:.3f} (6개 중 3개 -- 양수 쪽이 한 눈금 먼저 잘린다)")
ok(serdes.ADC(np.array([0.74, -0.99]), 3, 1.0)[1] == 0.0,
   "위 끝 +3, 아래 끝 -4 안쪽은 안 잘린다")
ok(serdes.ADC(np.array([1.0]), 3, 1.0)[1] == 1.0,
   "**+풀스케일 자신은 잘린다** -- 코드 4 는 3비트 2의 보수에 없다")
ok(serdes.ADC(np.array([-1.0]), 3, 1.0)[1] == 0.0, "-풀스케일은 안 잘린다")
ok(serdes.ADC(x, 0, 1.0)[0] is x, "0비트는 ADC 를 안 쓴다는 뜻")
ok(serdes.ADC(x, 12, 10.0)[1] == 0.0, "넉넉한 풀스케일이면 안 잘린다")
큰것 = serdes.ADC(x, 12, 10.0)[0]
ok(np.max(np.abs(큰것 - x)) < 10.0 / 2 ** 11, "12비트는 눈금 안에서 원래 값에 붙는다")

A = dict(비트수=60000, 손실dB=25.0, SNRdB=30.0, sps=8, FFE탭=11, DFE탭=8, 씨=7)
기준 = serdes.링크(**A)
ok(기준["ADC비트"] == 0 and 기준["클립비율"] == 0.0, "ADC 를 안 쓰면 안 잘린다")
넉넉 = serdes.링크(**A, ADC비트=12, ADC풀스케일시그마=3.0)
ok(넉넉["오류수"] == 기준["오류수"],
   f"**12비트 ADC 는 float 과 같은 답을 낸다**: {넉넉['오류수']} vs {기준['오류수']}")
거침 = serdes.링크(**A, ADC비트=3, ADC풀스케일시그마=2.5)
ok(거침["오류수"] > 기준["오류수"] * 3, f"3비트는 크게 나빠진다: {거침['오류수']}")
좁게 = serdes.링크(**A, ADC비트=6, ADC풀스케일시그마=1.0)
ok(좁게["클립비율"] > 0.2,
   f"**풀스케일을 좁히면 대량으로 잘린다**: {100 * 좁게['클립비율']:.1f}%")
ok("range failure" in serdes.말로(좁게),
   "많이 잘렸으면 **분해능 결과가 아니라 범위 실패라고 적는다**")
ok("range failure" not in serdes.말로(넉넉), "안 잘렸으면 안 적는다")
넓게 = serdes.링크(**A, ADC비트=5, ADC풀스케일시그마=8.0)
알맞게 = serdes.링크(**A, ADC비트=5, ADC풀스케일시그마=2.5)
ok(알맞게["오류수"] < 넓게["오류수"],
   f"**너무 넓은 풀스케일은 분해능을 버린다**: 2.5s {알맞게['오류수']} vs 8s {넓게['오류수']}")
ok(알맞게["클립비율"] > 0.001,
   f"**잘 맞춘 ADC 는 조금 자른다** -- 0% 가 최적이 아니다: "
   f"{100 * 알맞게['클립비율']:.2f}%")

쓸 = serdes.ADC쓸기((5, 8), (2.5, 3.0), 비트수=40000, 손실dB=25.0, SNRdB=30.0,
                 sps=8, FFE탭=11, DFE탭=8, 씨=7)
글 = serdes.ADC쓸기말로(쓸)
ok("clipped" in 글, "격자에 클립률을 같이 찍는다")
ok("winner's curse" in 글 and "re-measured BER" in 글,
   "**고른 값은 낙관적이라고 적고 다른 씨로 다시 잰 값을 따로 낸다**")
ok(쓸["고르기씨"] != 7, "다시 잴 때 쓴 씨가 쓸 때 쓴 씨와 다르다")
ok(any(x2["다시잰오류수"] != min(c["오류수"] for c in x2["칸"]) for x2 in 쓸["줄"]),
   "**다시 잰 오류 수가 격자의 최솟값과 다르다** -- 같으면 다시 잰 것이 아니다")
try:
    serdes.ADC쓸기((5,), (2.5,), 고르기씨=7, 비트수=20000, 손실dB=25.0, SNRdB=30.0,
                 sps=8, FFE탭=11, DFE탭=8, 씨=7)
    ok(False, "같은 씨로 다시 재는 것을 막는다")
except ValueError as e:
    ok("다른 씨라야" in str(e),
       f"**같은 씨로 '다시 재는' 것을 거부한다**: {str(e)[:60]}")
ok("same (within error)" not in 글, "여기서도 `same` 이라는 낱말을 안 쓴다")

print("\n[반사 -- 백플레인은 매끄러운 손실만 있는 것이 아니다]")
# H_total(f) = H_skin(f)(1 + G e^-j2pi f tau) -> f*tau = 1/2 에 노치, 깊이 20log10(1-G).
# 실측 2026-09-15: G=0.35, tau=4심볼 -> 이론 -3.74 dB @ 0.25 x Nyq, 잰 값 -3.75 @ 0.250.
sps16 = 16
민것 = serdes.채널(20.0, sps16, 64)
낀것 = serdes.채널(20.0, sps16, 64, ((0.35, 4.0),))
비 = np.abs(np.fft.rfft(낀것)) / np.maximum(np.abs(np.fft.rfft(민것)), 1e-15)
f = np.fft.rfftfreq(len(민것), 1.0) / (0.5 / sps16)
쓸 = (f > 0.02) & (f <= 1.0)
깊이 = 20 * np.log10(비[쓸].min())
자리 = f[쓸][int(np.argmin(비[쓸]))]
이론깊이 = 20 * math.log10(1 - 0.35)
ok(abs(깊이 - 이론깊이) < 0.2,
   f"**노치 깊이가 20log10(1-G) 와 맞는다**: 잰 {깊이:.2f} dB vs 이론 {이론깊이:.2f} dB")
ok(abs(자리 - 0.25) < 0.02,
   f"**노치 자리가 f*tau = 1/2 와 맞는다**: 잰 {자리:.3f} x Nyq vs 이론 0.250")
ok(비[쓸].min() < 0.9, "반사가 없으면 안 생기는 골이다")
ok(np.allclose(serdes.채널(20.0, sps16, 64, ()), 민것),
   "반사를 안 주면 스킨이펙트 그대로")
깊은것 = serdes.채널(20.0, sps16, 64, ((0.6, 4.0),))
비2 = np.abs(np.fft.rfft(깊은것)) / np.maximum(np.abs(np.fft.rfft(민것)), 1e-15)
ok(비2[쓸].min() < 비[쓸].min(), "계수가 크면 노치가 깊어진다")

ok(serdes.반사읽기("0.35@11, 0.2@4") == [(0.35, 11.0), (0.2, 4.0)], "반사 글을 읽는다")
ok(serdes.반사읽기("") == [], "빈 글은 빈 것")
for 나쁜, 까닭 in [("0.35", "꼴이라야"), ("1.5@11", "0 과 1 사이"),
               ("0.3@0", "0보다 커야"), ("x@1", "못 읽었다")]:
    try:
        serdes.반사읽기(나쁜)
        ok(False, f"**{나쁜!r} 를 막는다**")
    except ValueError as e:
        ok(까닭 in str(e), f"{나쁜!r} 를 막고 까닭을 댄다: {str(e)[:40]}")

print("\n[떠있는 DFE 탭 -- 어디에 놓느냐가 몇 개냐를 이긴다]")
반사 = ((0.35, 11.0),)
A = dict(비트수=200000, 손실dB=20.0, SNRdB=28.0, sps=8, FFE탭=11, 반사=반사, 씨=7)
r = serdes.링크(**A, DFE탭=4)
ok(r["DFE자리"] == [1, 2, 3, 4], f"탭 수를 주면 이어진 자리다: {r['DFE자리']}")
잔류 = [abs(float(np.mean(r["표본"][m:] * r["비트"][:len(r["표본"]) - m])))
      for m in range(1, 14)]
ok(잔류[10] > 4 * max(잔류[:10] + 잔류[11:]),
   f"**반사가 지연 11 에 홀로 선 커서로 나온다**: {잔류[10]:.3f} vs 나머지 최대 "
   f"{max(잔류[:10] + 잔류[11:]):.3f}")
찾은것 = serdes.반사자리찾기(r["표본"], r["비트"], 최대지연=30, 건너뛸앞=4, 몇개=3)
ok(11 in 찾은것, f"**반사 자리를 찾아낸다**: {찾은것}")
ok(serdes.반사자리찾기(r["표본"], r["비트"], 최대지연=30, 건너뛸앞=4, 몇개=1) == [11],
   "제일 큰 것 하나만 달라면 11 이다")

떠 = serdes.링크(**A, DFE자리=[1, 2, 3, 4, 11])
ok(떠["DFE자리"] == [1, 2, 3, 4, 11], f"준 자리를 그대로 쓴다: {떠['DFE자리']}")
ok(len(떠["DFE탭"]) == 5, "자리 수만큼 탭이 선다")
ok(abs(떠["DFE탭"][4] - 0.35) < 0.08,
   f"**11 번 탭이 반사 계수 0.35 를 잡는다**: {떠['DFE탭'][4]:.3f}")
이어진8 = serdes.링크(**A, DFE탭=8)
ok(떠["오류수"] < 이어진8["오류수"] / 10,
   f"**떠있는 5탭이 이어진 8탭을 자릿수로 이긴다**: {떠['오류수']} vs {이어진8['오류수']}")
하나 = serdes.링크(**A, DFE자리=[11])
ok(하나["오류수"] < 이어진8["오류수"] / 10,
   f"**탭 하나만 제자리에 놓아도 이어진 8탭을 이긴다**: {하나['오류수']} vs {이어진8['오류수']}")
ok("at 11 UI" in serdes.말로(떠) and "@1,2,3,4,11" in serdes.말로(떠),
   "답에 반사와 탭 자리를 적는다")
ok(serdes.링크(비트수=20000, 손실dB=20.0, SNRdB=28.0, sps=8, DFE자리=[3, 1, 3])["DFE자리"]
   == [1, 3], "자리를 정렬하고 겹친 것을 지운다")

print("\n[긴 FFE 가 발산하지 않는다 -- 걸음은 탭 수로도 나눠야 한다]")
# LMS 안정 조건이 mu < 2/(L*sigma^2) 다. 전력으로만 나누면 탭이 길어질 때 터진다 --
# 실측 2026-09-15: FFE 29탭이 탭 1.08e+06 까지 갔다. 그 상태로 "탭을 늘려도 안 낫다" 고
# 말하면 물리가 아니라 내 걸음을 잰 것이 된다.
for L in (11, 23, 29, 35):
    r = serdes.링크(비트수=60000, 손실dB=20.0, SNRdB=28.0, sps=8, FFE탭=L,
                  반사=((0.35, 11.0),), 씨=7)
    ok(r["판정"] != serdes.못잼 and not r["적응"]["발산"],
       f"FFE {L}탭이 수렴한다: {r['판정']} / {r['왜'][:44]}")
긴것 = serdes.링크(비트수=100000, 손실dB=20.0, SNRdB=28.0, sps=8, FFE탭=29,
                반사=((0.35, 11.0),), 씨=7)
짧은것 = serdes.링크(비트수=100000, 손실dB=20.0, SNRdB=28.0, sps=8, FFE탭=11,
                 반사=((0.35, 11.0),), 씨=7)
ok(긴것["오류수"] < 짧은것["오류수"] / 5,
   f"**스팬이 반사에 닿으면 FFE 로도 잡힌다**: 29탭 {긴것['오류수']} vs 11탭 {짧은것['오류수']}")

print("\n[학습 구간과 측정 구간을 가른다]")
r = serdes.링크(비트수=30000, 손실dB=12.0, SNRdB=26.0, sps=8, FFE탭=9, 학습비율=0.3, 씨=2)
ok(r["잰비트"] < 30000 * 0.75,
   f"**BER 을 학습에 안 쓴 비트로만 센다**: 잰비트 {r['잰비트']} / 3만")
ok(r["잰비트"] > 30000 * 0.6, f"측정 구간이 남아 있다: {r['잰비트']}")

print("\n[DFE 탭이 채널의 후행 커서 비와 맞는다 -- 손계산으로 확인되는 물리]")
# 상관으로 잰 첫 DFE 탭은 **p1/p0**(첫 후행 커서 / 메인 커서) 여야 한다. 이 항등식이
# 탭 추정과 AGC 를 한꺼번에 붙든다 -- AGC 를 빼면 탭이 이득만큼 작아져 어긋난다
# (실측 2026-09-15: 0.593 -> 0.143). BER 은 문턱 0 슬라이서라 그대로여서 안 걸린다.
h = serdes.채널(20.0, 8, 64)
c = serdes.커서들(h, 8)
바람 = c["후행"][0] / c["메인"]
r = serdes.링크(비트수=30000, 손실dB=20.0, SNRdB=28.0, sps=8, DFE탭=4, 씨=3)
ok(abs(r["DFE탭"][0] - 바람) < 0.05,
   f"첫 DFE 탭 {r['DFE탭'][0]:.4f} ~= p1/p0 {바람:.4f} "
   f"(어긋남 {100 * abs(r['DFE탭'][0] - 바람) / 바람:.1f}%)")
ok(all(abs(t) < 1.0 for t in r["DFE탭"]),
   f"탭이 메인 커서로 정규화돼 있다(읽을 수 있는 값이다): {[round(t, 3) for t in r['DFE탭']]}")
ok(r["DFE탭"][0] > r["DFE탭"][1] > r["DFE탭"][2],
   "후행 커서는 뒤로 갈수록 작아진다")

print("\n[정렬 -- 채널 지연만큼 밀지 않으면 BER 이 0.5 가 된다]")
# 실측: sps=8 에서 20dB 채널의 펄스 꼭대기는 심볼 하나 뒤에 있다(지연심볼=1).
# 그 밀기를 빼먹으면 정답을 한 심볼 어긋난 데 대고 세게 되어 **모든 BER 이 동전
# 던지기(0.5)로 나온다** -- 등화기가 나쁜 것처럼 보이지만 재는 자리가 틀린 것이다.
