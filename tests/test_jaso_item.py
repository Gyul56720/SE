"""**문항이 요건 여럿으로 갈리는가. 그리고 갈린 표가 `reason/` 에서 도는가.**

    python3 tests/test_jaso_item.py

두 가지를 붙든다.

  1. **교차 요건(F4).** 문항이 "무엇인지 짚어라" 와 "경험으로 뒷받침해라" 를 같이
     물으면 **짚은 것과 든 경험이 같은가** 라는 요건이 하나 더 생긴다. 일반 LLM 이
     지는 자리가 여기고, 따로 읽으면 안 보인다.
  2. **새 판정기를 안 만들었는가.** 쪼갠 표는 `reason/` 이 읽는 꼴이어야 한다.
     여기서 두 정거장을 또 구현하면 두 벌이 생기고 두 벌은 언젠가 갈라진다
     (`brain/README.md`).
"""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from jaso import item as IT                                        # noqa: E402
from reason import schema as RS                                    # noqa: E402

fails = []


def ok(cond, msg):
    print(("  OK   " if cond else "  실패 ") + msg)
    if not cond:
        fails.append(msg)


역량문항 = ("본인이 지원한 직무를 수행하기 위해 필요한 역량은 무엇이라고 생각하며, "
           "이를 갖추기 위해 어떤 노력을 했는지 구체적인 경험을 바탕으로 기술해 "
           "주십시오. (1,000자 이내, 공백 제외)")


print("── 한 문장에 요구가 여럿 숨어 있다 ──────────────────────")
q = IT.쪼개기(역량문항)
종류 = [r.종류 for r in q.요구]
ok(q.쪼갬 >= 3, f"요구가 {q.쪼갬}개로 갈렸다 ({' · '.join(종류)})")
ok("지목" in 종류 and "행동" in 종류 and "경험" in 종류,
   "지목 · 행동 · 경험이 다 잡혔다")


print("\n── 교차 요건 -- **F4 가 잡히는 유일한 자리** ────────────")
이음 = [r for r in q.요구 if r.이음인가]
ok(len(이음) == 1, "이음 요건이 하나 생겼다")
ok(이음 and 이음[0].이음대상[0] != 이음[0].이음대상[1],
   "이음이 서로 다른 두 요구를 견준다")
대상 = {r.id: r.종류 for r in q.요구}
ok(이음 and 대상.get(이음[0].이음대상[1]) == "경험",
   "**경험 쪽에 건다** -- 사전 순서로 집으면 `행동` 이 먼저 잡히는데, F4 는 "
   "'짚은 역량과 든 **경험**이 같은가' 라서 뜻이 어긋난다 (회귀 못)")
민문항 = IT.쪼개기("성장 과정에 대해 자유롭게 서술하십시오.")
ok(not [r for r in 민문항.요구 if r.이음인가],
   "(대조군) 지목도 경험도 없는 문항에는 이음이 안 생긴다")


print("\n── 글자 수 규약 -- 표기가 제각각이다 ────────────────────")
for 글, 하, 상, 포함 in (
        ("(1,000자 이내, 공백 제외)", 0, 1000, False),
        ("(500~700자)", 500, 700, True),
        ("(700자 이내)", 0, 700, True),
        ("(공백 포함 800자)", 0, 800, True),
        ("(300자 이상 600자 이내)", 300, 600, True)):
    got = IT.글자수규약(글)
    ok(got == (하, 상, 포함), f"{글} -> {got}")
ok(IT.글자수규약("자유롭게 서술하십시오.") == (0, 0, True),
   "**안 적혔으면 0 이다 -- 짐작하지 않는다.** J005 가 못 재는 것은 못 재는 것이다")
ok(IT.쪼개기("(500~700자)").하한 == 500,
   "(회귀 못) `500~700자` 의 하한을 놓치지 않는다 -- 하한 쪽 `자` 는 대개 없다")


print("\n── 못 쪼갠 것을 쪼갠 척하지 않는다 ─────────────────────")
ok(민문항.쪼갬 == 1 and 민문항.요구[0].종류 == "기술",
   "사전이 못 보는 문항은 `기술` 하나로 떨어진다")


print("\n── 문서에서 문항을 읽는다 ──────────────────────────────")
글 = "---\n회사: \"가\"\n---\n\n## 1. 지원 이유는? (300자)\n\n본문\n\n## 2. 포부는? (400자)\n\n본문\n"
qs = IT.문서읽기(글)
ok(len(qs) == 2 and qs[0].번호 == "1" and qs[1].상한 == 400,
   f"문항 {len(qs)}개를 번호와 글자 수까지 읽었다")


print("\n── **판정기를 새로 안 만들었다** -- reason 이 읽는다 ─────")
s = RS.읽기(IT.스키마(q, 걸린것={이음[0].id}))
vs = RS.검사(s)
ok(not RS.hard(vs), f"S001~S008 hard 위반이 없다 ({[str(v) for v in RS.hard(vs)]})")
ok(all(e.출처.strip() for e in s.요건),
   "요건마다 출처(문항 원문)가 적혀 있다 -- S005 가 보는 자리")
ok(s.요건 and len(s.입장) == len(q.요구), "요구마다 양측 입장이 적혔다")
빈것 = RS.검사(RS.읽기(IT.스키마(q)))
ok(any(v.규칙 == "S007" for v in 빈것),
   "**걸린 것이 없으면 S007 이 잡는다** -- 다툴 거리가 없으면 다툼 물음이 아니다. "
   "억지로 '섬' 을 내지 않는다")

print()
print(f"실패 {len(fails)}건" if fails else "전부 통과")
raise SystemExit(1 if fails else 0)
