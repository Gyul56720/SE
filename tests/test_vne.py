"""VNE 측정 자가 **자기 자신에게 속지 않는가.**

여기서 붙드는 것은 배치 방법의 품질이 아니라 **자의 정직성**이다. 오늘 이 저장소가 세 번
겪은 일이 전부 재는 쪽의 결함이었다 -- 붙여 센 관측, 자기에 안 닿은 사냥, 지난 세대를
지키던 게이트. 그러니 자부터 잰다.
"""

from __future__ import annotations

import sys
from pathlib import Path

뿌리 = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(뿌리))

from vne import embed as EM                                        # noqa: E402
from vne import measure as MS                                      # noqa: E402
from vne import topo as T                                          # noqa: E402

FAIL: list = []


def ok(cond, what):
    print(("  통과  " if cond else "  실패  ") + what)
    if not cond:
        FAIL.append(what)


작게 = dict(요청수=40, 바탕노드수=25)

print("== 인스턴스가 씨앗으로 재현되는가 ==")
ㄱ, ㄴ = T.바탕망(씨앗=3, 노드수=20), T.바탕망(씨앗=3, 노드수=20)
ok(ㄱ.링크 == ㄴ.링크 and ㄱ.노드 == ㄴ.노드, "같은 씨앗이면 **글자까지 같은 망**이다")
ok(T.바탕망(씨앗=4, 노드수=20).링크 != ㄱ.링크, "씨앗이 다르면 다른 망이다")
ok(len(T._가장큰덩이(ㄱ)) == len(ㄱ.노드),
   "**이어진 망만 돌려준다** -- 갈라진 망의 수용률은 위상 탓이지 방법 탓이 아니다")
흐름 = T.요청흐름(씨앗=2, 개수=10)
ok([r.이름 for _, _, r in 흐름] == [r.이름 for _, _, r in T.요청흐름(씨앗=2, 개수=10)],
   "요청 흐름도 재현된다")
ok(all(t1 > t0 for t0, t1, _ in 흐름), "요청마다 수명이 있다(나갈 때 > 들어온 때)")
ok(all(len(T._가장큰덩이(r)) == len(r.노드) for _, _, r in 흐름),
   "요청망도 이어져 있다 -- 끊긴 요청은 어느 방법으로도 못 받는다")

print("\n== 항등식: 분모에서 빠진 수를 숨길 수 없다 ==")
r = MS.한판("탐욕", 씨앗=0, **작게)
ok(r["맞나"], f"**온요청 = 받음 + 거절 + 못잼** ({r['온요청']} = {r['받음']}+{r['거절']}+{r['못잼']})")
ok(r["수용률"] == round(r["받음"] / r["온요청"], 4),
   "수용률의 분모가 **온요청**이다(받음+거절이 아니다)")
ok(len(r["칸"]) == r["온요청"], "요청마다 칸이 하나씩 남는다 -- 짝 비교의 단위")

print("\n== 터지는 방법이 수용률을 올리지 못한다 ==")
# **오늘 가장 비싸게 배운 함정.** 점수의 분모가 줄면 점수는 저절로 오른다. 어려운 요청에서
# 터지는 방법이 그 요청을 표본에서 떨어뜨리면 수용률이 올라간다 -- 덜 잰 것이 개선이 된다.
def _반쯤터짐(바탕, 요청, 쓴c, 쓴b):
    if len(요청.노드) >= 5:                      # 큰 요청에서만 터진다(어려운 것을 피한다)
        raise RuntimeError("일부러 터뜨림")
    return EM.탐욕배치(바탕, 요청, 쓴c, 쓴b)

EM.방법들["_반쯤터짐"] = _반쯤터짐
try:
    t = MS.한판("_반쯤터짐", 씨앗=0, **작게)
    ok(t["못잼"] > 0, f"터진 요청이 **못잼으로 센다** ({t['못잼']}개) -- 조용히 사라지지 않는다")
    ok(t["맞나"], "터져도 항등식이 선다")
    ok(t["수용률"] <= r["수용률"] + 1e-9,
       f"**터지는 방법의 수용률이 더 높지 않다** (터짐 {t['수용률']} <= 멀쩡 {r['수용률']})")
    ok(t["받음"] + t["거절"] < t["온요청"],
       "받음+거절만 보면 분모가 줄어 있다 -- 그래서 그것을 분모로 안 쓴다")
    if t["받음"] + t["거절"]:
        속은수 = round(t["받음"] / (t["받음"] + t["거절"]), 4)
        ok(속은수 >= t["수용률"],
           f"**잘못된 분모를 쓰면 {속은수} 로 부풀어 오른다** (참값 {t['수용률']}) -- 그 차이가 함정의 크기다")
finally:
    EM.방법들.pop("_반쯤터짐", None)

print("\n== 짝지어 견주기: 표본이 다르면 안 견준다 ==")
앞 = MS.한판("탐욕cpu", 씨앗=0, **작게)
뒤 = MS.한판("탐욕", 씨앗=0, **작게)
d = MS.짝(앞, 뒤)
ok(d["견줄수있나"] and d["공통"] == 앞["온요청"], f"같은 씨앗이면 모든 요청이 공통이다 ({d['공통']})")
ok(d["Δ수용"] == 뒤["받음"] - 앞["받음"], "Δ수용이 두 판의 차이와 맞는다")
ok(isinstance(d["뒤만받은요청"], list) and isinstance(d["앞만받은요청"], list),
   "**어느 요청에서 갈렸는지** 남긴다 -- 수만 보면 서로 맞바꾼 것을 못 본다")
딴씨앗 = MS.한판("탐욕", 씨앗=1, **작게)
ok(not MS.짝(앞, 딴씨앗)["견줄수있나"],
   "**씨앗이 다르면 안 견준다** -- 다른 인스턴스에서 잰 것이다")
ok(not MS.짝(앞, MS.한판("탐욕", 씨앗=0, 요청수=40, 바탕노드수=18))["견줄수있나"],
   "바탕망 크기가 다르면 안 견준다")
ok(not MS.짝({}, 뒤)["견줄수있나"], "한쪽이 비면 안 견준다(0 으로 안 채운다)")

print("\n== 씨앗 하나는 측정이 아니다 ==")
# **실측 2026-09-13.** 씨앗 0 하나로 재고 이렇게 보고했다.
#     요청 200 -> Δ수용률 +0.1100 / 요청 500 -> +0.0380
# 효과가 요청 수에 따라 준 것처럼 보였다. 씨앗 넷으로 다시 재니 중앙값은 n 에 거의 안
# 움직이고(+0.085 / +0.0925 / +0.090) **씨앗에 다섯 배로 움직였다**(+0.038 ~ +0.195).
# 그 +0.0380 은 하필 최솟값이었다. 씨앗 하나로 낸 수는 방법의 성질이 아니라 인스턴스의 성질이다.
여럿 = MS.여러씨앗("탐욕cpu", "탐욕", range(6), 요청수=40, 바탕노드수=25)
ok(여럿["됐나"] and 여럿["씨앗수"] == 6, f"씨앗마다 짝지어 잰다 ({여럿.get('씨앗수')}개)")
ok(여럿["최소"] <= 여럿["중앙값"] <= 여럿["최대"], "중앙값이 최소~최대 안에 있다")
ok(여럿["부호p"] is not None, f"**씨앗 사이 부호검정을 낸다** (p={여럿['부호p']})")
ok("최소" in MS.여러씨앗보고(여럿) and "최대" in MS.여러씨앗보고(여럿),
   "보고가 중앙값만 내지 않고 **흩어짐을 같이 낸다**")
자기 = MS.여러씨앗("탐욕", "탐욕", range(5), 요청수=40, 바탕노드수=25)
ok(all(x["Δ수용률"] == 0 for x in 자기["각각"]), "**같은 방법끼리는 Δ 가 전부 0 이다** (자가 안 흔들린다)")
ok(자기["이긴씨앗"] == 0, "비긴 것을 이긴 것으로 세지 않는다")
말 = MS.여러씨앗보고(자기)
ok("씨앗을 넘어 이긴다" not in 말, f"**차이가 없으면 이겼다고 안 한다** ({말.splitlines()[-1][:50]})")
하나 = MS.여러씨앗("탐욕cpu", "탐욕", [0], 요청수=40, 바탕노드수=25)
ok(하나["부호p"] is None or 하나["부호p"] > 0.01,
   f"**씨앗 하나로는 못 가른다** (p={하나['부호p']}) -- 이겨도 우연과 구별이 안 된다")
ok("씨앗들" in (뿌리 / "vne/measure.py").read_text(encoding="utf-8"), "CLI 에 `--씨앗들` 이 있다")
ok("씨앗 하나로 잰 것이다" in (뿌리 / "vne/measure.py").read_text(encoding="utf-8"),
   "**씨앗 하나만 쟀을 때 그렇다고 말한다** -- 조용히 한 씨앗 수를 내지 않는다")

print("\n== 다리: MIP 를 배치기로 쓴다 ==")
ok("FF" in EM.방법들, f"방법에 FF 가 있다 ({sorted(EM.방법들)})")
_바 = T.바탕망(씨앗=0, 노드수=8, 꼴="random", p=0.6)
_요 = T.요청망(씨앗=5, 노드범위=(2, 3))
_탐 = EM.탐욕배치(_바, _요, {}, {})
_ff = EM.FF배치(_바, _요, {}, {})
ok(_ff["됐나"], "MIP 가 배치를 찾는다")
ok(set(_ff["노드배치"]) == set(_요.노드), "가상 노드가 **전부** 배치됐다")
ok(len(set(_ff["노드배치"].values())) == len(_ff["노드배치"]), "일대일이다(한 자리에 둘이 없다)")
for e, 길 in _ff["링크배치"].items():
    ok(길[0] == _ff["노드배치"][e[0]] and 길[-1] == _ff["노드배치"][e[1]],
       f"가상 링크 {e} 의 경로 끝이 배치와 맞는다")
    ok(all((길[i], 길[i + 1]) in _바.링크 or (길[i + 1], 길[i]) in _바.링크
           for i in range(len(길) - 1)), f"경로 {e} 가 실제 바탕 링크로 이어진다")
ok(abs(_ff["가중비용"] - EM.가중비용(_바, _요, _ff)) < 1e-6,
   f"MIP 목적값이 가중비용과 같다 ({_ff['가중비용']}) -- **같은 자로 잰다**")
ok(_ff["가중비용"] <= EM.가중비용(_바, _요, _탐) + 1e-9,
   f"**MIP 가 탐욕보다 가중비용이 낮거나 같다** ({_ff['가중비용']} <= "
   f"{EM.가중비용(_바, _요, _탐)}) -- 최적이니 그래야 한다")
# 남은 용량 위에 세우는가 -- 다 써 버리면 불능이 나와야 한다
_다씀 = {u: _바.노드[u]["cpu"] for u in _바.노드}
_막 = EM.FF배치(_바, _요, _다씀, {})
ok(not _막["됐나"] and _막["사유"] == EM.MIP불능,
   "**남은 용량이 없으면 불능이다** -- 온라인이라 앞 요청이 문 자원을 봐야 한다")

print("\n== 단측검정을 양측 문장으로 읽지 않는다 ==")
# **실측 2026-09-13.** 탐욕 vs FF 에서 `짝 0/40 · p 100%` 가 나왔는데 보고가 "잡음과
# 구별되지 않는다" 고 적었다. 마흔 짝이 전부 반대쪽이었다 -- 구별이 안 되는 게 아니라
# 뒤가 뚜렷하게 느린 것이다. `짝으로갈렸나` 는 "뒤가 빠른가" 만 보는 단측이다.
_ㄱ, _ㄴ = MS.짝판("탐욕", "FF", 씨앗=0, 요청수=30, 바탕노드수=8)
_말 = MS.견줌보고(_ㄱ, _ㄴ).splitlines()[-1]
ok("느리다" in _말, f"**뒤가 느리면 느리다고 한다** ({_말[:50]})")
ok("구별되지 않는다" not in _말, "느린 것을 '구별 안 된다'고 하지 않는다")

print("\n== 시간은 **번갈아** 재야 한다 (자가 한쪽으로 기울어 있었다) ==")
# **실측 2026-09-14.** `한판` 을 두 번 따로 돌리고 순번으로 짝지으면, 그 사이의 기계
# 드리프트가 **모든 짝을 같은 쪽으로** 민다. 탐욕 vs 탐욕 30짝을 열두 번 재니 뒤가 이긴
# 짝이 평균 8.8/30 이었다(공정하면 15). 그래서 아래 "못 가른다" 가 세 번에 한 번 빨개졌다.
# 통계로 덮을 일이 아니라 **배치**를 고칠 일이다 -- 요청마다 두 방법을 잇따라 재고,
# 짝 안에서 누가 먼저인지도 순번마다 뒤집는다.
_ㄷ, _ㄹ = MS.짝판("탐욕", "탐욕", 씨앗=0, 요청수=30, 바탕노드수=8)
ok(_ㄷ.get("짝지어쟀나") and _ㄹ.get("짝지어쟀나"),
   "**어떻게 쟀는지가 표본에 남는다** -- 따로 잰 시간과 번갈아 잰 시간은 같은 자가 아니다")
ok(_ㄷ["수용률"] == _ㄹ["수용률"] and _ㄷ["받음"] == _ㄹ["받음"],
   f"번갈아 재도 배치 결과는 그대로다 ({_ㄷ['수용률']} vs {_ㄹ['수용률']})")
ok(MS.한판("탐욕", 씨앗=0, 요청수=30, 바탕노드수=8)["수용률"] == _ㄷ["수용률"],
   "`한판` 과 `짝판` 이 같은 수용률을 준다 -- 배치는 시간과 무관하다")
_같 = MS.견줌보고(_ㄷ, _ㄹ).splitlines()[-1]
ok("못 가른다" in _같, f"**같은 방법끼리는 못 가른다고 한다** ({_같[:44]})")
ok("빠르다" not in _같 and "느리다" not in _같, "차이가 없으면 어느 쪽도 말하지 않는다")

print("\n== 비긴 짝은 부호가 없다 -- 표본에서 빼되 **숨기지 않는다** ==")
# **실측 2026-09-14.** `짝이김` 이 `b < a` 만 이김으로 세고 분모는 `len(짝)` 이었다.
# 시간은 6자리 반올림이라 짧은 일은 정말로 자주 비긴다 -- 240짝 중 51개(21%).
#     비김을 빼면 뒤 86/189 = 45.5% · 비김을 지면 뒤 86/240 = 35.8%
# 한쪽으로만 기우는 잘못이고, `_시간말` 의 `짝 - 이김` 이 그 비김을 삼켜 "뒤가 느리다" 를
# 없는 데서 만들어 냈다.
import perf as _P  # noqa: E402
ok(_P.짝이김([1.0, 2.0, 3.0], [1.0, 1.0, 4.0]) == (1, 2),
   f"**비긴 짝은 분모에서 뺀다** ({_P.짝이김([1.0, 2.0, 3.0], [1.0, 1.0, 4.0])})")
ok(_P.짝비김([1.0, 2.0, 3.0], [1.0, 1.0, 4.0]) == 1, "몇이 빠졌는지 따로 낸다")
ok(_P.짝이김([1.0, 1.0], [1.0, 1.0]) == (0, 0), "전부 비기면 표본이 0 이다 -- 0/2 가 아니다")
ok(_P.부호검정p(*_P.짝이김([1.0, 1.0], [1.0, 1.0])) is None,
   "표본이 0 이면 p 를 안 낸다 -- **못잼이지 빨강이 아니다**")
_ㅁ = MS.짝(_ㄷ, _ㄹ)
ok("짝비김" in _ㅁ, "짝 결과에 비김 수가 있다")
ok(_ㅁ["짝이김"][1] + _ㅁ["짝비김"] == _ㅁ["공통"],
   f"**이김+짐+비김 = 공통** 이 성립한다 ({_ㅁ['짝이김']} + 비김 {_ㅁ['짝비김']} vs 공통 {_ㅁ['공통']})")
ok("비김" in MS.견줌보고(_ㄷ, _ㄹ), "보고가 비김 수를 적는다 -- 줄어든 분모를 숨기지 않는다")

print("\n== 거절 사유가 죽은 측정이 아니다 ==")
# 처음엔 "남은 대역 최대값" 으로 갈랐더니 155개 링크 중 하나만 여유 있어도 경로없음이 되어
# 102건이 한 칸에 몰렸다. 이제 대역을 빼고도 길이 없나를 실제로 본다.
바탕 = T.바탕망(씨앗=0, 노드수=20)
큰요청 = T.망("큰것")
큰요청.노드 = {i: {"cpu": 9999.0, "xy": (0, 0)} for i in range(2)}
큰요청.링크 = {(0, 1): {"대역": 1.0}}
ok(EM.탐욕배치(바탕, 큰요청, {}, {})["사유"] == EM.노드부족,
   "CPU 가 모자라면 **노드부족**이다")
