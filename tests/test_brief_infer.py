"""**추론 층** -- 명제 · 기준선 · 판정. 그리고 자가 뒤집히지 않는가.

    python3 tests/test_brief_infer.py

제일 중요한 검사는 **이진 지표에 순위검정을 쓰지 않는가**다. 그 자리에서 자가 한 번
뒤집혔다(실측 2026-09-09): 방향 일치(0/1)를 `분위of` 로 쟀더니 오늘 값 1 이 과거
표본의 최댓값이라 **언제나 최상위 분위**가 되어, 일치율이 66% 든 5% 든 똑같이 최소
p 를 냈다. **자가 무엇을 재든 같은 답을 주면 그것은 자가 아니다.**

`law/mutate.py` 의 규율 그대로다 -- 통과만 보면 자가 좋아서인지 아무것도 못 잡아서인지
모른다. 그래서 여기서는 **놀라운 원장과 안 놀라운 원장을 둘 다** 넣어 본다.
"""
from __future__ import annotations

import sys
from dataclasses import replace
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from brief import gate as GT                                       # noqa: E402
from brief import infer as INF                                     # noqa: E402
from brief import ledger as LG                                     # noqa: E402

fails = []


def ok(cond, msg):
    print(("  OK   " if cond else "  실패 ") + msg)
    if not cond:
        fails.append(msg)


def 원장(계열: dict, 받은날="2026-09-09"):
    """{칸: [변화율%...]} -> 원장. 100 에서 시작해 그 변화율대로 걷는다."""
    n = len(next(iter(계열.values())))
    lv = {k: 100.0 for k in 계열}
    줄 = []
    for i in range(n):
        row = {"id": f"2026-{1 + i // 28:02d}-{1 + i % 28:02d}"}
        for k, ch in 계열.items():
            lv[k] *= (1 + ch[i] / 100)
            row[k] = lv[k]
        줄.append(row)
    return LG.Ledger(출처="검사", 받은날=받은날, 질의="검사", 줄=줄)


print("── 변화 ─────────────────────────────────────────────")
led = LG.Ledger(줄=[{"id": "d1", "a": 100.0}, {"id": "d2", "a": 110.0},
                    {"id": "d3", "a": 99.0}])
ch = INF.변화(led, "a")
ok(len(ch) == 2 and abs(ch[0][1] - 10.0) < 1e-9, f"100 -> 110 은 +10% ({ch[0][1]:.2f})")
ok(abs(ch[1][1] + 10.0) < 1e-9, f"110 -> 99 는 -10% ({ch[1][1]:.2f})")
영 = LG.Ledger(줄=[{"id": "d1", "a": 0.0}, {"id": "d2", "a": 5.0}])
ok(INF.변화(영, "a") == [], "**앞 값이 0 이면 그 걸음은 없다** -- 0 으로 안 나눈다")
ok(INF.변화(led, "없는칸") == [], "없는 칸이면 빈 목록")

print()
print("── 분위 (연속) ───────────────────────────────────────")
과거 = [float(i) for i in range(100)]
q, p = INF.분위of(과거, 200.0)
ok(q == 1.0 and abs(p - 2 / 101) < 1e-9,
   f"과거 최댓값보다 크면 분위 1.0, p 는 도달 가능한 최소 {2/101:.4f} ({p:.4f})")
q, p = INF.분위of(과거, 50.0)
ok(0.4 < q < 0.6 and p > 0.9, f"가운데면 분위 {q:.2f}, p {p:.2f} 로 안 놀랍다")
ok(INF.분위of([], 1.0) == (None, None), "표본이 없으면 (None, None)")
ok(INF.분위of(과거, -1.0)[1] < 0.05, "아래쪽 꼬리도 잡는다 -- 양측이다")

print()
print("── **이진은 기저율로 잰다** (자가 뒤집혔던 자리) ────────")
많이 = [1.0] * 90 + [0.0] * 10
q, p = INF.기저(많이, 1.0)
ok(abs(p - 91 / 101) < 1e-9,
   f"90% 일어나는 일이 오늘 일어났으면 p 는 0.90 근처여야 한다 ({p:.3f})")
q, p2 = INF.기저(많이, 0.0)
ok(abs(p2 - 11 / 101) < 1e-9, f"10% 짜리가 일어났으면 p 0.11 ({p2:.3f})")
ok(p > p2, "**잦은 일과 드문 일이 다른 p 를 받는다** -- 이것이 뒤집혔던 자리다")
드묾 = [0.0] * 99 + [1.0]
ok(INF.기저(드묾, 1.0)[1] < INF.기저(많이, 1.0)[1],
   "1% 짜리가 90% 짜리보다 낮은 p 를 받는다")
ok(INF.기저([0.0] * 50, 1.0)[1] == 1 / 51,
   "**한 번도 없었다고 p=0 이라 하지 않는다** -- 라플라스 (k+1)/(n+1)")

# 회귀 못: 옛 방식(순위)으로 재면 둘이 같아진다
옛1 = INF.분위of(많이, 1.0)[1]
옛2 = INF.분위of(드묾, 1.0)[1]
ok(abs(옛1 - 옛2) < 1e-12,
   "(회귀 못) 순위로 재면 90% 짜리와 1% 짜리가 **똑같은 p** 를 받는다 -- "
   f"둘 다 {옛1:.4f}. 그래서 이진에는 못 쓴다")

print()
print("── 도달 가능한 최소 p ─────────────────────────────────")
ok(abs(INF.최소p(99, False) - 0.02) < 1e-12, "연속(양측) 표본 99 -> 0.02")
ok(abs(INF.최소p(99, True) - 0.01) < 1e-12, "이진(한쪽) 표본 99 -> 0.01")
ok(INF.최소p(0) == 1.0, "표본이 없으면 1.0")
ok(INF.최소p(19, False) > INF.ALPHA,
   "표본 19 로는 연속 명제를 문턱 아래로 못 내린다 -- 원장이 짧아서지 평범해서가 아니다")

print()
print("── Holm 보정 ────────────────────────────────────────")
got = INF.holm([0.01, 0.02, 0.03])
ok(abs(got[0] - 0.03) < 1e-12, f"제일 작은 것에 m=3 을 곱한다 ({got[0]:.3f})")
ok(got[1] <= got[2] + 1e-12 and got[0] <= got[1] + 1e-12,
   f"단조성이 지켜진다 {[round(x,3) for x in got]}")
ok(all(x >= y - 1e-12 for x, y in zip(got, [0.01, 0.02, 0.03])),
   "**보정은 조이는 것이지 푸는 것이 아니다** -- 늘 단독 p 이상")
ok(INF.holm([]) == [], "빈 목록에서 안 죽는다")
ok(INF.holm([None, 0.01]) [0] is None, "잴 수 없던 명제는 None 그대로")
ok(all(x <= 1.0 for x in INF.holm([0.5, 0.6, 0.9])), "1.0 을 안 넘는다")

print()
print("── 판정: **못잼을 먼저 본다** ──────────────────────────")
ok(INF._판정(0.001, 5, 1) == "못잼", "표본이 최소 미만이면 못잼")
ok(INF._판정(0.001, 30, 20) == "못잼",
   "표본 30 · 명제 20 개면 도달 가능한 최소 p 가 문턱 위다 -> 못잼")
ok(INF._판정(0.001, 300, 1) == "이례", "충분하면 이례")
ok(INF._판정(0.400, 300, 1) == "평범", "충분한데 p 가 크면 평범")
ok(INF._판정(None, 300, 1) == "못잼", "p 가 없으면 못잼")
ok(INF._판정(0.03, 100, 4, True) == "이례",
   "이진은 같은 표본에서 더 잘 갈린다 (최소 p 가 절반)")
ok(INF._판정(0.03, 100, 4, False) == "못잼",
   "**같은 수인데 연속이면 못잼이다** -- 이진/연속을 뭉뚱그리면 안 되는 이유")

print()
print("── 명제 세우기 -- 정답을 아는 원장으로 ──────────────────")
# 평소 ±0.1% 만 움직이다가 오늘 +5% -- 명제가 하나뿐이라 가를 힘이 있다
튐 = 원장({"A": [0.1, -0.1] * 30 + [5.0]})
ms = INF.따져보기(튐)
ok(len(ms) == 1 and ms[0].종류 == "이례", f"칸 하나면 명제도 하나 ({len(ms)}개)")
ok(ms[0].판정 == "이례",
   f"평소 ±0.1% 인데 오늘 +5% 면 이례다 (p {ms[0].p:.4f} -> 보정 {ms[0].p보정:.4f})")
ok("과거 어느 한 걸음을 빼도" in ms[0].뒤집기,
   f"뒤집기: {ms[0].뒤집기}")

밋밋 = 원장({"A": [0.1, -0.1] * 30 + [0.1]})
ms2 = INF.따져보기(밋밋)
ok(ms2[0].판정 == "평범",
   f"평소와 같은 크기면 평범이다 (p {ms2[0].p:.3f}) -- **아무 원장에나 이례라고 "
   "하지 않는다**")

짧음 = 원장({"A": [0.1, -0.1] * 5 + [5.0]})
ok(INF.따져보기(짧음)[0].판정 == "못잼",
   "**같은 +5% 인데 원장이 짧으면 못잼이다** -- 값이 아니라 원장 크기가 정한다")

print()
print("── 동조 · 배합 ──────────────────────────────────────")
# A 와 B 가 90% 같은 방향. 오늘은 같은 방향
같이 = 원장({"A": [1.0, -1.0] * 45 + [1.0, 1.0],
             "B": [1.0, -1.0] * 45 + [-1.0, 1.0]})
d = INF.동조(같이, "A", "B")
ok(d is not None and d.이진, "동조 명제는 이진이다")
ok(d.p > 0.8, f"거의 늘 같이 움직이는데 오늘도 같으면 안 놀랍다 (p {d.p:.3f})")
반대 = 원장({"A": [1.0, -1.0] * 45 + [1.0, 1.0],
             "B": [1.0, -1.0] * 45 + [-1.0, -1.0]})
d2 = INF.동조(반대, "A", "B")
ok(d2.p < d.p,
   f"평소 같이 가는데 오늘 갈렸으면 더 낮은 p ({d2.p:.3f} < {d.p:.3f})")

b = INF.배합(같이, ["A", "B"])
ok(b is not None and b.이진 and "드문가" in b.말, "배합 명제가 선다")
ok("과거" in b.기준 and "%" in b.기준, f"기저율을 기준선으로 적는다: {b.기준}")
ok(INF.배합(원장({"A": [1.0, 2.0]}), ["A"]) is not None or True, "한 칸이어도 안 죽는다")

print()
print("── 근거 · 요약 ──────────────────────────────────────")
ok(all(r in {x["id"] for x in 튐.줄} for r, _ in ms[0].근거),
   "**근거가 전부 원장의 줄을 가리킨다**")
s = INF.요약(ms)
ok(s["세운수"] == 1 and s["이례"] == 1, f"요약이 센다 {s}")
s2 = INF.요약(INF.따져보기(짧음))
ok(s2["필요표본"] and s2["필요표본"] > 20,
   f"**못 가르면 몇 걸음이 있어야 하는지 적어 준다** ({s2['필요표본']})")
ok(INF.요약([])["세운수"] == 0, "빈 목록에서 안 죽는다")
ok(INF.따져보기(LG.Ledger(줄=[])) == [], "빈 원장이면 명제가 없다")

print()
print("── 관문 I001~I004 (RED) ──────────────────────────────")
ok(not GT.hard(GT.check_claims(ms, 튐)), "멀쩡한 명제에는 hard 위반이 없다 (GREEN)")

작은n = replace(ms[0], 판정="이례", n=5)
ok(any(v.rule == "I001" for v in GT.check_claims([작은n], 튐)),
   "**I001: 표본 5걸음인데 이례라고 하면 잡는다**")
못잴 = [replace(ms[0], 판정="이례", n=30)] * 20
ok(any(v.rule == "I001" for v in GT.check_claims(못잴, 튐)),
   "I001: 명제를 20개 세워 도달 가능한 최소 p 가 문턱 위인데 이례라고 하면 잡는다")

안보정 = replace(ms[0], p보정=None)
ok(any(v.rule == "I002" for v in GT.check_claims([안보정], 튐)),
   "**I002: 보정을 안 했으면 잡는다** -- 그중 하나는 반드시 놀랍다")
푼보정 = replace(ms[0], p=0.04, p보정=0.01)
ok(any(v.rule == "I002" for v in GT.check_claims([푼보정], 튐)),
   "I002: 보정 p 가 단독 p 보다 작으면 잡는다 -- 보정은 조이는 것이다")

헛근거 = replace(ms[0], 근거=(("없는줄", "A"),))
ok(any(v.rule == "I003" for v in GT.check_claims([헛근거], 튐)),
   "I003: 원장에 없는 줄을 가리키면 잡는다")

약함 = replace(ms[0], 판정="이례", 뒤집기="과거 한 걸음(3번째)만 빼도 판정이 바뀐다 -- 약한 결론이다")
vs = GT.check_claims([약함], 튐)
ok(any(v.rule == "I004" for v in vs), "I004: 한 줄에 기대는 결론을 짚는다")
ok(all(v.severity == "soft" for v in vs if v.rule == "I004"),
   "**I004 는 soft 다** -- 짚어 줄 뿐 기각하지 않는다")

print()
print("── check() 가 두 층을 같이 본다 ────────────────────────")
vs = GT.check([], 튐, None, "", claims=ms)
ok(isinstance(vs, list), "수 층과 추론 층이 한 자리를 지난다")
ok(not GT.hard(GT.check_claims([], 튐)), "명제가 없으면 위반도 없다")

print()
if fails:
    print(f"추론: {len(fails)}개 실패 -- {fails}")
    sys.exit(1)
print("변화 · 분위 · **기저율(자 뒤집힘 회귀 못)** · Holm · 못잼 우선 판정 · "
      "명제 세우기 · 뒤집기 · 관문 I001~I004 -- 통과")
