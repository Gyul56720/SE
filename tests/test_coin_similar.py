"""**지금과 닮은 과거를 찾는가** -- 그리고 닮음이 창·시간대가 만든 것이 아닌가.

    python3 tests/test_coin_similar.py

목표를 좁힌 뒤 이 파이프라인의 중심이 여기로 옮겨 왔다. "~를 바탕으로 미루어 보면
~할 것 같다" 의 **앞부분이 이 파일에서 나온다.** 그러므로 여기가 틀리면 뒤가 다 틀린다.
"""
from __future__ import annotations

import sys
from datetime import datetime, timedelta, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "tests"))

import _coin_fixture as FX                                            # noqa: E402
from coin import similar as SM                                        # noqa: E402

fails = []


def ok(cond, msg):
    print(("  OK   " if cond else "  실패 ") + msg)
    if not cond:
        fails.append(msg)


# ---------------------------------------------------------------- 날짜 보정
ok(SM.날짜("2021-05-21T08:00:00+00:00", 0) == "2021-05-21", "UTC 낮은 그날")
ok(SM.날짜("2021-05-21T08:00:00+00:00", 9) == "2021-05-21", "한국 기준으로도 그날")
ok(SM.날짜("2021-05-21T20:00:00+00:00", 0) == "2021-05-21", "UTC 밤은 그날")
ok(SM.날짜("2021-05-21T20:00:00+00:00", 9) == "2021-05-22",
   "**UTC 20시는 한국 기준 다음 날** -- 하루의 3분의 1이 밀린다")
ok(SM.날짜("", 9) == "", "못 읽으면 빈 값 -- 지어내지 않는다")

# ---------------------------------------------------------------- 벡터
A, B = FX.날짜(300), FX.날짜(900)
사건 = []
for 기준 in (A, B):
    t = datetime.strptime(기준, "%Y-%m-%d").replace(tzinfo=timezone.utc)
    for k, (유형, 나라) in enumerate([("규제금지", ("CN", "US")),
                                     ("해킹유출", ("JP",)), ("ETF", ("US",))]):
        사건 += FX.사건([(t - timedelta(days=k)).strftime("%Y-%m-%d")], 유형, 나라=나라)
딴것 = [FX.날짜(i) for i in range(100, 1400, 40)]
사건 += FX.사건(딴것, "고래이동", 나라=("XX",))
c = FX.계열(효과=0.0)

v = SM.뉴스벡터(사건, B, 3, 9)
ok("규제금지|CN" in v and "규제금지|US" in v, "뉴스 벡터가 (유형|나라) 로 센다")
ok(sum(v.values()) >= 4, f"창 안의 것을 센다 ({sum(v.values())}건)")
ok(not SM.뉴스벡터(사건, B, 1, 9).get("ETF"), "창 밖의 것은 안 센다")
시 = SM.시장벡터(c, B)
ok(all(0 <= x <= 1 for x in 시.values()) and 시, f"시장 벡터는 백분위 {list(시)}")
ok(not SM.시장벡터(c, c.날들[10]), "자료가 짧으면 못 잰다 -- 지어내지 않는다")

# ---------------------------------------------------------------- 닮음
# 처음에 이 자리는 `== 0.0` 이었다. 1 을 막으려던 것인데 **못 잰 것과 0 점을 섞었다**
# -- VM 에서 그 0 이 무게 0.5 로 평균에 들어가 합을 0.49 에 가뒀다. 지금은 nan 이다.
ok(SM._코사인({}, {}) != SM._코사인({}, {}),
   "**빈 벡터끼리는 못 잼(nan)** -- 1 도 아니고 0 도 아니다")
ok(SM._코사인({"a": 1}, {"a": 1}) == 1.0, "같으면 1")
ok(abs(SM._코사인({"a": 1}, {"b": 1})) < 1e-9, "겹치는 것이 없으면 0")
ok(SM._가까움({"x": 0.5}, {"x": 0.5}) == 1.0, "백분위가 같으면 1")
ok(abs(SM._가까움({"x": 0.0}, {"x": 1.0})) < 1e-9, "정반대면 0")
ok(SM._가까움({"x": 0.5}, {"y": 0.5}) != SM._가까움({"x": 0.5}, {"y": 0.5}),
   "겹치는 칸이 없으면 nan -- 못 잰 것과 0 을 안 섞는다")

s = SM.닮음({"뉴스": {"a": 1}, "시장": {"x": 0.5}, "흐름": {}},
            {"뉴스": {"a": 1}, "시장": {"x": 0.5}, "흐름": {}})
ok(s["뉴스"] == 1.0 and s["시장"] == 1.0, "**셋을 따로 낸다** -- 어느 덩이가 끌었는지 보이게")
ok(s["흐름"] != s["흐름"], "못 잰 덩이는 nan")
ok(abs(s["합"] - 1.0) < 1e-9, "못 잰 덩이는 합에서 빠진다 (0 으로 안 센다)")

# ---------------------------------------------------------------- 찾기
r = SM.찾기(c, 사건, {}, 오늘=B, 창일=3, 몇=3, 걸음=5)
ok(r["닮은날"], f"닮은 날을 찾는다 ({len(r['닮은날'])}개 · 견준 것 {r['본것']})")
찾은 = [x["날"] for x in r["닮은날"]]
ok(any(abs((datetime.strptime(d, "%Y-%m-%d")
            - datetime.strptime(A, "%Y-%m-%d")).days) <= 3 for d in 찾은),
   f"**심어 둔 무늬를 찾는다**: {A} vs 찾은 {찾은[:2]}")
ok(r["닮은날"][0]["닮음"]["뉴스"] > 0.9, "그 날의 뉴스 닮음이 높다")
ok(all(x["날"] < B for x in r["닮은날"]), "**미래를 안 본다**")
기 = datetime.strptime(B, "%Y-%m-%d")
ok(all((기 - datetime.strptime(x["날"], "%Y-%m-%d")).days >= 30 for x in r["닮은날"]),
   "**가까운 날은 뺀다** -- 어제와 오늘이 닮은 것은 아무 말도 안 한 것이다")
ok(all("뒤" in x for x in r["닮은날"]), "그 날 뒤에 무엇이 있었는지가 같이 온다")

# ---------------------------------------------------------------- 창을 바꾸면
첫 = {}
for 창 in (1, 3, 7):
    rr = SM.찾기(c, 사건, {}, 오늘=B, 창일=창, 몇=1, 걸음=5)
    첫[창] = rr["닮은날"][0]["날"] if rr["닮은날"] else ""
ok(len(set(첫.values())) == 1,
   f"**창을 바꿔도 같은 날이 나온다**: {첫} -- 통째로 바뀌면 창이 만든 닮음이다")

# ---------------------------------------------------------------- 손잡이가 적히나
from coin import clock as CK                                          # noqa: E402
ok(r["창일"] == 3 and r["시간대"] == CK.시간대() and r["무게"],
   "**쓴 시간대가 잰 값에 적힌다** -- None 을 적으면 무엇으로 쟀는지 못 밝힌다")
r9 = SM.찾기(c, 사건, {}, 오늘=B, 창일=3, 시간대=9, 몇=1, 걸음=9)
ok(r9["시간대"] == 9, "밖에서 준 시간대가 그대로 적힌다")
글 = SM.적기(r9)
ok("창 3일" in 글 and "UTC+9" in 글, "화면에도 창·시간대가 나온다")
ok("셈이지 예언이 아니다" in 글, "표본 다섯으로 예언하지 않는다고 적는다")

# ---------------------------------------------------------------- 허수 칸
# **실측 2026-09-09 (VM): `변동폭@1d 100% · 거래량@1d 100%` 가 찍혔다.**
# 고·저·거래량이 없는 봉으로 잰 것이라 두 계열이 통째로 0 이었고, 0 만 든 계열의
# 앞선백분위는 모든 자리에서 1.0 이다. 지표가 아니라 허수인데 "역대 최고" 로 보였고,
# 게다가 모든 날이 그 칸에서 완벽히 일치해 **시장 닮음을 통째로 부풀렸다**
# (그날 상위 다섯이 0.94~0.96 으로 다 비슷했던 까닭).
from coin import chart as CH                                          # noqa: E402

죽은봉 = [[f"d{i}", 100 + i, 100 + i, 100 + i, 100 + i, 0.0] for i in range(200)]
p죽 = CH.전체(죽은봉)[-1]
ok("변동폭@1d" not in p죽, "**늘 0 인 변동폭은 칸에서 뺀다** (100% 로 안 찍는다)")
ok("거래량@1d" not in p죽, "늘 0 인 거래량도 뺀다")
ok(p죽, f"살아 있는 칸은 남는다 {sorted(p죽)}")
ok(CH.죽은칸([0.0] * 50) and CH.죽은칸([]) and CH.죽은칸([1.0]),
   "늘 같은 값 · 빈 것 · 하나뿐인 것은 죽은 칸")
ok(not CH.죽은칸([1.0, 2.0, 3.0]), "값이 움직이면 산 칸")
산봉 = [[f"d{i}", 100 + i, 101 + i, 99 + i, 100.5 + i, 1000 + i * 3] for i in range(200)]
ok("변동폭@1d" in CH.전체(산봉)[-1], "고·저가 있으면 변동폭이 산다")

# ---------------------------------------------------------------- 못 잼 != 0점
# 오늘 뉴스가 0건인 창에서 모든 후보의 뉴스 닮음이 0.00 으로 찍혔고, 그 0 이 무게
# 0.5 로 평균에 들어가 **합이 0.49 에서 천장을 쳤다.** 뉴스로 뽑힌 것이 아닌데
# 뉴스 점수가 순위를 눌렀다.
ok(SM._코사인({}, {}) != SM._코사인({}, {}), "**빈 뉴스끼리는 못 잼(nan)** -- 0 이 아니다")
ok(SM._코사인({"a": 1}, {}) != SM._코사인({"a": 1}, {}), "한쪽만 비어도 못 잼")
없 = SM.닮음({"뉴스": {}, "시장": {"x": 0.5}, "흐름": {"y": 0.3}},
             {"뉴스": {}, "시장": {"x": 0.5}, "흐름": {"y": 0.3}})
ok(abs(없["합"] - 1.0) < 1e-9,
   "**뉴스를 못 재면 시장·흐름으로만 잰다** -- 0.5 에서 천장 치지 않는다")
ok(없["뉴스"] != 없["뉴스"], "그리고 화면에 '못잼' 으로 나온다")
다름 = SM.닮음({"뉴스": {"a": 1}, "시장": {}, "흐름": {}},
               {"뉴스": {"b": 1}, "시장": {}, "흐름": {}})
ok(abs(다름["합"]) < 1e-9, "겹치는 뉴스가 없으면 그것은 **0 점이 맞다** (못 잰 것이 아니다)")

# ---------------------------------------------------------------- 비대칭
# 실측 2026-09-09 (VM): 오늘 뉴스 3건인데 상위 다섯이 전부 '뉴스 못잼 · 0건'.
# 한쪽만 비어도 못잼으로 뺐더니 **시험 안 본 날이 시험 본 날을 이겼다.**
있 = {"뉴스": {"규제금지|US": 1}, "시장": {"x": 0.5}, "흐름": {}}
빈 = {"뉴스": {}, "시장": {"x": 0.5}, "흐름": {}}
s1 = SM.닮음(있, 빈)
ok(s1["뉴스"] == 0.0,
   "**오늘 뉴스가 있는데 그날이 없으면 0점** -- 그날은 조용했다. 진짜 다름이다")
s2 = SM.닮음(빈, 있)
ok(s2["뉴스"] != s2["뉴스"],
   "**오늘 뉴스가 없으면 못잼** -- 아무도 뉴스로 못 견주니 공평하게 뺀다")
r2 = SM.찾기(c, 사건, {}, 오늘=B, 창일=3, 몇=3, 걸음=3)
ok(all(x["뉴스수"] > 0 for x in r2["닮은날"][:1]),
   "그래서 뉴스 있는 날이 다시 1등이다 (시험 안 본 날이 못 이긴다)")

# ---------------------------------------------------------------- 덩이별 · 브리핑
ok(set(r2.get("덩이별", {})) == {"뉴스", "시장", "흐름"},
   "**덩이별 의견이 따로 나온다** -- 뉴스·시장·흐름이 각자 과거를 고른다")
뉴탑 = r2["덩이별"]["뉴스"]
ok(뉴탑 == sorted(뉴탑, key=lambda x: -x["닮음"]["뉴스"]),
   "뉴스 덩이는 뉴스 닮음으로 줄 세운다 (합이 아니라)")
ok(r2.get("지금사건"), "브리핑에 실을 최근 사건이 같이 온다")
글2 = SM.적기(r2)
for 말 in ("실시간 브리핑", "뉴스가 고른 과거", "시장(차트)이 고른 과거",
           "돈 흐름이 고른 과거", "종합"):
    ok(말 in 글2, f"보고에 '{말}' 절이 있다")
ok("본보기" in 글2, "브리핑이 사건 제목을 그대로 싣는다 -- 벡터는 세지만 사람은 제목을 읽는다")

print()
print(f"실패 {len(fails)}개" if fails else "전부 통과")
raise SystemExit(1 if fails else 0)
