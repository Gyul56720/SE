"""`serdes.py` 의 **쓸기 도구들** -- 비트폭 · ADC · 손실. 도구의 배선을 붙든다.

`tests/test_serdes.py` 는 시뮬레이터의 물리와 교정을 본다(닫힌 꼴 BER · 아이 · 반사
노치 · 떠있는 탭). 이 파일은 그 위에 선 **쓸기 도구**가 제대로 말하는지를 본다:

    구별 안 된 것을 '같다' 로 읽지 않나
    한 씨로 워드 길이를 말하지 않나
    손실마다 같은 BER 자리로 옮겨 놓나 (고정 SNR 으로는 채널을 못 쓴다)

## 왜 갈랐나

한 파일일 때 2분 15초가 걸려 `scripts/precheck.sh` 의 25초 상한을 넘었고, 그래서
**매 커밋마다 안 돌았다.** 안 도는 검사는 검사가 아니다. 물리 쪽을 상한 안에 넣고
쓸기 쪽을 여기로 뺐다. 여기 숫자는 통계적 힘이 아니라 **배선**을 본다 -- 물리 주장은
저쪽 파일과 `serdes.py` 머리말의 실측이 붙든다.
"""

from __future__ import annotations

import math
import sys
from pathlib import Path

import numpy as np

뿌리 = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(뿌리))

import serdes

FAIL_목록 = []


def ok(참, 말):
    print(("  통과 " if 참 else "  실패 ") + 말)
    if not 참:
        FAIL_목록.append(말)


print("[교정 -- 닫힌 꼴 BER = Q(10^(SNR/20)) 과 나란히]")
for snr in (6.0, 8.0, 10.0):
    r = serdes.링크(비트수=200000, 손실dB=0.0, SNRdB=snr, sps=4, 학습비율=0.0, 씨=1)
    이론 = serdes.Q(10 ** (snr / 20.0))
    막대 = 3.0 / math.sqrt(max(r["오류수"], 1))          # 3시그마 상대폭
    어긋남 = abs(r["BER"] - 이론) / 이론
    ok(어긋남 < max(막대, 0.05),
       f"SNR {snr:.0f}dB: 잰 {r['BER']:.3e} vs 이론 {이론:.3e} "
       f"(어긋남 {100 * 어긋남:.1f}%, 3시그마 {100 * 막대:.1f}%)")

print("\n[구별 안 된 것을 같다고 읽지 않는다 -- 얼마나 더 세야 하는지 말한다]")
# 실측 2026-09-15: 25dB/SNR 30dB 에서 6비트가 35만 비트로 '구별 안 됨' 이었는데
# 필요한 것이 35.1만이었다 -- 경계였다. 140만으로 다시 재니 구별됐다(BER +31%).
# 그 한 줄이 없어서 "6비트면 열화 없음" 이라는 결론이 나왔다.
ok(serdes.가르려면몇비트(1e-3, 1e-3) == float("inf"), "같은 값은 영영 못 가른다")
ok(serdes.가르려면몇비트(0.0, 1e-3) == float("inf"), "0 은 이 식으로 못 다룬다")
필요 = serdes.가르려면몇비트(8.029e-4, 6.229e-4)
ok(3.4e5 < 필요 < 3.6e5, f"실측한 6비트 자리를 가르려면 ~35만 비트: {필요:,.0f}")
ok(serdes.가르려면몇비트(6.114e-4, 6.229e-4) > 1e7,
   "차이가 아주 작으면 필요한 비트가 천만을 넘는다 -- 사실상 같다는 뜻")
ok(serdes.가르려면몇비트(5.967e-2, 1.559e-2) < 1e4, "크게 다르면 조금만 세도 갈린다")

쓸 = serdes.비트폭쓸기((6, 8), 비트수=120000, 손실dB=25.0, SNRdB=30.0, sps=8,
                  FFE탭=11, DFE탭=8, 씨=7)
글 = serdes.쓸기말로(쓸)
ok("same (within error)" not in 글,
   "**`same` 이라는 낱말을 안 쓴다** -- 그 낱말이 'no degradation' 으로 옮겨 적혔다")
ok("NOT YET separated" in 글, "안 갈렸다고 말한다")
ok("evaluation bits to settle" in 글, "얼마나 더 세야 하는지 각 줄에 붙인다")
ok("not evidence of no degradation" in 글,
   "**없는 증거를 없음의 증거로 읽지 말라고 적는다**")
ok("PROVISIONAL" in 글, "못 가른 최소 비트폭에 잠정이라고 표를 단다")

print("\n[여러 씨 -- 한 씨로 워드 길이를 말하지 않는다]")
# 실측 2026-09-15, 손실 30dB 에서 계수 7비트를 씨 넷으로 돌린 값(float 대비 BER 올림):
#   -4.7% · +26.2% · +5.5% · -0.8%   -- 산포가 재려는 효과보다 크다.
# 한 씨만 보면 "7비트 충분" 도 "7비트 부족" 도 나온다. 그래서 평균과 산포를 같이 낸다.
m = serdes.여러씨((1, 2, 3, 4), lambda k: float(k))
ok(m["평균"] == 2.5 and m["씨수"] == 4, f"평균을 낸다: {m['평균']}")
ok(abs(m["산포"] - 1.118033988749895) < 1e-9, f"산포를 낸다: {m['산포']}")
ok(m["낮"] == 1.0 and m["높"] == 4.0, "제일 낮은 것과 높은 것도 낸다")
ok(serdes.여러씨((5,), lambda k: 7.0)["산포"] == 0.0, "씨 하나면 산포가 0 이다")
본것 = []
serdes.여러씨((3, 9), lambda k: 본것.append(k) or 0.0)
ok(본것 == [3, 9], f"**준 씨를 그대로 쓴다**: {본것}")

print("\n[손실 쓸기 -- 고정 SNR 으로는 채널을 못 쓴다]")
# 실측(SNR 30dB 고정, FFE11+DFE8): 10~20dB 는 오류 0(견줄 수 없다), 30dB 는 이미
# BER 3.2e-02 로 깨진 링크. 쓸 수 있는 창이 한 점뿐이라 손실끼리 견줄 수가 없다.
# 그래서 손실마다 SNR 을 이분법으로 옮겨 **같은 float BER 자리**에 놓는다.
점 = serdes.동작점SNR(20.0, 1e-3, 40000, 되풀이=7, sps=8, FFE탭=11, DFE탭=8, 씨=7)
ok(점["닿았나"], f"목표 BER 자리를 찾는다: {점['왜'][:60]}")
ok(0.2e-3 < 점["BER"] < 5e-3, f"찾은 자리의 BER 이 목표 언저리다: {점['BER']:.2e}")
ok(15.0 < 점["SNRdB"] < 35.0, f"그럴듯한 SNR 이다: {점['SNRdB']:.1f} dB")
높은손실 = serdes.동작점SNR(30.0, 1e-3, 40000, 되풀이=7, sps=8, FFE탭=11, DFE탭=8, 씨=7)
ok(높은손실["SNRdB"] > 점["SNRdB"] + 5,
   f"**손실이 크면 같은 BER 을 사는 데 SNR 이 더 든다**: "
   f"20dB {점['SNRdB']:.1f} -> 30dB {높은손실['SNRdB']:.1f}")
못닿 = serdes.동작점SNR(20.0, 1e-30, 30000, 낮게=10.0, 높게=12.0, 되풀이=3,
                   sps=8, FFE탭=11, DFE탭=8, 씨=7)
ok(not 못닿["닿았나"] and "믿지 마라" in 못닿["왜"],
   "**못 닿았으면 못 닿았다고 말한다** -- SNR 만 보면 닿은 줄 안다")

쓸 = serdes.손실쓸기((20.0, 30.0), (8, 10), 목표BER=1e-3, 비트수=30000,
                 찾기비트수=20000, 찾기되풀이=5, ADC도=False, 씨들=(7, 11),
                 sps=8, FFE탭=11, DFE탭=8)
글 = serdes.손실쓸기말로(쓸)
ok(len(쓸["줄"]) == 2 and all(len(x["칸"]) == 2 for x in 쓸["줄"]), "격자를 채운다")
ok(all(c["씨수"] == 2 for x in 쓸["줄"] for c in x["칸"]), "칸마다 씨를 여러 개 돌린다")
ok("+-" in 글 and "spread" in 글, "**산포를 같이 찍는다**")
ok("**A single seed cannot name a word length**" in 글,
   "**한 씨로는 워드 길이를 못 말한다고 적는다**")
ok("-4.7%" in 글 and "+26.2%" in 글, "그 실측 숫자를 그대로 든다")
ok(쓸["줄"][1]["동작점"]["SNRdB"] > 쓸["줄"][0]["동작점"]["SNRdB"],
   "손실이 큰 줄이 더 높은 SNR 에 앉는다")
# **평균이 작아도 산포가 크면 충분하다고 하지 않는다** -- 이것이 이 쓸기의 규율이다
# **판정을 검사 안에 다시 구현하지 않는다.** 첫 판이 그랬더니 `충분한가` 에서
# 산포 조건을 빼는 돌연변이가 그대로 살아남았다 -- 검사가 제 사본만 보고 있었다.
ok(not serdes.충분한가({"올림%": 0.5, "산포": 12.0}),
   "**평균 +0.5% 라도 산포 ±12% 면 충분하지 않다**")
ok(serdes.충분한가({"올림%": 1.0, "산포": 1.0}), "평균도 산포도 작아야 충분하다")
ok(not serdes.충분한가({"올림%": 40.0, "산포": 0.5}), "산포가 작아도 평균이 크면 아니다")
ok(serdes.충분한가({"올림%": 12.0, "산포": 12.0}, 넉넉함=3.0), "넉넉함이 바닥을 늘린다")
진짜 = serdes.손실쓸기((30.0,), (7, 10), 목표BER=1e-3, 비트수=60000, 찾기비트수=20000,
                  찾기되풀이=5, ADC도=False, 씨들=(7, 11, 23), sps=8, FFE탭=11, DFE탭=8)
칸7 = 진짜["줄"][0]["칸"][0]
칸10 = 진짜["줄"][0]["칸"][1]
ok(칸10["산포"] <= 칸7["산포"] + 3.0,
   f"**넓은 폭일수록 씨 산포가 무너진다**: 7b ±{칸7['산포']:.1f} vs 10b ±{칸10['산포']:.1f}")

print()
if FAIL_목록:
    print(f"실패 {len(FAIL_목록)}개 -- {FAIL_목록}")
    sys.exit(1)
print("serdes 쓸기: 구별 안 된 것을 같다고 안 한다 · 한 씨로 워드 길이를 안 말한다 · 손실마다 같은 BER 자리로 옮긴다 -- 통과")
