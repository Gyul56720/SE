"""`latex_formatter.답다듬기` -- 답에 박힌 LaTeX 가 **실제로 보이게** 바뀌나.

사용자(2026-09-15): "풀이는 latex 를 제공해줘야해."

프롬프트에 "LaTeX 로 써라" 고 적는 것만으로는 아무 일도 안 난다. 디스코드에는
`$\\frac{-3\\pm\\sqrt{17}}{2}$` 라는 **날글자**가 그대로 나간다. 그것을 바꾸는 것이
`답다듬기` 이고, 이 검사가 붙드는 것은 세 가지다.

  1. `$...$` 와 `$$...$$` 를 **실제로 집는가** (정규식이 빗나가면 아무 일도 안 난다)
  2. 못 그린 수식의 **원문이 남는가** -- 이 파일이 처음에 한 잘못이 "못 한 것을 한 척"
     이었다(```math 로 감싸 놓고 디스코드가 안 그리는 것을 몰랐다). 지우면 그때보다 나쁘다
  3. 수식이 **없으면 글을 안 건드리는가** -- 값 없이 글만 흔들면 그 자체가 결함이다
"""
from __future__ import annotations

import sys
from pathlib import Path

뿌리 = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(뿌리))
import latex_formatter as L                                       # noqa: E402

FAIL = []


def ok(조건, 말):
    print(("  통과  " if 조건 else "  실패  ") + 말)
    if not 조건:
        FAIL.append(말)


print("== 수식이 없으면 글을 안 건드린다 ==")
원문 = "이 문제는 그냥 2 더하기 3 이다.\n답: 5"
r = L.답다듬기(원문, 그림도=False)
ok(r["글"] == 원문.strip(), f"글이 그대로다 -- {r['글']!r}")
ok(r["셈"] == {"덩어리": 0, "줄안": 0, "그림": 0, "못그림": 0}, f"센 것이 0 -- {r['셈']}")
ok(r["그림들"] == [], "그림도 안 만든다")

print("\n== 줄 안 수식($...$)을 집는다 ==")
r = L.답다듬기(r"식은 $2x = 6$ 이다.", 그림도=False)
ok(r["셈"]["줄안"] == 1, f"하나 집었다 -- {r['셈']}")
ok("$" not in r["글"], f"**달러가 안 남는다** -- {r['글']!r}")
ok("`" in r["글"] and "\n" not in r["글"].strip(),
   f"한 줄로 그려지면 줄 안에 들어간다 -- {r['글']!r}")

# **지수가 붙으면 유니코드가 두 줄이 된다.** 처음에는 그럴 때 원문을 그대로 뒀는데,
# 그러면 사용자는 디스코드에서 `$b^2 - 4ac$` 라는 날글자를 본다 -- LaTeX 로 쓰게 시킨
# 보람이 거기서 사라진다. 산문이 한 번 끊기더라도 읽히는 쪽을 고른다.
r = L.답다듬기(r"판별식은 $b^2 - 4ac$ 이다.", 그림도=False)
ok("$" not in r["글"], f"**두 줄짜리도 날글자로 안 남는다** -- {r['글']!r}")
ok("```" in r["글"] and r["셈"].get("세운것") == 1,
   f"블록으로 세운다 -- {r['셈']} · {r['글']!r}")
ok("판별식은" in r["글"] and "이다." in r["글"], "둘레 글은 살아 있다")

print("\n== 세우는 수식($$...$$)을 집는다 ==")
r = L.답다듬기(r"따라서$$x^2 + 2x + 1 = 0$$이다.", 그림도=False)
ok(r["셈"]["덩어리"] == 1, f"하나 집었다 -- {r['셈']}")
ok("```" in r["글"], "블록으로 나간다")
ok("$$" not in r["글"], f"**달러가 안 남는다** -- {r['글']!r}")

print("\n== $$ 를 $ 로 잘못 집지 않는다 ==")
# `$...$` 를 먼저 찾으면 `$$x$$` 의 빈 안쪽을 집어 식이 통째로 깨진다
r = L.답다듬기(r"$a+b$ 와 $$c+d$$", 그림도=False)
ok(r["셈"] == {"덩어리": 1, "줄안": 1, "그림": 0, "못그림": 0},
   f"덩어리 1 · 줄안 1 로 갈라 센다 -- {r['셈']}")

print("\n== 못 그리면 **원문이 남는다** ==")
# sympy 가 못 읽는 것을 준다. 지워 버리면 사용자는 수식이 있었다는 것조차 모른다.
깨진것 = r"$\usepackage{amsmath}\badcmd{{{$"
r = L.답다듬기(f"앞 {깨진것} 뒤", 그림도=False)
ok("앞" in r["글"] and "뒤" in r["글"], "둘레 글이 살아 있다")
ok("badcmd" in r["글"] or "usepackage" in r["글"],
   f"**못 그린 수식의 원문이 남는다** -- 지우면 있었다는 것조차 모른다 ({r['글']!r})")

print("\n== 그림을 만들면 경로를 돌려준다 (matplotlib 있을 때만) ==")
확인 = L.그림("x^2")
if 확인["됐나"]:
    r = L.답다듬기(r"따라서 $$\frac{-b \pm \sqrt{b^2-4ac}}{2a}$$ 이다.")
    ok(r["셈"]["그림"] == 1, f"그림 하나 -- {r['셈']}")
    ok(len(r["그림들"]) == 1 and Path(r["그림들"][0]).is_file(),
       f"**파일이 실제로 생겼다** -- {r['그림들']}")
    ok(Path(r["그림들"][0]).stat().st_size > 0, "빈 파일이 아니다")
    ok("$$" not in r["글"], "그림으로 나간 자리는 글에서 빠진다")
else:
    print(f"  건너뜀  matplotlib 이 없다 -- {확인['왜'][:60]}")
    ok(True, "matplotlib 없는 데서도 답다듬기가 안 터진다")
    r = L.답다듬기(r"$$x^2$$")
    ok(r["글"], "못 그려도 글은 나온다")

print("\n== 그림 수에 상한이 있다 ==")
많이 = " ".join(f"$$x^{i}$$" for i in range(1, 10))
r = L.답다듬기(많이)
ok(len(r["그림들"]) <= L._그림상한,
   f"**한 답에 {L._그림상한}장까지** -- 열 장 붙이면 그것도 못 읽는다 ({len(r['그림들'])}장)")
ok(r["셈"]["덩어리"] == 9, f"집은 것은 다 셌다 -- {r['셈']}")

print("\n== 배선: 봇이 이것을 실제로 부른다 ==")
서버 = (뿌리 / "discord_bot_server.py").read_text(encoding="utf-8")
보내기 = 서버.split("async def _답보내기")[1].split("async def ")[0]
ok("latex_formatter" in 보내기 and "답다듬기" in 보내기,
   "**`_답보내기` 가 부른다** -- 두 채널이 다 이 함수를 지나므로 한쪽만 고쳐질 일이 없다")
ok("discord.File" in 보내기, "그림을 파일로 붙여 보낸다")
ok("except Exception" in 보내기,
   "**다듬기가 터져도 답은 나간다** -- 뒷단장이 산출물을 먹으면 안 된다(이 함수의 머리말)")

print()
if FAIL:
    print(f"실패 {len(FAIL)}개 -- {FAIL}")
    sys.exit(1)
print("latex 답다듬기: 집는다 · 안 지운다 · 상한이 있다 · 봇이 부른다 -- 통과")
