"""**경험 원장이 입구에서 성한지 보는가.**

    python3 tests/test_jaso_ledger.py

여기서 붙드는 것은 두 가지다.

  1. **성함은 거절하고 표시는 남긴다.** id 겹침·역할 오타·뒤집힌 기간은 판정을
     불가능하게 하므로 hard 다. 잰 방법 없는 수와 증빙 없음은 **사실이 남아야 하므로**
     soft 다 -- 거절하면 뺀 것을 아무도 못 되찾는다(`dig/README.md` 의 선).
  2. **앵커가 단위까지 묶여 있는가.** 수만 보면 어떤 항목의 재는 법에 `30일치` 가
     적힌 것만으로 `매출 30% 향상` 이 통과한다. 그 자리를 회귀 못으로 박는다.
"""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from jaso import ledger as LG                                      # noqa: E402

fails = []


def ok(cond, msg):
    print(("  OK   " if cond else "  실패 ") + msg)
    if not cond:
        fails.append(msg)


def 규칙(vs, name):
    return [v for v in vs if v.규칙 == name]


성한것 = {
    "id": "P1", "갈래": "프로젝트", "이름": "추천 개편", "곳": "무봉테크",
    "언제": ["2025-03", "2025-08"], "역할": "참여",
    "잰것": [{"무엇": "클릭률", "전": "2.1", "후": "2.6", "단위": "%",
             "어떻게": "2주 A/B, 24,000명"}],
    "쓴것": ["Airflow"], "같이": 4, "증빙": "커밋 로그",
}


print("── 성한 원장은 조용하다 (대조군) ────────────────────────")
L = LG.읽기([성한것])
ok(len(L) == 1, "한 항목을 읽었다")
ok(not LG.검사(L), f"위반이 없다 (난 것: {[str(v) for v in LG.검사(L)]})")
ok(LG.읽기(str(ROOT / "jaso" / "보기.json")) and not LG.검사(
    LG.읽기(str(ROOT / "jaso" / "보기.json"))),
   "**딸려 있는 `jaso/보기.json` 도 조용하다** -- 본보기가 위반을 품고 있으면 "
   "베껴 쓴 사람이 그 위반까지 물려받는다")


print("\n── E001~E003 은 hard -- 어기면 판정 자체가 불가능하다 ──")
겹침 = LG.검사(LG.읽기([성한것, dict(성한것)]))
ok(규칙(겹침, "E001") and 규칙(겹침, "E001")[0].등급 == "hard",
   "E001 같은 id 두 번은 hard")
역할오타 = LG.검사(LG.읽기([dict(성한것, 역할="팀원으로서 참여")]))
ok(규칙(역할오타, "E002") and 규칙(역할오타, "E002")[0].등급 == "hard",
   "E002 닫힌 목록 밖 역할은 hard -- 자유 서술이면 J004 가 눈이 없다")
뒤집힘 = LG.검사(LG.읽기([dict(성한것, 언제=["2025-08", "2025-03"])]))
ok(규칙(뒤집힘, "E003"), "E003 시작이 끝보다 뒤면 잡는다")
꼴틀림 = LG.검사(LG.읽기([dict(성한것, 언제=["작년 봄"])]))
ok(규칙(꼴틀림, "E003"), "E003 'YYYY-MM' 이 아니면 잡는다")


print("\n── E004~E006 은 soft -- **사실은 남고 표만 붙는다** ─────")
안잰수 = dict(성한것, 잰것=[{"무엇": "매출", "전": "100", "후": "130",
                          "단위": "%", "어떻게": ""}])
vs = LG.검사(LG.읽기([안잰수]))
ok(규칙(vs, "E004") and 규칙(vs, "E004")[0].등급 == "soft",
   "E004 잰 방법 없는 수는 soft")
ok(len(LG.읽기([안잰수])) == 1,
   "**그래도 항목은 원장에 남는다** -- 거절하면 뺀 것을 아무도 못 되찾는다")
ok(not LG.읽기([안잰수]).항목들[0].잰것[0].쓸수있나,
   "다만 `쓸수있나` 가 False 다 -- 자소서에서 막는 것은 J002 의 일이다")
ok(규칙(LG.검사(LG.읽기([dict(성한것, 증빙="")])), "E005"), "E005 증빙 없음을 표시한다")
겹 = LG.검사(LG.읽기([성한것,
                    dict(성한것, id="P2", 언제=["2025-06", "2025-12"])]))
ok(규칙(겹, "E006") and 규칙(겹, "E006")[0].등급 == "soft",
   "E006 전념 구간이 겹치면 표시한다 (겸업은 실제로 있으므로 hard 가 아니다)")
안겹 = LG.검사(LG.읽기([성한것,
                     dict(성한것, id="P2", 언제=["2025-06", "2025-12"],
                          전념=False)]))
ok(not 규칙(안겹, "E006"), "(대조군) 한쪽이 전념이 아니면 안 걸린다")
ok(not LG.hard(LG.검사(LG.읽기([안잰수]))),
   "soft 만 있으면 hard 는 비어 있다 -- 원장이 판정에 쓰인다")


print("\n── 앵커는 **수와 단위를 묶는다** (회귀 못) ──────────────")
h = LG.읽기([성한것]).항목들[0]
ok("2.1|%" in LG.값앵커(h) and "2.6|%" in LG.값앵커(h), "잰 값이 단위와 묶여 있다")
ok("24000|명" in LG.값앵커(h),
   "**재는 법에 적힌 수도 원장의 수다** -- '24,000명을 대상으로' 는 지어낸 것이 아니다")
ok("2|주" in LG.값앵커(h), "'2주간 A/B' 의 2주도 원장의 수다")
ok("6|개월" in LG.값앵커(h), "기간에서 온 개월 수도 앵커다")
땅 = dict(성한것, 잰것=성한것["잰것"] + [{"무엇": "지연", "전": "35", "후": "4",
                                     "단위": "분", "어떻게": "30일치 중앙값"}])
값 = LG.값앵커(LG.읽기([땅]).항목들[0])
ok("30|일" in 값 and "30|%" not in 값,
   "**`30일치` 가 있어도 `30|%` 는 앵커가 아니다** -- 이 자리를 안 가르면 "
   "지어낸 '매출 30% 향상' 이 통과한다")
ok("30" not in LG.값수(LG.읽기([땅]).항목들[0]),
   "`값수`(잰 값 그 자체)에는 재는 법의 수가 안 들어간다 -- hard/soft 를 가르는 자리")

print("\n── 앵커가 아닌 것 ───────────────────────────────────")
ok("분석" not in LG.말앵커(LG.읽기([dict(성한것, 쓴것=["분석", "Airflow"])])
                        .항목들[0]),
   "'분석' 같은 흔한 말은 앵커가 아니다 -- 아니면 어느 자소서에나 앵커가 있다")
ok(not any(not LG._글자.search(a) for a in LG.말앵커(
    LG.읽기([dict(성한것, 이름="졸업 -- 위치추정")]).항목들[0])),
   "(회귀 못) 글자가 없는 토막(`--`)은 앵커가 아니다")
ok(LG.앵커("클릭률이 2.1%에서 2.6%로 올랐습니다", h),
   "글에 박힌 수를 앵커로 찾는다")
ok(not LG.앵커("저는 열정적이고 책임감 있는 인재입니다", h),
   "(대조군) 일반론 문장에는 앵커가 없다")


print("\n── 빈 원장은 예외가 아니라 빈 원장이다 ──────────────────")
for 나쁜것 in ("{{{", "", [], {"id": ""}, 42, None):
    ok(len(LG.읽기(나쁜것)) == 0, f"{str(나쁜것)[:12]!r} -> 빈 원장 (안 죽는다)")

print()
print(f"실패 {len(fails)}건" if fails else "전부 통과")
raise SystemExit(1 if fails else 0)
