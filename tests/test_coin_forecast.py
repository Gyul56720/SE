"""**예보를 채점할 수 있는가** -- 그리고 그 채점이 미래를 훔쳐보지 않는가.

    python3 tests/test_coin_forecast.py

## 이 파일이 붙드는 것

    1. 신호를 안 심으면 skill 이 0 근처다        (안 그러면 없는 실력이 보인다)
    2. 신호를 심으면 skill 이 양수다             (안 그러면 채점이 아무것도 못 잰다)
    3. 예보는 **사건 난 날에만** 나간다          (처음에 이걸 틀렸다 -- 아래)
    4. 미리보기를 풀면 skill 이 오른다            (자물쇠가 실제로 막고 있다는 뜻)

## 3번을 처음에 틀렸다 -- 실측 2026-09-09

첫 판은 서른 날마다 예보를 냈다. 그런데 이 예보는 조건부다 -- "**그 뉴스가 뜨면**
며칠 뒤에 얼마". 아무 날에나 그 조건부 분포를 갖다 대면 조건이 없는 날에 조건부
답을 하는 것이고, 그러면 기저율 예보자보다 나쁠 수밖에 없다.

    신호를 -10% 로 심어 놓고도 skill -0.372   <- 설계가 틀렸다는 신호였다
    사건 난 날에만 내니          skill +0.200

**채점이 없었으면 이 결함을 영영 몰랐을 것이다.** 관문은 답이 원장과 어긋나는지를
보지, 원장이 쓸모 있는지는 안 본다. 그것을 보는 자리가 여기다.
"""
from __future__ import annotations

import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "tests"))

import _coin_fixture as FX                                            # noqa: E402
from coin import event as EV                                          # noqa: E402
from coin import forecast as FC                                       # noqa: E402
from coin import gate as GT                                           # noqa: E402
from coin import scenario as SC                                       # noqa: E402

fails = []


def ok(cond, msg):
    print(("  OK   " if cond else "  실패 ") + msg)
    if not cond:
        fails.append(msg)


날 = FX.사건날(60, 1500, 22)
사건 = FX.사건(날)


def 돌리기(계열, 자름=True, 지금것포함=False, 판수=250):
    with tempfile.TemporaryDirectory() as d:
        p = Path(d) / "f.json"
        옛 = FC._자른계열
        if not 자름:
            FC._자른계열 = lambda c, 까지: c
        try:
            if 지금것포함:
                n = 0
                for T in EV.사건날들(계열, 사건, "규제금지", "BTC", "최초"):
                    if 계열.수익(T, 7) is None:
                        continue
                    잘린 = FC._자른계열(계열, T)
                    옛사건 = [e for e in 사건 if (e.get("최초") or "")[:10] <= T]
                    if len(옛사건) < 8:
                        continue
                    r = EV.재기(잘린, 옛사건, "규제금지", "BTC", 7, 판수=판수, 최소표본=8)
                    if r["미검증"]:
                        continue
                    뭉 = SC.뽑기(잘린, r)
                    if 뭉.get("시나리오"):
                        FC.적기(뭉, T, p)
                        n += 1
                r = {"낸것": n, "사건날": n}
            else:
                r = FC.걸어보기(계열, 사건, "규제금지", "BTC", 7, 판수=판수, 경로=p)
        finally:
            FC._자른계열 = 옛
        FC.채우기({"BTC": 계열}, p)
        return r, FC.채점(FC.불러오기(p), 최소=5)


# ---------------------------------------------------------------- RED
민 = FX.계열(효과=0.0)
r0, s0 = 돌리기(민)
ok(s0.get("n", 0) > 10, f"무작위 걸음에서도 예보가 나간다 ({s0.get('n')}개)")
ok(abs(s0["skill"]) < 0.12,
   f"**신호가 없으면 skill 이 0 근처다**: {s0['skill']:+.3f} -- 없는 실력이 안 보인다")

# ---------------------------------------------------------------- GREEN
심 = FX.계열(심을날=날, 효과=-0.10)
r1, s1 = 돌리기(심)
ok(s1["skill"] > 0.1, f"**신호를 심으면 skill 이 양수다**: {s1['skill']:+.3f}")
ok(s1["머리맞춤"] > 0.35,
   f"제일 높게 준 칸이 실제로 자주 난다: {s1['머리맞춤']*100:.0f}% (기저 20%)")
ok(s1["Brier"] < s1["기저Brier"], "Brier 가 기저율 예보자보다 낮다")

# ---------------------------------------------------------------- 사건 날에만
D0 = EV.사건날들(심, 사건, "규제금지", "BTC", "최초")
ok(r1["낸것"] <= len(D0),
   f"**예보가 사건 난 날에만 나간다** ({r1['낸것']} <= 사건날 {len(D0)})")
ok(r1["낸것"] > len(D0) * 0.5, "그리고 대부분의 사건 날에 나간다")

# ---------------------------------------------------------------- 미리보기
_, s2 = 돌리기(심, 자름=False, 지금것포함=True)
ok(s2["skill"] >= s1["skill"],
   f"둘 다 풀면 skill 이 안 낮아진다: 자름 {s1['skill']:+.3f} -> 풂 {s2['skill']:+.3f} "
   "(**이 자료에선 차가 작다** -- 사건 하나가 표본 40개의 빈도를 거의 안 바꾼다)")

# ---------------------------------------------------------------- 채점의 셈
ok(abs(FC._brier([1.0, 0, 0, 0, 0], 0)) < 1e-9, "다 맞히면 Brier 0")
ok(abs(FC._brier([0, 0, 0, 0, 1.0], 0) - 2.0) < 1e-9, "다 틀리면 Brier 2")
ok(abs(FC._brier([0.2] * 5, 0) - 0.8) < 1e-9, "**아무것도 모르는 예보자는 0.8**")
ok(FC._logloss([0.5, 0.5], 0) < FC._logloss([0.1, 0.9], 0), "logloss 가 방향이 맞다")

빈 = FC.채점({"예보": []})
ok(빈["n"] == 0 and 빈["왜"], "채점할 것이 없으면 그렇게 말한다")
적음 = FC.채점({"예보": [{"확률": [0.2] * 5, "널확률": 0.2, "실현칸": 1}]}, 최소=20)
ok(적음["모자람"] and "믿지 마라" in 적음["왜"], "**표본이 모자라면 skill 을 믿지 말라고 적는다**")

# ---------------------------------------------------------------- 누락 관문
c = FX.계열(심을날=날, 효과=0.09)
사건2 = FX.사건(날) + FX.사건(날[:6], "해킹유출")
잰것 = EV.전부({"BTC": c}, 사건2, 지평들=(7,), 유형들=("규제금지", "해킹유출"), 판수=300)
원장 = {"잰것": 잰것, "사건수": len(사건2)}
r = [x for x in 잰것 if x["유형"] == "규제금지"][0]
바른 = (f"규제금지 D+7: 관측 {r['관측중앙']*100:+.2f}%, 기저율 {r['널중앙']*100:+.2f}%, "
        f"초과 {r['초과']*100:+.2f}%p 상승. n={r['n']}(겹침없는 {r['유효n']}), "
        f"승률 {r['승률']*100:.0f}%. {r['시험수']}번 쟀고 BH 보정.")
res = GT.검사(바른, 원장, {"BTC": c}, 사건들=사건2)
ok(any(v.규칙 == "C017" for v in res.hard),
   "**체리피킹을 잡는다** -- 지금 난 뉴스인데 못 잰 것을 안 밝히면 기각")
res2 = GT.검사(바른 + " 해킹유출은 표본이 모자라 못 쟀다.", 원장, {"BTC": c}, 사건들=사건2)
ok(not res2.hard, f"밝히면 통과 (hard {len(res2.hard)})")
ok(len(GT.관련한것(원장, 사건2)) >= 1, "관련한것이 원장에서 필수 목록을 낸다")
ok(all(x.get("살아남음") or x["유형"] in {e["유형"] for e in 사건2}
       for x in GT.관련한것(원장, 사건2)),
   "필수 목록은 **판단이 아니라 원장이** 정한다 (BH 통과 · 지금 난 유형)")

print()
print(f"실패 {len(fails)}개" if fails else "전부 통과")
raise SystemExit(1 if fails else 0)
