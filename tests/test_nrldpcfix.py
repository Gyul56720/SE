"""고정소수점 LDPC 골든 검사.

**여기서 제일 중요한 것은 '감싸기로 두면 망가진다' 가 실제로 물리는지다.**
DFE(`specdfe.py`)에서는 감싸기가 옳았다. 여기서는 반대다. 규칙을 옮겨 적기만 하고
재지 않으면 틀린 규칙을 스펙에 싣게 된다.
"""
import numpy as np

import nrldpc as F
import nrldpcfix as X


def _부():
    return F.부호("BG2", 8)


# ---------------------------------------------------------------- 산술 조각
def test_포화는_대칭범위로_자른다():
    v = np.array([-1000, -16, 0, 16, 1000])
    r = X.포화(v, 6)
    assert r.max() == 31 and r.min() == -31
    assert list(r[1:4]) == [-16, 0, 16]


def test_감싸기는_부호를_뒤집는다():
    """이것이 LDPC 에서 감싸기를 못 쓰는 이유다 -- 큰 확신이 반대 확신이 된다."""
    assert X.감싸기(np.array([32]), 6)[0] == -32
    assert X.감싸기(np.array([31]), 6)[0] == 31


def test_정규화는_0쪽으로_버린다():
    v = np.array([-100, -7, 0, 7, 100])
    r = X.정규화(v, 3, 2)                      # 3/4 배
    assert list(r) == [-75, -5, 0, 5, 75]      # 7*3>>2 = 5


def test_양자화가_클리핑한다():
    llr = np.array([[-100.0, 0.3, 100.0]])
    q = X.양자화(llr, 5, 1.0)
    assert q.max() == 15 and q.min() == -15


# ---------------------------------------------------------------- 규칙이 무는가
def test_감싸기로_두면_실제로_망가진다():
    """안 망가지면 '포화하라' 는 스펙에서 뺄 규칙이다.

    **동작점이 성한지 먼저 본다.** 첫 판은 (Z=8, -2.0 dB, W=5, 스케일=3) 에서
    쟀는데 **포화도 BLER 1.0** 이었다 -- 망가진 동작점에서는 "둘 다 1.0" 이 나와
    아무것도 안 갈린다. 그 위에서 나온 수는 버려야 한다.
    """
    c = _부()
    포 = X.측정(c, -1.5, W=5, 스케일=2, 블록수=40, 씨=22, 넘침="포화")
    assert 0.02 < 포["BLER"] < 0.6, f"동작점이 망가졌다: 포화 BLER {포['BLER']}"
    감 = X.측정(c, -1.5, W=5, 스케일=2, 블록수=40, 씨=22, 넘침="감싸기")
    assert 감["BLER"] > 포["BLER"] + 0.2, (포["BLER"], 감["BLER"])


def test_폭이_넉넉하면_두_방식이_같아진다():
    """넘치지 않으면 넘침 정책은 아무것도 안 한다 -- 그때까지 같아야 한다."""
    c = _부()
    포 = X.측정(c, -1.5, W=12, 스케일=8, 블록수=20, 씨=23, 넘침="포화")
    감 = X.측정(c, -1.5, W=12, 스케일=8, 블록수=20, 씨=23, 넘침="감싸기")
    assert abs(포["BLER"] - 감["BLER"]) < 1e-9


def test_W를_키우면_부동소수로_간다():
    c = _부()
    부 = F.측정(c, -1.5, 블록수=30, 씨=24)["BLER"]
    좁 = X.측정(c, -1.5, W=4, 스케일=2, 블록수=30, 씨=24)["BLER"]
    넓 = X.측정(c, -1.5, W=12, 스케일=8, 블록수=30, 씨=24)["BLER"]
    assert 넓 <= 좁, (좁, 넓)
    assert abs(넓 - 부) < 0.12, (넓, 부)


# ---------------------------------------------------------------- 계약
def test_정수만_쓴다():
    c = _부()
    q = X.양자화(F.채널llr(np.zeros((c.열수, c.Z), np.int8), -2.0,
                       np.random.default_rng(0), c), 6, 3)
    assert np.issubdtype(q.dtype, np.integer)
    r = X.복호(c, q, W=6, 최대반복=3)
    assert np.issubdtype(r["비트"].dtype, np.integer)


def test_수렴과_쓴반복을_반드시_같이_낸다():
    c = _부()
    q = X.양자화(F.채널llr(np.zeros((c.열수, c.Z), np.int8), -6.0,
                       np.random.default_rng(0), c), 6, 3)
    r = X.복호(c, q, W=6, 최대반복=4)
    assert isinstance(r["수렴"], bool) and r["쓴반복"] <= 4


def test_조기종료가_문다():
    c = _부()
    r = X.측정(c, 2.0, W=8, 스케일=4, 블록수=20, 씨=25, 최대반복=20)
    assert r["평균반복"] < 20.0


def test_오류0이면_상한만_말한다():
    c = _부()
    r = X.측정(c, 3.0, W=8, 스케일=4, 블록수=20, 씨=26)
    assert r["블록오류"] == 0 and r["상한만"] is True and "상한" in r["말"]


def test_입력포화율을_보고한다():
    """스케일을 크게 잡으면 입력이 포화한다 -- 그것이 보여야 고를 수 있다."""
    c = _부()
    작 = X.측정(c, -1.0, W=5, 스케일=1, 블록수=8, 씨=27)["입력포화율"]
    큰 = X.측정(c, -1.0, W=5, 스케일=30, 블록수=8, 씨=27)["입력포화율"]
    assert 큰 > 작, (작, 큰)
    assert 큰 > 0.3


def test_스케일이_BLER을_가른다():
    """**W 만 쓸면 틀린 결론이 난다** -- 같은 W 에서도 스케일로 크게 갈린다."""
    c = _부()
    값 = [X.측정(c, -1.5, W=5, 스케일=s, 블록수=30, 씨=28)["BLER"]
         for s in (1, 2, 30)]
    assert max(값) - min(값) > 0.15, 값


