"""**물음이 도출되는가. 답이 원장으로 돌아오는가.**

    python3 tests/test_jaso_ask.py

    물을 것 = 문항이 요구하는 것  −  원장이 이미 가진 것

이것이 계산이라는 것을 붙든다. 모델에게 물음을 지어내게 하면 그럴듯한 물음이 나오고,
**왜 그것을 묻는지는 아무도 모르며**, 답을 받아도 무엇이 채워졌는지 셀 수가 없다.

그리고 고리가 닫히는지 본다 -- 물어서 받은 답을 넣으면 **그 물음이 사라져야** 한다.
안 사라지면 사용자는 같은 것을 두 번 답하게 되고, 두 번째부터는 안 답한다.
"""
from __future__ import annotations

import json
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from jaso import ask as AS                                        # noqa: E402
from jaso import intake as IN                                     # noqa: E402
from jaso import item as IT                                       # noqa: E402
from jaso import ledger as LG                                     # noqa: E402

fails = []


def ok(cond, msg):
    print(("  OK   " if cond else "  실패 ") + msg)
    if not cond:
        fails.append(msg)


역량 = IT.쪼개기("직무에 필요한 역량은 무엇이며 이를 갖추기 위해 어떤 노력을 했는지 "
              "구체적 경험과 그 결과를 기술하시오 (1000자)", "1")
동기 = IT.쪼개기("우리 회사에 지원한 이유와 입사 후 포부를 기술하시오. (800자)", "2")


def 물음(L, 문항들=(역량,), 몇=20):
    return AS.물을것(list(문항들), L, 몇)


def 칸들(qs):
    return {q.칸.split(":")[0] for q in qs}


print("── 빈 원장 -- 경험부터 묻는다 ──────────────────────────")
qs = 물음(LG.원장())
ok(qs and qs[0].칸 == "새항목", "제일 급한 것이 맨 위다")
ok(all(q.왜 for q in qs),
   "**물음마다 왜 묻는지가 붙어 있다** -- 어느 관문이 지금 그 자리를 못 보는가")
ok(any("J001" in q.왜 or "P001" in q.왜 for q in qs), "왜에 관문 이름이 있다")
동기만 = 물음(LG.원장(), [동기])
새것 = [q for q in 동기만 if q.칸 == "새항목"]
ok(새것 and "지원한 이유" not in 새것[0].말,
   "**경험을 안 묻는 문항은 인용하지 않는다** -- '「우리 회사에 지원한 이유를…」 에 "
   "쓸 일이 필요합니다' 라고 물으면 사용자가 무엇을 답할지 모른다 (회귀 못). "
   "물음 자체는 남는다 -- 항목이 0 이면 어느 문항이든 미검증이다")

print("\n── 빈칸마다 그 칸을 묻는다 ─────────────────────────────")
반쯤 = LG.읽기({"항목": [{"id": "P1", "이름": "추천 개편", "곳": "무봉테크",
                     "언제": [], "역할": "", "쓴것": [], "증빙": "",
                     "잰것": [{"무엇": "클릭률", "전": "2.1", "후": "2.6",
                             "단위": "%", "어떻게": ""}]}]})
qs = 물음(반쯤)
ok("역할" in 칸들(qs), "역할이 비면 역할을 묻는다 (E002)")
ok("언제" in 칸들(qs), "기간이 비면 기간을 묻는다 (E003)")
ok("어떻게" in 칸들(qs), "**잰 방법이 없으면 재는 법을 묻는다** (E004 -> J002)")
ok("증빙" in 칸들(qs), "증빙이 비면 묻는다 (E005)")
ok(qs[0].급함 >= 85, f"hard 를 막고 있는 것이 위다 (맨 위 급함 {qs[0].급함})")
앵커없음 = LG.읽기({"항목": [{"id": "P2", "이름": "", "곳": "", "역할": "참여",
                         "언제": ["2025-03", "2025-08"], "증빙": "x"}]})
ok("쓴것" in 칸들(물음(앵커없음)),
   "**앵커가 하나도 없으면 고유한 것을 묻는다** (P001)")

print("\n── 사실로 못 채우는 자리는 물어본다 ────────────────────")
qs = 물음(LG.읽기({"항목": []}), [동기])
ok("생각" in 칸들(qs), "지원동기·포부는 생각으로 묻는다")
ok(any("지어낸다" in q.왜 for q in qs if q.칸.startswith("생각")),
   "**안 물으면 생성자가 지어낸다** 고 적혀 있다")
있음 = LG.읽기({"항목": [], "생각": [{"id": "G1", "갈래": "지원동기", "말": "쓴 것"},
                              {"id": "G2", "갈래": "포부", "말": "쓴 것"}]})
ok(not [q for q in 물음(있음, [동기]) if q.칸 == "생각:지원동기"],
   "(대조군) 이미 적은 생각은 다시 안 묻는다")

print("\n── 안 묻는 것 ─────────────────────────────────────────")
전부 = 물음(반쯤, [역량, 동기], 몇=0)
말들 = " ".join(q.말 for q in 전부)
for 금지 in ("강점이 무엇", "장단점", "성격을 한마디"):
    ok(금지 not in 말들,
       f"{금지!r} 를 안 묻는다 -- 사실에서 나올 결론이지 재료가 아니다")
ok("몇 개월" not in 말들 and "글자 수" not in 말들,
   "계산되는 것을 안 묻는다")

print("\n── 문구는 모델이, **칸은 코드가** ──────────────────────")
편입 = IT.쪼개기("본교 해당 학과에 지원하게 된 동기와 편입 후 학업 계획을 "
              "구체적 경험을 바탕으로 기술하시오. (1000자 이내)", "1")
qs = AS.물을것([편입], LG.원장(), 4)
프 = AS.프롬프트([편입], qs)
ok("본교 해당 학과" in 프, "문항 원문이 프롬프트에 들어간다")
ok(all(x.id in 프 for x in qs), "물어야 할 id 가 다 실린다")
ok("바꾸지 마십시오" in 프 and "JSON" in 프, "id 를 바꾸지 말고 JSON 으로 내라고 한다")
금지 = ("J001", "J002", "P001", "E004", "관문", "위반", "hard", "soft", "앵커", "미검증")
샌것 = [w for w in 금지 if w in 프]
ok(not 샌것, f"**프롬프트에 관문 이름이 없다** ({샌것}) -- 실으면 관문을 통과하는 "
   "물음이 나온다")
ok(all(v and "관문" not in v for v in AS.칸뜻.values()),
   "칸뜻은 **무엇을 알아낼지**이지 관문 이야기가 아니다")

옛말 = {x.id: x.말 for x in qs}
답 = ('```json\n{"물음": [' + ", ".join(
    f'{{"id": "{x.id}", "말": "편입 준비하며 실제로 한 일은?", "보기": "보기 글"}}'
    for x in qs) + ']}\n```')
새, n = AS.문구입히기(list(qs), 답)
ok(n == len(qs), f"모델 문구가 {n}개 붙었다")
ok(all(x.말 == "편입 준비하며 실제로 한 일은?" for x in 새), "말이 갈렸다")
ok(all(x.말 == 옛말[x.id] for x in qs),
   "**받은 목록은 안 바뀐다** -- 되돌림이 있는 함수가 되돌릴 것을 지워 버리면 "
   "되돌림이 아니다 (회귀 못)")
ok(all(x.보기 == "보기 글" for x in 새), "보기도 갈렸다")
ok(all(a.칸 == b.칸 and a.대상 == b.대상 and a.왜 == b.왜 and a.급함 == b.급함
       for a, b in zip(qs, 새)),
   "**칸·대상·왜·급함은 그대로다** -- 모델이 칸을 바꾸면 답이 엉뚱한 데로 들어가고 "
   "그러면 원장이 오염된다")

바꿔치기 = '{"물음": [{"id": "%s", "칸": "증빙", "대상": "남의것", "말": "새 말"}]}' % qs[0].id
새2, _ = AS.문구입히기(list(qs), 바꿔치기)
ok(새2[0].칸 == qs[0].칸 and 새2[0].대상 == qs[0].대상,
   "**모델이 칸·대상을 줘도 안 받는다** (회귀 못)")

for 나쁜답 in ("", "그냥 글입니다", "{망가진", '{"물음": "목록이 아님"}',
             '{"물음": [{"id": "없는것", "말": "x"}]}'):
    되돌린것, n2 = AS.문구입히기(qs, 나쁜답)
    ok(n2 == 0 and 되돌린것[0].말 == 옛말[qs[0].id],
       f"**{str(나쁜답)[:14]!r} -> 씨앗 문구로 되돌린다** -- 모델이 죽어도 물음은 나간다")

print("\n── 답이 원장으로 돌아온다 ──────────────────────────────")
답 = IN.답나누기("1) 사내 추천 시스템 개편, 무봉테크 인턴, 2025-03 ~ 2025-08, 참여\n"
              "2) 2주 A/B, 대조군 24,000 실험군 24,000명")
ok(set(답) == {"1", "2"}, f"`1) …` 꼴로 나뉜다 ({sorted(답)})")
ok(IN.답나누기("번호 없이 그냥 적었습니다") == {"1": "번호 없이 그냥 적었습니다"},
   "**번호가 없으면 통째로 1번이다** -- 버리지 않는다")
ok(IN._언제("2025년 3월부터 2025년 8월까지") == ("2025-03", "2025-08"),
   "'2025년 3월' 을 편다")
ok(IN._역할("팀원으로 참여했습니다") == "참여", "닫힌 목록에서 역할을 읽는다")
ok(not IN._역할("열심히 했습니다"), "(대조군) 없으면 안 읽는다")
잰 = IN._잰것("클릭률 2.1% -> 2.6% (2주 A/B, n=48,000)")
ok(잰 and 잰[0]["전"] == "2.1" and 잰[0]["후"] == "2.6" and 잰[0]["단위"] == "%",
   f"'얼마에서 얼마로' 를 읽는다 ({잰[:1]})")
ok(잰 and "A/B" in 잰[0]["어떻게"], "괄호 안이 재는 법으로 들어간다")

print("\n── I001 -- 답에 없는 값은 안 들어간다 ───────────────────")
ok(not IN.대조("2025-03", "2025년 3월부터"),
   "'2025년 3월' 을 '2025-03' 으로 편 것은 지어낸 것이 아니다")
없는것 = IN.대조("클릭률 30% 향상", "클릭률이 조금 올랐습니다")
ok("30" in 없는것,
   f"**답에 없는 수는 잡힌다** ({없는것}) -- 원장이 오염되면 아래 관문이 전부 "
   "오염된 것을 대조하게 된다")

print("\n── 고리가 닫힌다 -- 답하면 그 물음이 사라진다 ────────────")
L = LG.읽기({"항목": []})
문항들 = [역량]
바퀴, 답표 = 0, {"새항목": "추천 개편, 무봉테크 인턴, 2025-03 ~ 2025-08, 참여",
              "역할": "참여", "언제": "2025-03 ~ 2025-08",
              "쓴것": "Python, BigQuery", "증빙": "커밋 로그",
              "잰것": "클릭률 2.1% -> 2.6% (2주 A/B, n=48,000)",
              "어떻게": "2주 A/B, 24,000명", "생각": "지표를 의심하는 습관입니다"}
while (qs := AS.물을것(문항들, L, 0)) and 바퀴 < 8:
    바퀴 += 1
    글 = "\n".join(f"{i}) {답표[q.칸.split(':')[0]]}" for i, q in enumerate(qs, 1))
    L, vs, 채운것 = IN.넣기([q.__dict__ for q in qs], IN.답나누기(글), L)
    ok(채운것, f"{바퀴}바퀴: 물음 {len(qs)}개 -> {len(채운것)}칸을 채웠다")
    ok(not LG.hard([v for v in vs if v.규칙 == "I001"]),
       f"{바퀴}바퀴: I001 hard 없음")
ok(바퀴 < 8, f"**{바퀴}바퀴 만에 더 물을 것이 없어졌다** -- 고리가 닫힌다")
ok(not LG.hard(LG.검사(L)), f"원장에 hard 가 없다 ({[str(v) for v in LG.hard(LG.검사(L))]})")
ok(L.항목들 and L.생각들, f"항목 {len(L.항목들)}개 · 생각 {len(L.생각들)}개가 남았다")

print("\n── 되쓰고 되읽어도 같다 ────────────────────────────────")
with tempfile.TemporaryDirectory() as d:
    p = IN.쓰기(L, Path(d) / "원장.json")
    다시 = LG.읽기(str(p))
    ok(len(다시) == len(L) and len(다시.생각들) == len(L.생각들),
       "항목과 생각이 그대로 돌아온다")
    ok(json.loads(p.read_text(encoding="utf-8")).get("항목"), "읽은 꼴 그대로 담긴다")
    ok(not AS.물을것(문항들, 다시, 0), "되읽은 원장에도 물을 것이 없다")

print()
print(f"실패 {len(fails)}건" if fails else "전부 통과")
raise SystemExit(1 if fails else 0)
