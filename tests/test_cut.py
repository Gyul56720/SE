"""절단평면 판정기가 **거짓 초록을 내지 않는가.**

이 자리의 거짓 초록은 유난히 비싸다. 유효하지 않은 cut 을 유효라 부르면 solver 가
터지지 않는다 -- **조용히 다른 최적해**를 낸다. 크래시도 infeasible 도 아니라서 아무도
모르고, 그 위의 모든 수가 근거처럼 보인다.
"""

from __future__ import annotations

import sys
from pathlib import Path

뿌리 = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(뿌리))

from cut import ff as FF                                           # noqa: E402
from cut import 판정 as J                                          # noqa: E402
from vne import topo as T                                          # noqa: E402

FAIL: list = []


def ok(cond, what):
    print(("  통과  " if cond else "  실패  ") + what)
    if not cond:
        FAIL.append(what)


바탕 = T.바탕망(씨앗=0, 노드수=6, 꼴="random", p=0.7)
요청 = T.요청망(씨앗=5, 노드범위=(2, 3))
p = FF.짓기(바탕, 요청)
VR, VS = sorted(요청.노드), sorted(바탕.노드)

print("== FF 가 실제로 풀린다 ==")
크 = p.크기()
ok(크["변수"] == 크["x"] + 크["y"], f"변수 = x + y ({크['변수']} = {크['x']}+{크['y']})")
ok(크["x"] == 크["V_R"] * 크["V_S"], f"x 가 |V_R|x|V_S| 다 ({크['x']})")
ok(크["y"] == 크["E_R"] * 2 * 크["E_S"], f"**y 가 |E_R|x2|E_S| 다** -- 링크 하나가 호 둘 ({크['y']})")
정 = FF.풀기(p, 정수=True)
완 = FF.풀기(p, 정수=False)
ok(정["상태"] == "최적" and 완["상태"] == "최적", f"정수·완화 둘 다 풀린다 ({정['상태']}/{완['상태']})")
ok(완["값"] <= 정["값"] + 1e-9,
   f"**LP 완화 값 <= 정수 값** ({완['값']:.4f} <= {정['값']:.4f}) -- 경계 방향이 맞다")
ok(정["값"] - 완["값"] >= -1e-9, f"LPgap 이 음수가 아니다 ({정['값'] - 완['값']:.4f})")

print("\n== 유효판정: 무효를 유효라 하지 않는다 ==")
배치식 = {("x", VR[0], u): 1.0 for u in VS}
ok(J.유효판정(p, 배치식, 1.0)["판정"] == J.유효, "배치 제약과 같은 식은 **유효**다")
뒤집 = J.유효판정(p, 배치식, 0.0)
ok(뒤집["판정"] == J.무효, f"**b 를 0 으로 낮추면 무효다** ({뒤집['말'][:40]})")
ok(뒤집.get("반례") is not None, "무효일 때 **반례를 같이 준다** -- 말만 하지 않는다")
ok(J.유효판정(p, 배치식, 2.0)["판정"] == J.유효, "느슨한 b 도 유효다(유효는 자름과 다른 물음이다)")

print("\n== 자름판정: 아무것도 안 자르는 것을 걸러낸다 ==")
ok(J.자름판정(p, 배치식, 1.0)["판정"] == J.안자름,
   "**기존 제약과 같은 식은 안 자른다** -- 유효하지만 값어치가 없다")
배수 = {k: 2.0 * v for k, v in 배치식.items()}
ok(J.자름판정(p, 배수, 2.0)["판정"] == J.안자름,
   "**`2x <= 2` 도 안 자른다** -- 배수인지 보는 것보다 강한 판정이다(LP 한 번)")
ok(J.자름판정(p, 배치식, 0.0)["판정"] == J.자름, "b 를 낮추면 자를 것이 생긴다(대신 무효다)")

print("\n== 분리판정: 지금 이 점을 자르는가 ==")
ok(J.분리판정(p, 배치식, 0.0, 완["해"])["판정"] == "분리함", "LP 해를 자르면 분리함")
ok(J.분리판정(p, 배치식, 1.0, 완["해"])["판정"] == "못함", "안 자르면 못함")
ok(J.분리판정(p, 배치식, 0.0, None)["판정"] == J.못잼, "**z* 가 없으면 못잼이다** -- 0 으로 안 채운다")

print("\n== 조임판정: 제약을 더했는데 최소값이 줄 수는 없다 ==")
ㅈ = J.조임판정(p, 배치식, 1.0)
ok(ㅈ["판정"] in ("조임", "안조임"), f"판정이 셋 중 하나다 ({ㅈ['판정']})")
if "Δ" in ㅈ:
    ok(ㅈ["Δ"] >= -1e-9, f"**Δ 가 음수가 아니다** ({ㅈ['Δ']}) -- 음수면 못잼이라 답한다")
막 = J.조임판정(p, 배치식, -1.0)
ok(막["판정"] == J.못잼 and "불능" in 막["말"] or 막["판정"] == J.못잼,
   f"**cut 이 LP 를 불능으로 만들면 못잼이다** ({막['말'][:40]})")

print("\n== 채택판정: 기본은 REJECT ==")
ok(J.채택판정(p, 배치식, 1.0)["결정"] == "REJECT", "유효하지만 안 자르면 REJECT")
ok(J.채택판정(p, 배치식, 1.0)["막힌곳"] == "자름", "**어디서 막혔는지 적는다**")
무 = J.채택판정(p, 배치식, 0.0)
ok(무["결정"] == "REJECT" and 무["막힌곳"] == "유효", "무효면 **유효 단계에서** 막힌다")
ok(len(무["까닭"]) == 1,
   "**무효면 뒤 단계를 아예 안 잰다** -- 재면 그 수가 근거처럼 보인다(perf.py 와 같은 규율)")

print("\n== 모르는 것을 0 으로 안 채운다 ==")
try:
    J.벡터(p, {("x", "없는노드", VS[0]): 1.0})
    ok(False, "이 인스턴스에 없는 변수를 조용히 0 으로 채웠다")
except KeyError as e:
    ok(True, f"**없는 변수는 터뜨린다** ({str(e)[:46]})")
try:
    J.벡터(p, {("z", 1, 2): 1.0})
    ok(False, "모르는 변수 갈래를 조용히 받았다")
except KeyError:
    ok(True, "모르는 변수 갈래도 터뜨린다")

print("\n== 세 값 ==")
ok(J.못잼 == "못잼" and J.유효 == "유효" and J.무효 == "무효", "판정이 셋이다(예/아니오/못잼)")
없판 = FF.판(바탕=바탕, 요청=요청, x자리=p.x자리, y자리=p.y자리, 호들=p.호들, c=p.c,
          A_eq=p.A_eq, b_eq=p.b_eq + 99.0, A_ub=p.A_ub, b_ub=p.b_ub)
ok(FF.풀기(없판)["상태"] in ("불능", "못잼"), "풀 수 없는 판은 불능이나 못잼이다(최적이 아니다)")

print()
if FAIL:
    print(f"실패 {len(FAIL)}개 -- {FAIL}")
    raise SystemExit(1)
print("cut: FF 행렬 · LP<=MIP · 유효/무효 · 안자름 · 분리 · 조임 · 기본 REJECT · 세 값 -- 통과")
