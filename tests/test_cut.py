ok(J.자름판정(p, 배수, 2.0)["판정"] == J.안자름,
   "**`2x <= 2` 도 안 자른다** -- 배수인지 보는 것보다 강한 판정이다(LP 한 번)")
ok(J.자름판정(p, 배치식, 0.0)["판정"] == J.자름, "b 를 낮추면 자를 것이 생긴다(대신 무효다)")

print("\n== 분리판정: 지금 이 점을 자르는가 ==")
ok(J.분리판정(p, 배치식, 0.0, 완["해"])["판정"] == "분리함", "LP 해를 자르면 분리함")
ok(J.분리판정(p, 배치식, 1.0, 완["해"])["판정"] == "못함", "안 자르면 못함")
