"""절단평면 판정기가 **거짓 초록을 내지 않는가.**

이 자리의 거짓 초록은 유난히 비싸다. 유효하지 않은 cut 을 유효라 부르면 solver 가
터지지 않는다 -- **조용히 다른 최적해**를 낸다. 크래시도 infeasible 도 아니라서 아무도
모르고, 그 위의 모든 수가 근거처럼 보인다.
"""

from __future__ import annotations

import sys
from pathlib import Path

뿌리 = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(뿌리))

from cut import ff as FF                                           # noqa: E402
from cut import 판정 as J                                          # noqa: E402
from vne import topo as T                                          # noqa: E402

FAIL: list = []


def ok(cond, what):
    print(("  통과  " if cond else "  실패  ") + what)
    if not cond:
        FAIL.append(what)


바탕 = T.바탕망(씨앗=0, 노드수=6, 꼴="random", p=0.7)
요청 = T.요청망(씨앗=5, 노드범위=(2, 3))
p = FF.짓기(바탕, 요청)
VR, VS = sorted(요청.노드), sorted(바탕.노드)

print("== FF 가 실제로 풀린다 ==")
크 = p.크기()
ok(크["변수"] == 크["x"] + 크["y"], f"변수 = x + y ({크['변수']} = {크['x']}+{크['y']})")
ok(크["x"] == 크["V_R"] * 크["V_S"], f"x 가 |V_R|x|V_S| 다 ({크['x']})")
ok(크["y"] == 크["E_R"] * 2 * 크["E_S"], f"**y 가 |E_R|x2|E_S| 다** -- 링크 하나가 호 둘 ({크['y']})")
정 = FF.풀기(p, 정수=True)
완 = FF.풀기(p, 정수=False)
ok(정["상태"] == "최적" and 완["상태"] == "최적", f"정수·완화 둘 다 풀린다 ({정['상태']}/{완['상태']})")
ok(완["값"] <= 정["값"] + 1e-9,
   f"**LP 완화 값 <= 정수 값** ({완['값']:.4f} <= {정['값']:.4f}) -- 경계 방향이 맞다")
ok(정["값"] - 완["값"] >= -1e-9, f"LPgap 이 음수가 아니다 ({정['값'] - 완['값']:.4f})")

print("\n== 유효판정: 무효를 유효라 하지 않는다 ==")
배치식 = {("x", VR[0], u): 1.0 for u in VS}
ok(J.유효판정(p, 배치식, 1.0)["판정"] == J.유효, "배치 제약과 같은 식은 **유효**다")
뒤집 = J.유효판정(p, 배치식, 0.0)
ok(뒤집["판정"] == J.무효, f"**b 를 0 으로 낮추면 무효다** ({뒤집['말'][:40]})")
ok(뒤집.get("반례") is not None, "무효일 때 **반례를 같이 준다** -- 말만 하지 않는다")
ok(J.유효판정(p, 배치식, 2.0)["판정"] == J.유효, "느슨한 b 도 유효다(유효는 자름과 다른 물음이다)")

print("\n== 자름판정: 아무것도 안 자르는 것을 걸러낸다 ==")
ok(J.자름판정(p, 배치식, 1.0)["판정"] == J.안자름,
   "**기존 제약과 같은 식은 안 자른다** -- 유효하지만 값어치가 없다")
