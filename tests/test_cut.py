print("\n== 목적함수에 **노드 항**이 있어야 x-cut 이 경계를 올릴 수 있다 ==")
# **실측 2026-09-13, 결론이 뒤집힌 자리.** 처음엔 목적을 `min sum d_e * (지나는 호 수)` 로만
# 두었다. 그랬더니 노드덮개 후보 117개가 **전부 안조임**이었다 -- 유효하고 자르기까지 하는데
# LP 경계를 한 번도 못 올렸다. 까닭은 부등식이 약해서가 아니라 **목적함수가 x 를 안 봐서**다.
# 사용자가 준 꼴대로 노드 항을 넣으니 같은 117개에서 ACCEPT 9개가 나왔다.
#   min [ sum_{r,u} d_r w_u x[r,u] + sum_{e,(u,w)} d_e w_uw y[e,(u,w)] ]
# 그리고 w_u 가 노드마다 **같으면 안 된다** -- 배치 제약이 sum_u x = 1 이라 노드 항이
# 상수가 되고, 그러면 안 넣은 것과 똑같다.
ok(any("값" in 바탕.노드[u] for u in 바탕.노드), "바탕 노드가 w_u(값)를 들고 있다")
ok(len({바탕.노드[u]["값"] for u in 바탕.노드}) > 1,
   "**w_u 가 노드마다 다르다** -- 같으면 노드 항이 상수가 되어 없는 것과 같다")
_x자리들 = [p.x자리[(VR[0], u)] for u in VS]
ok(any(p.c[i] > 0 for i in _x자리들),
   "**목적 계수에 x 항이 실제로 들어 있다** (0 이면 x-cut 은 영영 경계를 못 올린다)")
ok(all(abs(p.c[p.x자리[(v, u)]] - 요청.노드[v]["cpu"] * 바탕.노드[u]["값"]) < 1e-9
       for v in VR for u in VS), "x 계수가 d_r · w_u 다")
# 노드 항이 없으면 어떻게 되는지를 같은 판에서 보인다 -- 회귀가 아니라 **까닭**의 증거다
import numpy as _np                                                # noqa: E402
_y만 = _np.array(p.c)
for _v in VR:
    for _u in VS:
        _y만[p.x자리[(_v, _u)]] = 0.0
_없 = FF.풀기(FF.판(바탕=바탕, 요청=요청, x자리=p.x자리, y자리=p.y자리, 호들=p.호들,
                 c=_y만, A_eq=p.A_eq, b_eq=p.b_eq, A_ub=p.A_ub, b_ub=p.b_ub), 정수=False)
_있 = FF.풀기(p, 정수=False)
ok(_없["상태"] == "최적" and _있["상태"] == "최적" and _있["값"] >= _없["값"] - 1e-9,
   f"노드 항을 넣으면 LP 값이 커진다 ({_없['값']:.2f} -> {_있['값']:.2f}) -- 목적이 x 를 본다")

print("\n== 찾기: 훑은 수가 칸의 합과 같아야 한다 ==")
from cut import 찾기 as S                                          # noqa: E402
빡빡바탕 = T.바탕망(씨앗=0, 노드수=6, 꼴="random", p=0.7, cpu범위=(4, 6), 대역범위=(20, 50))
