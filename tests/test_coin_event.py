"""**사건 연구가 실제로 재는가** -- 신호를 심어 놓고 찾는지, 안 심으면 안 찾는지.

    python3 tests/test_coin_event.py

여기서 제일 중요한 검사는 **RED** 다. 신호를 하나도 안 심은 무작위 걸음에서도
"규제 뉴스 뒤 7일 +2.9%" 같은 수가 그냥 나온다 -- 그것이 시장 추세이기 때문이다.
널이 그것을 걷어내지 못하면 이 파이프라인이 내는 모든 수가 거짓말이 된다.
"""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "tests"))

import _coin_fixture as FX                                            # noqa: E402
from coin import event as EV                                          # noqa: E402
from coin import null as NU                                           # noqa: E402
from coin import regime as RG                                         # noqa: E402
from coin import scenario as SC                                       # noqa: E402

fails = []


def ok(cond, msg):
    print(("  OK   " if cond else "  실패 ") + msg)
    if not cond:
        fails.append(msg)


날 = FX.사건날()
사건 = FX.사건(날)

# ---------------------------------------------------------------- 진입일
c = FX.계열()
ok(c.진입일("2018-05-21T08:00:00Z") == "2018-05-21",
   "아침 뉴스는 그날 종가가 첫 진입 (그 종가는 다음날 00:00 에 확정된다)")
ok(c.진입일("2018-05-21T23:30:00Z") == "2018-05-22",
   "마감 30분 전 뉴스는 **다음 날로 민다** -- 1분 뒤 종가로 잡는 것은 종이 위에서만 된다")
ok(c.수익(c.날들[-2], 7) is None, "원장 끝에서는 못 센다 -- 메우지 않고 None")

# ---------------------------------------------------------------- GREEN
좋 = FX.계열(심을날=날, 효과=0.09)
g = EV.흔들기(좋, 사건, "규제금지", "BTC", 7, 판수=800)
ok(not g["미검증"], f"신호를 심으면 쓸만한 값이 나온다 (n={g['n']})")
ok(g["초과"] > 0.05, f"심은 신호를 찾는다: 초과 {g['초과']*100:+.2f}%p")
ok(g["p양측"] < 0.05, f"널과 갈린다: p={g['p양측']:.3f}")

# ---------------------------------------------------------------- RED
민 = FX.계열(효과=0.0)
r = EV.흔들기(민, 사건, "규제금지", "BTC", 7, 판수=800)
ok(r["관측중앙"] > 0,
   f"**신호가 없어도 관측은 양수다**: {r['관측중앙']*100:+.2f}% -- 이것이 추세다")
ok(abs(r["초과"]) < abs(r["관측중앙"]),
   f"널이 추세를 걷어낸다: 관측 {r['관측중앙']*100:+.2f}% -> 초과 {r['초과']*100:+.2f}%p")
ok(r["p양측"] > 0.05, f"안 심은 것을 안 찾는다: p={r['p양측']:.3f}")

# ---------------------------------------------------------------- 널 꼴
이동 = NU.널(민, 날, 7, 판수=600, 꼴="이동")
무작위 = NU.널(민, 날, 7, 판수=600, 꼴="무작위")
ok(len(이동["판"]) > 500 and len(무작위["판"]) > 500, "널 두 꼴이 다 돈다")
ok(NU.널(민, 날, 7, 판수=200, 씨=7)["판"] == NU.널(민, 날, 7, 판수=200, 씨=7)["판"],
   "**같은 씨면 같은 널** -- 안 그러면 다시 셈(C002)이 못 돈다")
ok(NU.널(민, 날, 7, 판수=200, 씨=7)["판"] != NU.널(민, 날, 7, 판수=200, 씨=8)["판"],
   "씨가 다르면 다른 널 (씨를 안 읽고 있던 것이 아니다)")

# ---------------------------------------------------------------- 표본 · 겹침
적 = EV.흔들기(좋, 사건[:5], "규제금지", "BTC", 7, 판수=200)
ok(적["미검증"] and "표본" in 적["왜"], f"표본이 모자라면 미검증: {적['왜']}")
붙 = FX.사건([FX.날짜(i) for i in range(100, 160)])       # 하루 간격 60개
겹 = EV.재기(좋, 붙, "규제금지", "BTC", 30, 판수=200)
ok(겹["유효n"] < 겹["n"],
   f"겹치는 창을 따로 센다: n={겹['n']} 인데 유효n={겹['유효n']}")

# ---------------------------------------------------------------- 미리보기 뒤집힘
# 영어 기사가 7시간 늦게 나온 상황: 원문 시각으로 재야 옳다
느린 = [dict(e, 최초=e["최초"], 주류=e["최초"].replace("T09", "T16")) for e in 사건]
느 = EV.흔들기(좋, 느린, "규제금지", "BTC", 7, 판수=400)
ok(느["기준"] == "최초", "D0 는 **최초 보도**로 잡는다 (영어 기사 시각이 아니라)")

# ---------------------------------------------------------------- 다중비교
많 = EV.전부({"BTC": 민}, 사건, 지평들=(1, 3, 7, 14, 30),
            유형들=("규제금지", "해킹유출", "ETF"), 판수=300, 흔들=False)
ok(all("시험수" in x for x in 많), "잰 값마다 몇 번 쟀는지가 적힌다")
산것 = [x for x in 많 if not x["미검증"]]
ok(all(x["시험수"] == len(산것) for x in 산것),
   f"시험수가 쓸만한 것의 수와 같다 ({len(산것)})")

# ---------------------------------------------------------------- 시나리오
경계 = SC.칸경계(좋, 7, 5)
ok(len(경계) == 4 and 경계 == sorted(경계), "칸 경계는 **널 분포의 오분위**이고 오름차순이다")
뭉 = SC.뽑기(좋, g)
ok(abs(sum(s["확률"] for s in 뭉["시나리오"]) - 1.0) < 1e-9, "시나리오 확률의 합이 1")
ok(all(s["구간"][0] <= s["확률"] <= s["구간"][1] for s in 뭉["시나리오"]),
   "확률이 자기 신뢰구간 안에 있다 (Wilson)")
ok(all(abs(s["널확률"] - 0.2) < 1e-9 for s in 뭉["시나리오"]),
   "**칸을 오분위로 갈랐으므로 기저율이 정확히 20%** -- 초과확률이 바로 읽힌다")
ok(뭉["시나리오"] == sorted(뭉["시나리오"], key=lambda s: -s["확률"]),
   "확률이 높은 것부터 나온다")

# ---------------------------------------------------------------- 장세
장 = RG.장세(좋)
ok(0 <= 장["추세"]["백분위"] <= 1, "장세는 문턱이 아니라 **자기 역사의 백분위**")
ok(장["나쁨"] == (장["추세"]["백분위"] < 0.2), "아래 칸이면 나쁨 (오분위와 같은 자)")
갈 = RG.장세별(좋, g["날들"], g["수익들"])
ok(갈["약세n"] + 갈["강세n"] <= g["n"], "장세별로 갈라 세도 표본을 안 늘린다")

print()
print(f"실패 {len(fails)}개" if fails else "전부 통과")
raise SystemExit(1 if fails else 0)
