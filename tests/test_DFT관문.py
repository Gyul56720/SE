# -*- coding: utf-8 -*-
"""**DFT 관문 8·9 가 정말로 무는가 -- 떨어져야 할 값을 넣어 본다.**

`house/tapeout.py` 가 이 자리를 이렇게 적고 있었다.

    고장 커버리지 문턱    시연뿐   커버리지 수는 있는데 넘어야 할 선이 없다
    결함수준 (DPPM) 상한  시연뿐   같다

수를 내는 코드는 있는데 **아무도 그 수로 막지 않았다.** 그런 수는 관문이 아니라
장식이다. 그래서 선을 그었는데, **선을 그은 것과 그 선이 무는 것은 다른 일이다.**

여기서 대부분은 `시험성판정()` 에 잰 값을 **손으로 만들어** 넣는다. 고장
시뮬은 한 번 도는 데 13~47 초라, 커버리지가 낮은 회로를 실제로 지어 돌리면
검사가 안 돌게 된다 -- **안 도는 검사는 없는 검사다.** 대신 마지막에 진짜
넷리스트로 한 번 돌려 배선이 이어져 있는지 본다.

## 문턱을 정하기 전에 흔들림부터 쟀다 (실측 2026-09-23, nsw_fir)

묶음 6 못박고 씨앗만 바꿨을 때 고장 커버리지:

    표본 200   0.9400 ~ 0.9550   폭 0.0150
    표본 400   0.9375 ~ 0.9525   폭 0.0150
    표본 800   0.9487 ~ 0.9575   폭 0.0088

**95 % 를 문턱으로 두면 씨앗 하나로 초록과 빨강이 뒤집힌다.** 그래서 90 이다.

실행: python3 tests/test_DFT관문.py
"""
from __future__ import annotations

import sys
from pathlib import Path

뿌리 = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(뿌리))

FAIL = []


def ok(cond, what):
    print(("  통과  " if cond else "  실패  ") + what)
    if not cond:
        FAIL.append(what)


from house import gen as GEN            # noqa: E402
from house import tapeout as TO         # noqa: E402

문턱 = GEN.기본문턱
성한것 = {"플롭수": 425, "전체고장": 8732, "표본": 800, "표본인가": True,
        "패턴수": 384, "커버리지": 0.9487, "남은수": 41,
        "DPPM": 5390.0, "DPPM_몬테": 5523.0, "대조차이_pct": 2.46,
        "대조다이": 600_000, "수율_가정": 0.90, "초": 83.5,
        "시험입력": 478, "시험출력": 474, "대조표본": 30, "대조_시도": 30,
        "대조_잡은": 17, "대조_율": 56.67, "대조초": 21.5,
        "본_남은": 41, "본_시도": 12, "본_잡은": 1, "본_못잡은": 11,
        "본_안쳐본": 0, "본_율": 8.33, "본초": 15.0}


def 판정(**고침):
    return GEN.시험성판정({**성한것, **고침}, 문턱)


print("\n[1] 문턱이 있나 -- 그리고 그 문턱이 재는 것과 같은 단위인가")
for 열쇠 in ("고장커버리지_pct", "결함수준_DPPM", "대조차이_pct", "대조다이",
           "고장표본", "고장묶음", "고장씨", "수율_가정"):
    ok(열쇠 in 문턱, f"gen.기본문턱 에 {열쇠!r} 가 있다 ({문턱.get(열쇠)})")
ok(0 < 문턱["고장커버리지_pct"] <= 100,
   f"고장커버리지 문턱이 퍼센트 단위다 ({문턱['고장커버리지_pct']})")

print("\n[2] 성한 값은 통과한다 -- 늘 빨간 관문은 없느니만 못하다")
난것 = 판정()
ok(len(난것) == 3, f"관문 세 개를 낸다 ({len(난것)})")
ok([x[0].split(".")[0] for x in 난것] == ["8", "8b", "9"],
   f"이름표가 8 · 9 로 시작한다 ({[x[0][:4] for x in 난것]})")
ok(all(x[1] for x in 난것), "잰 값 그대로면 둘 다 초록이다")

print("\n[3] **관문이 무는가** -- 떨어져야 할 값을 하나씩 넣는다")
문다 = [
    ("커버리지가 문턱 바로 아래", dict(커버리지=(문턱["고장커버리지_pct"] - 0.1) / 100), 0),
    ("커버리지 0 (스캔이 아무것도 못 본다)", dict(커버리지=0.0), 0),
    ("DPPM 이 상한을 넘는다", dict(DPPM=문턱["결함수준_DPPM"] + 1), 2),
    ("닫힌꼴과 몬테카를로가 어긋난다",
     dict(대조차이_pct=문턱["대조차이_pct"] + 0.1), 2),
    ("둘 다 어긋난다", dict(DPPM=99999.0, 대조차이_pct=50.0), 2),
    # ---- 8b ----
    ("ATPG 대조가 문턱 아래 (엔진이 죽었다)",
     dict(대조_율=문턱["atpg대조율_pct"] - 0.1), 1),
    ("대조가 0 % (아무것도 못 잡는다)", dict(대조_율=0.0, 대조_잡은=0), 1),
    ("스캔에 플롭이 없다", dict(플롭수=0), 1),
    ("시험입력이 플롭보다 적다 (스캔이 덜 섰다)", dict(시험입력=10), 1),
    ("시험출력이 플롭보다 적다", dict(시험출력=10), 1),
]
for 왜, 고침, 자리 in 문다:
    r = 판정(**고침)
    ok(not r[자리][1], f"{왜} → 관문 {자리 + 8} 이 빨갛다")

print("\n[4] 문턱 **바로 위**는 통과한다 -- 경계가 한쪽으로 치우치지 않았나")
r = 판정(커버리지=문턱["고장커버리지_pct"] / 100)
ok(r[0][1], f"커버리지가 문턱과 꼭 같으면 통과한다 ({문턱['고장커버리지_pct']} %)")
r = 판정(DPPM=문턱["결함수준_DPPM"], 대조차이_pct=문턱["대조차이_pct"])
ok(r[2][1], "DPPM 과 대조차이가 상한과 꼭 같으면 통과한다")
ok(판정(대조_율=문턱["atpg대조율_pct"])[1][1],
   f"ATPG 대조가 문턱과 꼭 같으면 통과한다 ({문턱['atpg대조율_pct']} %)")
# **본(무작위가 놓친 고장)에는 문턱이 없다** -- 0 % 여도 초록이어야 한다
ok(판정(본_잡은=0, 본_율=0.0)[1][1],
   "무작위가 놓친 고장을 하나도 못 잡아도 초록이다 — 거기엔 문턱을 안 걸었다")

print("\n[5] 못 재면 초록이 아니라 빨강이다")
r = 판정(오류="스캔에 넣을 플롭이 하나도 없다")
ok(len(r) == 1 and not r[0][1],
   f"재기가 실패하면 관문 하나를 빨갛게 낸다 ({r[0][0] if r else '없음'})")

print("\n[6] 관문 글이 **무엇을 숨기지 않는가** -- 표본과 가정을 적는가")
말8, 말8b, 말9 = 판정()[0][2], 판정()[1][2], 판정()[2][2]
ok("표본" in 말8, "8 번 글이 '표본으로 잰 수' 라고 말한다")
ok("사인오프 문턱이 아니" in 말8 and "98" in 말8,
   "8 번 글이 이 문턱은 사인오프 문턱이 아니라고 말한다 (업계 98~99 %)")
ok("가정" in 말9, "9 번 글이 수율은 가정이라고 말한다")
ok("몬테카를로" in 말9 and "차이" in 말9, "9 번 글이 독립 대조와 그 차이를 적는다")
ok("ATPG 가 살아 있는가" in 말8b,
   "8b 글이 이 수가 재는 것은 설계가 아니라 ATPG 엔진이라고 말한다")
ok("문턱을 안 건다" in 말8b and "0~5" in 말8b,
   "8b 글이 본에는 문턱이 없다는 것과 그 까닭(잰 폭)을 적는다")
r = 판정(표본인가=False)
ok("전부" in r[0][2], "표본이 아닐 때는 '전부' 라고 적는다 — 표본으로 잰 것처럼 안 쓴다")

print("\n[7] 테이프아웃 표가 이 관문을 실제로 찾는가")
이름별 = {x["이름"]: x for x in TO.표(주인="dft")}
for n in ("고장 커버리지 문턱", "결함수준 (DPPM) 상한", "스캔 삽입 · ATPG 패턴"):
    x = 이름별.get(n)
    ok(x is not None and x["상태"] == TO.있다, f"{n} 이 「있다」 로 올라왔다")
ok(not TO.안걸린붙듦(), f"막아야 하는데 관문이 없는 것이 0개다 ({TO.안걸린붙듦()})")
ok(TO._관문있나("8") and TO._관문있나("8b") and TO._관문있나("9")
   and not TO._관문있나("99"),
   "관문 증거 찾기가 8·8b·9 는 찾고 없는 99 는 안 찾는다")

print("\n[8] 배선이 이어져 있나 -- 진짜 넷리스트로 한 번 돈다")
# **이 한 번이 [2]~[6] 을 떠받친다.** 위는 전부 손으로 만든 값이라, 재는 쪽이
# 그런 모양의 값을 실제로 내는지는 여기서만 확인된다.
import time                                                   # noqa: E402
t0 = time.time()
try:
    from house import designs as DES                          # noqa: E402
    from house import synth as SYN                            # noqa: E402
    합 = SYN.합성(DES.파라기본(DES.NSW_FIR) or None, 설계=DES.NSW_FIR)
    ok(합.get("됐나"), "합성이 됐다")
    D = GEN.시험성(합, {**문턱, "고장표본": 120, "고장묶음": 3})
    ok(not D.get("오류"), f"시험성()이 돌았다 ({D.get('오류', '')[:80]})")
    ok(set(성한것) <= set(D),
       f"손으로 만든 값과 **칸이 같다** (빠진 칸 {sorted(set(성한것) - set(D))})")
    ok(0.0 <= D["커버리지"] <= 1.0, f"커버리지가 0~1 이다 ({D['커버리지']})")
    ok(D["DPPM"] > 0 and D["DPPM_몬테"] > 0,
       f"DPPM 둘 다 양수다 ({D['DPPM']:,.0f} · {D['DPPM_몬테']:,.0f})")
    ok(D["대조차이_pct"] <= 문턱["대조차이_pct"],
       f"독립 대조가 문턱 안이다 ({D['대조차이_pct']} % ≤ {문턱['대조차이_pct']} %)")
    r = GEN.시험성판정(D, 문턱)
    ok(len(r) == 3, f"잰 값으로 판정 셋이 난다 ({len(r)})")
    print(f"       (진짜 실행: 커버리지 {D['커버리지'] * 100:.2f} % · "
          f"{D['DPPM']:,.0f} DPPM · {round(time.time() - t0, 1)} s)")
except Exception as e:                                        # noqa: BLE001
    ok(False, f"진짜 넷리스트로 못 돌렸다: {type(e).__name__}: {e}")

print("\n[9] 관문 수를 사람이 적지 않는가 -- 저장소 일곱 군데가 틀려 있었다")
번호 = GEN.관문번호들()
# **이 줄은 일부러 못박은 목록이다.** 관문이 늘면 여기가 빨개지고, 그때
# 사람이 "정말 늘린 것이 맞나" 를 한 번 본다. 자동으로 따라가면 관문이
# 조용히 사라져도 아무도 모른다.
ok(번호 == ("1", "2", "3", "4", "4b", "4c", "5", "5b", "5c", "6", "7", "8", "8b",
           "9"),
   f"관문번호들() 이 이름표 순서대로 {len(번호)}개를 센다 ({번호})")
ok(all(f" {n}." in (GEN.__doc__ or "") or f"\n    {n}." in (GEN.__doc__ or "")
       for n in 번호),
   "house/gen.py 머리글의 목록에 그 번호가 다 있다")
# **낡은 수가 다시 들어오는 것을 막는다.** 관문이 열 개일 때 일곱 군데가
# '관문 7개' 라고 적고 있었다 -- 수를 사람이 적으면 늘 이렇게 된다.
낡은말 = ("관문 7개", "관문 일곱")
샌곳 = []
for 길 in sorted(뿌리.glob("house/**/*.py")) + sorted(뿌리.glob("*.py")):
    글 = 길.read_text(encoding="utf-8", errors="replace")
    for w in 낡은말:
        # 이 검사가 붙든 자리를 적어 둔 줄은 빼고 센다
        for 줄 in 글.splitlines():
            if w in 줄 and "라고 적" not in 줄 and "낡은말" not in 줄:
                샌곳.append(f"{길.relative_to(뿌리)}: {줄.strip()[:60]}")
ok(not 샌곳, f"소스에 굳은 관문 수가 없다 ({len(샌곳)}곳)")
for x in 샌곳[:5]:
    print("       " + x)
from house import discord_cmd as DC                           # noqa: E402
도움 = DC._도움()
ok(f"관문 {len(번호)}개" in 도움,
   f"디스코드 도움말이 센 수를 그대로 말한다 ({len(번호)}개)")

print("\n" + "=" * 62)
if FAIL:
    print(f"실패 {len(FAIL)}개")
    for x in FAIL:
        print("  · " + x)
    raise SystemExit(1)
print("전부 통과")
