# -*- coding: utf-8 -*-
"""**사람 승인(0) 과 스펙 판독(0b) 이 무는가 -- 스펙을 몰래 바꿔 본다.**

`house/flow.py` 의 흐름 그림이 `제안서 -> 사람 승인 -> RTL·TB 생성` 을 약속하고
`run.승인하기()` 의 docstring 이 이렇게 적고 있었다.

    **제안서를 낸 그 스펙 그대로 짓는다.** 요청 글을 다시 읽지 않는다 --
    다시 읽으면 모델이 또 다르게 채우고, 그러면 **사람이 본 것과 다른 것을
    짓게 된다.**

맞는 말인데 **그것을 확인하는 것이 아무것도 없었다.** 누가 언제 승인했는지도
안 남았다.

## 모르는 칸이 조용히 기본값이 되던 자리

디스코드는 승인 전에 이렇게 알린다.

    ⚠ **아직 모르는 것이 4개 남아 있습니다** — 그 칸은 기본값으로 채워집니다

그런데 승인하면 그냥 지어졌다. 지금은 승인 기록이 그 목록을 안고 있고,
관문 0b 가 **새 모르는 칸이 생겼는데 아무도 안 봤는지**를 본다.

## 이 관문이 못 하는 것 -- 적어 둔다

**누가** 승인했는지는 증명하지 못한다. 이 저장소에 신원을 확인할 길이 없다.
서명이 아니라 **이력**이다. 검사도 그 한계를 못박는다([4]).

실행: python3 tests/test_승인관문.py
"""
from __future__ import annotations

import sys
from pathlib import Path

뿌리 = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(뿌리))

FAIL = []


def ok(cond, what):
    print(("  통과  " if cond else "  실패  ") + what)
    if not cond:
        FAIL.append(what)


from house import approve as AP       # noqa: E402
from house import gen as GEN          # noqa: E402
from house import spec as SPEC        # noqa: E402
from house import tapeout as TO       # noqa: E402

문턱 = GEN.기본문턱


def _스펙(모른다=(), 이름="t_gate"):
    s = SPEC.스펙()
    s.요청 = "검사가 지어 낸 요청"
    s.이름 = 이름
    s.모른다 = list(모른다)
    return s


print("\n[1] 해시가 내용을 따라가는가")
a, b = _스펙(["가"]), _스펙(["가"])
ok(AP.스펙해시(a) == AP.스펙해시(b), "같은 내용이면 같은 해시다")
c = _스펙(["가", "나"])
ok(AP.스펙해시(a) != AP.스펙해시(c), "내용이 다르면 해시가 다르다")
ok(len(AP.스펙해시(a)) == 64, "sha256 이다")

# **검사가 진짜 스펙방을 더럽히지 않게** 임시 자리로 옮긴다.
import tempfile                                               # noqa: E402
방 = Path(tempfile.mkdtemp(prefix="nsw_approve_"))
옛방 = AP.스펙방
AP.스펙방 = 방
try:
    키 = "t_gate"
    s = _스펙(["모르는 칸 하나", "모르는 칸 둘"])

    print("\n[2] **기록이 없으면 빨갛다**")
    A0 = GEN.승인점검(키, s, 문턱)
    ok(not GEN.승인판정(A0, 문턱)[0][1], "제안·승인 기록이 없으면 관문 0 이 빨갛다")
    ok(any("제안 기록이 없다" in x for x in A0["깨짐"]),
       f"무엇이 없는지 적는다 ({A0['깨짐']})")
    S0 = GEN.스펙점검(키, s, 문턱)
    ok(len(S0["안본모른다"]) == 2 and not GEN.스펙판정(S0, 문턱)[0][1],
       "승인 기록이 없으면 모르는 칸이 전부 '안 본 것' 이고 관문 0b 가 빨갛다")

    print("\n[3] 제안만 있고 승인이 없으면")
    AP.제안적기(키, s)
    A1 = GEN.승인점검(키, s, 문턱)
    ok(not GEN.승인판정(A1, 문턱)[0][1], "승인 기록이 없으면 여전히 빨갛다")
    ok(any("승인 기록이 없다" in x for x in A1["깨짐"]), "그것을 이름으로 적는다")

    print("\n[4] 승인하면 초록 -- 그리고 **신원은 증명 안 한다**")
    r = AP.승인적기(키, "형님", "하나로 진행")
    ok(r["됐나"], f"승인 기록이 남았다 ({r.get('까닭','')})")
    ok(r["기록"]["알고승인한것"] == s.모른다,
       f"**승인 기록이 그때의 모르는 칸을 안고 있다** ({r['기록']['알고승인한것']})")
    A2 = GEN.승인점검(키, s, 문턱)
    ok(GEN.승인판정(A2, 문턱)[0][1], "관문 0 이 초록이다")
    ok(GEN.스펙판정(GEN.스펙점검(키, s, 문턱), 문턱)[0][1], "관문 0b 도 초록이다")
    말 = GEN.승인판정(A2, 문턱)[0][2]
    ok("누가 승인했는지를 증명하지 않는다" in 말,
       "**신원을 증명하지 않는다고 관문 글이 먼저 말한다**")
    ok("서명이 아니라" in 말 and "이력" in 말, "서명이 아니라 이력이라고 적는다")
    ok("형님" in 말, "적힌 이름은 그대로 보인다")

    print("\n[5] **스펙을 몰래 바꾸면 잡는가** -- 이 파일의 심장")
    s2 = _스펙(["모르는 칸 하나", "모르는 칸 둘", "뒤에 슬쩍 더한 칸"])
    A3 = GEN.승인점검(키, s2, 문턱)
    ok(not GEN.승인판정(A3, 문턱)[0][1],
       "제안 뒤에 스펙이 바뀌면 관문 0 이 빨갛다")
    ok(any("스펙이 바뀌었다" in x for x in A3["깨짐"]),
       f"**제안 해시와 지금 해시가 다르다고 적는다** ({A3['깨짐'][0][:60]})")
    S3 = GEN.스펙점검(키, s2, 문턱)
    ok(S3["안본모른다"] == ["뒤에 슬쩍 더한 칸"],
       f"**새로 생긴 모르는 칸만 집어낸다** ({S3['안본모른다']})")
    ok(not GEN.스펙판정(S3, 문턱)[0][1], "관문 0b 도 빨갛다")

    print("\n[6] 다시 승인하면 다시 초록 -- 늘 빨간 관문이 아니다")
    AP.제안적기(키, s2)
    AP.승인적기(키, "형님", "바뀐 것 보고 다시 승인")
    ok(GEN.승인판정(GEN.승인점검(키, s2, 문턱), 문턱)[0][1], "관문 0 이 다시 초록이다")
    ok(GEN.스펙판정(GEN.스펙점검(키, s2, 문턱), 문턱)[0][1], "관문 0b 도 다시 초록이다")

    print("\n[7] 제안 없이 승인만 남기려 하면 -- 잇지 못하는 기록은 안 만든다")
    AP.제안길("t_없음").unlink(missing_ok=True)
    r2 = AP.승인적기("t_없음", "형님")
    ok(not r2["됐나"] and not AP.승인길("t_없음").exists(),
       f"제안 기록이 없으면 승인 기록을 안 만든다 ({r2.get('까닭','')})")
finally:
    AP.스펙방 = 옛방
    import shutil                                             # noqa: E402
    shutil.rmtree(방, ignore_errors=True)

print("\n[8] 스펙을 안 주면 **건너뛰지 않고 빨갛다**")
ok(not GEN.승인판정(GEN.승인점검("", None, 문턱), 문턱)[0][1],
   "스펙 없이 부르면 관문 0 이 빨갛다 — 못 본 것을 통과로 적지 않는다")
ok(not GEN.스펙판정(GEN.스펙점검("", None, 문턱), 문턱)[0][1],
   "관문 0b 도 그렇다")

print("\n[9] 사람이 정할 것이 남으면 빨갛다")
성 = {"문제수": 3, "남김": [], "되물음수": 3, "모른다": [], "알고승인한것": [],
     "안본모른다": [], "요약": ""}
ok(GEN.스펙판정(성, 문턱)[0][1], "남김 0 이면 초록")
ok(not GEN.스펙판정({**성, "남김": [{"규칙": "S001", "말": "사람이 정해라"}]},
                문턱)[0][1],
   f"사람이 정할 것이 하나라도 남으면 빨갛다 (허용 {문턱['스펙남김허용']})")

print("\n[10] 짓는 자리가 이 관문을 실제로 부르는가")
from tests._소스보기 import 산주장                             # noqa: E402
g = 산주장((뿌리 / "house" / "gen.py").read_text(encoding="utf-8"))
ok("스펙=s, 키=키" in g, "gen.짓기 가 관문에 스펙과 키를 넘긴다")
ok("승인판정(승인점검(키, 스펙, 문턱)" in g and "스펙판정(스펙점검(키, 스펙, 문턱)" in g,
   "관문() 이 둘을 맨 앞에서 부른다")
r = 산주장((뿌리 / "house" / "run.py").read_text(encoding="utf-8"))
ok("AP.승인적기(" in r, "run.승인하기 가 승인 이력을 남긴다")
ok("승인 이력을 못 남겼다" in r, "못 남기면 짓지 않는다")
a2 = 산주장((뿌리 / "house" / "arch.py").read_text(encoding="utf-8"))
ok("_AP.제안적기(" in a2, "arch.스펙두기 가 제안 기록을 남긴다")

print("\n[11] 테이프아웃")
이름별 = {x["이름"]: x for x in TO.표(주인="rtl")}
for n in ("스펙 판독 검사", "아키텍처 제안서 · 사람 승인"):
    x = 이름별.get(n)
    ok(x is not None and x["상태"] == TO.있다, f"{n} 이 「있다」 다")
i = 이름별.get("승인자 신원 확인")
ok(i is not None and i["상태"] == TO.없다 and not i["막나"],
   "「승인자 신원 확인」 은 없는 채로 남고 **막는 칸으로 안 센다**")
ok(TO._관문있나("0") and TO._관문있나("0b"), "관문 0 · 0b 를 찾는다")
ok(not TO.검사() and not TO.거짓증거() and not TO.안걸린붙듦(),
   f"계획에 흠이 없다 ({TO.검사()})")
w = TO.어디까지()
ok("M1" in (w["지난것"][0] if w["지난것"] else ""),
   f"**M1 이 지난 칸이 된다** (지난 칸: {w['지난것']})")

print("\n" + "=" * 62)
if FAIL:
    print(f"실패 {len(FAIL)}개")
    for x in FAIL:
        print("  · " + x)
    raise SystemExit(1)
print("전부 통과")
