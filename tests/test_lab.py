def _규약없이(self, 거래들, 모델):
    for tt in 거래들:
        if tt.관측acc is None:
            self.어긋남.append((tt, "done 이 안 떴다", None, None))
            continue
        self.본것 += 1
        기 = 모델.기대(tt)
        if tt.관측acc != 기:
            self.어긋남.append((tt, "acc 가 다르다", 기, tt.관측acc))
    return not self.어긋남


