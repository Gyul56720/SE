# -*- coding: utf-8 -*-
"""**코드 커버리지 관문(4c) 이 무는가 -- 그리고 그 수가 진짜인가.**

테이프아웃 지도의 M3 이 이렇게 적고 있었다.

    코드 커버리지 (줄 · 분기 · 토글)   없다   verilator --coverage 를 안 켠다

## 켜는 데 한 번 크게 틀렸다 -- 여기 적어 둔다

verilator 의 계수기는 **모델 객체 안**에 있고 `VerilatedCovImp` 는 그 자리를
가리키는 포인터만 든다. 그래서 하니스가 `delete dut` 한 **뒤**에 쓰면 해제된
메모리를 읽는다. 링커로 `main` 을 감싸 그렇게 해 봤더니 파일은 나왔고 수도
그럴듯했다 -- **그런데 거짓이었다.**

    nsw_fir.sv:253 (always @(posedge clk))  카운트 1,563,439,451
    txn 400 -> 선 20/21   ·   txn 2000 -> 선 18/21

누적 계수기에서 자극을 늘렸는데 맞은 점이 **줄 수는 없다.** 10^5 사이클에
15억이 찍힐 수도 없다. 둘 다 "해제된 자리를 읽었다" 는 표시였다.

**이 검사가 그 두 가지를 지킨다** -- 단조인가, 카운트가 사이클 수에 맞나.
글자를 안 보고 **실제로 두 번 돌려 견준다.**

고친 뒤(테스트벤치가 모델이 살아 있을 때 쓴다):

    선 21/21 · 분기 36/38 · 토글 914/945 · 씨앗 1~8 에서 폭 0.00 pp

실행: python3 tests/test_코드커버리지관문.py
"""
from __future__ import annotations

import sys
from pathlib import Path

뿌리 = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(뿌리))

FAIL = []


def ok(cond, what):
    print(("  통과  " if cond else "  실패  ") + what)
    if not cond:
        FAIL.append(what)


from house import designs as DES       # noqa: E402
from house import gen as GEN           # noqa: E402
from house import tapeout as TO        # noqa: E402

문턱 = GEN.기본문턱
성한것 = {"초": 0.1, "안맞은수": 33,
        "선": {"맞은것": 21, "전체": 21, "pct": 100.0},
        "분기": {"맞은것": 36, "전체": 38, "pct": 94.74},
        "토글": {"맞은것": 914, "전체": 945, "pct": 96.72},
        "합계_pct": 96.71, "점수": 1004,
        "안맞은것": [{"갈래": "v_branch", "파일": "nsw_fir.sv", "줄": "168",
                  "무엇": "if", "어디": "TOP.nsw_fir.u_mac"},
                  {"갈래": "v_toggle", "파일": "nsw_fir.sv", "줄": "213",
                   "무엇": "len[10]", "어디": "TOP.nsw_fir.u_ctrl"}]}


def 판정(**고침):
    return GEN.코드커버리지판정({**성한것, **고침}, 문턱)


print("\n[1] 문턱이 있고 단위가 맞나")
for 열쇠 in ("선_pct", "분기_pct", "토글_pct", "커버리지벡터", "커버리지씨"):
    ok(열쇠 in 문턱, f"gen.기본문턱 에 {열쇠!r} 가 있다 ({문턱.get(열쇠)})")
ok(문턱["토글_pct"] is None,
   "토글에는 문턱을 안 건다 — 버스 폭이 정하는 수라 여유 폭을 흠으로 만든다")

print("\n[2] 성한 값은 통과한다")
r = 판정()
ok(len(r) == 1 and r[0][1], "잰 값 그대로면 초록이다")
ok(r[0][0].startswith("4c."), f"이름표가 4c 로 시작한다 ({r[0][0][:20]})")

print("\n[3] **관문이 무는가**")
ok(not 판정(선={"맞은것": 18, "전체": 21, "pct": 85.71})[0][1],
   "선 85.71 % < 95 % → 빨갛다")
ok(not 판정(분기={"맞은것": 30, "전체": 38, "pct": 78.95})[0][1],
   "분기 78.95 % < 85 % → 빨갛다")
ok(판정(토글={"맞은것": 100, "전체": 945, "pct": 10.58})[0][1],
   "토글이 10 % 여도 초록이다 — 문턱을 안 걸었으니 그렇게 동작해야 한다")
r = 판정(오류="커버리지 파일이 안 나왔다")
ok(not r[0][1], "파일이 안 나오면 빨갛다 — 못 쟀는데 통과시키지 않는다")
ok("SE_COV_OUT" in r[0][2] or "커버리지 파일" in r[0][2],
   "그 빨간불이 무엇을 해야 하는지 말해 준다")

print("\n[4] 문턱과 꼭 같으면 통과한다")
ok(판정(선={"맞은것": 20, "전체": 21, "pct": 문턱["선_pct"]})[0][1],
   f"선이 문턱과 같으면 초록 ({문턱['선_pct']} %)")
ok(판정(분기={"맞은것": 33, "전체": 38, "pct": 문턱["분기_pct"]})[0][1],
   f"분기가 문턱과 같으면 초록 ({문턱['분기_pct']} %)")

print("\n[5] 관문 글이 숨기지 않는가")
말 = 판정()[0][2]
ok("문턱 없음" in 말, "토글에 문턱이 없다는 것을 글에 적는다")
ok("구조적 퇴행" in 말 and "5c" in 말,
   "이 관문이 검증의 질을 재는 것이 아니라고 적고, 그것은 5c 가 잰다고 가리킨다")
ok("nsw_fir.sv:168" in 말, "안 맞은 점을 파일:줄 로 적는다 — 값은 이 목록에 있다")

print("\n[6] **진짜로 재 본다 -- 그리고 그 수가 거짓이 아닌지 견준다**")
import re                                                     # noqa: E402
import time                                                   # noqa: E402
t0 = time.time()
C = GEN.코드커버리지(DES.NSW_FIR, 문턱)
ok(not C.get("오류"), f"코드커버리지()가 돌았다 ({C.get('오류', '')[:120]})")
if not C.get("오류"):
    ok(set(성한것) <= set(C),
       f"손으로 만든 값과 칸이 같다 (빠진 칸 {sorted(set(성한것) - set(C))})")
    for 이름 in ("선", "분기", "토글"):
        v = C[이름]
        ok(0 < v["전체"] and 0 <= v["맞은것"] <= v["전체"],
           f"{이름}: {v['맞은것']}/{v['전체']} — 맞은 것이 전체를 안 넘는다")
    # **여기가 이 파일의 심장이다.** 해제된 메모리를 읽으면 이 둘이 깨진다.
    적 = GEN.코드커버리지(DES.NSW_FIR, {**문턱, "커버리지벡터": 20})
    많 = GEN.코드커버리지(DES.NSW_FIR, {**문턱, "커버리지벡터": 2000})
    ok(적["점수"] == 많["점수"] == C["점수"],
       f"점의 개수(분모)가 자극과 무관하다 ({적['점수']} · {많['점수']} · {C['점수']})")
    깨짐 = [이름 for 이름 in ("선", "분기", "토글")
          if 많[이름]["맞은것"] < 적[이름]["맞은것"]]
    ok(not 깨짐,
       "자극을 100배 늘렸을 때 맞은 점이 **줄지 않는다** — 줄면 해제된 메모리를 "
       f"읽는 것이다 (깨진 것 {깨짐})")
    print(f"       (txn 20 → {적['합계_pct']} % · txn 2000 → {많['합계_pct']} % · "
          f"점 {C['점수']}개 · {C['초']} s)")
    # 씨앗을 바꿔도 같아야 한다 -- 코드 커버리지는 구조적인 수다
    씨2 = GEN.코드커버리지(DES.NSW_FIR, {**문턱, "커버리지씨": 7})
    ok(씨2["합계_pct"] == C["합계_pct"],
       f"씨앗을 바꿔도 같다 ({C['합계_pct']} % · {씨2['합계_pct']} %)")
    r = GEN.코드커버리지판정(C, 문턱)
    ok(len(r) == 1 and r[0][1], f"잰 값으로 관문이 초록이다 ({r[0][3]} %)")

print("\n[7] 테스트벤치가 커버리지를 **모델이 살아 있을 때** 내는가")
tb = (뿌리 / "house" / "dv" / "tb_nsw_fir.cpp").read_text(encoding="utf-8")
ok("VerilatedCov::write" in tb, "테스트벤치가 커버리지를 쓴다")
ok(tb.index("VerilatedCov::write") < tb.rindex("return (fail"),
   "그 호출이 main 의 return 보다 앞에 있다 — 모델이 아직 살아 있는 자리")
ok("VerilatedCov::write" in GEN.TB프롬프트 and "SE_COV_OUT" in GEN.TB프롬프트,
   "짓는 테스트벤치에도 같은 것을 시킨다 (TB프롬프트)")

print("\n[8] 테이프아웃 표가 이 관문을 찾는가")
이름별 = {x["이름"]: x for x in TO.표(주인="dv")}
x = 이름별.get("코드 커버리지 (줄 · 분기 · 토글)")
ok(x is not None and x["상태"] == TO.있다, "「코드 커버리지」 가 「있다」 로 올라왔다")
ok(TO._관문있나("4c"), "관문 증거 찾기가 4c 를 찾는다")
ok(not TO.거짓증거() and not TO.안걸린붙듦(),
   f"거짓 증거도 안 걸린 붙듦도 없다 ({TO.거짓증거()} · {TO.안걸린붙듦()})")
ok("4c" in GEN.관문번호들(), f"관문 목록에 4c 가 있다 ({GEN.관문번호들()})")

print("\n" + "=" * 62)
if FAIL:
    print(f"실패 {len(FAIL)}개")
    for x in FAIL:
        print("  · " + x)
    raise SystemExit(1)
print("전부 통과")
