"""**박자 종류를 내가 안 정하는가. 그리고 흔들리지 않는가.**

    python3 tests/test_jaso_beats.py

## 왜 하드코딩을 안 하나

`novel/arc.py` 의 `STAGES` 는 손으로 적은 목록이다. 소설에서는 그래도 됐다 -- 3막
8시퀀스가 밖에 있는 이론이므로. **자소서에는 그런 것이 없다.** '상황·행동·결과' 같은
목록을 내가 적으면 그 순간 그것이 사양서가 되고, 캐 온 자료는 내 목록을 확인해 주는
데밖에 못 쓰인다.

그래서 문단을 재고 **무리를 짓는다.** 무리가 박자이고, 이름도 중심에서 나온다.

## 흔들리면 문법이 아니다

무리짓기는 시작점에 따라 답이 달라진다. 돌릴 때마다 다른 박자가 나오면 그것은 문법이
아니라 잡음이다 -- 그리고 그 잡음으로 만든 프롬프트를 사람이 믿게 된다.
"""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from jaso import beats as BT                                      # noqa: E402
from jaso import mine as MN                                       # noqa: E402

fails = []


def ok(cond, msg):
    print(("  OK   " if cond else "  실패 ") + msg)
    if not cond:
        fails.append(msg)


장면 = "2025년 3월, 로그 파이프라인이 여섯 시간씩 밀리는 화면을 처음 봤습니다. 무봉테크 데이터플랫폼팀에서였습니다."
한일 = "저는 수집 경로를 스트리밍으로 바꾸는 일을 맡았습니다. Airflow 로 스케줄을 걸고 BigQuery 에서 집계했습니다."
결과 = "반영 지연을 35분에서 4분으로 줄였고, 2주간 24000명씩 재니 클릭률이 2.1%에서 2.6%로 올랐습니다."
되새 = "그때부터 저는 지표를 의심하는 쪽으로 일한다는 것을 배웠습니다. 무엇을 재는지 먼저 정하지 않은 수는 안 씁니다."
포부 = "입사 후에는 지표 정의부터 문서로 남기는 일을 하고 싶습니다. 앞으로 그렇게 나아가겠습니다."

한편 = "\n\n".join([장면, 한일, 결과, 되새, 포부])


print("── 축은 말의 꼴이지 박자가 아니다 ──────────────────────")
ok(len(BT.축) == 9, f"축 {len(BT.축)}개")
박자말 = ("상황", "행동", "결과", "도입", "마무리", "STAR", "기승전결", "서론", "본론")
샌것 = [w for w in 박자말 for a in BT.축 if w in a]
ok(not 샌것, f"**축 이름에 박자 이름이 한 글자도 없다** (샌 것: {샌것})")
ok(not any(w in str(BT.이름.__doc__ or "") for w in ("상황", "행동", "결과")),
   "이름 붙이는 자리에도 박자 목록이 없다")
v장면, v결과, v되새 = BT.재기(장면), BT.재기(결과), BT.재기(되새)
ok(v결과[BT.축.index("수")] > v되새[BT.축.index("수")], "수 축이 갈린다")
ok(v되새[BT.축.index("되새김")] > v결과[BT.축.index("되새김")], "되새김 축이 갈린다")
ok(BT.재기(포부)[BT.축.index("앞말")] > 0, "앞말 축이 잡힌다")
ok(len(BT.글재기(한편)) == 5, "편마다 문단 수만큼 벡터가 나온다")
ok(all(isinstance(x, (int, float)) for v in BT.글재기(한편) for x in v),
   "**돌려주는 것이 수뿐이다** -- 글이 안 따라 나온다")


print("\n── 무리가 박자다 -- k 도 데이터가 정한다 ────────────────")
편별 = [BT.글재기(한편) for _ in range(6)]
for i, 편 in enumerate(편별):                     # 서로 조금씩 다른 편인 척
    편별[i] = [tuple(x + (i % 3) * 0.01 for x in v) for v in 편]
표 = BT.세우기(편별)
ok(표.표본 == 6, f"표본 {표.표본}편")
ok(2 <= len(표.이름들) <= 7, f"박자 {len(표.이름들)}개 -- k 를 안 줬는데 정해졌다")
ok(len(표.차례들) == 6 and all(len(x) == 5 for x in 표.차례들),
   "편마다 문단 수만큼 박자 번호가 붙는다")
ok(all(이 for 이 in 표.이름들), f"박자마다 이름이 있다 ({표.이름들})")
ok(any("·" in 이 or 이 == "평이" for 이 in 표.이름들),
   "**이름이 축에서 나온다** -- 내가 붙인 뜻이 아니다")


print("\n── 흔들리지 않는다 (제일 중요) ─────────────────────────")
표2 = BT.세우기(편별)
ok(표.이름들 == 표2.이름들 and 표.차례들 == 표2.차례들,
   "**같은 자료면 같은 답이다** -- 무작위 시작이면 돌릴 때마다 다른 박자가 나오고, "
   "그 잡음으로 만든 프롬프트를 사람이 믿게 된다")
뒤집힌것 = list(reversed(편별))
표3 = BT.세우기(뒤집힌것)
ok(sorted(표3.이름들) == sorted(표.이름들),
   f"편 차례를 바꿔도 같은 박자가 나온다 ({sorted(표3.이름들)})")


print("\n── 차례 -- 무엇 다음에 무엇이 오나 ─────────────────────")
전이 = 표.전이()
ok(전이, f"전이 {len(전이)}가지")
흔한 = 표.흔한차례(3, 3)
ok(흔한 and 흔한[0][1] >= 3, f"흔한 3박자 차례가 나온다 ({흔한[0][1]}번)")
앞자리 = min(표.자리(i) for i in range(len(표.이름들)))
뒷자리 = max(표.자리(i) for i in range(len(표.이름들)))
ok(앞자리 < 뒷자리, f"**박자마다 글의 어디쯤에 오는지가 나온다** ({앞자리}~{뒷자리})")
말 = BT.문법말(표)
ok(말 and any("차례로 놓습니다" in x for x in 말), f"차례가 말로 옮겨진다 ({len(말)}줄)")
ok(any("첫 문단" in x for x in 말) and any("마지막 문단" in x for x in 말),
   "여는 자리와 닫는 자리를 짚는다")
붙 = " ".join(말)
ok("J002" not in 붙 and "관문" not in 붙 and "합격" not in 붙,
   "**문법말에 관문·합격 이야기가 없다**")
ok(BT.문법말(BT.박자표()) == [], "빈 표에도 안 죽는다")


print("\n── mine 이 문단 벡터를 담는다 (M001 을 안 깨고) ─────────")
x = MN.재기(한편, "https://example.com/a")
ok(len(x.문단벡터) == 5, f"문단 {len(x.문단벡터)}개의 벡터가 담긴다")
ok(all(isinstance(u, (int, float)) for v in x.문단벡터 for u in v),
   "**수뿐이다** -- 글이 한 조각도 안 들어간다")
ok(not any(v.규칙 == "M001" for v in MN.검사(x, 한편)),
   "M001 을 안 깬다 -- 벡터는 글이 아니다")
ok(BT.세우기([[tuple(v) for v in x.문단벡터]]).표본 == 1,
   "담긴 벡터로 박자를 다시 세울 수 있다")

print("\n── 표본이 적으면 무리가 뜻이 없다 ──────────────────────")
ok(len(BT.세우기([BT.글재기(장면)]).이름들) <= 2,
   "한 문단짜리 한 편이면 박자가 거의 안 갈린다 -- 그래도 안 죽는다")
ok(BT.세우기([]).표본 == 0, "빈 것에도 안 죽는다")
ok(BT.k고르기([]) >= 1, "빈 것에서도 k 가 나온다")

print()
print(f"실패 {len(fails)}건" if fails else "전부 통과")
raise SystemExit(1 if fails else 0)
