"""**긁어 온 것에서 자소서가 아닌 것을 가르는가. 그리고 말없이 안 지우는가.**

    python3 tests/test_jaso_sift.py

## 왜 있나 -- 실측

사용자 런에서 23편이 들어왔는데 **논문 초록 여섯 편이 2만자대로** 섞였고, 음악·지도·
라이선스 쪽도 있었다. 이대로 `mine` 에 넣으면 **논문의 형식이 '합격 자소서의 형식'
으로 집계되고**, 그 분포로 만든 문법 후보가 프롬프트에 들어간다. 잡음이 아니라
**틀린 값**이 된다.

## 그런데 말없이 지우면 안 된다

이 자는 **꼴로만 본다.** 뜻을 안 읽으므로 자소서인데 낮게 나오는 것이 있을 수 있고,
자동으로 지우면 아무도 모른다. `dig/README.md` 의 규율이다 -- 줄이면 줄인 것을
아무도 못 되찾는다.
"""
from __future__ import annotations

import contextlib
import io
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from jaso import keep as KP                                      # noqa: E402
from jaso import sift as SF                                      # noqa: E402

fails = []


def ok(cond, msg):
    print(("  OK   " if cond else "  실패 ") + msg)
    if not cond:
        fails.append(msg)


자소서 = """2025년 3월, 로그 파이프라인이 여섯 시간씩 밀리는 화면을 처음 봤습니다.
저는 수집 경로를 스트리밍으로 바꾸는 일을 맡았고 지연을 35분에서 4분으로 줄였습니다.
그때 저는 지표를 의심하는 습관을 얻었습니다. 지원 동기도 거기서 나왔습니다.
데이터 분석 직무에 필요한 역량이 무엇인지 그 경험에서 배웠습니다. 입사 후에도
그렇게 일하겠습니다. 협업 과정에서 겪었던 갈등도 그 기준으로 풀었습니다."""
논문 = """초록 본 연구는 편입학 전형의 효과를 분석하였다. Keywords: 편입, 전형
연구는 2020년부터 2024년까지의 자료를 사용하였다. 참고문헌 목록은 다음과 같다.
DOI:10.1234/abcd Vol. 12 No. 3 pp. 45-67 한국교육학회 등재 논문이다. 저자명 홍길동."""
서점 = """정가 18,000원 판매가 16,200원 적립 900원 장바구니 바로 구매 배송 안내
출판사 ○○ ISBN 979-11 판매지수 1,234 리뷰 12건 품절 재고 없음 결제 쿠폰 할인율"""
껍데기 = """로그인 회원가입 검색어 카테고리 공지사항 이용약관 저작권 Copyright
더 보기 전체 보기 이전 글 다음 글 태그 목록 라이선스 License"""


print("── 네 갈래가 갈리는가 ─────────────────────────────────")
점 = {이름: SF.점수(SF.재기(글)) for 이름, 글 in
     (("자소서", 자소서), ("논문", 논문), ("서점", 서점), ("껍데기", 껍데기))}
print("   " + " · ".join(f"{k} {v:.1f}" for k, v in 점.items()))
ok(점["자소서"] > 0, f"자소서는 양수 ({점['자소서']:.1f})")
ok(점["논문"] < 0, f"**논문은 음수** ({점['논문']:.1f}) -- dbpia 가 여기 걸린다")
ok(점["서점"] < 0, f"서점 쪽은 음수 ({점['서점']:.1f})")
ok(점["껍데기"] < 0, f"목록 껍데기는 음수 ({점['껍데기']:.1f})")
ok(점["자소서"] > max(점["논문"], 점["서점"], 점["껍데기"]),
   "**자소서가 셋 다보다 높다** -- 순위가 뒤집히지 않는다")

print("\n── **안내문이 본문을 이기지 못한다** (실측 519편, 회귀 못) ──")
안내문 = """자기소개서 작성법 완벽 가이드. 지원동기 작성법, 성장과정 작성법,
성격의 장단점 작성법, 입사 후 포부 작성법을 정리했습니다. 직무 역량 자기소개서
예시와 합격 자소서 항목별 예시를 제공합니다. 자기소개서 첨삭 서비스도 있습니다.
지원동기 예시, 학업계획서 예시, 편입 자소서 예시를 확인하세요."""
ㅂ, ㅇ = SF.재기(자소서), SF.재기(안내문)
ok(SF.점수(ㅂ) > SF.점수(ㅇ),
   f"**본문 {SF.점수(ㅂ):.1f} > 안내문 {SF.점수(ㅇ):.1f}** -- 실측: 519편을 긁고 "
   "보니 상위권이 전부 '자소서에 대한 글'(가이드·항목 목록·판매 미리보기)이었다. "
   "그 글들은 `지원동기·성장과정·포부` 를 되풀이해 나열하므로 밀도가 치솟았고, "
   "옛 눈금으로는 안내문 107.2 대 본문 30.2 였다")
ok(SF.점수(ㅇ) < 0, f"안내문은 음수 ({SF.점수(ㅇ):.1f})")
ok(SF.본문성(ㅂ) > SF.본문성(ㅇ) * 3,
   f"**본문성이 갈린다** ({SF.본문성(ㅂ):.1f} vs {SF.본문성(ㅇ):.1f}) -- 1인칭과 "
   "과거 서술이 본문의 서명이고, 안내문에는 그것이 없다")
ok(SF.메타성(ㅇ) > SF.메타성(ㅂ) * 3,
   f"**메타성이 갈린다** ({SF.메타성(ㅇ):.1f} vs {SF.메타성(ㅂ):.1f})")
ok("자소서말" in SF.까닭(ㅇ) or "목록" in SF.까닭(ㅇ),
   f"안내문의 까닭이 나온다 ({SF.까닭(ㅇ)})")
넘친것 = SF.재기("지원동기 성장과정 포부 역량 " * 200)
ok(SF.점수(넘친것) < 0,
   f"**자소서말만 넘치면 감점이다** ({SF.점수(넘친것):.1f}) -- 되풀이 자체가 "
   "'본문이 아니다' 는 신호다")

print("\n── 길이로 이기지 못한다 ────────────────────────────────")
긴논문 = 논문 * 30
ok(SF.점수(SF.재기(긴논문)) < 0,
   f"**논문을 30배로 늘려도 음수다** ({SF.점수(SF.재기(긴논문)):.1f}) -- 1,000자당으로 "
   "재므로 긴 글이 그냥 이기지 않는다. 실측에서 논문이 2만자대로 들어왔다")
ok(abs(SF.점수(SF.재기(긴논문)) - 점["논문"]) < abs(점["논문"]) * 0.5,
   "길이를 바꿔도 점수가 크게 안 흔들린다")
ok(SF.점수(SF.재기(자소서 * 5)) > 0, "(대조군) 자소서도 길이에 안 흔들린다")

print("\n── 까닭이 붙는가 ─────────────────────────────────────")
ok("학술" in SF.까닭(SF.재기(논문)), f"논문은 학술 축이 끌었다고 말한다 ({SF.까닭(SF.재기(논문))})")
ok("상업" in SF.까닭(SF.재기(서점)), "서점은 상업 축")
ok(SF.까닭(SF.재기(자소서)), f"자소서도 까닭이 나온다 ({SF.까닭(SF.재기(자소서))})")
ok(SF.까닭({}) == "", "잰 것이 없으면 빈 말 (지어내지 않는다)")
ok(len({이름 for 이름, _, _, _ in SF.축들}) == len(SF.축들), "축 이름이 안 겹친다")
ok(sum(1 for _, _, w, _ in SF.축들 if w > 0) >= 2
   and sum(1 for _, _, w, _ in SF.축들 if w < 0) >= 2,
   "올리는 축과 내리는 축이 둘 이상씩 있다")

print("\n── **말없이 안 지운다** (제일 중요) ─────────────────────")
곳 = KP.보기DIR / "_sift검사"
쓴것 = []
try:
    for 이름, 글 in (("자소서", 자소서), ("논문", 논문), ("서점", 서점)):
        p, vs = KP.담기(글 * 3, f"https://example.com/{이름}", 곳)
        ok(p is not None, f"{이름} 표본을 담았다")
        쓴것.append(p)
    것들 = SF.훑기(곳)
    ok(len(것들) == 3, f"{len(것들)}편을 훑었다")
    ok(것들[0][1] < 것들[-1][1], "**점수 낮은 것이 위로** -- 버릴 것이 먼저 보인다")
    ok("자소서" in 것들[-1][5], f"자소서가 맨 아래 ({것들[-1][5]})")

    buf, err = io.StringIO(), io.StringIO()
    with contextlib.redirect_stdout(buf), contextlib.redirect_stderr(err):
        code = SF.main(["--곳", str(곳)])
    out = buf.getvalue()
    ok(code == 0 and len(SF.훑기(곳)) == 3,
       "**임계를 안 주면 한 편도 안 지운다**")
    ok("아직 아무것도 안 지웠다" in out, "안 지웠다고 말한다")
    ok("꼴로만 본다" in out and "말없이 지우면 아무도 모른다" in out,
       "**왜 자동으로 안 자르는지** 화면이 말한다 -- 뜻을 안 읽으므로 자소서인데 "
       "낮게 나오는 것이 있을 수 있다")
    ok("--버리기" in out, "어떻게 자르는지 알려 준다")

    buf2 = io.StringIO()
    with contextlib.redirect_stdout(buf2):
        SF.main(["--곳", str(곳), "--버리기", "0"])
    남은것 = SF.훑기(곳)
    ok(len(남은것) == 1 and "자소서" in 남은것[0][5],
       f"**임계를 주면 그때 지운다** ({len(남은것)}편 남음: {남은것[0][5]})")
    ok("지움" in buf2.getvalue() and "지웠다" in buf2.getvalue(),
       "무엇을 지웠는지 한 줄씩 적는다")
finally:
    if 곳.exists():
        for f in 곳.glob("*"):
            f.unlink()
        곳.rmdir()

print("\n── 볼 것이 없으면 그렇게 말한다 ────────────────────────")
buf3, err3 = io.StringIO(), io.StringIO()
with contextlib.redirect_stdout(buf3), contextlib.redirect_stderr(err3):
    code = SF.main(["--곳", str(KP.보기DIR / "_없는데")])
ok(code == 3 and "볼 것이 없다" in err3.getvalue(), "빈 곳이면 끝값 3")

print()
print(f"실패 {len(fails)}건" if fails else "전부 통과")
raise SystemExit(1 if fails else 0)
