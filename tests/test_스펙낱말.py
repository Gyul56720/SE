# -*- coding: utf-8 -*-
"""**판독기가 낱말 안에 든 낱말에 걸리지 않는가 -- 두 쪽을 다 잰다.**

실측 2026-09-23. AESA 레이더 규격서를 `house/spec.py 읽기()` 에 먹였더니:

    회로 = [... '암호' ...]    <- **AES** 가 `AESA` 여덟 군데 안에 들어 있었다
    쓰임새 = ['자동차' ...]    <- 한 글자 별칭 `차` 가 `차세대`·`오차`·`편차` 에 걸렸다
    온도_C = [204.0]           <- `JESD204C` 를 204 ℃ 로 읽었다.
                                  진짜 온도 `-54 ℃ ~ +85 ℃` 는 **하나도 못 잡았다**

세 번째가 가장 나쁘다. **못 잡은 것이 아니라 엉뚱한 것을 잡았다** -- 빈 칸은
'모른다' 로 보이지만 거짓 판독은 사실처럼 보인다.

이 저장소는 같은 병을 세 번 앓았다(`ack` ⊂ `backpressure` · `st` ⊂ `wrst_n` ·
`수` ⊂ `주파수`). 그래서 **두 쪽을 다 잰다** -- 안 닿아야 할 것이 안 닿나,
그리고 **닿아야 할 것은 닿나**. 늘 빨간 장치는 늘 초록인 장치와 똑같이 쓸모없다.

실행: python3 tests/test_스펙낱말.py
"""
from __future__ import annotations

import sys
from pathlib import Path

뿌리 = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(뿌리))

FAIL = []


def ok(cond, what):
    print(("  통과  " if cond else "  실패  ") + what)
    if not cond:
        FAIL.append(what)


from house import spec as SPEC          # noqa: E402

print("\n[1] 낱말 안에 든 낱말에 안 걸린다")
안닿아야 = [
    ("AESA 능동위상배열 레이더", "회로", "암호", "AES ⊂ AESA"),
    ("차세대 전투기 탑재 센서, 채널간 편차 3도", "쓰임새", "자동차", "차 ⊂ 차세대·편차"),
    ("RMS 위상 오차 2.5도", "쓰임새", "자동차", "차 ⊂ 오차"),
]
for 글, 칸, 갈래, 왜 in 안닿아야:
    난것 = getattr(SPEC.읽기(글), 칸)
    ok(갈래 not in 난것, f"{왜} — {글[:22]!r} 에서 {칸} 에 {갈래!r} 가 안 붙는다 ({난것})")

print("\n[2] 닿아야 할 것은 닿는다 -- 늘 빨간 장치도 쓸모없다")
닿아야 = [
    ("AES-256 암호 가속기를 설계해줘", "회로", "암호"),
    ("자동차 범퍼용 TTD 회로", "쓰임새", "자동차"),
    ("차량용 레이더 프런트엔드", "쓰임새", "자동차"),
    ("ADAS 카메라 인터페이스", "쓰임새", "자동차"),
    ("64탭 FIR 필터", "회로", "FIR"),
    ("14-bit 3 GSps ADC 인터페이스", "회로", "ADC"),
]
for 글, 칸, 갈래 in 닿아야:
    난것 = getattr(SPEC.읽기(글), 칸)
    ok(갈래 in 난것, f"{글[:24]!r} 에서 {칸} 에 {갈래!r} 가 붙는다 ({난것})")

print("\n[3] 한 글자 한글 별칭을 표에 두지 않는다 -- 어느 낱말 안에든 들어간다")
for 이름, 표 in (("쓰임새표", SPEC.쓰임새표), ("문제표", SPEC.문제표),
               ("회로표", SPEC.회로표)):
    한글자 = [(g, w) for g, 말들 in 표.items() for w in 말들
            if len(w.strip()) == 1 and not w.strip().isascii()]
    ok(not 한글자, f"{이름} 에 한 글자 한글 별칭이 없다 ({한글자})")
ok(not SPEC._닿나("차", "차세대", "차세대"),
   "맞추는 자리도 한 글자 한글을 안 받는다 — 표가 뚫려도 여기서 막힌다")

print("\n[4] 온도 -- 글자에 붙은 수를 안 받고 ℃ 를 받는다")
잰다 = [
    ("JESD204C 고속 직렬 링크", [], "링크 이름의 204 를 온도로 안 읽는다"),
    ("동작 온도 -54 ℃ ~ +85 ℃", [-54.0, 85.0], "℃(U+2103) 를 받는다"),
    ("접합 온도 125°C 까지", [125.0], "°C 를 받는다"),
    ("주변 온도 85 C 에서", [85.0], "그냥 C 도 받는다"),
    ("PCIe Gen4 x8 / 100GbE", [], "규격 이름의 숫자를 온도로 안 읽는다"),
]
for 글, 바람, 왜 in 잰다:
    난것 = SPEC.읽기(글).수.get("온도_C", [])
    ok(sorted(난것) == sorted(바람), f"{왜} — {글[:26]!r} -> {난것}")

print("\n[5] 그 규격서 전체를 먹여도 그대로다")
문서 = ("AESA-RADAR-SPEC · 차세대 전투기 다목적 센서. JESD204C 링크, "
      "14-bit 3.0 GSps ADC, 8192-point FFT 펄스압축, 8-탭 병렬 MAC 배열, "
      "동작 온도 -54 ℃ ~ +85 ℃, 채널간 편차 < 3℃, RMS 위상 오차 2.5°")
s = SPEC.읽기(문서)
ok("암호" not in s.회로, f"AESA 를 암호 회로로 안 읽는다 ({s.회로})")
ok("자동차" not in s.쓰임새, f"차세대·편차·오차 를 자동차로 안 읽는다 ({s.쓰임새})")
ok(204.0 not in s.수.get("온도_C", []), f"204 ℃ 가 없다 ({s.수.get('온도_C')})")
ok(-54.0 in s.수.get("온도_C", []) and 85.0 in s.수.get("온도_C", []),
   f"진짜 동작 온도 둘은 잡는다 ({s.수.get('온도_C')})")
ok("ADC" in s.회로 and "FIR" in s.회로,
   f"실제로 있는 회로는 그대로 잡는다 ({s.회로})")

print("\n" + "=" * 62)
if FAIL:
    print(f"실패 {len(FAIL)}개")
    for x in FAIL:
        print("  · " + x)
    raise SystemExit(1)
print("전부 통과")
