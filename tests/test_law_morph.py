"""형태소가 **뜯은 것과 못 뜯은 것을 갈라 말하는가.**

분석기의 위험은 틀리는 것이 아니라 **틀린 채로 조용한 것**이다. 조사를 잘못 떼면
어간이 낱말 아닌 것이 되고, 그 낱말로 조문을 뒤지면 안 걸린다 -- 그러면 심판은
"조문에 그런 말이 없다" 고 한다. 기각이 아니라 **오독으로 인한 기각**이다.

그래서 여기서 보는 것은 두 가지다: 뜯은 것이 맞는가, 그리고 **못 뜯은 것을
못 뜯었다고 적는가.**

    python3 tests/test_law_morph.py
"""
from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from law import exam as EX                                            # noqa: E402
from law import morph as M                                            # noqa: E402

fails = []


def ok(cond, msg):
    print(("  OK   " if cond else "  실패 ") + msg)
    if not cond:
        fails.append(msg)


print("[조사] **긴 것부터 뗀다** -- '에게' 를 '에' 로 떼면 '게' 가 어간에 남는다")
for 어절, 어간, 격 in (("당사자가", "당사자", "주격"), ("의사표시를", "의사표시", "목적"),
                      ("채무자에게", "채무자", "여격"), ("법원은", "법원", "주제"),
                      ("계약의", "계약", "관형"), ("등기로써", "등기", "수단"),
                      ("매도인으로부터", "매도인", "탈격")):
    t = M.분해(어절)
    ok(t.어간 == 어간 and t.격 == 격,
       f"{어절!r} -> 어간 {어간!r}·격 {격} (얻은 값 {t.어간!r}·{t.격!r})")

print()
print("[겁] **안 뗀 것이 잘못 뗀 것보다 낫다**")
# '법인이' 의 '이' 를 떼면 '법인' 이지만 '법인이다' 에서 떼면 '법인' 이 아니라
# 서술어다. 남는 어간이 짧으면 안 뗀다 -- 그리고 **안 뗐다고 적는다.**
ok(M.분해("법인이다").갈래 == "용언", "'법인이다' 는 용언이지 체언+조사가 아니다")
_짧 = M.분해("값이")
ok(_짧.왜 == "미분석" and _짧.어간 == "값이",
   f"뗐을 때 한 글자만 남으면 안 떼고 **미분석이라 적는다** (얻은 값 {_짧})")

# **'인' 과 '임' 은 사람이거나 이름씨다.** 실측으로 잡힌 자리다.
for _w, _st in (("매도인으로부터", "매도인"), ("차임", "차임"), ("대리인이", "대리인"),
                ("책임을", "책임")):
    ok(M.분해(_w).어간 == _st,
       f"{_w!r} 의 '인·임' 을 안 뗀다 -> {_st!r} (얻은 값 {M.분해(_w).어간!r})")
# 그래도 진짜 용언은 그대로 뜯긴다 -- 넓힌 것이지 눈을 감은 것이 아니다.
for _w, _st in (("청구할", "청구"), ("취득한", "취득"), ("확정된", "확정")):
    ok(M.분해(_w).어간 == _st and M.분해(_w).갈래 == "용언",
       f"{_w!r} -> {_st!r} 용언 (얻은 값 {M.분해(_w)})")

print()
print("[한 글자 체언] 시험의 당사자는 甲·乙·丙 이다")
# 실측: 이것을 안 받아서 `甲이` `乙에게` `丙은` 따위가 통째로 미분석이었다.
# 당사자를 못 뜯으면 **누가 무엇을 하는가** 를 못 세운다 -- 명제의 주어가 사라진다.
for 어절, 어간 in (("甲이", "甲"), ("乙에게", "乙"), ("丙은", "丙"), ("소를", "소"),
                   ("것으로", "것")):
    t = M.분해(어절)
    ok(t.어간 == 어간 and t.왜 != "미분석",
       f"{어절!r} -> {어간!r} (얻은 값 {t.어간!r}·{t.왜!r})")

print()
print("[서법] **동사에 붙는다** -- 금지를 재량보다 먼저 본다")
# '할 수 없다' 를 '할 수 있다' 로 읽으면 답이 정확히 뒤집힌다. 차례가 곧 규칙이다.
for 글, 몫 in (("취소할 수 있다.", "재량"), ("취소할 수 없다.", "금지"),
               ("대항하지 못한다.", "금지"), ("증명하여야 한다.", "기속"),
               ("하여서는 아니 된다.", "금지"), ("소유권을 취득한다.", "단정")):
    ok(M.서법(글) == 몫, f"{글!r} -> {몫} (얻은 값 {M.서법(글)!r})")

_서술 = M.서술("당사자가 착오를 증명한 때에는 그 의사표시를 취소할 수 있다.")
ok(("취소", "재량") in _서술,
   f"서법이 어느 동사에 붙었는지 말한다 (얻은 값 {_서술})")

print()
print("[조건] 요건은 '…한 때에는' 앞에 있다")
ok(M.조건("당사자가 착오를 증명한 때에는 취소할 수 있다.").startswith("당사자가"),
   "조건절을 앞에서 끊어 낸다")
ok(M.조건("소유권을 취득한다.") == "", "조건이 없으면 빈 문자열 -- 지어내지 않는다")

print()
print("[재기] **미분석률은 자가 눈감은 자리의 넓이다**")
# 이 수를 재는 이유: 분석기가 못 뜯은 자리는 대조가 아예 안 일어나므로 **어긋남 0 이
# 뜻을 잃는다.** 검사하지 않은 초록불이 검사한 빨간불보다 나쁘다는 규율 그대로다.
# 처음 재었을 때 33.9% 였고, 몰린 자리를 보니 두 가지가 섞여 있었다:
#   - 진짜 못 뜯은 것: 甲이(37) · 乙이(27) · 있는(30) · 없는(24) ...
#   - **못 뜯은 것이 아닌 것**: '경우'(95) 처럼 조사가 안 붙은 맨 체언
# 뒤엣것을 미분석으로 세면 **자가 눈감은 자리를 부풀려 재게 된다** -- 어디를 고쳐야
# 하는지가 그 숫자에 안 보인다. 갈라 세고 앞엣것만 고쳐 1.4% 가 되었다.
_시험지 = Path(__file__).resolve().parent.parent / "law" / "exam" / "2026_민사법_선택형_손옮김.txt"
if _시험지.is_file():
    _문항 = EX.parse(_시험지.read_text(encoding="utf-8"))
    _지문 = [t for q in _문항 for _, t in q.보기]
    _지문 += [t for q in _문항 for t in q.선택지 if len(t) > 20]
    _형 = [t for s in _지문 for t in M.분석(s) if t.갈래 != "기타"]
    _미 = sum(1 for t in _형 if t.왜 == "미분석")
    _율 = _미 / len(_형) if _형 else 1.0
    ok(len(_지문) >= 300 and len(_형) >= 5000,
       f"진짜 지문 위에서 잰다 (지문 {len(_지문)} · 어절 {len(_형)})")
    ok(_율 <= 0.05,
       f"미분석 5% 아래 (얻은 값 {_미}건 · {_율 * 100:.1f}%)")
    # **좁아지는 것도 막는다.** 갈래가 한쪽으로 쏠리면 뜯긴 것이 아니라 뭉갠 것이다.
    _용언 = sum(1 for t in _형 if t.갈래 == "용언")
    ok(0.1 <= _용언 / len(_형) <= 0.5,
       f"용언이 한쪽으로 안 쏠린다 (얻은 값 {_용언 / len(_형) * 100:.0f}%)")
else:
    print("  건너뜀 시험지가 없다")

print()
if fails:
    print(f"형태소: {len(fails)}개 실패 -- {fails}")
    sys.exit(1)
print("형태소: 조사 · 겁 · 한 글자 체언 · 서법 · 조건 · 미분석률 -- 통과")
