"""논리 엔진이 **따라 나오는 것만 참이라 하는가.**

LEET 의 규칙이 이 저장소의 규율과 같다 -- 사전 지식을 안 쓴다. 그래서 검사도
두 쪽으로 온다: 따라 나오는 것을 참이라 하는가, 그리고 **그럴듯하지만 지문에
없는 것을 '모름' 이라 하는가.** 뒤엣것이 더 중요하다. 사전 지식이 새어 들어오는
자리가 바로 거기다.

    python3 tests/test_law_logic.py
"""
from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from law import logic as L                                            # noqa: E402

fails = []


def ok(cond, msg):
    print(("  OK   " if cond else "  실패 ") + msg)
    if not cond:
        fails.append(msg)


A, B, C, D = (L.원자(x) for x in "ABCD")


def 망(*줄):
    m = L.망()
    for i, f in enumerate(줄, 1):
        m.넣기(f, f"{i}줄")
    return m


print("[따라 나온다] 진리표는 규칙을 안 빠뜨린다")
for 이름, m, c in (
    ("전건긍정", 망(L.함의(A, B), A), B),
    ("후건부정", 망(L.함의(A, B), L.부정(B)), L.부정(A)),
    ("가언삼단논법", 망(L.함의(A, B), L.함의(B, C)), L.함의(A, C)),
    ("선언삼단논법", 망(L.또는(A, B), L.부정(A)), B),
    ("대우", 망(L.함의(A, B)), L.함의(L.부정(B), L.부정(A))),
    ("드모르간", 망(L.부정(L.그리고(A, B))), L.또는(L.부정(A), L.부정(B))),
    ("구성적 양도논법", 망(L.또는(A, B), L.함의(A, C), L.함의(B, C)), C),
):
    ok(m.묻기(c).값 == "참", f"{이름} (얻은 값 {m.묻기(c).값})")

print()
print("[안 따라 나온다] **그럴듯한 것은 답이 아니다**")
# LEET 가 매년 내는 자리다. 꼴이 비슷하고 결론이 반대라서 사람이 잘 속는다.
_후건 = 망(L.함의(A, B), B)
ok(_후건.묻기(A).값 == "모름", f"후건긍정: B 라고 A 인 것은 아니다 (얻은 값 {_후건.묻기(A).값})")
ok("후건긍정" in L.오류이름([L.함의(A, B), B], A), "그 걸음의 이름을 댄다")
_전건 = 망(L.함의(A, B), L.부정(A))
ok(_전건.묻기(L.부정(B)).값 == "모름",
   f"전건부정: A 가 아니라고 B 가 아닌 것은 아니다 (얻은 값 {_전건.묻기(L.부정(B)).값})")
ok("전건부정" in L.오류이름([L.함의(A, B), L.부정(A)], L.부정(B)), "그 걸음의 이름을 댄다")
# '모름' 은 반례를 든다 -- 어느 해석에서 갈리는지 보여야 사람이 확인할 수 있다.
ok(_후건.묻기(A).반례, f"모름이면 갈리는 해석을 하나 든다 (얻은 값 {_후건.묻기(A).반례})")

print()
print("[충분과 필요] 'A 라야 B' 는 'A 이면 B' 가 아니다")
# 한국어에서 이 둘이 뒤집힌다. '오직 A 만이 B 이다' = B -> A 다.
# 이 자리를 틀리면 조건문이 통째로 뒤집혀 답이 정확히 반대가 된다.
_필요 = 망(L.함의(B, A))                    # 'A 라야 B' -- A 는 B 의 필요조건
ok(_필요.묻기(L.함의(A, B)).값 == "모름",
   "필요조건을 충분조건으로 읽지 않는다")
ok(망(L.함의(B, A), B).묻기(A).값 == "참", "필요조건은 제 방향으로는 그대로 듣는다")

print()
print("[양화] **지문에 이름이 나온 것들 위에서만 편다**")
# 도메인을 지문 밖으로 넓히면 그 순간 사전 지식이 들어온다.
_것 = ["갑", "을"]
_정언 = 망(L.모든("사람", "죽는다", _것), L.이다("사람", "갑"))
ok(_정언.묻기(L.이다("죽는다", "갑")).값 == "참", "모든 사람은 죽는다 + 갑은 사람이다")
ok(_정언.묻기(L.이다("죽는다", "을")).값 == "모름",
   "을이 사람이라는 말이 지문에 없으면 을에 대해서는 모른다")
# '모든 A 는 B' 에서 '어떤 A 가 있다' 가 따라 나오지 않는다(존재함의 없음).
ok(망(L.모든("사람", "죽는다", _것)).묻기(L.어떤("사람", "죽는다", _것)).값 == "모름",
   "'모든 A 는 B' 가 'A 가 있다' 를 뜻하지 않는다")

print()
print("[근거] **지문 전체를 근거라 하면 아무것도 안 가리킨다**")
_긴 = 망(L.함의(A, B), L.함의(B, C), A, D)
_판 = _긴.묻기(C)
ok(_판.값 == "참" and set(_판.근거) == {"1줄", "2줄", "3줄"},
   f"쓰인 줄만 근거로 댄다 -- 4줄(D)은 안 쓰였다 (얻은 값 {_판.근거})")
_판2 = 망(L.함의(A, B), L.함의(B, C), A).묻기(L.함의(L.부정(C), L.부정(A)))
ok(set(_판2.근거) == {"1줄", "2줄"},
   f"대우에는 전제 A 가 필요 없다 (얻은 값 {_판2.근거})")

print()
print("[안 되는 것을 안 된다고 한다]")
# 지문이 모순이면 무엇이든 따라 나온다. 그 '참' 은 답이 아니다.
ok(망(A, L.부정(A)).묻기(B).값 == "지문모순",
   f"모순된 지문에서는 답을 안 낸다 (얻은 값 {망(A, L.부정(A)).묻기(B).값})")
# 원자가 너무 많으면 못 쟀다고 한다. **짐작해서 답하지 않는다.**
_큰 = L.망()
for i in range(L.한계 + 2):
    _큰.넣기(L.원자(f"P{i}"), f"{i}줄")
ok(_큰.묻기(L.원자("P0")).값 == "못잼",
   f"셀 수 없으면 못 쟀다고 한다 (얻은 값 {_큰.묻기(L.원자('P0')).값})")

print()
print("[거짓] 거스르는 것은 거스른다고 말한다")
ok(망(L.함의(A, B), A).묻기(L.부정(B)).값 == "거짓", "따라 나오는 것의 부정은 거짓이다")
ok(망(L.또는(A, B), L.부정(A), L.부정(B)).묻기(C).값 == "지문모순",
   "선언지가 다 막히면 지문이 모순이다")

print()
if fails:
    print(f"논리: {len(fails)}개 실패 -- {fails}")
    sys.exit(1)
print("논리: 따라 나옴 · 안 따라 나옴 · 충분/필요 · 양화 · 근거 · 못잼 -- 통과")
