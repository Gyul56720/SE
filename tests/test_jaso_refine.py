"""**루프가 정말 나아지는가. 그리고 나빠진 바퀴를 버리는가.**

    python3 tests/test_jaso_refine.py

LLM 은 안 부른다 -- 가짜를 주입한다.

## 붙드는 것 넷

1. **프롬프트에 관문 이름이 안 실린다.** 실으면 모델이 원장의 수를 아무 데나 끼워
   넣어 관문을 통과시킨다 -- 그 문장은 **통과했는데 틀린 문장**이다.
2. **나빠진 바퀴를 버린다.** 그냥 돌리는 것은 정제가 아니다(`mathdrift/mono.py` 가
   "사슬이 어디로 가는가" 를 세는 자리와 같다).
3. **재료가 없어 못 고치는 것에 매달리지 않는다.** 원장에 없는 것을 모델이 채우면
   그것이 지어낸 것이다. 그때는 사람에게 물을 것을 낸다.
4. **재료를 빼고 고치라고 하지 않는다.** 재료를 빼면 모델이 나머지를 기억으로 다시
   채우고, 그 순간 원장 밖이 들어온다.
"""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from jaso import item as IT                                       # noqa: E402
from jaso import ledger as LG                                     # noqa: E402
from jaso import refine as RF                                     # noqa: E402
from jaso import write as WR                                      # noqa: E402

fails = []


def ok(cond, msg):
    print(("  OK   " if cond else "  실패 ") + msg)
    if not cond:
        fails.append(msg)


L = LG.읽기(str(ROOT / "jaso" / "보기.json"))
q = IT.쪼개기("직무에 필요한 역량은 무엇이며 어떤 노력을 했는지 구체적 경험과 "
            "그 결과를 기술하시오 (700자)", "1")

나쁨 = ("무봉테크에서 추천 개편을 주도하며 매출을 30% 향상시켰습니다.\n\n"
       "또한 저는 열정적으로 임했습니다.")
좋음 = ("무봉테크 데이터플랫폼팀 인턴으로 사내 추천 시스템 개편에 참여하며 로그 "
       "파이프라인을 다시 썼습니다. 2주간 A/B 로 24000명씩 재니 클릭률이 2.1%에서 "
       "2.6%로 올랐습니다.\n\n지연은 35분에서 4분으로 줄었습니다. Airflow 로 "
       "스케줄을 걸고 BigQuery 에서 집계했습니다.")


print("── 재기 -- 무엇이 좋고 나쁜지 잴 수 있는가 ─────────────")
나쁜잰, 나쁜위반 = RF.재기(q, 나쁨, L)
좋은잰, 좋은위반 = RF.재기(q, 좋음, L)
ok(나쁜잰.hard > 0, f"나쁜 벌에 hard 가 있다 ({나쁜잰})")
ok(좋은잰.hard == 0, f"좋은 벌에 hard 가 없다 ({좋은잰})")
ok(좋은잰.점수 < 나쁜잰.점수, "**좋은 것이 낮은 점수다** -- 사전식, 작을수록 좋다")
ok(좋은잰.앵커 > 나쁜잰.앵커, "앵커도 잰다")
ok(RF.잰것(0, 5, 9, 1.0).점수 < RF.잰것(1, 0, 9, 1.0).점수,
   "**hard 하나가 soft 다섯보다 무겁다** -- 사전식이라 그렇다")


print("\n── 위반을 **사실로** 옮긴다 (관문 이름 없이) ────────────")
말들 = RF.고칠말(나쁜위반, L, q, 나쁨)
붙 = " ".join(말들)
ok(말들, f"되먹일 말 {len(말들)}개")
금지 = ("J001", "J002", "J004", "P001", "P002", "P003", "D001", "D002",
        "관문", "위반", "hard", "soft", "앵커", "치환", "상투구", "승격")
샌것 = [w for w in 금지 if w in 붙]
ok(not 샌것, f"**관문 이름이 한 글자도 안 샌다** (샌 것: {샌것})")
ok("2.1" in 붙 and "2.6" in 붙,
   "**대신 제 기록의 값을 준다** -- '이 값으로 다시 쓰거나 수를 빼라'")
ok("참여" in 붙, "역할도 기록 그대로 준다")
ok(any("면접" in m for m in 말들),
   "왜 크게 적으면 안 되는지까지 말한다 -- 되물었을 때 답할 수 없다")
빈것 = RF.위반을말로(LG.위반("Z999", "hard", "x", "모르는 규칙"), L, q, 나쁨)
ok(빈것 == "", "**못 옮기는 위반은 빈 말이다** -- 지어내지 않는다")


print("\n── 고침 프롬프트는 **재료를 안 뺀다** ──────────────────")
항목, 생각 = WR.고르기(q, L)
프 = RF.고침프롬프트(q, 항목, 생각, 나쁨, 말들, "누리하나", "데이터 분석")
ok("2주간 A/B" in 프 and "무봉테크" in 프,
   "**첫 프롬프트의 재료가 그대로 있다** -- 빼면 모델이 나머지를 기억으로 채우고 "
   "그 순간 원장 밖이 들어온다")
ok(나쁨.split("\n")[0] in 프, "먼저 쓴 것도 같이 준다")
ok("고쳐 주셨으면" in 프 and "새로 넣지는 마십시오" in 프, "고칠 데만 고치라고 한다")
샌것2 = [w for w in 금지 if w in 프]
ok(not 샌것2, f"**고침 프롬프트에도 관문이 안 샌다** (샌 것: {샌것2})")


print("\n── 루프 -- 나아지면 들고, 나빠지면 버린다 ───────────────")
차례 = [나쁨, 좋음, 나쁨]          # 첫벌 나쁨 -> 1바퀴 좋음 -> 2바퀴 다시 나쁨


def 가짜(_):
    return 차례.pop(0) if 차례 else 좋음


r = RF.돌리기(q, L, 바퀴수=2, 벌=1, 묻기=가짜)
ok(r["글있나"] and r["최선"], "돌았다")
ok(r["최선"]["글"] == 좋음, "**최선이 좋은 벌이다**")
ok(r["최선"]["잰"].hard == 0, "최선에 hard 가 없다")
번호별 = {b.번호: b for b in r["바퀴들"]}
ok(번호별[0].잰.hard > 0, "0바퀴(첫벌)는 나빴다")
ok(번호별.get(1) and 번호별[1].나아졌나, "1바퀴에서 나아졌다")
ok(번호별.get(2) and not 번호별[2].나아졌나,
   "**2바퀴는 나빠져서 버렸다** -- 그래도 최선은 그대로다")
ok(r["최선"]["글"] == 좋음, "버린 바퀴가 최선을 못 밀어낸다 (단조)")
ok(all(b.준말 for b in r["바퀴들"] if b.번호),
   "**바퀴마다 무엇을 되먹였는지 남는다** -- 정제됐다는 말을 검사받게 한다")


print("\n── 재료가 없으면 매달리지 않고 사람에게 돌아간다 ────────")
빈원장 = LG.읽기([{"id": "P1", "이름": "무엇", "곳": "어디", "역할": "참여",
                "언제": ["2025-01", "2025-06"], "증빙": "x"}])
일반론 = "저는 성실하고 열정적인 사람입니다.\n\n최선을 다하겠습니다."
r2 = RF.돌리기(q, 빈원장, 바퀴수=8, 벌=1, 묻기=lambda _: 일반론)
ok(len(r2["바퀴들"]) <= 4,
   f"**{len(r2['바퀴들'])}바퀴에서 멈췄다 (상한 8)** -- 안 움직이면 멈춘다. "
   "그냥 도는 것은 정제가 아니고 바퀴마다 호출이 나간다")
ok(r2["남은것"], "남은 위반을 숨기지 않는다")
ok(r2["물을것"], "**대신 사람에게 물을 것을 낸다** -- 거기서부터는 루프 일이 아니다")
ok(any(x.칸 for x in r2["물을것"]), "물음이 어느 칸을 채우는지까지 온다")
ok(not any(b.나아졌나 for b in r2["바퀴들"] if b.번호),
   "안 나아진 바퀴가 하나도 최선을 못 밀어냈다")
r5 = RF.돌리기(q, L, 바퀴수=9, 벌=1, 묻기=lambda _: 나쁨)
ok(len(r5["바퀴들"]) <= 3,
   f"(원장이 차 있어도) 두 바퀴 헛돌면 셋째를 안 돈다 ({len(r5['바퀴들'])}바퀴, "
   "상한 9) -- **바퀴마다 호출이 나가는 자리다**")
차례2 = [나쁨, 나쁨, 좋음]
r6 = RF.돌리기(q, L, 바퀴수=9, 벌=1,
             묻기=lambda _: 차례2.pop(0) if 차례2 else 좋음)
ok(r6["최선"]["글"] == 좋음 and r6["최선"]["잰"].hard == 0,
   "**한 번 헛돌아도 그 다음에 나아지면 받는다** -- 정체는 이어질 때만 센다")


print("\n── 한 벌도 못 받으면 빈 것을 안 낸다 ───────────────────")
def 죽는다(_):
    raise RuntimeError("LLM 후보 풀이 비었다")


r3 = RF.돌리기(q, L, 바퀴수=2, 벌=2, 묻기=죽는다)
ok(not r3["글있나"] and r3["최선"] is None, "글이 없으면 최선이 없다")
ok("비었다" in r3["왜"], f"왜 못 받았는지 남는다 ({r3['왜'][:40]})")


print("\n── 바퀴 0 이면 첫 벌 그대로 (루프를 끌 수 있다) ─────────")
r4 = RF.돌리기(q, L, 바퀴수=0, 벌=1, 묻기=lambda _: 좋음)
ok(len(r4["바퀴들"]) == 1 and r4["최선"]["글"] == 좋음, "첫 벌만 내고 안 돈다")

print()
print(f"실패 {len(fails)}건" if fails else "전부 통과")
raise SystemExit(1 if fails else 0)
