"""LEET 지문을 **화자별 원장**으로 가르는가.

지문 전체를 원장 하나로 뭉치면 갑과 을의 말이 서로 모순이라 `지문모순` 이 나고
아무것도 못 푼다. 실측(2023 추리논증 24문항): **원장을 둘 이상 세워야 하는 문항이
14개**다. 가르기가 곧 푸는 일의 절반이다.

    python3 tests/test_law_leet.py
"""
from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from law import leet as L                                             # noqa: E402

fails = []


def ok(cond, msg):
    print(("  OK   " if cond else "  실패 ") + msg)
    if not cond:
        fails.append(msg)


샘플 = """문 1.
 다음 논쟁에 대한 분석으로 옳은 것만을 <보기>에서 있는 대로 고른 것은?

 어떤 문제를 놓고 갑과 을이 논쟁하였다.
갑: 첫째 주장이다. 갑은 이렇게 말했다고 전해진다.
을: 둘째 주장이다.
견해1: 셋째 주장이다.

<보기>
ㄱ. 첫째 보기.
ㄴ. 둘째 보기.
ㄷ. 셋째 보기.

① ㄱ
② ㄴ
③ ㄱ, ㄷ
④ ㄴ, ㄷ
⑤ ㄱ, ㄴ, ㄷ
"""

print("[가르기] 화자 · 보기 · 선택지를 따로 집는다")
_q = L.읽기(샘플)[0]
ok(_q.번호 == 1, f"문 번호를 읽는다 (얻은 값 {_q.번호})")
ok(set(_q.화자) == {"갑", "을", "견해1"},
   f"화자를 셋 다 집는다 (얻은 값 {sorted(_q.화자)})")
ok(list(_q.보기) == ["ㄱ", "ㄴ", "ㄷ"], f"보기 셋 (얻은 값 {list(_q.보기)})")
ok(len(_q.선택지) == 5, f"선택지 다섯 (얻은 값 {len(_q.선택지)})")
ok(_q.지문.startswith("어떤 문제를"), f"이름표 없는 앞머리는 지문이다 (얻은 값 {_q.지문[:14]!r})")

# **본문 가운데의 '갑은' 을 화자 전환으로 읽으면 지문이 산산조각 난다.**
ok("갑은 이렇게 말했다" in _q.화자["갑"],
   "줄 가운데의 '갑은' 에서 안 끊는다 -- 줄 첫머리 + 콜론만 화자다")

print()
print("[없으면 없다고 한다] 화자를 지어내지 않는다")
_민 = L.한문항("다음으로부터 추론한 것은?\n\n 설명문 한 덩이일 뿐이다.\n")
ok(_민.화자 == {} and _민.원장수() == 1,
   f"이름표가 없으면 원장 하나 (얻은 값 화자={_민.화자} 원장={_민.원장수()})")
ok(_민.보기 == {}, "보기가 없으면 빈 것으로 둔다")

print()
print("[선택지] 다섯이 이어져야 선택지다")
# 본문 속 (1)(2) 는 선택지가 아니다. 실측: 문 10 의 [규정] 안에 (1)(2) 가 있다.
_속 = L.한문항("적용한 것으로 옳은 것은?\n\n 체결가능수량은 ① 과 ② 중 적은 것이다.\n")
ok(_속.선택지 == [], f"본문 속 동그라미 둘은 선택지가 아니다 (얻은 값 {_속.선택지})")

print()
print("[꼴] 물음에서 읽는다 -- **닫힌 목록이고 모르면 '?' 다**")
for 물, 몫 in (("다음으로부터 추론한 것으로 옳은 것만을", "추론"),
               ("[규정]을 <사례>에 적용한 것으로 옳은", "적용"),
               ("<주장>에 대한 반대 논거가 될 수 있는", "반대논거"),
               ("다음 글에 대한 평가로 옳은 것만을", "평가"),
               ("다음 논쟁에 대한 분석으로 옳은", "분석"),
               ("다음 논증의 구조를 가장 적절하게", "구조"),
               ("전혀 새로운 꼴의 물음이다", "?")):
    ok(L.한문항(물 + "\n\n 몸통.\n").꼴() == 몫,
       f"{물[:20]!r} -> {몫} (얻은 값 {L.한문항(물 + chr(10) * 2 + ' 몸통.' + chr(10)).꼴()})")

print()
print("[재기] **무엇을 만들지는 세어 보고 정한다**")
_손 = Path(__file__).resolve().parent.parent / "law" / "leet" / "추리논증" / "2023_추리논증_손옮김.txt"
if _손.is_file():
    qs = L.읽기(_손.read_text(encoding="utf-8"))
    s = L.통계(qs)
    ok(s["문항"] >= 20, f"진짜 시험지 위에서 잰다 ({s['문항']}문항)")
    # 이 수가 설계를 정했다. 원장 하나로 뭉치면 이 문항들이 전부 '지문모순' 이 된다.
    ok(s["원장둘이상"] >= 10,
       f"원장을 둘 이상 세워야 하는 문항이 많다 (얻은 값 {s['원장둘이상']}/{s['문항']})")
    # 표도 수량도 없는 문항이 논리만으로 닿을 수 있는 자리다.
    ok(s["논리만으로"] >= s["문항"] * 0.6,
       f"표도 수량도 없는 문항이 여섯 할 넘는다 (얻은 값 {s['논리만으로']}/{s['문항']})")
    ok(all(q.물음 for q in qs), "문항마다 물음을 읽어 냈다")
    _빈보기 = [q.번호 for q in qs if not q.보기 and "보기" in q.물음]
    ok(not _빈보기, f"물음이 <보기>를 말하는데 보기를 못 집은 문항이 없다 (얻은 값 {_빈보기})")
else:
    print("  건너뜀 손옮김이 없다")

print()
if fails:
    print(f"LEET 가르기: {len(fails)}개 실패 -- {fails}")
    sys.exit(1)
print("LEET 가르기: 화자 · 보기 · 선택지 · 꼴 · 지어내지 않기 · 재기 -- 통과")
