# -*- coding: utf-8 -*-
"""**코너 STA 와 OCV 가 실제로 슬랙에 들어가는가 -- 두 군데가 거짓이었다.**

`house/tapeout.py` 가 이 칸을 이렇게 적고 있었다.

    다중 코너 STA (PVT 전부)   시연뿐   코너표는 도는데 관문 7 은 단일 코너만 본다
    OCV · 온칩 편차 유도        시연뿐   같다

붙이려고 보니 **두 군데가 말과 달랐다.**

## 하나. `synth.sta(..., 디레이트=)` 는 받기만 하고 안 썼다

선언에는 있는데 본문 어디에도 안 나왔다. 그 사이 `house/syn/agent.py` 의
보고서는 STA 결과 바로 옆에 `derate early 0.95 / late 1.05` 라고 적고 있었다.
**읽는 사람은 그 배수가 걸린 수를 본다고 읽는다.** 죽은 인자는 조용히
공칭값을 돌려주므로 아무도 안 틀렸다고 느낀다.

## 둘. OCV 를 셈해서 보고서에 적고, 슬랙에서는 안 뺐다

같은 함수 안에서 `ocv스큐(0.8)` 을 불러 127 ps 를 적어 놓고 코너 슬랙은
`주기 - 경로 - setup` 으로만 셈했다.

**이 검사는 글자를 안 본다.** 배수를 넣어 보고 수가 따라 움직이는지,
OCV 를 넣고 빼 보고 슬랙이 그만큼 달라지는지를 **잰다.**

실행: python3 tests/test_코너STA.py
"""
from __future__ import annotations

import sys
from pathlib import Path

뿌리 = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(뿌리))

FAIL = []


def ok(cond, what):
    print(("  통과  " if cond else "  실패  ") + what)
    if not cond:
        FAIL.append(what)


from house import gen as GEN            # noqa: E402
from house import tapeout as TO         # noqa: E402
from house.syn import pvt as PVT        # noqa: E402

문턱 = GEN.기본문턱

print("\n[1] 코너 묶음과 OCV 가 문턱에 드러나 있나 -- 숨은 선택이 없게")
for 열쇠 in ("코너공정들", "코너전압들", "코너온도들", "ocv삽입지연_ns",
           "setup불확실_ns"):
    ok(열쇠 in 문턱, f"gen.기본문턱 에 {열쇠!r} 가 있다 ({문턱.get(열쇠)})")

print("\n[2] **OCV 가 슬랙에서 실제로 빠지는가** -- 넣고 빼서 잰다")
o = PVT.ocv스큐(0.8)
없 = PVT.코너타이밍(4.0, 10.0, ocv=None)
있 = PVT.코너타이밍(4.0, 10.0, ocv=o)
차 = 없["최악"]["슬랙_ns"] - 있["최악"]["슬랙_ns"]
# 허용오차 2e-4 ns 는 **눈감아 주는 것이 아니라 반올림 자릿수**다. 슬랙을
# `round(x, 4)` 로 0.1 ps 단위에 맞춰 적으므로 두 값의 차는 최대 0.2 ps 만큼
# 어긋날 수 있다(실측 126.90 vs 126.88 ps). 그보다 크게 어긋나면 OCV 가
# 안 들어갔거나 딴 것이 들어간 것이다.
ok(abs(차 - o["실효스큐_ps"] / 1e3) < 2e-4,
   f"OCV 를 넣으면 슬랙이 실효 스큐만큼 줄어든다 "
   f"({차 * 1e3:.2f} ps vs {o['실효스큐_ps']} ps · 반올림 0.1 ps 단위)")
# **그 허용오차가 아무 값이나 받아 주지 않는지 본다** -- 늘 통과하는 검사 방지
ok(abs((없["최악"]["슬랙_ns"] - 있["최악"]["슬랙_ns"]) - 0.5) >= 2e-4,
   "엉뚱한 값(0.5 ns)은 그 허용오차로 안 통과한다")
ok(있["ocv실효스큐_ns"] > 0 and 없["ocv실효스큐_ns"] == 0.0,
   "OCV 없이 부르면 0 으로 적힌다 — 안 넣고 넣은 척하지 않는다")

print("\n[3] setup 불확실도 빠지는가")
a = PVT.코너타이밍(4.0, 10.0, setup불확실_ns=0.0)
b = PVT.코너타이밍(4.0, 10.0, setup불확실_ns=0.25)
ok(abs((a["최악"]["슬랙_ns"] - b["최악"]["슬랙_ns"]) - 0.25) < 1e-6,
   f"setup 0.25 ns 를 넣으면 슬랙이 그만큼 준다 "
   f"({a['최악']['슬랙_ns']} → {b['최악']['슬랙_ns']})")

print("\n[4] 코너를 좁히면 최대 지연배수가 내려가는가 -- 그 손잡이가 진짜인가")
넓 = PVT.코너타이밍(4.0, 10.0, 코너들=PVT.코너표())
좁 = PVT.코너타이밍(4.0, 10.0, 코너들=PVT.코너표(
    공정들=("tt",), 전압들=(1.80,), 온도들=(25.0, 85.0)))
ok(좁["최대지연배수"] < 넓["최대지연배수"],
   f"좁은 묶음의 최대배수가 더 작다 ({좁['최대지연배수']} < {넓['최대지연배수']})")
ok(좁["최악"]["슬랙_ns"] > 넓["최악"]["슬랙_ns"],
   f"그래서 최악 슬랙도 낫다 ({좁['최악']['슬랙_ns']} > {넓['최악']['슬랙_ns']})")

print("\n[5] **관문이 무는가**")
성한것 = PVT.코너타이밍(1.0, 30.0, ocv=o)      # 아주 느린 클럭 -- 다 닫힌다
성한것.update({"ocv": o, "공칭슬랙_ns": 29.0, "공칭Fmax_MHz": 1000.0,
            "통과코너수": sum(1 for c in 성한것["코너"] if c["통과"]), "초": 0.1})
r = GEN.코너타이밍판정(성한것, 문턱)
ok(len(r) == 1 and r[0][1],
   f"모든 코너가 닫히면 초록이다 ({성한것['통과코너수']}/{성한것['전체코너수']})")
ok(r[0][0].startswith("7b."), f"이름표가 7b 로 시작한다 ({r[0][0][:12]})")

깨진것 = PVT.코너타이밍(13.14855, 10.0, ocv=o)   # 실측 nsw_fir
깨진것.update({"ocv": o, "공칭슬랙_ns": -3.14855, "공칭Fmax_MHz": 76.05,
            "통과코너수": sum(1 for c in 깨진것["코너"] if c["통과"]), "초": 0.1})
r2 = GEN.코너타이밍판정(깨진것, 문턱)
ok(not r2[0][1], "코너 하나라도 못 닫으면 빨갛다")
ok(GEN.코너타이밍판정({"오류": "공칭 STA 를 못 냈다"}, 문턱)[0][1] is False,
   "공칭 STA 를 못 내면 빨갛다 — 못 쟀는데 통과시키지 않는다")

# **가장 아슬아슬한 자리**: 한 코너만 아주 조금 음수여도 빨개야 한다
아슬 = PVT.코너타이밍(4.9, 10.0, ocv=o)
아슬.update({"ocv": o, "공칭슬랙_ns": 5.1, "공칭Fmax_MHz": 204.0,
           "통과코너수": sum(1 for c in 아슬["코너"] if c["통과"]), "초": 0.1})
ok(아슬["최악"]["슬랙_ns"] < 0 and not GEN.코너타이밍판정(아슬, 문턱)[0][1],
   f"공칭은 넉넉한데(슬랙 5.1) 최악 코너가 {아슬['최악']['슬랙_ns']} ns 면 빨갛다 "
   "— 관문 7 만으로는 초록이었을 자리")

print("\n[6] 관문 글이 길을 알려 주는가 -- 막기만 하지 않는다")
말 = r2[0][2]
ok("필요" in 말 or "이하여야" in 말, "닫으려면 공칭 경로가 얼마여야 하는지 적는다")
ok("관문 7 은 이 한 칸만 본다" in 말, "관문 7 과의 차이를 적는다")
ok("파운드리가 특성화한" in 말, "모형에서 셈한 배수라는 한계를 적는다")
ok("자동차 등급" in 말, "코너 묶음이 어느 등급인지 적는다")
ok(f"{o['실효스큐_ps']:.1f} ps" in 말 or "126.9 ps" in 말,
   "OCV 실효 스큐를 수로 적는다")

print("\n[7] **`디레이트` 가 죽은 인자가 아닌가** -- 진짜 넷리스트로 잰다")
import time                                                   # noqa: E402
t0 = time.time()
try:
    from house import designs as DES                          # noqa: E402
    from house import synth as SYN                            # noqa: E402
    합 = SYN.합성(DES.파라기본(DES.NSW_FIR) or None, 설계=DES.NSW_FIR)
    ok(합.get("됐나"), "합성이 됐다")
    공 = SYN.sta(합, 주기=10.0)
    두배 = SYN.sta(합, 주기=10.0, 디레이트=2.0)
    ok(공.get("임계경로_ns") is not None, "공칭 STA 가 임계경로를 낸다")
    ok(abs(두배["임계경로_ns"] - 공["임계경로_ns"] * 2.0) < 1e-6,
       f"디레이트 2.0 이면 경로가 정확히 두 배다 "
       f"({공['임계경로_ns']} → {두배['임계경로_ns']})")
    ok(abs(두배["최악슬랙_ns"] - (10.0 - 공["임계경로_ns"] * 2.0)) < 1e-6,
       f"슬랙도 그에 맞게 다시 셈한다 ({두배['최악슬랙_ns']})")
    ok(공["디레이트"] == 1.0 and 두배["디레이트"] == 2.0,
       "무엇이 걸렸는지 결과에 적는다 — 걸었는지 안 걸었는지 뒤에서 알 수 있게")
    K = GEN.코너타이밍(합, 10.0, 문턱)
    ok(not K.get("오류"), f"코너타이밍()이 돌았다 ({K.get('오류','')[:80]})")
    ok(K["전체코너수"] == 27 and K["잰코너수"] == 27,
       f"27 코너를 다 셌다 ({K['잰코너수']}/{K['전체코너수']})")
    ok(K["최악"]["슬랙_ns"] < K["공칭슬랙_ns"],
       f"최악 코너가 공칭보다 나쁘다 ({K['최악']['슬랙_ns']} < {K['공칭슬랙_ns']})")
    print(f"       (공칭 {K['공칭경로_ns']} ns · 최악 {K['최악']['P']} "
          f"{K['최악']['V']} V {K['최악']['T']} °C 슬랙 {K['최악']['슬랙_ns']} ns · "
          f"{round(time.time() - t0, 1)} s)")
except Exception as e:                                        # noqa: BLE001
    ok(False, f"진짜 넷리스트로 못 돌렸다: {type(e).__name__}: {e}")

print("\n[8] 슬랙을 두 군데서 셈하지 않는가")
from tests._소스보기 import 산주장                             # noqa: E402
_syn = 산주장((뿌리 / "house" / "syn" / "agent.py").read_text(encoding="utf-8"))
ok("PVT.코너타이밍(" in _syn,
   "house/syn/agent.py 가 공유 함수를 부른다")
ok("슬랙 = 주기 - 경로 - 불확실" not in _syn,
   "제 안에서 코너 슬랙을 따로 셈하던 줄이 사라졌다")
ok("R[\"OCV\"]" in _syn and "ocv=R[\"OCV\"]" in _syn,
   "보고서가 적는 그 OCV 를 슬랙에도 넘긴다 — 적는 수와 쓰는 수가 같다")

print("\n[9] 테이프아웃 표가 이 관문을 찾는가")
이름별 = {x["이름"]: x for x in TO.표(주인="syn")}
for n in ("다중 코너 STA (PVT 전부)", "OCV · 온칩 편차 유도"):
    x = 이름별.get(n)
    ok(x is not None and x["상태"] == TO.있다, f"{n} 이 「있다」 로 올라왔다")
ok(TO._관문있나("7b"), "관문 증거 찾기가 7b 를 찾는다")
ok("7b" in GEN.관문번호들(), f"관문 목록에 7b 가 있다 ({GEN.관문번호들()})")
ok(not TO.거짓증거() and not TO.안걸린붙듦(),
   f"거짓 증거도 안 걸린 붙듦도 없다 ({TO.거짓증거()} · {TO.안걸린붙듦()})")

print("\n" + "=" * 62)
if FAIL:
    print(f"실패 {len(FAIL)}개")
    for x in FAIL:
        print("  · " + x)
    raise SystemExit(1)
print("전부 통과")
