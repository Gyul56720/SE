# -*- coding: utf-8 -*-
"""**요구사항에 번호가 붙는가 -- 답을 아는 스펙으로 잰다.**

정리해 둔 것(`paper/선행조사/스펙-읽기와쓰기.md` §4)이 가리킨 빈 칸:

    우리 사슬:  포트/스캔 → 시나리오 → 커버 빈 → 커버리지 %
    업계 사슬: **요구사항(REQ-ID)** → 시나리오 → 커버 빈 → PASS/FAIL → 되짚기

**여기서 가장 중요한 것은 번호가 안 움직이는 것이다.** 사람이 메일에
`REQ-MERA-003` 을 적은 뒤 스펙에 한 줄이 끼었을 때 번호가 밀리면, 그 메일은
**조용히 딴것을 가리키게 된다** -- 틀린 것이 맞아 보이는 꼴이라 이 저장소가
가장 싫어하는 부류다. 그래서 줄을 **맨 앞에** 끼워 넣고 옛 번호를 본다.

실행: python3 tests/test_요구사항.py
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

뿌리 = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(뿌리))

FAIL = []


def ok(cond, what):
    print(("  통과  " if cond else "  실패  ") + what)
    if not cond:
        FAIL.append(what)


from house import spec as SPEC       # noqa: E402
from house import specq as SPECQ     # noqa: E402
from house import req as REQ         # noqa: E402

_요청 = """# MERA-1 v1.0 Event Recorder Core

| 항목 | 값 |
|---|---|
| 채널 수 | 4 |
| 샘플레이트 | 2.5 GSPS |
| PRE 깊이 | 4096 sample |

내부 canonical interface 는 AXI4-Stream 256-bit 이다. 제어는 AXI4-Lite.
aresetn 으로 비동기 리셋하고 동기로 해제한다. 오류는 sticky flag. 500 MHz.
"""


def _스펙(요청=_요청, 목표=None):
    s = SPEC.읽기(요청)
    s.이름 = "MERA-1 Event Recorder Core"
    s.목표 = 목표 or []
    return s


_s = _스펙(목표=[{"항목": "처리율", "값": "고성능"},
               {"항목": "면적", "값": "120 kGE"}])
r = REQ.붙이기(_s, SPECQ.세우기(_s))
_아이디 = [x["id"] for x in r["요구사항"]]

# ============================================ 1. 번호가 실제로 붙는다
ok(r["수"] >= 10, f"요구사항이 모인다 ({r['수']}개)")
ok(len(set(_아이디)) == len(_아이디), "**번호가 겹치지 않는다**")
ok(all(re.fullmatch(r"REQ-[0-9A-Z]{1,8}-\d{3}", i) for i in _아이디),
   f"꼴이 `REQ-<IP>-NNN` 이다 ({_아이디[0]})")
ok(all(i.isascii() for i in _아이디),
   "**번호에 한글이 안 섞인다** — 메일·이슈·로그에 적히는 것이라 깨지면 안 된다")
ok(r["접두"] == "MERA", f"접두를 이름에서 뽑는다 ({r['접두']})")

# 한글 이름만 있어도 ASCII 로 떨어진다
ok(REQ.접두(None, "계측용 이벤트 기록기") == "IP",
   "이름이 온통 한글이면 접두는 `IP` 로 떨어진다 — 깨진 글자를 번호에 안 넣는다")

# **모델 키가 없으면 `s.이름` 이 빈다.** 그때 제목 줄에서 뽑는다 (실측 2026-09-22:
# 제목에 MERA-1 이 버젓이 있는데 번호가 전부 `REQ-IP-NNN` 으로 나왔다).
ok(REQ.접두(None, "", "# MERA-1 v1.0 Event Recorder Core\n\n본문") == "MERA",
   "이름이 비면 **제목 줄**에서 접두를 뽑는다")
# 그런데 **본문에서는 안 줍는다** -- 글을 한 줄 고칠 때마다 번호 전체가
# 딴 이름으로 바뀌면 번호를 붙인 뜻이 없다.
ok(REQ.접두(None, "", "안녕하세요, AXI4 필터를 하나 만들어 주세요.") == "IP",
   "**본문의 첫 ASCII 낱말은 안 줍는다** — 번호가 글 따라 움직이면 안 된다")

# ============================================ 2. **줄이 끼어도 번호가 안 밀린다**
# 이 검사가 이 파일의 이유다. 맨 앞에 줄을 끼운다 -- 자리로 세면 전부 밀린다.
_끼운요청 = _요청.replace("| 채널 수 | 4 |",
                    "| 트리거 지연 | 3 cycle |\n| 채널 수 | 4 |")
_s2 = _스펙(_끼운요청, 목표=[{"항목": "처리율", "값": "고성능"},
                       {"항목": "면적", "값": "120 kGE"}])
r2 = REQ.붙이기(_s2, SPECQ.세우기(_s2), 이전=r["요구사항"])
_전 = {x["글"]: x["id"] for x in r["요구사항"]}
_후 = {x["글"]: x["id"] for x in r2["요구사항"]}
_밀린것 = [g for g in _전 if g in _후 and _전[g] != _후[g]]
ok(not _밀린것,
   "**맨 앞에 줄이 끼어도 옛 번호가 그대로다** — "
   + (f"밀린 것 {len(_밀린것)}개: {_밀린것[:2]}" if _밀린것 else "한 줄도 안 밀렸다"))
_새줄 = [x for x in r2["요구사항"] if x["글"] not in _전]
ok(len(_새줄) == 1 and _새줄[0]["id"] not in set(_아이디),
   f"새 줄만 **새 번호**를 받는다 ({_새줄[0]['id'] if _새줄 else '없다'})")
_남은것 = set(_전) & set(_후)
ok(r2["물려받은수"] == len(_남은것),
   f"물려받은 수를 세어 돌려준다 ({r2['물려받은수']}/{len(_남은것)})")
# **한 줄이 사라지는 것이 맞다.** `트리거 지연 3 cycle` 이 끼자 specq 가
# "지연의 상한은 몇 주기인가?" 를 **안 묻는다** -- 답이 생겼기 때문이다.
# 이것이 이 사슬이 도는 증거다: 요청이 채워지면 TBD 가 줄어든다.
_사라진 = set(_전) - set(_후)
ok(_사라진 == {"TBD — 지연(latency)의 상한은 몇 주기인가?"},
   f"**답이 생긴 TBD 는 목록에서 빠진다** ({sorted(_사라진)})")

# 이전을 안 주면 1번부터 -- 그리고 그때도 겹치지 않는다
r3 = REQ.붙이기(_s2, SPECQ.세우기(_s2))
ok(r3["요구사항"][0]["id"].endswith("-001") and r3["물려받은수"] == 0,
   "이전을 안 주면 001 부터 새로 매긴다")

# ============================================ 3. **검증 가능한가를 실제로 가른다**
# Wiegers 의 예: "The filter shall provide high performance" 는 요구사항이 아니다.
_판 = {x["글"]: x["판정"] for x in r["요구사항"]}
ok(_판.get("처리율: 고성능") == "잴 것이 없다",
   "**«고성능» 을 잡는다** — 시험으로 참/거짓을 못 가리는 줄이다")
ok(_판.get("면적: 120 kGE") == "잴 수 있다", "수가 붙은 목표는 통과시킨다")
ok(any(x["글"].startswith("채널 수") and x["판정"] == "잴 수 있다"
       for x in r["요구사항"]), "요청 표가 못박은 수는 잴 수 있다")

# 신호 이름만 있어도 잴 수 있다 -- 밑줄 없는 `aresetn` 까지
ok(REQ.검증가능("aresetn 으로 비동기 리셋하고 동기로 해제한다",
             ["aresetn"])["판정"] == "잴 수 있다",
   "**밑줄 없는 신호 이름(`aresetn`)도 신호로 본다**")

# **낱말로 봐야 한다.** 포트 `ack` 가 "backpressure" 속에 들어 있다고 신호가
# 있는 것이 아니다 (실측 2026-09-22: 이렇게 거짓 «잴 수 있다» 가 났다).
ok(REQ.검증가능("받는 쪽이 못 받을 때 backpressure 를 어떻게 하나",
             ["ack"])["판정"] != "잴 수 있다",
   "**`ack` 가 `backpressure` 속에 든 것을 신호로 안 본다**")

# ============================================ 4. **물음에는 잣대를 안 댄다**
# TBD 는 물음이라 언제나 «못 가린다» 가 나온다 -- 사소한 이유로 나오는 판정이고,
# 그런 줄이 여덟이면 "못 가릴 것 8개" 라는 수가 통째로 뜻을 잃는다.
_tbd = [x for x in r["요구사항"] if x["상태"] == "TBD"]
ok(_tbd and all(x["판정"] == "아직 요구사항이 아니다" for x in _tbd),
   f"TBD 는 «아직 요구사항이 아니다» 로 둔다 ({len(_tbd)}개)")
ok(not any(x["상태"] == "TBD" for x in r["못잴것"]),
   "**«못 가릴 것» 셈에 TBD 를 안 섞는다** — 섞으면 그 수가 물음 수가 된다")
ok(r["TBD수"] == len(_tbd), f"TBD 를 따로 센다 ({r['TBD수']}개)")

# ============================================ 5. 지어내지 않는다
_빈 = REQ.붙이기(SPEC.스펙(요청=""), {"물음": []})
ok(_빈["수"] == 0, "빈 스펙에서는 요구사항이 한 줄도 안 난다 — 지어내지 않는다")
ok(all(x["출처"] for x in r["요구사항"]),
   "**줄마다 출처가 있다** — 없으면 그것은 모은 것이 아니라 지어낸 것이다")
ok(all(x["열쇠"] for x in r["요구사항"]), "줄마다 내용 열쇠가 있다 (번호를 물려줄 자리)")
ok(len({x["열쇠"] for x in r["요구사항"]}) == r["수"], "같은 줄을 두 번 안 센다")

# ============================================ 6. 제안서가 이 표를 낸다
_소스 = (뿌리 / "house" / "arch.py").read_text(encoding="utf-8")
ok("from house import req as REQ" in _소스 and "REQ.붙이기" in _소스,
   "**제안서가 이것을 실제로 부른다** — 코드에만 있고 문서에 없으면 사람은 모른다")
ok("REQ-" in _소스 and "시험으로 가릴 수 있나" in _소스,
   "제안서 표에 번호와 **검증 가능성**이 열로 선다")
ok(r["못하는것"], "못 하는 것을 같이 돌려준다 (요구사항이 옳은지는 모른다)")

print()
if FAIL:
    print(f"실패 {len(FAIL)}개")
    for f in FAIL:
        print("   · " + f)
    raise SystemExit(1)
print("요구사항: 번호 붙음 · 안 밀림 · 모호말 잡힘 · TBD 안 섞임 · 안 지어냄 -- 통과")
