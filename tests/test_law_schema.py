"""스키마가 **같은 말을 묶고 다른 말을 안 묶는가.**

묶기는 두 쪽으로 틀린다. 안 묶으면 심판이 같은 명제를 어긋남이라며 기각하고(W001 이
그렇게 틀렸다), 지나치게 묶으면 다른 명제를 같다고 해서 **틀린 답을 통과시킨다.**
그래서 검사는 짝으로 온다 -- 묶여야 하는 짝과 **묶이면 안 되는 짝**.

    python3 tests/test_law_schema.py
"""
from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from law import exam as EX                                            # noqa: E402
from law import schema as S                                           # noqa: E402

fails = []


def ok(cond, msg):
    print(("  OK   " if cond else "  실패 ") + msg)
    if not cond:
        fails.append(msg)


def 같(a, b):
    return S.같은가(S.읽기(a), S.읽기(b))


print("[요건-효과 뒤집기] **이 자리에서 W001 이 틀렸다**")
# 실측(민사소송법 제288조 편, law/wording.py 의 머리말에 적힌 그 자리):
#   조문  "... 증명한 때에는 취소할 수 있다"       재량
#   문서  "취소하려면 ... 증명하여야 한다"          기속   -> 어긋남으로 잡혔다
# 그런데 같은 말이다. 조문은 요건-효과로, 문서는 효과-요건으로 적었을 뿐이다.
# wording.py 는 이것을 **동사 단위 대조**로 비켜갔다. 여기서는 명제로 세워 묶는다.
_조문 = "당사자가 착오로 말미암은 것임을 증명한 때에는 그 의사표시를 취소할 수 있다."
_문서 = "취소하기 위하여는 당사자가 착오로 말미암은 것임을 증명하여야 한다."
ok(같(_조문, _문서), f"뒤집어 적은 같은 명제가 묶인다\n         {S.읽기(_조문).열쇠()}\n         {S.읽기(_문서).열쇠()}")
ok(S.읽기(_문서).뒤집힘 and S.읽기(_문서).서법 == "재량",
   f"뒤집힌 문장의 기속은 **요건에 붙은 것**이지 효과의 서법이 아니다 "
   f"(얻은 값 뒤집힘={S.읽기(_문서).뒤집힘}·서법={S.읽기(_문서).서법})")

print()
print("[꼴은 접는다] 서법·태의 다른 꼴은 같은 명제다")
for a, b in (("선의의 제3자에게 대항하지 못한다.", "선의의 제3자에게 대항할 수 없다."),
             ("선의의 제3자에게 대항하지 못한다.", "선의의 제3자에게 대항하여서는 아니 된다."),
             ("법원은 그 결정을 취소한다.", "법원은 그 결정을 취소시킨다.")):
    ok(같(a, b), f"{a[:22]}… = {b[:22]}…")

print()
print("[뜻은 안 접는다] **비슷해 보인다고 묶으면 틀린 답이 통과한다**")
# 취소·무효·해제·해지는 요건도 효과도 다르다. 꼴에서 멈추고 뜻은 사람이 가른다.
for a, b, 왜 in (
    ("법원은 그 결정을 취소할 수 있다.", "법원은 그 결정을 취소할 수 없다.", "서법이 반대다"),
    ("법원은 그 결정을 취소할 수 있다.", "법원은 그 결정을 무효로 할 수 있다.", "낱말 뜻이 다르다"),
    ("甲은 乙에게 대금을 청구할 수 있다.", "乙은 甲에게 대금을 청구할 수 있다.", "당사자가 뒤바뀌었다"),
    ("법원은 소를 각하하여야 한다.", "법원은 소를 각하할 수 있다.", "기속과 재량은 다르다"),
):
    ok(not 같(a, b), f"안 묶는다 -- {왜}")

_a, _b = S.읽기("甲은 乙에게 대금을 청구할 수 있다."), S.읽기("甲은 乙에게 대금을 청구할 수 없다.")
ok("서법이 부딪힌다" in S.부딪힘(_a, _b),
   f"같은 자리를 두고 반대로 말하는 것은 **어긋남의 재료**로 낸다 (얻은 값 {S.부딪힘(_a, _b)!r})")

print()
print("[빈 칸은 모름이다] 그러나 **둘 다 비면 안 묶는다**")
# 뒤집힌 문장은 목적어를 아예 안 쓴다 -- 없는 것을 다른 값으로 세면 영영 안 묶인다.
# 그렇다고 양쪽이 다 비었는데 묶으면 사실관계가 다른 지문들이 한 덩이가 된다.
ok(같("당사자가 증명한 때에는 그 의사표시를 취소할 수 있다.",
      "당사자가 증명한 때에는 취소할 수 있다."),
   "한쪽이 말을 아낀 것은 다른 명제가 아니다")
ok(not S.같은가(S.명제(행위="취득", 서법="단정"), S.명제(행위="취득", 서법="단정")),
   "주체도 대상도 없는 둘은 안 묶는다 -- 모름이 둘이면 같다는 근거가 없다")

print()
print("[마디] **시험 지문은 조문 한 문장이 아니다**")
# 실측: 문 13 ㄱ·ㄴ·ㄹ 은 "甲이 ...한 경우, ...한다" 꼴이다. 문장 전체에서 격을 뽑으면
# 주체·대상이 **사실관계**에서 잡혀(주체=甲·대상=건물) 사실관계가 전혀 다른 세 지문이
# '취득/단정' 한 덩이로 묶였다. 명제는 맨 끝 마디에 있고 앞 마디는 요건이다.
_긴 = ("甲이 乙과 함께 X 토지를 공유하고 있었는데 甲이 그 지분을 丙에게 양도한 경우, "
       "乙은 그 토지의 소유권을 취득한다.")
ok(S.결론절(_긴).startswith("乙은"),
   f"맨 끝 마디를 명제로 삼는다 (얻은 값 {S.결론절(_긴)!r})")
ok(S.읽기(_긴).주체 == "乙",
   f"주체를 사실관계가 아니라 결론에서 잡는다 (얻은 값 {S.읽기(_긴).주체!r})")
ok(S.결론절("선의의 제3자에게 대항하지 못한다.") == "선의의 제3자에게 대항하지 못한다.",
   "마디가 하나뿐이면 자르지 않는다")

print()
print("[재기] **진짜 시험지 위에서 얼마나 묶이는가**")
_시험지 = Path(__file__).resolve().parent.parent / "law" / "exam" / "2026_민사법_선택형_손옮김.txt"
if _시험지.is_file():
    _문항 = EX.parse(_시험지.read_text(encoding="utf-8"))
    _지문, _출처 = [], []
    for q in _문항:
        for ㄱ, t in q.보기:
            _지문.append(t)
            _출처.append(f"문{q.번호}{ㄱ}")
        for i, t in enumerate(q.선택지):
            if len(t) > 20:
                _지문.append(t)
                _출처.append(f"문{q.번호}{'①②③④⑤'[i]}")
    _명 = [S.읽기(t, o) for t, o in zip(_지문, _출처)]
    _세움 = sum(1 for p in _명 if p.행위)
    ok(len(_지문) >= 300, f"진짜 지문 위에서 잰다 ({len(_지문)}개)")
    ok(_세움 / len(_명) >= 0.7,
       f"지문 열에 일곱 이상에서 행위를 세운다 (얻은 값 {_세움}/{len(_명)})")
    # **행위가 보조용언이면 명제를 세운 것이 아니다.** 처음 재었을 때 가장 흔한
    # '행위' 가 '않는다'(22) · '있다'(19) · '없다'(15) 였다 -- 문장 끝 글자를 센 것이다.
    _보조 = sum(1 for p in _명 if p.행위 in S.보조용언)
    ok(_보조 == 0, f"보조용언을 행위로 세우지 않는다 (얻은 값 {_보조}건)")
    # 시험 지문은 **일부러 서로 다르게** 낸다. 그러니 많이 묶이면 그것이 과잉이다.
    _묶 = S.묶기(_지문, _출처)
    _여럿 = [g for g in _묶 if len(g) > 1]
    ok(len(_여럿) <= 5,
       f"시험 지문끼리는 거의 안 묶인다 -- 많이 묶이면 그것이 과잉이다 "
       f"(얻은 값 묶음 {len(_여럿)}개 · 지문 {sum(len(g) for g in _여럿)}개)")
else:
    print("  건너뜀 시험지가 없다")

print()
if fails:
    print(f"스키마: {len(fails)}개 실패 -- {fails}")
    sys.exit(1)
print("스키마: 뒤집기 접기 · 꼴 접기 · 뜻 안 접기 · 빈 칸 · 마디 · 시험지 재기 -- 통과")
