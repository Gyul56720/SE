# -*- coding: utf-8 -*-
"""**요청이 제안서에 시킨 일을 뽑는가 · 제안서가 스스로와 어긋나는 데를 잡는가.**

실측 2026-09-23, MERA-1 스펙 원문과 그 제안서를 나란히 놓고 보니 둘이 나왔다.

## 하나 -- 요청이 제안서에 시킨 일이 조용히 사라졌다

원문 §10:

    ## 10. 제안서에서 답해 주실 것
    온칩 80 KiB 를 플립플롭으로 할지 SRAM 매크로로 할지 **면적으로 비교**해서
    제안서로 내 주세요.

제안서는 그것을 §4 목표의 "어떻게 잴 것인가" 칸으로 **넘기기만** 했다 --
"합성 도구의 게이트 카운트 및 온칩 80 KiB 플립플롭 vs SRAM 매크로로 면적 비교
리포트 확인". 넘긴 것은 **답한 것이 아니다.** 그런데 넘기고 나면 답한 것처럼 보인다.

## 둘 -- 제안서가 스스로와 어긋났다

    §2  클럭 물음 -> "답 있다: RFDC 데이터 인터페이스와 capture core 를 같은
        클럭 도메인에 두어 CDC 를 만들지 않습니다"
    §3  클럭 계획 -> s_axis_aclk 2.0 ns · s_axi_aclk 10.0 ns **(비동기)**

요청 글이 "CDC 를 안 만든다" 고 답했는데 모델은 **비동기 도메인 둘**을 제안했다.
둘 다 말이 될 수는 있다 -- 그렇다고 말 없이 넘어갈 일은 아니다.

실행: python3 tests/test_시킨일과어긋남.py
"""
from __future__ import annotations

import sys
from pathlib import Path

뿌리 = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(뿌리))
sys.path.insert(0, str(뿌리 / "tests"))

FAIL = []


def ok(cond, what):
    print(("  통과  " if cond else "  실패  ") + what)
    if not cond:
        FAIL.append(what)


from house import spec as SPEC                               # noqa: E402
from house import specq as Q                                 # noqa: E402
import _소스보기                                              # noqa: E402

_소스보기.자기검사()

# MERA 원문의 그 자리 (줄바꿈까지 그대로 -- 문단으로 뽑기 때문이다)
_요청 = """# MERA-1 v1.0 Event Recorder Core

목표 주파수 500 MHz, 공급 전압 0.8 V.

## 4. 클럭과 타임스탬프

- RFDC 데이터 인터페이스와 capture core 를 **같은 클럭 도메인**에 두어 **CDC 를 만들지 않습니다.**
- **외부 트리거만** synchronizer 를 거칩니다.

## 10. 제안서에서 답해 주실 것

**온칩 80 KiB 를 플립플롭으로 할지 SRAM 매크로로 할지 면적으로 비교**해서
제안서로 내 주세요.
"""

# ============================================ 1. 시킨 일을 **내용까지** 뽑는다
_시 = Q.제안서에시킨것(_요청)
ok(_시, f"요청이 제안서에 시킨 일을 뽑는다 ({len(_시)}개)")
ok(any("플립플롭" in x and "SRAM" in x for x in _시),
   f"**무엇을 비교하라는 것인지까지 들고 온다** ({_시[0][:52] if _시 else ''}…)")
ok(all(len(x) >= 20 for x in _시),
   "**제목만 있는 토막은 안 낸다** — 문장으로 쪼개면 제목과 몸이 갈라져 "
   "무엇을 비교하라는 것인지가 사라진다")

# 아무 데나 안 걸린다
ok(not Q.제안서에시킨것("제안서를 읽었습니다. 고맙습니다."),
   "**«제안서» 가 나온다고 다 걸지 않는다** — 시키는 말이 같이 있어야 한다")
ok(not Q.제안서에시킨것("면적으로 비교해 주세요."),
   "시키는 말만 있고 «제안서» 가 없으면 안 건다")

# ============================================ 2. 어긋남을 잡는다
_포트 = [{"이름": n, "방향": "input", "폭": 1} for n in
       ("s_axis_aclk", "s_axi_aclk", "s_axis_tvalid", "s_axis_aresetn")]
_둘 = [{"이름": "s_axis_aclk", "주기_ns": 2.0, "도메인": "RFDC/Capture 공통"},
     {"이름": "s_axi_aclk", "주기_ns": 10.0, "도메인": "AXI4-Lite 제어 (비동기)"}]


def _스펙(클럭):
    s = SPEC.읽기(_요청)
    s.포트, s.클럭 = _포트, 클럭
    return s


_s = _스펙(_둘)
_미 = Q.세우기(_s)
ok(any(x.get("id") == "q_clk_rel" and x.get("이미답함") for x in _미["물음"]),
   "요청 글이 클럭 물음에 답한 것을 찾는다")
_어 = Q.어긋난것(_s, _미)
ok(len(_어) == 1 and _어[0]["무엇"] == "클럭 도메인",
   f"**«CDC 안 만든다» 고 해 놓고 비동기 도메인 둘을 제안한 것을 잡는다** ({_어})")
ok("비동기" in _어[0]["모델"] and "CDC" in _어[0]["요청글"],
   "양쪽을 나란히 보인다 — 요청 글과 모델이 한 것")

# **한쪽만으로는 안 건다** (거짓 빨간불이 검사를 못 믿게 만든다)
_한개 = _스펙([{"이름": "s_axis_aclk", "주기_ns": 2.0, "도메인": "공통"}])
ok(Q.어긋난것(_한개, Q.세우기(_한개)) == [],
   "**도메인이 하나면 안 건다**")
_동기 = _스펙([{"이름": "a", "주기_ns": 2.0, "도메인": "공통"},
            {"이름": "b", "주기_ns": 4.0, "도메인": "같은 소스에서 나눈 것"}])
ok(Q.어긋난것(_동기, Q.세우기(_동기)) == [],
   "**둘이어도 «비동기» 가 아니면 안 건다** — 같은 소스에서 나눈 클럭은 CDC 가 아니다")
_답없음 = SPEC.읽기("# X\n\n500 MHz. aresetn.")
_답없음.포트, _답없음.클럭 = _포트, _둘
ok(Q.어긋난것(_답없음, Q.세우기(_답없음)) == [],
   "**요청 글이 그 답을 안 했으면 안 건다** — 어긋날 것이 없다")

# ============================================ 3. 제안서가 이것을 낸다
_산 = _소스보기.산주장((뿌리 / "house" / "arch.py").read_text(encoding="utf-8"))
ok("SPECQ.제안서에시킨것" in _산 and "SPECQ.어긋난것" in _산,
   "**제안서가 둘을 실제로 부른다**")
ok("요청이 이 제안서에 시킨 일" in _산,
   "시킨 일을 표로 낸다 — 「답했나」는 사람이 본다")
ok("요청 글의 답과 모델이 채운 칸이 어긋난다" in _산,
   "어긋남을 경고로 낸다")

print()
if FAIL:
    print(f"실패 {len(FAIL)}개")
    for f in FAIL:
        print("   · " + f)
    raise SystemExit(1)
print("시킨일과어긋남: 내용까지 뽑는다 · 한쪽만으로 안 건다 · 제안서가 낸다 -- 통과")
