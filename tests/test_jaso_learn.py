"""**작법은 밖에서 배우고, 사실은 사람에게서만 온다.**

    python3 tests/test_jaso_learn.py

## 제일 중요한 못 두 개

**(1) 남의 자소서는 재료가 아니다.** 원장에 넣으면 J001~J004 가 남의 이력을 대조하고,
생성자는 남의 경험을 그 사람 것처럼 쓴다. 그리고 한국 채용 실무의 주력은 AI 판별이
아니라 **표절 검사**이며 그 DB 가 정확히 '인터넷에 도는 합격 자소서' 다 -- 그것을
재료로 쓰는 것이 **가장 확실히 걸리는 길**이다.

**(2) 사전을 늘리다가 관문을 못 쓰게 만들지 않는다.** '저는' 이 상투구로 들어오면
모든 자소서가 P003 을 문다. 그래서 배운 낱말은 C001~C003 을 지나야 붙고, 그중 C003 이
**성한 표본을 걸면 안 받는다** -- `law/mutate.py` 의 GREEN 과 같은 규율이다.
"""
from __future__ import annotations

import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from jaso import fetch as JF                                      # noqa: E402
from jaso import learn as LN                                      # noqa: E402
from jaso import wording as WD                                    # noqa: E402

fails = []


def ok(cond, msg):
    print(("  OK   " if cond else "  실패 ") + msg)
    if not cond:
        fails.append(msg)


성한글 = (ROOT / "tests" / "fixtures" / "자소서_성한것.md").read_text(encoding="utf-8")
가이드 = """자기소개서 작성 안내

'귀사의 인재상에 부합하는' 같은 표현은 피하십시오. 어느 회사에나 들어가는 말입니다.
또한 '뼈를 깎는 노력' 이라는 표현은 진부합니다.
'저는' 이라는 말은 쓰지 마십시오.
'지표를 의심하는' 이라는 표현도 식상합니다.
그리고 '성실하게 임하겠습니다' 는 식상한 문구입니다.
"""
출처 = "https://career.example.edu/guide"


print("── 가이드에서 캔다 (LLM 0회) ───────────────────────────")
것들 = LN.뽑기(가이드, 출처)
말들 = [x.말 for x in 것들]
ok("귀사의 인재상에 부합하는" in 말들, f"따옴표로 지목한 것을 캔다 ({말들})")
ok("뼈를 깎는 노력" in 말들, "'~라는 표현은 진부합니다' 도 캔다")
ok(all(x.출처 == 출처 and x.받은날 for x in 것들), "출처와 받은날이 붙는다")
ok(not any("쓰지 마십시오" in m or "피하" in m for m in 말들),
   "**안내문 자체는 안 문다** -- 실측: `이라는 말은 쓰지 마십시오. 그리고` 를 통째로 "
   "물어 왔었다. C001 이 잡긴 했지만, 잡는 것과 애초에 안 무는 것은 다른 일이다 "
   "(버린 것 목록이 잡음으로 차면 아무도 안 읽는다)")


print("\n── C001~C003 -- 사전에 붙기 전에 세 관문 ────────────────")
받을것, vs = LN.검사(것들, 가이드, 성한글)
받은말 = [x.말 for x in 받을것]
ok("귀사의 인재상에 부합하는" in 받은말 and "뼈를 깎는 노력" in 받은말,
   f"성한 것은 받는다 ({받은말})")


def 걸린것(vs, 말):
    return [v for v in vs if v.어디 == 말]


ok(걸린것(vs, "저는") and 걸린것(vs, "저는")[0].규칙 == "C003",
   "**'저는' 은 안 받는다** -- 받으면 모든 자소서가 P003 을 문다")
ok(걸린것(vs, "지표를 의심하는")
   and 걸린것(vs, "지표를 의심하는")[0].규칙 == "C003",
   "**성한 표본에 있는 말은 안 받는다** -- 가이드가 식상하다고 해도, 받으면 원장에 "
   "붙은 글이 걸린다. 사전을 늘리다가 관문을 못 쓰게 만드는 자리다")
지어냄 = [LN.배운것(말="원문에 없는 말", 출처=출처, 받은날="2026-09-09")]
_, vs2 = LN.검사(지어냄, 가이드, 성한글)
ok(vs2 and vs2[0].규칙 == "C001",
   "**원문에 없는 것은 버린다** -- 모델이 다듬었거나 지어낸 것이다 (고쳐 넣지 않는다)")
_, vs3 = LN.검사([LN.배운것(말="무엇", 출처="")], 가이드, 성한글)
ok(vs3 and vs3[0].규칙 == "C002", "출처 없는 것은 안 받는다")
ok(all(v.등급 == "hard" for v in vs + vs2 + vs3),
   "C 계열은 전부 hard -- 통과 못 하면 붙지 않는다")


print("\n── 배운 것이 사전을 늘린다 ─────────────────────────────")
with tempfile.TemporaryDirectory() as d:
    p = LN.담기(받을것, d)
    ok(p and p.exists(), f"담긴다 ({p.name if p else '-'})")
    다시 = LN.읽기(d)
    ok(len(다시) == len(받을것), f"되읽으면 {len(다시)}개")
    ok(다시.갈래("상투구") and all(x.출처 for x in 다시.것들), "출처가 살아 있다")
    ok(LN.담기([LN.배운것(말="x", 출처="")], d) is None, "출처 없으면 안 담는다")
ok(len(LN.읽기("/그런/데는/없다")) == 0, "없는 데는 빈 것 (안 죽는다)")

원래 = WD._배운것
try:
    WD._배운것 = ("귀사의 인재상에 부합하는", "뼈를 깎는 노력")
    ok("뼈를 깎는 노력" in WD.상투("저는 뼈를 깎는 노력으로 임했습니다"),
       "**배운 말이 P003 에 들어간다** -- 씨앗에 없던 것을 잡는다")
    ok("귀사의 인재상" in WD.상투("귀사의 인재상에 부합하며"),
       "씨앗도 그대로 돈다")
    ok(not WD.상투(성한글),
       "**(대조군) 배운 사전을 붙여도 성한 글은 조용하다** -- C003 이 그 자리를 지킨다")
finally:
    WD._배운것 = 원래
ok(isinstance(WD.배운상투(), tuple),
   "원장이 없어도 씨앗만으로 돈다 (예외로 안 죽는다)")


print("\n── **남의 자소서는 안 받는다** ──────────────────────────")
ok(JF.안받는곳, f"안 받는 곳 목록이 있다 ({JF.안받는곳})")
보고 = JF.받기(urls=["https://합격자소서.example.com/x"], 몇=1)
ok("안 받는 곳" in str(보고["쪽별"]), "문항 수집도 그 곳은 건너뛴다")
ok("남의 자소서는 안 받는다" in LN.__doc__ and "표절 검사" in LN.__doc__,
   "**왜 안 받는지가 파일에 적혀 있다** -- 도덕론이 아니라 기능이 무너지기 때문이다")
ok("사실" in LN.__doc__ and "사람만 채운다" in LN.__doc__,
   "원장(사실)과 작법(글 쓰는 법)이 다른 자리라고 적혀 있다")


print("\n── 모델을 써도 판정은 코드가 한다 ───────────────────────")
가짜답 = "귀사의 인재상에 부합하는\n뼈를 깎는 노력\n제가 지어낸 표현\n"
것들2 = LN.모델로뽑기(가이드, 출처, 묻기=lambda _: 가짜답)
ok(len(것들2) == 3, f"모델이 뽑은 것을 그대로 받는다 ({len(것들2)}개)")
받2, vs4 = LN.검사(것들2, 가이드, 성한글)
ok([x.말 for x in 받2] == ["귀사의 인재상에 부합하는", "뼈를 깎는 노력"],
   f"**원문에 있는 것만 붙는다** ({[x.말 for x in 받2]})")
ok(any(v.규칙 == "C001" and v.어디 == "제가 지어낸 표현" for v in vs4),
   "지어낸 것은 C001 이 버린다 -- `intake.py` I001 과 같은 수다")
프 = LN.프롬프트(가이드)
ok("C001" not in 프 and "관문" not in 프 and "P003" not in 프,
   "**프롬프트에 판정 이야기가 없다** -- 실으면 통과하는 것만 뽑아 온다")

print()
print(f"실패 {len(fails)}건" if fails else "전부 통과")
raise SystemExit(1 if fails else 0)
