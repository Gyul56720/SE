# -*- coding: utf-8 -*-
"""**미정 행동을 인터페이스에서 기계로 뽑는가 -- 답을 아는 스펙으로 잰다.**

정리해 둔 것(`paper/선행조사/스펙-읽기와쓰기.md`)의 첫 문장:

> 스펙을 읽는다는 것은 숫자를 읽는 것이 아니라
> **"아직 정의되지 않은 행동을 찾아내는 것"** 에 가깝다.

그리고 그 미정 항목은 **인터페이스에서 따라 나온다.** 우리는 이 목록을 모델에게
맡기고 있었고, 그래서 회로마다 들쭉날쭉했다(실측 2026-09-22: 같은 것이 세 줄로
나뉘고, 이미 읽은 칸이 다시 물음으로 올라왔다).

**여기서 가장 중요한 것은 방향이다.** 거짓 '답있음' 은 **물음을 지운다** --
이 파일의 목적이 미정 행동을 찾는 것인데 못 찾게 만든다. 그래서 두 쪽을 다 잰다:
답이 없는 스펙에서 **묻는가**, 답이 있는 스펙에서 **안 묻는가**.

실행: python3 tests/test_미정뽑기.py
"""
from __future__ import annotations

import sys
from pathlib import Path

뿌리 = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(뿌리))

FAIL = []


def ok(cond, what):
    print(("  통과  " if cond else "  실패  ") + what)
    if not cond:
        FAIL.append(what)


from house import spec as SPEC       # noqa: E402
from house import specq as Q         # noqa: E402

_포트 = [{"이름": n, "방향": "input", "폭": 1} for n in
       ("s_axis_tvalid", "s_axis_tready", "s_axis_tlast", "s_axis_tkeep",
        "out_acc", "aresetn", "aclk", "cfg_clk", "ovf_sticky", "s_axi_awaddr")]

# ============================================ 1. 답이 없으면 **묻는다**
_빈 = SPEC.스펙(요청="AXI4-Stream 을 받아 DDR 에 쓰는 IP 를 설계해 주세요.",
            수={"주파수_Hz": [5e8]}, 포트=_포트)
r = Q.세우기(_빈)
_id = {x["id"] for x in r["미정"]}
for 있어야 in ("q_valid_hold", "q_reset_valid", "q_pkt_len", "q_partial",
            "q_overflow", "q_accw", "q_rst_kind", "q_rst_value",
            "q_clk_rel", "q_throughput", "q_latency", "q_err_clear", "q_regmap"):
    ok(있어야 in _id, f"**묻는다**: {있어야}")
ok(all(x["출처"] for x in r["물음"]),
   "**물음마다 출처가 있다** — 어느 포트/수에서 나왔는지")
ok(all(x["왜"] for x in r["물음"]), "물음마다 왜 물어야 하는지가 있다")

# ============================================ 2. 답이 있으면 **안 묻는다**
_답 = SPEC.스펙(요청="""
누산기가 넘치면 포화 처리합니다. 누산기 폭은 40비트입니다.
곱셈 결과는 반올림 처리 방식을 적용합니다.
리셋은 비동기로 걸고 동기로 해제합니다. 리셋 값은 모든 출력이 0 으로 갑니다.
지연은 12 주기 이내입니다. 처리율은 매 주기 한 표본입니다.
sticky 플래그는 레지스터 쓰기로 지운다. 레지스터 맵은 아래 주소 표에 있습니다.
리셋 중에는 출력 valid 가 0 이다. tvalid 가 선 뒤에는 데이터가 불변이다.
tkeep 의 부분 바이트는 마지막 beat 에서만 허용한다.
패킷 최대 길이는 4096 beat 이다. 두 클럭은 서로 비동기다.
""", 수={"주파수_Hz": [1e8]}, 포트=_포트)
r2 = Q.세우기(_답)
ok(r2["미정수"] == 0,
   f"**답이 다 적힌 스펙에서는 하나도 안 묻는다** (미정 {r2['미정수']}개: "
   f"{[x['id'] for x in r2['미정']]})")
ok(r2["이미답한수"] == len(r2["물음"]), "전부 '이미답함' 으로 센다")
ok(all(x["이미답함"] for x in r2["물음"]), "답으로 본 문장을 같이 들고 온다")

# ============================================ 3. **거짓 '답있음' 을 안 낸다**
# 실측 2026-09-22 (MERA 스펙): 한 낱말만 보고 이렇게 잘못 지웠다.
#   "패킷의 최소·최대 길이는?" -> 'beat'   (그 beat 는 "한 beat = sample 8개")
#   "레지스터 맵은?"           -> 'offset' (그 offset 은 "채널별 고정 offset")
#   "valid 를 유지하나?"       -> '유지'   (그 유지는 "circular buffer 로 유지")
# **거짓 '답있음' 은 물음을 지운다** -- 겹쳐 묻는 것보다 못 물은 것이 나쁘다.
_미끼 = SPEC.스펙(요청="""
canonical 256-bit 한 beat = complex sample 8개.
채널별 고정 offset 을 레지스터로 보정할 수 있게 하세요.
평상시 circular buffer 로 유지하다 트리거가 오면 capture 를 합니다.
포트 이름은 AMD 규약을 따라 주세요 (`s_axis_*` · `*_aresetn`).
""", 수={"주파수_Hz": [5e8]}, 포트=_포트)
r3 = Q.세우기(_미끼)
_답한id = {x["id"] for x in r3["물음"] if x["이미답함"]}
for 안돼 in ("q_pkt_len", "q_regmap", "q_valid_hold", "q_rst_kind"):
    ok(안돼 not in _답한id,
       f"**엉뚱한 문장에 안 속는다**: {안돼} 를 '답있음' 으로 지우지 않는다")

# ============================================ 4. 포트가 없어도 요청 글에서 세운다
# **미정 항목이 가장 쓸모 있는 때가 포트가 아직 없을 때다** -- 모델이 채우기 전에
# 사람에게 보여야 하는 것이니까. 실측: 규칙만으로 읽으면 포트가 비어서 인터페이스
# 물음이 10개 중 4개만 나왔다.
_포트없음 = SPEC.스펙(요청="AXI4-Stream 입력, AXI4-Lite 제어, sticky flag 로 오류를 남긴다. "
                  "500 MHz. aresetn 으로 리셋한다.",
                  수={"주파수_Hz": [5e8]}, 포트=[])
r4 = Q.세우기(_포트없음)
ok("요청 글" in r4["포트어디서"], f"포트가 없으면 요청 글에서 세운다 ({r4['포트어디서']})")
_id4 = {x["id"] for x in r4["미정"]}
ok({"q_valid_hold", "q_regmap", "q_err_clear"} <= _id4,
   f"**글만으로도 인터페이스 물음이 나온다** ({sorted(_id4)})")
ok(all("포트는 아직 없다" in x["출처"] for x in r4["물음"]),
   "**아직 없는 포트를 '포트' 라고 안 적는다** — 출처가 틀리면 되짚을 수 없다")

# 인터페이스를 하나도 안 부른 글에서는 그 물음이 안 나온다
_민 = SPEC.스펙(요청="무언가를 만들어 주세요.", 수={}, 포트=[])
r5 = Q.세우기(_민)
ok(not any(x["id"] in ("q_valid_hold", "q_regmap", "q_partial") for x in r5["물음"]),
   "**없는 인터페이스의 물음을 지어내지 않는다**")

# ============================================ 5. 겹치면 `모른다` 에 안 더한다
_s = SPEC.스펙(요청="AXI4-Stream IP", 수={"주파수_Hz": [1e8]}, 포트=_포트,
            모른다=["누산기가 넘칠 때 포화인지 되돌이인지"])
_전 = len(_s.모른다)
_더 = Q.모른다에넣기(_s, Q.세우기(_s))
ok(not any("넘칠 때" in x for x in _더),
   f"**모델이 이미 적은 줄과 겹치면 안 더한다** — '모르는 것 N개' 가 부풀면 "
   f"사람이 설계 상태를 잘못 읽는다 ({[x[:24] for x in _더][:3]})")
ok(len(_s.모른다) == _전 + len(_더), "더한 만큼만 늘어난다")

# ============================================ 6. 제안서가 이 표를 낸다
_소스 = (뿌리 / "house" / "arch.py").read_text(encoding="utf-8")
ok("from house import specq as SPECQ" in _소스 and "SPECQ.모른다에넣기" in _소스,
   "**제안서가 이것을 실제로 부른다** — 코드에만 있고 문서에 없으면 사람은 모른다")
ok("어디서 나왔나" in _소스 and "요청 글의 답" in _소스,
   "제안서 표에 **출처**와 **요청 글의 답**이 열로 선다")
ok(r["못하는것"], "못 하는 것을 같이 돌려준다 (무엇이 옳은 답인지는 모른다)")

print()
if FAIL:
    print(f"실패 {len(FAIL)}개")
    for f in FAIL:
        print("   · " + f)
    raise SystemExit(1)
print("미정뽑기: 묻는다 · 안 묻는다 · 거짓 답있음 없음 · 글에서 세우기 · 겹침 -- 통과")
