"""**곱셈기 0개 구조가 어디서 지는가** -- 그 경계를 재서 붙든다.

앞선 판은 "메모리가 아주 길면 표의 주소가 지수로 터질 것이다" 라고 적어만 두고 그런
경우를 짓지 않았다. 이번에 지어서 재 봤고, **내가 생각한 그것이 아니었다.**

## 재고 나서 뒤집힌 것 -- 실측 2026-09-16

*생각.* AC 결합 드룹(시상수 tau) 뒤에 압축을 두면 보정에 tau 만큼의 과거가 필요하다.
표의 주소는 2^(창·색인비트) 로 터지므로 어디선가 신경망이 이겨야 한다.

*잰 것.* 드룹을 18.8 UI 까지 길게 줘도 표/망의 순서가 거의 안 움직였다(1.28 -> 1.47).
**순서를 움직인 것은 메모리 길이가 아니라 압축의 세기 k 였다.**

    바꾼 것(25dB · SNR30 · 나머지 고정)   NN/표 중앙값   NN 이긴 씨
    기준(k=1.0, 필터 없음)                    1.28         5/8
    k = 1.3                                  2.17         8/8
    k = 1.6                                  2.50         8/8
    k = 2.0                                  3.40         8/8
    드룹 tau = 18.8 UI                        1.47         7/8    <- 거의 안 움직인다
    압축뒤대역 beta = 0.35                     0.56         1/8    <- 오히려 표 쪽으로

*그런데 그 1.28 조차 공정하지 않았다.* 표 앞에는 FFE 가 있고, **메모리 없는 압축을
그대로 둔 채 선형 적응기를 돌리고 있었다.** 이 저장소가 이미 낸 결론(명제 1)이
"메모리 없는 비선형은 ADC 코드 표가 곱셈 0개로 되돌린다" 인데, 정작 비교에서는
그 표를 안 쓰고 있었다. 앞단에 그것을 두자 k=2.0 에서 표가 5.9e-2 -> 1.1e-2 로
**5.2배** 좋아졌다. 표가 구조적으로 모자란 것이 아니라 **앞단을 안 깔아 준 것**이었다.

## 그래서 이 검사가 붙드는 것

양쪽에 똑같이 메모리 없는 역보정을 깔고 나면 경계가 이렇게 선다.

    k = 1.0   표가 이긴다 (NN/표 0.59, NN 1/8)
    k = 1.3   표가 이긴다 (0.71, 0/8)
    k = 1.6   표가 이긴다 (0.78, 2/8)
    k = 2.0   **망이 이긴다** (1.79, 8/8)

곱셈기 0개 구조는 **생각보다 멀리 간다.** 그래도 끝이 있고, 그 끝은 k≈2 다.
"""
from __future__ import annotations

import sys
from pathlib import Path

import numpy as np

뿌리 = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(뿌리))

import nneq
import serdes

FAIL_목록 = []


def ok(참, 말):
    print(("  통과 " if 참 else "  실패 ") + 말)
    if not 참:
        FAIL_목록.append(말)


N, 씨수 = 640000, 3
밑 = dict(비트수=N, 손실dB=25.0, SNRdB=30.0, ADC비트=7)


def 표(k, 창=2, 비트=4, 역=True, **더):
    return [serdes.링크(**밑, 압축=k, 역압축=역, FFE탭=11, 표본표창=창,
                      표본표비트=비트, 씨=s, **더) for s in range(씨수)]


def 망(k, 역=True, **더):
    return [nneq.링크(**밑, 압축=k, 역압축=역, 앞뒤=2, 은닉수=2, 에폭=12,
                    가중치비트=7, 씨=s, **더) for s in range(씨수)]


def 합(rs):
    return sum(r["오류수"] for r in rs) / sum(r["잰비트"] for r in rs)


def 비(기준, 견줄):
    return [a["BER"] / b["BER"] for a, b in zip(기준, 견줄) if b["BER"] > 0]


print("[가 -- 압축이 세면(k=2.0) 12곱셈 신경망이 표를 이긴다]")
표2, 망2 = 표(2.0), 망(2.0)
r2 = 비(표2, 망2)
ok(len(r2) == 씨수 and float(np.median(r2)) > 1.3 and sum(1 for x in r2 if x > 1) == 씨수,
   f"k=2.0: NN 5->2(7비트) {합(망2):.2e} vs 표2x4 {합(표2):.2e} -- "
   f"씨별 중앙값 {np.median(r2):.2f}배, 이긴씨 {sum(1 for x in r2 if x > 1)}/{len(r2)}")

print("[나 -- 약한 압축 + 압축뒤대역(논문의 그 자리)에서는 표가 이긴다(대조)]")
# **이 대조가 없으면 (가)는 아무 뜻이 없다.** 어디서나 망이 이기면 그것은 손상이
# 아니라 비교가 기운 것이다. 논문의 동작점(k=1.0 · beta=0.35)을 그대로 쓴다 --
# 8씨로는 k=1.0·필터없음도 표가 이기지만(NN/표 0.59) 씨 3개로는 안 갈린다.
# **안 갈리는 것을 갈렸다고 적지 않는다**: 갈리는 자리를 고른다.
표1, 망1 = 표(1.0, 압축뒤대역=0.35), 망(1.0, 압축뒤대역=0.35)
r1 = 비(표1, 망1)
ok(float(np.median(r1)) < 0.7,
   f"k=1.0 · beta=0.35: NN {합(망1):.2e} vs 표 {합(표1):.2e} -- "
   f"씨별 중앙값 {np.median(r1):.2f}배 (1 보다 작아야 한다)")
ok(float(np.median(r2)) / max(float(np.median(r1)), 1e-9) > 2.0,
   f"손상의 꼴이 순서를 뒤집는다: k=2.0 에서 {np.median(r2):.2f}배 vs "
   f"논문 동작점에서 {np.median(r1):.2f}배")

print("[다 -- 표가 무너진 것은 앞단을 안 깔아서였다]")
# 메모리 없는 역보정(ADC 코드 표, 곱셈 0개)을 **빼고** 같은 표를 돌린다.
민표 = 표(2.0, 역=False)
ok(합(민표) / 합(표2) > 3.0,
   f"k=2.0 에서 앞단을 빼면 표가 {합(민표):.2e} 로 무너진다 "
   f"(깔면 {합(표2):.2e}, {합(민표) / 합(표2):.1f}배 차이) -- "
   f"구조가 모자란 것이 아니라 앞단이 없던 것이다")

print("[라 -- 표를 키우는 것으로는 못 넘는다(데이터의 벽)]")
큰 = 표(2.0, 창=3, 비트=5)
찬, 칸 = 큰[0]["표본표찬칸"], 큰[0]["표본표칸수"]
ok(합(큰) > 합(표2),
   f"{칸:,}칸({합(큰):.2e})이 256칸({합(표2):.2e})보다 **나쁘다**")
작은찬, 작은칸 = 표2[0]["표본표찬칸"], 표2[0]["표본표칸수"]
# **찬 칸은 칸수보다 훨씬 느리게 는다** -- 문턱을 눈대중으로 고르지 않으려고
# 작은 표의 채움 비율에 견준다(작은 표는 거의 다 찬다).
ok(찬 / 칸 < 0.5 * (작은찬 / 작은칸),
   f"{칸:,}칸은 {100 * 찬 / 칸:.0f}%({찬:,})만 차는데 "
   f"{작은칸}칸은 {100 * 작은찬 / 작은칸:.0f}%({작은찬}) 찬다 -- "
   f"막는 것은 면적이 아니라 프리앰블 길이다")

print()
if FAIL_목록:
    print(f"실패 {len(FAIL_목록)}개")
    for m in FAIL_목록:
        print("  - " + m)
    sys.exit(1)
print("전부 통과")
