# -*- coding: utf-8 -*-
"""**LEC(관문 6c) 가 증명하는가 -- 그리고 못 한 것을 못 했다고 하는가.**

테이프아웃 지도 M4 의 마지막 칸이었다.

    LEC (RTL ↔ 넷리스트 등가)   없다   칸 자체가 없다

## 실측 2026-09-23 (yosys 0.33, nsw_fir) -- 경계가 뚜렷하다

    nsw_icg     증명됨   0.03 s
    nsw_sync2   증명됨   0.03 s
    nsw_afifo   증명됨   0.50 s
    nsw_ctrl    증명됨   0.18 s   <- FSM. 가장 값진 자리다
    nsw_mac     못 끝냄  240 s 예산 초과 (16x16 곱셈 + 40비트 누산)
    nsw_fir     못 끝냄  equiv_induct 가 18분에도 안 끝난다 (클럭 둘)

**`async2sync` 가 없으면 아무것도 못 한다** -- "No SAT model available for
async FF cell" 이 191번 나고 전부 미증명으로 끝난다. 우리 플롭이 전부 비동기
리셋이기 때문이다.

## 부분 증명을 전체 증명으로 세지 않는다

그래서 관문은 **반례**와 **증명 개수**로만 죈다. 예산을 넘겨 못 끝낸 것은
이름을 적고 넘어간다 -- 빨갛게 하면 관문이 영영 빨갛고, 초록으로 세면 거짓이다.

## 한 번 덜 보고 초록을 냈다

첫 판은 예산 초과 `except` 가 **for 바깥**에 있었다. `nsw_mac` 이 20 s 를
넘기자 **뒤 모듈이 통째로 빠졌다** -- "모듈 6개" 라고 적으면서 줄은 4개였고,
가장 값진 `nsw_ctrl` 이 아예 안 돌았다. 관문이 덜 보고 초록을 낸 것이다.
이 검사의 [6] 이 그 자리를 붙든다.

실행: python3 tests/test_LEC관문.py
"""
from __future__ import annotations

import sys
from pathlib import Path

뿌리 = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(뿌리))

FAIL = []


def ok(cond, what):
    print(("  통과  " if cond else "  실패  ") + what)
    if not cond:
        FAIL.append(what)


from house import designs as DES       # noqa: E402
from house import gen as GEN           # noqa: E402
from house import tapeout as TO        # noqa: E402

문턱 = GEN.기본문턱
성한것 = {"모듈별": [{"모듈": "nsw_icg", "상태": "증명됨", "말": "", "초": 0.04},
                {"모듈": "nsw_sync2", "상태": "증명됨", "말": "", "초": 0.03},
                {"모듈": "nsw_afifo", "상태": "증명됨", "말": "", "초": 0.5},
                {"모듈": "nsw_mac", "상태": "못끝냄", "말": "20 s 예산 초과",
                 "초": 20.0},
                {"모듈": "nsw_ctrl", "상태": "증명됨", "말": "", "초": 0.18},
                {"모듈": "nsw_fir", "상태": "못끝냄", "말": "20 s 예산 초과",
                 "초": 20.0}],
        "셈": {"증명됨": 4, "반례": 0, "못끝냄": 2, "합성실패": 0},
        "모듈수": 6, "예산_초": 20.0, "초": 65.0}


def 판정(**고침):
    return GEN.등가검사판정({**성한것, **고침}, 문턱)


print("\n[1] 문턱이 있나")
for 열쇠 in ("lec예산_초", "lec증명수"):
    ok(열쇠 in 문턱, f"gen.기본문턱 에 {열쇠!r} 가 있다 ({문턱.get(열쇠)})")

print("\n[2] 성한 값은 통과한다")
r = 판정()
ok(len(r) == 1 and r[0][1], "반례 0 · 증명 4개면 초록이다")
ok(r[0][0].startswith("6c."), f"이름표가 6c 로 시작한다 ({r[0][0][:12]})")
ok(r[0][3] == 4, f"내는 수는 증명된 모듈 수다 ({r[0][3]})")

print("\n[3] **관문이 무는가**")
반례든것 = {**성한것,
        "모듈별": [{**성한것["모듈별"][0], "상태": "반례",
                 "말": "Inequivalent: \\o_gold != \\o_gate"}]
                + 성한것["모듈별"][1:],
        "셈": {"증명됨": 3, "반례": 1, "못끝냄": 2, "합성실패": 0}}
ok(not GEN.등가검사판정(반례든것, 문턱)[0][1],
   "**반례가 하나라도 나오면 빨갛다** — 증명이 문턱을 넘어도")
ok("반례" in GEN.등가검사판정(반례든것, 문턱)[0][2],
   "그 반례를 모듈 이름과 함께 적는다")
적은것 = {**성한것, "셈": {**성한것["셈"], "증명됨": 문턱["lec증명수"] - 1}}
ok(not GEN.등가검사판정(적은것, 문턱)[0][1],
   f"증명된 모듈이 {문턱['lec증명수']}개보다 적으면 빨갛다 — 장치가 죽은 것이다")
ok(GEN.등가검사판정({**성한것, "셈": {**성한것["셈"], "증명됨": 문턱["lec증명수"]}},
                문턱)[0][1],
   "문턱과 꼭 같으면 통과한다")
ok(not GEN.등가검사판정({"오류": "RTL 이나 셀 모델이 없다"}, 문턱)[0][1],
   "못 돌리면 빨갛다")

print("\n[4] **못 끝낸 것이 관문을 빨갛게 하지 않는가** -- 그러면 영영 빨갛다")
다못 = {**성한것,
      "모듈별": [{**x, "상태": "못끝냄"} for x in 성한것["모듈별"]],
      "셈": {"증명됨": 0, "반례": 0, "못끝냄": 6, "합성실패": 0}}
r2 = GEN.등가검사판정(다못, 문턱)
ok(not r2[0][1],
   "**전부 못 끝내면 빨갛다** — 증명 0개는 장치가 죽은 것과 구별이 안 된다")
절반 = {**성한것, "셈": {"증명됨": 4, "반례": 0, "못끝냄": 2, "합성실패": 0}}
ok(GEN.등가검사판정(절반, 문턱)[0][1],
   "몇 개를 못 끝내도 증명이 문턱을 넘으면 초록이다")

print("\n[5] 관문 글이 경계를 적는가")
말 = 판정()[0][2]
ok("부분 증명을 전체 증명으로 세지 않는다" in 말, "부분 증명임을 먼저 말한다")
ok("nsw_mac" in 말 and "nsw_ctrl" in 말, "모듈마다 무엇이 됐는지 이름으로 적는다")
ok("6b" in 말, "못 증명한 자리를 무엇이 덮는지(자극) 가리킨다")
ok("증명은 아니다" in 말, "그 덮음이 증명이 아니라는 것도 적는다")

print("\n[6] **덜 보고 초록을 내지 않는가** -- 첫 판이 그랬다")
# 예산 초과가 하나 나도 **모듈 목록은 다 있어야** 한다. 첫 판은 except 가
# for 바깥이라 뒤 모듈이 통째로 빠졌다.
from tests._소스보기 import 산주장                             # noqa: E402
src = 산주장((뿌리 / "house" / "gen.py").read_text(encoding="utf-8"))
i = src.index("def 등가검사(")
j = src.index("def 등가검사판정(")
몸 = src[i:j]
ok("except subprocess.TimeoutExpired:" in 몸 and "continue" in 몸,
   "예산 초과를 잡고 **다음 모듈로 넘어간다**")
ok(몸.count("for M in 모듈들") == 1, "모듈을 도는 고리가 하나다")
ok(몸.index("for M in 모듈들") < 몸.index("except subprocess.TimeoutExpired:"),
   "그 except 가 for **안**에 있다 — 바깥에 있으면 한 번 걸릴 때 나머지가 빠진다")
ok("async2sync" in 몸,
   "async2sync 를 건다 — 없으면 비동기 리셋 플롭 때문에 아무것도 증명 못 한다")

print("\n[7] 낸 목록이 실제 모듈 수와 맞는가 -- 손으로 만든 값에서 먼저 본다")
ok(len(성한것["모듈별"]) == 성한것["모듈수"],
   f"모듈별 줄 수와 모듈수가 같다 ({len(성한것['모듈별'])}/{성한것['모듈수']})")
ok(sum(성한것["셈"].values()) == 성한것["모듈수"],
   f"셈을 다 더하면 모듈수다 ({sum(성한것['셈'].values())})")

print("\n[8] **진짜로 증명해 본다** -- 예산을 줄여 한 모듈만")
import time                                                   # noqa: E402
t0 = time.time()
L = GEN.등가검사(DES.NSW_FIR, {**문턱, "lec예산_초": 6.0})
ok(not L.get("오류"), f"등가검사()가 돌았다 ({str(L.get('오류',''))[:150]})")
if not L.get("오류"):
    ok(set(성한것) <= set(L),
       f"손으로 만든 값과 칸이 같다 (빠진 칸 {sorted(set(성한것) - set(L))})")
    ok(len(L["모듈별"]) == L["모듈수"],
       f"**모듈이 한 개도 안 빠졌다** ({len(L['모듈별'])}/{L['모듈수']}) — "
       "첫 판이 여기서 4/6 이었다")
    ok(sum(L["셈"].values()) == L["모듈수"], "셈을 다 더하면 모듈수다")
    ok(L["셈"]["반례"] == 0,
       f"반례가 없다 ({[x['모듈'] for x in L['모듈별'] if x['상태'] == '반례']})")
    ok(L["셈"]["증명됨"] >= 문턱["lec증명수"],
       f"증명된 모듈이 문턱 이상이다 ({L['셈']['증명됨']} ≥ {문턱['lec증명수']}) — "
       f"{[x['모듈'] for x in L['모듈별'] if x['상태'] == '증명됨']}")
    ok(any(x["모듈"] == "nsw_ctrl" and x["상태"] == "증명됨" for x in L["모듈별"]),
       "**FSM(nsw_ctrl)이 증명된다** — 합성이 상태기계를 안 바꿨다는 증명이다")
    ok(GEN.등가검사판정(L, 문턱)[0][1], "잰 값으로 관문이 초록이다")
    print(f"       ({L['셈']} · {L['초']} s · 예산 6 s)")

print("\n[9] 테이프아웃 표 -- 못 하는 쪽이 남았나")
이름별 = {x["이름"]: x for x in TO.표(주인="syn")}
x = 이름별.get("LEC — 제어 · 글루 블록")
ok(x is not None and x["상태"] == TO.있다, "「LEC — 제어·글루」 가 「있다」 다")
d = 이름별.get("LEC — 데이터패스 · 최상위")
ok(d is not None and d["상태"] == TO.없다 and d["막나"],
   "「LEC — 데이터패스·최상위」 는 **없는 채로 남고 여전히 막는다**")
ok("수렴하지 않는다" in (d or {}).get("메모", ""),
   "왜 못 하는지(수렴 안 함)를 적어 둔다")
ok(TO._관문있나("6c") and "6c" in GEN.관문번호들(), "관문 6c 가 있다")
ok(not TO.검사() and not TO.거짓증거() and not TO.안걸린붙듦(),
   f"계획에 흠이 없다 ({TO.검사()})")

print("\n" + "=" * 62)
if FAIL:
    print(f"실패 {len(FAIL)}개")
    for x in FAIL:
        print("  · " + x)
    raise SystemExit(1)
print("전부 통과")
