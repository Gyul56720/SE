"""**sky130 + ngspice 로 손계산을 친다.** 둘이 없으면 건너뛴다.

`afe.py` 는 닫힌 꼴이고 `afespice.py` 는 같은 양을 진짜 소자로 다시 잰다. 이 검사가
붙드는 것은 **두 값이 같다**가 아니라 **어긋나는 자리를 알고 있다**는 것이다 --
어긋남을 숫자로 적어 두면, 나중에 누가 닫힌 꼴을 회로처럼 쓰려 할 때 걸린다.

    (가) CTLE: `serdes.CTLE` 의 꼴은 실제 CTLE 를 ~1.6 dB 안에서 흉내 낸다.
         **못 쓰는 것은 꼴이 아니라 회로값 -> 파라미터 매핑이다**(그쪽은 3.7 dB).
    (나) 오프셋: 미스매치가 없으면 정확히 0, 있으면 mV 급 -- **ADC LSB 와 같은 자리**
    (다) Pelgrom: 면적을 키우면 sigma 가 준다. 같은 면적이면 W·L 배분이 달라도 같다.
    (라) CML: 에지가 UI 의 몇 분의 일인가. **꼬리 노드가 접지 위에 있나**(자기모순 검사)
    (마) StrongARM: 재생이 지수인가. `tau = C/gm` 이 실측과 만나나.
"""
from __future__ import annotations

import math
import sys
from pathlib import Path

import numpy as np

뿌리 = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(뿌리))

import afe
import afespice
import pdk
import serdes
import spice

FAIL_목록 = []


def ok(참, 말):
    print(("  통과 " if 참 else "  실패 ") + 말)
    if not 참:
        FAIL_목록.append(말)


if not spice.있나():
    print("ngspice 가 없다 -- 건너뛴다")
    raise SystemExit(0)
if not (pdk.있나() or pdk.받기()["됐나"]):
    print("sky130 모델을 못 구했다 -- 건너뛴다:", pdk.말로()[:120])
    raise SystemExit(0)

print("[가 -- 실제 CTLE 를 두 모형이 얼마나 맞추나]")
c = afespice.ctle()
ok(c["판정"] == serdes.PASS, f"sky130 CTLE AC 가 돈다 ({c.get('왜', '')[:60]})")
if c["판정"] == serdes.PASS:
    ok(2.0 < c["피킹dB"] < 12.0 and 3e8 < c["피크Hz"] < 1e10,
       f"피킹 {c['피킹dB']:.2f} dB @ {c['피크Hz'] / 1e9:.2f} GHz -- 실제 CTLE 의 자리다")
    ok(c["자유맞춤_최대잔차dB"] < 2.5,
       f"`serdes.CTLE` 의 3파라미터를 **자유 맞춤**하면 최대 잔차 "
       f"{c['자유맞춤_최대잔차dB']:.2f} dB -- 꼴 자체는 쓸 만하다")
    # **매핑은 그만큼 못 한다** -- 그 차이가 이 검사의 요점이다
    매 = afe.ctle_검증()
    ok(매["최대차dB"] > c["자유맞춤_최대잔차dB"],
       f"회로값을 그대로 넣은 매핑은 {매['최대차dB']:.2f} dB 로 더 나쁘다 -- "
       f"**고칠 것은 꼴이 아니라 매핑이다**")

print("[나 -- 비교기 오프셋(미스매치 몬테카를로)]")
o = afespice.오프셋(씨수=12)
ok(o["판정"] == serdes.PASS, f"tt_mm 몬테카를로가 돈다 ({o.get('왜', '')[:60]})")
if o["판정"] == serdes.PASS:
    ok(abs(o["대조_미스매치없음_mV"]) < 1e-6,
       f"대조: 미스매치 없는 tt 코너에서 오프셋이 정확히 0 이다 "
       f"({o['대조_미스매치없음_mV']:.2e} mV) -- 검사가 살아 있다")
    ok(0.3 < o["시그마mV"] < 6.0,
       f"sigma {o['시그마mV']:.2f} mV (면적 {o['면적um2']:.0f} um2, {o['회수']}회)")
    # **ADC LSB 와 같은 자리인가** -- 이것이 §17.2 의 바닥과 이어지는 고리다
    b = afe.바닥원인(ADC비트=7, 풀스케일시그마=2.5, AFE입력rmsV=0.067)
    비 = o["시그마mV"] * 1000.0 / b["ADC_LSB_uV"]
    ok(0.1 < 비 < 3.0,
       f"오프셋 sigma 가 ADC LSB 의 {비:.2f}배 -- **바닥의 기여자가 둘이고 크기가 비슷하다** "
       f"(재생 감도는 {b['인터리빙']}-way 인터리빙에서 {b['비교기감도uV']:.3g} uV "
       f"로 그 둘보다 훨씬 작다)")
    # **인터리빙을 안 세면 결론이 뒤집힌다** -- 그것을 검사가 붙든다
    하나 = afe.바닥원인(ADC비트=7, 풀스케일시그마=2.5, AFE입력rmsV=0.067, 인터리빙=1)
    ok(하나["지배"] == "비교기 재생" and b["지배"] == "양자화",
       f"인터리빙 1 이면 감도 {하나['비교기감도uV'] / 1e3:.0f} mV 로 **비교기가** 바닥을 "
       f"정하고, {b['인터리빙']}-way 면 **양자화가** 정한다 -- "
       f"'양자화가 바닥을 정한다' 는 인터리빙 조건이 붙는 문장이다")

print("[다 -- Pelgrom 면적 법칙]")
p = afespice.면적별오프셋(짝들=((20.0, 0.5, 4), (80.0, 0.5, 4)), 씨수=12)
ok(p["판정"] == serdes.PASS, f"면적 쓸기가 돈다 ({p.get('왜', '')[:60]})")
if p["판정"] == serdes.PASS:
    작, 큰 = p["줄"][0], p["줄"][1]
    ok(큰["시그마mV"] < 작["시그마mV"],
       f"면적 {작['면적um2']:.0f} -> {큰['면적um2']:.0f} um2 에서 "
       f"sigma {작['시그마mV']:.2f} -> {큰['시그마mV']:.2f} mV 로 준다")
    비 = 큰["시그마mV"] / max(큰["예측시그마mV"], 1e-9)
    ok(0.6 < 비 < 1.7,
       f"1/sqrt(면적) 예측 {큰['예측시그마mV']:.2f} mV 대비 {비:.2f}배 -- "
       f"면적 법칙이 선다")

print("[라 -- CML 드라이버의 에지 (serdes.슬루 의 S)]")
c = afespice.cml(CL=60.0)
ok(c["판정"] == serdes.PASS, f"CML 과도해석이 돈다 ({c.get('왜', '')[:60]})")
if c["판정"] == serdes.PASS:
    # 이 검사가 붙드는 첫째는 **회로가 자기모순이 아니라는 것**이다. 앞판 세 번이
    # 다 여기서 무너졌다 -- 꼬리 노드가 -0.337 V 로 내려갔다.
    ok(c["꼬리최소V"] > 0.1,
       f"꼬리 노드 최소 {c['꼬리최소V']:.3f} V > 0 -- 전류원이 실현 가능한 전류만 "
       f"요구한다(앞판은 -0.337 V 였다)")
    # 스윙은 **꼬리에 따로 단 0V 원**으로 잰 전류와 맞아야 한다 -- KCL 이 다른 길로
    # 한 번 더 닫힌다. 창 전체 MAX/MIN 으로 읽으면 Cgd 스파이크 때문에 1.31 이 나왔다.
    ok(0.95 < c["스윙_IR비"] < 1.05,
       f"단일단 스윙 {c['단일단스윙V'] * 1e3:.1f} mV = I·R_eff "
       f"({c['꼬리전류평균A'] * 1e3:.2f} mA × {c['R_eff옴']:.0f} Ω) 의 "
       f"{c['스윙_IR비']:.3f}배 -- 자기모순이 없다")
    ok(c["상승UI"] < 0.3,
       f"20-80% 에지 {c['상승s'] * 1e12:.2f} ps = {c['상승UI']:.3f} UI -- "
       f"슬루가 UI 를 먹지 않는다")
    # **닫힌 꼴이 자기 영역에서 맞나**: C_L 이 지배하면 tau = R_eff·C_L 이라야 한다
    큰 = afespice.cml(CL=500.0)
    if 큰["판정"] == serdes.PASS:
        예 = 큰["R_eff옴"] * 500e-15
        ok(0.9 < 큰["tau_s"] / 예 < 1.1,
           f"C_L=500 fF 에서 tau {큰['tau_s'] * 1e12:.2f} ps vs R_eff·C_L "
           f"{예 * 1e12:.2f} ps -- **닫힌 꼴은 자기 영역에서 정확하다**")
        ok(c["tau_s"] > 큰["R_eff옴"] * 60e-15,
           f"C_L=60 fF 에서는 tau {c['tau_s'] * 1e12:.2f} ps 가 R_eff·C_L "
           f"{큰['R_eff옴'] * 60e-15 * 1e12:.2f} ps 보다 크다 -- **차동쌍 스위칭 바닥**이 "
           f"남는다(닫힌 꼴이 안 적은 항)")
    ok(c["S"] > 10 * 0.05,
       f"논문이 쓴 가장 순한 S=0.05 보다도 {c['S'] / 0.05:.0f}배 크다. S=0.05 는 "
       f"C_L = {c['표본s'] / 0.05 / c['R_eff옴'] * 1e12:.1f} pF 라는 뜻이고 "
       f"진짜 패드·ESD 는 0.1~0.3 pF 다 -- **그 쓸기는 드라이버의 값이 아니라 "
       f"표를 깨려면 어디까지 가야 하는가다**")

print("[마 -- StrongARM 재생: 지수인가, tau = C/gm 인가]")
a = afespice.strongarm(dV들=(0.4, 0.1, 0.02, 5e-3, 1e-3))
ok(a["판정"] == serdes.PASS, f"래치 쓸기가 돈다 ({a.get('왜', '')[:60]})")
if a["판정"] == serdes.PASS:
    # 로그 법칙이 서는 것 자체가 "재생이 지수다" 의 증거다.
    # 기준은 tau 가 아니라 **쓸기가 만든 폭**이다 -- 로그 법칙이 그 폭의 몇 %를
    # 못 담나를 본다. tau 로 재면 점 수에 따라 문턱이 흔들린다(5점에서 10.7%, 11점에서
    # 8.9% -- 같은 곡선인데 판정이 갈렸다).
    ok(a["잔차비"] < 0.05,
       f"t_해결 = t0 + tau·ln(1/dV) 가 {a['쓸기배수']:.0f}배 쓸기가 만든 폭 "
       f"{a['해결폭_s'] * 1e12:.0f} ps 의 {a['잔차비'] * 100:.1f}% 만 못 담는다 "
       f"(잔차 rms {a['잔차rms_s'] * 1e12:.2f} ps) -- **재생이 지수다**")
    ok(5e-12 < a["tau_s"] < 40e-12,
       f"tau = {a['tau_s'] * 1e12:.2f} ps")
    극 = afespice.래치극점()
    ok(극["판정"] == serdes.PASS, f"교차결합단 AC 가 돈다 ({극.get('왜', '')[:60]})")
    if 극["판정"] == serdes.PASS:
        비 = 극["tau_C_gm_s"] / a["tau_s"]
        ok(0.7 < 비 < 1.4,
           f"tau = C/gm = {극['C_F'] * 1e15:.1f} fF / {극['gm_S'] * 1e3:.2f} mS = "
           f"{극['tau_C_gm_s'] * 1e12:.2f} ps 가 실측의 {비:.2f}배 -- **닫힌 꼴은 맞다**")
        ok(극["C_F"] > 5 * 2e-15,
           f"고리가 지는 C 는 {극['C_F'] * 1e15:.1f} fF 로 밖에 단 짐 2 fF 의 "
           f"{극['C_F'] / 2e-15:.0f}배 -- **C_L 에 게이트 용량을 안 넣으면 tau 가 "
           f"그만큼 작게 나온다**(afe.strongarm 의 기본값이 그랬다)")
    # 그리고 그 tau 가 §17.2 의 바닥 이야기를 어떻게 바꾸나
    ok(a["필요인터리빙"] >= 2,
       f"ADC LSB(2,617 uV)를 한 UI 안에 못 푼다 -- 감도 {a['감도V'] * 1e3:.0f} mV, "
       f"**{a['필요인터리빙']}-way 이상 인터리빙해야** '양자화가 바닥을 정한다' 가 선다")

print()
if FAIL_목록:
    print(f"실패 {len(FAIL_목록)}개")
    for m in FAIL_목록:
        print("  - " + m)
    sys.exit(1)
print("전부 통과")
