"""**닫힌 꼴이 시뮬레이터와 맞는가.** 몬테카를로는 틀려도 그럴듯하다.

이 저장소의 숫자는 전부 시뮬레이션에서 나온다. 배선이 어긋나도 BER 은 여전히 어떤
값을 내고, 그것이 틀렸는지는 눈으로 모른다. 그래서 핵심 숫자마다 **손으로 푼 식**을
옆에 놓고 맞대 본다. 어긋나면 둘 중 하나가 틀렸고, 어느 쪽이든 알아야 한다.

    A1 역압축이 ADC 양자화 잡음을 cosh^4 만큼 키운다 -- 실측 5.3배와 맞나
    A3 압축 뒤 대역제한의 메모리는 sps/beta 표본이다 -- 시뮬레이터의 필터와 맞나
    A4 판정만 보는 구조는 깊이를 늘려도 멈춘다
    A5 찬 칸 수를 푸아송으로 미리 셀 수 있다
    B1 BER 이득을 SNR 여유 dB 로 옮긴다 -- 7.98배는 1e-12 에서 몇 dB 인가
    B2~B6 곱셈기 수 · 칸 수 · 면적 · 누산기 폭
"""
from __future__ import annotations

import math
import sys
from pathlib import Path

import numpy as np

뿌리 = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(뿌리))

import eqrtl
import serdes
import theory

FAIL_목록 = []


def ok(참, 말):
    print(("  통과 " if 참 else "  실패 ") + 말)
    if not 참:
        FAIL_목록.append(말)


print("[B1 -- BER 이득을 dB 로]")
높 = theory.이득을dB로(7.98, 1e-2)
낮 = theory.이득을dB로(7.98, 1e-12)
ok(abs(높["dB"] - 2.27) < 0.1 and abs(낮["dB"] - 0.34) < 0.05,
   f"같은 7.98배가 1e-2 에서 {높['dB']:.2f} dB, 1e-12 에서 {낮['dB']:.2f} dB")
ok(낮["dB"] < 높["dB"] / 4,
   f"낮은 BER 일수록 같은 이득이 훨씬 적은 dB 다 ({높['dB']:.2f} -> {낮['dB']:.2f})")
# 되돌리기: 여유 dB 만큼 진폭을 **키우면** BER 이 G 배 낮아져야 한다.
# (첫 판은 나눴다 -- 이득은 Q 의 인자를 키우는 쪽이다. 6.83 이 나와서 걸렸다.)
from bound import Q역
되 = 1e-12 / serdes.Q(Q역(1e-12) * 10 ** (낮["dB"] / 20.0))
ok(abs(되 - 7.98) / 7.98 < 0.02, f"되돌리면 {되:.2f}배 (7.98 이라야 한다)")

print("[B2 · B3 -- 곱셈기 수와 칸 수]")
ok(theory.곱셈기수("ffe", 탭=11) == 11 and theory.곱셈기수("dfe") == 0
   and theory.곱셈기수("표") == 0 and theory.곱셈기수("mlp", 창=5, 은닉=2) == 12,
   "FFE 11 -> 11 · DFE -> 0 · 표 -> 0 · MLP 5->2 -> 12")
ok(theory.칸수(2, 4) == 256 and theory.칸수(3, 5) == 32768
   and theory.칸수(2, 4, 3) == 2048,
   "칸수 = 2^(창·색인비트 + 특징비트)")

print("[B4 -- 면적은 곱셈기 수에 비례한다(iCE40)]")
m = theory.면적모형([(12, 2336), (48, 9515), (88, 17646), (192, 37371)])
ok(m["판정"] == serdes.PASS and 150 < m["곱셈기당LC"] < 250,
   f"LC = {m['곱셈기당LC']:.1f}·M + {m['고정LC']:.0f}, "
   f"최대 상대오차 {100 * m['최대상대오차']:.1f}% (곱셈기 12~192 에 걸쳐)")

print("[B6 -- 누산기 폭이 RTL 과 같은가]")
# **RTL 에서 읽어 와 맞댄다.** 숫자를 여기 박아 두면 RTL 이 바뀌어도 초록이다.
창, 은닉, XW, WW, FRAC = 5, 2, 7, 7, 4
예 = theory.누산기폭(XW, WW, 창, FRAC, 은닉)
ZW = XW + WW + eqrtl.주소폭(창 + 1)
HW = FRAC + 2
YW = HW + WW + eqrtl.주소폭(은닉 + 1)
ok(예["W_z"] == ZW and 예["W_h"] == HW and 예["W_u"] == YW,
   f"W_z {예['W_z']}={ZW} · W_h {예['W_h']}={HW} · W_u {예['W_u']}={YW}")

print("[A3 -- 압축 뒤 필터의 메모리 길이]")
for 베타 in (1.0, 0.5, 0.35, 0.25):
    예 = theory.필터메모리(베타, 8)
    실 = max(3, int(round(8 / 베타)))          # `serdes.링크` 가 세우는 그 길이
    ok(예["지지표본"] == 실,
       f"beta={베타}: 지지 {예['지지표본']}표본 = {예['지지UI']:.2f} UI "
       f"({예['영역']})")
ok(theory.필터메모리(0.35, 8)["영역"] == "표본 색인 표의 자리"
   and theory.필터메모리(1.0, 8)["영역"] == "메모리 없음"
   and theory.필터메모리(0.2, 8)["영역"].startswith("창 밖"),
   "세 영역이 실측된 창(beta=0.35 에서만 8/8 씨)과 같은 자리를 가리킨다")

print("[A1 -- 역압축이 양자화 잡음을 키운다]")
g = theory.역압축_잡음이득(1.0)
ok(abs(g["판정자리이득"] - math.cosh(1.0) ** 2) < 1e-9 and g["판정자리이득"] > 2.0,
   f"판정 자리(|r|=rms)에서 진폭 이득 cosh^2(1.0) = {g['판정자리이득']:.2f}배 "
   f"({g['dB']:.1f} dB)")
ok(g["꼬리평균이득"] > 50 * g["판정자리이득"],
   f"꼬리 평균 E[cosh^4] = {g['꼬리평균이득']:.0f} 은 판정 자리 값보다 훨씬 크다 "
   f"-- **평균을 여기서 잡으면 안 된다**(첫 판이 그래서 16 dB 를 냈다)")
예 = theory.역압축_BER예측(세기=1.0, ADC비트=7, 풀스케일시그마=2.5, SNRdB=30.0,
                     기준BER=6.5e-4)
ok(2.0 < 예["예측배수"] < 15.0,
   f"ADC 7비트에서 예측 벌점 {예['예측배수']:.1f}배 (실측 5.3배)")
얇 = theory.역압축_BER예측(세기=1.0, ADC비트=10, 풀스케일시그마=2.5, SNRdB=30.0,
                     기준BER=6.5e-4)
ok(얇["예측배수"] < 예["예측배수"] / 2,
   f"ADC 를 10비트로 올리면 벌점이 {얇['예측배수']:.2f}배로 준다 "
   f"-- 실측 바닥 쓸기와 같은 방향이다")

print("[A5 -- 찬 칸을 미리 센다]")
for 창, 비트 in ((2, 4), (2, 5), (3, 4)):
    r = serdes.링크(비트수=400000, 손실dB=25.0, SNRdB=30.0, sps=8, ADC비트=7,
                  압축=1.0, 압축뒤대역=0.35, 역압축=True, FFE탭=11,
                  표본표창=창, 표본표비트=비트, 씨=0)
    끝 = int(len(r["표본"]) * 0.3)
    _, 주소, _ = serdes.표본색인표학습(r["표본"], r["비트"].astype(float), 창, 비트, 끝)
    p = theory.찬칸예측(주소, 끝, 1 << (창 * 비트))
    어긋 = abs(p["기대찬칸"] - p["실제찬칸"]) / max(p["실제찬칸"], 1)
    ok(어긋 < 0.05,
       f"표{창}x{비트}({p['칸수']}칸): 예측 {p['기대찬칸']:.0f} vs 실제 "
       f"{p['실제찬칸']} -- {100 * 어긋:.1f}%")
# 표본 복잡도는 칸 수에 **선형**이라야 한다
ok(abs(theory.필요표본수(1024) / theory.필요표본수(256) - 4.0) < 1e-9,
   "필요 표본수가 칸 수에 선형이다 -- 칸이 2^(창·비트) 이므로 **창에 지수**다")

print()
if FAIL_목록:
    print(f"실패 {len(FAIL_목록)}개")
    for m in FAIL_목록:
        print("  - " + m)
    sys.exit(1)
print("전부 통과")
