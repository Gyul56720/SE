"""**관문이 실제로 잡는가** -- 틀린 답을 일부러 만들어 놓고 걸리는지 본다.

    python3 tests/test_coin_gate.py

제일 중요한 검사는 **C002(다시 셈)** 다. 나머지 관문은 꼬리표를 보지만 C002 는 값을
본다 -- 원장의 수를 손으로 바꿔치기해 놓고 잡는지 본다(`brief` 의 B004, `law/mutate.py`
의 RED/GREEN 과 같은 자리). **어긋남 0 은 관문이 좋아서일 수도 있고 아무것도 못
잡아서일 수도 있다.**
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "tests"))

import _coin_fixture as FX                                            # noqa: E402
from coin import event as EV                                          # noqa: E402
from coin import gate as GT                                           # noqa: E402
from coin import regime as RG                                         # noqa: E402

fails = []


def ok(cond, msg):
    print(("  OK   " if cond else "  실패 ") + msg)
    if not cond:
        fails.append(msg)


def 급(res, 규칙):
    return [v.규칙 for v in res.위반들 if v.급 == "hard"].count(규칙)


날 = FX.사건날()
사건 = FX.사건(날)
c = FX.계열(심을날=날, 효과=0.09)
잰것 = EV.전부({"BTC": c}, 사건, 지평들=(7,), 유형들=("규제금지",), 판수=600)
원장 = {"잰것": 잰것, "사건수": len(사건)}
계열들 = {"BTC": c}
r = 잰것[0]

바른 = (f"규제금지 유형 뉴스 뒤 D+7 을 보면 관측 중앙값 {r['관측중앙']*100:+.2f}% 인데, "
        f"아무 날이나 골랐을 때의 기저율이 {r['널중앙']*100:+.2f}% 라 "
        f"초과는 {r['초과']*100:+.2f}%p 로 상승 쪽이다. 표본 n={r['n']} "
        f"(겹치지 않는 것 {r['유효n']}), 승률 {r['승률']*100:.0f}%. "
        f"이번 실행에서 {r['시험수']}번 쟀고 BH 보정을 걸었다.")

res = GT.검사(바른, 원장, 계열들)
ok(res.통과(), f"제대로 쓴 답은 통과한다 (hard {len(res.hard)})")
ok(res.인용 == ["규제금지|BTC|D+7"], "무엇을 짚었는지 안다")

# ---------------------------------------------------------------- 하나씩 망가뜨린다
못된 = {
    "C001": 바른.replace(f"{r['관측중앙']*100:+.2f}%", "+99.99%"),
    "C004": (f"규제금지 D+7 수익률 중앙값 {r['관측중앙']*100:+.2f}%. "
             f"표본 {r['n']}건. {r['시험수']}번 쟀다."),
    "C003": 바른.replace(f"n={r['n']}", "표본은 충분하다"),
    "C006": 바른 + " 다음에도 반드시 오른다.",
    "C012": 바른 + " 지금 사세요.",
    "C010": 바른.replace("상승 쪽이다", "하락 쪽이다"),
}
for 규칙, 답 in 못된.items():
    res = GT.검사(답, 원장, 계열들)
    ok(급(res, 규칙) >= 1 and not res.통과(),
       f"{규칙} {GT.규칙표[규칙][0]:<10} 을 잡는다")

# ---------------------------------------------------------------- C002 바꿔치기
망 = {"잰것": [dict(r)], "사건수": len(사건)}
망["잰것"][0]["관측중앙"] = r["관측중앙"] + 0.05          # 값만 조용히 바꾼다
res = GT.검사(바른.replace(f"{r['관측중앙']*100:+.2f}%",
                          f"{(r['관측중앙']+0.05)*100:+.2f}%"), 망, 계열들)
ok(급(res, "C002") >= 1,
   "**C002: 원장의 값을 바꿔치기하면 다시 세서 잡는다** (재는 자리가 조용히 틀린 경우)")

망2 = {"잰것": [dict(r)], "사건수": len(사건)}
망2["잰것"][0]["초과"] = r["초과"] + 0.03
res = GT.검사(바른, 망2, 계열들)
ok(급(res, "C002") >= 1, "C002: 초과를 바꿔치기해도 잡는다")

res = GT.검사(바른, 원장, None)                          # 가격 원장 없이
ok(any(v.규칙 == "C002" and v.급 == "미검증" for v in res.위반들),
   "가격 원장이 없으면 C002 는 **미검증** -- 통과가 아니다")

# ---------------------------------------------------------------- C014 · C015
좋장 = {"BTC": RG.장세(c)}
나쁜장 = {"BTC": dict(RG.장세(c), 나쁨=True)}
res = GT.검사(바른, 원장, 계열들, 장세=나쁜장)
ok(급(res, "C014") >= 1,
   "C014: 장세가 아래 칸인데 안 밝히고 오름을 말하면 기각")
res = GT.검사(바른 + " 장세는 자기 역사의 아래 칸이다.", 원장, 계열들, 장세=나쁜장)
ok(급(res, "C014") == 0, "C014: 장세를 밝히면 통과")

res = GT.검사(바른 + " 고래가 움직였다.", 원장, 계열들, 흐름={})
ok(급(res, "C015") >= 1, "C015: 지갑 자료가 없는데 '고래' 라고 하면 기각")
res = GT.검사(바른 + " 거래량이 자기 역사 상위였다.", 원장, 계열들, 흐름={})
ok(급(res, "C015") == 0, "C015: 거래량이라고 바르게 부르면 통과")
res = GT.검사(바른 + " 고래 이체가 늘었다.", 원장, 계열들,
             흐름={"대형이체": {"백분위": 0.97, "값": 12, "날": "2026-09-09", "n": 300}})
ok(급(res, "C015") == 0, "C015: 지갑 자료가 실제로 있으면 '고래' 라고 해도 된다")

# ---------------------------------------------------------------- 미검증
적 = EV.흔들기(c, 사건[:5], "해킹유출", "BTC", 7, 판수=200)
원장2 = {"잰것": 잰것 + [적], "사건수": len(사건)}
res = GT.검사("해킹유출 뉴스 뒤 D+7 은 오른다.", 원장2, 계열들)
ok(급(res, "C003") >= 1, "미검증인 것을 근거로 단정하면 기각")
res = GT.검사("해킹유출 뉴스 뒤 D+7 은 표본이 모자라 못 쟀다.", 원장2, 계열들)
ok(급(res, "C003") == 0, "못 쟀다고 적으면 통과")

# ---------------------------------------------------------------- 되먹임
res = GT.검사(못된["C001"], 원장, 계열들)
되 = GT.되먹임(res)
ok(되 and "99.99" in 되, "되먹임이 어긋난 자리를 짚는다")
ok(not re.search(r"C0\d\d", 되),
   "**되먹임에 관문 이름이 안 샌다** -- 알려 주면 관문이 사양서가 된다")
ok("hard" not in 되 and "soft" not in 되, "급 이름도 안 샌다")

print()
print(f"실패 {len(fails)}개" if fails else "전부 통과")
raise SystemExit(1 if fails else 0)
