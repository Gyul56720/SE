"""**관문이 진짜 잡는가. 그리고 성한 글에 빨간불을 안 켜는가.**

    python3 tests/test_jaso_gate.py

이 검사가 붙드는 것은 **두 방향이다.**

    RED    결함을 심으면 반드시 잡는다      -- `jaso/mutate.py` 가 20개를 심는다
    GREEN  성한 자소서에는 hard 가 0 이다   -- 과잉 기각하는 심판은 맞는 답도 버린다

한쪽만 보면 뜻이 없다. 다 잡는 관문은 `return ["위반"]` 으로도 만들 수 있고, 조용한
관문은 `return []` 으로도 만들 수 있다. **둘을 같이 봐야 판정이 판정이 된다**
(`seek/` 가 대조군 `P3` 를 둔 자리와 같다).

여기에 실측으로 얻은 회귀 못 넷이 박혀 있다. 넷 다 **성한 글에 빨간불이 켜진** 것이고,
그중 둘은 같은 고장으로 **지어낸 수를 놓치기까지** 했다 -- 관문이 낼 수 있는 최악의 짝.
"""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from jaso import gate as GT                                        # noqa: E402
from jaso import ledger as LG                                      # noqa: E402
from jaso import mutate as MU                                      # noqa: E402
from jaso import swap as SW                                        # noqa: E402
from jaso import wording as WD                                     # noqa: E402

fails = []


def ok(cond, msg):
    print(("  OK   " if cond else "  실패 ") + msg)
    if not cond:
        fails.append(msg)


표본 = (ROOT / "tests" / "fixtures" / "자소서_성한것.md").read_text(encoding="utf-8")
L = LG.읽기(str(ROOT / "jaso" / "보기.json"))


def 검사(글, 원장=None):
    vs, _, _ = GT.검사(GT.읽기(글), L if 원장 is None else 원장)
    return vs


def 규칙(vs, name, 등급=None):
    return [v for v in vs if v.규칙 == name and (등급 is None or v.등급 == 등급)]


print("── GREEN -- 성한 자소서에 hard 가 없다 ─────────────────")
성한것 = 검사(표본)
hard = [v for v in 성한것 if v.등급 == "hard"]
ok(not hard, f"hard 0건 (난 것: {[str(v) for v in hard]})")
ok(L and len(L) == 3, "원장이 살아 있다 -- 안 그러면 위 초록불은 미검증이다")


print("\n── RED -- 심으면 잡는다 (`jaso/mutate.py`) ──────────────")
tally = MU.돌리기(표본, L)
심 = sum(t["심음"] for t in tally.values())
잡 = sum(t["잡음"] for t in tally.values())
ok(심 >= 12, f"심을 자리가 {심}개 있었다")
ok(심 == 잡, f"심은 {심}개를 {잡}개 잡았다 (놓친 것 {심 - 잡}개)")
for 이름, _, _ in MU.돌연변이들:
    t = tally[이름]
    ok(not t["심음"] or t["잡음"],
       f"{이름}: {t['심음']}개 심어 {t['잡음']}개 잡음"
       + ("  <- **이 관문은 지금 눈이 없다**" if t["심음"] and not t["잡음"] else ""))


print("\n── J002 -- 지어낸 수를 잡고 성한 수는 안 잡는다 ────────")
지어냄 = 표본.replace("클릭률이 2.1%에서 2.6%로 올랐습니다",
                    "매출을 30% 향상시켰습니다")
ok(규칙(검사(지어냄), "J002", "hard"),
   "**'매출을 30% 향상' 을 hard 로 잡는다** -- F1(수치 창작)이 잡히는 자리")
ok(not 규칙(검사(표본), "J002"),
   "(대조군) 원장에서 온 2.1% · 2.6% · 35분 · 4분 · 24000명 · 2주는 안 잡는다")
안잰원장 = LG.읽기([{**{"id": "P1", "이름": "추천 개편", "곳": "무봉테크",
                    "언제": ["2025-03", "2025-08"], "역할": "참여",
                    "잰것": [{"무엇": "클릭률", "전": "2.1", "후": "2.6",
                            "단위": "%", "어떻게": ""}], "증빙": "x"}}])
ok(규칙(검사(표본, 안잰원장), "J002", "hard"),
   "**잰 방법이 안 적힌 값은 원장에 있어도 hard** -- 안 잰 수는 못 쓴다(E004 의 짝)")


print("\n── J004 -- '참여' 를 '주도' 로 올려 쓰면 잡는다 ─────────")
올려씀 = 표본.replace("사내 추천 시스템 개편에 참여하며",
                    "사내 추천 시스템 개편을 주도하며")
ok(규칙(검사(올려씀), "J004", "hard"),
   "원장이 `참여` 인 항목에 `주도` 를 쓰면 hard -- 면접에서 다시 물어보는 자리다")
ok(not 규칙(검사(표본), "J004"),
   "(대조군) 원장이 `주도` 인 스터디를 '주도하며' 라고 쓴 것은 안 잡는다")


print("\n── J005 -- 글자 수는 원장이 없어도 판정된다 ─────────────")
넘침 = 표본.replace("(700자 이내)", "(200자 이내)")
ok(규칙(검사(넘침, LG.원장()), "J005", "hard"), "상한을 넘기면 원장 없이도 hard")
ok(not 규칙(검사(표본), "J005", "hard"), "(대조군) 안 넘기면 조용하다")


print("\n── J006 -- **어림으로 기각하지 않는다** (회귀 못) ────────")
ok(not 규칙(검사(표본), "J006", "hard"),
   "성한 답변이 요구 하나를 표지말로 못 맞혀도 hard 가 아니다 -- 실측: '어려웠던 "
   "경험' 을 '문제를 만났습니다' 로 쓴 성한 답변이 기각됐었다")
딴글 = 표본.split("## 2.")[0].replace(
    표본.split("(700자 이내)")[1].split("## 2.")[0],
    "\n\n저는 성실합니다. 뽑아 주시면 열심히 하겠습니다.\n\n")
ok(규칙(검사(딴글), "J006", "hard"),
   "**요구가 하나도 안 닿으면 hard** -- 어림이 아니라 사실이므로 이것만 남긴다")


print("\n── J008 -- **인원은 안 본다. 그렇게 적어 두었다** ────────")
ok(not 규칙(검사(표본), "J008"),
   "실측: 한 문단의 '24000명'(표본 크기)과 '4명'(팀 크기)을 모순으로 봤었다 -- "
   "**둘을 가르려면 뜻을 읽어야 하고 이 관문은 뜻을 안 읽는다**")
어긋남 = 표본.replace("파이프라인과 지표 쪽을 맡았고", "12개월 동안 맡았고")
ok(규칙(검사(어긋남), "J003", "hard"),
   "**기간은 항목마다 하나뿐이라 뜻을 안 읽어도 갈린다** -- 6개월짜리를 12개월로 "
   "적으면 J003 이 잡는다")
ok(not 규칙(검사(표본.replace("파이프라인과 지표 쪽을 맡았고", "6개월 동안 맡았고")),
          "J003"),
   "(대조군) 원장과 같은 6개월이라고 적은 것은 안 잡는다")


print("\n── P001 -- 치환 검사 ──────────────────────────────────")
일반론 = """---
회사: "누리하나"
---

## 1. 지원 동기를 기술하시오. (500자)

저는 귀사의 인재상에 부합하는 인재입니다. 어릴 적부터 무엇이든 최선을 다하는
성격이었고, 맡은 일은 끝까지 해내 왔습니다.

앞으로도 열정을 가지고 회사와 함께 성장하고 싶습니다.
"""
ok(규칙(검사(일반론), "P001", "hard"),
   "**앵커가 하나도 없는 답변은 hard** -- 회사 이름만 바꾸면 어디에나 들어간다")
ok(not 규칙(검사(표본), "P001", "hard"),
   "(대조군) 원장에서 온 것이 박힌 답변은 안 잡는다")
ok(not 규칙(검사(일반론, LG.원장()), "P001"),
   "**원장이 비면 P001 은 위반이 아니라 미검증이다** -- 앵커가 없어서 걸린 것인지 "
   "원장이 없어서 못 찾은 것인지 안 가르면 그 판정은 거짓말이다")
_, _, 미검증 = GT.검사(GT.읽기(일반론), LG.원장())
ok(미검증 > 0, f"원장이 비면 미검증이 {미검증}건으로 셈에 남는다 -- 조용히 안 사라진다")


print("\n── P 계열 -- 설득력 ───────────────────────────────────")
ok(규칙(검사(일반론), "P003", "soft"), "P003 상투구를 센다")
ok(규칙(검사(일반론), "P002", "soft"),
   "P002 근거 없는 자기 신고 -- 같은 문단에 원장에서 온 것이 하나도 없다")
ok(not 규칙(검사(표본), "P003"), "(대조군) 성한 글에는 상투구가 없다")


print("\n── 자가 고장났던 자리 (회귀 못) ────────────────────────")
ok([x[:2] for x in WD.성과수들("클릭률을 2.1%에서 2.6%로 개선했습니다")]
   == [("2.1", "%"), ("2.6", "%")],
   "**소수점을 문장 끝으로 안 읽는다** -- 실측: `2`/`1%에서 2`/`6%로` 로 갈려서 "
   "성한 문장이 J002 위반이 됐었다")
ok(WD.성과수들("참석 인원이 6명에서 19명으로 늘었습니다"),
   "**활용형 `늘었` 를 안 빠뜨린다** -- 실측: 빠뜨려서 그 문장의 수를 아예 안 "
   "견주었고 J007 은 '결과가 없다' 고 잘못 보고했다")
ok(WD.성과수들("클릭률이 2.1%에서 2.6%로 올랐습니다"), "활용형 `올랐` 도 본다")
ok(not WD.성과수들("저는 3학년 때 2025년에 지원했습니다"),
   "(대조군) 성과 동사가 없는 문장의 수는 값 주장이 아니다")


print("\n── 문단이 어느 항목을 말하는지 -- 흔들리지 않는다 ───────")
문단 = "무봉테크에서 클릭률을 2.1%에서 2.6%로 올렸습니다"
가리킨것 = SW.가리키는것(문단, L)
ok(가리킨것 is not None and 가리킨것.id == "P-2025-추천",
   "앵커가 제일 많은 항목을 가리킨다")
ok(SW.가리키는것("저는 열정적인 사람입니다", L) is None,
   "(대조군) 앵커가 없으면 아무것도 안 가리킨다 -- J003·J004 가 조용해진다")

print()
print(f"실패 {len(fails)}건" if fails else "전부 통과")
raise SystemExit(1 if fails else 0)
