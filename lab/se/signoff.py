# -*- coding: utf-8 -*-
"""07 사인오프 -- 배선된 기하에서 기생을 꺼내 **다시** 잰다.

T17.2 가 말한 그 표류를 여기서 실제로 잰다: 합성 직후의 슬랙과 배선 뒤의
슬랙이 얼마나 다른가.  같은 끝점에 대해 두 수를 나란히 놓는 것이 핵심이다 --
"배선 뒤에도 통과했다" 가 아니라 **얼마나 움직였나**가 흐름이 수렴하는지를
말해 주므로.

여기서 보는 것
    타이밍   배선 RC 를 넣고 재STA.  끝점별 슬랙 표류
    밀도     칸마다 금속이 얼마나 찼나.  창 밖이면 채움(fill)이 필요하다
    전원     T18 의 IR/EM 판정을 그대로 받아 적는다
"""
from __future__ import annotations

import sta


class 사인오프:
    def __init__(self, nl, 배치, fp, 배선, 주기=10.0, 클럭스큐=0.0,
                 밀도창=(0.20, 0.70)):
        self.nl, self.p, self.fp, self.r = nl, 배치, fp, 배선
        self.주기, self.클럭스큐 = 주기, 클럭스큐
        self.밀도창 = 밀도창

    # ----------------------------------------------------------------
    def 전후(self):
        """배선 전/후 STA 를 둘 다 돌리고 끝점별로 맞대어 본다."""
        전 = sta.분석기(self.nl, 주기=self.주기).풀기()
        지연, 부하 = self.r.지연함수()
        후분석 = sta.분석기(self.nl, 주기=self.주기, 배선지연=지연,
                        배선부하=부하, 클럭스큐=self.클럭스큐)
        후 = 후분석.풀기()
        전맵 = {k: s for s, k, *_ in 전.끝점들}
        후맵 = {k: s for s, k, *_ in 후.끝점들}
        공통 = sorted(set(전맵) & set(후맵))
        표류 = [(후맵[k] - 전맵[k], k, 전맵[k], 후맵[k]) for k in 공통]
        표류.sort()
        return 전, 후, 표류, 후분석

    # ----------------------------------------------------------------
    def 밀도(self):
        """칸마다 금속이 찬 비율.  배선 수요를 공급으로 나눈 것이 곧 밀도다."""
        d = self.r.수요()
        총 = self.r.NX * self.r.NY
        값 = [d.get((i, j), 0) / self.r.공급
              for i in range(self.r.NX) for j in range(self.r.NY)]
        낮, 높 = self.밀도창
        return {
            "칸": 총,
            "평균": round(sum(값) / 총, 4),
            "최대": round(max(값), 4),
            "최소": round(min(값), 4),
            "창_아래_칸": sum(1 for v in 값 if v < 낮),
            "창_위_칸": sum(1 for v in 값 if v > 높),
            "채움이_필요한_칸": sum(1 for v in 값 if v < 낮),
        }

    # ----------------------------------------------------------------
    def 돌리기(self):
        전, 후, 표류, _ = self.전후()
        최악표류 = 표류[0] if 표류 else (0.0, None, 0, 0)
        평균표류 = sum(t[0] for t in 표류) / len(표류) if 표류 else 0.0
        return {
            "배선전": 전.요약(),
            "배선후": 후.요약(),
            "표류_평균_ps": round(평균표류 * 1e3, 2),
            "표류_최악_ps": round(최악표류[0] * 1e3, 2),
            "표류_최악_끝점": (최악표류[1][0] + "/" + 최악표류[1][1])
            if 최악표류[1] else None,
            "Fmax_떨어진비": round(
                1 - (전.주기 - 전.최악슬랙) / (후.주기 - 후.최악슬랙), 4)
            if (후.주기 - 후.최악슬랙) > 0 else None,
            "밀도": self.밀도(),
            "전원": {"무는것": self.fp.무는것(),
                   "그리드해_mV": round(self.fp.그리드풀기() * 1e3, 4),
                   "IR예산_mV": round(self.fp.IR예산 * 1e3, 2)},
        }
