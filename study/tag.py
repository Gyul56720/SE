"""**태그는 모델이 붙이고, 흩어지지 않게 막는 것은 코드가 한다.**

태그를 사람이 붙이면 안 붙인다. 그래서 모델에게 맡긴다 -- `law/` 가 조문에서 요건을
뽑게 하고 쟁점은 코드가 도출하는 것과 같은 분업이다.

## 그런데 자유롭게 붙이면 **취약점이 영영 안 나온다**

이것이 이 파일이 있는 진짜 까닭이다. 모델은 문제마다 그럴듯한 이름을 새로 짓는다.

    조건부확률 · 조건부 확률 · 조건부  · 베이즈 · 확률의 곱셈정리 ...

사람 눈에는 한 덩어리인데 **코드에는 다섯 태그**다. 그러면 둘이 동시에 일어난다.

    1. 태그마다 문제가 두세 개씩만 남는다 -> 다 `못잼`
    2. 태그 수 m 이 커져 Holm 문턱이 조여진다 -> 남은 것도 `못잼`

**약점을 못 찾는 쪽으로만 기운다.** 그리고 화면은 "약한 데가 없다" 로 보인다 --
못 잰 것을 잘하는 것으로 읽게 되는, 이 저장소가 계속 막아 온 그 자리다.

## 그래서 셋을 건다

    1. **이미 쓰이는 태그를 먼저 보여 준다.** 새 이름은 꼭 필요할 때만
    2. **닮으면 묶는다**(`묶기`, 문턱 0.72). 사용자 지시: "유사도 높으면 묶어버려."
       한때 글자가 똑같을 때만 묶고 나머지는 짚기만 했는데, 그러면 `조건부확률` ·
       `조건부` · `베이즈` 가 따로 남아 m 이 커지고 **7/8 을 틀린 진짜 약점이
       `평범` 으로 나왔다**(실측). 안 묶는 쪽이 안전해 보였지만 못 찾는 쪽으로만 기운다
    3. **묶은 것은 늘 화면에 적는다.** 묶는 것은 짐작이므로, 조용히 하면 화면의 이름이
       모델이 쓴 것과 달라지고 읽는 쪽이 못 알아챈다
    4. **문제당 태그 수를 묶는다.** 하나에 태그를 여섯 개 달면 m 만 커진다

## 태그만이 아니다 -- **오답 사유도 같은 것으로 묶는다**

취약점이 `확률` 이면 "특정 과목에 약하다" 밖에 안 된다. 사용자가 요구한 것은 훨씬
좁은 것이다 -- **"조건부확률에서 분모를 P(A) 가 아니라 전체로 잡는다".** 그것은
문제의 태그가 아니라 **틀린 까닭**이고, 까닭도 모델이 말로 적으므로 태그와 똑같이
흩어진다. 그래서 `묶기` 를 두 축에 다 쓴다(`study/weak.py 축별`).

## 호출은 여기서 안 한다

`brain/route.py` · `reason/ask.py` 와 같다 -- `--프롬프트` 로 줄 것만 내고, 모델이
답한 것을 `--태그 답.json` 으로 도로 받는다. 여기서 부르면 검사가 망을 타게 된다.
"""
from __future__ import annotations

import difflib
import json
import re
import unicodedata

태그상한 = 3          # 문제 하나에 이보다 많이 안 단다
붙임최소 = 2          # 이보다 짧은 태그는 안 받는다 (한 글자짜리는 뭉개진다)


def 고르게(t: str) -> str:
    """견줄 수 있게 고른다. **뜻은 안 본다.**"""
    t = unicodedata.normalize("NFKC", str(t or "")).strip()
    return re.sub(r"[\s_\-·,/()\[\]]+", "", t).lower()


def 모으기(새태그: str, 이미: list) -> str:
    """이미 쓰이는 태그 중 **글자로 같은 것**이 있으면 그 이름으로 돌려준다.

    ## 부분문자열로 합치다가 층을 무너뜨렸다 (실측 2026-09-09)

    처음에 "한쪽이 다른 쪽에 들어 있으면 짧은 쪽으로 모은다" 고 했다. 그랬더니
    **`조건부확률` 이 `확률` 에 삼켜졌다** -- `확률` 이 `조건부확률` 의 부분문자열이라서.
    같은 규칙이 `이차방정식` 을 `대수` 로는 못 모으면서 `방정식` 으로는 모은다.

    그런데 프롬프트는 **넓은 것과 좁은 것을 같이 달라**고 시킨다(`확률` 다음에
    `조건부`). 그 층이 무너지면 태그가 넓은 것 하나만 남고, 그러면 "확률에 약하다"
    까지만 알 수 있지 **조건부가 문제라는 것은 영영 못 본다.** 취약점을 좁히려고
    만든 자리인데 반대로 넓혀 버린 것이다.

    그래서 **글자가 같을 때만 합친다.** 공백·기호만 다른 것(`조건부 확률` ·
    `조건부확률`)이 실제로 흔한 갈라짐이고, 그것은 짐작 없이 확실하다.
    `베이즈` 같은 딴 이름은 여기서 안 합친다 -- 뜻으로 합치는 것은 짐작이고,
    짐작으로 합친 태그 위에서 취약점 판정이 돈다.

    남은 갈라짐은 두 군데가 맡는다: **프롬프트**가 이미 쓰는 이름을 먼저 보여 주고,
    **`흩어짐()`** 이 새어 나온 것을 화면에 적는다.
    """
    n = 고르게(새태그)
    if not n:
        return ""
    for t in 이미:
        if 고르게(t) == n:
            return t
    return str(새태그).strip()


닮음문턱 = 0.65       # 이보다 닮으면 **한 이름으로 묶는다**
짧은것 = 8            # 고르게() 한 길이가 이 아래면 낱말이 아니라 이름으로 본다

# 뒤에 붙는 토씨·어미. 떼야 `조건부확률에서` 와 `조건부확률의` 가 같은 낱말이 된다.
# **뜻을 보는 것이 아니다** -- 한국어에서 같은 낱말이 어떻게 늘어나는지만 안다.
_꼬리 = ("에서의", "으로써", "으로서", "이라고", "라고", "에서", "에게", "으로", "로써",
        "한다", "된다", "인다", "는다", "ㄴ다", "하는", "되는", "라는", "이나", "거나",
        "부터", "까지", "보다", "만큼", "처럼", "의", "를", "을", "은", "는", "이", "가",
        "에", "로", "과", "와", "도", "만", "다", "음", "함", "됨", "임", "기", "고")


def _줄기(w: str) -> str:
    """낱말에서 꼬리를 뗀다. **두 글자 아래로는 안 깎는다** -- 깎으면 딴 말이 된다."""
    w = 고르게(w)
    for k in _꼬리:
        if len(w) > len(k) + 1 and w.endswith(k):
            return w[: -len(k)]
    return w


def _줄기들(s: str) -> set:
    return {t for t in (_줄기(w) for w in re.split(r"\s+", str(s or "")) ) if len(t) > 1}


def 닮음(a: str, b: str) -> float:
    """0~1. **짧은 이름과 긴 문장을 다른 자로 잰다.**

    ## 글자만 보다가 반대로 묶을 뻔했다 (실측 2026-09-09)

        등비수열 합 공식 자체를 모른다  vs  등차수열 합 공식 자체를 모른다   0.923
        조건부확률에서 분모를 ... 잡는다 vs  조건부확률의 분모를 ... 잡음      0.700

    **묶어야 할 것이 0.70 이고 묶으면 안 되는 것이 0.92 였다.** 글자 거리로는 이 둘을
    영영 못 가른다 -- `등비`/`등차` 는 한 글자 차이인데 그 한 글자가 전부이고, 위쪽
    둘은 절반이 달라도 같은 말이다. 문턱을 어디에 두어도 한쪽이 틀린다.

    그래서 갈랐다.

        짧은 이름(태그)   글자 겹침. `조건부확률`/`조건부 확률` 같은 표기 차이를 문다
        긴 문장(사유)     **낱말 줄기**의 겹침. `등비수열`/`등차수열` 은 다른 낱말이라
                          안 겹치고, 토씨만 다른 것은 겹친다

    잘못 묶으면 **없는 약점이 교안에 실린다.** 안 묶으면 되풀이를 못 본다. 둘 다
    나쁘지만 앞쪽이 더 나쁘다 -- 학생이 멀쩡한 데를 고치러 간다.
    """
    x, y = 고르게(a), 고르게(b)
    if not x or not y:
        return 0.0
    if x == y:
        return 1.0
    if len(x) <= 짧은것 and len(y) <= 짧은것:
        return difflib.SequenceMatcher(None, x, y).ratio()
    ta, tb = _줄기들(a), _줄기들(b)
    if not ta or not tb:
        return difflib.SequenceMatcher(None, x, y).ratio()
    return len(ta & tb) / len(ta | tb)


def 묶기(이름들: list, 문턱: float = 닮음문턱) -> dict:
    """`{원래이름: 대표이름}`. **닮으면 한 이름으로 묶는다.**

    사용자 지시(2026-09-09): "유사도 높으면 묶어버려."

    처음에는 글자가 똑같을 때만 묶고 나머지는 짚기만 했다. 그랬더니 `조건부확률` ·
    `조건부` · `베이즈` 가 따로 남아 태그 수 m 이 커졌고, **7/8 을 틀린 진짜 약점이
    `평범` 으로 나왔다**(실측). 안 묶는 쪽이 더 안전해 보였지만 실제로는 못 찾는
    쪽으로만 기울었다.

    대표는 **자주 나온 것**, 같으면 **짧은 것**으로 고른다 -- 자주 나온 이름이 이미
    쓰이던 이름이고, 짧은 쪽이 넓어서 표본이 크다.

    묶는 것은 짐작이다. 그래서 **무엇을 무엇으로 묶었는지 늘 돌려준다** -- 조용히
    묶으면 화면의 이름이 모델이 쓴 것과 달라지고 읽는 쪽이 못 알아챈다.
    """
    셈: dict = {}
    for t in 이름들:
        t = str(t).strip()
        if t:
            셈[t] = 셈.get(t, 0) + 1
    # 자주 나온 것부터 대표 자리를 잡는다. 같은 수면 **깔끔한 쪽**을 세운다 --
    # 공백·기호가 적은 것. `조건부 확률` 과 `조건부확률` 이 한 번씩이면 뒤엣것이
    # 대표가 되어야 화면이 읽기 좋다(앞엣것이 뽑히던 것을 검사가 잡았다).
    def _지저분(t):
        return sum(1 for c in str(t) if c in " _-·,/()[]")
    차례 = sorted(셈, key=lambda t: (-셈[t], _지저분(t), len(고르게(t)), t))
    대표: list = []
    표: dict = {}
    for t in 차례:
        붙은 = next((r for r in 대표 if 닮음(t, r) >= 문턱), "")
        if 붙은:
            표[t] = 붙은
        else:
            대표.append(t)
            표[t] = t
    return 표


짚기문턱 = 0.45       # 묶기엔 모자라도 **눈에 띄게는 한다**


def 닮은쌍(이름들: list, 아래문턱: float = 짚기문턱,
          위문턱: float = None) -> list:
    """**묶기엔 모자란데 닮은 짝.** `(a, b, 닮음)`. 합치지는 않는다.

    묶는 자(0.65)는 일부러 짜다 -- 잘못 묶으면 **없는 약점이 교안에 실리고** 학생이
    멀쩡한 데를 고치러 간다. 그 대가로 진짜 되풀이를 몇 개 놓친다(실측: `조건부확률에서
    분모를...잡는다` 와 `조건부확률의 분모를...잡음` 이 0.50 이라 안 묶였다).

    놓친 것을 **말은 해 준다.** 안 하면 사용자는 표본이 왜 안 모이는지 모른 채 늘
    `못잼`/`평범` 만 본다. 사람이 보고 같다고 하면 같은 말로 다시 적으면 된다.
    """
    위문턱 = 닮음문턱 if 위문턱 is None else 위문턱
    쌍 = []
    이름들 = [t for t in dict.fromkeys(이름들) if str(t).strip()]
    for i, a in enumerate(이름들):
        for b in 이름들[i + 1:]:
            v = 닮음(a, b)
            if 아래문턱 <= v < 위문턱:
                쌍.append((a, b, round(v, 3)))
    return sorted(쌍, key=lambda x: -x[2])


def 프롬프트(문제들: list, 이미: list = ()) -> str:
    """**모델에게 줄 것.** 검사 이야기가 한 줄도 없다 -- 태그만 붙이게 한다."""
    쓰던 = ", ".join(sorted(이미)) if 이미 else "(아직 없다)"
    목록 = "\n".join(
        f'{{"id": "{q.id}", "문제": {json.dumps(q.말[:300], ensure_ascii=False)}}}'
        for q in 문제들)
    return f"""다음 문제마다 **무엇을 묻는 문제인지** 태그를 달아라.

## 이미 쓰이는 태그 -- **여기 있으면 그대로 쓴다**

{쓰던}

새 이름을 지으면 그 태그에는 문제가 몇 개 안 남는다. 같은 것을 다르게 부르면
(`조건부확률` · `조건부 확률` · `베이즈`) 사람 눈에는 한 덩어리인데 셈에서는
갈라져서, **어느 쪽도 판단할 만큼 안 모인다.** 위 목록에 맞는 것이 있으면 그것을 쓰고,
정말 없을 때만 새로 짓는다.

## 어떻게 다나

  · 문제 하나에 **{태그상한}개까지.** 많이 달수록 갈라진다.
  · 넓은 것부터 좁은 것으로: `확률` 다음에 `조건부`. 좁은 것만 달지 마라.
  · **무엇을 묻는가**로 단다. 어렵다·쉽다·긴 문제 같은 것은 태그가 아니다.
  · 모르겠으면 넓은 것 하나만 단다. 억지로 좁히지 마라.

## 문제

{목록}

## 출력 (JSON 하나만. 다른 말은 붙이지 마라)

{{"태그": {{"문제id": ["넓은것", "좁은것"]}}}}"""


def 읽기(d) -> dict:
    """모델 답 -> `{문제id: [태그]}`. **꼴이 아니면 빈 것이다.**"""
    if isinstance(d, str):
        try:
            d = json.loads(d)
        except json.JSONDecodeError:
            i, j = d.find("{"), d.rfind("}")
            if i < 0 or j <= i:
                return {}
            try:
                d = json.loads(d[i:j + 1])
            except json.JSONDecodeError:
                return {}
    if not isinstance(d, dict):
        return {}
    표 = d.get("태그") if isinstance(d.get("태그"), dict) else d
    if not isinstance(표, dict):
        return {}
    out = {}
    for qid, ts in 표.items():
        if isinstance(ts, str):
            ts = [ts]
        if not isinstance(ts, list):
            continue
        고른 = []
        for t in ts:
            t = str(t).strip()
            if len(고르게(t)) >= 붙임최소 and 고르게(t) not in [고르게(x) for x in 고른]:
                고른.append(t)
        if 고른:
            out[str(qid).strip()] = 고른[:태그상한]
    return out


def 붙이기(n, 표: dict, 덮어쓰기: bool = False) -> dict:
    """공책에 붙인다. `{붙임, 건너뜀, 모은것, 없는id}`.

    **이미 태그가 있으면 안 덮는다**(사람이 붙인 것일 수 있다). `--덮어쓰기` 로만 덮는다.
    """
    이미 = sorted({t for q in n.문제.values() for t in (q.태그 or [])})
    붙임, 건너, 모음, 없는 = 0, 0, {}, []
    # **닮은 것을 미리 묶어 둔다.** 공책에 이미 있는 이름과 이번에 온 이름을 한자리에
    # 놓고 묶어야, 새 이름이 옛 이름에 붙는다. 따로 묶으면 같은 것이 두 벌 남는다.
    묶음표 = 묶기(이미 + [str(t) for ts in 표.values() for t in ts])
    for qid, ts in 표.items():
        q = n.문제.get(qid)
        if not q:
            없는.append(qid)
            continue
        if q.태그 and not 덮어쓰기:
            건너 += 1
            continue
        새 = []
        for t in ts:
            모은 = 모으기(묶음표.get(str(t).strip(), t), 이미)
            if 모은 and 고르게(모은) not in [고르게(x) for x in 새]:
                # **글자 그대로 견준다.** 고르게() 로 견주면 `조건부 확률` ->
                # `조건부확률` 이 '같다' 로 나와 보고가 안 된다 -- 그런데 그것이
                # 바로 여기서 실제로 일어난 합침이다. 조용히 합치면 화면의 태그가
                # 모델이 쓴 것과 달라지고, 읽는 쪽은 그것을 못 알아챈다(검사가 잡았다).
                if 모은 != t:
                    모음[t] = 모은
                새.append(모은)
                if 모은 not in 이미:
                    이미.append(모은)
        if 새:
            q.태그 = 새[:태그상한]
            붙임 += 1
    return {"붙임": 붙임, "건너뜀": 건너, "모은것": 모음, "없는id": 없는}


def 흩어짐(n) -> dict:
    """**태그가 너무 잘게 쪼개졌는가.** 그러면 무슨 결과가 나와도 못 가른다.

    `brief/최소p` 와 같은 자리다 -- 재기 전에 잴 수 있는지부터 말한다. 여기서는
    태그 수가 곧 Holm 의 m 이라, m 이 커지면 문턱이 그만큼 조여진다.
    """
    from study import weak as WK                       # 되돌이 import 를 피한다

    표 = WK.태그별(n)
    전, _, _ = WK.전체기저(n)
    잰것 = [t for t, v in 표.items() if v[0] >= WK.MIN_N]
    묶음 = {"태그수": len(표), "잴수있는태그": len(잰것), "채점된문제": 전,
           "태그당평균": (sum(v[0] for v in 표.values()) / len(표)) if 표 else 0.0,
           "작은태그": sorted(t for t, v in 표.items() if v[0] < WK.MIN_N),
           "닮은쌍": 닮은쌍(sorted(표))}
    m = len(잰것) or 1
    # 이 m 으로 **다 틀려도** 문턱을 넘으려면 태그마다 몇 문제가 있어야 하나
    p0 = max(WK.전체기저(n)[2], 1e-6)
    필요 = 0
    for k in range(WK.MIN_N, 200):
        if min(1.0, m * WK.도달가능최소p(k, p0)) < WK.ALPHA:
            필요 = k
            break
    묶음["태그당필요"] = 필요 or -1
    묶음["흩어짐"] = bool(표) and 묶음["태그당평균"] < (필요 or 999)
    return 묶음


# ── 오답 사유 ────────────────────────────────────────────────────────
def 사유프롬프트(것들: list, 이미: list = ()) -> str:
    """**모델에게 줄 것.** 틀린 것마다 왜 틀렸는지 / 무엇을 모르는지 한 줄로.

    `것들` 은 `(문제, 시도)` 짝. 갈래(오답/모름)는 **학생이 이미 골랐다** -- 모델은
    그 안에서 무엇인지만 적는다. 갈래까지 모델이 정하면 학생이 아는지 모르는지를
    모델이 짐작하는 셈이고, 그것은 여기서 제일 지어내기 쉬운 자리다.
    """
    쓰던 = ", ".join(sorted(이미)) if 이미 else "(아직 없다)"
    줄 = []
    for q, a in 것들:
        줄.append(json.dumps({
            "id": q.id, "갈래": a.갈래, "문제": q.말[:300], "정답": q.정답[:120],
            "낸답": a.낸답[:120], "메모": a.메모[:200], "해설": q.해설[:200],
        }, ensure_ascii=False))
    return f"""틀린 문제마다 **무엇이 어긋났는지**를 한 줄로 적어라.

## 이미 쓰이는 사유 -- **여기 있으면 그대로 쓴다**

{쓰던}

## 어떻게 적나

  · **과목 이름을 적지 마라.** `확률` · `대수` 는 사유가 아니다. 그건 이미 태그에 있다.
  · **무엇을 어떻게 잘못했는지**를 적는다. 다시 읽었을 때 그 자리를 짚을 수 있게:
        나쁨: 조건부확률을 모름 · 계산 실수 · 개념 부족
        좋음: 조건부확률에서 분모를 P(A) 가 아니라 전체로 잡는다
              여사건으로 바꿔야 빠른데 직접 세다가 경우를 빠뜨린다
              등비수열 합 공식에서 r=1 인 경우를 안 나눈다
  · `갈래` 가 **오답**이면 아는데 어긋난 자리를, **모름**이면 무엇을 몰라서 못 폈는지
    (어떤 유형·어떤 도구가 없어서인지) 적는다.
  · 같은 어긋남은 **같은 말로** 적어라. 다르게 부르면 갈라져서 되풀이인 줄 모른다.
  · 근거가 없으면 (메모도 없고 낸 답으로도 알 수 없으면) `""` 로 비워라.
    **지어내지 마라** -- 지어낸 사유가 그대로 교안이 된다.

## 틀린 문제

{chr(10).join(줄)}

## 출력 (JSON 하나만. 다른 말은 붙이지 마라)

{{"사유": {{"문제id": "무엇이 어긋났는지 한 줄"}}}}"""


def 사유읽기(d) -> dict:
    """모델 답 -> `{문제id: 사유}`."""
    if isinstance(d, str):
        try:
            d = json.loads(d)
        except json.JSONDecodeError:
            i, j = d.find("{"), d.rfind("}")
            if i < 0 or j <= i:
                return {}
            try:
                d = json.loads(d[i:j + 1])
            except json.JSONDecodeError:
                return {}
    if not isinstance(d, dict):
        return {}
    표 = d.get("사유") if isinstance(d.get("사유"), dict) else d
    if not isinstance(표, dict):
        return {}
    return {str(k).strip(): str(v).strip()
            for k, v in 표.items() if str(v or "").strip()}


def 사유붙이기(n, 표: dict, 덮어쓰기: bool = False) -> dict:
    """사유를 시도에 붙이고 **닮은 것끼리 묶는다.**

    묶는 것이 여기서 더 중요하다. 태그는 모델이 몇 안 되는 이름을 돌려쓰지만, 사유는
    문장이라 매번 조금씩 다르게 쓴다 -- 안 묶으면 사유가 문제 수만큼 생기고 그러면
    **되풀이가 하나도 안 보인다.** 그게 이 자리의 요점인데.
    """
    이미 = sorted({a.사유 for a in n.시도 if a.사유})
    묶음표 = 묶기(이미 + [v for v in 표.values() if v])
    붙임, 건너, 모음, 없는 = 0, 0, {}, []
    for qid, 사 in 표.items():
        a = n.마지막(qid)
        if not a:
            없는.append(qid)
            continue
        if a.사유 and not 덮어쓰기:
            건너 += 1
            continue
        모은 = 묶음표.get(사, 사)
        if 모은 != 사:
            모음[사] = 모은
        a.사유 = 모은
        붙임 += 1
    return {"붙임": 붙임, "건너뜀": 건너, "모은것": 모음, "없는id": 없는}
