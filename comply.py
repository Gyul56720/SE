"""**규격 문턱으로 구조를 견준다** -- "몇 배 좋아졌나" 가 아니라 "몇 dB 가 드나".

## 잣대를 바꾼다

앞판은 **BER 비(比)** 로 말했다: "표가 baseline 보다 7.98배 좋다". 그 문장의 문제는
**어느 BER 에서인가**를 안 적으면 아무 뜻이 없다는 것이다. 실제로 그 7.98배는
1e-2 에서 2.27 dB 였고 1e-12 에서는 0.34 dB 였다 -- 같은 "7.98배" 가 동작점에 따라
일곱 배 다른 값이 된다.

그래서 잣대를 **규격의 잣대**로 바꾼다.

    물음:  KP4 pre-FEC 문턱(~2.2e-4)에 닿는 데 SNR 이 몇 dB 드나?
    답:    팔마다 그 dB. 그 차이가 **규격 여유(compliance margin)** 다.

이 잣대는 동작점을 고를 여지가 없다 -- 문턱이 부호가 정한 값이다.

## **바닥을 먼저 본다** -- 이것이 이 모듈의 핵심

SNR 을 올려도 안 내려가는 바닥이 문턱 위에 있으면, 그 구조는 **어떤 SNR 로도 규격을
못 넘는다.** 이분법으로 "필요 SNR" 을 찾으면 그런 경우에도 **숫자 하나가 나와서**
닿은 줄 알게 된다 -- 그것이 정확히 앞판이 저지른 잘못이다.

그래서 `필요SNR()` 은 **이분법 전에** 아주 높은 SNR(`바닥SNR`, 기본 55 dB)에서 한 번
돌려 본다.

    바닥BER > 문턱   ->  판정 `바닥` : 규격 불가. **필요 SNR 을 내지 않는다.**
    바닥BER <= 문턱  ->  이분법으로 필요 SNR 을 찾는다

## 재고 나서 -- 이 모듈이 낸 결론 (PAM4 · 20 dB · 7비트 ADC · KP4 문턱 2.262e-4)

**압축 κ=0.5, 씨 4개, 200,000 심볼. 네 팔 다 만장일치다.**

    팔                        규격            바닥 / 필요 SNR        ASIC 면적
    선형 FFE11+DFE8           **불가**        바닥 4.55e-3 (문턱의 20배)   37,666 um2
    + 메모리없는 역변환(곱셈 0)  **통과**        36.15 dB (4/4)           **38,562 um2**
    MLP 96곱셈                **불가**        바닥 9.24e-4 (문턱의 4.1배)  368,026 um2
    MLP 96곱셈 + 역변환        통과            36.25 dB (4/4)           368,922 um2

**세 가지가 한꺼번에 나온다.**

1. **96곱셈 망은 규격을 못 넘는다.** 선형보다는 4.9배 나은 바닥(9.24e-4 대 4.55e-3)
   을 내므로 **역함수를 배우기는 한다.** 그런데 근사라서 문턱 아래로 못 내려간다.
   표는 같은 일을 **정확히** 한다 -- 그것이 명제 1 의 뜻이다.
2. **망에 그 표를 달아도 표 단독과 구별이 안 된다.** 36.25 vs 36.15 dB, 씨 사이
   흩어짐이 0.62~1.11 dB 다. **곱셈기 96개가 사는 것이 0.1 dB 안쪽**이라는 뜻이고,
   부호가 붙는 방향도 아니다(표 단독이 오히려 조금 낮다).
3. **실리콘으로는 9.5배다.** 규격을 넘긴 구조는 38,562 um2, 망은 368,026 um2 --
   **열 배 가까운 실리콘을 쓰고도 규격을 못 넘는다.**

## 대조가 둘 다 섰다

    κ=0 (선형 채널)   역변환이 정확히 아무 일도 안 한다 (36.10 = 36.10 dB)
                     MLP 은 선형보다 **0.25 dB 나쁘다** -- 최적이 선형인 자리에서
                     비선형 근사를 얹었으니 그래야 맞다
    표본색인표        PAM4 에서는 계속 진다(43.8~46.0 dB, 씨 1/2). 표본 두 개로는
                     FFE11+DFE8 의 스팬을 못 당한다

## 이 결론의 한계를 같이 적는다

이 망은 **앞뒤 5 · 은닉 8 · 8에폭 · 200,000 심볼**이다. 더 크고 더 오래 학습한 망은
문턱을 넘을 수 있다 -- **"신경망으로는 안 된다" 가 아니다.** 다만 그때는 실리콘이
368,026 um2 에서 더 늘고, 표는 여전히 896 um2 다. 주장은 그 **비**에 있다.

## 오류 0 을 BER 0 으로 읽지 않는다

3의 규칙으로 위쪽 한계 `3/N` 을 쓴다. 그리고 그 한계가 문턱보다 **크면** 판정을
못 한다 -- 그때는 심볼을 더 보내야 한다고 말한다(`모자란다`).
"""
from __future__ import annotations

import inspect
import math

import numpy as np

import fec
import serdes


def _BER위한계(r: dict) -> float:
    """오류 0 이면 3의 규칙, 아니면 잰 값."""
    if r.get("오류수", 0) > 0:
        return float(r["BER"])
    return 3.0 / max(int(r.get("잰비트", 0)), 1)


def _인자맞추기(돌리기, 구성: dict, 뺄것=()) -> dict:
    """`돌리기` 가 실제로 받는 인자만 남긴다. **조용히 버리지 않는다.**

    팔마다 돌리는 함수가 다르다(`serdes.링크` 는 `FFE탭` 을 받고 `nneq.링크` 는 안
    받는다). 안 받는 인자를 말없이 떨구면 **내가 의도한 것과 다른 구성을 견주게**
    되므로, 버릴 것은 `뺄것` 에 **적어야** 하고 적지 않은 것이 안 맞으면 터뜨린다.
    """
    받 = set(inspect.signature(돌리기).parameters)
    난것, 남 = {}, []
    for k, v in 구성.items():
        if k in ("SNRdB", "씨") or k in set(뺄것):
            continue
        if k in 받:
            난것[k] = v
        else:
            남.append(k)
    if 남:
        raise TypeError(
            f"{getattr(돌리기, '__module__', '?')}.{getattr(돌리기, '__name__', '?')} "
            f"가 안 받는 인자가 있다: {남}. 일부러 빼려면 `_뺄것` 에 적어라 -- "
            f"말없이 떨구면 다른 구성을 견주게 된다")
    return 난것


def 필요SNR(구성: dict, 부호: str = "KP4", 목표: float = 0.0,
         바닥SNR: float = 55.0, 낮게: float = 10.0, 높게: float = 55.0,
         되풀이: int = 15, 씨: int = 0, 돌리기=None, 뺄것=()) -> dict:
    """**문턱에 닿는 데 드는 SNR.** 못 닿으면 못 닿는다고 말한다.

    `구성` 은 `돌리기` 에 그대로 넘어가는 딕셔너리다(SNRdB 와 씨는 여기서 준다).
    `돌리기` 를 안 주면 `serdes.링크` 다 -- `nneq.링크` 를 주면 **신경망 팔**이 된다.
    """
    목표 = float(목표) if 목표 else fec.문턱(1e-15, 부호)
    돌 = 돌리기 or serdes.링크
    인자 = _인자맞추기(돌, 구성, 뺄것)

    # (가) **바닥 먼저.** 아주 높은 SNR 에서도 문턱을 못 넘으면 이분법은 뜻이 없다.
    바닥r = 돌(SNRdB=float(바닥SNR), 씨=씨, **인자)
    if 바닥r.get("판정") != serdes.PASS:
        return {"판정": serdes.못잼, "왜": 바닥r.get("왜", ""), "목표": 목표}
    바닥p = _BER위한계(바닥r)
    잰비트 = int(바닥r["잰비트"])
    if 3.0 / max(잰비트, 1) > 목표:
        return {"판정": serdes.못잼, "목표": 목표, "바닥BER": 바닥p,
                "왜": (f"심볼이 모자란다 -- 오류 0 이어도 위한계가 {3.0/잰비트:.2e} 로 "
                      f"문턱 {목표:.2e} 보다 크다. 심볼수를 "
                      f"{int(3.0/목표/max(1,바닥r.get('M',2)))*2:,} 이상으로")}
    if 바닥p > 목표:
        return {"판정": serdes.PASS, "결과": "바닥", "목표": 목표,
                "바닥BER": 바닥p, "바닥SNR": float(바닥SNR),
                "SNRdB": float("nan"), "닿나": False,
                "문턱대비": 바닥p / 목표,
                "왜": (f"SNR {바닥SNR:.0f} dB 에서도 BER {바닥p:.3e} 로 문턱 "
                      f"{목표:.2e} 의 {바닥p/목표:.1f}배 -- **바닥에 걸려 어떤 SNR "
                      f"로도 규격을 못 넘는다**")}

    # (나) 이분법
    낮, 높 = float(낮게), float(높게)
    for _ in range(int(되풀이)):
        가 = 0.5 * (낮 + 높)
        p = _BER위한계(돌(SNRdB=가, 씨=씨, **인자))
        if p > 목표:
            낮 = 가
        else:
            높 = 가
    SNR = 0.5 * (낮 + 높)
    끝 = 돌(SNRdB=SNR, 씨=씨, **인자)
    p = _BER위한계(끝)
    닿았나 = 끝["오류수"] > 0 and 0.2 * 목표 < 끝["BER"] < 5.0 * 목표
    판 = fec.판정(끝.get("비트오류자리", np.array([], dtype=np.int64)),
                끝["잰비트"], 부호)
    return {"판정": serdes.PASS, "결과": "닿는다", "목표": 목표,
            "SNRdB": float(SNR), "BER": p, "오류수": int(끝["오류수"]),
            "잰비트": int(끝["잰비트"]), "바닥BER": 바닥p, "닿나": True,
            "이분법닿았나": bool(닿았나), "FEC": 판,
            "왜": (f"SNR {SNR:.2f} dB 에서 BER {p:.3e} (문턱 {목표:.2e})"
                  + ("" if 닿았나 else "  **이분법이 목표에 못 앉았다 -- 믿지 마라**"))}


def 팔들(바탕: dict, 팔: dict, 부호: str = "KP4", 씨들=(0, 1, 2), **인자) -> dict:
    """여러 구조를 **필요 SNR** 로 견준다. 씨마다 재고 씨 사이 흩어짐을 같이 낸다.

    돌려주는 `여유dB` 는 **기준 팔 대비 아낀 dB** 다 -- 양수면 그만큼 싼 링크로도
    규격을 넘는다는 뜻이다. 어느 팔이 `바닥` 이면 그 팔에는 dB 가 없다(그것이 답이다).
    """
    이름들 = list(팔.keys())
    난것 = {}
    for 이름 in 이름들:
        # 팔이 `_돌리기`/`_뺄것` 을 들고 있으면 그 팔만 다른 함수로 돈다.
        덧 = dict(팔[이름])
        돌리기 = 덧.pop("_돌리기", None)
        뺄것 = tuple(덧.pop("_뺄것", ()))
        줄 = []
        for s in 씨들:
            r = 필요SNR({**바탕, **덧}, 부호=부호, 씨=s,
                     돌리기=돌리기, 뺄것=뺄것, **인자)
            줄.append(r)
        닿 = [x for x in 줄 if x.get("닿나")]
        바닥들 = [x for x in 줄 if x.get("결과") == "바닥"]
        난것[이름] = {
            "줄": 줄, "닿은씨": len(닿), "씨수": len(줄),
            "바닥씨": len(바닥들),
            "SNRdB평균": float(np.mean([x["SNRdB"] for x in 닿])) if 닿 else float("nan"),
            "SNRdB최대차": (float(np.ptp([x["SNRdB"] for x in 닿]))
                        if len(닿) > 1 else 0.0),
            "바닥BER평균": float(np.mean([x["바닥BER"] for x in 줄
                                    if np.isfinite(x.get("바닥BER", np.nan))]))
                        if 줄 else float("nan"),
        }
    기준 = 이름들[0]
    for 이름 in 이름들:
        a, b = 난것[기준]["SNRdB평균"], 난것[이름]["SNRdB평균"]
        난것[이름]["여유dB"] = (a - b) if (np.isfinite(a) and np.isfinite(b)) else float("nan")
        # **기준이 바닥이면 dB 차를 못 낸다 -- 그리고 그것이 더 센 진술이다.**
        # "몇 dB 아꼈다" 가 아니라 "못 넘던 것을 넘게 했다" 이므로 그렇게 적는다.
        난것[이름]["기준못넘음"] = 난것[기준]["닿은씨"] == 0
    return {"판정": serdes.PASS, "기준": 기준, "부호": 부호, "팔": 난것}


def 말로(r: dict) -> str:
    if r.get("판정") != serdes.PASS:
        return f"못 잼: {r.get('왜','')}"
    줄 = [f"[{r['부호']} 문턱 기준 -- 필요 SNR, 기준={r['기준']}]"]
    for 이름, d in r["팔"].items():
        if d["닿은씨"] == 0:
            줄.append(f"  {이름:22s} **못 넘는다** -- {d['바닥씨']}/{d['씨수']} 씨가 "
                     f"바닥(평균 {d['바닥BER평균']:.2e})")
        else:
            꼬 = ""
            if 이름 != r["기준"]:
                꼬 = ("  <- **기준이 못 넘는 자리를 넘긴다**" if d.get("기준못넘음")
                     else f"  여유 {d['여유dB']:+.2f} dB")
            줄.append(f"  {이름:22s} {d['SNRdB평균']:6.2f} dB "
                     f"(씨 {d['닿은씨']}/{d['씨수']}, 흩어짐 {d['SNRdB최대차']:.2f} dB)" + 꼬)
    return "\n".join(줄)
