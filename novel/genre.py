def names() -> list:
    return sorted(PACKS)


def get(name: str) -> dict:
    """갈래 꾸러미. 빈 이름이면 없음(지금까지의 틀 그대로)."""
    if not name:
        return {}
    if name not in PACKS:
        raise ValueError(f"모르는 갈래: {name} (있는 것: {', '.join(names())})")
    return PACKS[name]


def tune(name: str, key: str, default):
    """저울 값 하나. 갈래가 없거나 그 값이 없으면 원래 값을 그대로 돌려준다."""
    return get(name).get("저울", {}).get(key, default) if name else default


def event(name: str, seed: str, n: int) -> dict:
    """이번 덩어리의 **뒤틀림** 하나. 갈래가 사건축을 가진 경우에만 나온다.

    목록에서 하나를 뽑으면 그 목록 크기가 곧 이야기의 가짓수다. 축을 갈라 곱하면
    18 x 12 x 8 x 6 = 10,368 가지가 되고, **한 축씩 따로 흔들리므로** 이웃한
    덩어리끼리도 안 닮는다. 축마다 따로 해시하는 것은 shock 이 쓰던 그대로다."""
    pack = get(name)
    ax = pack.get("사건축") if pack else None
    if not ax:
        return {}
    from novel import shock
    return {k: shock._pick(v, f"{seed}|{k}", n, k) for k, v in ax.items()}


def size(name: str) -> int:
    """사건 가짓수. 목록이면 그 길이, 축이면 곱."""
    pack = get(name)
    if not pack:
        return 0
    ax = pack.get("사건축")
    if not ax:
        return len(pack.get("사건", {}))
    out = 1
    for v in ax.values():
        out *= len(v)
    return out


def brief(name: str, seed: str, n: int, k: int = 2) -> str:
    """이번 덩어리에 얹을 갈래 몫. 관계와 사건을 하나씩 뽑는다 -- 목록을 다 시키지
    않는 것은 다른 목록과 같은 이유다(한꺼번에 시키면 안 지켜진다)."""
    pack = get(name)
    if not pack:
        return ""
    from novel import shock
    from novel.wording import menu
    rel = shock._batch(pack["관계"], f"{seed}|rel", n, "rel", k)
    eve = shock._batch(pack["사건"], f"{seed}|eve", n, "eve", 1)
    axes = event(name, seed, n)
    out = [f"[{pack['name']}] {pack['머리']}",
           menu(pack["관계"], rel, "이번 대목의 관계",
                "관계는 **말로 진전되지 않는다.** 같이 겪은 일이 사이를 바꾼다."),
           menu(pack["사건"], eve, "이번 대목에 일어날 수 있는 일",
                "일어나야만 하는 것은 아니다. 다만 **이 대목이 끝났을 때 세계가"
                " 조금은 달라져 있어야** 한다.")]
    if axes:
        out.append(
            "  · **이번 대목의 뒤틀림** -- "
            + " / ".join(f"**{v}**" for v in axes.values())
            + "\n      읽는 대로: **" + axes["무엇이"] + "**가 " + axes["어떻게"]
            + ". 걸리는 쪽은 **" + axes["누구에게"] + "**, 드러나는 것은 **"
            + axes["언제"] + "**."
            + "\n      **이것이 이번 덩어리의 사건이다.** 대사로 알리지 말고 **일로**"
              " 벌어지게 해라 -- 누가 그것을 발견하고, 무엇을 하고, 그래서 무엇이 달라지는지."
            + "\n      **이미 있는 것에 붙여라.** 새 회사를 만들지 말고 [세계]에 놓인"
              " 사람·자리·서류를 쓴다. 붙일 데가 없으면 그때만 새로 만든다."
            + "\n      비틀어도 된다 -- 축은 출발점이지 각본이 아니다.")
    if pack.get("화법"):                     # 갈래가 제 말투를 가진 경우에만
        way = shock._batch(pack["화법"], f"{seed}|way", n, "way", 2)
        out.append(menu(pack["화법"], way, "이번 대목의 화법",
                        "이 갈래의 말버릇이다. 다 쓰지는 마라 -- 한 대목에 하나둘이면 된다."))
    return "\n".join(out)
