def names() -> list:
    return sorted(PACKS)


def get(name: str) -> dict:
    """갈래 꾸러미. 빈 이름이면 없음(지금까지의 틀 그대로)."""
    if not name:
        return {}
    if name not in PACKS:
        raise ValueError(f"모르는 갈래: {name} (있는 것: {', '.join(names())})")
    return PACKS[name]


def tune(name: str, key: str, default):
    """저울 값 하나. 갈래가 없거나 그 값이 없으면 원래 값을 그대로 돌려준다."""
    if not name:
        return default
    scale = get(name).get("저울", {})
    if key in scale:
        return scale[key]
    # "대사" 는 축 dialog 의 옛 이름이다. 두 군데 적으면 한 군데만 고치는 날이 온다.
    if key == "대사":
        return band(name, "dialog", default)
    return default


def band(name: str, axis: str, default=None):
    """**갈래가 옮기는 축 목표.** 없으면 표본값(targets.json)이 그대로 산다.

    저울의 다른 값들과 갈라 두는 이유. 이것만은 **재는 축에 매여 있다** -- 갈래가
    옮겨 놓아도 지켜졌는지 다음 덩어리에서 잴 수 있다. 그래서 프롬프트를 축에서
    짓는 경로(compose.py)에도 실을 자격이 있다. 화법이나 부름은 그렇지 않다."""
    return get(name).get("저울", {}).get("축", {}).get(axis, default) if name else default


def event(name: str, seed: str, n: int) -> dict:
    """이번 덩어리의 **뒤틀림** 하나. 갈래가 사건축을 가진 경우에만 나온다.

    목록에서 하나를 뽑으면 그 목록 크기가 곧 이야기의 가짓수다. 축을 갈라 곱하면
    18 x 12 x 8 x 6 = 10,368 가지가 되고, **한 축씩 따로 흔들리므로** 이웃한
    덩어리끼리도 안 닮는다. 축마다 따로 해시하는 것은 shock 이 쓰던 그대로다."""
    pack = get(name)
    ax = pack.get("사건축") if pack else None
    if not ax:
        return {}
    from novel import shock
    return {k: shock._pick(v, f"{seed}|{k}", n, k) for k, v in ax.items()}


def opening(name: str, seed: str) -> str:
    """**여는 좌표.** 첫 문장을 사람이 지어 넣으면 그 문장의 세계가 원고 전체를 정한다
    -- 지명 하나, 연도 하나가 백 덩어리를 끌고 간다(실측). 그렇다고 고정 문장을 두면
    매번 같은 데서 열린다.

    그래서 **문장 대신 좌표를 뽑는다.** 무대 · 관계 · 어긋나는 것을 갈래의 축에서
    무작위로 뽑아 주고, 첫 문장은 화자가 그 자리에서 짓는다. 우리는 어디서 여는지만
    정하고 무엇을 쓸지는 안 정한다."""
    pack = get(name)
    if not pack:
        return ""
    from novel import shock
    slots = [("무대", pack.get("무대")),
             ("관계", tuple(pack.get("관계", {}))),
             ("일어난 일", tuple(pack.get("사건", {})))]
    ax = pack.get("사건축") or {}
    for k in ("무엇이", "어떻게"):
        if ax.get(k):
            slots.append((k, ax[k]))
    lines = []
    for k, pool in slots:
        if pool:
            lines.append(f"  · {k} -- {shock._pick(tuple(pool), f'{seed}|open|{k}', 0, k)}")
    return "[좌표]\n" + "\n".join(lines) + "\n"


def size(name: str) -> int:
    """사건 가짓수. 목록이면 그 길이, 축이면 곱."""
    pack = get(name)
    if not pack:
        return 0
    ax = pack.get("사건축")
    if not ax:
        return len(pack.get("사건", {}))
    out = 1
    for v in ax.values():
        out *= len(v)
    return out


def brief(name: str, seed: str, n: int, k: int = 2) -> str:
    """이번 덩어리에 얹을 갈래 몫. 관계와 사건을 하나씩 뽑는다 -- 목록을 다 시키지
    않는 것은 다른 목록과 같은 이유다(한꺼번에 시키면 안 지켜진다)."""
    pack = get(name)
    if not pack:
        return ""
    from novel import shock
    from novel.wording import menu
    rel = shock._batch(pack["관계"], f"{seed}|rel", n, "rel", k)
    eve = shock._batch(pack["사건"], f"{seed}|eve", n, "eve", 1)
    axes = event(name, seed, n)
