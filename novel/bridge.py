"""**연결** -- 따로 세워 둔 둘을 잇는다. 세계가 넓어지는 두 번째 방식.

지금까지 세계는 세 가지로 자랐다. 새것을 놓고(확산), 이름을 세분하고(웅포 → 웅포 소금
공장), 앞엣것을 다시 만졌다(회수). 셋 다 **한 갈래를 따라가는** 성장이다.

수학이 크게 도약하는 자리는 거기가 아니다. 오일러가 한 것은 지수를 더 정교하게 만든 것이
아니라, **따로 자라던 셋(지수 · 허수 · 각도)이 실은 한 식이라는 것**을 보인 것이다.
데카르트가 대수와 기하를 좌표로 묶은 것도, 갈루아가 방정식과 대칭을 묶은 것도 같다.
이미 있던 것들 사이에 없던 다리가 놓이면 세계는 넓어지는 것이 아니라 **접힌다.**

소설에서도 같다. 세 덩어리 전의 우체부와 열 덩어리 전의 소금 공장은 서로 아무 상관이
없었다. 그 둘이 이어지는 순간, 독자는 새 정보를 받는 것이 아니라 **이미 읽은 것을 다시
읽게 된다.** 그것이 이 장치가 하는 일이다.

두 가지를 지킨다. 앞서 정한 것과 부딪히면 안 되기 때문이다.

  · **연결은 모순이 아니어야 한다.** 둘을 잇느라 앞에 쓴 것을 뒤집으면 그건 다리가
    아니라 다른 이야기다. 이어 붙이되 둘 다 그대로 남아야 한다(보존적 확장).
  · **연결이 문제를 풀지 않는다.** 알고 보니 그 사람이 열쇠를 갖고 있었다 -- 이런 것은
    편의주의다. 다리는 일을 **복잡하게** 만든다. 풀리는 것이 아니라 얽힌다.
"""
from __future__ import annotations

import hashlib

# 잇는 방식. 무엇과 무엇을 이을지는 원장이 정하고, 어떻게 이을지가 여기 있다.
WAY = (
    "**같은 것이었다.** 다른 이름으로 두 번 나왔을 뿐이다",
    "**하나가 다른 하나의 원인이었다.** 순서가 그제야 보인다",
    "**한 사람이 둘 다에 얽혀 있다.** 그 사람은 그것을 말한 적이 없다",
    "**하나가 다른 하나의 나중 모습이다.** 시간이 그 사이에 있었다",
    "**둘이 한 짝이었다.** 떨어져 있어서 아무도 몰랐다",
    "**하나를 건드리면 다른 하나가 움직인다.** 왜 그런지는 아무도 모른다",
    "**셋째 것이 둘을 잇는다.** 그것이 이번에 나온다",
    "**둘이 같은 자리에서 왔다.** 출처가 하나다",
    "**하나가 다른 하나를 흉내 낸 것이다.** 먼저 있던 쪽이 어느 쪽인지가 뒤집힌다",
    "**둘을 같이 놓으면 값이 달라진다.** 따로 있을 때와 뜻이 다르다",
    "**하나가 다른 하나의 대가였다.** 주고받은 것이 있었다",
    "**둘 다 같은 사람을 향하고 있었다.** 방향이 그제야 보인다",
)

# 다리가 놓인 뒤에 일어나는 일. 연결은 정보가 아니라 사건이어야 한다.
AFTER = (
    "그것을 알아챈 사람이 하나뿐이고, 그 사람은 입을 안 연다",
    "알아챈 쪽이 틀렸다. 그런데 그 오해로 일이 굴러간다",
    "그것 때문에 앞서 한 결정이 잘못된 것이 된다",
    "아무도 못 알아챈다. 독자만 안다",
    "그 자리에서 말해 버린다. 분위기가 이상해진다",
    "그것으로 새 미결이 하나 생긴다",
    "둘 중 하나를 잃게 된다",
    "그것을 아는 사람이 하나 더 늘어난다",
)


def _raw(pool, seed: str, n: int, axis: str) -> int:
    h = hashlib.sha256(f"{seed}|{n}|bridge|{axis}".encode()).digest()
    return int.from_bytes(h[:8], "big") % len(pool)


def _pick(pool, seed: str, n: int, axis: str):
    prev = None
    for k in range(max(0, n - 8), n + 1):
        i = _raw(pool, seed, k, axis)
        if prev is not None and i == prev:
            i = (i + 1) % len(pool)
        prev = i
    return pool[prev]


def pair(ledger: dict, seed: str, n: int) -> tuple[str, str]:
    """**멀리 있는 둘을 고른다.** 방금 같이 나온 것을 잇는 것은 다리가 아니다.

    나이(_age)를 알면 오래된 쪽 하나와 최근 쪽 하나를 짝짓는다 -- 그래야 독자가 앞을
    다시 읽게 된다. 나이를 모르는 옛 원고는 그냥 양 끝에서 하나씩 집는다.
    """
    from novel import diffusion

    names = [p for p in diffusion.props(ledger) if len(p) >= 2]
    if len(names) < 2:
        return ("", "")
    age = ledger.get("_age") or {}
    names.sort(key=lambda p: age.get(p, 0))
    half = max(1, len(names) // 2)
    old = names[:half]
    new = names[half:] or old
    # 짝도 직전과 겹치면 민다. 안 그러면 같은 것이 계속 한쪽에 선다(실측).
    a = _pick(old, seed, n, "a")
    b = _pick(new, seed, n, "b")
    if a == b and len(new) > 1:
        b = new[(new.index(b) + 1) % len(new)]
    return (a, b)


def gate(seed: str, n: int, rate: float) -> bool:
    if rate >= 1.0:
        return True
    h = hashlib.sha256(f"{seed}|{n}|bridge|gate".encode()).digest()
    return (int.from_bytes(h[:8], "big") % 1000) < rate * 1000


def draw(ledger: dict, seed: str, n: int) -> dict:
    a, b = pair(ledger, seed, n)
    return {"a": a, "b": b,
            "way": _pick(WAY, seed, n, "way"),
            "after": _pick(AFTER, seed, n, "after")}


def brief(d: dict) -> str:
    if not (d.get("a") and d.get("b")):
        return ""
    return f"""[연결] **따로 있던 둘을 잇는다.** 세계는 넓어지기만 하는 것이 아니라 접히기도 한다.

  · 이을 것 -- **{d['a']}** 와 **{d['b']}**
  · 잇는 방식 -- {d['way']}
  · 이어진 뒤 -- {d['after']}

  * 이 둘은 지금까지 서로 상관이 없었다. 이어지는 순간 독자는 새 정보를 받는 것이 아니라
    **이미 읽은 것을 다시 읽게 된다.** 그것이 이 장치가 노리는 것이다.
  * **앞에 쓴 것을 뒤집지 마라.** 둘 다 그대로 남은 채로 이어야 한다 -- 뒤집으면 그건
    다리가 아니라 다른 이야기다.
  * **이것으로 문제를 풀지 마라.** '알고 보니 그 사람이 열쇠를 갖고 있었다' 는 편의주의다.
    다리는 일을 **복잡하게** 만든다. 풀리는 것이 아니라 얽힌다.
  * 설명하지 마라. **둘을 같은 자리에 놓기만 해도 독자는 안다.**
  * 이을 것이 더 나은 짝이 보이면 그리로 가라. 이것도 출발점이다."""
