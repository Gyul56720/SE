def pick_kind(pool, counts: dict) -> str:
    """pool 안에서 목표 비율에 가장 모자란 종류를 고른다.

    무작위가 아니라 **결손 최대**로 고른다. 무작위는 표본이 작을 때(회차당 3씬) 비율이
    맞지 않고, 같은 세계를 다시 돌렸을 때 재현되지도 않는다. counts 는 지금까지 배정한
    종류별 개수이고 호출자가 들고 다닌다."""
    total = sum(counts.values()) or 0
    best, best_deficit = pool[0], None
    for k in pool:
        share = (counts.get(k, 0) / total) if total else 0.0
        deficit = SCENE_KINDS[k]["share"] - share
        if best_deficit is None or deficit > best_deficit:
            best, best_deficit = k, deficit
    return best


def brief(kind: str) -> str:
    """그 종류의 규율 블록. 모르는 종류면 빈 문자열 -- 없는 규율을 지어내지 않는다."""
    spec = SCENE_KINDS.get(kind)
    return (spec["brief"] + "\n\n") if spec else ""


def tally(scenes) -> dict:
    """이미 배정된 씬들의 종류별 개수. 재개할 때 배분을 이어서 세기 위한 것이다."""
    out: dict = {}
    for s in scenes:
        k = getattr(s, "kind", "")
        if k:
            out[k] = out.get(k, 0) + 1
    return out


