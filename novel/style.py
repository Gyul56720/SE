PERSONAS = {"cider": CIDER, "hardboiled": HARDBOILED, "ropan": ROPAN}
ACTIVE = "cider"


def use(name: str) -> None:
    """페르소나를 고른다. 없는 이름이면 사실대로 실패한다 -- 조용히 기본값으로 물러서면
    엉뚱한 문체로 몇 시간을 쓰고도 아무도 모른다."""
    global ACTIVE
    if name not in PERSONAS:
        raise ValueError(f"모르는 페르소나: {name!r} (있는 것: {sorted(PERSONAS)})")
    ACTIVE = name


def P() -> dict:
    return PERSONAS[ACTIVE]


def narrator() -> str:
    return P()["narrator"]


def actor() -> str:
    return P()["actor"]


def director() -> str:
    return P()["director"]


def kinds() -> dict:
    return P()["kinds"]


def spine_pool() -> tuple:
    return P()["spine"]


def subplot_pool() -> tuple:
    return P()["subplot"]


def brief(kind: str) -> str:
    """그 종류의 규율 블록. 모르는 종류면 빈 문자열 -- 없는 규율을 지어내지 않는다."""
    spec = kinds().get(kind)
    return (spec["brief"] + "\n\n") if spec else ""


def finale_kind() -> str:
    """블록의 결말 씬에 붙일 종류. 페르소나가 정한다 -- 사이다에서는 가장 큰 성취이고,
    하드보일드에서는 증발하는 해결이다."""
    return P()["finale"]


def episode_brief(episode: int) -> str:
    """회차 단위 구조 지시(3화 법칙 등). 없으면 빈 문자열."""
    got = P()["episode_plot"].get(episode)
    return (got + "\n\n") if got else ""


