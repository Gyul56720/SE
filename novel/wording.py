"""말맛 장부 -- **쓴 것은 세어 두고, 안 쓴 쪽으로 민다.**

문제. 화자는 편하게 쓸 수 있는 것부터 쓴다. 종결어미는 '-다/-었다' 로 몰리고, 비유는
직유 하나로 몰리고, 문장 성분은 '주어 + 목적어 + 서술어' 로 몰린다. 한 덩어리만 보면
안 보이는데 스무 덩어리를 이어 읽으면 같은 소리가 난다. 그것이 "글이 비슷하다" 의 정체다.

고치는 법. **하한을 더 두지 않는다** -- 하한을 두면 하한을 정확히 맞춘다는 것을 이미
겪었다(짧은 '-다' 62%, 긴 대사 여덟 할). 대신 **원고에서 실제로 쓰인 횟수를 세어**,
적게 쓴 것을 이번 덩어리에 밀어 넣는다. 많이 쓴 것은 이번엔 빼라고 한다.

이건 금지가 아니라 **복원력**이다. 한쪽으로 기울면 반대쪽으로 미는 힘이고, 기울지
않았으면 아무 일도 하지 않는다. 목록에 없는 것을 쓰는 것은 언제나 자유다.
"""
from __future__ import annotations

import os
import re

# 종결 어미. **뜻이 아니라 소리로 가른다** -- 같은 뜻이라도 말끝이 다르면 다른 문장이다.
ENDINGS = {
    # **겹쳐 세지 않는다.** '-겠다 / -것이다 / -었다' 까지 '-다' 로 세면 '-다' 는 언제나
    # 과반이 되어 매번 "쉬어라" 가 나온다 -- 늘 켜져 있는 경고는 꺼져 있는 것과 같다.
    "-다":      re.compile(r"(?<![었았였겠는ㄴ이])다[.!?…]"),
    "-었다":    re.compile(r"(었|았|였)다[.!?…]"),
    "-ㄴ다":    re.compile(r"[가-힣](ㄴ다|는다)[.!?…]"),
    "-겠다":    re.compile(r"겠다[.!?…]"),
    "-것이다":  re.compile(r"(것|거)(이|)다[.!?…]"),
    "-까":      re.compile(r"[가-힣](까|을까|ㄹ까)[.?…]"),
    "-지":      re.compile(r"[가-힣]지[.?…]"),
    "-군":      re.compile(r"[가-힣](군|구나|네)[.!…]"),
    "-야":      re.compile(r"[가-힣](야|이야|아)[.!…]"),
    "명사로":   re.compile(r"[가-힣](음|기|것|뿐|만|채|척|둥)[.…]"),
    "말줄임":   re.compile(r"…"),
    "-라":      re.compile(r"[가-힣](라|아라|어라)[.!…]"),
}

# 비유. 이름이 아니라 **꼴**로 가른다 -- 은유를 '은유' 라고 부르면 진단서가 된다.
FIGURES = {
    "직유":   "'-처럼 / -같이 / -듯이' 로 견준다",
    "은유":   "견주는 말 없이 그냥 그것이라고 한다",
    "환유":   "옆에 있는 것으로 대신 부른다 -- 사람을 그 사람의 신발로 부르듯",
    "의인":   "사람 아닌 것이 사람처럼 군다",
    "과장":   "터무니없이 키운다. 본인은 진지하다",
    "축소":   "큰일을 사소한 것처럼 말한다",
    "감각바꿈": "소리를 색으로, 냄새를 무게로 -- 감각을 건너뛴다",
    "숫자로":  "재서 말한다 -- 몇 시 몇 분, 몇 미터, 몇 번째",
}

# **글의 꼴 자체를 흔든다.** 문장만 흔들면 원고는 여전히 같은 모양이다 -- 다 산문이고,
# 다 3인칭이고, 다 한국어 어순이다. 여기 있는 것들은 규칙이 아니라 **재료**다. 이번
# 덩어리에 하나쯤 섞으라는 것이지, 매번 다 하라는 뜻이 아니다.
FORMS = {
    "번역체":   "영어로 먼저 생각하고 옮긴 듯한 문장 -- 관계대명사가 남고, 수동태가 남고,"
                " '그것은 ~한 것이었다' 가 남는다",
    "목록":     "번호나 줄표로 늘어놓는다. 소설 한가운데 목록이 끼면 그 자체가 사건이다",
    "문서":     "영수증 · 시간표 · 규정 · 안내문 · 진단서를 그대로 옮겨 적는다",
    "숫자판":   "재서 말한다. 몇 시 몇 분, 몇 미터, 몇 호, 몇 번째 -- 정확할수록 진짜 같다",
    "기호":     "괄호, 줄표, 별표, 화살표를 문장 안에 그대로 쓴다",
    "말없음":   "한 줄이 통째로 공백이거나 점 세 개다. 아무 설명도 없다",
    "이인칭":   "'너' 라고 부른다. 누가 누구에게 하는 말인지는 밝히지 않는다",
    "현재형":   "지금 일어나는 일처럼 쓴다 -- 시제를 한 대목만 바꾼다",
    "인용":     "누가 한 말을 옮겨 적고, 그 말이 맞는지는 따지지 않는다",
    "각주":     "본문 옆에 딴 얘기를 단다. 딴 얘기가 본문보다 중요하다",
    "되감기":   "끝을 먼저 말하고 어쩌다 그리 됐는지로 간다",
    "겹말":     "같은 문장을 조금씩 바꿔 가며 세 번 쓴다. 셋째에서 뜻이 달라진다",
}
PUSH_FORM = int(os.environ.get("DRIFT_PUSH_FORM", "1"))

# 몇 개를 밀어 넣을 것인가. 너무 많이 시키면 안 지켜진다(한꺼번에 시키면 안 지켜진다).
PUSH_END = int(os.environ.get("DRIFT_PUSH_END", "3"))
PUSH_FIG = int(os.environ.get("DRIFT_PUSH_FIG", "2"))
# 전체의 이만큼을 넘게 차지하면 "이번엔 쉬어라" 고 한다.
HOG = float(os.environ.get("DRIFT_HOG", "0.35"))


def count(text: str) -> dict:
    """어떤 말끝을 몇 번 썼는가. 겹쳐 세도 된다 -- 몫이 아니라 **기울기**를 보는 것이다."""
    return {k: len(p.findall(text)) for k, p in ENDINGS.items()}


def tally(chunks) -> dict:
    """원고 전체의 말끝 셈."""
    out = {k: 0 for k in ENDINGS}
    for c in chunks:
        for k, v in count(c).items():
            out[k] += v
    return out


def thin(chunks, k: int = PUSH_END) -> list:
    """**적게 쓴 말끝** k 개. 원고가 없으면 아무것도 안 민다 -- 밀 방향이 없다."""
    if not chunks:
        return []
    t = tally(chunks)
    return [x for x, _ in sorted(t.items(), key=lambda kv: (kv[1], kv[0]))[:k]]


def hogs(chunks) -> list:
    """**너무 많이 쓴 말끝.** 전체의 HOG 를 넘게 차지한 것들."""
    if not chunks:
        return []
    t = tally(chunks)
    total = sum(t.values())
    if total < 20:                     # 표본이 적으면 기울기를 말할 수 없다
        return []
    return [k for k, v in sorted(t.items(), key=lambda kv: -kv[1]) if v / total > HOG]


def figures(seed: str, n: int, k: int = PUSH_FIG) -> list:
    """이번 덩어리에 쓸 비유의 꼴. **뽑아서 흔든다** -- 세는 것은 말끝만 한다.
    비유는 정규식으로 셀 수 없어서(은유를 어떻게 찾겠는가) 대신 매번 다르게 뽑는다."""
    from novel import shock
    names = tuple(FIGURES)
    return list(shock._batch(names, f"{seed}|figure", n, "fig", k))


def forms(seed: str, n: int, k: int = PUSH_FORM) -> list:
    """이번 덩어리에 섞을 글의 꼴. 비유와 같은 이유로 세지 않고 뽑는다."""
    from novel import shock
    return list(shock._batch(tuple(FORMS), f"{seed}|form", n, "form", k))


def brief(chunks, seed: str, n: int) -> str:
    """이번 덩어리에 밀어 넣을 것. 기울지 않았으면 짧아지고, 기울었으면 길어진다."""
    lines = []
    few = thin(chunks)
    if few:
        lines.append("  · **이번 대목에서 써 볼 말끝** -- " + " · ".join(few)
                     + "\n      원고 전체에서 적게 쓴 것들이다. 억지로 다 쓰지는 마라 --"
                       " 문장이 그리로 가면 그리로 가게 두라는 뜻이다.")
    over = hogs(chunks)
    if over:
        lines.append(f"  · **이번엔 쉬어라** -- {' · '.join(over)}"
                     "\n      원고에서 이미 너무 많다. 같은 소리가 계속 나면 그게 단조로움이다.")
    fig = figures(seed, n)
    if fig:
        body = " / ".join(f"**{f}**({FIGURES[f]})" for f in fig)
        lines.append(f"  · **이번 대목의 비유** -- {body}"
                     "\n      한 덩어리에 한둘이면 족하다. 매 문단에 넣으면 그것도 버릇이다."
                     " 비유의 재료는 **이 세계 안에 이미 있는 것**에서 가져와라.")
    lines.append(
        "  · **지어내되 있을 법하게.** 여기 있는 것들은 자세해지라는 것이지 이상해지라는"
        " 것이 아니다.\n"
        "      없는 것을 지어내도 되지만 **현실의 테두리 안**이어야 한다 -- 지명·상표·규정·"
        "값·직함이 실제로 그런 것이 있을 법한 꼴이어야 한다.\n"
        "      자세함이 그럴듯함을 만든다: 왜 그렇게 불리는지, 누가 언제 그렇게 정했는지,"
        " 얼마인지, 몇 번째인지. **재서 말하면 진짜가 된다.**\n"
        "      마법도 초능력도 없다. 이상한 일이 일어나도 **사람이 저질러서** 일어난다.")
    for f in forms(seed, n):
        lines.append(f"  · **이번 대목에 섞을 꼴** -- **{f}**: {FORMS[f]}"
                     "\n      한 대목이면 된다. 원고 전체를 이걸로 쓰지 마라 --"
                     " 산문 한가운데 다른 꼴이 하나 끼는 것이 재미다.")
    if not lines:
        return ""
    return "[말맛] **쓰던 것으로만 쓰지 마라 -- 기울면 되민다.**\n" + "\n".join(lines)
