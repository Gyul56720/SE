def feel_rate(text: str) -> float:
    """**서술문에서** 감정에 이름을 붙인 비율. 대사는 안 센다 -- 사람은 자기 기분을
    말하고, 그건 대사가 할 일이다. 화자가 대신 말해 버리면 그때 진단서가 된다."""
    from novel import rhythm
    tell, _ = rhythm._lines(text)
    if not tell:
        return 0.0
    return sum(bool(FEELING.search(s)) for s in tell) / len(tell)


def feel_push(chunks) -> str:
    """**프롬프트에는 안 싣는다.** 재 두기만 한다.

    한때 이것을 프롬프트로 밀었는데, 그것은 초고의 감정을 단속하는 짓이었다 -- 초고에는
    감정이 있어도 좋다. 여기서 잡을 것은 내용이 아니라 방향과 꼴이다. 숫자는 남겨 둔다:
    원고가 어느 쪽으로 기울었는지 나중에 볼 때 쓴다.

    기울었으면 되민다. 안 기울었으면 아무 말도 안 한다.

    무엇과 견주는가 -- **이 원고 자신**이다. 바깥에서 가져온 숫자를 기준으로 삼으면
    그 숫자가 다시 하드코딩이다. 최근 몇 덩어리가 원고 전체 평균보다 도드라지면
    그때만 민다. 원고가 처음부터 담담했으면 여기서 할 일이 없다."""
    if len(chunks) < 3:
        return ""
    rates = [feel_rate(c) for c in chunks]
    whole = sum(rates) / len(rates)
    recent = sum(rates[-3:]) / 3
    if recent <= whole or recent < 0.05:
        return ""
    return ("  · **이번엔 화자가 감정에 이름을 붙이지 마라** -- 최근 서술문에서 "
            f"{recent:.0%}가 그렇게 끝난다(원고 평균 {whole:.0%}).\n"
            "      슬펐다고 적지 말고 **무엇을 했는지** 적어라. 읽는 사람이 알아서 안다.\n"
            "      **대사에서는 자유다** -- 사람은 자기 기분을 말한다. 화자가 대신 말하는 "
            "것만 문제다.")


def _out_share(seed: str, n: int) -> float:
    """이번 덩어리에서 **밖(외현)이 차지할 몫.** 고정하지 않는다 -- 반반으로 박아 두면
    매 덩어리가 반반이 되고, 그 자체가 한 가지 가락이다."""
    from novel import rhythm
    return rhythm.wave(f"{seed}|outshare", n, 0.25, 0.75, 2)


def menu(pool, picked, head: str, tail: str) -> str:
    """**목록 전체를 보여 주고 이번 것만 짚는다.**

    뽑힌 둘만 보여 주면 모델이 아는 것이 둘뿐이 된다 -- 점층 이음말을 넷만 보여 줬다가
    원고가 그 넷으로 도배된 일이 있었다. 반대로 전부를 똑같은 무게로 늘어놓으면
    아무것도 안 고른다(고르라고 시키지 않은 목록은 배경이 된다). 그래서 **이름은 다
    보여 주고 설명은 이번 것에만** 붙인다. 목록 밖도 자유라고 매번 말해 준다."""
    names = list(pool) if isinstance(pool, dict) else list(pool)
    rest = " · ".join(k for k in names if k not in picked)
    if isinstance(pool, dict):
        body = "\n".join(f"      - **{k}** -- {pool[k]}" for k in picked)
    else:
        body = "\n".join(f"      - {k}" for k in picked)
    out = f"  · **{head}** -- 이번 대목은 이것들이다:\n{body}"
    if rest:
        out += f"\n      그 밖에 쓸 수 있는 것: {rest}"
    return out + f"\n      **골라 쓴다. 목록 밖도 자유다.** {tail}"


def brief(chunks, seed: str, n: int) -> str:
    """이번 덩어리에 밀어 넣을 것. 기울지 않았으면 짧아지고, 기울었으면 길어진다."""
    lines = []
    few = thin(chunks)
    if few:
        lines.append("  · **이번 대목에서 써 볼 말끝** -- " + " · ".join(few)
                     + "\n      원고 전체에서 적게 쓴 것들이다. 억지로 다 쓰지는 마라 --"
                       " 문장이 그리로 가면 그리로 가게 두라는 뜻이다.")
    over = hogs(chunks)
    if over:
        lines.append(f"  · **이번엔 쉬어라** -- {' · '.join(over)}"
                     "\n      원고에서 이미 너무 많다. 같은 소리가 계속 나면 그게 단조로움이다.")
    fig = figures(seed, n)
