"""**재미 -- 논문이 말하는 것을 덩어리마다 한 줄로 얹는다.**

## 왜 있나

사용자 평(2026-09-08): "필력도 좋고 대사도 좋은데, 스토리가 재미없어."

문체는 잰 것으로 고쳤다(style.ROPAN). 스토리는 잴 것이 없어서 **연구가 이미 잰 것**을
빌린다. 아래 다섯은 전부 실제 논문이고, 각각이 이 파이프라인의 어느 구멍을 가리키는지
적는다. 지어낸 규칙은 없다 -- 없는 근거로 규칙을 만들면 그 규칙이 다음 사고다.

## 다섯 근거와 다섯 구멍

1. **Brewer & Lichtenstein (1982), 구조-정서 이론.** 재미는 사건이 아니라 **사건을 보여
   주는 순서**에서 온다. 셋뿐이다:
     서스펜스   결과를 **미룬다** -- 독자가 위험을 먼저 알고 인물은 모른다
     궁금증     결과를 **먼저** 보여 주고 원인을 감춘다
     놀람       예상 밖인데 되돌아보면 앞에 근거가 있다
   구멍: DRIFT 는 사건(shock)을 **그 자리에서 다 보여 준다.** 미루는 것도 감추는 것도
   없다. 그래서 일은 많은데 긴장이 없다.

2. **Trabasso & van den Broek (1985), 인과 연결망.** 독자가 중요하다고 느끼고 기억하는
   사건은 극적인 사건이 아니라 **다른 사건과 인과로 많이 이어진 사건**이다.
   구멍: 사건축(genre.event)은 무작위로 뽑힌다. 앞 덩어리와 **인과가 없다.** 프롬프트는
   "이미 있는 것에 붙여라" 고 하지만 무엇에 붙일지 안 준다. 연결이 없는 사건은 아무리
   커도 독자에게 중요하지 않다 -- "일은 벌어지는데 재미없다" 의 정체가 이것이다.

3. **Ely, Frankel & Kamenica (2015), 서스펜스와 놀람.** 서스펜스 = 다음 순간 **믿음이
   얼마나 흔들릴 수 있는가**(분산). 결과가 뻔하면 0 이다. 최적 설계는 믿음을 **오락가락**
   시키는 것이다 -- 한 방향으로만 가면 분산이 죽는다.
   구멍: 성장 단계(serial.STAGES)는 마디 단위로 진다 → 버틴다 → 이긴다 다. 마디 안에서는
   한 방향이다. 지는 마디에서 셋에 하나는 작게 이기고, 이기는 마디에서 셋에 하나는
   되맞아야 믿음이 흔들린다. 웹소설이 고구마 · 사이다 라고 부르는 그것이다.

4. **Zillmann, 정서적 성향 이론 (Knobloch-Westerwick & Keplinger 2006 가 확인).** 서스펜스는
   **좋아하는 인물에게 나쁜 결과가 다가올 때**만 선다. 그러려면 **뜻을 가지고 움직이는
   적**이 있어야 한다.
   구멍: 관계 축에 "웃는 적" 이 있지만 뽑힐 때만 있다. 적이 수를 두지 않는 덩어리가
   대부분이다. 위험이 없으면 서스펜스가 설 자리가 없다.

5. **Loewenstein (1994), 정보 간극.** 궁금증은 **무엇을 모르는지 아는** 순간 생긴다.
   막연히 모르는 것은 궁금하지 않다.
   구멍: 원장의 "열린 것" 은 추출기가 적을 뿐, **독자에게 그것이 열려 있다는 것을
   보여 주라**고는 안 한다. 그리고 덩어리가 답이 난 자리에서 끝난다 -- 웹소설 연재가
   회차 끝을 **답이 안 난 자리**에서 끊는 것(전기수의 침묵)과 반대다.

## 그래서 무엇을 하나

덩어리마다 **[재미] 한 블록**을 당김 바로 뒤에 싣는다. 넷이 들어간다:

    인과     앞 덩어리의 일 → 이번 대목은 그것 **때문에** 시작한다 (Trabasso)
    꼴       이번 대목은 서스펜스 · 궁금증 · 놀람 중 하나로 짠다 (Brewer)
    적       이번 대목에서 적이 한 수 둔다 -- 둘에 하나 (Zillmann)
    끊기     답이 안 난 자리에서 끝낸다 (Loewenstein · 연재)

그리고 마디 안의 **오락가락**(Ely)은 serial.STAGES 위에 셋에 하나를 뒤집는다.

추출은 `chain` 한 칸을 더 받는다 -- "앞의 무엇 → 이번의 무엇". 원장에 사슬로 남아
다음 덩어리가 그것을 이어받는다. 인과가 **말로만** 있으면 다음 덩어리가 잊는다.

## 재지 않는다

이것들은 아직 못 잰다 -- 서스펜스를 정규식으로 셀 수 없다(Wilmot & Keller 2020 은
언어모델로 잰다; 호출이 든다). 그래서 이 모듈은 **프롬프트만** 바꾼다. 잰 값이 생기면
그때 자를 단다. 지어낸 자는 안 단다.
"""
from __future__ import annotations

import hashlib

# 이번 대목의 꼴. 순서는 정해진 것이고 씨앗으로 섞인다 -- 무작위가 아니라서 같은 원고는
# 같은 순서다. 놀람은 여섯에 하나다: 자주 놀라면 놀람이 아니다(Brewer: 놀람은 드물어야
# 되돌아볼 근거가 선다).
SHAPES = (
    ("서스펜스", "**독자가 먼저 안다.** 이 대목의 어딘가에서 독자는 위험 하나를 보고 인물은"
                " 못 본다 -- 문 뒤의 사람, 바꿔치기된 잔, 이미 떠난 마차. 그리고 그 위험은"
                " **이 대목에서 터지지 않는다.** 터질 자리 직전에서 끊어라."),
    ("궁금증", "**결과가 먼저다.** 이 대목은 이미 벌어진 것 하나로 연다 -- 깨진 인장,"
              " 빈 침소, 돌아온 편지. **왜** 그렇게 됐는지는 이 대목이 끝나도 안 나온다."
              " 인물이 그 이유를 찾아 움직이고, 찾은 것은 절반이다."),
    ("서스펜스", "**시계가 간다.** 이 대목 안에 정해진 때가 있다 -- 종이 치기 전에, 연회가"
                " 끝나기 전에, 그가 돌아오기 전에. 인물이 그때까지 해야 할 일이 있고,"
                " 방해가 하나 들어온다. 때가 되기 **직전**에서 끊어라."),
    ("궁금증", "**한 사람이 안 하는 말.** 이 대목에서 누군가 알고 있는 것을 말하지 않는다."
              " 독자는 그가 안다는 것을 안다 -- 손이 멈추거나, 대답이 반 박자 늦거나."
              " 무엇을 아는지는 안 나온다."),
    ("서스펜스", "**독자가 먼저 안다.** 이 대목의 어딘가에서 독자는 위험 하나를 보고 인물은"
                " 못 본다. 그리고 그 위험은 **이 대목에서 터지지 않는다.** 터질 자리 직전에서"
                " 끊어라."),
    ("놀람", "**예상 밖인데 근거가 있다.** 이 대목에서 하나가 독자의 예상과 반대로 간다 --"
            " 편일 줄 알았던 사람이 적이거나, 죽은 줄 알았던 것이 살아 있거나. 다만 [세계]에"
            " **이미 놓인 것**에서 나와야 한다. 새 것을 꺼내 놀래키면 그건 놀람이 아니라"
            " 속임수다. 되돌아보면 앞에 있었던 것으로 해라."),
)


def _pick(seed: str, n: int, size: int) -> int:
    h = hashlib.sha1(f"{seed}|{n}".encode("utf-8")).hexdigest()
    return int(h[:8], 16) % size


def shape(book: dict) -> tuple:
    """이번 덩어리의 꼴. 씨앗과 덩어리 번호로 정해진다."""
    n = len(book.get("chunks") or [])
    seed = str(book.get("seed_id") or book.get("first") or "")
    return SHAPES[_pick(seed, n, len(SHAPES))]


def enemy_moves(book: dict) -> bool:
    """이번 대목에서 적이 한 수 두는가. **둘에 하나.** 매번이면 적이 배경이 된다."""
    n = len(book.get("chunks") or [])
    seed = str(book.get("seed_id") or book.get("first") or "")
    return _pick(seed + "|enemy", n, 2) == 0


def swing(book: dict, stage_name: str) -> str:
    """마디 안의 오락가락 (Ely et al.). 셋에 하나는 단계와 **반대로** 간다.

    지는 마디에서 작게 이기는 덩어리가 사이다이고, 이기는 마디에서 되맞는 덩어리가
    다음 사이다의 값이다. 한 방향으로만 가면 믿음의 분산이 0 -- 서스펜스가 죽는다."""
    n = len(book.get("chunks") or [])
    seed = str(book.get("seed_id") or book.get("first") or "")
    if _pick(seed + "|swing", n, 3) != 0:
        return ""
    if stage_name == "진다":
        return ("**이번 한 대목은 작게 이긴다.** 큰 판은 여전히 지는 중인데, 여기서 한 가지가"
                " 처음으로 화자 쪽으로 온다 -- 사람 하나, 문서 한 장, 말 한 마디. 독자가"
                " 숨을 한 번 쉬게 하고, 다음 대목에서 그 값을 치르게 해라.")
    if stage_name == "이긴다":
        return ("**이번 한 대목은 되맞는다.** 이기는 중인데 여기서 하나를 잃는다. 이겨야"
                " 할 것이 뻔해지면 아무도 안 읽는다 -- 결과가 흔들려야 다음 장을 넘긴다.")
    return ("**이번 한 대목은 한쪽으로 기운다.** 버티던 판이 잠깐 무너지거나 잠깐 열린다."
            " 어느 쪽이든 다음 대목에서 되돌아온다.")


def _last_links(book: dict, k: int = 2) -> list:
    chain = (book.get("ledger") or {}).get("chain") or []
    return [c for c in chain if isinstance(c, str) and c.strip()][-k:]


def _fresh_open(book: dict, k: int = 2) -> list:
    """가장 최근에 열린 것. 원장은 나이를 `_age` 에 둔다 -- 없으면 뒤에서부터."""
    L = book.get("ledger") or {}
    opn = L.get("open") or {}
    if not opn:
        return []
    age = L.get("_age") or {}
    names = sorted(opn, key=lambda x: age.get(x, -1), reverse=True)
    return [f"{x}: {opn[x]}" for x in names[:k]]


def brief(book: dict, stage_name: str = "") -> str:
    """**[재미] 블록.** 당김 바로 뒤에 실린다. 첫 덩어리에는 인과가 없으니 꼴과 끊기만."""
    n = len(book.get("chunks") or [])
    name, how = shape(book)
    rows = []

    # 인과 -- Trabasso. 앞 덩어리의 사슬과 열린 것을 **이름을 대고** 준다.
    if n:
        links = _last_links(book)
        opens = _fresh_open(book)
        src = links or opens
        if src:
            rows.append("  · **이 대목은 앞 대목의 결과로 시작한다.** 앞에서 벌어진 것: "
                        + " / ".join(src)
                        + "\n      이번 대목의 일은 이 중 하나 **때문에** 벌어져야 한다."
                        " 새 일을 들이려면 이것에 붙여서 들여라. 붙을 데가 없는 사건은"
                        " 아무리 커도 독자에게 중요하지 않다.")
        else:
            rows.append("  · **이 대목은 앞 대목의 결과로 시작한다.** 앞 대목에서 벌어진 일"
                        " 하나를 골라 그것 때문에 이번 일이 벌어지게 해라.")

    # 꼴 -- Brewer & Lichtenstein.
    rows.append(f"  · 이번 대목의 꼴은 **{name}**이다. {how}")

    # 적 -- Zillmann. 둘에 하나.
    if enemy_moves(book):
        rows.append("  · **적이 한 수 둔다.** 화자를 꺾으려는 사람이 이 대목에서 실제로"
                    " 무엇을 한다 -- 사람을 옮기거나, 말을 흘리거나, 문서를 바꾼다. 독자는"
                    " 그것을 보고 화자는 다는 못 본다. 적에게 이유가 있어야 한다; 나쁘기"
                    " 때문에 나쁜 짓을 하는 사람은 없다.")

    # 오락가락 -- Ely et al.
    sw = swing(book, stage_name) if stage_name else ""
    if sw:
        rows.append("  · " + sw)

    # 끊기 -- Loewenstein · 연재.
    rows.append("  · **답이 안 난 자리에서 끝낸다.** 마지막 문장은 문이 열리거나, 이름이"
                " 불리거나, 편지가 펼쳐진 채로다. 정리하고 끝내지 마라 -- 정리는 다음"
                " 대목의 첫 줄이 한다. 독자가 무엇을 모르는지 **알게** 하고 끊어라.")

    return "[재미] **일은 순서가 만든다**\n" + "\n".join(rows)


def show(book: dict) -> str:
    """사람이 보는 것 -- 지금 원고에 남은 사슬."""
    chain = (book.get("ledger") or {}).get("chain") or []
    if not chain:
        return "사슬이 없다 -- 아직 추출이 chain 을 안 냈다."
    return "\n".join(f"  {i + 1}. {c}" for i, c in enumerate(chain[-12:]))
