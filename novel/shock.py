def _raw(pool: tuple, seed: str, n: int, axis: str) -> int:
    h = hashlib.sha256(f"{seed}|{n}|{axis}".encode()).digest()
    return int.from_bytes(h[:8], "big") % len(pool)


# 연속 중복을 피하려고 뒤로 이만큼만 거슬러 본다. 전부 거슬러 올라갈 필요는 없다 --
# 직전 것과만 안 겹치면 되고, 그 직전 것도 같은 규칙으로 정해졌다.
_LOOKBACK = 8


def _pick(pool: tuple, seed: str, n: int, axis: str):
    """축마다 **따로** 해시해서 고르고, **직전 사건과 같으면 한 칸 민다.**

    처음엔 축 다섯을 한 난수원에서 연달아 뽑았는데, 씨앗 문자열이 한 글자만 다르다 보니
    이웃한 사건끼리 값이 붙어 나왔다(실측: 0~3번 사건의 온도가 넷 다 '시시하게'). 연달아
    터지는 사건이 같은 톤이면 신선함이 죽는다. 그래서 축 이름까지 넣어 따로 해시한다.

    미는 것도 **확정된 직전 값**과 비교해야 한다. 날값끼리만 비교하면, 직전이 이미 밀려서
    옮겨 온 자리와 겹치는 경우를 놓친다(실측: 그렇게 해도 연속 중복이 300번에 14번 남았다).
    """
    start = max(0, n - _LOOKBACK)
    prev = None
    for k in range(start, n + 1):
        i = _raw(pool, seed, k, axis)
        if prev is not None and i == prev:
            i = (i + 1) % len(pool)
        prev = i
    return pool[prev]


def draw(seed: str, n: int) -> dict:
    """n 번째 사건. 씨앗에 묶여 있어 이어 쓰기에도 같은 것이 나온다."""
    out = {axis: _pick(pool, seed, n, axis) for axis, pool in
           (("who", WHO), ("how", HOW), ("mark", MARK),
            ("scale", SCALE), ("tone", TONE))}
    # 셋에 하나쯤은 주인공이 불러온 사건이다 -- 급발진과 사건이 따로 놀지 않게.
    out["mine"] = _raw(("자기", "남", "남"), seed, n, "mine") == 0
    return out


def due(chars_since: int, ledger_size: int, level: float = 1.0) -> bool:
    """터뜨릴 때인가 -- 분량이 찼거나, 원장이 부풀어 프롬프트가 무거워졌거나.

    계수가 낮으면 **간격이 벌어진다**(0.8 이면 2,500자마다). 다만 원장이 부푼 경우는
    계수와 무관하게 터뜨린다 -- 그건 취향이 아니라 프롬프트가 무거워지는 기술적 한계다.
    """
    every = EVERY / level if level > 0 else float("inf")
    return chars_since >= every or ledger_size >= PRESSURE


