"""**의심** -- 세워 둔 것을 흔든다. 뒤집지 않고 흔든다.

수학이 가장 크게 넓어진 자리는 공리를 의심한 자리다. 평행선 공리를 부정해도 무모순인
세계가 있다는 것이 밝혀지면서 기하학은 하나가 아니게 됐다. 공리를 **틀렸다고** 한 것이
아니다 -- **꼭 그래야 하는 것은 아니라고** 한 것이다.

소설에서 그것을 그대로 하면 게이트와 정면으로 부딪힌다. 원장에 적힌 것을 뒤집는 것은
이 파이프라인이 유일하게 죽이는 일이다. 그래서 자리를 가른다.

  · **사실을 뒤집기** -- 마흔둘이던 사람이 서른이 된다. 세계가 무너진다. 계속 금지.
  · **출처를 흔들기** -- 그가 마흔둘이라는 것은 누가 말했나? 그 사람은 어떻게 알았나?
    아무도 확인한 적이 없다. **사실은 그대로 있고, 그것의 지반만 흔들린다.**

둘째가 여기서 하는 일이다. 원장은 한 글자도 안 바뀌는데 독자가 읽는 것이 달라진다.
그리고 이것은 새 미결을 낳는다 -- 흔들린 것은 아직 안 닫힌 것이 된다.

같은 원리가 시점에도 걸린다. **누가 주인공인가는 사실이 아니라 믿음이다.** 자기를
주인공으로 자처하는 사람이 나오고, 독자가 어느 순간 그를 주인공이라고 믿고, 그러다
그 믿음이 옮겨간다 -- 그동안 원장은 아무것도 안 바뀐다. 그것도 여기 있다.
"""
