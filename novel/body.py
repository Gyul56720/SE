def _raw(pool: tuple, seed: str, n: int, axis: str) -> int:
    h = hashlib.sha256(f"{seed}|{n}|body|{axis}".encode()).digest()
    return int.from_bytes(h[:8], "big") % len(pool)


def _pick(pool: tuple, seed: str, n: int, axis: str):
    """직전과 겹치면 민다 -- shock.py 와 같은 규칙이다. 같은 몸이 연달아 나오면
    두 인물이 한 사람처럼 읽힌다."""
    prev = None
    for k in range(max(0, n - 8), n + 1):
        i = _raw(pool, seed, k, axis)
        if prev is not None and i == prev:
            i = (i + 1) % len(pool)
        prev = i
    return pool[prev]


def draw(seed: str, n: int) -> dict:
    return {"fact": _pick(FACT, seed, n, "fact"), "use": _pick(USE, seed, n, "use")}


def gate(seed: str, n: int, rate: float) -> bool:
    """매 덩어리에 넣으면 소설이 진료 기록이 된다. 셋에 하나쯤만."""
    if rate >= 1.0:
        return True
    h = hashlib.sha256(f"{seed}|{n}|body|gate".encode()).digest()
    return (int.from_bytes(h[:8], "big") % 1000) < rate * 1000


