CATS = {"전개": EVENTS, "연출": STAGING, "대사": LINES, "인물": CHARS, "빌드업": PLANTING,
        "전투": BATTLE, "세계": WORLD, "쾌감": PAYOFF, "줄기": ARCS}


def draw(cat: str, seed: str, n: int, k: int) -> list:
    """이번 회차(또는 덩어리)에 보여 줄 본보기 k개. 씨앗과 번호로 정해진다 -- 같은 원고는 같다."""
    items = CATS[cat]
    h = hashlib.sha1(f"{seed}|space|{cat}|{n}".encode("utf-8")).digest()
    order = sorted(range(len(items)), key=lambda i: h[i % len(h)] * 31 + i * 7 + n)
    return [items[i] for i in order[:k]]


def render(cat: str, seed: str, n: int, k: int) -> str:
    return "\n".join(f"    {name}: {rule}" for name, rule, _ in draw(cat, seed, n, k))


def rules(cat: str) -> str:
    """빌드업처럼 **다 실어야 하는** 칸. 돌리지 않는다."""
    return "\n".join(f"    {name}: {rule}" for name, rule, _ in CATS[cat])


def names(cat: str) -> list:
    return [name for name, _, _ in CATS[cat]]
