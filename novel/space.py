# 뽑기에서 빼고 **늘 싣는** 머리 항목의 수. 조건이지 본보기가 아닌 것들이다.
HEAD = {"부상": 2,          # 부위를 댄다 · 기전을 댄다 -- 리얼리티의 뿌리다
        "수위": 2,          # 어른만 · 원하는지가 보인다 -- 조건이라 늘 실린다
        "액션": 1}         # 한 문장에 동작 하나 -- 싸우는 자리에 늘 실린다


def draw(cat: str, seed: str, n: int, k: int, skip: int = 0) -> list:
    """이번 회차(또는 덩어리)에 보여 줄 본보기 k개. 씨앗과 번호로 정해진다 -- 같은 원고는 같다.

    `skip` 은 앞에서 몇 개를 뽑기에서 뺄지다. 늘 싣는 머리 항목이 뽑기에 또 걸리면
    같은 줄이 두 번 실린다."""
    items = CATS[cat][skip:]
    h = hashlib.sha1(f"{seed}|space|{cat}|{n}".encode("utf-8")).digest()
    order = sorted(range(len(items)), key=lambda i: h[i % len(h)] * 31 + i * 7 + n)
    return [items[i] for i in order[:k]]


def render(cat: str, seed: str, n: int, k: int, skip: int = 0) -> str:
    return "\n".join(f"    {name}: {rule}"
                     for name, rule, _ in draw(cat, seed, n, k, skip))


def head(cat: str) -> str:
    """늘 싣는 머리 항목. 없으면 빈 것."""
    return "\n".join(f"    {name}: {rule}"
                     for name, rule, _ in CATS[cat][:HEAD.get(cat, 0)])


def rules(cat: str, k: int = 0) -> str:
    """빌드업처럼 **규칙으로 실어야 하는** 칸. k 를 주면 앞 k 개만(핵심)."""
    items = CATS[cat][:k] if k else CATS[cat]
    return "\n".join(f"    {name}: {rule}" for name, rule, _ in items)


def names(cat: str) -> list:
    return [name for name, _, _ in CATS[cat]]


def total() -> int:
    """별칭은 한 번만 센다."""
    return sum(len(v) for v in {id(v): v for v in CATS.values()}.values())
