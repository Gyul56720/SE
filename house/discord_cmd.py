# **실측 2026-09-22.** 사용자가 스펙 파일을 붙여 보냈고 봇이 이렇게 답했다:
#
#     **못 띄웠다.** 로그: `/home/ubuntu/SE/logs/house-arch-20260922-141726.log`
#
# **이 답은 두 가지로 틀렸다.**
#
#   1. 못 띄운 것이 아니었다. 프로세스는 떴고, 돌았고, 0.25초 안에 종료코드 2 로
#      끝났다 -- `pgrep` 의 첫 조회보다 빨랐다. "안 보인다" 를 "안 떴다" 로 읽었다.
#   2. 까닭이 로그에 적혀 있는데 그 로그가 **VM 에 있다.** 디스코드로 말을 거는
#      사람은 그 파일을 영영 못 본다. 사람 몫으로 넘긴 셈인데, 이 저장소의 규율은
#      **사람에게 시키지 않는 것**이다.
#
# 그래서 안 보이면 **로그를 열어 무슨 일인지 읽고, 그 꼬리를 답에 싣는다.**
def _무슨일(로그: Path, 줄수: int = 12) -> dict:
    """pgrep 이 못 찾았을 때 실제로 무슨 일이었나. {"갈래","꼬리"}.

    갈래는 셋뿐이고 **모르면 '모르겠다' 라고 한다** -- 모르는 것을 '안 떴다' 로
    적으면 이 답이 거짓말이 되고, 거짓말하는 답은 없느니만 못하다.
    """
    try:
        글 = 로그.read_text(encoding="utf-8", errors="replace")
    except OSError:
        return {"갈래": "모르겠다", "꼬리": []}
    줄 = [x for x in 글.splitlines() if x.strip()]
    if not 줄:
        return {"갈래": "안떴다", "꼬리": []}
    if any("Traceback" in x for x in 줄):
        return {"갈래": "죽었다", "꼬리": 줄[-줄수:]}
    return {"갈래": "끝났다", "꼬리": 줄[-줄수:]}


def 못띄운글(r: dict) -> str:
    """`_띄우기` 가 실패했을 때 사람에게 내는 말. **까닭을 같이 싣는다.**"""
    갈 = r.get("갈래", "모르겠다")
    꼬 = r.get("꼬리") or []
    머리 = {
        "안떴다": "**못 띄웠습니다.** 로그가 비어 있습니다 — 프로세스가 아예 안 떴습니다.",
        "죽었다": "**떴다가 죽었습니다.** 로그 끝은 이렇습니다:",
        "끝났다": "**떴는데 곧바로 끝났습니다.** (`pgrep` 의 첫 조회보다 빨랐습니다.) "
                "로그 끝은 이렇습니다:",
        "모르겠다": "**떠 있는지 모르겠습니다.** 로그를 못 읽었습니다.",
    }[갈]
    줄 = [머리]
    if 꼬:
        줄.append("```\n" + "\n".join(x[:200] for x in 꼬[-12:]) + "\n```")
    줄.append(f"_로그: `{r.get('로그')}`_")
    return "\n".join(줄)


def _메일줄(메일: bool) -> str:
    """답 끝에 붙이는 한 줄. **보낼 수 있는지 지금 확인해서 적는다** -- 나중에 조용히
    실패하면 사람은 기다리기만 한다."""
    if not 메일:
        return "_메일은 끄고 돌립니다(`메일없이`). 끝나면 채널로 알립니다._"
    m = 메일된다()
    if m["된다"]:
        return "📧 **끝나면 보고서 PDF 를 첨부해 메일로 보냅니다.** 채널에도 알립니다."
    return (f"⚠ **끝나도 메일은 못 나갑니다** — {m['말']}\n"
            f"  (일은 그대로 돌고, 보고서 PDF 는 `house/out/` 에 남습니다. "
            f"채널로도 알립니다.)")


def 메일된다() -> dict:
    """**보내기 전에 미리 묻는다.** 여섯 분을 돌고 나서 "받는 주소를 모른다" 로 끝나면
    그 여섯 분이 버려진다 -- 사람은 메일을 기다리고 있는데 아무것도 안 온다.

    `mailer.필요한것()` 이 빠진 열쇠를 돌려주고, `USER_EMAIL` 이 없으면 보낼 곳이 없다.
    둘 다 사람이 `!열쇠 이름=값` 한 줄로 준다."""
    sys.path.insert(0, str(REPO))
    try:
        import mailer
    except Exception as e:                                    # noqa: BLE001
        return {"된다": False, "빠진": ["mailer"], "말": f"{type(e).__name__}: {e}"}
    빠진 = list(mailer.필요한것() or [])
    if not (mailer.내정보() or {}).get("주소"):
        빠진.append("USER_EMAIL")
    빠진 = list(dict.fromkeys(빠진))
    return {"된다": not 빠진, "빠진": 빠진,
            "말": ("보낼 수 있다" if not 빠진 else
                  "메일을 못 보낸다 -- " + " · ".join(f"`!열쇠 {k}=<값>`" for k in 빠진))}


def _표(줄들: "list[dict]") -> str:
    if not 줄들:
        return "_아직 낸 보고서가 없다._"
    out = []
    for d in 줄들:
        if not d.get("됐나"):
            out.append(f"· ❌ {d.get('이름')} — {d.get('까닭', '')[:80]}")
            continue
        메 = d.get("메일")
        꼬 = " · 📧" if 메 else ""
        out.append(f"· ✅ {d.get('이름')} — `{Path(d.get('pdf', '')).name}` "
                  f"{d.get('쪽')}쪽 / 그림 {d.get('그림')} / 표 {d.get('표')} / "
                  f"{d.get('초')}s{꼬}  ({d.get('때', '')[:16]})")
    return "\n".join(out)


