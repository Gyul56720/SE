# ---------------------------------------------------------------- 자리표와 두 줄
# **실측 2026-09-22.** 내가 답으로 준 두 줄을 사용자가 통째로 붙여 넣었다.
#
#     !회사 <MERA 스펙 첨부 또는 본문>
#     !회사 승인
#
# 봇은 이렇게 답했다:
#
#     **누구를 말하는지 모르겠다**: `<MERA 스펙 첨부 또는 본문> !회사 승인`
#
# 두 가지가 한꺼번에 틀렸다.
#
#   · `나머지.split()` 이 **줄바꿈까지 공백으로 뭉갠다.** 그래서 두 명령이 한 요청이
#     됐다. 둘째 줄의 `!회사` 가 첫 요청의 낱말이 되어 버린다.
#   · `<...>` 자리표가 그대로 들어왔는데 "모르겠다" 로만 답했다 -- **무엇을 고치면
#     되는지는 한 글자도 안 알려 준다.** 이 저장소가 자리표로 앓은 것이 다섯 번째다.
#
# 그래서 "모르겠다" 대신 **무엇이 잘못됐고 무엇을 치면 되는지**를 낸다.
_자리표꼴 = re.compile(r"<[^<>]{1,40}>")


def 자리표(첫줄: str) -> str:
    """붙여 넣다 만 자리표(`<...>`)면 그것을, 아니면 빈 글.

    **긴 글에는 안 문다.** 스펙 본문에 `<` 와 `>` 가 우연히 짝지어 들어갈 수 있는데,
    그것을 자리표로 읽으면 **멀쩡한 스펙을 거절한다** -- 고치려던 것보다 나쁘다.
    자리표는 짧은 명령 줄에만 남으므로 거기서만 본다.
    """
    if len(첫줄) > 120:
        return ""
    m = _자리표꼴.search(첫줄)
    return m.group(0) if m else ""


def 줄가르기(나머지: str) -> "tuple[str, list[str]]":
    """(첫 명령, 뒤에 붙은 다른 `!회사` 명령들). **뭉개지 않는다.**

    여러 줄이어도 `!회사` 가 하나뿐이면 그대로 둔다 -- 스펙 본문이 여러 줄인 것은
    잘못이 아니다. 가르는 것은 **뒤에 또 명령이 있을 때**뿐이다.
    """
    줄들 = [x.strip() for x in 나머지.splitlines() if x.strip()]
    if not 줄들:
        return 나머지.strip(), []
    뒤 = [x for x in 줄들[1:] if x.lower().startswith(PREFIX)]
    if not 뒤:
        return 나머지.strip(), []
    return 줄들[0], 뒤


def run(text: str, runner=None, allow_write: bool = True) -> "str | None":
    """모르는 말에는 None. 그러면 봇이 예전처럼 에이전트로 넘긴다."""
    t = (text or "").strip()
    if not t.startswith(PREFIX):
        return None
    나머지 = t[len(PREFIX):].strip()
    if not 나머지 or 나머지 in ("도움", "help", "?"):
        return _도움()

    나머지, 뒤명령 = 줄가르기(나머지)

    자리 = 자리표(나머지)
    if 자리:
        return (f"**자리표가 그대로 들어왔습니다**: `{자리}`\n\n"
                "`<...>` 는 *여기에 진짜 내용을 넣으세요* 라는 뜻입니다 — 꺾쇠까지 "
                "같이 보내시면 회사는 무엇을 만들라는 것인지 읽을 수 없습니다.\n\n"
                "**스펙이 길면 파일로 붙이세요.** `.md` · `.txt` 를 끌어다 넣고 "
                "`!회사` 한 마디만 적으면 본문에 이어 붙여 읽습니다 — "
                "디스코드 2000자 벽을 그렇게 넘습니다.")

    답 = _한명령(나머지, allow_write=allow_write)
    if 답 is None or not 뒤명령:
        return 답
    return (답 + "\n\n---\n**한 메시지에 명령이 둘이었습니다 — 첫 줄만 돌렸습니다.**\n"
            + "\n".join(f"· 안 돌린 것: `{x[:70]}`" for x in 뒤명령)
            + "\n_하나씩 따로 보내 주세요. 앞엣것이 끝나야 뒤엣것이 뜻이 있습니다._")


def _한명령(나머지: str, allow_write: bool = True) -> "str | None":
    낱말 = 나머지.split()
    머리 = 낱말[0].lower()
    # **메일은 기본으로 켠다.** 사용자(2026-09-21): "이메일로 보고서 자동으로 보내야지."
    # 다 된 보고서가 디스크에만 남아 있는 것은 낸 것이 아니다. 끄고 싶으면 `메일없이`.
    메일없이 = any(w in ("메일없이", "nomail", "메일빼고") for w in 낱말)
    메일 = not 메일없이

    # ---- 준비 ----
    if 머리 in ("준비", "ready", "점검", "준비됐나"):
        return 준비글(준비())

    # ---- 승인 -> RTL·TB 생성 ----
    # 사용자(2026-09-22): 제안서를 보고 "하나로 진행". 흐름 그림의 `사람 승인` 칸을
    # 탈 길이 없었다 -- 그림에는 있는데 명령이 없었고, `!회사 rtl` 은 **고정 회로**를
    # 돌릴 뿐 승인한 스펙을 안 본다. 그림이 약속한 것을 코드가 안 하고 있었다.
    if 머리 in ("승인", "짓기", "approve", "go"):
        if not allow_write:
            return "`!회사 승인` 은 RTL 을 짓고 파일을 냅니다 — 지금은 쓰기가 막혀 있습니다."
        if _도나():
            return "**이미 돌고 있다.** `!회사 상태` 로 확인해라."
        sys.path.insert(0, str(REPO))
        from house import arch as _ARCH
        from house import gen as _GEN
        키 = " ".join(w for w in 낱말[1:] if not w.startswith("메일")).strip()
        둔것 = _ARCH.둔스펙들()
        if not 둔것:
            return ("**승인할 제안서가 없습니다.** 먼저 설계를 돌려 주세요 — "
                    "만들 것을 그냥 적으시면 됩니다.\n"
                    "_제안서를 보고 나서 `!회사 승인` 하시면 그때 RTL 을 짓습니다._")
        if not 키 and len(둔것) > 1:
            return ("**어느 것을 승인하시는지 알려 주세요.**\n"
                    + "\n".join(f"· `!회사 승인 {k}`" for k in 둔것))
        키 = 키 or 둔것[0]
        if 키 not in 둔것:
            return (f"**`{키}` 로 둔 스펙이 없습니다.**\n"
                    + "\n".join(f"· `!회사 승인 {k}`" for k in 둔것))
        쓸 = _GEN.쓸수있나()
        if not 쓸["됨"]:
            # **못 지으면 띄우지 않는다.** 돌려 놓고 빈 손으로 끝나면 사람이 기다린다.
            return (f"**RTL 을 못 짓습니다 — {쓸['말']}**\n"
                    "_제안서는 그대로 있습니다. 갖춰지면 `!회사 승인` 을 다시 치세요._")
        r = _띄우기(["--승인", 키] + (["--메일"] if 메일 else []), "gen")
        if not r["떴나"]:
            return 못띄운글(r)
        s0 = _ARCH.스펙꺼내기(키)
        줄 = [f"**승인받았습니다 — `{키}` 의 RTL·TB 를 짓습니다.** (백그라운드)",
             f"· 로그: `{r['로그']}`",
             "",
             "**제안서를 낸 그 스펙 그대로 짓습니다** — 요청 글을 다시 읽지 않습니다. "
             "다시 읽으면 모델이 또 다르게 채우고, 그러면 보신 것과 다른 것이 나옵니다.",
             ""]
        if s0 is not None:
            줄.append(f"· 블록 {len(s0.블록 or [])}개 · 포트 {len(s0.포트 or [])}개 "
                     f"· 검증 시나리오 {len(s0.검증계획 or [])}개")
            if s0.모른다:
                줄.append(f"· ⚠ **아직 모르는 것이 {len(s0.모른다)}개 남아 있습니다** — "
                         "그 칸은 기본값으로 채워집니다")
        줄 += ["",
              "**관문 7개를 지나야 등록됩니다**(문법 · 두 번째 도구 · 빌드 · 골든 대조 · "
              "재현 · 합성 · STA). 하나라도 빨가면 모델에 돌려주고 다시 시킵니다. "
              "그래도 안 되면 **'못 지었다' 로 보고합니다** — 반쯤 된 RTL 위에 "
              "다음 단계를 쌓지 않습니다.",
              "",
              "`!회사 상태` 로 진행을 봅니다."]
        return "\n".join(줄)

    # ---- 상태 ----
    if 머리 in ("상태", "status"):
        도 = _도나()
        줄 = ["**돌고 있다** — " + f"{len(도)}개" if 도 else "**지금 도는 작업이 없다.**"]
        for l in 도[:3]:
            줄.append(f"  `{l[:150]}`")
        최근 = sorted(로그방.glob("house-*.log"), key=lambda p: p.stat().st_mtime)[-1:] \
            if 로그방.exists() else []
        if 최근:
            꼬리 = 최근[0].read_text(encoding="utf-8", errors="replace").splitlines()[-6:]
            줄.append(f"\n마지막 로그 `{최근[0].name}`:")
            줄 += ["  " + x[:150] for x in 꼬리]
        줄.append("\n**마지막에 낸 것**\n" + _표(_원장읽기(5)))
        return "\n".join(줄)

    # ---- 회로 목록 ----
    if 머리 in ("회로", "설계목록", "designs"):
        sys.path.insert(0, str(REPO))
        from house import designs as DES
        return ("**맡고 있는 회로**\n" + DES.목록글()
                + "\n\n`!회사 <사람> <회로>` 로 회로를 고른다 (예: `!회사 검증 fir`).\n"
                  "새 회로는 `!회사 설계 <무엇을 만들지 한국어로>`.")

    # ---- 새 회로 구상 ----
    if 머리 in ("설계", "구상", "design", "새회로"):
        # **몸통은 `설계돌리기()` 하나뿐이다.** 여기와 자연어 길이 두 벌이면 한쪽만
        # 고치게 된다 -- 이 저장소가 여러 번 앓은 병이다.
        return 설계돌리기(나머지[len(낱말[0]):].strip(), 메일=메일,
                      allow_write=allow_write)["글"]
    # ---- 보고서 목록 ----
    if 머리 in ("보고서", "reports", "목록"):
        pdfs = sorted(내는곳.glob("*.pdf"), key=lambda p: p.stat().st_mtime, reverse=True) \
            if 내는곳.exists() else []
        if not pdfs:
            return "_아직 낸 보고서가 없다._ `!회사 전체` 로 다섯 명을 돌려라."
        줄 = [f"**{len(pdfs)}개** (`house/out/`)"]
        for p in pdfs[:12]:
            줄.append(f"· `{p.name}` — {p.stat().st_size/1e3:,.0f} kB · "
                     f"{time.strftime('%Y-%m-%d %H:%M', time.localtime(p.stat().st_mtime))}")
        return "\n".join(줄)

    if not allow_write:
        return ("`!회사` 는 도구를 실제로 돌리고 파일을 낸다 — 지금은 쓰기가 막혀 있다. "
                "`!회사` 만 쳐서 조직도를 보거나 `!회사 보고서` 로 이미 낸 것을 봐라.")

    # ---- 전체 ----
    if 머리 in ("전체", "다", "all", "모두"):
        if _도나():
            return ("**이미 돌고 있다.** 두 벌 띄우면 같은 파일을 서로 덮는다.\n"
                    "`!회사 상태` 로 어디까지 왔는지 봐라.")
        인자 = (["--메일"] if 메일 else []) + (["--빠르게"] if "빠르게" in 낱말 else [])
        r = _띄우기(인자, "all")
        if not r["떴나"]:
            return 못띄운글(r)
        return (f"**다섯 명을 백그라운드로 시작했다** (살아있는 것을 `pgrep` 으로 확인했다).\n"
                f"· 로그: `{r['로그']}`\n"
                f"· 프로세스: `{r['프로세스'][0][:120]}`\n"
                + ("· " + _메일줄(메일) + "\n")
                + "`!회사 상태` 로 진행을 본다. 다섯 명 다 도는 데 수십 분 걸린다.")

    # ---- 한 사람 ----
    people = _people()
    후보 = " ".join(w for w in 낱말 if w not in ("메일", "mail", "보내", "gmail", "빠르게",
                                                "메일없이", "nomail", "메일빼고"))
    p = people.find(후보)
    if p is None:
        # **이름이 아니면 요청으로 읽는다** -- 위 `요청으로읽히나()` 의 기록 참고.
        if 요청으로읽히나(나머지):
            r = 설계돌리기(나머지, 메일=메일, allow_write=allow_write)
            머리말 = ("_(`설계` 라고 안 쓰셔도 됩니다 — 요청으로 읽었습니다.)_\n\n"
                   if r["돌았나"] else "")
            return 머리말 + r["글"]
        return (f"**누구를 말하는지 모르겠다**: `{후보[:70]}`\n\n"
                "_이름 말고 **만들 것을 그냥 적어도 됩니다** — "
                "`!회사 500MHz 8탭 FIR 필터 만들어줘` 처럼요. "
                "다만 회로 갈래나 수가 하나도 안 읽히면 돌리지 않습니다 "
                "(빈 제안서가 나오기 때문입니다)._\n\n" + _도움())
    if _도나():
        return ("**이미 돌고 있다.** `!회사 상태` 로 확인해라 — "
                "두 벌 띄우면 같은 `house/out/` 파일을 서로 덮는다.")
    # 회로 이름이 같이 왔나
    회로 = None
    try:
        sys.path.insert(0, str(REPO))
        from house import designs as DES
        표 = DES.읽기()
        for w in 낱말[1:]:
            k = w.strip().lower()
            if k in 표:
                회로 = k
                break
    except Exception:                                        # noqa: BLE001
        pass
    인자 = [p.키] + (["--회로", 회로] if 회로 else []) \
        + (["--메일"] if 메일 else []) + (["--빠르게"] if "빠르게" in 낱말 else [])
    r = _띄우기(인자, p.키)
    if not r["떴나"]:
        return 못띄운글(r)
    return (f"**{p.name}** ({p.team} / {p.title}) 에게 "
            + (f"회로 `{회로}` 를 " if 회로 else "") + "넘겼다.\n"
            f"· 맡은 것: {p.tagline}\n"
            f"· 로그: `{r['로그']}`\n"
            + ("· 끝나면 보고서 PDF 를 첨부해 메일로 보낸다.\n" if 메일
               else "· 끝나면 `house/out/` 에 PDF 가 생긴다. 메일까지 보내려면 "
                    f"`!회사 {p.키} 메일`.\n")
            + "`!회사 상태` 로 진행을 본다.")
