def _꼬리(이름: str) -> str:
    """`m_axi_awlen` -> `awlen`.  접두사를 떼고 마지막 토막만."""
    return (이름 or "").rsplit("_", 1)[-1].lower()


def _묶음이름(이름: str) -> str:
    """`m_axi_awlen` -> `m_axi`.  같은 인터페이스에 속한 포트를 묶는 열쇠."""
    조각 = (이름 or "").split("_")
    return "_".join(조각[:-1]) if len(조각) > 1 else ""


def _글(x) -> str:
    return "" if x is None else str(x)


def _폭(p) -> "int | None":
    try:
        return int(str(p.get("폭", "")).strip())
    except (TypeError, ValueError, AttributeError):
        return None


def _탄력이름(이름: str) -> str:
    """`capture_buffer_async_fifo` -> `capture_elastic_buffer`.

    단순 치환이면 `capture_buffer_elastic_buffer` 처럼 낱말이 겹친다. 이름은 다음
    사람이 읽는 것이라 겹친 낱말을 걷어낸다."""
    t = _비동기이름.sub("elastic", 이름 or "")
    t = re.sub(r"_fifo\b", "_buffer", t)
    조각 = [x for x in t.split("_") if x]
    깎 = []
    for x in 조각:
        if 깎 and x == 깎[-1]:
            continue
        깎.append(x)
    # buffer 가 두 번 나오면 뒤엣것만 남긴다
    if 깎.count("buffer") > 1:
        첫 = 깎.index("buffer")
        깎.pop(첫)
    return "_".join(깎)


# ---------------------------------------------------------------- 요청과 대조한다
# **실측 2026-09-22 — 이 관문이 없어서 틀린 제안서가 나갔다.**
#
# 사용자가 2,851자 스펙을 첨부로 줬는데 `dispatch.py` 의 `[:900]` 이 그것을 900자에서
# 잘랐다. 모델은 §5(`AXI4-MM ... data 128-bit` · `제어는 AXI4-Lite`)를 **아예 못 봤고**,
# 빈 칸을 제 기본값으로 채웠다.
#
#     스펙   m_axi_wdata 128-bit · wstrb 16 · AXI4-Lite 제어 있음
#     제안서 m_axi_wdata 256-bit · wstrb 32 · AXI4-Lite 포트 통째로 없음
#
# **S016~S022 가 한 건도 안 걸렸다.** 까닭은 그것들이 *스펙 안의 일관성*만 보기
# 때문이다 -- 32 == 256/8 이라 S017 은 만족한다. 관문이 **요청을 안 봤다.**
#
# 그래서 요청 글과 대조한다. 모델이 요청에 적힌 수를 **조용히 바꾸는 것**이
# 이 파이프라인에서 가장 비싼 고장이다: 아래 모든 수(면적·타이밍·전력)가 그 위에 쌓인다.
#
# **애매하면 안 문다.** 요청에 "256-bit AXI4-Stream" 과 "128-bit MM data" 가 같이
# 있으므로, 수만 긁으면 짝을 잘못 맞춘다. 그래서 **인터페이스 이름이 같은 줄에
# 있을 때만** 그 줄의 수를 그 인터페이스 것으로 본다.
_인터페이스말 = {
    "s_axis": ("axi4-stream", "axi-stream", "axis", "스트림"),
    "m_axi":  ("axi4-mm", "axi4 mm", "axi-mm", "memory mapped", "memory-mapped", "ddr"),
    "s_axi":  ("axi4-lite", "axi4 lite", "axi-lite", "lite"),
}
# 그 줄 안에서 '무엇의 폭인가' 를 가르는 말 -> 인터페이스별 포트 꼬리.
# **꼬리를 인터페이스마다 따로 둔다** -- `tdata` 는 스트림 것이지 MM 것이 아니다.
_폭말 = (
    (("data", "데이터"), {"m_axi": ("wdata", "rdata"),
                        "s_axi": ("wdata", "rdata"),
                        "s_axis": ("tdata",)}),
    (("addr", "address", "주소"), {"m_axi": ("awaddr", "araddr"),
                                 "s_axi": ("awaddr", "araddr")}),
)
_수꼴 = re.compile(r"(\d{1,4})\s*[-\u2011]?\s*(?:bit|비트)", re.I)


def _요청폭(요청: str) -> dict:
    """요청 글에서 (인터페이스, 포트꼬리) -> 폭.

    **두 단으로 가른다.**
      줄     어느 인터페이스 이야기인가 (`AXI4-MM` · `AXI4-Stream` · `AXI4-Lite`)
      토막   그 줄을 쉼표·막대로 쪼갠 조각 하나 -- 여기서 낱말과 수를 짝짓는다

    한 줄 안에서 '가장 가까운 낱말' 로 짝지으면 틀린다. 실측 2026-09-22:

        address **64-bit**, data **128-bit**

    여기서 64 는 `address` 것인데, `data` 가 4자 뒤에 있고 `address` 는 10자 앞에
    있어서 **64 가 data 로 갔다.** 쉼표로 먼저 쪼개면 토막마다 낱말 하나 수 하나가
    되어 그 일이 안 난다.

    **애매하면 안 문다** -- 토막에 낱말이 둘 이상이거나 인터페이스가 둘 이상 걸리면
    건너뛴다. 없는 결함을 만드는 관문은 없느니만 못하다.
    """
    out = {}
    for 줄 in re.split(r"[\n.。]", 요청 or ""):
        낮줄 = 줄.lower()
        무슨 = [k for k, 말들 in _인터페이스말.items() if any(w in 낮줄 for w in 말들)]
        if len(무슨) != 1:
            continue
        iface = 무슨[0]
        for 토막 in re.split(r"[,，|·/]", 줄):
            낮 = 토막.lower()
            수들 = [int(m.group(1)) for m in _수꼴.finditer(토막)]
            if len(수들) != 1:
                continue                  # 수가 없거나 둘 이상이면 짝을 못 정한다
            걸린 = [꼬리맵 for 말들, 꼬리맵 in _폭말 if any(w in 낮 for w in 말들)]
            if len(걸린) != 1:
                continue                  # 낱말이 없거나 둘 다면 건너뛴다
            for 꼬 in 걸린[0].get(iface, ()):
                out.setdefault((iface, 꼬), 수들[0])

    # **스트림은 데이터 버스가 하나뿐이다.** 그래서 `AXI4-Stream, canonical 256-bit`
    # 처럼 'data' 라는 낱말 없이 폭만 적는 일이 흔하다(실측: 이 스펙이 그랬다).
    # 위 규칙은 낱말이 없으면 안 물므로 그 줄을 놓친다. 스트림에 한해 **줄에 폭이
    # 딱 하나일 때만** 그것을 `tdata` 로 본다 -- 둘 이상이면 여전히 안 문다.
    if ("s_axis", "tdata") not in out:
        for 줄 in re.split(r"[\n.。]", 요청 or ""):
            낮줄 = 줄.lower()
            무슨 = [k for k, 말들 in _인터페이스말.items() if any(w in 낮줄 for w in 말들)]
            if 무슨 != ["s_axis"]:
                continue
            수들 = [int(m.group(1)) for m in _수꼴.finditer(줄)]
            if len(수들) == 1:
                out.setdefault(("s_axis", "tdata"), 수들[0])
                break
    return out


def _요청인터페이스(요청: str) -> set:
    """요청이 이름을 대고 요구한 인터페이스."""
    낮 = (요청 or "").lower()
    return {k for k, 말들 in _인터페이스말.items()
            if any(w in 낮 for w in 말들) and k != "m_axi"} | (
           {"m_axi"} if any(w in 낮 for w in _인터페이스말["m_axi"]) else set())


def 검사(s) -> list:
    """스펙 -> [문제]. 문제 하나는 다음 칸을 갖는다.

        규칙   S001 …
        자리   어디가 잘못됐나
        말     무엇이 잘못됐나 (사람이 읽는 글)
        갈래   고침 | 되물음 | 남김
        고친값 '고침' 일 때 무엇으로 바꿀 것인가
    """
    난것 = []

    def 적기(규칙, 자리, 말, 갈래, 고친값=None):
        난것.append({"규칙": 규칙, "자리": 자리, "말": 말, "갈래": 갈래,
                   "고친값": 고친값})

    포트 = list(s.포트 or [])
    블록 = list(s.블록 or [])
    클럭 = list(s.클럭 or [])

    # ---------------------------------------------------------------- 포트
    for p in 포트:
        이름 = _글(p.get("이름"))
        w = _폭(p)
        if w is not None and w < 1:
            # **TBD 는 0 이 아니다.** 폭 0 포트는 SV 에서 불법이고, 이 표가 RTL
            # 생성기의 입력이라 `[-1:0]` 같은 것이 나간다.
            적기("S001", f"포트 {이름}",
               f"폭이 {w} 다 — 폭 0/음수 포트는 SystemVerilog 에서 불법이다. "
               f"모르는 폭은 0 이 아니라 **파라미터**로 둔다",
               "고침", {"폭": 1, "뜻꼬리": " (폭 TBD — 파라미터로 둘 것)"})
        if w is None and 이름:
            적기("S002", f"포트 {이름}", "폭을 못 읽었다 — 수로 적어야 한다", "되물음")
        if 이름 and not _식별자.match(이름):
            적기("S003", f"포트 {이름}",
               "SystemVerilog 식별자 꼴이 아니다 (영문/숫자/밑줄, 숫자로 시작 못 함)",
               "남김")
        if _글(p.get("방향")).lower() not in ("input", "output", "inout", "입력", "출력"):
            적기("S004", f"포트 {이름}",
               f"방향이 `{_글(p.get('방향'))}` 이다 — input/output/inout 중 하나여야 한다",
               "되물음")

    이름들 = [_글(p.get("이름")) for p in 포트]
    if len(이름들) != len(set(이름들)):
        겹 = sorted({n for n in 이름들 if 이름들.count(n) > 1 and n})
        적기("S005", "포트 목록", f"이름이 겹친다: {' · '.join(겹)}", "남김")

    # ---------------------------------------------------------------- 클럭
    포트클럭 = sorted({n for n in 이름들 if n and _클럭이름.search(n)})
    if 포트클럭 and len(포트클럭) > max(1, len(클럭)):
        # **숨은 CDC.** 보고서가 클럭 표에 "둘 이상이면 CDC 가 생긴다" 고 적어 놓고
        # 제 포트 목록을 안 보는 일이 실제로 났다(실측 2026-09-22).
        적기("S006", "클럭",
           f"포트에는 클럭이 {len(포트클럭)}개인데({' · '.join(포트클럭)}) "
           f"클럭 표에는 {len(클럭)}개뿐이다 — **도메인이 둘이면 CDC 가 생긴다**. "
           f"같은 도메인이면 포트를 하나로 줄이고, 아니면 클럭 표에 다 적고 "
           f"건너는 신호마다 동기화 방식을 적어라",
           "남김")

    for c in 클럭:
        try:
            주기 = float(c.get("주기_ns"))
        except (TypeError, ValueError, AttributeError):
            적기("S007", f"클럭 {_글(c.get('이름'))}", "주기를 수로 못 읽었다", "되물음")
            continue
        if 주기 <= 0:
            적기("S007", f"클럭 {_글(c.get('이름'))}", f"주기가 {주기} ns 다", "되물음")

    # ---------------------------------------------------------------- 블록 이름과 구조
    for b in 블록:
        이름 = _글(b.get("이름"))
        if _비동기이름.search(이름) and len(클럭) <= 1:
            적기("S008", f"블록 {이름}",
               "이름이 도메인 교차를 말하는데 클럭 도메인은 하나다 — "
               "같은 클럭이면 비동기 FIFO 가 아니라 **탄력 버퍼(elastic buffer)** 이고, "
               "이름이 남으면 다음 사람이 필요 없는 그레이 포인터를 넣는다",
               "고침", {"이름": _탄력이름(이름)})
        if 이름 and not _식별자.match(이름):
            적기("S009", f"블록 {이름}", "SystemVerilog 모듈 이름 꼴이 아니다", "남김")
    if len(블록) <= 1:
        적기("S010", "블록 분할",
           f"블록이 {len(블록)}개다 — 나누지 않은 것은 설계가 아니다", "되물음")

    # ---------------------------------------------------------------- 문제 <-> 목표
    목표글 = " ".join(_글(g.get("항목")) + " " + _글(g.get("값")) for g in (s.목표 or [])).lower()
    for 문 in (s.문제 or []):
        말들 = _문제말.get(_글(문))
        if not 말들:
            continue
        if not any(w in 목표글 for w in 말들):
            # **잴 방법이 있는 목표인데 목표 칸에 없으면 아무도 안 잰다.**
            적기("S011", f"목표 — {문}",
               f"문제를 `{문}` 으로 읽어 놓고 목표 표에 그 항목이 없다 — "
               f"목표에 없으면 아무도 안 잰다",
               "되물음")

    for g in (s.목표 or []):
        if not _글(g.get("어떻게 잴 것인가") or g.get("어떻게잴것인가")).strip():
            적기("S012", f"목표 {_글(g.get('항목'))}",
               "잴 방법이 비었다 — 잴 방법이 없는 목표는 목표가 아니라 광고다", "되물음")

    # ---------------------------------------------------------------- 검증·위험
    if len(s.검증계획 or []) < 검증최소:
        적기("S013", "검증 계획",
           f"시나리오가 {len(s.검증계획 or [])}개다 — {검증최소}개 이상이어야 한다",
           "되물음")
    for v in (s.검증계획 or []):
        if not _글(v.get("노리는 것") or v.get("노리는것")).strip():
            적기("S014", f"검증 {_글(v.get('시나리오'))}",
               "무엇을 노리는지 비었다 — 노림이 없는 시나리오는 통과만 한다", "되물음")
    if not (s.위험 or []):
        적기("S015", "위험",
           "위험이 비었다 — 주장이 깨지는 조건을 못 적으면 그것은 주장이 아니라 광고다",
           "되물음")

    # ---------------------------------------------------------------- AMD/AXI 규약
    폭맵 = {_글(p.get("이름")).lower(): _폭(p) for p in 포트}
    for p in 포트:
        이름 = _글(p.get("이름"))
        꼬 = _꼬리(이름)
        w = _폭(p)
        if w is None:
            continue
        # 고정 폭 칸
        바른, 까닭 = AXI규약.get(꼬, (None, ""))
        if 바른 is not None and w != 바른:
            적기("S016", f"포트 {이름}",
               f"폭이 {w} 인데 AXI4 규약은 {바른} 이다 — {까닭}",
               "고침", {"폭": 바른})
        # 바이트당 한 비트인 칸 (TKEEP = TDATA/8)
        짝 = _바이트당.get(꼬)
        if 짝:
            묶 = _묶음이름(이름)
            데이터 = 폭맵.get(f"{묶}_{짝}".lower())
            if 데이터:
                바른2 = 데이터 // 8
                if w != 바른2:
                    적기("S017", f"포트 {이름}",
                       f"폭이 {w} 인데 `{묶}_{짝}` 가 {데이터} 비트이므로 "
                       f"{바른2} 여야 한다 — 바이트 하나당 한 비트다",
                       "고침", {"폭": 바른2})
        # AXI4-Lite 의 데이터 폭
        if "axi" in 이름.lower() and "lite" in _글(p.get("뜻")).lower() \
                and 꼬 in ("wdata", "rdata") and w not in _LITE폭:
            적기("S018", f"포트 {이름}",
               f"AXI4-Lite 데이터 폭은 32 또는 64 여야 한다 (지금 {w})", "남김")
        if 꼬 in ("awaddr", "araddr") and w > 64:
            적기("S019", f"포트 {이름}", f"주소 폭 {w} 는 64 를 넘는다", "남김")

    # 핸드셰이크 짝: valid 가 있으면 ready 가 있어야 한다
    있는것 = {n for n in 폭맵}
    for n in sorted(있는것):
        if not n.endswith("valid"):
            continue
        짝 = n[:-5] + "ready"
        if 짝 not in 있는것:
            적기("S020", f"포트 {n}",
               f"`{짝}` 가 없다 — AXI 핸드셰이크는 valid/ready 한 쌍이다", "되물음")

    # 이름 규약: 리셋은 active-low 이고 AMD IP 는 `aresetn` 으로 쓴다
    for n in sorted(있는것):
        if n in ("rst", "reset") or n.endswith("_rst"):
            적기("S021", f"포트 {n}",
               "AMD IP 규약은 active-low 리셋 `aresetn` 이다 — "
               "`rst`/`reset` 은 Vivado IP Integrator 가 자동으로 못 묶는다",
               "남김")
        if n in ("rst_n", "resetn", "reset_n") and not any(
                x.endswith("aresetn") for x in 있는것):
            적기("S022", f"포트 {n}",
               "AMD IP 규약으로는 `aresetn` 이다 — 이름이 다르면 IP Integrator 가 "
               "인터페이스로 못 알아보고, 블록 디자인에서 손으로 이어야 한다",
               "고침", {"이름": "aresetn"})

    # ---------------------------------------------------------------- 요청과 대조
    # **S016~S022 는 스펙 안의 일관성만 본다.** 모델이 요청에 적힌 수를 조용히
    # 바꿔도 그것들은 통과한다 -- 실측 2026-09-22: 요청은 `data 128-bit` 인데
    # 제안서가 `m_axi_wdata 256` · `wstrb 32` 로 나왔고, 32 == 256/8 이라
    # S017 이 만족했다. **관문이 요청을 안 봤다.** 여기서 본다.
    요청글 = _글(getattr(s, "요청", ""))
    if 요청글:
        폭표 = {_글(p.get("이름")).lower(): _폭(p) for p in 포트}
        for (iface, 꼬), 바른 in _요청폭(요청글).items():
            for 이름, 폭 in 폭표.items():
                if 폭 is None or not 이름.startswith(iface) or _꼬리(이름) != 꼬:
                    continue
                if 폭 != 바른:
                    적기("S023", f"포트 {이름}",
                       f"폭이 {폭} 인데 **요청 글에는 {바른} 으로 적혀 있다** — "
                       f"모델이 요청의 수를 바꿨다. 아래 수(면적·타이밍·전력)가 "
                       f"전부 이 위에 쌓이므로 여기서 틀리면 다 틀린다",
                       "고침", {"폭": 바른})
        # 요청이 이름을 대고 요구한 인터페이스가 포트표에 아예 없다
        # **`s_axis_tdata`.startswith(`s_axi`) 는 참이다.** 첫 판이 그래서
        # AXI4-Lite 가 통째로 없는데도 "있다" 로 읽었다(실측 2026-09-22).
        # 밑줄까지 붙여 보고, `s_axi` 는 `s_axis` 를 빼고 센다.
        def _묶음있나(i):
            for n in 폭표:
                if i == "s_axi" and n.startswith("s_axis_"):
                    continue
                if n.startswith(i + "_"):
                    return True
            return False

        있는묶음 = {i for i in _인터페이스말 if _묶음있나(i)}
        for i in sorted(_요청인터페이스(요청글) - 있는묶음):
            적기("S024", f"인터페이스 {i}",
               f"요청 글이 `{i}_*` 인터페이스를 요구하는데 **포트표에 한 개도 없다** — "
               f"통째로 빠뜨린 것이다",
               "되물음")

    # ------------------------------------------------- S025~S030: 제안서를 보고 찾은 것
    # **실측 2026-09-22 (제안서 `mera_rec`).** 파이프라인이 끝까지 돌아 6쪽을 냈는데,
    # 그 안에 아래 것들이 그대로 들어 있었다. S001~S024 가 한 건도 안 물었다.
    _S025_접두사갈라짐(포트, 적기)
    _S026_이름없는포트(포트, 적기)
    _S027_읽은칸을모른다(s, 적기)
    _S028_모른다중복(s, 적기)
    _S029_모드가같다(s, 적기)
    _S030_못재는목표(s, 적기)

    return 난것


# 인터페이스 묶음의 '앵커' -- 이 신호를 가진 접두사가 그 인터페이스의 진짜 이름이다
_앵커 = {"s_axis": ("tdata",), "m_axi": ("wdata", "awaddr"), "s_axi": ("wdata", "awaddr")}


def _갈래(이름: str) -> str:
    """`s_axis_rfdc_tdata` -> `s_axis`.  AXI 갈래(집안)를 고른다."""
    n = (이름 or "").lower()
    for k in ("s_axis", "m_axis", "m_axi", "s_axi"):
        if n.startswith(k + "_"):
            return "s_axis" if k == "m_axis" else k
    return ""


def _S025_접두사갈라짐(포트, 적기):
    """**한 인터페이스인데 접두사가 갈라지면 Vivado 는 둘로 묶는다.**

    실측: 제안서가 `s_axis_rfdc_tdata`(256) 와 `s_axis_tvalid`(1) 를 **같은
    AXI4-Stream 묶음**이라고 표에 적었다. 그런데 이름의 접두사가 다르다 --
    IP Integrator 는 `s_axis_rfdc` 와 `s_axis` 를 **서로 다른 인터페이스**로
    본다. 스펙이 못박은 AMD 이름 규약을 제안서가 제 표 안에서 깬 것이다.

    **두 스트림이 진짜로 둘인 경우와 가른다**: 앵커(`tdata`)를 가진 접두사가
    하나뿐일 때만 문다. 진짜 두 인터페이스면 각자 제 `tdata` 를 갖는다.
    """
    집안 = {}
    for p in 포트:
        이름 = _글(p.get("이름"))
        g = _갈래(이름)
        if not g:
            continue
        집안.setdefault(g, []).append(이름)
    for g, 이름들 in 집안.items():
        앞 = {}
        for n in 이름들:
            앞.setdefault(_묶음이름(n).lower(), []).append(n)
        if len(앞) < 2:
            continue
        주인 = [pre for pre, ns in 앞.items()
              if any(_꼬리(x) in _앵커.get(g, ()) for x in ns)]
        if len(주인) != 1:
            continue                      # 앵커가 둘이면 진짜 두 인터페이스다
        바른 = 주인[0]
        for pre, ns in sorted(앞.items()):
            if pre == 바른:
                continue
            for n in sorted(ns):
                적기("S025", f"포트 {n}",
                   f"접두사가 `{pre}` 인데 이 인터페이스의 데이터 포트는 `{바른}_*` 다 — "
                   f"Vivado IP Integrator 는 접두사로 묶으므로 이대로면 **두 인터페이스로 "
                   f"쪼개져** 블록 디자인에서 손으로 이어야 한다",
                   "고침", {"이름": f"{바른}_{_꼬리(n)}"})


def _S026_이름없는포트(포트, 적기):
    """**이름 없는 포트가 표에 실렸다.**

    실측: `(개별 신호) / None / input / 1 / 외부 트리거 입력`. 파이썬의 `None` 이
    글자 그대로 찍혔다. 이 표는 RTL 생성기의 입력이라, 이름이 없으면 그 자리에
    포트가 안 나가거나 `None` 이라는 이름으로 나간다.
    """
    for i, p in enumerate(포트):
        n = _글(p.get("이름")).strip()
        if n and n.lower() not in ("none", "null", "n/a", "미정", "tbd", "-"):
            continue
        적기("S026", f"포트 #{i + 1}",
           f"이름이 없다 (`{n or '빈칸'}`) — 뜻은 "
           f"`{_글(p.get('뜻'))[:40] or '없음'}` 이다. **이름을 정해야 포트가 된다**",
           "되물음")


# '모른다' 에 올라왔지만 이미 읽은 칸 -- 낱말이 맞으면 뺀다
_읽은칸말 = (
    ("쓰임새", ("쓰임새", "어디에 쓰", "용도", "응용 분야", "application")),
    ("온도_C", ("온도",)),
    ("전압_V", ("전압", "공급 전압")),
    ("주파수_Hz", ("주파수", "클럭 주파수", "동작 속도")),
)


def _S027_읽은칸을모른다(s, 적기):
    """**이미 읽은 칸을 '사람이 정해야 한다' 고 다시 묻지 않는다.**

    실측: 제안서가 쓰임새를 "계측/시험장비" 로 **읽었다고 적어 놓고**, 같은 문서
    다음 절에서 "어디에 쓰는지" 를 모르는 것으로 올렸다. 게다가 그 줄의 설명은
    "온도 등급(자동차 −40~125 °C)" 이었는데, 요청에는 **junction 0~100 °C
    (Extended)** 라고 적혀 있었다 -- 없는 수를 끌어온 것이다.

    한 문서 안에서 서로 어긋나면 사람은 어느 쪽을 믿어야 할지 모른다.
    """
    수 = dict(getattr(s, "수", {}) or {})
    for x in list(getattr(s, "모른다", []) or []):
        낮 = _글(x).lower()
        for 칸, 말들 in _읽은칸말:
            if not any(w.lower() in 낮 for w in 말들):
                continue
            읽힘 = bool(수.get(칸)) if 칸 in 수 or 칸.endswith(("_C", "_V", "_Hz"))                 else bool(getattr(s, 칸, None))
            if 칸 == "쓰임새":
                읽힘 = bool(getattr(s, "쓰임새", None))
            if not 읽힘:
                continue
            # **수 칸은 지우지 않고 보인다.** `온도_C` 를 읽었다고 해서 "온도
            # 센서 교정 계수" 까지 아는 것은 아니다 -- 낱말이 스쳤다는 이유로
            # 진짜 모르는 것을 지우면, 부풀린 수보다 나쁜 일이 난다.
            # 쓰임새는 칸 자체가 하나라 그런 어긋남이 없다.
            if 칸 == "쓰임새":
                적기("S027", f"모른다 {x}",
                   f"이 칸은 **이미 읽혔다** (`{칸}` = "
                   f"{' · '.join(getattr(s, '쓰임새', []) or [])}) — 읽은 것을 다시 "
                   f"'사람이 정해야 한다' 고 적으면 같은 문서가 스스로와 어긋난다",
                   "고침", {"모른다뺀다": x})
            else:
                적기("S027", f"모른다 {x}",
                   f"`{칸}` 는 이미 읽혔다 ({수.get(칸)}) — 이 줄이 그 값을 "
                   f"말하는 것이면 지워야 하고, 다른 것을 묻는 것이면 그렇게 "
                   f"고쳐 적어야 한다. **사람이 본다**",
                   "남김")
            break


_버릴말 = {"tbd", "미정", "대기", "확인", "필요", "구체적", "정확한", "정보", "및",
        "관련", "값", "것", "데이터"}


def _속말(글: str) -> set:
    """견줄 때 쓰는 의미 토막. 괄호·기호를 털고 흔한 말은 버린다."""
    토막 = re.findall(r"[0-9A-Za-z가-힣]+", (글 or "").lower())
    return {t for t in 토막 if t not in _버릴말 and len(t) > 1}


def _S028_모른다중복(s, 적기):
    """**같은 것을 여러 줄로 적으면 '모르는 것 N개' 가 부풀어 오른다.**

    실측: 7개 중 "RFDC TDATA 구체적 폭 및 포맷" · "RFDC TDATA 폭(TBD)" ·
    "I/Q 비트 정렬 방식(TBD)" 이 요청에서는 한 덩어리였다. 그 수가 요약 줄에도
    "아직 모르는 것 7개" 로 실린다.

    **덜 묶는 쪽으로 틀린다.** 잘못 묶으면 진짜 모르는 것이 사라지는데, 그것이
    부풀린 수보다 나쁘다. 그래서 **한쪽 토막이 다른 쪽에 다 들어 있을 때만** 묶고,
    닮기만 한 것은 '남김' 으로 사람에게 보인다.
    """
    것들 = [(_글(x), _속말(x)) for x in (getattr(s, "모른다", []) or [])]
    버림 = set()
    for i, (a, A) in enumerate(것들):
        if not A or a in 버림:
            continue
        for j, (b, B) in enumerate(것들):
            if i == j or not B or b in 버림 or a == b:
                continue
            if B < A or (B == A and j > i):
                적기("S028", f"모른다 {b}",
                   f"`{a}` 와 같은 것을 두 번 적었다 — 겹친 줄이 그대로 "
                   f"'모르는 것 N개' 로 세어진다",
                   "고침", {"모른다뺀다": b})
                버림.add(b)
            elif len(A & B) >= 2 and not (A <= B or B <= A):
                적기("S028", f"모른다 {b}",
                   f"`{a}` 와 겹쳐 보인다 (같은 말: "
                   f"{' · '.join(sorted(A & B))}) — 한 줄로 합칠 것인지 사람이 본다",
                   "남김")


def _S029_모드가같다(s, 적기):
    """**모든 모드의 전력이 같으면 그 표는 아무 말도 안 한다.**

    실측: CIRCULAR 최대 · RECORDING 최대. 표의 설명은 "전력이 문제라면 모드가
    답의 대부분이다" 인데, 두 줄이 같은 값이면 고를 것이 없다.
    """
    모드 = [m for m in (getattr(s, "모드", []) or []) if _글(m.get("이름"))]
    값 = {_글(m.get("전력")).strip().lower() for m in 모드}
    if len(모드) >= 2 and len(값) == 1:
        적기("S029", "동작 모드",
           f"모드 {len(모드)}개의 전력이 전부 `{sorted(값)[0]}` 이다 — "
           f"고를 것이 없으면 모드 표가 아무 말도 안 한다. 서로 다른 값을 "
           f"적거나 이 표를 빼야 한다",
           "남김")


# 잴 방법이 없는 절대어. 목표 칸에 이런 말이 들어가면 그것은 목표가 아니라 광고다.
_절대어 = ("jitter free", "jitter-free", "zero ", "무한", "완벽", "100% ", "무손실",
        "lossless", "no jitter", "glitch free", "glitch-free", "error free")


def _S030_못재는목표(s, 적기):
    """**잴 수 없는 절대어는 목표가 아니다** (CLAUDE.md '과장하지 않는다').

    실측: 결정성의 목표 값이 `Jitter Free` 였다. 재는 법 칸은 멀쩡했다 --
    "트리거 수신부터 기록 시작까지의 사이클 수 고정 검증". **잴 수 있는 것을
    적어 놓고 목표 칸에는 광고를 적었다.**
    """
    for g in (getattr(s, "목표", []) or []):
        값 = _글(g.get("값"))
        낮 = 값.lower()
        맞 = [w for w in _절대어 if w in 낮 or w.strip() == 낮]
        if not 맞:
            continue
        적기("S030", f"목표 {_글(g.get('항목'))}",
           f"값이 `{값}` 이다 — 잴 방법이 없는 절대어다. 재는 법 칸에 적힌 "
           f"`{_글(g.get('어떻게 잴 것인가'))[:50] or '…'}` 이 실제 목표다. "
           f"그 수(사이클·ps 따위)를 값으로 적어야 한다",
           "되물음")


def 고치기(s, 난것: list) -> "tuple[object, list]":
    """'고침' 갈래를 실제로 고친다. (스펙, 고친 목록) 을 돌려준다.

    **고치고 나서 조용히 지나가지 않는다** -- 무엇을 고쳤는지 목록으로 돌려주고,
    보고서가 그것을 적는다. 사람이 나중에 "왜 이 이름이 바뀌었지" 를 되짚을 수 있어야
    한다."""
    고친것 = []
    for 문 in 난것:
        if 문["갈래"] != "고침" or not 문["고친값"]:
            continue
        자리 = 문["자리"]
        값 = 문["고친값"]
        if 자리.startswith("포트 "):
            이름 = 자리[3:]
            for p in (s.포트 or []):
                if _글(p.get("이름")) != 이름:
                    continue
                if "폭" in 값:
                    전 = p.get("폭")
                    p["폭"] = 값["폭"]
                    고친것.append(f"포트 `{이름}` 폭 {전} → {p['폭']} ({문['규칙']})")
                if 값.get("뜻꼬리") and 값["뜻꼬리"] not in _글(p.get("뜻")):
                    p["뜻"] = _글(p.get("뜻")) + 값["뜻꼬리"]
                if "이름" in 값 and 값["이름"] != 이름:
                    # **이름을 바꾸면 그 이름을 쓰던 곳이 있는지 봐야 한다.** 포트
                    # 이름은 블록의 '하는일' 글에도 나온다 -- 거기도 같이 고친다.
                    p["이름"] = 값["이름"]
                    for b in (s.블록 or []):
                        if 이름 in _글(b.get("하는일")):
                            b["하는일"] = _글(b["하는일"]).replace(이름, 값["이름"])
                    고친것.append(f"포트 `{이름}` → `{값['이름']}` ({문['규칙']})")
        elif 자리.startswith("블록 "):
            이름 = 자리[3:]
            for b in (s.블록 or []):
                if _글(b.get("이름")) != 이름 or "이름" not in 값:
                    continue
                b["이름"] = 값["이름"]
                고친것.append(f"블록 `{이름}` → `{값['이름']}` ({문['규칙']})")
        elif 자리.startswith("모른다 ") and "모른다뺀다" in 값:
            # **'모르는 것' 에서 한 줄을 뺀다.** 이 수는 요약 줄에도 실리므로
            # 부풀면 사람이 설계의 상태를 잘못 읽는다.
            뺄 = 값["모른다뺀다"]
            남 = [x for x in (s.모른다 or []) if _글(x) != 뺄]
            if len(남) != len(s.모른다 or []):
                s.모른다 = 남
                고친것.append(f"모르는 것에서 `{뺄}` 를 뺐다 ({문['규칙']})")
    return s, 고친것


def 되물을글(난것: list) -> str:
    """'되물음' 을 모델에게 돌려줄 글로. `gen.py` 가 빨간 관문을 돌려주는 것과 같다."""
    줄 = [m for m in 난것 if m["갈래"] == "되물음"]
    if not 줄:
        return ""
    out = ["아래는 네가 낸 스펙을 기계가 검사해서 찾은 결함이다. **이것만 고쳐서 "
           "같은 JSON 을 다시 내라.** 나머지 칸은 그대로 두고, 지어내지 마라."]
    for m in 줄:
        out.append(f"- [{m['규칙']}] {m['자리']}: {m['말']}")
    return "\n".join(out)


def 남은것(난것: list) -> list:
    return [m for m in 난것 if m["갈래"] == "남김"]


def 요약(난것: list, 고친것: list) -> str:
    """마지막 검사 결과 기준. **고친 것은 바퀴를 가로질러 쌓인다.**

    같은 고침이 두 번 나오면 그것은 **모델이 고쳐 준 결함을 다시 냈다**는 뜻이다.
    합쳐서 숨기지 않고 그렇게 적는다 -- 되물음이 먹히고 있는지 아닌지의 신호다.
    """
    되 = sum(1 for m in 난것 if m["갈래"] == "되물음")
    남 = sum(1 for m in 난것 if m["갈래"] == "남김")
    겹 = len(고친것) - len(set(고친것))
    꼬 = f" · **모델이 같은 결함을 {겹}건 다시 냈다**" if 겹 else ""
    return (f"스펙 검사 — 고친 것 {len(set(고친것))}건 · 되물음 {되} · "
            f"사람이 정할 것 {남}{꼬}")
