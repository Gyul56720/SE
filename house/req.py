# -*- coding: utf-8 -*-
"""house/req -- **요구사항마다 번호를 붙인다(REQ-ID).**

## 왜 있나

정리해 둔 것(`paper/선행조사/스펙-읽기와쓰기.md` §4)의 결론이 이것이었다.

    우리 사슬:   포트/스캔 → 시나리오 → 커버 빈 → 커버리지 %
    업계 사슬:  **요구사항(REQ-ID)** → 시나리오 → 커버 빈 → PASS/FAIL → 요구사항으로 되짚기

**맨 위 한 칸이 없다.** 우리 문서의 수는 어디에도 매여 있지 않아서, 시험이
초록이어도 *어느 요구사항이 지켜졌는지* 를 되짚을 수가 없다. 번호가 그 고리다.

## 지어내지 않는다 -- 이미 있는 것에 번호만 매긴다

이 파일은 요구사항을 **쓰지 않는다.** 이미 문서 안에 있는 것을 모아 번호를 붙인다.

    s.못박힌수      요청 표가 못박은 수      -> 상태 `못박힘`
    s.목표          모델이 제안한 목표       -> 상태 `제안`
    specq 미정      아직 답이 없는 물음      -> 상태 `TBD`
    specq 이미답함  요청 글에 답이 있는 물음 -> 상태 `글에 답 있음`

TBD 를 목록에 **같이** 넣는 것이 요점이다. 업계 스펙이 `TBD` 를 지우지 않고
번호를 붙여 두는 까닭과 같다 -- 번호가 없으면 빠진 요구사항은 **세어지지도 않는다.**

## 번호는 한 번 나가면 안 움직인다

`REQ-MERA-003` 을 사람이 메일에 적은 뒤 스펙에 한 줄이 끼면, 자리로 세는 번호는
전부 한 칸씩 밀린다. 그러면 그 메일은 **조용히 딴것을 가리키게 된다** -- 이
저장소가 가장 싫어하는 꼴(틀린 것이 맞아 보이는 것)이다.

그래서 `붙이기(..., 이전=...)` 에 지난번 목록을 주면 **내용 열쇠로 번호를 물려받고**
새 줄에만 다음 번호를 준다. `tests/test_요구사항.py` 가 줄을 맨 앞에 끼워 넣고
옛 번호가 그대로인지 본다.

## 검증 가능한가 -- 여기서 기계가 보는 것

*"The filter shall provide high performance"* 는 요구사항이 아니다. 시험으로
참/거짓을 가릴 수 없기 때문이다. 이 파일이 보는 것은 **딱 두 가지**다.

    잴 것이 있나   수 또는 신호 이름이 글에 있나
    모호말이 있나  `고성능` · `충분히` · `적절` · `high` · `efficient` ...

## 이 파일이 못 하는 것

  · **요구사항이 옳은지는 모른다.** 번호를 붙이고 꼴만 본다
  · 수가 붙어 있으면 모호말이 섞여도 통과시킨다 -- "high performance at 100 MHz"
    는 앞쪽이 여전히 요구사항이 아닌데 여기서는 못 잡는다
  · 두 요구사항이 **서로 어긋나는지**는 안 본다
  · 시나리오와의 연결(3번)은 아직 없다 -- `검증` 칸이 비어 있는 까닭이다

실행: python3 house/req.py [회로키]
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

뿌리 = Path(__file__).resolve().parent
저장소 = 뿌리.parent
if str(저장소) not in sys.path:
    sys.path.insert(0, str(저장소))


# ------------------------------------------------------------------ 접두어

_제목줄 = re.compile(r"^\s{0,3}#{1,3}\s*(.+?)\s*$", re.M)


def 접두(키: "str | None" = None, 이름: str = "", 요청: str = "") -> str:
    """`REQ-<여기>-001` 의 가운데 토막. **ASCII 만** 쓴다.

    번호는 메일·이슈·시험 로그에 적히는 것이라 한글이 섞이면 자리마다 깨진다
    (CLAUDE.md 의 `pgrep -f` 한글 사고와 같은 부류다).

    차례는 `키` → `s.이름` → **요청 글의 제목 줄**이다. 실측 2026-09-22:
    모델 키가 없으면 `s.이름` 이 비어서 MERA-1 제안서의 번호가 전부
    `REQ-IP-NNN` 으로 나왔다 -- 회로 이름이 제목에 버젓이 적혀 있는데도.

    **본문은 안 본다.** 제목만 본다. 아무 줄에서나 첫 ASCII 낱말을 주워 오면
    "안녕하세요, AXI4 필터를…" 같은 글에서 접두가 `AXI4` 가 되고, 글을 한 줄
    고칠 때마다 **번호 전체가 딴 이름으로 바뀐다.** 번호는 안 움직여야 한다.
    """
    m = _제목줄.search(요청 or "")
    for 후보 in (키 or "", 이름 or "", m.group(1) if m else ""):
        t = re.sub(r"[^0-9A-Za-z]+", " ", str(후보)).strip()
        if not t:
            continue
        첫 = t.split()[0]
        if 첫:
            return 첫.upper()[:8]
    return "IP"


# ------------------------------------------------------------------ 내용 열쇠

def 열쇠(글: str) -> str:
    """번호를 물려줄 때 쓰는 내용 열쇠. 띄어쓰기·부호·대소문자를 지운다."""
    return re.sub(r"[^0-9a-z가-힣]+", "", str(글 or "").lower())


# ------------------------------------------------------------------ 검증 가능한가

# **수가 붙어 있으면 이 말들이 섞여도 넘어간다** -- 이 파일이 못 하는 것에 적었다.
모호말 = (
    "고성능", "높은 성능", "충분히", "충분한", "적절", "적당", "가능한 한", "최적",
    "우수", "유연", "빠른", "빠르게", "느리지 않", "효율적", "안정적으로", "잘 ",
    "high performance", "fast", "efficient", "optimal", "adequate", "sufficient",
    "reasonable", "robust", "user-friendly", "as needed", "best effort", "minimal",
    "good ", "low latency", "high speed",
)

_수있나 = re.compile(r"\d")
_신호꼴 = re.compile(r"(?<![0-9A-Za-z_])[a-z][a-z0-9]*(?:_[a-z0-9]+)+(?![0-9A-Za-z_])")


def _신호있나(낮: str, 신호들) -> str:
    """포트 이름이 **낱말로** 들어 있나.

    실측 2026-09-22: 그냥 `n in 낮` 으로 봤더니 포트 `ack` 가
    "backpressure" 속에 들어 있어 **«신호 `ack` 가 있으니 잴 수 있다»** 가 나왔다.
    그 줄은 신호 이야기를 한 줄이 아니었다. 이 저장소가 여러 번 겪은 꼴이다
    (`"s_axis_tdata".startswith("s_axi")` 가 참인 것과 같다).
    """
    for n in (신호들 or []):
        n = str(n or "")
        if n and re.search(rf"(?<![0-9A-Za-z_]){re.escape(n.lower())}(?![0-9A-Za-z_])", 낮):
            return n
    m = _신호꼴.search(낮)
    return m.group(0) if m else ""


def 검증가능(글: str, 신호들=(), 상태: str = "") -> dict:
    """{"판정", "까닭", "모호말"}.

    판정 = 잴 수 있다 | 모호하다 | 잴 것이 없다 | **아직 요구사항이 아니다**.

    **물음에는 이 잣대를 대지 않는다.** 실측 2026-09-22: TBD 줄 열 개에
    "시험으로 참/거짓을 못 가린다" 가 붙었다. 물음이니 당연히 못 가린다 --
    **사소한 이유로 나온 판정**이고, 그런 줄이 여덟이면 "못 가릴 것 8개" 라는
    수가 통째로 뜻을 잃는다. 물음은 답이 오면 그때 잰다.
    """
    t = str(글 or "")
    낮 = t.lower()
    걸린말 = [w for w in 모호말 if w.lower() in 낮]
    if 상태 == "TBD":
        return {"판정": "아직 요구사항이 아니다",
                "까닭": "답이 오면 그때 잰다 — 물음에 이 잣대를 대면 언제나 못 가린다",
                "모호말": 걸린말}
    수 = bool(_수있나.search(t))
    이름 = _신호있나(낮, 신호들)
    if not 수 and not 이름:
        return {"판정": "잴 것이 없다",
                "까닭": "글에 수도 신호 이름도 없다 — 시험으로 참/거짓을 못 가린다",
                "모호말": 걸린말}
    if not 수 and 걸린말:
        return {"판정": "모호하다",
                "까닭": f"수 없이 «{걸린말[0]}» 로 적혀 있다 — 얼마면 되는지가 안 적혔다",
                "모호말": 걸린말}
    까닭 = ("수가 적혀 있다" if 수 else "") + \
          (" · " if 수 and 이름 else "") + (f"신호 `{이름}`" if 이름 else "")
    return {"판정": "잴 수 있다", "까닭": 까닭, "모호말": 걸린말}


# ------------------------------------------------------------------ 모으기

# 갈래를 이 차례로 늘어놓는다. **나온 차례가 아니다** -- 나온 차례로 두면
# 판독기 코드를 한 줄 고칠 때마다 번호가 밀린다.
_갈래차례 = ("인터페이스", "데이터", "산술", "성능", "클럭", "리셋", "오류",
          "프로토콜", "프로그래밍 모델", "목표", "기타")

# **정해진 것이 위, 안 정해진 것이 아래.** 실측 2026-09-22: 갈래로만 세웠더니
# 요청 표가 못박은 수 여섯 줄(채널 수 · 샘플레이트 · PRE · POST · payload ·
# header)이 **목록 맨 끝**으로 갔다. 사람이 제 손으로 못박은 수가 물음 열 개
# 아래에 깔리면 그 표를 우리가 읽었는지부터 안 보인다.
_상태차례 = ("못박힘", "글에 답 있음", "제안", "TBD")


def _차례(갈래: str) -> int:
    try:
        return _갈래차례.index(갈래)
    except ValueError:
        return len(_갈래차례)


def _상태값(상태: str) -> int:
    try:
        return _상태차례.index(상태)
    except ValueError:
        return len(_상태차례)


def 모으기(스펙=None, 미정: "dict | None" = None) -> list:
    """문서 안에 이미 있는 것을 요구사항 줄로 모은다. **번호는 아직 안 붙인다.**"""
    s = 스펙
    난것 = []

    def 더하기(글, 갈래, 출처, 상태, 뿌리="", 열쇠글=""):
        글 = " ".join(str(글 or "").split())
        if not 글:
            return
        # **열쇠는 보이는 글이 아니라 내용이다.** 실측 2026-09-22: 물음을
        # 이름표로 붙이자 `트리거 지연: 3 cycle` 과 `지연의 상한은? → | 트리거
        # 지연 | 3 cycle |` 이 **서로 다른 줄로 남았다** -- 같은 것을 두 번
        # 요구사항으로 센 것이다. 이름표는 읽으라고 붙인 것이지 세라고 붙인 것이 아니다.
        난것.append({"글": 글, "갈래": 갈래, "출처": 출처, "상태": 상태,
                   "뿌리": 뿌리, "열쇠": 열쇠(열쇠글 or 글)})

    # 1) 요청 표가 못박은 수 -- 해석하지 않는다. 옮기기만 한다.
    for 항, 값 in list(getattr(s, "못박힌수", None) or []):
        더하기(f"{항}: {값}", "기타", "요청 표 (house/spec.py 표에서읽기)", "못박힘")

    # 2) 글에서 읽은 수
    for 이름, 값들 in (getattr(s, "수", None) or {}).items():
        if not 값들:
            continue
        더하기(f"{이름} = " + ", ".join(f"{v:g}" for v in 값들),
             "성능" if "주파수" in 이름 else "기타",
             "요청 글 (house/spec.py 읽기)", "못박힘")

    # 3) 모델이 제안한 목표 -- **여기가 모호말이 나오는 자리다**
    for g in list(getattr(s, "목표", None) or []):
        if not isinstance(g, dict):
            continue
        항 = str(g.get("항목") or "").strip()
        값 = str(g.get("값") or "").strip()
        if not 항 and not 값:
            continue
        더하기(f"{항}: {값}" if 값 else 항, "목표", "모델 제안 (s.목표)", "제안",
             str(g.get("어떻게 잴 것인가") or ""))

    # 4) specq 의 물음 -- 답이 없으면 TBD, 있으면 그 문장이 요구사항이다
    for q in list((미정 or {}).get("물음") or []):
        답 = str(q.get("이미답함") or "")
        if 답:
            # **답 문장만 적으면 요구사항으로 안 읽힌다.** 실측 2026-09-22:
            # `0 -- 파라미터로 치수가 정해지는 8탭 FIR/MAC 가속기 …` 한 줄이
            # 요구사항 자리에 앉았다 -- 무엇에 대한 답인지가 없으니 되짚을 수가
            # 없다. **물음을 이름표로 붙여** 줄 하나가 스스로 설명하게 한다.
            이름표 = str(q.get("물음") or "").rstrip("?").strip()
            더하기(f"{이름표} → {답}" if 이름표 else 답, q.get("갈래") or "기타",
                 f"요청 글 문장 (물음 {q.get('id')})", "글에 답 있음",
                 q.get("물음") or "", 열쇠글=답)
        else:
            더하기(f"TBD — {q.get('물음')}", q.get("갈래") or "기타",
                 str(q.get("출처") or "") + f" (물음 {q.get('id')})", "TBD",
                 q.get("왜") or "")

    # **같은 줄을 두 번 세지 않는다.** 못박힌수와 수가 같은 것을 말하는 일이 있다.
    본것, 남길것 = set(), []
    for r in 난것:
        if r["열쇠"] in 본것:
            continue
        본것.add(r["열쇠"])
        남길것.append(r)
    남길것.sort(key=lambda r: (_상태값(r["상태"]), _차례(r["갈래"])))
    return 남길것


# ------------------------------------------------------------------ 번호 붙이기

_번호꼴 = re.compile(r"-(\d+)$")


def 붙이기(스펙=None, 미정: "dict | None" = None, 키: "str | None" = None,
        이전: "list | None" = None) -> dict:
    """요구사항을 모아 `REQ-<IP>-NNN` 을 붙인다.

    `이전` 에 지난번 목록을 주면 **내용이 같은 줄은 번호를 물려받는다.**
    """
    s = 스펙
    앞 = 접두(키, getattr(s, "이름", "") or "",
           str(getattr(s, "요청", "") or ""))
    물려받을 = {}
    가장큰 = 0
    for r in (이전 or []):
        k, i = r.get("열쇠"), str(r.get("id") or "")
        m = _번호꼴.search(i)
        if k and m:
            물려받을.setdefault(k, i)
            가장큰 = max(가장큰, int(m.group(1)))

    신호들 = [str(p.get("이름") or "") for p in (getattr(s, "포트", None) or [])]
    # **포트가 아직 없을 때가 이 문서가 쓰이는 때다.** 실측 2026-09-22:
    # "aresetn 으로 비동기 리셋하고 동기로 해제한다" 가 «수도 신호 이름도 없다»
    # 로 떨어졌다. `aresetn` 은 신호 이름인데, 포트 목록이 비어 있었고 밑줄이
    # 없어 낱말꼴에도 안 걸렸다. specq 가 요청 글에서 세운 이름을 빌려 쓴다.
    if not 신호들:
        for _, 포트들 in ((미정 or {}).get("글로본것") or []):
            신호들 += [str(x) for x in 포트들]
    난것 = 모으기(s, 미정)
    쓴번호 = set(물려받을.values())
    for r in 난것:
        기존 = 물려받을.get(r["열쇠"])
        if 기존:
            r["id"] = 기존
        else:
            가장큰 += 1
            r["id"] = f"REQ-{앞}-{가장큰:03d}"
        쓴번호.add(r["id"])
        r.update(검증가능(r["글"], 신호들, r["상태"]))
        r["검증"] = ""          # 3번(시나리오 걸기)이 채운다

    갈래별, 상태별 = {}, {}
    for r in 난것:
        갈래별[r["갈래"]] = 갈래별.get(r["갈래"], 0) + 1
        상태별[r["상태"]] = 상태별.get(r["상태"], 0) + 1
    # **TBD 는 여기서 세지 않는다** -- 물음이라 못 가리는 것이 당연하고,
    # 섞어 세면 "못 가릴 것 N개" 가 사실은 "아직 안 물어본 것 N개" 가 된다.
    못잴것 = [r for r in 난것
           if r["판정"] not in ("잴 수 있다", "아직 요구사항이 아니다")]
    겹 = 겹쳐보이는것(난것)
    return {"됐나": True, "접두": 앞, "요구사항": 난것, "수": len(난것),
            "겹쳐보임": 겹,
            "갈래별": 갈래별, "상태별": 상태별,
            "못잴것": 못잴것, "못잴수": len(못잴것),
            "TBD수": 상태별.get("TBD", 0),
            "물려받은수": sum(1 for r in 난것 if r["열쇠"] in 물려받을),
            "못하는것": [
                "요구사항이 옳은지는 모른다 — 번호를 붙이고 꼴만 본다",
                "수가 붙어 있으면 모호말이 섞여도 통과시킨다",
                "두 요구사항이 서로 어긋나는지는 안 본다",
                "시나리오와의 연결은 아직 없다 (`검증` 칸이 비어 있다)",
                "겹쳐 보이는 것을 알리기만 한다 — 묶지 않는다 (잘못 묶으면 "
                "진짜 요구사항이 사라진다)",
            ]}


def 겹쳐보이는것(줄들: list) -> list:
    """같은 것을 두 번 센 것으로 **보이는** 짝. [(a, b, 무엇이 겹치나)].

    실측 2026-09-23 (MERA 제안서): 같은 사실이 두 번 번호를 받았다.

        REQ-MERA1-001  주파수_Hz = 5e+08   (못박힘, 글에서 읽음)
        REQ-MERA1-015  클럭 주파수: 500 MHz (제안, 모델 목표)
        REQ-MERA1-012  전압_V = 0.8   ↔  REQ-MERA1-016  공급 전압: 0.8 V

    글이 달라서 내용 열쇠로는 안 걸린다. 그런데 **묶지는 않는다** --
    잘못 묶으면 진짜 요구사항이 사라진다(`speccheck` 의 S028 이 배운 것이다).
    **겹쳐 보인다고 알리고 사람이 정하게 한다.**

    거는 규칙: 한쪽이 글에서 읽은 수(`주파수_Hz` 처럼 `<주제>_<단위>`)이고
    다른 쪽 항목에 그 **주제말**이 들어 있으면 겹쳐 보이는 것으로 친다.
    """
    수줄 = []
    for r in 줄들:
        m = re.match(r"([0-9A-Za-z가-힣]+)_[A-Za-z]+\s*=", r.get("글") or "")
        if m and r.get("상태") == "못박힘":
            수줄.append((m.group(1), r))
    난것 = []
    for 주제, a in 수줄:
        for b in 줄들:
            if b is a or b.get("상태") == "TBD":
                continue
            항 = str(b.get("글") or "").split(":")[0]
            if 주제 in 항 and a.get("id") != b.get("id"):
                난것.append((a, b, 주제))
    return 난것


def 요약글(r: dict) -> str:
    if not r.get("됐나"):
        return "요구사항에 번호를 못 붙였다"
    조각 = [f"요구사항 {r['수']}개"]
    if r.get("TBD수"):
        조각.append(f"그중 TBD {r['TBD수']}개")
    if r.get("못잴수"):
        조각.append(f"시험으로 못 가릴 것 {r['못잴수']}개")
    if r.get("물려받은수"):
        조각.append(f"번호 물려받음 {r['물려받은수']}개")
    return " · ".join(조각)


