def _폭수(폭) -> "int | None":
    if isinstance(폭, int):
        return 폭
    t = str(폭 or "").strip()
    if t.isdigit():
        return int(t)
    m = re.fullmatch(r"\[\s*(\d+)\s*:\s*(\d+)\s*\]", t)
    return abs(int(m.group(1)) - int(m.group(2))) + 1 if m else None


