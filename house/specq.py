# ------------------------------------------------------------------ 요청이 제안서에 시킨 것
#
# **실측 2026-09-23 (MERA).** 요청 글 §10 이 이렇게 적혀 있었다.
#
#     ## 10. 제안서에서 답해 주실 것
#     온칩 80 KiB 를 플립플롭으로 할지 SRAM 매크로로 할지 **면적으로 비교**해서
#     제안서로 내 주세요.
#
# 제안서는 그것을 §4 목표의 "어떻게 잴 것인가" 칸으로 **넘기기만** 했다 --
# 합성 뒤에 보겠다고. 그런데 요청은 **제안서에 답하라**고 했다. 넘긴 것과
# 답한 것은 다르다.
#
# 기계는 답했는지 못 본다. 다만 **무엇을 시켰는지는 뽑을 수 있다** -- 그러면
# 사람이 한 줄씩 대조한다. 안 뽑으면 그 줄은 조용히 사라진다.

_시킨말 = ("제안서", "이 문서", "여기서")
_답하라 = ("답해", "답하", "내 주세요", "내주세요", "비교해", "적어 주세요",
        "적어주세요", "제시해", "알려 주세요", "알려주세요", "정해 주세요")


def 제안서에시킨것(요청: str, 몇=8) -> list:
    """요청 글이 **제안서에 답하라고 한 문장들**. 없으면 빈 목록.

    한 문장 안에 «제안서» 류와 «답해 주세요» 류가 **같이** 있어야 한다 --
    낱말 하나로 잡으면 "제안서" 가 나오는 아무 문장이나 걸린다.
    """
    # **문장이 아니라 문단으로 본다.** 실측 2026-09-23: 문장으로 쪼갰더니
    # 제목("제안서에서 답해 주실 것")과 본문("온칩 80 KiB 를 … 비교해서")이
    # 따로 떨어져, **무엇을 비교하라는 것인지가 사라졌다.** 시킨 일은 대개
    # 여러 줄이다.
    난것 = []
    for 덩 in re.split(r"\n\s*\n", 요청 or ""):
        낮 = 덩.lower()
        if any(w in 낮 for w in _시킨말) and any(w in 덩 for w in _답하라):
            줄 = 따온글(" ".join(덩.split()).lstrip("# ").strip())
            # 제목만 있고 몸이 없는 덩어리는 다음 덩어리가 몸이다 -- 짧으면 버린다
            if len(줄) < 20 or 줄 in 난것:
                continue
            난것.append(줄)
    return 난것[:몇]


