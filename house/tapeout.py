def 증거확인(증거: str) -> dict:
    """{"증거","갈래","있나","말"}.  **꼴이 틀린 증거는 없는 것으로 다룬다.**"""
    m = _증거꼴.match(증거 or "")
    if not m:
        return {"증거": 증거, "갈래": "?", "있나": False, "말": "증거 꼴이 아니다"}
    갈래, 몸 = m.group(1), m.group(2)
    if 갈래 == "파일":
        return {"증거": 증거, "갈래": 갈래, "있나": _파일있나(몸),
                "말": "" if _파일있나(몸) else f"{몸} 가 없다"}
    if 갈래 == "함수":
        if "::" not in 몸:
            return {"증거": 증거, "갈래": 갈래, "있나": False, "말": "길::이름 꼴이 아니다"}
        길, 이름 = 몸.split("::", 1)
        ok = _이름있나(길, 이름)
        말 = "" if ok else (f"{길} 가 없다" if not _파일있나(길)
                           else f"{길} 안에 {이름} 가 없다")
        return {"증거": 증거, "갈래": 갈래, "있나": ok, "말": 말}
    if 갈래 == "관문":
        ok = _관문있나(몸)
        return {"증거": 증거, "갈래": 갈래, "있나": ok,
                "말": "" if ok else f"house/gen.py 에 관문 {몸} 이 없다"}
    if 갈래 == "문턱":
        ok = _문턱있나(몸)
        return {"증거": 증거, "갈래": 갈래, "있나": ok,
                "말": "" if ok else f"gen.기본문턱 에 {몸!r} 열쇠가 없다"}
    ok = _게이트있나(몸)
    return {"증거": 증거, "갈래": 갈래, "있나": ok,
            "말": "" if ok else f"gates/ 에 {몸} 이 없다"}


def 상태(항목: dict) -> dict:
    """**손으로 적은 상태를 안 읽는다.** 증거를 찾아보고 나서 정한다."""
    능 = [증거확인(x) for x in 항목["능력"]]
    붙 = [증거확인(x) for x in 항목["붙듦"]]
    깨진증거 = [x for x in (능 + 붙) if not x["있나"]]
    능있나 = bool(능) and all(x["있나"] for x in 능)
    붙있나 = bool(붙) and all(x["있나"] for x in 붙)
    값 = 있다 if (능있나 and 붙있나) else (시연뿐 if 능있나 else 없다)
    return {**항목, "상태": 값, "능력본것": 능, "붙듦본것": 붙,
            "깨진증거": [x["말"] for x in 깨진증거 if x["말"]]}


