def 절(R, 주인키: str) -> None:
    """**에이전트 보고서에 이 사람 몫의 테이프아웃 칸을 붙인다.**

    다섯 보고서가 같은 표를 저마다 적으면 한 군데만 고치게 된다. 그래서 표는
    여기 하나만 두고, 보고서는 **자기 주인 것만 걸러** 보인다.
    """
    t = 표(주인=주인키)
    if not t:
        return
    c = 셈(주인=주인키)
    P = PEOPLE.BY_KEY.get(주인키)
    R.절(f"테이프아웃까지 — {P.name if P else 주인키} 몫으로 남은 것")
    R.글("이 칸은 <b>손으로 적은 상태를 안 읽는다</b>. 항목마다 "
        "<code>능력</code>(그 일을 하는 코드가 있나)과 "
        "<code>붙듦</code>(그것을 못 지나가게 막는 관문·문턱이 있나)을 "
        "따로 찾아보고 상태를 정한다. 능력만 있고 붙듦이 없으면 "
        "<b>시연뿐</b>이다 — 돌기는 하는데 아무도 안 막는다.")
    R.그림(지도(폭=820, 주인=주인키),
         f"<b>{P.name if P else 주인키} 몫만 칠했다</b> — 흐린 칸은 남의 일이다. "
         "칩 색이 상태이고(초록 <code>있다</code> · 주황 <code>시연뿐</code> · "
         "빨강 <code>없다</code>), <b>!</b> 는 그 항목이 테이프아웃을 막는다는 뜻이다.",
         "house/tapeout.py 지도()")
    R.표(["항목", "단계", "상태", "막나", "증거", "왜 필요한가"],
        [[x["이름"], x["단계"], x["상태"], "막는다" if x["막나"] else "—",
          " · ".join(x["능력"] + x["붙듦"]) or "—",
          x["왜"] + ((" — " + x["메모"]) if x["메모"] else "")] for x in t],
        f"<b>{P.name if P else 주인키} 몫 {c['전체']}항목</b> — "
        f"있다 {c[있다]} · 시연뿐 {c[시연뿐]} · 없다 {c[없다]}. "
        "<b>「없다」 를 표에서 빼지 않는다</b> — 빼면 계획이 초록으로 보인다.",
        "house/tapeout.py", 강조열=[2])
    막 = 막는것(주인=주인키)
    if 막:
        R.짚기(f"<b>이 사람 몫으로 테이프아웃을 막는 것 {len(막)}개:</b> "
              + " · ".join(f"<code>{x['이름']}</code>({x['상태']})" for x in 막))
    else:
        R.짚기("<b>이 사람 몫으로 테이프아웃을 막는 것은 없다.</b>")


