_증거꼴 = re.compile(r"^(파일|함수|관문|문턱|게이트):(.+)$")


def _파일있나(상대길: str) -> bool:
    return (저장소 / 상대길).is_file()


def _이름있나(상대길: str, 이름: str) -> bool:
    p = 저장소 / 상대길
    if not p.is_file():
        return False
    글 = p.read_text(encoding="utf-8", errors="replace")
    return re.search(rf"^\s*(?:def|class)\s+{re.escape(이름)}\b", 글, re.M) is not None


