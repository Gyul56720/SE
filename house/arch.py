def 스펙꺼내기(키: str):
    """둔 스펙을 되살린다. 없으면 None -- **없는 것을 지어내지 않는다.**"""
    길 = 스펙방 / f"{키}.json"
    if not 길.is_file():
        return None
    try:
        d = json.loads(길.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return None
    s = SPEC.스펙()
    for k, v in d.items():
        if hasattr(s, k):
            setattr(s, k, v)
    return s


