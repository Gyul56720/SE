def 일하기(요청: str, 묻기=None) -> dict:
    t0 = time.time()
    R = {"요청": 요청, "시작": t0}
    s = SPEC.읽기(요청)
    R["코드가읽은것"] = s.읽은것만()
    R["모델썼나"] = False
    try:
        from house import gen as GEN
        R["쓸수있나"] = GEN.쓸수있나()
    except Exception:                                        # noqa: BLE001
        R["쓸수있나"] = {}
    if 묻기 is not None or (R.get("쓸수있나") or {}).get("모델키"):
        전 = len(s.블록)
        s = SPEC.다듬기(s, 묻기=묻기)
        R["모델썼나"] = len(s.블록) > 전 or bool(s.이름)

    # ------------------------------------------------------------------
    # **제안서를 내기 전에 스펙을 검사한다.** 사용자(2026-09-22): "결함을 내가 일일이
    # 너한테 보고하는게 아니라, 결함을 스스로 고치거나 혹은 결함이 없어야해."
    #
    # `gen.py` 가 생성된 RTL 에 관문 일곱을 거는 것과 같은 일을 스펙에 건다.
    # 고칠 수 있는 것은 고치고, 모델이 고칠 것은 **한 번 돌려주고**, 사람이 정할 것만
    # 남겨 보고서에 올린다. 판정은 전부 글자와 수로 한다 -- 모델을 안 쓴다.
    from house import speccheck as CHK
    난것 = CHK.검사(s)
    s, 고친것 = CHK.고치기(s, 난것)
    되물을 = CHK.되물을글(난것)
    R["검사_되물었나"] = False
    if 되물을 and (묻기 is not None or (R.get("쓸수있나") or {}).get("모델키")):
        # **한 번만 되묻는다.** 두 번째 바퀴는 같은 지적을 되풀이하기 쉽고, 그 사이
        # 사람은 기다린다. 한 번 고쳐서 남은 것은 보고서에 적어 사람에게 넘긴다.
        try:
            s2 = SPEC.다듬기(s, 묻기=묻기, 덧붙임=되물을)
            난것2 = CHK.검사(s2)
            if len([m for m in 난것2 if m["갈래"] != "고침"]) <= \
               len([m for m in 난것 if m["갈래"] != "고침"]):
                s = s2                      # **나아졌을 때만 받는다**
                s, 더고침 = CHK.고치기(s, 난것2)
                고친것 += 더고침
                난것 = 난것2
                R["검사_되물었나"] = True
        except Exception as e:              # noqa: BLE001
            s.모른다.append(f"스펙 재검 중 모델 호출 실패: {type(e).__name__}"[:120])
    R["검사"] = {"난것": 난것, "고친것": 고친것,
               "남은것": CHK.남은것(난것), "요약": CHK.요약(난것, 고친것)}
    R["스펙"] = s.사전()
    R["초"] = round(time.time() - t0, 1)
    # **미정 행동을 인터페이스에서 기계로 뽑는다.** 사용자가 정리해 준 말:
    # "스펙을 읽는다는 것은 숫자를 읽는 것이 아니라 아직 정의되지 않은 행동을
    # 찾아내는 것에 가깝다." 그 목록을 **모델에게만 맡기면 회로마다 들쭉날쭉**하다
    # (실측 2026-09-22: 같은 것이 세 줄로 나뉘고, 이미 읽은 칸이 다시 올라왔다).
    # `dv/plan.py` 가 시나리오를 인터페이스에서 뽑듯 미정 항목도 그렇게 뽑는다.
    try:
        from house import specq as SPECQ
        R["미정"] = SPECQ.세우기(s)
        R["미정더함"] = SPECQ.모른다에넣기(s, R["미정"])
    except Exception as e:                                   # noqa: BLE001
        R["미정"] = {"됐나": False, "까닭": f"{type(e).__name__}: {e}"}
        R["미정더함"] = []

    # **요구사항마다 번호를 붙인다(REQ-ID).** 업계 사슬은 우리 것보다 한 칸 위에서
    # 시작한다 -- `요구사항 → 시나리오 → 커버 빈 → PASS/FAIL → 요구사항으로 되짚기`.
    # 번호가 없으면 시험이 초록이어도 **어느 요구사항이 지켜졌는지** 를 못 되짚는다.
    # 여기서 요구사항을 **쓰지 않는다** -- 이미 문서 안에 있는 것에 번호만 매긴다.
    try:
        from house import req as REQ
        R["요구"] = REQ.붙이기(s, R.get("미정"), 키=None)
    except Exception as e:                                   # noqa: BLE001
        R["요구"] = {"됐나": False, "까닭": f"{type(e).__name__}: {e}"}

    # **요구사항에 시나리오를 건다.** 번호만으로는 사슬이 안 이어진다 --
    # 업계 사슬의 화살표는 `요구사항 → 시나리오 → 커버 빈` 이고, 그 첫 화살표가
    # 비어 있었다. 여기서 값은 걸린 것이 아니라 **안 걸린 것**에 있다:
    # "이 요구사항은 시험할 시나리오가 하나도 없다" 를 제안서가 말하게 한다.
    #
    # 제안 단계에는 RTL 이 없으므로 **포트로** 시나리오를 뽑는다.
    try:
        from house.dv import plan as PLAN
        from house.dv import trace as TRACE
        R["계획"] = PLAN.세우기(훑기={"포트": TRACE.포트세우기(s, R.get("미정"))},
                          스펙=s)
        R["이음"] = TRACE.걸기(R.get("요구") or {}, R["계획"])
    except Exception as e:                                   # noqa: BLE001
        R["계획"] = {"됐나": False}
        R["이음"] = {"됐나": False, "까닭": f"{type(e).__name__}: {e}"}

    R["_s"] = s
    return R


