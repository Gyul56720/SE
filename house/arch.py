def _질의만들기(s) -> list:
    바탕 = []
    회 = s.회로 or []
    문 = s.문제 or []
    쓰 = s.쓰임새 or []
    for c in 회 or ["digital IP"]:
        바탕.append(f"{c} architecture low power CMOS")
        for f in 문:
            영 = {"전력": "low power", "속도": "high speed", "면적": "area efficient",
                 "정밀도": "high resolution", "신뢰성": "fault tolerant"}.get(f, f)
            바탕.append(f"{c} {영} design")
        for u in 쓰:
            영u = {"자동차": "automotive", "의료": "biomedical", "산업": "industrial",
                  "소비자": "consumer", "우주항공": "aerospace radiation",
                  "통신": "communication"}.get(u, u)
            바탕.append(f"{영u} {c} ASIC power reduction")
    return 바탕[:8]


