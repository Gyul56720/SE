def 표(갈래만=None) -> list:
    """[{"단계","입력","출력","주인","갈래","우리","메모"}]."""
    난것 = []
    for 이름, 앞, 입, 출, 주인, 갈래, 우리, 메모 in (단계들 + 따로):
        if 갈래만 and 갈래 != 갈래만:
            continue
        난것.append({"단계": 이름, "앞": 앞, "입력": 입, "출력": 출, "주인": 주인,
                   "갈래": 갈래, "우리": 우리, "메모": 메모})
    return 난것


