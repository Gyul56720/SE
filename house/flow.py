def 이어지나() -> list:
    """**적어 둔 앞 단계**가 실제로 있는 단계인가. 없는 이름을 가리키면 낸다.

    흐름도를 그려 놓고 칸이 안 이어지면 그림이 거짓말을 한다. 다만 끊김을
    **목록 순서**로 재면 나란한 칸을 끊겼다고 잘못 읽는다 -- 그래서 앞 단계를
    이름으로 적고, 그 이름이 있는지만 본다.
    """
    있는이름 = {x[0] for x in (단계들 + 따로)}
    끊김 = []
    for 이름, 앞, *_ in (단계들 + 따로):
        for a in 앞:
            if a not in 있는이름:
                끊김.append((이름, a))
    # 시작 칸은 하나여야 한다 -- 앞이 없는 칸이 여럿이면 흐름이 둘이다
    시작 = [x[0] for x in 단계들 if not x[1]]
    if len(시작) != 1:
        끊김.append(("(시작 칸)", f"앞이 없는 칸이 {len(시작)}개: {시작}"))
    return 끊김


def 요약글() -> str:
    b = 경계()
    return "\n".join([
        f"인도물 {len(b['인도물'])}칸: " + " · ".join(b["인도물"]),
        f"검토  {len(b['검토'])}칸: " + " · ".join(b["검토"]),
        f"시연  {len(b['시연'])}칸: " + " · ".join(b["시연"]),
        f"없음  {len(b['없음'])}칸: " + " · ".join(b["없음"]),
    ])


