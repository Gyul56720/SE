def 일하기(규모="보통", 설계=None) -> dict:
    """규모: 빠르게 | 보통 | 밤새"""
    설정 = {"빠르게": dict(닫기=[10, 30, 100, 300, 1000], 회귀씨앗=8, 회귀거래=500, 변이거래=200),
          "보통": dict(닫기=[10, 30, 100, 300, 1000, 3000, 10000], 회귀씨앗=30, 회귀거래=2000, 변이거래=400),
          "밤새": dict(닫기=[10, 30, 100, 300, 1000, 3000, 10000, 30000], 회귀씨앗=200, 회귀거래=5000, 변이거래=1000),
          }[규모]
    from house import designs as DES
    d0 = 설계 or DES.NSW_FIR
    R = {"시작": time.time(), "규모": 규모, "설정": 설정,
        "설계": d0.키, "설계이름": d0.이름, "top": d0.top}

    # --- 1. 커버리지 닫기 곡선 (같은 씨앗, 거래 수만 늘린다) ---
    곡선 = []
    for n in 설정["닫기"]:
        d = SIM.돌리기(None, seed=99, txn=n, maxlen=256, cap=200000, 설계=d0)
        곡선.append({"거래": n, "cov": d["cov_pct"], "주기": d["clk_cycles"],
                   "초": d["_초"], "pass": d["pass"], "fail": d["fail"]})
    R["닫기곡선"] = 곡선

    # --- 2. 큰 회귀: 여러 씨앗 ---
    t0 = time.time()
    회귀 = []
    for s in range(1, 설정["회귀씨앗"] + 1):
        d = SIM.돌리기(None, seed=s, txn=설정["회귀거래"], maxlen=256, cap=200000)
        회귀.append({"seed": s, "pass": d["pass"], "fail": d["fail"], "timeout": d["timeout"],
                   "proto": d["proto_err"], "cov": d["cov_pct"], "주기": d["clk_cycles"],
                   "초": d["_초"], "sat": d["sat_txn"], "cyc_med": d["cyc_med"],
                   "cyc_max": d["cyc_max"]})
    R["회귀"] = 회귀
    R["회귀초"] = round(time.time() - t0, 2)
    R["총거래"] = sum(x["pass"] + x["fail"] + x["timeout"] for x in 회귀)
    R["총주기"] = sum(x["주기"] for x in 회귀)

    # --- 3. 지시 시험으로 구멍 닫기 (랜덤만 vs 랜덤+지시) ---
    랜덤만 = SIM.돌리기(None, seed=7, txn=max(설정["닫기"]), maxlen=2000, cap=900000)
    지시포함 = SIM.돌리기(None, seed=7, txn=max(설정["닫기"]), maxlen=2000, cap=900000,
                     dir=max(20, max(설정["닫기"]) // 50))
    R["랜덤만"] = 랜덤만
    R["지시포함"] = 지시포함
    R["큰실행"] = 지시포함

    # --- 4. 주기 분포 ---
    R["주기분포"] = 지시포함.get("cyc_hist", [])[:4000]

    # --- 5. 자해 검사 ---
    t1 = time.time()
    R["변이"] = MUT.한바퀴(txn=설정["변이거래"], 씨앗들=(101, 102, 103), 지시=20)
    R["변이초"] = round(time.time() - t1, 2)

    # --- 6. 파라미터 구성별 회귀 (IP 는 한 구성이 아니다) ---
    구성 = []
    for c in ({"STAGES": 2}, {"STAGES": 3}, {"CDC_STAGES": 3}, {"GATE_POLICY": 0}):
        d = SIM.돌리기(c, seed=55, txn=설정["회귀거래"] // 2, maxlen=256, cap=200000)
        구성.append({"파라": c, "pass": d["pass"], "fail": d["fail"], "timeout": d["timeout"],
                   "cov": d["cov_pct"]})
    R["구성"] = 구성

    # --- 7. 파형: 시뮬레이터가 쓴 VCD 를 실제로 읽는다 ---
    t2 = time.time()
    R["파형"] = _파형뜨기()
    R["파형초"] = round(time.time() - t2, 2)

    R["초"] = round(time.time() - R["시작"], 1)
    return R


def _파형뜨기() -> dict:
    """VCD 를 한 번 뜨고 세 장면을 뽑는다 -- **구간은 규칙으로 고른다**.

    "잘 나온 데를 골랐다" 를 막으려고, 각 장면의 구간은 `vcd.구간찾기` 가
    **그 사건이 처음 일어나는 자리**로 정한다. 손으로 고르지 않는다.
    """
    out = {"됐나": False}
    try:
        길 = str(RPT.내는곳 / "nsw_fir.vcd")
        RPT.내는곳.mkdir(parents=True, exist_ok=True)
        r = SIM.돌리기({"TAPS": 8, "STAGES": 3, "GATE_POLICY": 1},
                    seed=1, txn=6, cap=6000, cfg=3, maxlen=6, dir=2, vcd=길)
        d = VCD.읽기(길)
        out["파일"] = 길
        out["바이트"] = pathlib.Path(길).stat().st_size
        out["눈금"] = d["눈금"]
        out["신호수"] = d["신호수"]
        out["변화수"] = d["변화수"]
        out["끝시각"] = d["끝시각"]
        out["실행"] = {k: r.get(k) for k in ("pass", "fail", "timeout", "proto_err",
                                            "clk_cycles", "gclk_cycles", "gate_save_pct")}

        # (1) 거래 한 건: FSM 이 IDLE->LOAD->RUN->FLUSH->DONE 을 지나는 구간
        a, b = VCD.구간찾기(d, "u_ctrl.busy", "1", 앞=60, 뒤=520)
        out["거래"] = {
            "신호": VCD.구간뽑기(d, ["u_srst_sync.clk", "u_ctrl.start", "u_ctrl.in_vld",
                                 "u_ctrl.state_o", "u_mac.push", "u_mac.acc_o",
                                 "u_mac.vld_o", "u_ctrl.done"], a, b, 점=240),
            "띠": VCD.띠만들기(d, "u_ctrl.state_o", a, b, 점=240,
                            이름표={"1": "IDLE", "10": "LOAD", "100": "RUN",
                                 "1000": "FLUSH", "10000": "DONE",
                                 "00001": "IDLE", "00010": "LOAD", "00100": "RUN",
                                 "01000": "FLUSH", "10000": "DONE"}),
            "구간": [a, b]}

        # (2) 클럭 게이팅: CGIC 의 EN · 래치 출력 · 게이팅된 클럭
        a2, b2 = VCD.구간찾기(d, "u_icg.en", "1", 앞=30, 뒤=210)
        out["게이팅"] = {
            "신호": VCD.구간뽑기(d, ["u_srst_sync.clk", "u_icg.en", "u_icg.en_lat",
                                 "u_mac.clk"], a2, b2, 점=220),
            "구간": [a2, b2]}

        # (3) CDC: 느린 도메인의 그레이 포인터가 2FF 를 지나온다
        a3, b3 = VCD.구간찾기(d, "u_coef_fifo.wpush", "1", 앞=40, 뒤=340)
        out["cdc"] = {
            "신호": VCD.구간뽑기(d, ["u_coef_fifo.wclk", "u_coef_fifo.wpush",
                                 "u_coef_fifo.wgray", "u_coef_fifo.rq1_wgray",
                                 "u_coef_fifo.rq2_wgray", "u_coef_fifo.rempty_r"],
                                a3, b3, 점=240),
            "구간": [a3, b3]}
        out["됐나"] = True
    except Exception as e:                                   # noqa: BLE001
        out["까닭"] = f"{type(e).__name__}: {e}"[:200]
    return out


