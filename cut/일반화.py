"""일반화 -- **발견군에서 고르고, 안 본 인스턴스에서 검증한다.**

사용자가 준 v5(2026-09-13): *"small graphs -> discover -> inequality family -> large unseen
graphs -> verify."*

## 무엇을 일반화하나 -- 과장하지 않고 적는다

족 자체는 **손으로 적고 손으로 증명했다**(`찾기.py`). 그러니 여기서 "새 족을 발견한다" 고
말하면 거짓이다. 여기서 재는 것은 그 다음 물음이다.

    이 족이 **안 본 인스턴스에서도 쓸모가 있나?**

유효성은 이미 모든 인스턴스에 대해 증명돼 있다 -- 그건 물을 것이 없다. 물을 것은
**자르나 · 조이나** 이고, 그것은 인스턴스마다 다르다. 발견군에서 잘 나온 족이 검증군에서
무너지면 그것은 **그 인스턴스군의 성질**이었지 족의 성질이 아니었다.

## 왜 갈라야 하나

발견한 그 인스턴스에서 성적을 재면 그것은 training set 이다. 이 저장소가 이미 두 번
겪은 함정과 같은 자리다 -- 덜 재서 점수를 올리기, 씨앗 하나를 효과 크기로 읽기.

    발견군   seeds 0..k-1     여기서 족을 고른다
    검증군   seeds k..n-1     **한 번도 안 본다.** 여기 성적만 보고한다

## 셋으로 답한다

    지켜짐   검증군에서도 생산적이다 (ACCEPT 율이 문턱 위)
    무너짐   발견군에서만 생산적이었다 -> **그 인스턴스군의 성질이었다**
    못잼     후보가 안 나왔거나 표본이 모자라다
"""

from __future__ import annotations

import statistics

from . import ff as FF
from . import 찾기 as S
from . import 판정 as J

생산문턱 = 0.10          # ACCEPT / 훑은 이 이것보다 커야 "생산적" 이다
최소인스턴스 = 3          # 이만큼의 인스턴스에서 나와야 추측한다


def 한판재기(바탕, 요청, 족: str, 상한: int = 40, 시한초: float = 30.0) -> dict:
    """인스턴스 하나에서 족 하나의 성적. {훑은, ACCEPT, 무효, Δ들}."""
    r = S.훑기(바탕, 요청, 족=족, 상한=상한, 시한초=시한초)
    if not r.get("됐나"):
        return {"됐나": False, "말": r.get("말")}
    # Δ(LP 경계가 얼마나 올랐나)는 ACCEPT 한 것에서만 모은다
    p = FF.짓기(바탕, 요청)
    Δ들 = []
    for 이름, a, b in S.족들[족](바탕, 요청, 상한=상한):
        d = J.채택판정(p, a, b, 시한초=시한초)
        if d["결정"] == "ACCEPT":
            Δ들.append(d["조임"]["Δ"])
    return {"됐나": True, "족": 족, "훑은": r["훑은"], "ACCEPT": r["ACCEPT"],
            "무효": r["무효"], "안자름": r["안자름"], "안조임": r["안조임"], "못잼": r["못잼"],
            "생산율": (round(r["ACCEPT"] / r["훑은"], 4) if r["훑은"] else None),
            "Δ중앙값": (round(statistics.median(Δ들), 4) if Δ들 else None), "Δ수": len(Δ들)}


def 무리재기(씨앗들, 족: str, 인스턴스짓기, 상한: int = 40, 시한초: float = 30.0) -> dict:
    """여러 인스턴스에서 족 하나. **인스턴스마다 따로 세고 합치지 않는다** -- 합치면
    한 인스턴스가 나머지를 끌고 간다(씨앗 하나를 효과 크기로 읽는 그 자리다)."""
    각각 = []
    for s in 씨앗들:
        바탕, 요청 = 인스턴스짓기(s)
        r = 한판재기(바탕, 요청, 족, 상한, 시한초)
        if r.get("됐나"):
            각각.append({"씨앗": s, **{k: v for k, v in r.items() if k != "됐나"}})
    쓸것 = [x for x in 각각 if x["훑은"] > 0]
    율들 = [x["생산율"] for x in 쓸것]
    Δ들 = [x["Δ중앙값"] for x in 쓸것 if x["Δ중앙값"] is not None]
    return {
        "족": 족, "인스턴스수": len(각각), "후보난인스턴스": len(쓸것),
        "훑은합": sum(x["훑은"] for x in 각각), "ACCEPT합": sum(x["ACCEPT"] for x in 각각),
        "무효합": sum(x["무효"] for x in 각각),
        "생산율중앙값": (round(statistics.median(율들), 4) if 율들 else None),
        "생산율최소": (round(min(율들), 4) if 율들 else None),
        "생산율최대": (round(max(율들), 4) if 율들 else None),
        "Δ중앙값": (round(statistics.median(Δ들), 4) if Δ들 else None),
        "각각": 각각,
    }


def 추측(발견: dict, 문턱: float = 생산문턱, 최소: int = 최소인스턴스) -> dict:
    """발견군 성적에서 "이 족은 생산적이다" 를 추측한다. **기본은 안 한다.**"""
    중 = 발견.get("생산율중앙값")
    난 = 발견.get("후보난인스턴스", 0)
    if 발견.get("무효합", 0) > 0:
        return {"추측": False, "말": f"**무효가 {발견['무효합']}개 나왔다** -- 증명부터 다시 보라"}
    if 난 < 최소:
        return {"추측": False, "말": f"후보가 난 인스턴스가 {난}개뿐이다(최소 {최소}) -- 못 고른다"}
    if 중 is None or 중 <= 문턱:
        return {"추측": False, "말": f"생산율 중앙값 {중} 가 문턱 {문턱} 을 못 넘었다"}
    return {"추측": True, "문턱": 문턱,
            "말": f"발견군 {난}개 인스턴스에서 생산율 중앙값 {중} > {문턱}"}


def 검증(족: str, 발견씨앗들, 검증씨앗들, 인스턴스짓기, 상한: int = 40,
       문턱: float = 생산문턱, 시한초: float = 30.0, 말하기=None) -> dict:
    r"""발견군에서 고르고 **검증군에서 잰다.** 검증군은 고르는 데 한 번도 안 쓴다.

    셋으로 답한다 -- 지켜짐 / 무너짐 / 못잼."""
    말 = 말하기 or (lambda s: None)
    겹 = set(발견씨앗들) & set(검증씨앗들)
    if 겹:
        return {"판정": "못잼", "말": f"**발견군과 검증군이 겹친다** {sorted(겹)[:5]} -- "
                                  "겹치면 검증이 아니라 그냥 같은 것을 두 번 재는 것이다"}
    발견 = 무리재기(발견씨앗들, 족, 인스턴스짓기, 상한, 시한초)
    말(f"[일반화] 발견군: 생산율 중앙값 {발견['생산율중앙값']} (인스턴스 {발견['후보난인스턴스']}개)")
    ㅊ = 추측(발견, 문턱)
    if not ㅊ["추측"]:
        return {"판정": "못잼", "발견": 발견, "검증": None, "추측": ㅊ,
                "말": f"추측을 못 세웠다: {ㅊ['말']}"}
    검 = 무리재기(검증씨앗들, 족, 인스턴스짓기, 상한, 시한초)
    말(f"[일반화] 검증군: 생산율 중앙값 {검['생산율중앙값']} (인스턴스 {검['후보난인스턴스']}개)")
    if 검["무효합"] > 0:
        return {"판정": "무너짐", "발견": 발견, "검증": 검, "추측": ㅊ,
                "말": f"**검증군에서 무효가 {검['무효합']}개 나왔다** -- 증명이 틀렸다"}
    if 검["후보난인스턴스"] == 0:
        return {"판정": "못잼", "발견": 발견, "검증": 검, "추측": ㅊ,
                "말": "검증군에서 후보가 하나도 안 났다 -- 쓸모를 못 쟀다"}
    중 = 검["생산율중앙값"]
    if 중 is not None and 중 > 문턱:
        return {"판정": "지켜짐", "발견": 발견, "검증": 검, "추측": ㅊ,
                "말": f"**안 본 인스턴스에서도 생산적이다** "
                    f"(발견군 {발견['생산율중앙값']} -> 검증군 {중}, 문턱 {문턱})"}
    return {"판정": "무너짐", "발견": 발견, "검증": 검, "추측": ㅊ,
            "말": f"**발견군에서만 생산적이었다** (발견군 {발견['생산율중앙값']} -> "
                f"검증군 {중}) -- 그 인스턴스군의 성질이었지 족의 성질이 아니었다"}


def 보고(r: dict) -> str:
    말 = [f"**일반화 판정: {r.get('판정')}** -- {r.get('말')}"]
    for 이름 in ("발견", "검증"):
        d = r.get(이름)
        if not d:
            continue
        말.append(f"  {이름}군  인스턴스 {d['인스턴스수']}개(후보 난 것 {d['후보난인스턴스']}) · "
                 f"훑은 {d['훑은합']} · ACCEPT {d['ACCEPT합']} · 무효 {d['무효합']}")
        말.append(f"         생산율 중앙값 {d['생산율중앙값']} "
                 f"(최소 {d['생산율최소']} ~ 최대 {d['생산율최대']}) · Δ중앙값 {d['Δ중앙값']}")
    말.append("  **검증군은 고르는 데 한 번도 안 썼다.** 그것이 이 판정의 전부다")
    return "\n".join(말)
