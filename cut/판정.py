"""결정 단계 넷. **기능 하나가 결정 하나다.** 각각 세 값을 돌려준다.

부등식은 `a·z <= b` 꼴이고, `a` 는 변수 이름으로 준다.

    {("x", 가상노드, 바탕노드): 계수, ("y", 가상링크, (u,w)): 계수}

없는 자리는 0 이다. 이 꼴이라야 사람이 읽고 쓸 수 있고, 발견기가 뱉어도 그대로 받는다.

    1. 유효판정   max{a z : z in X_VNE} <= b       유효 / **무효** / 못잼
    2. 자름판정   max{a z : z in P_LP}  >  b       자름 / 안자름 / 못잼
    3. 분리판정   a z* > b                          분리함 / 못함 / 못잼
    4. 조임판정   LPgap 이 줄었나                   조임 / 안조임 / 못잼

**기본은 전부 '아니오'다.** 못 재면 못잼이고, 못잼은 통과가 아니다. 까닭: 유효하지 않은
cut 을 유효라 부르면 solver 가 **터지지 않고 조용히 틀린 최적해**를 낸다. 크래시도
infeasible 도 아니라서 아무도 모른다. 그래서 이 자리의 거짓 초록은 유난히 비싸다.

## 1번의 한계를 이름으로 적어 둔다

`유효판정` 은 **그 인스턴스 하나에 대한 증명**이다(MIP 를 최적까지 푼다 -- 표본이 아니다).
모든 인스턴스에 대한 유효성(= inequality *family*)은 여기서 안 나온다. 그것은 증명
의무이고, 이 도구는 반례를 못 찾았다는 것까지만 말한다.
"""

from __future__ import annotations

import numpy as np

from . import ff as FF

유효, 무효, 못잼 = "유효", "무효", "못잼"
자름, 안자름 = "자름", "안자름"


def 벡터(p: FF.판, a: dict) -> np.ndarray:
    """이름으로 준 계수를 변수 벡터로. **모르는 이름이 있으면 터뜨린다** -- 조용히 0 으로
    채우면 '그 항이 빠진 다른 부등식'을 재게 된다."""
    v = np.zeros(p.변수수)
    for 열쇠, 계수 in (a or {}).items():
        if 열쇠[0] == "x":
            자리 = p.x자리.get((열쇠[1], 열쇠[2]))
        elif 열쇠[0] == "y":
            자리 = p.y자리.get((열쇠[1], 열쇠[2]))
        else:
            raise KeyError(f"모르는 변수 갈래: {열쇠[0]!r} (x 또는 y 여야 한다)")
        if 자리 is None:
            raise KeyError(f"이 인스턴스에 없는 변수: {열쇠!r}")
        v[자리] = float(계수)
    return v


def 유효판정(p: FF.판, a: dict, b: float, 시한초: float = 60.0) -> dict:
    """**이 인스턴스에서** `a z <= b` 가 모든 정수 가능해에 대해 성립하는가.

    `max{a z : z in X_VNE}` 를 MIP 로 최적까지 푼다. 볼록포 위의 최대는 정수점 위의 최대와
    같으므로 정수점만 봐도 된다. 최적까지 풀었으면 그 값이 **인증서**다.

    가능해가 아예 없으면(요청을 배치할 수 없으면) `못잼` 이다 -- 공허하게 참인 것을
    유효라고 부르지 않는다."""
    r = FF.풀기(p, 정수=True, 시한초=시한초, 목적=벡터(p, a), 최대화=True)
    if r["상태"] == "불능":
        return {"판정": 못잼, "최대": None,
                "말": "이 인스턴스에 가능해가 없다 -- 공허하게 참인 것을 유효라 하지 않는다"}
    if r["상태"] != "최적":
        return {"판정": 못잼, "최대": None, "말": f"최대값을 못 구했다: {r['왜']}"}
    최대 = r["값"]
    if 최대 <= b + 1e-9:
        return {"판정": 유효, "최대": round(최대, 6),
                "말": f"max {최대:.6f} <= b {b:.6f} -- **이 인스턴스에서는 증명이다**"
                    "(모든 인스턴스는 아니다)"}
    return {"판정": 무효, "최대": round(최대, 6), "반례": r["해"],
            "말": f"**무효다.** 가능해 하나가 {최대:.6f} > b {b:.6f} 를 낸다 -- "
                "이 부등식을 넣으면 solver 가 조용히 틀린 최적해를 낸다"}


def 자름판정(p: FF.판, a: dict, b: float, 시한초: float = 60.0) -> dict:
    """**무엇이라도 자르는가.** `max{a z : z in P_LP} > b` 인가 (LP 한 번).

    이것이 '기존 부등식과 독립인가' 의 정확한 꼴이다. 배수인지 보는 것보다 강하다 --
    배수가 아니면서 기존 제약에 함의되는 경우가 훨씬 많고, 그런 것은 아무것도 안 자른다.
    `2x1+2x2<=2` 도 여기서 걸린다."""
    r = FF.풀기(p, 정수=False, 시한초=시한초, 목적=벡터(p, a), 최대화=True)
    if r["상태"] != "최적":
        return {"판정": 못잼, "최대": None, "말": f"LP 최대값을 못 구했다: {r['왜']}"}
    최대 = r["값"]
    if 최대 > b + 1e-9:
        return {"판정": 자름, "최대": round(최대, 6),
                "말": f"LP 위에서 max {최대:.6f} > b {b:.6f} -- 자를 것이 있다"}
    return {"판정": 안자름, "최대": round(최대, 6),
            "말": f"LP 위에서도 max {최대:.6f} <= b {b:.6f} -- **아무것도 안 자른다.** "
                "기존 제약에 이미 함의된다(버린다)"}


def 분리판정(p: FF.판, a: dict, b: float, z별: np.ndarray) -> dict:
    """**지금 이 fractional 점을 자르는가.** `a z* > b` -- 산수 한 줄이다.

    `자름판정` 과 다르다. 저쪽은 '무엇이라도 자르나', 이쪽은 '이것을 자르나'."""
    if z별 is None:
        return {"판정": 못잼, "값": None, "말": "z* 가 없다 -- LP 를 먼저 풀어라"}
    값 = float(np.dot(벡터(p, a), np.asarray(z별)))
    if 값 > b + 1e-9:
        return {"판정": "분리함", "값": round(값, 6),
                "말": f"a z* = {값:.6f} > b {b:.6f}"}
    return {"판정": "못함", "값": round(값, 6),
            "말": f"a z* = {값:.6f} <= b {b:.6f} -- 이 점은 안 잘린다"}


def 조임판정(p: FF.판, a: dict, b: float, 시한초: float = 60.0) -> dict:
    """**LP 경계를 얼마나 조이나.** cut 을 넣기 전후의 LP 최적값을 잰다.

    목적이 최소화이므로 cut 을 넣으면 LP 값은 **오르거나 같다**(가능 영역이 줄기 때문).
    내려가면 그것은 조인 것이 아니라 **어딘가 틀린 것**이다 -- 그때는 못잼이다."""
    앞 = FF.풀기(p, 정수=False, 시한초=시한초)
    if 앞["상태"] != "최적":
        return {"판정": 못잼, "말": f"cut 없는 LP 를 못 풀었다: {앞['왜']}"}
    뒤판 = FF.판(바탕=p.바탕, 요청=p.요청, x자리=p.x자리, y자리=p.y자리, 호들=p.호들,
              c=p.c, A_eq=p.A_eq, b_eq=p.b_eq,
              A_ub=np.vstack([p.A_ub, 벡터(p, a)[None, :]]),
              b_ub=np.append(p.b_ub, float(b)))
    뒤 = FF.풀기(뒤판, 정수=False, 시한초=시한초)
    if 뒤["상태"] == "불능":
        return {"판정": 못잼, "앞": round(앞["값"], 6),
                "말": "**cut 이 LP 를 통째로 불능으로 만들었다** -- 유효판정부터 다시 보라"}
    if 뒤["상태"] != "최적":
        return {"판정": 못잼, "앞": round(앞["값"], 6), "말": f"cut 넣은 LP 를 못 풀었다: {뒤['왜']}"}
    Δ = 뒤["값"] - 앞["값"]
    if Δ < -1e-9:
        return {"판정": 못잼, "앞": round(앞["값"], 6), "뒤": round(뒤["값"], 6), "Δ": round(Δ, 6),
                "말": "**LP 값이 내려갔다.** 제약을 더했는데 최소값이 줄 수는 없다 -- "
                    "어딘가 틀렸다. 조였다고 말하지 않는다"}
    if Δ <= 1e-9:
        return {"판정": "안조임", "앞": round(앞["값"], 6), "뒤": round(뒤["값"], 6), "Δ": 0.0,
                "말": "LP 최적값이 그대로다 -- 자르기는 해도 경계는 안 조인다"}
    return {"판정": "조임", "앞": round(앞["값"], 6), "뒤": round(뒤["값"], 6), "Δ": round(Δ, 6),
            "말": f"LP 경계가 {앞['값']:.6f} -> {뒤['값']:.6f} 로 {Δ:.6f} 올랐다"}


def 채택판정(p: FF.판, a: dict, b: float, 시한초: float = 60.0) -> dict:
    """넷을 차례로. **하나라도 아니면 REJECT 다.** 기본은 REJECT.

    순서가 곧 비용이다 -- 유효(MIP, 비쌈) 를 먼저 두는 까닭은, 무효인 것을 뒤 단계에
    넘기면 그 뒤 수가 전부 근거처럼 보이기 때문이다. `perf.py` 가 V 안 서면 시간을
    아예 안 재는 것과 같은 규율이다."""
    까닭 = []
    ㅇ = 유효판정(p, a, b, 시한초)
    if ㅇ["판정"] != 유효:
        return {"결정": "REJECT", "막힌곳": "유효", "까닭": [ㅇ["말"]], "유효": ㅇ}
    까닭.append(f"유효: {ㅇ['말']}")
    ㅈ = 자름판정(p, a, b, 시한초)
    if ㅈ["판정"] != 자름:
        return {"결정": "REJECT", "막힌곳": "자름", "까닭": 까닭 + [ㅈ["말"]], "유효": ㅇ, "자름": ㅈ}
    까닭.append(f"자름: {ㅈ['말']}")
    ㅁ = 조임판정(p, a, b, 시한초)
    까닭.append(f"조임: {ㅁ['말']}")
    if ㅁ["판정"] != "조임":
        return {"결정": "REJECT", "막힌곳": "조임", "까닭": 까닭, "유효": ㅇ, "자름": ㅈ, "조임": ㅁ}
    return {"결정": "ACCEPT", "막힌곳": "", "까닭": 까닭, "유효": ㅇ, "자름": ㅈ, "조임": ㅁ}
