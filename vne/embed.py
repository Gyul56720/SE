"""바탕 배치 방법 -- **풀이기 없이 도는 것만.** 여기 있는 것이 비교의 바탕(baseline)이다.

정수계획(FF)과 그 LP 완화는 solver 가 있어야 돌고, 이 기계에는 없다(실측 2026-09-13:
scipy·pulp·highs 전부 없음). 그래서 **못 재는 것을 지어내는 대신** 자를 먼저 세운다:
탐욕 배치는 stdlib 로 돌고, 온라인 VNE 논문이 실제로 바탕으로 쓰는 부류다.

배치가 성립하려면 둘 다여야 한다.
  노드   가상 노드마다 다른 바탕 노드 하나 (일대일 -- **이 모델의 가정**이지 VNE 일반의
         가정이 아니다. 여러 가상 노드를 한 바탕 노드에 얹는 모델도 흔하다)
  링크   가상 링크마다 바탕 경로 하나, 그 경로의 모든 링크에 대역이 남아 있어야 한다
"""

from __future__ import annotations

import heapq

from . import topo as T

# 거절 사유. **사유를 세지 않으면 "왜 못 받았나"를 못 본다.**
# 거절 사유는 **갈라야 뜻이 있다.** 실측 2026-09-13: 처음엔 "남은 대역 최대값이 필요량보다
# 크면 경로없음, 아니면 링크부족" 으로 갈랐더니 링크 155개 가운데 하나만 여유가 있어도
# 경로없음이 되어 **102건이 전부 한 칸에 몰렸다.** 죽은 측정이다. 이제 실제로 갈라 본다 --
# 대역을 무시하고도 길이 없으면 끊김, 길은 있는데 대역이 모자라면 대역부족.
노드부족 = "노드자원부족"
대역부족 = "대역부족"
끊김 = "끊김"
링크부족 = 대역부족                      # 옛 이름. 부르던 데가 안 깨지게 남긴다


def _남은cpu(바탕: T.망, 쓴cpu: dict) -> dict:
    return {u: 바탕.노드[u]["cpu"] - 쓴cpu.get(u, 0.0) for u in 바탕.노드}


def _남은대역(바탕: T.망, 쓴대역: dict) -> dict:
    return {k: 바탕.링크[k]["대역"] - 쓴대역.get(k, 0.0) for k in 바탕.링크}


def 최단경로(바탕: T.망, 남대역: dict, s, t, 필요: float) -> "list | None":
    """대역이 `필요` 이상 남은 링크만 지나는 **홉 수 최소** 경로. 없으면 None.

    홉 수를 재는 까닭: 비용이 `대역 x 경로길이` 라서 홉이 곧 비용이다."""
    if s == t:
        return [s]
    앞 = {s: None}
    큐 = [(0, s)]
    while 큐:
        d, u = heapq.heappop(큐)
        if u == t:
            길, x = [], t
            while x is not None:
                길.append(x)
                x = 앞[x]
            return 길[::-1]
        for v in 바탕.이웃(u):
            if v in 앞:
                continue
            if 남대역[바탕.링크키(u, v)] < 필요:
                continue
            앞[v] = u
            heapq.heappush(큐, (d + 1, v))
    return None


def 노드순위(바탕: T.망, 남cpu: dict, 남대역: dict) -> list:
    """`cpu x (붙은 링크의 남은 대역 합)` 이 큰 바탕 노드부터. 온라인 VNE 의 표준 순위다.

    cpu 만 보면 대역이 말라 있는 노드를 골라 링크 단계에서 다 실패한다."""
    def 점수(u):
        대역합 = sum(남대역[바탕.링크키(u, v)] for v in 바탕.이웃(u))
        return 남cpu[u] * 대역합
    return sorted(바탕.노드, key=lambda u: (-점수(u), u))


def 탐욕배치(바탕: T.망, 요청: T.망, 쓴cpu: dict, 쓴대역: dict) -> dict:
    """한 요청을 배치해 본다. {됐나, 사유, 노드배치, 링크배치, 비용, 매출}.

    **자원을 여기서 안 깎는다** -- 부른 쪽이 `됐나` 를 보고 깎는다. 실패한 배치가 자원을
    반쯤 먹고 물러나는 일이 없게(그러면 뒤 요청의 거절이 이 요청 탓이 된다)."""
    남cpu = _남은cpu(바탕, 쓴cpu)
    남대역 = _남은대역(바탕, 쓴대역)
    순위 = 노드순위(바탕, 남cpu, 남대역)

    노드배치, 쓴자리 = {}, set()
    for v, 속 in sorted(요청.노드.items(), key=lambda kv: -kv[1]["cpu"]):
        골랐나 = None
        for u in 순위:
            if u not in 쓴자리 and 남cpu[u] >= 속["cpu"]:
                골랐나 = u
                break
        if 골랐나 is None:
            return {"됐나": False, "사유": 노드부족, "노드배치": {}, "링크배치": {},
                    "비용": 0.0, "매출": 0.0}
        노드배치[v] = 골랐나
        쓴자리.add(골랐나)
        남cpu[골랐나] -= 속["cpu"]

    링크배치, 임시대역 = {}, dict(남대역)
    for (a, b), 속 in 요청.링크.items():
        필요 = 속["대역"]
        길 = 최단경로(바탕, 임시대역, 노드배치[a], 노드배치[b], 필요)
        if 길 is None:
            # **대역을 빼고도 길이 없나**를 실제로 본다. 그래야 "위상이 끊겼다" 와
            # "자원이 말랐다" 가 갈린다 -- 둘은 고치는 법이 전혀 다르다.
            무한 = {k: float("inf") for k in 바탕.링크}
            끊겼나 = 최단경로(바탕, 무한, 노드배치[a], 노드배치[b], 0.0) is None
            return {"됐나": False, "사유": 끊김 if 끊겼나 else 대역부족,
                    "막힌링크": (a, b), "필요대역": 필요,
                    "노드배치": {}, "링크배치": {}, "비용": 0.0, "매출": 0.0}
        링크배치[(a, b)] = 길
        for i in range(len(길) - 1):
            임시대역[바탕.링크키(길[i], 길[i + 1])] -= 필요

    cpu합 = sum(s["cpu"] for s in 요청.노드.values())
    대역합 = sum(s["대역"] for s in 요청.링크.values())
    홉비용 = sum(요청.링크[(a, b)]["대역"] * (len(길) - 1) for (a, b), 길 in 링크배치.items())
    return {"됐나": True, "사유": "", "노드배치": 노드배치, "링크배치": 링크배치,
            # 매출 = 요청이 달라는 자원. 비용 = 실제로 문 자원(대역은 경로 길이만큼 곱해진다)
            "매출": cpu합 + 대역합, "비용": cpu합 + 홉비용}


def 자원깎기(바탕: T.망, 요청: T.망, 배치: dict, 쓴cpu: dict, 쓴대역: dict, 부호: int = 1) -> None:
    """`부호=1` 이면 물고, `-1` 이면 돌려준다. 수명이 끝난 요청을 돌려주는 데 쓴다."""
    for v, u in 배치["노드배치"].items():
        쓴cpu[u] = 쓴cpu.get(u, 0.0) + 부호 * 요청.노드[v]["cpu"]
    for (a, b), 길 in 배치["링크배치"].items():
        필요 = 요청.링크[(a, b)]["대역"]
        for i in range(len(길) - 1):
            k = 바탕.링크키(길[i], 길[i + 1])
            쓴대역[k] = 쓴대역.get(k, 0.0) + 부호 * 필요


def 탐욕cpu(바탕: T.망, 요청: T.망, 쓴cpu: dict, 쓴대역: dict) -> dict:
    """**일부러 더 나쁜 바탕.** 노드 순위를 CPU 만 보고 매긴다(대역을 안 본다).

    왜 두나: 자가 실제로 갈리는지 보려면 **갈려야 마땅한 둘**이 있어야 한다. 이것이 없으면
    "Δ 가 0 이다" 를 보고 자가 옳은지 방법이 같은지 구별할 수 없다 -- 못 잼을 초록으로 읽는
    그 자리다. 이론상 이쪽이 나빠야 하고, 안 나쁘면 **자를 의심할 근거**가 된다."""
    옛순위 = 노드순위
    try:
        globals()["노드순위"] = lambda 바, 남c, 남b: sorted(바.노드, key=lambda u: (-남c[u], u))
        return 탐욕배치(바탕, 요청, 쓴cpu, 쓴대역)
    finally:
        globals()["노드순위"] = 옛순위


방법들 = {"탐욕": 탐욕배치, "탐욕cpu": 탐욕cpu}
