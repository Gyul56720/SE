"""IP 사인오프 흐름. **현업이 IP 를 넘길 때 실제로 지나는 관문을 순서대로 돌린다.**

사용자(2026-09-15): "IP & design house 의 실제 현업 process 를 담당해야 해."

## 왜 있나 -- "돌아가는 RTL" 은 딜리버러블이 아니다

상용 IP 를 넘긴다는 것은 파일 하나를 주는 일이 아니다. 최소한 이만큼이 같이 간다.

    RTL · 검증 IP(VIP) · 커버리지 리포트 · 합성 결과(면적) · 타이밍(Fmax, SDC) ·
    린트/CDC 사인오프 · 레지스터 맵 · TRM · 통합 가이드 · 버전과 릴리스 노트

`run_rtl` 하나만 돌리고 "동작한다" 고 말하는 것과, 이 관문을 다 지나 "넘길 수 있다"
고 말하는 것은 다른 주장이다. 여기서는 그 둘을 낱말로 가른다.

## 관문 하나라도 안 지나면 사인오프가 아니다

    LINT      verilator -Wall          경고 0 이어야 한다
    SIM       iverilog + 자가검사 벤치  통과 표시가 찍혀야 한다
    COVERAGE  verilator, DUT 만        바닥을 넘어야 한다
    FORMAL    yosys sat, 무계 귀납     성질이 있고 증명돼야 한다
    SYNTH     yosys                    셀 수가 나와야 한다
    TIMING    nextpnr, 목표 대비       목표를 넘어야 한다
    DOCS      딜리버러블 목록          무엇이 빠졌는지 센다

**하나라도 PASS 가 아니면 전체가 PASS 가 아니다.** 그리고 못 잰 관문은 통과로 세지
않는다 -- 이 저장소의 규율을 사인오프에 그대로 옮긴 것이다.

## 이것이 "실무를 흉내 낸다" 는 말은 아니다

여기서 도는 것은 오픈 도구뿐이다(verilator · iverilog · yosys · nextpnr).
상용 흐름의 DFT · MBIST · IR 드롭 · DRC/LVS · 다중 코너는 **여기서 못 잰다.**
그것을 '통과' 로 적지 않고 `못잼` 으로 적는다. 못 잰 것을 안 말하면 리포트가
거짓말을 한다.
"""
from __future__ import annotations

import os
import re

PASS, FAIL, 못잼 = "PASS", "FAIL", "못잼"

# 상용 사인오프에는 있는데 **여기서는 못 재는 것들.** 숨기지 않고 리포트에 적는다.
못재는것 = [
    ("DFT / ATPG", "스캔 삽입과 고장 커버리지 -- 상용 툴이 필요하다"),
    ("MBIST", "메모리 자가시험 -- 컴파일러와 메모리 모델이 필요하다"),
    ("CDC / RDC sign-off", "도메인 교차 정적 검사 -- verilator 가 일부만 본다"),
    ("Power / IR drop", "전력망과 IR 드롭 -- 레이아웃과 PDK 가 필요하다"),
    ("DRC / LVS", "물리 검증 -- 파운드리 규칙과 레이아웃이 필요하다"),
    ("MCMM", "다중 코너·다중 모드 -- 코너별 .lib 가 필요하다"),
]

# 딜리버러블 목록. **있는지 없는지만 센다** -- 내용의 질은 기계가 못 잰다.
딜리버러블 = [
    ("rtl", "합성되는 RTL"),
    ("testbench", "자가검사 테스트벤치(VIP 의 씨앗)"),
    ("sdc", "타이밍 제약(SDC) -- 없으면 합성·STA 가 뜻을 잃는다"),
    ("register_map", "레지스터 맵 -- 통합하는 쪽이 제일 먼저 찾는다"),
    ("trm", "기술 문서(TRM) -- 인터페이스·타이밍도·프로그래밍 모델"),
    ("version", "버전과 릴리스 노트 -- 무엇이 바뀌었나"),
]


def 딜리버러블점검(있는것) -> dict:
    """무엇이 있고 무엇이 없나. `있는것` 은 이름의 모음."""
    가진것 = {str(x).strip().lower() for x in (있는것 or [])}
    빠진것 = [(k, 말) for k, 말 in 딜리버러블 if k not in 가진것]
    return {"모두": len(딜리버러블), "가진수": len(딜리버러블) - len(빠진것),
            "빠진것": 빠진것}


def 모으기(난것: "list[dict]") -> "tuple[str, str]":
    """관문 판정들을 하나로. **하나라도 깨지면 전체가 깨진 것이다.**

    순서가 뜻을 정한다: 깨진 것(FAIL)이 있으면 FAIL, 없어도 못 잰 것이 있으면 못잼.
    **못 잰 관문을 통과로 세지 않는다** -- 이 저장소의 규율을 사인오프에 옮긴 것이고,
    이 함수가 그 규율이 사는 자리다. 도구를 안 돌리므로 검사가 곧바로 붙든다.
    """
    깨진것 = [g for g in 난것 if g["판정"] == FAIL]
    못잰것 = [g for g in 난것 if g["판정"] == 못잼]
    if 깨진것:
        return FAIL, ("**사인오프가 아니다 -- 깨진 관문이 있다: "
                      + " · ".join(g["관문"] for g in 깨진것) + "**")
    if 못잰것:
        return 못잼, ("**사인오프가 아니다 -- 안 잰 관문이 있다: "
                      + " · ".join(g["관문"] for g in 못잰것) + "**. "
                      "못 잰 것은 통과가 아니다")
    if not 난것:
        return 못잼, "**관문을 하나도 안 돌렸다** -- 빈 것은 통과가 아니다"
    return PASS, "**관문을 다 지났다** -- 이 도구들이 볼 수 있는 범위 안에서"


def 관문들(설계: str, 벤치: str, top: str = "tb", 커버리지바닥: float = 80.0,
        목표MHz: float = 0.0, 칩: str = "hx8k", 딜리버러블있는것=(),
        초: int = 300) -> dict:
    """사인오프 관문을 차례로 돌린다. {판정, 관문:[...], 왜, 못재는것}."""
    import rtl
    난것 = []

    # 1. LINT -- 합성에서 무는 것들을 먼저 턴다
    r = rtl.린트(설계, 엄하게=True)
    난것.append({"관문": "LINT", "판정": r["판정"], "값": f"warnings {r['경고수']}",
                "왜": r["왜"]})

    # 2. SIM + 3. COVERAGE -- 한 번 돌려서 **두 판정을 따로 낸다.**
    # `rtl.시뮬` 은 커버리지가 바닥을 못 넘으면 제 판정을 못잼으로 내린다. 그것을 그대로
    # SIM 칸에 쓰면 **멀쩡히 통과한 시뮬이 못잼으로 찍힌다** -- 두 물음이 한 칸에 섞인다.
    # 여기서는 SIM 을 로그에서 다시 판정하고, 커버리지는 숫자로 따로 센다.
    r = rtl.시뮬(설계, 벤치, top, 초, 커버리지바닥=커버리지바닥)
    if r.get("로그"):
        시뮬판정, 시뮬왜 = rtl.판정하기(r["로그"])
    else:
        시뮬판정, 시뮬왜 = r["판정"], r["왜"]
    if r.get("끝값", 0) in (-1, 127) or "도구가 없다" in r.get("왜", ""):
        시뮬판정, 시뮬왜 = 못잼, r["왜"]
    난것.append({"관문": "SIM", "판정": 시뮬판정,
                "값": f"exit {r.get('끝값', '?')}", "왜": 시뮬왜})

    커 = r.get("커버리지")
    if 커 is None or 커 < 0:
        난것.append({"관문": "COVERAGE", "판정": 못잼, "값": "-",
                    "왜": r.get("커버리지말") or "커버리지를 못 쟀다"})
    else:
        난것.append({"관문": "COVERAGE",
                    "판정": PASS if 커 >= 커버리지바닥 else 못잼,
                    "값": f"{커:.1f}% (floor {커버리지바닥:.0f}%)",
                    "왜": r.get("커버리지말") or ""})

    # 4. FORMAL -- 성질이 없으면 공허한 통과다
    import formal
    r = formal.증명(설계, "", 20, True, 초=min(초, 280))
    난것.append({"관문": "FORMAL", "판정": r["판정"],
                "값": f"{r.get('성질수', 0)} properties", "왜": r["왜"]})

    # 5. SYNTH -- 면적
    r = rtl.합성(설계, "")
    난것.append({"관문": "SYNTH", "판정": r["판정"], "값": f"{r.get('셀수', -1)} cells",
                "왜": r["왜"]})

    # 6. TIMING -- 목표가 없으면 통과가 뜻이 없다
    if 목표MHz and 목표MHz > 0:
        import pnr
        r = pnr.맞춰보기(설계, "", 목표MHz, 칩, 초=초)
        난것.append({"관문": "TIMING", "판정": r["판정"],
                    "값": (f"{r['Fmax']:.1f} MHz / target {목표MHz:.0f}"
                          if r.get("Fmax", -1) > 0 else "-"), "왜": r["왜"]})
    else:
        난것.append({"관문": "TIMING", "판정": 못잼, "값": "-",
                    "왜": ("**목표 주파수를 안 줬다** -- 목표 없는 타이밍 통과는 뜻이 "
                          "없다(nextpnr 는 제 기본값 12MHz 에 대고 PASS 를 낸다)")})

    # 7. DOCS -- 있는지만 센다
    d = 딜리버러블점검(딜리버러블있는것)
    난것.append({"관문": "DOCS", "판정": PASS if not d["빠진것"] else 못잼,
                "값": f"{d['가진수']}/{d['모두']}",
                "왜": ("다 있다" if not d["빠진것"] else
                      "빠진 것: " + " · ".join(f"`{k}`({말})" for k, 말 in d["빠진것"]))})

    판정, 왜 = 모으기(난것)
    return {"판정": 판정, "관문": 난것, "왜": 왜, "못재는것": 못재는것}


def 말로(r: dict) -> str:
    줄 = [f"IP sign-off: **{r['판정']}** — {r['왜']}", ""]
    for g in r["관문"]:
        줄.append(f"  {g['관문']:9} {g['판정']:5} {g['값']:28} {g['왜'][:110]}")
    줄.append("")
    줄.append("**not measured here** (needs commercial tools / a PDK): "
              + " · ".join(f"{k}" for k, _ in r["못재는것"]))
    return "\n".join(줄)
