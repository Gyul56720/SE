"""graph/verify -- 요약이 원문에 서 있는가. 판정은 코드가 낸다 (brain 의 '대조' 꼴).

모델이 요약과 깃발을 제안할 수 있게 되면서 필요한 자리다: 지어낸 요약이 색인에
들어가는 것을 막는 검사. brain 의 대조 꼴 그대로 -- **이 주장이 원장의 어느 줄과
글자 그대로 맞는가.** 여기서 원장은 원문이다.

세 가지를 잰다.

  수치   요약의 수(값·%·연도)가 원문에 그대로 있는가. 하나라도 없으면 어긋남.
         지어낸 수가 제일 위험하다 -- 이 저장소의 원장 대조 규율이 온 자리다.
  깃발   깃발이 원문·이름 어디에도 없으면 어긋남. 연월 깃발(\\d{6})은 코드가 이름에서
         만든 것이라 면제다.
  근거율 요약 낱말이 원문에 얼마나 서 있는가. 문턱(0.7) 아래면 어긋남 -- 수는 안
         지어냈어도 원문에 없는 말로 채운 요약을 잡는다. 낱말 뒤 조사 한 글자는
         떼고도 본다(한국어 요약은 조사가 갈리는 것이 정상이다).

판정: **맞음 · 어긋남 · 미검증**(잴 것이 아예 없음). 참/거짓 둘뿐인 꼴은 두지 않는다
-- 못 잰 것을 한쪽에 밀어 넣으면 그 순간 거짓말이 된다(brain 규율).

모델에게 이 검사의 내용을 알려 주지 않는다 -- 알려 주면 통과하는 요약이 나오고
검사가 사양서가 된다(law/write.py 와 같은 규율).
"""
from __future__ import annotations

import re

문턱 = 0.7

불용 = {"그", "이", "저", "것", "수", "등", "및", "때", "안", "위해", "대한", "있다",
       "없다", "한다", "된다", "하는", "않는", "the", "and", "for", "with", "this",
       "that", "was", "are", "not"}

_수꼴 = re.compile(r"\d[\d,]*(?:\.\d+)?")
_말꼴 = re.compile(r"[0-9A-Za-z가-힣_.-]{2,}")
연월꼴 = re.compile(r"\d{6}")


def 수뽑기(text: str) -> "set[str]":
    """수를 정규화해 뽑는다: 12,000 -> 12000. 날짜(2026-08-28)는 조각으로 갈라져
    양쪽에서 같은 꼴이 되므로 그대로 견줄 수 있다."""
    return {m.replace(",", "") for m in _수꼴.findall(text or "")}


def 대조(요약: str, 깃발들, 원문: str, 이름: str = "") -> dict:
    """{판정, 위반, 근거율}. 판정은 맞음/어긋남/미검증."""
    바탕 = f"{원문 or ''}\n{이름 or ''}"
    바탕소 = 바탕.lower()
    위반: list = []
    잰 = False

    수들 = 수뽑기(요약)
    if 수들:
        잰 = True
        원문수 = 수뽑기(바탕)
        없는수 = sorted(n for n in 수들 if n not in 원문수)
        if 없는수:
            위반.append(f"원문에 없는 수: {', '.join(없는수[:5])}")

    검사깃발 = [f for f in (깃발들 or []) if not 연월꼴.fullmatch(str(f))]
    if 검사깃발:
        잰 = True
        없는깃발 = [f for f in 검사깃발 if str(f).lower() not in 바탕소]
        if 없는깃발:
            위반.append(f"원문에 없는 깃발: {', '.join(없는깃발[:5])}")

    토막 = [w.lower() for w in _말꼴.findall(요약 or "")
           if w.lower() not in 불용 and not w.isdigit()]
    근거율 = None
    if 토막:
        잰 = True
        선것 = sum(1 for t in 토막
                  if t in 바탕소 or (len(t) > 2 and t[:-1] in 바탕소))
        근거율 = 선것 / len(토막)
        if 근거율 < 문턱:
            위반.append(f"낱말 근거율 {근거율:.0%} < {문턱:.0%} -- 원문에 없는 말이 많다")

    판정 = "미검증" if not 잰 else ("맞음" if not 위반 else "어긋남")
    return {"판정": 판정, "위반": 위반, "근거율": 근거율}
