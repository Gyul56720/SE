"""**낱말 사전과 자.** 관문이 판정할 때 쓰는 눈금은 여기 한 벌만 둔다.

`law/wording.py` 를 뒤집은 자리다. 법에서는 문언을 바꿔 쓰면 안 되므로 치환을 잡았고,
자소서에서는 **사실을 부풀리는 낱말**을 잡는다. 둘 다 같은 것을 말한다 --
**낱말 하나가 사실을 바꾼다.**

    참여 -> 주도       한 일이 달라진다      (J004)
    2.1 -> 30          잰 값이 달라진다      (J002)

자를 여기 한 벌만 두는 이유는 `law/gate.py` 가 문장 자르는 자를 corpus 에 한 벌만
둔 것과 같다 -- 관문과 보고가 각자 들고 있으면 언젠가 갈라지고, 갈라지면 "걸렸다고
적으면서 통과시키는" 꼴이 된다.
"""
from __future__ import annotations

import re

# ---------------------------------------------------------------- 역할 승격 (J004)
#
# 원장이 `참여`·`보조`·`관찰` 인데 본문이 이렇게 쓰면 사실이 달라진다.
# `주도` 로 적힌 항목에 이 말을 쓰는 것은 위반이 아니다 -- 사실 그대로이므로.
승격어 = ("주도", "총괄", "리드", "이끌", "주관", "도맡", "진두지휘", "책임지고",
          "혼자", "전담", "기획부터", "처음부터 끝까지")
_승격 = re.compile("|".join(re.escape(w) for w in 승격어))

# ---------------------------------------------------------------- 성과 문맥 (J002)
#
# 수 뒤에 이런 단위가 붙고, 같은 문장에 성과 동사가 있으면 **잰 값을 주장한 것**이다.
# 그 수는 원장에 있어야 한다. 이 두 조건을 다 걸어야 '3학년' · '2025년' 같은 수가
# 안 걸린다 -- 안 걸면 관문이 정상 문장을 계속 보고하고, 그러면 아무도 안 읽는다.
성과단위 = ("%", "퍼센트", "배", "건", "명", "점", "위", "원", "만원", "억",
            "분", "초", "시간", "일", "개월", "주", "회", "개", "종", "m", "km",
            "MB", "GB", "ms")
# **활용형을 빠뜨리면 관문이 그 문장을 못 본다.**
#
# 실측: 처음에 `늘렸`·`늘어` 만 넣고 `늘었` 를 빠뜨렸다. 그래서 "참석 인원이 6명에서
# 19명으로 **늘었습니다**" 가 성과 문장으로 안 잡혔고, J002 는 그 수들을 아예 안
# 견주었으며 J007 은 "결과가 없다" 고 잘못 보고했다. 성한 문장에 빨간불이 켜지고
# 지어낸 수는 안 걸리는, 관문이 낼 수 있는 최악의 짝이다.
성과동사 = ("향상", "개선", "증가", "감소", "단축", "절감", "달성", "돌파", "상승",
            "하락", "줄였", "줄어", "줄었", "늘렸", "늘어", "늘었", "높였", "높였",
            "낮췄", "높아", "낮아", "올랐", "올라", "내렸", "떨어졌", "앞당",
            "확대", "축소", "끌어올", "이르렀", "기록했", "성장", "배로", "두 배")
_성과동사 = re.compile("|".join(성과동사))
_수단위 = re.compile(r"(\d[\d,]*(?:\.\d+)?)\s*(" +
                     "|".join(re.escape(u) for u in sorted(성과단위, key=len,
                                                           reverse=True)) + ")")

# ---------------------------------------------------------------- 상투구 (P003)
#
# **실측으로 늘린다.** 지금 목록은 씨앗이다. 사용자가 준 예전 자소서와 공고 게시판에서
# 실제로 반복되는 말을 보태 간다 -- 지어낸 사전은 지어낸 것만 잡는다.
상투구 = ("귀사의 인재상", "인재상에 부합", "어릴 적부터", "어렸을 때부터",
          "누구보다", "최선을 다하", "열정을 가지고", "밑거름", "초석",
          "성장할 수 있는 기회", "함께 성장", "일조하고 싶", "이바지하고 싶",
          "빠르게 변화하는", "4차 산업혁명", "무한한 가능성", "값진 경험",
          "소중한 경험", "뼈저리게", "몸소 느꼈", "각별한 관심", "매료되었",
          "천직", "적임자라고 확신", "뽑아 주신다면", "믿고 맡겨")
_상투 = re.compile("|".join(re.escape(w) for w in 상투구))

# ---------------------------------------------------------------- 주장 형용사 (P002)
#
# 이런 말은 **근거가 붙어야 말이 된다.** 붙지 않으면 자기 신고일 뿐이다.
# **어간으로 둔다.** 실측: `열정적` 만 넣었더니 "열정을 가지고 성장하고 싶습니다"
# 를 놓쳤다 -- 자기 신고를 잡으려고 만든 사전이 자기 신고의 제일 흔한 꼴을 놓친 것이다.
주장어 = ("열정", "책임감", "성실", "꼼꼼", "도전적", "적극적", "긍정적",
          "소통 능력", "커뮤니케이션 능력", "협업 능력", "리더십", "끈기",
          "인내심", "창의적", "분석적", "논리적", "친화력", "주인의식",
          "최선을 다하", "끝까지 해내")
_주장 = re.compile("|".join(re.escape(w) for w in 주장어))

# ---------------------------------------------------------------- 수동·명사화 (P004)
#
# 행위자가 사라지면 **누가 했는지가 안 보인다.** 자소서에서 그것은 치명적이다 --
# 읽는 사람이 재는 것이 바로 그것이므로.
_수동 = re.compile(r"되었습니다|되었다|되어졌|지게\s*되|하게\s*되었|이루어졌|"
                   r"진행되었|수행되었|만들어졌|생각됩니다|보여집니다|여겨집니다")

# **소수점을 문장 끝으로 읽지 않는다.**
#
# 실측: 처음에 `[^.!?\n]+[.!?]?` 로 잘랐더니 "클릭률을 2.1%에서 2.6%로 개선했습니다" 가
# `2`/`1%에서 2`/`6%로 개선했습니다` 로 갈렸다. 그러면 성과수로 잡히는 것이 `6` 하나가
# 되고, 원장의 `2.1`·`2.6` 과 안 맞으니 **성한 문장이 J002 위반으로 걸린다.**
# 관문이 눈이 없는 것이 아니라 **자가 고장난 것**이다 -- 자를 먼저 의심해야 한다는 것이
# 이 저장소의 규율이다(`law/mutate.py` 의 `_rewrite` 가 같은 자리에서 데었다).
_문장끝 = re.compile(r"(?<![0-9])[.!?]+(?![0-9])\s*|\n+")


def 문장들(글: str) -> list:
    return [s.strip() for s in _문장끝.split(글 or "") if s and s.strip()]


def 승격(글: str) -> list:
    """이 글이 쓴 승격어들."""
    return sorted(set(_승격.findall(글 or "")))


def 성과수들(글: str) -> list:
    """**잰 값을 주장한 자리.** `[(수, 단위, 문장), ...]`

    수 하나만으로는 안 잡는다 -- 같은 문장에 성과 동사가 있어야 한다. `2025년 3월`
    이나 `3학년` 은 값 주장이 아니다.
    """
    out = []
    for s in 문장들(글):
        if not _성과동사.search(s):
            continue
        for m in _수단위.finditer(s):
            out.append((_펴기(m.group(1)), m.group(2), s))
    return out


def _펴기(x: str) -> str:
    v = (x or "").replace(",", "")
    return v[:-2] if v.endswith(".0") else v


def 수단위쌍(글: str) -> list:
    """성과 동사를 안 따지고 (수, 단위, 문장) 을 전부. **원장 쪽에서 쓴다** --
    `어떻게` 는 재는 법이지 성과 서술이 아니므로 동사 조건을 걸면 아무것도 안 나온다."""
    return [(_펴기(m.group(1)), m.group(2), 글) for m in _수단위.finditer(글 or "")]


_배운것 = None


def 배운상투(다시: bool = False) -> tuple:
    """`jaso/corpus/작법/` 에서 배운 상투구. **없으면 빈 것이다 -- 예외가 아니다.**

    씨앗(`상투구`)은 손으로 적은 것이고 이쪽은 공개 작성 가이드에서 배운 것이다.
    `jaso/learn.py` 의 C001~C003 을 지난 것만 담기므로, 여기서 다시 거르지 않는다.
    지연 임포트인 까닭은 `learn` 이 이 파일을 쓰기 때문이다.
    """
    global _배운것
    if _배운것 is None or 다시:
        try:
            from jaso import learn as LN
            _배운것 = tuple(LN.읽기().갈래("상투구"))
        except Exception:                    # 원장이 없거나 깨졌어도 씨앗은 돈다
            _배운것 = ()
    return _배운것


def 상투(글: str) -> list:
    """씨앗 사전 + **배운 사전.** 배운 것이 없으면 씨앗만으로 돈다."""
    글 = 글 or ""
    return sorted(set(_상투.findall(글)) | {w for w in 배운상투() if w in 글})


def 주장문장들(글: str) -> list:
    """주장 형용사가 든 문장들. P002 가 이 문장의 문단에 근거가 있는지 본다."""
    return [s for s in 문장들(글) if _주장.search(s)]


def 수동밀도(글: str) -> tuple:
    """(수동 표현 수, 문장 수). 밀도는 부르는 쪽이 낸다 -- 여기서 판정하지 않는다."""
    ss = 문장들(글)
    return len(_수동.findall(글 or "")), len(ss)


def 글자수(글: str, 공백포함: bool = True) -> int:
    """제출 폼이 세는 대로 센다. **공백 규약이 문항마다 다르다.**

    마크다운 머리(`## `)와 앞뒤 빈 줄은 본문이 아니므로 부르는 쪽이 떼고 넣는다.
    """
    t = 글 or ""
    return len(t) if 공백포함 else len(re.sub(r"\s", "", t))

# ---------------------------------------------------------------- 일반성 (D 계열)
#
# **여기 있는 것은 탐지기 점수가 아니다.** 어떤 프로그램이 쓰이는지 모르고, 알아도
# 그 점수를 여기서 재현할 수 없다. 재는 것은 **글이 얼마나 일반적인가** 뿐이다.
#
# 겹치는 이유는 하나다. 판별 프로그램이 지어낸 글을 알아보는 까닭과, 사람이 읽고
# "누구나 쓸 수 있는 글" 이라고 느끼는 까닭이 같기 때문이다 -- 문장이 다 비슷한 길이고,
# 이음말로 굴러가고, 그 사람만 아는 것이 없다. **지어내지 않으면 이 값이 저절로 좋아진다.**

# 글을 굴리는 이음말. 하나씩은 멀쩡하고 **몰려 있으면 군더더기**다.
이음말 = ("또한", "뿐만 아니라", "이를 통해", "이러한 과정을 통해", "그 결과",
          "결과적으로", "무엇보다", "특히", "더불어", "나아가", "이와 같이",
          "이를 바탕으로", "먼저", "다음으로", "마지막으로", "즉", "따라서")
_이음 = re.compile("|".join(re.escape(w) for w in 이음말))

# 문항을 되풀이하고 시작하는 첫 문장.
_되풀이 = re.compile(r"^.{0,40}?(에 대해|에 관하여|에 관해)\s*(말씀드리|서술하|기술하|"
                     r"말씀|소개해)|^저는 .{0,30}(지원|말씀드리)")


def 고름(수들) -> float:
    """변동계수. **작을수록 다 비슷하다.** 0 이면 완전히 같다."""
    수들 = [x for x in 수들 if x]
    if len(수들) < 3:
        return 1.0                       # 재기에 모자라면 판정하지 않는 쪽으로
    m = sum(수들) / len(수들)
    if not m:
        return 1.0
    var = sum((x - m) ** 2 for x in 수들) / len(수들)
    return (var ** 0.5) / m


def 문장고름(글: str) -> float:
    return 고름([len(s) for s in 문장들(글)])


def 이음밀도(글: str) -> tuple:
    """(이음말 수, 문장 수)."""
    return len(_이음.findall(글 or "")), len(문장들(글))


def 문항되풀이(글: str) -> bool:
    """첫 문장이 문항을 되풀이하는가. 모델이 늘 하는 것이고, 칸만 먹는다."""
    ss = 문장들(글)
    return bool(ss and _되풀이.search(ss[0]))
