# 생각을 물어야 하는 요구 종류. 이것들은 원장의 **사실**로는 못 채운다.
생각요구 = {"지원동기": "지원동기", "이유": "지원동기", "계획": "포부",
            "성찰": "성찰", "지목": "가치"}


@dataclass
class 물음:
    id: str = ""
    칸: str = ""              # 답이 원장의 어디로 가나 -- intake 가 이것으로 넣는다
    대상: str = ""            # 어느 항목/생각에 붙나 (빈 문자열이면 새로 만든다)
    말: str = ""
    왜: str = ""              # 어느 관문이 지금 이 자리를 못 보나
    보기: str = ""            # 어떻게 적으면 되는지
    급함: int = 0             # 클수록 먼저. hard 를 막고 있는 것이 위다

    def __str__(self) -> str:
        머리 = f"[{self.id}] {self.말}"
        return (f"{머리}\n     왜: {self.왜}"
                + (f"\n     보기: {self.보기}" if self.보기 else ""))


def _새경험(n: int, q: IT.문항 | None) -> 물음:
    무엇 = (f"'{q.원문[:44]}…' 에 쓸" if q else "자소서에 쓸")
    return 물음(id=f"Q{n}", 칸="새항목", 말=f"{무엇} 일이 하나 필요합니다. "
               "**무엇을 · 어디서 · 언제부터 언제까지 · 무슨 역할로** 했습니까?",
               왜="원장에 항목이 없으면 J001~J004 와 P001 이 전부 미검증이 된다 -- "
                  "그 위에 쓴 자소서는 그냥 일반 LLM 출력이다",
               보기="사내 추천 시스템 개편, 무봉테크 인턴, 2025-03~2025-08, 참여",
               급함=100)


def 물을것(문항들: list, L: LG.원장, 몇: int = 8) -> list:
    """**빈칸을 센다.** 물음마다 어느 관문이 그 자리를 못 보고 있는지 적는다."""
    out, n = [], 0

    def 더(칸, 대상, 말, 왜, 보기="", 급함=0):
        nonlocal n
        n += 1
        out.append(물음(f"Q{n}", 칸, 대상, 말, 왜, 보기, 급함))

    # 1. 경험이 아예 없다 -- 다른 무엇보다 먼저다
    if not L.항목들:
        # **경험을 묻는 문항만 인용한다.** 지원동기 문항을 두고 "'우리 회사에 지원한
        # 이유를…' 에 쓸 일이 필요합니다" 라고 물으면 사용자는 무엇을 답해야 할지
        # 모른다 -- 그 문항이 경험을 안 물었으므로. 물음 자체는 없애지 않는다:
        # 항목이 0 이면 어느 문항이든 J001~J004 와 P001 이 전부 미검증이다.
        경험문항 = [q for q in 문항들
                   if {"경험", "행동", "결과"} & {r.종류 for r in q.요구}]
        for q in (경험문항[:2] or [None]):
            n += 1
            out.append(_새경험(n, q))
    else:
        # 2. 항목마다 판정을 막고 있는 빈칸 (E002 · E003 · E005 · P001)
        for h in L.항목들:
            이름 = h.이름 or h.id
            if h.역할 not in LG.역할들:
                더("역할", h.id,
                  f"[{이름}] 에서 당신의 역할은 {' · '.join(LG.역할들)} 중 "
                  "무엇이었습니까?",
                  "E002 -- 자유 서술이면 J004(역할 승격)가 눈이 없다. 원장이 '참여' "
                  "인지 '주도' 인지 정해져야 자소서의 '주도했다' 를 견줄 수 있다",
                  "참여", 급함=90)
            if not h.언제 or not all(LG._YM.match(x) for x in h.언제):
                더("언제", h.id, f"[{이름}] 은 언제부터 언제까지였습니까?",
                  "E003 -- J003 이 이것으로 기간을 잰다. '6개월간' 을 '1년간' 으로 "
                  "적는 것은 이력서와 대조되면 바로 걸린다",
                  "2025-03 ~ 2025-08", 급함=90)
            if not LG.말앵커(h) and not LG.수앵커(h):
                더("쓴것", h.id,
                  f"[{이름}] 에서 **당신만 말할 수 있는 것**을 하나만 적어 주십시오. "
                  "쓴 도구·기관 이름·다룬 수 아무거나 됩니다.",
                  "P001 -- 원장에서 온 것이 하나도 안 박힌 문단은 회사 이름만 바꾸면 "
                  "어느 회사에나 들어간다. 읽는 사람이 제일 먼저 알아보는 자리다",
                  "Python, BigQuery / 8개 층 40지점", 급함=80)
            for i, m in enumerate(h.잰것):
                if not m.쓸수있나:
                    더(f"어떻게:{i}", h.id,
                      f"[{이름}] 의 '{m.무엇 or '그 수'}' 를 **어떻게 쟀습니까?** "
                      "무엇을 · 얼마 동안 · 몇 건으로 쟀는지.",
                      "E004 -- 잰 방법이 없으면 그 수는 원장에 남아도 자소서에 "
                      "못 쓴다(J002 가 막는다). 안 잰 수를 쓰는 것이 자소서에서 "
                      "제일 흔한 거짓말이다",
                      "2주 A/B, 대조군 24,000 · 실험군 24,000명", 급함=85)
            if not h.잰것 and any("결과" in {r.종류 for r in q.요구}
                                 for q in 문항들):
                더("잰것", h.id,
                  f"[{이름}] 로 **무엇이 달라졌습니까?** 잰 수가 있으면 그 수와 "
                  "재는 법을 같이 적어 주십시오. 없으면 '안 쟀다' 고 적으십시오.",
                  "문항이 결과를 묻는데 원장에 잰 것이 없다 -- 없는 채로 쓰면 "
                  "생성자가 수를 지어내고 그것이 J002 에 걸린다(F1)",
                  "클릭률 2.1% -> 2.6% (2주 A/B, n=48,000)", 급함=70)
            if not h.증빙.strip():
                더("증빙", h.id,
                  f"[{이름}] 을 면접에서 물으면 무엇을 보여 주시겠습니까?",
                  "E005 -- 판정에는 안 쓰지만, 못 보여 줄 것은 자소서에도 안 쓰는 "
                  "편이 낫다", "커밋 로그 · 최종 보고서", 급함=20)

        # 3. 재료가 문항 수에 모자라다 (P006 재탕)
        if 문항들 and len(L.항목들) < len(문항들):
            더("새항목", "",
              f"문항이 {len(문항들)}개인데 쓸 경험이 {len(L.항목들)}개입니다. "
              "하나 더 있습니까?",
              "P006 -- 한 경험을 여러 문항에 돌려 쓰면 한 벌을 통째로 읽는 사람에게 "
              "재료가 하나뿐인 것으로 보인다", 급함=40)

    # 4. 생각 -- 사실로는 못 채우는 자리
    필요한생각 = {}
    for q in 문항들:
        for r in q.요구:
            if (갈래 := 생각요구.get(r.종류)):
                필요한생각.setdefault(갈래, q)
    for 갈래, q in 필요한생각.items():
        if L.생각찾기(갈래):
            continue
        말 = {"지원동기": "**왜 이 회사·이 직무입니까?** 남들도 할 수 있는 말 말고, "
                       "당신이 실제로 보거나 겪어서 그렇게 생각하게 된 것을 적어 주십시오.",
             "포부": "들어가서 **처음 1년에 무엇을 하고 싶습니까?**",
             "성찰": "위 경험에서 **생각이 바뀐 것**이 있습니까? 무엇을 믿고 있었고 "
                    "무엇을 보고 바뀌었는지.",
             "가치": "이 직무에서 **가장 중요한 것 하나**를 꼽는다면 무엇이고, 왜 "
                    "그렇게 생각합니까?"}[갈래]
        더(f"생각:{갈래}", "", 말,
          f"문항이 이것을 묻는데(‘{q.원문[:30]}…’) 원장에 대조할 바깥이 없다. "
          "**안 물으면 생성자가 지어낸다** -- 지어낸 지원동기가 P001 에 걸리는 "
          "바로 그 문단이다", 급함=60)

    out.sort(key=lambda x: -x.급함)
    for i, x in enumerate(out, 1):
        x.id = f"Q{i}"
    return out[:몇] if 몇 else out


def 남은것(문항들: list, L: LG.원장) -> dict:
    """지금 **무엇이 미검증인가**. 물음을 다 답하면 이 수가 준다."""
    막힌것 = len(LG.hard(LG.검사(L)))
    앵커없음 = sum(1 for h in L.항목들 if not LG.말앵커(h) and not LG.수앵커(h))
    못쓰는수 = sum(1 for h in L.항목들 for m in h.잰것 if not m.쓸수있나)
    필요생각 = {생각요구[r.종류] for q in 문항들 for r in q.요구
                if r.종류 in 생각요구}
    return {"항목": len(L.항목들), "문항": len(문항들), "원장hard": 막힌것,
            "앵커없는항목": 앵커없음, "못쓰는수": 못쓰는수,
            "빈생각": sorted(필요생각 - {g.갈래 for g in L.생각들})}


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description="무엇을 물을지 계산한다 (LLM 안 씀)")
    ap.add_argument("--표", dest="표", default="", help="경험 원장 JSON (없으면 빈 원장)")
    ap.add_argument("--문항", dest="문항", action="append", default=[])
    ap.add_argument("--문항원장", action="store_true", help="jaso/corpus 의 문항을 쓴다")
    ap.add_argument("--곳", default=str(CP.문항DIR))
    ap.add_argument("--몇", dest="몇", type=int, default=8)
    ap.add_argument("--json", dest="asjson", action="store_true")
    a = ap.parse_args(argv)

    문항들 = [IT.쪼개기(x, str(i + 1)) for i, x in enumerate(a.문항)]
    if a.문항원장:
        문항들 += [q.쪼갠것() for q in CP.읽기(a.곳).문항들]
    L = LG.읽기(a.표) if a.표 else LG.원장()

    qs = 물을것(문항들, L, a.몇)
    남 = 남은것(문항들, L)
    if a.asjson:
        print(json.dumps({"물음": [x.__dict__ for x in qs], "남은것": 남},
                         ensure_ascii=False, indent=2))
        return 0

    if not 문항들:
        print("문항이 없다 -- `--문항 \"<원문>\"` 을 주거나 `--문항원장` 을 쓰십시오.\n"
              "  (원장을 채우려면: python3 jaso/fetch.py --질의 \"...\" · VM 에서)",
              file=sys.stderr)
    print(f"문항 {남['문항']}개 · 원장 항목 {남['항목']}개")
    막힌말 = []
    if 남["원장hard"]:
        막힌말.append(f"원장 hard {남['원장hard']}건")
    if 남["앵커없는항목"]:
        막힌말.append(f"앵커 없는 항목 {남['앵커없는항목']}개")
    if 남["못쓰는수"]:
        막힌말.append(f"못 쓰는 수 {남['못쓰는수']}개")
    if 남["빈생각"]:
        막힌말.append("빈 생각: " + " · ".join(남["빈생각"]))
    print("지금 막고 있는 것: " + (" · ".join(막힌말) if 막힌말 else "없다"))

    if not qs:
        print("\n**더 물을 것이 없다.** 재료가 찼다.")
        print("  이제 씁니다:  python3 jaso/write.py --표 내원장.json --문항 \"...\"")
        return 0
    print(f"\n물을 것 {len(qs)}개 -- 번호를 붙여 답해 주십시오 "
          "(`1) …` 꼴이면 그대로 원장에 들어갑니다)\n")
    for x in qs:
        print(x)
        print()
    print("답을 다 적으셨으면:  python3 jaso/intake.py --표 내원장.json "
          "--물음 물음.json --답 답.txt")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
