"""**물음은 생성물이 아니라 도출물이다.** LLM 을 안 쓴다.

    python3 jaso/ask.py --문항원장                      # 원장의 문항으로
    python3 jaso/ask.py --문항 "<문항 원문>" --표 내원장.json
    python3 jaso/ask.py --문항원장 --표 내원장.json --몇 10 --json

## 무엇을 물을지는 계산된다

```
물을 것 = 문항이 요구하는 것  −  원장이 이미 가진 것
```

`law/METHOD.md` 의 결론이 **쟁점은 생성물이 아니라 도출물**이었고 `brief/` 가 **수는
생성물이 아니라 도출물**이었다. 여기서도 같다 -- 무엇을 물어야 하는지는 모델에게
물어볼 것이 아니라 **빈칸을 세면 나온다.**

그래서 물음마다 `왜` 가 붙는다. 어느 관문이 지금 그 자리를 못 보고 있는지다.

    [E004] 이 수를 어떻게 쟀습니까      -> 못 적으면 J002 가 그 수를 자소서에서 막는다
    [P001] 고유한 것을 하나만 더        -> 앵커가 0 이면 어느 회사에나 들어가는 문단이 된다

**모델에게 물음을 지어내게 하면 이 줄이 사라진다.** 그럴듯한 물음이 나오고, 왜 그것을
묻는지는 아무도 모르며, 답을 받아도 무엇이 채워졌는지 셀 수가 없다.

## 사실만으로는 자소서가 안 된다

지원동기·포부·성찰은 원장에 대조할 바깥이 없다. 그래도 **물어는 본다** -- 안 물으면
생성자가 그 자리를 지어내고, 지어낸 지원동기가 바로 P001 에 걸리는 그 문단이다.
받은 것은 `생각` 으로 원장에 담기고 **구성상 미검증**이라고 표시된다.

## 안 묻는 것

- **"당신의 강점은 무엇입니까"** 를 안 묻는다. 그것은 사실에서 나올 결론이지 재료가
  아니다. 물어서 받으면 그대로 자소서에 옮겨 적게 되고, 그것이 P002(근거 없는 자기
  신고)다.
- **계산되는 것**을 안 묻는다. 기간의 개월 수, 글자 수, 어느 문항에 어느 경험을 쓸지 --
  다 코드가 낸다.
- **관문 이름을 사용자에게 숨기지 않는다.** 생성자에게는 숨기지만(`law/write.py`),
  사람에게는 왜 묻는지 알려 주는 편이 낫다. 사람은 관문을 통과하려고 사실을 바꾸지
  않는다 -- 바꾸면 그건 사실이 아니게 되므로 애초에 목적이 어긋난다.
"""
from __future__ import annotations

import argparse
import json
import sys
