# 문항이 여러 물음을 잇는 자리. 여기가 갈리면 요구가 둘 이상이라는 신호다.
_이음 = re.compile(r"(하고|하며|이며|또한|그리고|,|및)\s")

# **하한 쪽 `자` 는 없을 때가 더 많다** -- `500~700자` 로 쓴다. 처음에 `자` 를
# 필수로 두었더니 하한 500 을 통째로 놓쳤다(실측). 그러면 J005 가 밑을 못 본다.
_글자수 = re.compile(r"(?:(\d[\d,]*)\s*자?\s*(?:이상|~|∼|-|부터)\s*)?"
                     r"(\d[\d,]*)\s*자(?:\s*(이내|이하|내외))?")
_공백제외 = re.compile(r"공백\s*(제외|미포함|불포함)")
_공백포함 = re.compile(r"공백\s*(포함)")


@dataclass
class 요구:
    id: str
    종류: str
    말: str
    표지: str = ""            # 답변에서 이것이 보이면 닿은 것으로 본다
    이음대상: tuple = ()      # 이 요구가 견주는 두 요구 (F4 의 자리)

    @property
    def 이음인가(self) -> bool:
        return bool(self.이음대상)


@dataclass
class 문항:
    원문: str
    상한: int = 0             # 0 이면 안 적힌 것 -- **모르는 것은 안 잰다**
    하한: int = 0
    공백포함: bool = True
    요구: list = field(default_factory=list)
    번호: str = ""

    @property
    def 쪼갬(self) -> int:
        return len([r for r in self.요구 if not r.이음인가])


def 글자수규약(글: str) -> tuple:
    """문항에서 (하한, 상한, 공백포함) 을 읽는다. **없으면 0 이다 -- 짐작하지 않는다.**

    한국 자소서에서 이 규약은 hard 다. 넘으면 제출 폼이 자른다. 그런데 표기가 제각각이라
    (`1000자 이내` · `500~700자` · `공백 제외 1,000자`) 하나씩 다 받는다.
    """
    포함 = not bool(_공백제외.search(글)) if not _공백포함.search(글) else True
    m = _글자수.search(글.replace(" ", " "))
    if not m:
        return 0, 0, 포함
    하 = int((m.group(1) or "0").replace(",", ""))
    상 = int(m.group(2).replace(",", ""))
    return 하, 상, 포함


def 쪼개기(글: str, 번호: str = "") -> 문항:
    """문항 원문 -> 요구 목록. **못 쪼개면 `기술` 하나로 떨어진다.**"""
    하, 상, 포함 = 글자수규약(글)
    본문 = _글자수.sub(" ", 글)
    reqs, n = [], 0
    for 종류, 문항말, 답변말, 설명 in 요구들:
        if re.search(문항말, 본문):
            n += 1
            reqs.append(요구(id=f"r{n}", 종류=종류, 말=설명, 표지=답변말))
    if not reqs:
        reqs = [요구(id="r1", 종류="기술", 말="문항이 물은 것을 적었는가",
                    표지=r"습니다|입니다|였다|했다")]

    # **이음 요건.** 짚은 것과 든 경험이 같은 것인가 -- F4 가 잡히는 유일한 자리다.
    지목 = next((r for r in reqs if r.종류 == "지목"), None)
    # **경험을 먼저 본다.** 사전 순서로 집으면 `행동` 이 먼저 잡히는데, F4 는
    # "짚은 역량과 **든 경험**이 같은가" 라서 경험 쪽에 걸어야 뜻이 맞다.
    경험 = (next((r for r in reqs if r.종류 == "경험"), None)
            or next((r for r in reqs if r.종류 == "행동"), None))
    if 지목 and 경험:
        reqs.append(요구(id=f"r{len(reqs) + 1}", 종류="이음",
                        말=f"짚은 것({지목.id})과 든 경험({경험.id})이 같은 것인가",
                        이음대상=(지목.id, 경험.id)))
    return 문항(원문=글.strip(), 상한=상, 하한=하, 공백포함=포함, 요구=reqs, 번호=번호)


# ---------------------------------------------------------------- reason 다리

def 스키마(q: 문항, 걸린것=()) -> dict:
    """`reason/` 이 읽는 표로 옮긴다. **판정은 거기서 한다.**

    `걸린것` 은 관문이 못 닿았다고 본 요구 id 들이다. 심사자 쪽 입장이 그것으로
    정해진다 -- 그래야 두 정거장이 **실제로** 갈리고, 갈리는 자리가 이 자소서가
    떨어지는 자리가 된다. 비워 두면 양쪽이 같은 말을 해서 `reason` 의 S007 이 잡는다
    (그리고 그것이 맞다 -- 다툴 거리가 없으면 다툼 물음이 아니다).
    """
    걸린것 = set(걸린것)
    요건 = []
    for r in q.요구:
        요건.append({"id": r.id, "말": r.말, "역할": "세움",
                    "출처": f"문항 원문: {q.원문[:60]}"})
    return {
        "물음": "이 답변이 문항이 물은 것에 답했는가",
        "세우는쪽": "지원자", "다투는쪽": "심사자",
        "요건": 요건,
        "입장": {r.id: {"지원자": True, "심사자": r.id not in 걸린것}
                for r in q.요구},
    }


# ---------------------------------------------------------------- 문서에서 문항 읽기

# `## 1. <문항> (700자)` 꼴. 번호는 있어도 없어도 된다.
_머리 = re.compile(r"^##\s+(?:(\d+)\s*[.)]\s*)?(.+?)\s*$")


def 문서읽기(글: str) -> list:
    """자소서 한 벌에서 문항들을 읽는다. `## ` 머리가 문항 원문이다."""
    out = []
    for line in (글 or "").splitlines():
        m = _머리.match(line)
        if m:
            out.append(쪼개기(m.group(2), m.group(1) or ""))
    return out


# ---------------------------------------------------------------- CLI

def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description="자소서 문항을 요건으로 쪼갠다 (LLM 안 씀)")
    ap.add_argument("글", nargs="?", default="", help="문항 원문")
    ap.add_argument("--문서", default="", help="자소서 .md 에 든 문항 전부")
    ap.add_argument("--스키마", action="store_true", help="reason/ 에 넘길 표를 낸다")
    a = ap.parse_args(argv)

    if a.문서:
        qs = 문서읽기(Path(a.문서).read_text(encoding="utf-8"))
    elif a.글:
        qs = [쪼개기(a.글)]
    else:
        ap.error("문항을 주거나 --문서 를 주십시오")

    if not qs:
        print("문항을 못 찾았다 -- `## <문항> (700자)` 꼴이어야 한다", file=sys.stderr)
        return 3

    for q in qs:
        if a.스키마:
            print(json.dumps(스키마(q), ensure_ascii=False, indent=2))
            continue
        칸 = (f"{q.하한}~{q.상한}자" if q.하한 else
              (f"{q.상한}자" if q.상한 else "**글자 수가 안 적혔다 -- J005 를 못 잰다**"))
        print(f"\n[문항 {q.번호 or '?'}] {q.원문[:70]}")
        print(f"  {칸} · 공백{'포함' if q.공백포함 else '제외'} · 요구 {q.쪼갬}개")
        for r in q.요구:
            print(f"    {r.id} [{r.종류}] {r.말}")
        if q.쪼갬 == 1 and q.요구[0].종류 == "기술":
            print("    ** 사전이 이 문항을 못 쪼갰다.** 요구 하나로 떨어졌다 -- "
                  "J006 이 여기서는 거의 아무것도 못 본다")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
