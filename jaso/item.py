"""**문항을 요건으로 쪼갠다.** LLM 을 안 쓴다.

    python3 jaso/item.py "지원 직무에 필요한 역량은 무엇이며 그것을 갖추기 위해 어떤 노력을 했는지 구체적 경험을 바탕으로 기술하시오. (1000자)"
    python3 jaso/item.py --문서 자소서.md          # 문서에 든 문항 전부
    python3 jaso/item.py "<문항>" --스키마          # reason/ 에 넘길 표를 낸다

## 왜 쪼개야 하는가

자소서 문항은 겉으로 한 문장이지만 **요구가 여럿 숨어 있다.**

    "필요한 역량은 무엇이며, 그것을 갖추기 위해 어떤 노력을 했는지,
     구체적인 경험을 바탕으로 기술하시오"

    -> 지목: 역량을 하나 짚었는가
    -> 행동: 그것을 갖추려 한 노력이 적혔는가
    -> 경험: 그 노력이 구체적 경험으로 뒷받침되는가
    -> **이음: 짚은 역량과 든 경험이 같은 것인가**   <- 여기가 제일 잘 깨진다

넷째가 F4 다. 일반 LLM 은 역량은 A 라고 해 놓고 경험은 B 를 쓴다 -- 각각은 잘 쓰여
있어서 따로 읽으면 안 보이고, 둘을 견줄 때만 보인다. **견주는 자리가 이 파일이다.**

## 새 판정기를 안 만든다

쪼갠 표는 `reason/` 으로 넘긴다(`--스키마`). 두 정거장과 뒤집기는 거기 이미 있다 --
`brain/README.md` 가 "여기서 또 하면 두 벌이 생기고 두 벌은 언젠가 갈라진다" 고 적은
자리다. 여기서는 **쪼개기까지만** 한다.

세우는 쪽은 지원자, 다투는 쪽은 심사자다. 지원자는 요건이 다 섰다고 하고, 심사자는
관문에 걸린 요건만 안 섰다고 한다. 그러면 두 정거장이 갈리는 자리가 곧 **이 자소서가
떨어지는 자리**다.

## 사전으로 쪼갠다 -- 그리고 그 한계를 적어 둔다

요구 종류마다 한국어 문항에서 실제로 쓰이는 말이 정해져 있다("무엇이라고 생각",
"어떤 노력", "그 결과", "느낀 점"). 사전이 못 보는 문항은 **`기술` 요건 하나로
떨어진다** -- 못 쪼갠 것을 쪼갠 척하지 않는다. `--쪼갬` 이 몇 개로 갈렸는지 늘 적는다.
"""
