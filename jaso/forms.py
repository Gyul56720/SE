"""**프롬프트 문법 후보.** 무엇이 나은가는 여기서 안 정한다 -- `bench.py` 가 잰다.

    python3 jaso/forms.py                    # 어떤 문법이 있나
    python3 jaso/forms.py --문법 두괄        # 그 문법이 무엇을 시키나

## 왜 목록으로 두나

"자소서는 두괄식이 좋다" · "첫 문장은 장면으로" 는 **감으로 정해진 채 굳어 있다.**
이 저장소의 규율은 감으로 정한 것을 재서 정하는 것이므로, 후보를 늘어놓고 관문으로
견준다 -- `mathgen` 이 생성기를 진화시키고 sympy 가 채점하는 자리, `compression` 이
코덱을 탐색하고 심판이 채점하는 자리와 같은 배치다.

**여기 있는 것은 후보이고 순위가 아니다.** 순위는 `jaso/bench.py` 가 낸다.

## 캔 형식을 넣을 때는 **손으로 붙인다**

`jaso/mine.py --문법후보` 가 여기 붙일 초안을 낸다. 그런데 그것을 **자동으로 읽어
오지 않는다** -- 읽어 오면 밖에서 긁은 분포가 말없이 프롬프트를 바꾸고, 어느 날
프롬프트가 왜 그런지 아무도 모르게 된다. 붙이는 것은 사람이 보고 하고, 붙인 뒤에는
반드시 `bench.py` 로 잰다.

## 무엇이 아닌가

**합격률이 아니다.** 합격률을 재려면 (자소서, 합격여부) 짝이 있어야 하는데 그것이
없고, 인터넷의 '합격 자소서' 는 합격자만 올리므로 **불합격 쪽이 통째로 빠진 표본**이다
(선택 편향). 게다가 합격은 자소서만으로 정해지지 않는다 -- 학점·전공·경력·면접·TO 가
대부분이고, 그것을 빼고 자소서만 회귀하면 교란이 그대로 결론이 된다.

그래서 여기서 견주는 축은 **관문**이다. 지어내지 않고 · 문항에 답하고 · 그 사람만
쓸 수 있는 글이 나오는 비율. 그것이 합격률의 대리라고 주장하지 않는다.
"""
from __future__ import annotations

import argparse
from dataclasses import dataclass, field


@dataclass
class 문법:
    이름: str
    설명: str
    어떻게: list = field(default_factory=list)     # '## 어떻게 쓰나' 에 들어갈 줄들

    def 조각(self) -> str:
        return "\n".join(f"- {x}" for x in self.어떻게)


