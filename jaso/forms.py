def 고르기(이름: str) -> 문법:
    """**모르는 이름은 기본이다.** 예외로 죽으면 런이 통째로 없어진다."""
    return 문법들.get((이름 or "").strip(), 문법들["기본"])


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description="프롬프트 문법 후보 (순위는 bench 가 낸다)")
    ap.add_argument("--문법", dest="문법", default="")
    a = ap.parse_args(argv)

    if a.문법:
        f = 고르기(a.문법)
        print(f"# {f.이름} -- {f.설명}\n")
        print(f.조각())
        return 0
    print("프롬프트 문법 후보\n")
    for f in 문법들.values():
        print(f"  {f.이름:<8} {f.설명}")
    print("\n무엇이 나은가는 여기서 안 정한다:")
    print("  python3 jaso/bench.py --표 원장.json --문항 \"<원문>\"")
    print("\n**이 축은 합격률이 아니다.** 합격률은 (자소서, 합격여부) 짝이 있어야 "
          "재는데 그것이 없고,\n인터넷의 '합격 자소서' 는 합격자만 올리므로 불합격 "
          "쪽이 통째로 빠진 표본이다.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
