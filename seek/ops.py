r"""**문제를 바꾸는 수.** 식을 바꾸는 수가 아니다.

`mathdrift/ops.py` 는 식에 거는 연산자였다(매장 · 완비화 · 국소화). 여기서 거는
것은 **문제**이고, 문제는 (물음, 표본, 판정) 셋이라 바꿀 자리가 다르다.

    후보꼴을 바꾼다   자원 풀기 · 차원 올리기 · 표현 바꾸기 · 층 나누기
    판정을 바꾼다     경계화 · 무작위화 · 국소화 · 물음 바꾸기 · 증인 요구
    둘 다             합성 · 뒤집기

**거리**는 mathdrift 와 같은 뜻이다. 1 은 이웃, 2 는 급발진. 급발진 몫은 낮게 둔다 --
문제를 멀리 던지면 판정기를 못 쓰고, 판정기를 못 쓰면 원장이 안 받는다. 발산이
아니라 그냥 버려진다.

**골라 낸 목록이 아니다.** 이 열둘이 좋아서가 아니라, 실측으로 도약을 낸 것(경계화)과
재작성을 낸 것(뒤집기)이 둘 다 여기 있어야 자가 뜻을 갖기 때문이다.
"""
from __future__ import annotations

import hashlib
import os

OPS = [
    ("경계화", "정확함을 조금 놓아 준다. 몇 개까지 틀려도 받는다"
               " (Schoenhage 의 경계 랭크가 이 수다)", 1),
    ("자원 풀기", "문제에 상수로 박혀 있던 자원(개수·크기·차수)을 **자유롭게** 놓는다."
                  " 그러면 그것을 줄이는 것이 새 물음이 된다", 1),
    ("차원 올리기", "같은 물음을 한 치수 큰 데서 묻는다", 1),
    ("제약 더하기", "후보가 만족해야 할 구조를 하나 더 건다 (대칭 · 층 · 희소)", 1),
    ("표현 바꾸기", "같은 것을 다른 자료로 적는다. 후보꼴이 달라진다", 1),
    ("국소화", "전부가 아니라 **일부 입력에서만** 맞으면 된다고 한다", 1),
    ("무작위화", "확률로 맞으면 받는다. 판정이 표본을 쓰게 된다", 1),
    ("증인 요구", "답만으로는 안 받고 **왜 답인지**를 같이 내게 한다."
                  " 판정기가 그 증거를 검산한다", 1),
    ("뒤집기", "묻는 방향을 뒤집는다. 최대를 최소로, 존재를 부재로", 1),
    ("물음 바꾸기", "같은 대상에 **다른 것**을 묻는다", 2),
    ("합성", "두 문제를 한꺼번에 만족시키라고 한다", 2),
    ("역문제", "답을 주고 **어떤 문제의 답인가**를 묻는다", 2),
]

BY_NAME = {n: (w, d) for n, w, d in OPS}
NEAR = [n for n, _, d in OPS if d == 1]
JUMP = [n for n, _, d in OPS if d >= 2]

# 급발진 몫. mathdrift 는 0.2 였는데 여기는 낮다 -- 멀리 던진 문제는 판정기를 못 써서
# 원장이 안 받고, 그건 발산이 아니라 버려지는 것이다.
JUMP_SHARE = float(os.environ.get("SEEK_JUMP_SHARE", "0.12"))


def draw(seed: str, n: int) -> tuple:
    """씨앗에 묶인 뽑기. 같은 (씨앗, n) 에는 같은 연산자 -- 이어 돌려도 재현된다."""
    h = int(hashlib.sha256(f"{seed}/{n}".encode()).hexdigest(), 16)
    pool = JUMP if (h % 100) / 100.0 < JUMP_SHARE else NEAR
    name = pool[(h >> 8) % len(pool)]
    what, dist = BY_NAME[name]
    return name, what, dist


def rarest(used: dict) -> list:
    """덜 써 본 것부터. 기각이 아니라 순서만 바꾸는 약한 균형추다."""
    return sorted((n for n, _, _ in OPS), key=lambda n: (used.get(n, 0), n))
