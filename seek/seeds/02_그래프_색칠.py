r"""그래프 색칠 -- **그래프 이론.** 대상: 정점에 붙인 색.

페테르센 그래프를 고정해 둔다. 그래프가 고정이라 판정이 완전하다 -- 변 15개를
다 본다. 색수가 3이므로 답이 있다(3-색칠이 120가지).
"""

물음 = "페테르센 그래프(정점 10 · 변 15)를 색 3가지로 칠할 수 있는가"


def sample(rng):
    """정점 10개에 0·1·2 중 하나씩."""
    return [rng.randrange(3) for _ in range(10)]


def judge(x):
    """변 15개를 다 본다. **완전 판정** -- 그래프가 고정이라 표본이 아니다."""
    변 = [(0, 1), (1, 2), (2, 3), (3, 4), (4, 0),
          (5, 7), (7, 9), (9, 6), (6, 8), (8, 5),
          (0, 5), (1, 6), (2, 7), (3, 8), (4, 9)]
    if not isinstance(x, (list, tuple)) or len(x) != 10:
        raise ValueError("정점이 10개가 아니다")
    색 = [int(c) for c in x]
    if any(not (0 <= c < 3) for c in 색):
        raise ValueError("색이 0·1·2 가 아니다: %r" % (색,))
    return all(색[a] != 색[b] for a, b in 변)
