def sample(rng):
    """20비트 고르기."""
    return [rng.randrange(2) for _ in range(20)]


def judge(x):
    """더해 보면 끝이다. **완전 판정.**"""
    수 = [92, 145, 27, 311, 68, 203, 154, 39, 276, 118,
          87, 231, 165, 49, 298, 132, 76, 219, 103, 187]
    if not isinstance(x, (list, tuple)) or len(x) != 20:
        raise ValueError("고르기가 20칸이 아니다")
    고름 = [int(v) for v in x]
    if any(v not in (0, 1) for v in 고름):
        raise ValueError("0이나 1이 아니다: %r" % (고름,))
    return sum(n for n, v in zip(수, 고름) if v) == 1000
