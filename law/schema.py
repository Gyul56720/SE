"""법률명제 스키마 -- **같은 말을 같은 열쇠로 묶는다.**

문장은 같은 것을 여러 꼴로 쓴다. 그 꼴이 다르다는 이유로 심판이 어긋남을 매기면
**맞는 답이 버려진다.** 이 저장소는 그 자리를 이미 두 번 앓았다:

    W001  조문 "착오를 증명한 때에는 취소할 수 있다"        재량
          문서 "취소하려면 착오를 증명하여야 한다"          기속   -> 어긋남으로 잡힘
          그런데 **같은 명제다.** 요건-효과를 앞뒤로 뒤집어 적었을 뿐이다.

    L003  조문 제449조를 부른 지문의 '2년' 이 제450조에 있었다 -> 없는 수량이라며 기각

앞의 것은 `wording.py` 가 **동사 단위 대조**로 비켜갔고 뒤의 것은 `corpus.via` 가
**2홉**으로 비켜갔다. 둘 다 옳은 처방이지만 둘 다 *그 자리에서만* 듣는다. 여기서는
문장을 **명제로 세워** 놓고 그 위에서 견준다.

**접는 것과 안 접는 것을 갈라 둔다.**

    접는다     서법의 다른 꼴      하지 못한다 = 할 수 없다 = 하여서는 아니 된다
               능동·피동·사동      취소한다 = 취소된다 = 취소시킨다
               요건-효과 뒤집기    A한 때 B할 수 있다 = B하려면 A하여야 한다

    안 접는다  낱말 뜻            '취소' 와 '무효' 는 다른 말이다
               당사자             甲이 한 것과 乙이 한 것은 다른 명제다
               부정               '대항한다' 와 '대항하지 못한다' 는 반대다

**뜻으로 접지 않는 이유**: 법에서 취소·무효·해제·해지는 요건도 효과도 다르다.
비슷해 보인다고 묶으면 심판이 다른 명제를 같다고 하고, 그때는 **틀린 답이 통과한다.**
접기는 꼴에서 멈춘다 -- 뜻은 사람이 판례로 가른다.
"""

from __future__ import annotations

import re
from dataclasses import dataclass, field

from . import morph as M

# 목적절을 여는 꼴. 이 뒤에 오는 기속은 **효과가 아니라 요건**이다.
_목적 = re.compile(r"(.+?)(?:하기\s*위하여(?:는)?|하려면|하고자\s*하는\s*경우(?:에는)?|"
                   r"함에\s*있어(?:서는)?|하기\s*위해(?:서는)?)")

# 능동·피동·사동. 꼴만 다르고 명제는 같다.
_태 = re.compile(r"(?:되|시키|당하|받)$")

_공백 = re.compile(r"\s+")

# 결론절을 여는 자리. **시험 지문은 조문 한 문장이 아니다.**
# 실측: 문 13 의 ㄱ·ㄴ·ㄹ 은 "甲이 ...한 경우, ...한다" 꼴인데, 문장 전체에서
# 격을 뽑으면 주체·대상이 **사실관계**에서 잡힌다(주체=甲 · 대상=건물). 그래서
# 사실관계가 전혀 다른 세 지문이 '취득/단정/甲/건물' 하나로 묶였다.
# 명제는 **맨 끝 마디**에 있다. 앞 마디는 요건이다.
# **낱말 안에서 끊기면 자른 것이 문장보다 나쁘다.** 실측: 처음엔 '여' 와 '어서' 도
# 마디로 봤는데 "대항하**여서**는 아니 된다" 가 "서는 아니 된다" 로 잘렸다.
# 그래서 마디 표시 뒤에 **빈칸이나 쉼표가 와야** 마디로 본다 -- 닫아 두는 쪽이다.
_마디 = re.compile(r"(?:한\s*경우(?:에는)?|인\s*경우(?:에는)?|경우(?:에는)?|"
                   r"때에는|한\s*때|하면|이면|더라도|하더라도|"
                   r"라면|이라면|는데|은데|므로|,)[,\s]\s*")

# **보조용언은 행위가 아니다.** 문장 끝의 용언을 그대로 행위로 세웠더니 실측에서
# 시험 지문 360개의 가장 흔한 '행위' 가 '않는다'(22) · '있다'(19) · '없다'(15) 로
# 나왔다 -- 명제를 세운 것이 아니라 문장 끝 글자를 세운 것이다.
보조용언 = {"있다", "없다", "있는", "없는", "있고", "없고", "있으며", "없으며",
            "않는다", "않는", "않은", "아니다", "아니한다", "아니하다", "못한다",
            "한다", "된다", "하는", "되는", "하고", "되고", "하며", "되며",
            "한", "할", "함", "된", "될", "됨", "같다", "그러하다"}


@dataclass
class 명제:
    """문장 하나에서 세운 법률명제."""

    행위: str = ""              # 무엇을 하는가 (동사 어간, 태를 벗긴 꼴)
    서법: str = ""              # 기속 · 재량 · 금지 · 단정
    부정: bool = False
    주체: str = ""              # …은/는/이/가
    대상: str = ""              # …을/를
    상대: str = ""              # …에게 / …에 대하여
    요건: tuple = ()            # 조건절의 핵심어
    예외: bool = False          # '다만' 이 붙었는가
    뒤집힘: bool = False        # 요건-효과를 뒤집어 적은 문장이었는가
    원문: str = ""
    출처: str = ""

    def 열쇠(self) -> str:
        """**묶는 자리.** 같은 명제면 같은 문자열이 나온다.

        요건은 **집합**으로 넣는다 -- 적는 차례가 명제를 바꾸지 않는다.
        빈 칸은 여기서 빈 칸 그대로 나간다 -- **열쇠는 정확히 같은 꼴만 묶는다.**
        생략까지 견디는 묶기는 `같은가()` 가 한다. 둘을 갈라 두는 이유: 열쇠는
        칸을 나누는 데 쓰고(문장이 많아도 제곱으로 안 커진다), 판정은 `같은가()`
        가 한다.
        """
        req = "+".join(sorted(self.요건))
        return (f"{self.주체}|{self.대상}|{self.행위}|{self.서법}"
                f"|{'아님' if self.부정 else '임'}|{req}")


def 결론절(text: str) -> str:
    """**맨 끝 마디.** 명제는 여기 있고, 앞은 요건이다.

    너무 짧게 잘리면(따옴표 안, 나열) 자른 것이 문장보다 나빠진다. 잘라 낸 것이
    여덟 자 미만이면 자르지 않는다 -- 좁히는 변경은 조용히 눈을 감는다.
    """
    끝 = 0
    for m in _마디.finditer(text):
        끝 = m.end()
    남 = text[끝:].strip()
    return 남 if len(남) >= 8 else text.strip()


def _벗기기(어간: str) -> str:
    """태를 벗긴 동사 어간. '취소되' -> '취소' · '취소시키' -> '취소'."""
    s = 어간
    for _ in range(2):
        s2 = _태.sub("", s)
        if s2 == s or len(s2) < 2:
            break
        s = s2
    return s


def _격(형태소들, 격들) -> str:
    """그 격을 단 **체언**의 어간. 여럿이면 맨 앞 -- 법령문은 주체를 앞에 놓는다.

    용언은 뺀다. 실측: "취소하기 **위하여는** ..." 에서 '위하여는' 이 주제격을 달고
    있어 주체가 '위' 로 잡혔고, 그 한 글자 때문에 같은 명제 둘이 안 묶였다.
    """
    for t in 형태소들:
        if t.격 in 격들 and t.어간 and t.갈래 == "체언":
            return t.어간
    return ""


def 읽기(sent: str, 출처: str = "") -> 명제:
    """문장 -> 명제 하나. **못 세우면 행위를 비워 둔다** -- 지어내지 않는다."""
    s = _공백.sub(" ", sent.strip())
    끝 = 결론절(s)
    ts = M.분석(끝)
    서법 = M.서법(끝)
    서술 = M.서술(끝)
    조건절 = M.조건(s) or (s[: -len(끝)].strip() if 끝 != s else "")

    행위, 뒤집힘 = "", False
    목 = _목적.search(s)
    if 목 and 서법 == "기속" and 서술:
        # **요건-효과 뒤집기.** "B하려면 A하여야 한다" 의 기속은 A(요건)에 붙어 있다.
        # 명제의 효과는 B 다. 조문이 "A한 때에는 B할 수 있다" 라 적은 것과 같다.
        꼬리 = 목.group(1).split()[-1] if 목.group(1).split() else ""
        행위 = _벗기기(M.분해(꼬리).어간)
        서법 = "재량"
        뒤집힘 = True
        조건절 = 조건절 or s[목.end():]
    elif 서술:
        행위 = _벗기기(서술[-1][0])
        서법 = 서술[-1][1]
    elif ts:
        # 뒤에서부터 **보조용언이 아닌** 용언을 찾는다. 못 찾으면 비워 둔다 --
        # 문장 끝 글자를 행위로 적느니 행위를 못 세웠다고 적는 것이 낫다.
        본 = [t for t in ts
              if t.갈래 == "용언" and t.어간 and t.어간 not in 보조용언
              and len(t.어간) >= 2]
        행위 = _벗기기(본[-1].어간) if 본 else ""

    요건 = tuple(sorted(set(_벗기기(x) for x in M.핵심어(조건절)))) if 조건절 else ()
    # **뒤집힌 문장의 주체·대상은 요건절 것이다.** "취소하려면 당사자가 착오를
    # 증명하여야 한다" 에서 '당사자' 와 '착오' 는 *증명*의 것이지 *취소*의 것이 아니다.
    # 남의 자리 값을 제 자리에 적느니 **모른다고 비워 둔다** -- 빈 칸은 묶을 때
    # 모름으로 다뤄지므로, 조문 쪽이 적어 둔 값과 그대로 맞는다.
    주체 = "" if 뒤집힘 else _격(ts, ("주격", "주제"))
    대상 = "" if 뒤집힘 else _격(ts, ("목적",))
    return 명제(
        행위=행위, 서법=서법 or "단정", 부정=M.부정(s) and 서법 != "금지",
        주체=주체, 대상=대상,
        상대="" if 뒤집힘 else (_격(ts, ("여격",))
                               or (M.구절조사(s)[0][0] if M.구절조사(s) else "")),
        요건=요건, 예외=M.예외(s), 뒤집힘=뒤집힘, 원문=s, 출처=출처,
    )


def 같은가(a: 명제, b: 명제, 엄격: bool = False) -> bool:
    """두 명제가 같은 말인가.

    **빈 칸은 '다름' 이 아니라 '모름' 이다.** 실측: 조문은 "그 의사표시를 취소할 수
    있다" 라고 목적어를 적는데, 요건-효과를 뒤집은 문장은 "취소하기 위하여는 ...
    증명하여야 한다" 로 **목적어를 아예 안 쓴다.** 없는 것을 다른 값으로 세면 같은
    명제 둘이 영영 안 묶인다 -- 이 한 칸 때문에 W001 짝이 안 묶였다.

    넓히는 것이지만 **닫혀 있다**: 양쪽에 값이 있으면 반드시 같아야 하고, 행위와
    서법과 부정은 빈 칸을 안 받는다. 그리고 이 느슨함은 **묶는 쪽에만** 준다 --
    `부딪힘()` 은 세 칸이 다 차고 다 같을 때만 어긋남의 재료를 낸다.
    `엄격=True` 면 빈 칸도 값으로 보고 열쇠를 그대로 견준다.
    """
    if 엄격:
        return a.열쇠() == b.열쇠()
    if not (a.행위 and b.행위):
        return False
    # **양쪽이 다 비어 있으면 묶지 않는다.** 빈 칸을 '모름' 으로 본다는 것은 한쪽이
    # 말을 아꼈다는 뜻이지, 둘 다 아무 말도 안 했는데 같은 명제라는 뜻이 아니다.
    # 실측: 이것을 안 막았더니 문 13 의 ㄱ·ㄴ·ㄹ 이 '취득/단정' 하나로 묶였다 --
    # 사실관계가 전혀 다른 세 지문이다.
    # 실측: "선의의 제3자에게 대항하지 못한다" 는 주격도 목적격도 없다 -- 아는 것이
    # 여격(상대)뿐이다. 상대를 안 세면 이 세 꼴이 '아무것도 모르는 명제' 가 되어
    # 서로 안 묶인다. 법령문이 주어를 자주 생략하므로 이 꼴이 드물지 않다.
    if not (a.주체 or a.대상 or a.상대 or b.주체 or b.대상 or b.상대):
        return False
    if (a.행위, a.서법, a.부정) != (b.행위, b.서법, b.부정):
        return False
    for x, y in ((a.주체, b.주체), (a.대상, b.대상), (a.상대, b.상대)):
        if x and y and x != y:
            return False
    if a.요건 and b.요건 and set(a.요건) != set(b.요건):
        return False
    return True


def 묶기(문장들, 출처=None) -> list:
    """문장들 -> 패러프레이즈 묶음 목록. **둘 이상 든 묶음이 곧 같은 말들이다.**

    행위·서법·부정이 같아야 한다는 것이 먼저 걸리므로 그 셋으로 칸을 나눈 뒤
    칸 안에서만 견준다 -- 문장 수가 늘어도 제곱으로 안 커진다.
    """
    칸 = {}
    for i, t in enumerate(문장들):
        p = 읽기(t, 출처=(출처[i] if 출처 else ""))
        칸.setdefault((p.행위, p.서법, p.부정), []).append(p)
    out = []
    for (행위, _, _), ps in 칸.items():
        if not 행위:
            out += [[p] for p in ps]        # 행위를 못 세운 것은 안 묶는다
            continue
        묶음 = []
        for p in ps:
            for g in 묶음:
                if 같은가(g[0], p):
                    g.append(p)
                    break
            else:
                묶음.append([p])
        out += 묶음
    return out


def 부딪힘(a: 명제, b: 명제) -> str:
    """같은 자리를 두고 **반대로** 말하는가. 어긋남의 재료지 판정이 아니다."""
    if (a.주체, a.대상, a.행위) != (b.주체, b.대상, b.행위):
        return ""
    if a.부정 != b.부정:
        return "부정이 반대다"
    반대 = {("재량", "금지"), ("금지", "재량"), ("기속", "금지"), ("금지", "기속")}
    if (a.서법, b.서법) in 반대:
        return f"서법이 부딪힌다 ({a.서법} 대 {b.서법})"
    return ""
