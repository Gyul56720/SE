_CIT_CONJ = re.compile(
    r"(제\s*\d+\s*조(?:\s*의\s*\d+)?)\s*(?:및|또는|와|과|이나|,)\s*(?=제\s*\d+\s*조)")

# **필자의 당위는 조문의 서법이 아니다.**
# 실측: "관련 법정 절차와 해석 기준을 엄격히 검토해야 한다는 점에서" 가 W001 로 기각됐다.
# 조문이 재량인데 문서가 기속이라고 본 것인데, 그 '해야 한다' 는 조문을 옮긴 것이 아니라
# 읽는 사람에게 하는 말이었다. 닫힌 목록이라야 기계가 가른다.
_AUTHOR_DUTY = re.compile(
    r"(검토|유의|주의|숙지|확인|구별|구분|기억|판단|참고|이해|명심|고려|살펴)"
    r"\s*(?:하여야|해야)\s*(?:한다|합니다|하며|하고|할)")


# **'그 조문이 적용된다' 는 조문의 법효과어가 아니다.**
#
# 실측: "청산인의 직무와 잔여재산 분배를 규율하는 제724조가 적용되나" 가 법효과어
# 어긋남으로 잡혔다. 민법 제724조는 청산인의 직무를 제87조의 '준용' 으로 정하는데
# 문서는 '적용' 이라 썼으니 값이 다르다고 본 것이다.
#
# 그런데 이 둘은 같은 것을 두고 다투는 말이 아니다. **주어가 다르다.**
#
#     조문의 '준용'   그 조문이 **남의 조문을** 성질에 맞게 끌어다 쓴다
#     문서의 '적용'   그 조문이 **이 사안에** 걸린다
#
# 뒤엣것은 어느 조문에나 할 수 있는 말이라 조문이 무엇이라 쓰든 어긋날 수가 없다.
# 그런 자리를 어긋남으로 세면 진짜 어긋남이 그 소리에 묻힌다.
#
# 닫힌 목록으로 가른다 -- **인용한 조문 자신이 주어이고 피동('적용되-')일 때만** 지운다.
# "제12조를 적용한다"(능동·목적어)는 그대로 둔다. 그건 조문이 준용이라 쓴 자리를
# 문서가 적용으로 납작하게 만든 것이라 **진짜 법효과어 주장**이고, 준용의 '성질에
# 반하지 않는 한도에서' 가 통째로 사라지는 자리다.
_APPLIES_TO_CASE = re.compile(
    r"((?:제\s*\d+\s*조(?:\s*의\s*\d+)?(?:\s*제\s*\d+\s*항)?"
    r"|이\s*규정|이\s*조항|본조|동조|같은\s*조)\s*(?:가|이|은|는|도|만)?\s*)"
    r"적용[되된될됨][가-힣]*")


# **'오해' 를 옮긴 문장은 문서의 주장이 아니다.**
# '5. 실무상 흔한 오해' 절은 틀린 명제를 일부러 적는 자리다. "제715조에 의해 금지되는데
# 상계할 수 있다고 오해한다" 는 문장에서 '할 수 있다'(재량)는 문서가 그렇다고 말한 것이
# 아니라 남의 잘못된 생각을 옮긴 것이다. 실측에서 서법 어긋남 세 건이 전부 이 꼴이었다.
# 그 절은 어차피 soft 라 여기서 빼도 잃는 것이 적고, 소리만 줄어든다.
_MISCONCEPTION = re.compile(r"오해|오인|착각|잘못\s*알|혼동")


# **접속은 같은 두 낱말 사이에서만 견딜 수 있다.**
#
# 실측이 이것을 못 박았다. 조문 원장을 채우고 법이론서를 돌리니 접속 어긋남이 여섯 건
# 나왔는데 **여섯 건 전부 오탐**이었다. 문서가 자기 서술의 낱말 둘을 '및' 으로 묶었을 뿐인데
# (`법정형 및 세부 구성요건`, `결원 및 손해 염려`, `임무 위배 및 법정형 기준`) 조문 어딘가에
# '또는' 이 있다는 이유로 잡혔다. 집합 비교로는 그 접속사가 **어느 요건 둘을 묶는지**를
# 못 짚기 때문이다.
#
# 그래서 비교의 단위를 바꾼다. 문서가 `X 및 Y` 라고 쓰면 조문에서 **바로 그 X 와 Y 가
# 접속사로 묶인 자리**를 찾고, 그 자리의 접속사가 다를 때만 어긋남이다. 조문이 그 둘을
# 안 묶고 있으면 견줄 것이 없다.
# **서법은 동사에 붙는다.** 문장 전체에 붙는 것이 아니다.
#
# 실측: 민사소송법 제288조 편의 이 문장이 어긋남으로 잡혔다.
#
#     문서  "취소하기 위하여 ... 착오로 말미암은 것임을 **증명하여야 한다**"   기속
#     조문  "... 증명한 때에는 **취소할 수 있다**"                            재량
#
# 그런데 **같은 말이다.** 조문의 '재량' 은 *취소*에 붙고 문서의 '기속' 은 *증명*에 붙는다.
# 조문이 "증명한 때에는 취소할 수 있다"(요건-효과)라고 쓴 것을 문서가 "취소하려면
# 증명하여야 한다"(효과-요건)로 뒤집어 적었을 뿐이다. 논리적으로 같은 명제다.
#
# 문장을 값의 집합으로 보면 이것을 못 가른다 -- 조문 어딘가에 '재량' 이 있고 문서
# 어딘가에 '기속' 이 있다는 것만 보이기 때문이다. W002 접속이 똑같은 이유로 집합 비교를
# 버리고 짝 비교로 간 자리다(실측 6건이 전부 오탐이었다).
#
# 그래서 **같은 동사에 다른 서법이 붙었을 때만** 어긋남으로 센다. 조문이 그 동사를
# 안 다루면 견줄 것이 없다.
# **어간과 어미 사이에 띄어쓰기가 들어간다.** 처음엔 붙어 있는 것만 받았다가
# 돌연변이 하나를 놓쳤다(실측): 민법 제32조는 "이를 법인으로 **할 수 있다**" 이고
# 문서는 "법인으로 **하여야 한다**" 로 뒤집혔는데, 어미 앞이 공백이라 동사를 하나도
# 못 뜯었고 -- 양쪽 다 빈 손이니 짝이 없다며 그냥 넘어갔다. 좁히는 변경은 이렇게
# **조용히** 눈을 감는다. 어미 앞의 공백을 받는다.
_MOOD_VERB = (
    ("기속", re.compile(r"([가-힣]{1,8})\s*(?:하여야|해야)\s*(?:한다|합니다|하며|하고|하는|할)")),
    ("재량", re.compile(r"([가-힣]{1,8})\s*할\s*수\s*있")),
    ("금지", re.compile(r"([가-힣]{1,8})\s*할\s*수\s*없")),
    ("금지", re.compile(r"([가-힣]{1,8})\s*하지\s*못한다")),
    ("금지", re.compile(r"([가-힣]{1,8})\s*하여서는\s*아니")),
)


def mood_verbs(text: str) -> dict:
    """어느 동사가 어떤 서법을 달고 있는가. '증명하여야 한다' -> {'증명': {'기속'}}."""
    out = {}
    for mood, pat in _MOOD_VERB:
        for m in pat.finditer(text):
            v = m.group(1)
            if v:
                out.setdefault(v, set()).add(mood)
    return out


def mood_share(sent: str, article: str, mine: str) -> bool:
    """문서가 `mine` 서법을 붙인 동사를, 조문은 **다른 서법**으로 다루는가.

    참일 때만 어긋남이다. 조문이 그 동사를 아예 안 다루면 견줄 것이 없다 --
    다른 동사의 서법을 끌어다 이 동사를 판정할 수는 없다.
    """
    dv, tv = mood_verbs(sent), mood_verbs(article)
    for v, moods in dv.items():
        if mine not in moods:
            continue
        for tw in _stems(v):
            ref = tv.get(tw)
            if ref and mine not in ref:
                return True
    return False


_CONJ_PAIR = re.compile(r"([가-힣]{2,12})\s*(및|또는|이나|와|과)\s*([가-힣]{2,12})")
_CONJ_KIND = {"및": "결합", "와": "결합", "과": "결합", "또는": "선택", "이나": "선택"}


# 낱말 끝에 붙는 조사. 문서는 "등록 또는 신고를", 조문은 "등록 및 신고" 처럼 조사가
# 달라 붙으므로, 붙은 채로 견주면 같은 낱말을 다른 낱말로 본다.
_JOSA = ("를", "을", "이", "가", "은", "는", "의", "에", "도", "만", "로", "으로",
         "와", "과", "께", "에게", "라", "이라")


def _stems(t: str) -> list:
    """낱말과 그 조사 뗀 꼴. 긴 조사부터 떼 본다."""
    out = [t]
    for j in sorted(_JOSA, key=len, reverse=True):
        if t.endswith(j) and len(t) - len(j) >= 2:
            out.append(t[:-len(j)])
            break
    return out


def conj_mismatch(sent: str, article: str) -> list:
    """(문서가 쓴 접속, 조문이 같은 두 낱말에 쓴 접속, X, Y) 목록."""
    flat_art = _flat(article)
    out = []
    for m in _CONJ_PAIR.finditer(_for_compare(sent)):
        x, conj, y = m.group(1), m.group(2), m.group(3)
        found = None
        for fx in _stems(_flat(x)):
            for fy in _stems(_flat(y)):
                if fx not in flat_art or fy not in flat_art:
                    continue              # 조문이 안 쓰는 낱말이다 -- 견줄 것이 없다
                found = found or re.search(
                    re.escape(fx) + r"(및|또는|이나|와|과)" + re.escape(fy), flat_art)
        if not found:
            continue                      # 조문은 그 둘을 접속사로 묶지 않는다
        mine, theirs = _CONJ_KIND[conj], _CONJ_KIND[found.group(1)]
        if mine != theirs:
            out.append((mine, theirs, _stems(x)[-1], _stems(y)[-1]))
    return out


def _for_compare(sent: str) -> str:
    """조문과 견주기 전에 문장에서 **조문의 것이 아닌 꼴**을 지운다."""
    prev = None
    while prev != sent:                      # 인용이 셋 이상 이어질 수 있다
        prev = sent
        sent = _CIT_CONJ.sub(r"\1 ", sent)
    sent = _APPLIES_TO_CASE.sub(r"\1 ", sent)
    return _AUTHOR_DUTY.sub(" ", sent)


def _flat(t: str) -> str:
    """띄어쓰기를 지운다. '재산상 이익' 과 '재산상이익' 은 같은 낱말이다."""
    return _WS.sub("", t)


# 긴 것부터 늘어놓는다 -- 정규식 선택지는 왼쪽부터 시도되므로 이것이 곧 최장일치다.
_ALL_TERMS = sorted({t for p in PAIRS for t in p} | set(MASKS),
                    key=lambda t: -len(_flat(t)))


def _shapes(term: str) -> str:
    """한 용어가 조문에서 취하는 꼴들. **사이에 '의' 가 끼는 것을 받는다.**

    실측: 형법 제355조②는 `재산상**의** 이익` 이라 쓰는데 사전은 `재산상 이익` 이다.
    띄어쓰기만 지우니 `재산상의이익` 과 `재산상이익` 이 서로 다른 낱말이 됐고, 조문에
    그 말이 버젓이 있는데 없다고 봤다. 그래서 배임죄 문서의 맞는 서술("재산상 이익을
    취득하려 한 사안")이 **'재물' 을 '재산상 이익' 으로 바꿔 적었다** 며 기각됐다.

    관형격 '의' 는 한국 법령문이 같은 말을 쓰는 두 가지 꼴이다. **낱말 경계에만 넣는다**
    -- 아무 데나 넣으면 다른 낱말을 삼킨다.
    """
    return "의?".join(re.escape(_flat(w)) for w in term.split() if w)


_TERM_RE = re.compile("|".join(_shapes(t) for t in _ALL_TERMS))
# 찾은 꼴 -> 사전의 이름. `재산상의이익` 을 `재산상이익` 으로 되돌려야 집합 비교가 된다.
_CANON = {}
for _t in _ALL_TERMS:
    _f = _flat(_t)
    _CANON[_f] = _f
    _CANON["의".join(_flat(w) for w in _t.split() if w)] = _f


def terms_in(text: str) -> set:
    """텍스트에 나타난 법률용어. **긴 것부터 먹는다.**

    '무과실' 안의 '과실', '제척기간' 안의 '기간', '소유권' 안의 '소유' 를 따로 세면
    멀쩡한 문장이 기각된다(실측으로 둘 다 확인했다). findall 은 겹치지 않게 훑으므로,
    긴 낱말이 먼저 소비되면 그 안의 짧은 용어는 잡히지 않는다.
    """
    return {_CANON.get(m, m) for m in _TERM_RE.findall(_flat(text))}


def bucket(text: str) -> dict:
    """범주별로 어떤 값이 나타나는가. novel/wording.py 의 count() 자리."""
    out = {}
    for rule, (_, forms) in AXES.items():
        hits = {v for v, pat in forms.items() if pat.search(text)}
        if hits:
            out[rule] = hits
    return out


def _sentences(text: str) -> list:
    """gate.py 와 같은 자를 쓴다 -- corpus 에 한 벌만 있다."""
    return CP.sentences(text)


def _targets(sent, doc, corpus):
    """이 문장이 부른 조문들의 원문. 원장이 안 담은 법령은 빠진다(미검증).

    **끌어다 쓰는 조문까지 한 홉 따라간다.** 민법 제724조는 청산인의 직무를 "제87조의
    규정을 준용한다" 로만 정한다 -- 제724조 본문만 보면 청산인의 직무에 관한 서술은
    영영 '견줄 값 없음' 이다. 준용된 조문은 여기서 그대로 사는 조문이므로 그 낱말이
    곧 이 자리의 낱말이다(corpus.via 가 어디까지 따라가는지 적어 두었다).
    """
    out, seen = [], set()
    for c in CP.find_citations(sent):
        st = c.statute or getattr(doc, "statute", None)
        body = corpus.text(st, c.article)
        if not body or c.article in seen:
            continue
        seen.add(c.article)
        out.append((c.raw, body))
        for name, borrowed in corpus.via(st, c.article):
            key = name.split("(")[-1].rstrip(")")
            if key in seen:
                continue
            seen.add(key)
            out.append((f"{c.raw}→{name}", borrowed))
    return out


def check(doc, corpus) -> list:
    """W001~W005. gate.py 의 CHECKS 규약(doc, corpus) 을 그대로 따른다."""
    from law.gate import Violation

    out = []
    for name, text in doc.sections.items():
        sev = "hard" if name.startswith(("2.", "3.")) else "soft"
        for sent in _sentences(text):
            tg = _targets(sent, doc, corpus)
            if not tg or _MISCONCEPTION.search(sent):
                continue
            raws = ", ".join(r for r, _ in tg)
            joined = " ".join(b for _, b in tg)
            for mine_k, theirs_k, x, y in conj_mismatch(sent, joined):
                out.append(Violation(
                    "W002", "soft", f"{doc.path.name} · {name}",
                    f"접속: 조문({raws})은 {x!r} 과 {y!r} 를 {theirs_k} 로 묶는데 "
                    f"문서는 {mine_k} 로 묶었다"))
            mine, theirs = bucket(_for_compare(sent)), bucket(joined)
            for rule, vals in mine.items():
                if rule == "W002":         # 위에서 짝으로 따로 본다
                    continue
                ref = theirs.get(rule)
                if not ref:                       # 조문에 그 범주가 없다 -- 견줄 것이 없다
                    continue
                # **하나라도 맞게 썼으면 나머지는 일상 용법이다.**
                # 실측: "제709조의 대리권 **추정** 규정을 **적용**하여 검토할 것" 이
                # 법효과어 어긋남으로 잡혔다. 조문의 값('추정')을 문서가 이미 맞게 썼고
                # '적용' 은 "규정을 적용하여" 라는 보통 동사였다. 문서가 그 범주에서
                # 조문과 만나는 값을 하나도 안 썼을 때만 바꿔 쓴 것으로 본다.
                if vals & ref:
                    continue
                gone = vals - ref
                if rule == "W001":
                    gone = {v for v in gone if mood_share(sent, joined, v)}
                if gone:
                    axis = AXES[rule][0]
                    # **접속은 기각하지 않는다.** 인용을 잇는 '및' 을 지워도, 문장 단위
                    # 집합 비교로는 그 접속사가 **어느 요건 둘을 묶는지**를 못 짚는다.
                    # 조문 어딘가에 '또는' 이 있고 문서가 다른 자리에서 '및' 을 썼다는
                    # 것만으로 기각하면 멀쩡한 문장을 버린다(실측 4건이 그랬다).
                    # 판정할 자격이 없는 것은 보고로 내린다.
                    out.append(Violation(
                        rule, "soft" if rule == "W002" else sev,
                        f"{doc.path.name} · {name}",
                        f"{axis}: 조문({raws})은 {'/'.join(sorted(ref))} 인데 "
                        f"문서는 {'/'.join(sorted(gone))} 로 적었다"))
            st, at = terms_in(sent), terms_in(joined)
            body = terms_in(_body_only(joined))     # 기각에는 본문을 요구한다
            if _HEAD_TITLE.search(sent):            # 표제를 옮겨 적었으면 표제도 본다
                body = at
            for a, b in PAIRS:
                for used, other in ((a, b), (b, a)):
                    fu, fo = _flat(used), _flat(other)
                    if fu in st and fo in body and fu not in at and fo not in st:
                        out.append(Violation(
                            "W005", sev, f"{doc.path.name} · {name}",
                            f"조문({raws})은 {other!r} 인데 문서는 {used!r} 로 바꿔 적었다"))
    return out


# **표제는 규정이 아니다.**
#
# 실측: 민사소송법 제203조는 표제가 `(처분권주의)` 이고 본문은 "법원은 당사자가
# 신청하지 아니한 사항에 대하여는 판결하지 못한다" 뿐이다. 그런데 문서가 '변론주의' 를
# 쓰자 "조문은 '처분권주의' 인데 바꿔 적었다" 며 hard 로 기각했다 -- **그 낱말은 조문
# 본문에 한 번도 안 나온다.** 표제어 하나로 문서의 다른 낱말을 기각한 것이다.
#
# 그렇다고 표제를 통째로 버릴 것도 아니다. 문서가 표제어를 쓴 것은 근거가 있는 일이다.
# 그래서 **한쪽으로만 쓴다**:
#
#     맞음    표제까지 본다 -- 문서가 조문의 말을 썼다면 표제어도 조문의 말이다
#     어긋남  본문만 본다   -- 기각하려면 규정 본문에 그 낱말이 있어야 한다
#
# 과잉 기각하는 심판은 맞는 답도 버린다(novel/gate.py 가 배운 것). 기각은 무겁고
# 인정은 가벼우므로, 무거운 쪽에만 더 센 근거를 요구한다.
_HEAD_TITLE = re.compile(r"제\s*\d+\s*조(?:\s*의\s*\d+)?\s*\([^)\n]*\)")


def _body_only(article: str) -> str:
    """조문에서 표제를 뺀 본문. 본문 안의 `제87조의 규정` 같은 참조는 괄호가 없어 안 지워진다."""
    return _HEAD_TITLE.sub(" ", article)


_PARTNERS = {}
for _a, _b in PAIRS:
    _PARTNERS.setdefault(_flat(_a), []).append(_b)
    _PARTNERS.setdefault(_flat(_b), []).append(_a)


def _term_rows(sent: str, article: str) -> list:
    """W005 를 세 갈래로. **check() 의 기각 조건을 그대로 옮긴다** -- 두 벌이 갈라지면
    보고와 판정이 어긋난다.

        맞음        문서가 쓴 낱말을 조문도 쓴다
        어긋남      문서는 이쪽, 조문은 짝이 되는 저쪽만 쓴다 (= check 가 기각하는 자리)
        견줄것없음  조문이 그 짝의 어느 쪽도 안 쓴다

    **낱말 단위로 한 번씩만 적는다.** 짝 목록을 그대로 돌면 한 낱말이 여러 짝에 걸려
    같은 줄이 두세 번 나오고, 한쪽 짝에서는 맞음인데 다른 짝에서는 견줄것없음이 되어
    읽는 사람이 어느 쪽을 믿어야 할지 모르게 된다. 조문이 그 낱말을 쓰는지 아닌지는
    짝과 무관하게 정해지므로, 낱말에서 출발해야 답이 하나가 된다.
    """
    st = terms_in(sent)
    at, body = terms_in(article), terms_in(_body_only(article))
    # **문서가 표제를 직접 옮겨 적었으면 표제도 대조 대상이다.**
    # 실측: `형법 제30조(방조)는 "2인 이상이 공동하여 죄를 범한 때에는..."` -- 제30조의
    # 표제는 (공동정범)이고 그 낱말은 본문에 없다. 표제를 통째로 뺐더니 표제를 **옮겨
    # 적으면서 틀린** 이 자리가 그늘로 들어갔다.
    # 그러나 "변론주의에 관하여는 제203조 원문에 명시되지 않음" 은 표제를 옮겨 적은
    # 것이 아니라 딴 얘기를 한 것이다. 가르는 것은 `제N조(...)` 꼴 하나다.
    if _HEAD_TITLE.search(sent):
        body = at
    out = []
    for used in sorted(st):
        if used not in _PARTNERS:      # 짝이 없는 낱말은 이 관문의 관할이 아니다
            continue
        if used in at:                 # 맞음에는 표제도 근거다
            out.append((f"용어:{used}", "맞음"))
            continue
        others = [o for o in _PARTNERS[used]   # 기각에는 본문을 요구한다
                  if _flat(o) in body and _flat(o) not in st]
        if others:
            out.append((f"용어:{used}(조문은 {'·'.join(others)})", "어긋남"))
        else:
            out.append((f"용어:{used}", "견줄것없음"))
    return out


def trace(doc, corpus) -> list:
    """**낱말이 어디에 근거하는가.** 문장마다 세 갈래로 갈라 돌려준다.

        맞음        조문에도 같은 값이 있다
        어긋남      조문에 그 범주가 있는데 값이 다르다 -- 이것만 관문이 잡는다
        견줄것없음  조문에 그 범주가 아예 없다 -- 위반이 아니라 대조 불가다

    세 번째를 '근거 없음' 이라고 뭉뚱그렸던 것이 이 파일의 흠이었다(실측: 법이론서를
    돌리니 '근거 없음' 18건 중 대부분이 이것이었고, 정작 관문은 hard 2건만 냈다).
    관문은 조문에 그 범주가 없으면 판정하지 않는데 보고만 위반처럼 적은 것이다.
    **판정이 셋인 시스템의 보고도 셋이어야 한다** -- 원장이 없는 인용을 '미검증' 으로
    따로 세는 것과 같은 이유다.
    """
    rows = []
    for name, text in doc.sections.items():
        for sent in _sentences(text):
            cits = CP.find_citations(sent)
            if not cits:
                continue
            tg = _targets(sent, doc, corpus)
            row = {"절": name, "문장": sent, "인용": [c.raw for c in cits],
                   "맞음": [], "어긋남": [], "견줄것없음": [], "조문값": {},
                   "미검증": not tg,
                   "오해": bool(_MISCONCEPTION.search(sent))}
            # **대조하지 않기로 한 문장은 아예 안 견준다.** 전에는 '오해' 표만 달고
            # 값은 그대로 채웠다 -- 보고가 세지 않을 뿐 줄 안에는 어긋남이 들어 있어서,
            # 읽는 사람에게는 잡힌 것으로 보이고 수에는 없는 유령이 됐다.
            if tg and not row["오해"]:
                row["인용"] = [r for r, _ in tg]
                joined = " ".join(b for _, b in tg)
                mine, theirs = bucket(_for_compare(sent)), bucket(joined)
                for rule, vals in mine.items():
                    axis = AXES[rule][0]
                    ref = theirs.get(rule)
                    hit = bool(ref and (vals & ref))
                    for v in sorted(vals):
                        key = f"{axis}:{v}"
                        if rule == "W002":
                            continue       # 아래에서 짝으로 따로 본다
                        if not ref:
                            row["견줄것없음"].append(key)
                        elif v in ref:
                            row["맞음"].append(key)
                        elif hit:
                            row["견줄것없음"].append(key)   # 다른 값을 맞게 썼다
                        elif rule == "W001" and not mood_share(sent, joined, v):
                            # 조문이 그 동사를 안 다룬다 -- 다른 동사의 서법으로
                            # 이 동사를 판정할 수는 없다.
                            row["견줄것없음"].append(key)
                        else:
                            row["어긋남"].append(key)
                            # **조문이 대신 무엇이라 썼는지 같이 들고 나온다.**
                            # 어긋남 한 줄만 보면 그 자리가 진짜 어긋난 것인지 자가
                            # 헛짚은 것인지 가릴 수 없어, 원장을 손으로 다시 열어야
                            # 했다. 판정의 반대편이 없는 보고는 반쪽이다.
                            row["조문값"][axis] = sorted(ref)
                for mk, tk, x, y in conj_mismatch(sent, joined):
                    row["어긋남"].append(f"접속:{x}·{y} 를 {tk} 아닌 {mk} 로")
                # **W005 가 보고에 아예 없었다.** trace 는 AXES 만 돌아서, 용어 치환은
                # check() 가 기각하는데 보고는 "볼 것이 없다" 고 적었다. 실측: 그렇게
                # 센 '대조할 낱말을 아예 안 쓴 문장' 이 161개였는데, 그중 얼마가 실은
                # W005 의 관할인지 알 수 없었다. **보고와 판정이 같은 것을 보아야 한다**
                # -- 세 갈래 판정을 만들 때 이미 한 번 겪은 그 어긋남이다.
                for key, kind in _term_rows(sent, joined):
                    row[kind].append(key)
            rows.append(row)
    return rows


def main(argv=None):
    ap = argparse.ArgumentParser(description="문언 대조 -- 낱말 하나가 결론을 바꾼다")
    ap.add_argument("target", nargs="?", default="법이론서")
    ap.add_argument("--corpus", default=str(CP.CORPUS_DIR))
    ap.add_argument("--trace", action="store_true", help="낱말의 근거를 늘어놓는다")
    a = ap.parse_args(argv)

    from law.gate import parse
    corpus = CP.load(a.corpus)
    t = Path(a.target)
    files = sorted(t.rglob("*.md")) if t.is_dir() else [t]
    files = [f for f in files if not f.name.lower().startswith("readme")]

    hard = soft = 0
    unver = good = bad = nocmp = miscon = mute = gap = hop2 = 0
    for f in files:
        doc = parse(f)
        if a.trace:
            for r in trace(doc, corpus):
                if r["미검증"]:
                    unver += 1
                    continue
                if r["오해"]:
                    miscon += 1
                    continue
                mark = ("어긋남: " + ", ".join(r["어긋남"])) if r["어긋남"] else \
                    ("맞음 " + ", ".join(r["맞음"]) if r["맞음"] else "견줄 값 없음")
                if r["어긋남"]:
                    bad += 1
                elif r["맞음"]:
                    good += 1
                elif r["견줄것없음"]:
                    # **문서는 낱말을 썼는데 조문에 그 범주가 없다.** 원장을 넓히거나
                    # 2홉을 늘리면 줄어드는 수 -- 여기가 자의 눈이 감긴 자리다.
                    gap += 1
                else:
                    # **문서가 대조할 낱말을 아예 안 썼다.** 서법도 접속도 경계도
                    # 법효과어도 없는 서술이라 견줄 것이 없다. 이건 자가 못 보는
                    # 것이 아니라 **볼 것이 없는** 것이라, 줄인다고 나아지지 않는다.
                    # 처음엔 이 둘을 한 수(168개)로 묶고 "줄여야 할 수" 라 적었는데,
                    # 그러면 자가 나아져도 이 수는 안 줄어 사람을 헷갈리게 한다.
                    mute += 1
                hop2 += any("→" in c for c in r["인용"])
                if r["견줄것없음"]:
                    nocmp += 1
                    mark += "  (조문에 없는 범주라 대조 못 함: " \
                        + ", ".join(r["견줄것없음"]) + ")"
                print(f"[{f.name} · {r['절']}] {', '.join(r['인용'])}  {mark}")
                if r["어긋남"]:
                    for axis, ref in sorted(r["조문값"].items()):
                        minev = [k.split(":", 1)[1] for k in r["어긋남"]
                                 if k.startswith(axis + ":")]
                        print(f"    {axis}: 문서는 '{'·'.join(minev)}' · "
                              f"조문은 '{'·'.join(ref)}'")
                    # **자르지 않는다.** 90자에서 끊으니 정작 어긋난 낱말이 잘려 나가
                    # 무엇을 보고 잡았는지가 안 보였다(실측: 제724조 두 건).
                    print(textwrap.fill(r["문장"], 96,
                                        initial_indent="    ", subsequent_indent="    "))
            continue
        for v in check(doc, corpus):
            print(f"  {v}")
            hard += v.severity == "hard"
            soft += v.severity == "soft"
    if a.trace:
        print(f"\n문장 {good + bad}개를 조문과 견줬다 -- 맞음 {good} · **어긋남 {bad}**")
        if gap:
            print(f"문서는 낱말을 썼는데 조문에 그 범주가 없던 문장 {gap}개 "
                  f"<- **줄여야 할 수는 이것이다** (원장·2홉이 넓어지면 준다)")
        if nocmp:
            print(f"조문에 그 범주가 없어 일부만 대조한 문장 {nocmp}개 "
                  f"(위반이 아니라 대조 불가다)")
        if mute:
            print(f"문서가 대조할 낱말을 아예 안 쓴 문장 {mute}개 "
                  f"(자가 못 보는 것이 아니라 볼 것이 없다 -- 축을 늘려야 준다)")
        if hop2:
            print(f"준용·전조를 따라가 조문을 더 끌어온 문장 {hop2}개 "
                  f"(2홉이 실제로 일을 한 자리다)")
        if miscon:
            print(f"'오해' 를 옮긴 문장 {miscon}개는 대조하지 않았다 "
                  f"(문서의 주장이 아니다)")
        if unver:
            print(f"원장에 없어 대조 못 한 문장 {unver}개")
        return 0
    print(f"\n문언 대조: 문서 {len(files)}개 · hard {hard} · soft {soft}")
    if not corpus:
        print("원장이 비어 있다 -- 대조할 조문이 없으면 이 관문은 아무것도 못 본다.")
    return 1 if hard else 0


if __name__ == "__main__":
    raise SystemExit(main())
