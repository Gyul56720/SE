# 실측: "제32조 및 제43조 등의 조문에서..." 가 W002 로 기각됐다. 여기서 '및' 은 조문
# 번호 둘을 잇는 말이지 요건 둘을 묶는 말이 아니다. 견주기 전에 지운다.
_CIT_CONJ = re.compile(
    r"(제\s*\d+\s*조(?:\s*의\s*\d+)?)\s*(?:및|또는|와|과|이나|,)\s*(?=제\s*\d+\s*조)")

# **필자의 당위는 조문의 서법이 아니다.**
# 실측: "관련 법정 절차와 해석 기준을 엄격히 검토해야 한다는 점에서" 가 W001 로 기각됐다.
# 조문이 재량인데 문서가 기속이라고 본 것인데, 그 '해야 한다' 는 조문을 옮긴 것이 아니라
# 읽는 사람에게 하는 말이었다. 닫힌 목록이라야 기계가 가른다.
_AUTHOR_DUTY = re.compile(
    r"(검토|유의|주의|숙지|확인|구별|구분|기억|판단|참고|이해|명심|고려|살펴)"
    r"\s*(?:하여야|해야)\s*(?:한다|합니다|하며|하고|할)")


# **'오해' 를 옮긴 문장은 문서의 주장이 아니다.**
# '5. 실무상 흔한 오해' 절은 틀린 명제를 일부러 적는 자리다. "제715조에 의해 금지되는데
# 상계할 수 있다고 오해한다" 는 문장에서 '할 수 있다'(재량)는 문서가 그렇다고 말한 것이
# 아니라 남의 잘못된 생각을 옮긴 것이다. 실측에서 서법 어긋남 세 건이 전부 이 꼴이었다.
# 그 절은 어차피 soft 라 여기서 빼도 잃는 것이 적고, 소리만 줄어든다.
_MISCONCEPTION = re.compile(r"오해|오인|착각|잘못\s*알|혼동")


# **접속은 같은 두 낱말 사이에서만 견딜 수 있다.**
#
# 실측이 이것을 못 박았다. 조문 원장을 채우고 법이론서를 돌리니 접속 어긋남이 여섯 건
# 나왔는데 **여섯 건 전부 오탐**이었다. 문서가 자기 서술의 낱말 둘을 '및' 으로 묶었을 뿐인데
# (`법정형 및 세부 구성요건`, `결원 및 손해 염려`, `임무 위배 및 법정형 기준`) 조문 어딘가에
# '또는' 이 있다는 이유로 잡혔다. 집합 비교로는 그 접속사가 **어느 요건 둘을 묶는지**를
# 못 짚기 때문이다.
#
# 그래서 비교의 단위를 바꾼다. 문서가 `X 및 Y` 라고 쓰면 조문에서 **바로 그 X 와 Y 가
# 접속사로 묶인 자리**를 찾고, 그 자리의 접속사가 다를 때만 어긋남이다. 조문이 그 둘을
# 안 묶고 있으면 견줄 것이 없다.
_CONJ_PAIR = re.compile(r"([가-힣]{2,12})\s*(및|또는|이나|와|과)\s*([가-힣]{2,12})")
_CONJ_KIND = {"및": "결합", "와": "결합", "과": "결합", "또는": "선택", "이나": "선택"}


# 낱말 끝에 붙는 조사. 문서는 "등록 또는 신고를", 조문은 "등록 및 신고" 처럼 조사가
# 달라 붙으므로, 붙은 채로 견주면 같은 낱말을 다른 낱말로 본다.
_JOSA = ("를", "을", "이", "가", "은", "는", "의", "에", "도", "만", "로", "으로",
         "와", "과", "께", "에게", "라", "이라")


def _stems(t: str) -> list:
    """낱말과 그 조사 뗀 꼴. 긴 조사부터 떼 본다."""
    out = [t]
    for j in sorted(_JOSA, key=len, reverse=True):
        if t.endswith(j) and len(t) - len(j) >= 2:
            out.append(t[:-len(j)])
            break
    return out


def conj_mismatch(sent: str, article: str) -> list:
    """(문서가 쓴 접속, 조문이 같은 두 낱말에 쓴 접속, X, Y) 목록."""
    flat_art = _flat(article)
    out = []
    for m in _CONJ_PAIR.finditer(_for_compare(sent)):
        x, conj, y = m.group(1), m.group(2), m.group(3)
        found = None
        for fx in _stems(_flat(x)):
            for fy in _stems(_flat(y)):
                if fx not in flat_art or fy not in flat_art:
                    continue              # 조문이 안 쓰는 낱말이다 -- 견줄 것이 없다
                found = found or re.search(
                    re.escape(fx) + r"(및|또는|이나|와|과)" + re.escape(fy), flat_art)
        if not found:
            continue                      # 조문은 그 둘을 접속사로 묶지 않는다
        mine, theirs = _CONJ_KIND[conj], _CONJ_KIND[found.group(1)]
        if mine != theirs:
            out.append((mine, theirs, _stems(x)[-1], _stems(y)[-1]))
    return out


def _for_compare(sent: str) -> str:
    """조문과 견주기 전에 문장에서 **조문의 것이 아닌 꼴**을 지운다."""
    prev = None
    while prev != sent:                      # 인용이 셋 이상 이어질 수 있다
        prev = sent
        sent = _CIT_CONJ.sub(r"\1 ", sent)
    return _AUTHOR_DUTY.sub(" ", sent)


def _flat(t: str) -> str:
    """띄어쓰기를 지운다. '재산상 이익' 과 '재산상이익' 은 같은 낱말이다."""
    return _WS.sub("", t)


# 긴 것부터 늘어놓는다 -- 정규식 선택지는 왼쪽부터 시도되므로 이것이 곧 최장일치다.
_ALL_TERMS = sorted({t for p in PAIRS for t in p} | set(MASKS),
                    key=lambda t: -len(_flat(t)))
_TERM_RE = re.compile("|".join(re.escape(_flat(t)) for t in _ALL_TERMS))


def terms_in(text: str) -> set:
    """텍스트에 나타난 법률용어. **긴 것부터 먹는다.**

    '무과실' 안의 '과실', '제척기간' 안의 '기간', '소유권' 안의 '소유' 를 따로 세면
    멀쩡한 문장이 기각된다(실측으로 둘 다 확인했다). findall 은 겹치지 않게 훑으므로,
    긴 낱말이 먼저 소비되면 그 안의 짧은 용어는 잡히지 않는다.
    """
    return set(_TERM_RE.findall(_flat(text)))


def bucket(text: str) -> dict:
    """범주별로 어떤 값이 나타나는가. novel/wording.py 의 count() 자리."""
    out = {}
    for rule, (_, forms) in AXES.items():
        hits = {v for v, pat in forms.items() if pat.search(text)}
        if hits:
            out[rule] = hits
    return out


def _sentences(text: str) -> list:
    text = _WS.sub(" ", text)
    return [s.strip() for s in re.split(r"(?<=[.!?])\s+", text) if s.strip()]


def _targets(sent, doc, corpus):
    """이 문장이 부른 조문들의 원문. 원장이 안 담은 법령은 빠진다(미검증)."""
    out = []
    for c in CP.find_citations(sent):
        body = corpus.text(c.statute or getattr(doc, "statute", None), c.article)
        if body:
            out.append((c.raw, body))
    return out


def check(doc, corpus) -> list:
    """W001~W005. gate.py 의 CHECKS 규약(doc, corpus) 을 그대로 따른다."""
    from law.gate import Violation

    out = []
    for name, text in doc.sections.items():
        sev = "hard" if name.startswith(("2.", "3.")) else "soft"
        for sent in _sentences(text):
            tg = _targets(sent, doc, corpus)
            if not tg or _MISCONCEPTION.search(sent):
                continue
            raws = ", ".join(r for r, _ in tg)
            joined = " ".join(b for _, b in tg)
            for mine_k, theirs_k, x, y in conj_mismatch(sent, joined):
                out.append(Violation(
                    "W002", "soft", f"{doc.path.name} · {name}",
                    f"접속: 조문({raws})은 {x!r} 과 {y!r} 를 {theirs_k} 로 묶는데 "
                    f"문서는 {mine_k} 로 묶었다"))
            mine, theirs = bucket(_for_compare(sent)), bucket(joined)
            for rule, vals in mine.items():
                if rule == "W002":         # 위에서 짝으로 따로 본다
                    continue
                ref = theirs.get(rule)
                if not ref:                       # 조문에 그 범주가 없다 -- 견줄 것이 없다
                    continue
                # **하나라도 맞게 썼으면 나머지는 일상 용법이다.**
                # 실측: "제709조의 대리권 **추정** 규정을 **적용**하여 검토할 것" 이
                # 법효과어 어긋남으로 잡혔다. 조문의 값('추정')을 문서가 이미 맞게 썼고
                # '적용' 은 "규정을 적용하여" 라는 보통 동사였다. 문서가 그 범주에서
                # 조문과 만나는 값을 하나도 안 썼을 때만 바꿔 쓴 것으로 본다.
                if vals & ref:
                    continue
                gone = vals - ref
                if gone:
                    axis = AXES[rule][0]
                    # **접속은 기각하지 않는다.** 인용을 잇는 '및' 을 지워도, 문장 단위
                    # 집합 비교로는 그 접속사가 **어느 요건 둘을 묶는지**를 못 짚는다.
                    # 조문 어딘가에 '또는' 이 있고 문서가 다른 자리에서 '및' 을 썼다는
                    # 것만으로 기각하면 멀쩡한 문장을 버린다(실측 4건이 그랬다).
                    # 판정할 자격이 없는 것은 보고로 내린다.
                    out.append(Violation(
                        rule, "soft" if rule == "W002" else sev,
                        f"{doc.path.name} · {name}",
                        f"{axis}: 조문({raws})은 {'/'.join(sorted(ref))} 인데 "
                        f"문서는 {'/'.join(sorted(gone))} 로 적었다"))
            st, at = terms_in(sent), terms_in(joined)
            for a, b in PAIRS:
                for used, other in ((a, b), (b, a)):
                    fu, fo = _flat(used), _flat(other)
                    if fu in st and fo in at and fu not in at and fo not in st:
                        out.append(Violation(
                            "W005", sev, f"{doc.path.name} · {name}",
                            f"조문({raws})은 {other!r} 인데 문서는 {used!r} 로 바꿔 적었다"))
    return out


def trace(doc, corpus) -> list:
    """**낱말이 어디에 근거하는가.** 문장마다 세 갈래로 갈라 돌려준다.

        맞음        조문에도 같은 값이 있다
        어긋남      조문에 그 범주가 있는데 값이 다르다 -- 이것만 관문이 잡는다
        견줄것없음  조문에 그 범주가 아예 없다 -- 위반이 아니라 대조 불가다

    세 번째를 '근거 없음' 이라고 뭉뚱그렸던 것이 이 파일의 흠이었다(실측: 법이론서를
    돌리니 '근거 없음' 18건 중 대부분이 이것이었고, 정작 관문은 hard 2건만 냈다).
    관문은 조문에 그 범주가 없으면 판정하지 않는데 보고만 위반처럼 적은 것이다.
    **판정이 셋인 시스템의 보고도 셋이어야 한다** -- 원장이 없는 인용을 '미검증' 으로
    따로 세는 것과 같은 이유다.
    """
    rows = []
    for name, text in doc.sections.items():
        for sent in _sentences(text):
            cits = CP.find_citations(sent)
            if not cits:
                continue
            tg = _targets(sent, doc, corpus)
            row = {"절": name, "문장": sent, "인용": [c.raw for c in cits],
                   "맞음": [], "어긋남": [], "견줄것없음": [],
                   "미검증": not tg, "오해": bool(_MISCONCEPTION.search(sent))}
            if tg:
                row["인용"] = [r for r, _ in tg]
                joined = " ".join(b for _, b in tg)
                mine, theirs = bucket(_for_compare(sent)), bucket(joined)
                for rule, vals in mine.items():
                    axis = AXES[rule][0]
                    ref = theirs.get(rule)
                    hit = bool(ref and (vals & ref))
                    for v in sorted(vals):
                        key = f"{axis}:{v}"
                        if rule == "W002":
                            continue       # 아래에서 짝으로 따로 본다
                        if not ref:
                            row["견줄것없음"].append(key)
                        elif v in ref:
                            row["맞음"].append(key)
                        elif hit:
                            row["견줄것없음"].append(key)   # 다른 값을 맞게 썼다
                        else:
                            row["어긋남"].append(key)
                for mk, tk, x, y in conj_mismatch(sent, joined):
                    row["어긋남"].append(f"접속:{x}·{y} 를 {tk} 아닌 {mk} 로")
            rows.append(row)
    return rows


def main(argv=None):
    ap = argparse.ArgumentParser(description="문언 대조 -- 낱말 하나가 결론을 바꾼다")
    ap.add_argument("target", nargs="?", default="법이론서")
    ap.add_argument("--corpus", default=str(CP.CORPUS_DIR))
    ap.add_argument("--trace", action="store_true", help="낱말의 근거를 늘어놓는다")
    a = ap.parse_args(argv)

    from law.gate import parse
    corpus = CP.load(a.corpus)
    t = Path(a.target)
    files = sorted(t.rglob("*.md")) if t.is_dir() else [t]
    files = [f for f in files if not f.name.lower().startswith("readme")]

    hard = soft = 0
    unver = good = bad = nocmp = miscon = 0
    for f in files:
        doc = parse(f)
        if a.trace:
            for r in trace(doc, corpus):
                if r["미검증"]:
                    unver += 1
                    continue
                if r["오해"]:
                    miscon += 1
                    continue
                mark = ("어긋남: " + ", ".join(r["어긋남"])) if r["어긋남"] else \
                    ("맞음 " + ", ".join(r["맞음"]) if r["맞음"] else "견줄 값 없음")
                if r["어긋남"]:
                    bad += 1
                elif r["맞음"]:
                    good += 1
                if r["견줄것없음"]:
                    nocmp += 1
                    mark += "  (조문에 없는 범주라 대조 못 함: " \
                        + ", ".join(r["견줄것없음"]) + ")"
                print(f"[{f.name} · {r['절']}] {', '.join(r['인용'])}  {mark}")
                if r["어긋남"]:
                    print(f"    {r['문장'][:90]}")
            continue
        for v in check(doc, corpus):
            print(f"  {v}")
            hard += v.severity == "hard"
            soft += v.severity == "soft"
    if a.trace:
        print(f"\n문장 {good + bad}개를 조문과 견줬다 -- 맞음 {good} · **어긋남 {bad}**")
        if nocmp:
            print(f"조문에 그 범주가 없어 일부만 대조한 문장 {nocmp}개 "
                  f"(위반이 아니라 대조 불가다)")
        if miscon:
            print(f"'오해' 를 옮긴 문장 {miscon}개는 대조하지 않았다 "
                  f"(문서의 주장이 아니다)")
        if unver:
            print(f"원장에 없어 대조 못 한 문장 {unver}개")
        return 0
    print(f"\n문언 대조: 문서 {len(files)}개 · hard {hard} · soft {soft}")
    if not corpus:
        print("원장이 비어 있다 -- 대조할 조문이 없으면 이 관문은 아무것도 못 본다.")
    return 1 if hard else 0


if __name__ == "__main__":
    raise SystemExit(main())
