"""법령문 형태소 -- **일반 한국어 분석기가 아니다.**

`konlpy` · `kiwipiepy` 를 안 쓴다. 두 가지 이유다.

1. **깔리지 않는다.** 이 환경에서 `pip install kiwipiepy` 가 모델 빌드에서 깨진다.
   VM 도 같은 처지면 심판이 기계마다 다르게 돈다 -- 두 벌은 언젠가 갈라진다.
2. **필요한 것이 다르다.** 우리가 알아야 하는 것은 품사 45종이 아니라 **법령문이
   쓰는 닫힌 꼴 몇 가지**다: 조사 · 서법 · 부정 · 조건 · 접속. 법령문은 이것들을
   거의 어기지 않는다 -- 그래서 규칙으로 잡히고, 규칙이라 **재현된다.**

그 대신 **못 뜯은 것을 못 뜯었다고 적는다.** 짐작해서 채우면 그 자리가 조용히
틀린 채 심판에 들어간다 -- 미검증을 통과로 세지 않는다는 이 저장소의 규율이
형태소에서도 그대로다. `분해()` 는 확신이 없으면 `조사=""` 로 두고 `왜="미분석"`
을 남긴다.
"""

from __future__ import annotations

import re
from dataclasses import dataclass, field

# 조사. **긴 것부터 떼야 한다** -- '에게' 를 '에' 로 떼면 '게' 가 어간에 남는다.
# 격조사 · 보조사 · 접속조사를 갈라 둔다. 스키마가 격으로 자리를 잡기 때문이다.
격조사 = {
    "이": "주격", "가": "주격", "께서": "주격",
    "을": "목적", "를": "목적",
    "의": "관형",
    "에": "처격", "에서": "처격", "에게": "여격", "에게서": "탈격",
    "께": "여격", "한테": "여격", "으로부터": "탈격", "로부터": "탈격",
    "으로": "도구", "로": "도구", "로서": "자격", "으로서": "자격",
    "로써": "수단", "으로써": "수단",
    "와": "공동", "과": "공동", "하고": "공동",
    "보다": "비교", "처럼": "비교", "같이": "비교",
}
보조사 = {"은": "주제", "는": "주제", "도": "역시", "만": "한정", "까지": "도달",
          "부터": "시작", "조차": "포함", "마저": "포함", "라도": "양보",
          "이라도": "양보", "이나": "선택", "나": "선택", "밖에": "한정"}

# 법령문이 즐겨 쓰는 붙임꼴. '에 대하여' 처럼 띄어 쓰는 것은 어절이 갈리므로
# `구절조사()` 가 따로 본다.
_조사 = {**격조사, **보조사}
_조사차례 = sorted(_조사, key=len, reverse=True)

# 어절이 아니라 **구절**에 붙는 것. 법령문의 상대·대상이 대개 여기 실린다.
구절조사표 = (
    ("에 대하여", "대상"), ("에 대한", "대상"), ("에 관하여", "대상"),
    ("에 관한", "대상"), ("에 대해", "대상"),
    ("에 의하여", "근거"), ("에 의한", "근거"), ("에 따라", "근거"),
    ("에 따른", "근거"), ("에 의해", "근거"),
    ("을 위하여", "목적"), ("를 위하여", "목적"),
    ("을 위한", "목적"), ("를 위한", "목적"),
)

# **서법은 동사에 붙는다** -- 조 단위로 못 판정한다는 것을 W001 이 돌연변이 12개로
# 배웠다(law/wording.py). 여기서는 그 판을 어미까지 넓혀 든다.
# 차례가 곧 우선순위다. '할 수 없다' 를 '할 수 있다' 보다 먼저 봐야 한다.
서법표 = (
    ("금지", r"(?:하여서는|해서는)\s*아니\s*(?:된다|되며|하고)"),
    ("금지", r"지\s*못한다"),
    ("금지", r"(?:할|될)\s*수\s*없"),
    ("금지", r"지\s*아니한다"),
    ("기속", r"(?:하여야|해야|어야|아야)\s*(?:한다|하며|하고|하는|할)"),
    ("재량", r"(?:할|될)\s*수\s*있"),
    # 끝의 마침표를 받는다. 실측: '소유권을 취득한다.' 가 서법 없음으로 나왔다 --
    # `$` 가 온점 앞에서 안 걸린다. 한 글자 때문에 명제의 서법이 통째로 비었다.
    ("단정", r"(?:한다|된다|이다|다|함)\s*[.。]?\s*$"),
)
_서법 = tuple((m, re.compile(p)) for m, p in 서법표)

# 부정. 서법의 '금지' 와 다르다 -- '아니다' 는 명제 자체를 뒤집는다.
_부정 = re.compile(r"아니(?:다|한|하다|하며|하고)|않(?:는다|다|으며)|없(?:다|으며|는)|"
                   r"못(?:한다|하며)")

# 조건절을 여는 꼴. 법령문의 요건이 여기 실린다.
조건표 = ("때에는", "경우에는", "경우", "때", "하면", "이면", "한다면",
          "함에는", "에 있어서는", "인 때", "한 때")
_조건 = re.compile(r"(.+?)(" + "|".join(re.escape(c) for c in
                                        sorted(조건표, key=len, reverse=True)) + r")\s")

# 예외를 여는 꼴. '다만' 뒤는 본문과 다른 명제다.
_예외 = re.compile(r"(?:다만|단,|그러나|그러하지)")

# 접속. W002 가 이미 쓰는 자리라 낱말만 맞춘다.
접속표 = {"및": "그리고", "와": "그리고", "과": "그리고", "또는": "또", "이나": "또",
          "나": "또", "그 밖에": "그리고", "아울러": "그리고"}

# 용언 꼬리. **길수록 먼저** -- '하여야' 를 '한' 으로 뜯으면 어간이 뭉개진다.
# **'인' 과 '임' 은 안 뗀다.** 법률 한국어에서 그 자리는 사람(人)이거나 이름씨다 --
# 매도인 · 대리인 · 채권자 · 차임 · 책임. 실측: '매도인으로부터' 가 '매도' 로,
# '차임' 이 '차' 로 잘렸다. 잘린 어간은 조문에서 안 걸리고, 그러면 심판이
# "조문에 그런 말이 없다" 고 한다 -- **오독으로 인한 기각**이다.
# '인한'·'의한' 처럼 진짜 용언인 것은 꼬리가 '한' 이라 그대로 걸린다.
용언꼬리 = ("하여야", "해야", "하여서", "하여", "하기", "하는", "하고", "하며",
            "하면", "하지", "한다", "했다", "합니다", "한", "할", "함",
            "되어야", "되어", "되는", "되고", "되며", "되면", "되기", "되지",
            "된다", "된", "될", "됨", "시킨다", "시키는",
            "이며", "이면", "이다", "이고",
            "있어야", "있으면", "있으며", "있는", "있고", "있다", "있어",
            "없으면", "없으며", "없는", "없고", "없다", "없어",
            "않는다", "않으면", "않는", "않은", "않아", "않고",
            "아니한", "아니하는", "아니하며", "아니하고", "아니하면")

# 그 자체가 용언인 어절. 꼬리를 떼면 아무것도 안 남으므로 따로 본다.
# 실측: '있는' 54건 · '없는' 47건이 통째로 미분석이었다.
홑용언 = {"있는", "없는", "있다", "없다", "있고", "없고", "있으며", "없으며",
          "있어", "없어", "있을", "없을", "있음", "없음", "한다", "된다", "하는",
          "되는", "한", "할", "함", "된", "될", "됨", "하고", "되고", "하며", "되며"}
_용언차례 = sorted(용언꼬리, key=len, reverse=True)

# 관형사·부사. 한 글자짜리가 많아 조사 규칙에 안 걸리는데, 그렇다고 '미분석' 으로
# 세면 **자가 눈감은 자리를 부풀려 잰다.** 닫힌 목록으로 따로 센다.
관형부사 = {"그", "이", "저", "각", "위", "해당", "모든", "다른", "같은", "어떤",
            "그러한", "이러한", "또한", "다만", "그러나", "그리고", "따라서",
            "아니", "못", "더", "덜", "곧", "이미", "다시", "직접", "다", "모두",
            "없이", "같이", "달리", "함께", "각각", "다소", "매우", "곧바로"}

_어절나눔 = re.compile(r"\s+")
_한글 = re.compile(r"[가-힣]")


@dataclass
class 형태소:
    """어절 하나를 뜯은 결과. **못 뜯으면 못 뜯었다고 적는다.**"""

    표층: str
    어간: str = ""
    조사: str = ""
    격: str = ""
    갈래: str = "기타"          # 체언 · 용언 · 수 · 조문 · 접속 · 기타
    왜: str = ""                # '미분석' 이면 조사를 못 갈랐다는 뜻


_수 = re.compile(r"^\d+(?:[,\.]\d+)*(?:년|월|일|개월|주|시간|분|원|만원|억원|배|"
                 r"퍼센트|%|명|인|회|호|항|조|점|등)?$")
_조문 = re.compile(r"^제\d+조(?:의\d+)?")


def 분해(어절: str) -> 형태소:
    """어절 -> 어간 + 조사. **짧아지는 쪽으로 겁을 낸다.**

    '법인이' 에서 '이' 를 떼면 '법인' 이지만 '법인이다' 에서 떼면 안 된다.
    남는 어간이 두 글자 미만이면 안 뗀다 -- 한자어 낱말이 대개 두 글자 이상이라
    이 문턱이 실용적으로 듣는다. 못 갈랐으면 `왜='미분석'` 을 남긴다.
    """
    w = 어절.strip(" \t.,·")
    if not w:
        return 형태소(어절, 왜="빈칸")
    if _조문.match(w):
        return 형태소(w, 어간=w, 갈래="조문")
    if _수.match(w):
        return 형태소(w, 어간=w, 갈래="수")
    if w in 접속표:
        return 형태소(w, 어간=w, 갈래="접속")
    if not _한글.search(w):
        return 형태소(w, 어간=w)
    if w in 관형부사:
        return 형태소(w, 어간=w, 갈래="관형부사")
    for m, pat in _서법:
        if pat.search(w):
            return 형태소(w, 어간=_용언어간(w), 갈래="용언", 왜=m)
    if w in 홑용언:
        return 형태소(w, 어간=w, 갈래="용언")
    꼬리 = _용언꼬리(w)
    if 꼬리:
        return 형태소(w, 어간=w[: -len(꼬리)], 조사=꼬리, 갈래="용언")
    for j in _조사차례:
        if not w.endswith(j):
            continue
        남 = w[: -len(j)]
        if not _뗄만한가(남):
            # 겁을 낸다 -- 안 뗀 것이 잘못 뗀 것보다 낫다. **이때만 미분석이다.**
            return 형태소(w, 어간=w, 갈래="체언", 왜="미분석")
        격 = 격조사.get(j) or 보조사.get(j, "")
        # 조사를 떼고 나서 용언이 드러나는 것이 있다. '위하여는' -> '위하여' -> '위'.
        꼬리2 = _용언꼬리(남)
        if 꼬리2:
            return 형태소(w, 어간=남[: -len(꼬리2)], 조사=j, 격=격, 갈래="용언")
        return 형태소(w, 어간=남, 조사=j, 격=격, 갈래="체언")
    # 조사 자리에 아무것도 안 붙은 맨 체언이다. **못 뜯은 것이 아니다.**
    # 처음엔 이것을 미분석으로 셌다가 '경우' 하나에 95건이 몰렸다(실측) -- 자가
    # 눈감은 자리를 부풀려 재면 어디를 고쳐야 하는지가 안 보인다.
    return 형태소(w, 어간=w, 갈래="체언")


# 한 글자 체언. 법률 문제의 당사자는 甲·乙·丙 이고 조사가 붙으면 어간이 한 자다.
# 실측: 이것을 안 받아서 `甲이` `乙에게` 따위 200건 남짓이 통째로 미분석이었다.
_한자 = re.compile(r"^[\u3400-\u4DBF\u4E00-\u9FFF]+$")
# 한 글자 한자어 체언. **재고 나서 늘렸다** -- 이 시험지 지문 360개에서 미분석
# 570건을 세어, 몰린 자리를 위에서부터 담았다(소 26 · 이 24 · 것 45 · 전/내/중 38 ...).
# 지어내지 않고 나온 것만 담는 이유: 한 글자를 함부로 열면 '법인이' 의 '인' 처럼
# **낱말 아닌 것을 낱말로 만든다.**
_홑체언 = {"甲", "乙", "丙", "丁", "戊", "己", "庚", "辛", "壬", "癸",
           "A", "B", "C", "D", "X", "Y", "Z",
           "것", "이", "그", "수", "때", "바", "자", "소", "죄", "법", "등",
           "중", "후", "전", "내", "외", "시", "점", "말", "일", "곳", "안"}


def _뗄만한가(남: str) -> bool:
    """조사를 뗀 나머지가 낱말 노릇을 하는가."""
    if len(남) >= 2:
        return True
    return bool(남) and (남 in _홑체언 or bool(_한자.match(남)))


def _용언꼬리(w: str) -> str:
    """이 어절이 달고 있는 용언 꼬리. 없으면 빈 문자열."""
    for k in _용언차례:
        if w.endswith(k) and len(w) - len(k) >= 1:
            return k
    return ""


def _용언어간(w: str) -> str:
    """서법 어미가 붙은 어절의 어간. '증명하여야' -> '증명'."""
    k = _용언꼬리(w)
    return w[: -len(k)] if k else w


def 분석(text: str) -> list:
    """문장 -> 형태소 목록."""
    return [분해(w) for w in _어절나눔.split(text.strip()) if w.strip()]


def 핵심어(text: str) -> list:
    """조사를 뗀 체언들. 견줄 때 쓰는 낱말 자루."""
    return [t.어간 for t in 분석(text) if t.갈래 in ("체언", "조문", "수") and t.어간]


def 구절조사(text: str) -> list:
    """'에 대하여' 처럼 **띄어 쓰는** 조사. (앞말, 구실) 목록."""
    out = []
    for 꼴, 구실 in 구절조사표:
        for m in re.finditer(r"([가-힣A-Za-z0-9一-鿿]+)\s*" + re.escape(꼴), text):
            out.append((m.group(1), 구실))
    return out


def 서법(text: str) -> str:
    """문장 하나의 서법. 여럿이면 **가장 센 것** -- 금지 > 기속 > 재량 > 단정."""
    for m, pat in _서법:
        if pat.search(text):
            return m
    return ""


def 서술(text: str) -> list:
    """(동사어간, 서법) 목록. `wording.mood_verbs` 의 어미판 -- 서법은 동사에 붙는다."""
    out = []
    for m, pat in _서법:
        if m == "단정":
            continue
        for mt in pat.finditer(text):
            앞 = text[: mt.start()].rstrip()
            v = re.search(r"([가-힣]{1,10})(?:하|되)?$", 앞)
            어간 = re.sub(r"(?:하|되|시키)$", "", v.group(1)) if v else ""
            if 어간:
                out.append((어간, m))
    return out


def 부정(text: str) -> bool:
    """명제를 뒤집는 말이 있는가. 서법 '금지' 와 다르다."""
    return bool(_부정.search(text))


def 조건(text: str) -> str:
    """'…한 때에는' 앞의 요건절. 없으면 빈 문자열."""
    m = _조건.search(text)
    return m.group(1).strip() if m else ""


def 예외(text: str) -> bool:
    """'다만' 처럼 본문과 다른 명제를 여는 말이 있는가."""
    return bool(_예외.search(text))


def 미분석률(text: str) -> float:
    """못 뜯은 어절의 비율. **자가 얼마나 눈을 감고 있는지 재는 자리다.**"""
    ts = [t for t in 분석(text) if t.갈래 != "기타"]
    return sum(1 for t in ts if t.왜 == "미분석") / len(ts) if ts else 0.0
