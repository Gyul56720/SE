"""회로·IC 설계를 **문제 풀이와 다르게** 다루라는 지시. 한 자리에 둔다.

사용자(2026-09-15): "admin agent 에서 회로 설계 질문을 '문제'로 파악하고 수학 문제
풀듯이 나온다. 디지털·아날로그 회로설계 부분은 따로 답하는 원칙에 어긋난다."

## 왜 갈렸나

도구(`draw_circuit` · `run_spice` · `run_rtl` · `concept` ...)는 두 채널에 다 물렸는데
**갈래 규칙은 공개 프롬프트에만 적혀 있었다.** 관리 프롬프트에는

    문제가 오면 **풀이 · 약한 개념 · 오답노트 · 예상 질문과 답변** 넷을 다 내라.

가 예외 없이 적혀 있어서, 회로 질문이 그대로 그 숙제 틀로 들어갔다.

## 그래서 한 자리에 둔다

같은 글을 두 군데 적으면 한쪽만 고쳐져 또 갈린다. 여기 한 벌만 두고 두 프롬프트가
이것을 끼워 쓴다. `tests/test_eda_prompt.py` 가 **둘 다에 들어갔는지** 본다.
"""
from __future__ import annotations

표 = "[EDA]"
_안쓰임 = 1          # 두 프롬프트에 실제로 들어갔는지 검사가 이 표를 찾는다

갈래규칙 = (
    표 + " **회로·IC 설계 물음은 '문제'가 아니다 -- 숙제 틀로 답하지 마라.**\n"
    "묻는 것이 아날로그/디지털 집적회로 · RTL · FPGA · IP 설계라면, 풀이/약한 개념/"
    "오답노트/예상 질문 네 토막으로 쪼개지 마라. 그것은 시험 문제용 틀이다. 여기서는 "
    "**설계자가 쓰는 꼴**로 답한다:\n"
    "1. `concept(name)` 으로 그 개념의 정의식과 그것이 정하는 양을 먼저 못 박는다. "
    "학부/석사/박사 층까지 붙어 있으니 답할 깊이를 거기서 정하라.\n"
    "2. **말로 끝내지 말고 그려라** -- `draw_circuit`. 회로는 그림이 절반이다.\n"
    "3. **주장하지 말고 돌려라** -- 아날로그는 `run_spice`(DC/AC/트랜지언트, `.meas` 로 "
    "재라), 공정 산포는 `monte_carlo`, 디지털은 `run_rtl`(파형까지 온다) · `lint_rtl` · "
    "`synth_rtl`(셀 수) · `prove_rtl`(형식 증명) · `place_rtl`(실제 Fmax).\n"
    "4. **'벤치가 통과했다' 는 검증이 아니다.** IP 딜리버러블은 RTL 만이 아니라 커버리지 리포트가 같이 간다. 검증했다고 말하려면 `run_rtl(..., min_coverage=80)` 처럼 바닥을 줘라 -- 실측으로 같은 카운터의 두 벤치가 **둘 다 PASS** 인데 하나는 DUT 52.9%(`load` 를 한 번도 안 흔듦), 하나는 100% 였다.\n"
    "5. 잰 숫자를 **손계산과 나란히 놓아라.** 어긋나면 어긋났다고 말하고 까닭을 찾는다.\n"
    "6. 도구가 `못잼` 을 내면 그것은 통과가 아니다. 왜 못 쟀는지 그대로 옮겨라.\n"
    "\n"
    "**말은 갈라 쓴다.** 수학·물리·전공 시험 문제를 푸는 것은 지금까지처럼 **한국어**다. "
    "회로·IC·RTL·FPGA·IP 설계는 **영어**로 답하고 회로도 라벨도 영어로 쓴다 -- 그쪽은 "
    "용어와 도구 흐름과 데이터시트가 전부 영어이고, 한글 라벨은 글꼴이 없으면 두부로 "
    "그려진다. 한 물음에 둘이 섞여 있으면 설계 대목만 영어로 쓴다.\n"
)


def 끼우기(프롬프트: str, 앵커: str) -> str:
    """`앵커` 바로 앞에 갈래규칙을 끼운다. 이미 있으면 그대로 둔다."""
    if 표 in 프롬프트:
        return 프롬프트
    if 앵커 not in 프롬프트:
        raise ValueError(f"앵커를 못 찾았다: {앵커[:40]!r}")
    return 프롬프트.replace(앵커, 갈래규칙 + "\n" + 앵커, 1)
