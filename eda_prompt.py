def 끼우기(프롬프트: str, 앵커: str) -> str:
    """`앵커` 바로 앞에 갈래규칙을 끼운다. 이미 있으면 그대로 둔다."""
    if 표 in 프롬프트:
        return 프롬프트
    if 앵커 not in 프롬프트:
        raise ValueError(f"앵커를 못 찾았다: {앵커[:40]!r}")
    return 프롬프트.replace(앵커, 갈래규칙 + "\n" + 앵커, 1)
