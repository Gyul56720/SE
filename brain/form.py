"""**검사 꼴 -- 도메인이 아니라 꼴이 닫혀 있다.**

한 번 잘못 짰다(실측 2026-09-09). 판정기를 `법.조문대조` · `모델.승률` 처럼 **도메인별로**
등록했다. 그러면 내가 예상한 물음만 된다 -- `brief/source.py` 에 출처를 미리 등록해 둔
것과 **똑같은 하드코딩**을 한 층 위에서 되풀이한 것이다. 스포츠·영어·논문·법·의학은
사용자가 든 **예시**였지 목록이 아니었다.

## 그런데 기존 파이프라인들은 왜 닮았나

닮은 것이 도메인이 아니라 **검사하는 꼴**이었기 때문이다.

    law L001 인용한 조문이 원장에 실재하는가  |
    brief B002 이 수의 근거가 원장에 있는가    |  같은 것이다 -- **대조**
                                              |
    brief B004 다시 셈해도 같은가              |  **재계산**
                                              |
    lol  기준선(동전던지기)을 이기는가          |
    brief 과거 분포에서 이례인가                |  같은 것이다 -- **기준선**
                                              |
    law  logic 진리표: 지문에서 따라 나오는가   |
    mathdrift prove: 유도가 이어지는가          |  같은 것이다 -- **연역**
                                              |
    law  J005 그 요건이 갈리면 결론이 갈리는가  |
    brief I004 한 걸음 빼면 판정이 바뀌는가     |  같은 것이다 -- **뒤집기**

**다섯이다.** 그리고 다섯 다 도메인을 모른다. 티켓값이든 촉매든 처음 보는 물음이든,
검사할 수 있으면 이 다섯 중 하나로 가고 아니면 **관할 밖**이다. 셋째 길은 없다.

## 무엇이 닫혀 있고 무엇이 열려 있나

    닫힘   검사 **꼴** 다섯. 판정하는 코드. 여기는 요청 시점에 못 늘린다
    열림   **무엇을** 대조할지 · 무엇을 다시 셀지 · 무엇을 기준선으로 둘지

`--url` 과 같은 배치다. 거기서도 출처는 열려 있고 `inspect` 는 닫혀 있었다.
**검사기 자체가 열리면 검사기를 검사할 것이 없어진다** -- 그 하나는 닫아 둔다.

## 관할 밖은 실패가 아니다

`law/METHOD.md` 1-7(Alexy)의 선이다 -- 기계가 판정하는 것은 **내적 정당화**뿐이고,
전제가 옳은가는 관할이 아니다. 관할 밖이라고 답을 못 하는 것이 아니라, **판정 없이
답한다고 말하고 답하면 된다.** 하면 안 되는 것은 판정 안 받은 답에 판정받은 옷을
입히는 것이다 -- 없는 출처, 근거 없는 수치, "연구에 따르면".
"""
from __future__ import annotations

from dataclasses import dataclass


@dataclass
class 검사꼴:
    이름: str
    묻는것: str
    있어야: tuple          # 이것이 없으면 이 꼴로 못 간다
    판정: tuple            # 나올 수 있는 판정. **모름 갈래가 없는 꼴은 없다**
    돌리는것: str          # 실제로 판정하는 코드
    못하는것: str


FORMS: dict = {}


def 등록(f: 검사꼴) -> 검사꼴:
    FORMS[f.이름] = f
    return f


등록(검사꼴(
    이름="대조",
    묻는것="이 주장이 원장의 어느 줄과 **글자 그대로** 맞는가",
    있어야=("원장", "주장", "근거"),          # 근거 = 원장의 어느 줄을 가리키는가
    판정=("맞음", "어긋남", "미검증"),
    돌리는것="brief/gate.py B002 · law/gate.py L001~L003 · law/wording.py W001~W005",
    못하는것="그 주장이 **중요한가** · 원장이 옳은가. 원장 밖은 전부 미검증이다",
))

등록(검사꼴(
    이름="재계산",
    묻는것="주장한 수를 원장에서 **다시 세면 같은가**",
    있어야=("원장", "수", "규칙"),
    판정=("같음", "다름", "못셈"),
    돌리는것="brief/gate.py B004 (derive.RULES · derive.ACROSS 를 직접 다시 돌린다)",
    못하는것="규칙이 옳은가. 규칙대로 셌는지만 본다",
))

등록(검사꼴(
    이름="기준선",
    묻는것="이 관측이 **기준선 아래서 놀라운가**",
    있어야=("관측", "과거표본", "기준선"),
    판정=("이례", "평범", "못잼"),
    돌리는것="brief/infer.py (경험분위·기저율·Holm) · lol/score.py (백테스트)",
    못하는것="왜 그런가 · 앞으로 어떨까. 그리고 표본이 짧으면 **아무것도 못 가른다**",
))

등록(검사꼴(
    이름="연역",
    묻는것="전제에서 **따라 나오는가**",
    있어야=("전제", "결론"),   # 스키마로 물으면 전제 = 요건표, 결론 = 세우려는 주장
    판정=("참", "거짓", "모름"),
    돌리는것="reason/ask.py (스키마 -> 두 정거장 -> 결론) · law/logic.py (진리표, "
              "건전·완전) · mathdrift/prove.py (sympy)",
    못하는것="전제가 참인가. **그럴듯한데 전제에 없는 것은 `모름` 이다** -- 그것이 요점",
))

등록(검사꼴(
    이름="뒤집기",
    묻는것="근거 하나를 빼면 **결론이 바뀌는가**",
    있어야=("결론", "근거묶음"),
    판정=("굳음", "약함", "못잼"),
    돌리는것="reason/derive.py 뒤집는가 · law/issue.py J005 · brief/infer.py 뒤집기",
    못하는것="바뀐다고 틀린 것이 아니다. **짚어 줄 뿐 기각하지 않는다**",
))


def get(name: str):
    """**없으면 None.** 비슷한 것을 골라 주지 않는다 -- 딴 꼴로 검사하게 된다."""
    return FORMS.get(name)


def 필요한것(name: str) -> tuple:
    f = FORMS.get(name)
    return f.있어야 if f else ()


# 어떤 꼴로도 안 가는 것들. **"아직 안 만든 것" 이 아니라 원장이 정하지 않는 것**이다.
# 도메인 목록이 아니라 **물음의 종류**로 적는다 -- 도메인으로 적으면 또 예시 목록이 된다.
관할밖 = {
    "인과": "왜 그렇게 되었는가. 관측 원장으로는 상관까지다",
    "전망": "앞으로 어떻게 되는가. 되짚을 원장이 아직 없는 일이다",
    "가치": "무엇이 좋은가 · 어느 학설이 옳은가 · 어떻게 사는 게 나은가",
    "처방": "이 사람이 무엇을 해야 하는가. 원장은 무엇이 있는지를 정하지 "
            "이 사람에게 무엇이 맞는지를 안 정한다 -- **의학·법에서 특히 그렇다**",
    "원장없음": "밖에 대조할 것이 아예 없는 물음. 답하면 되지만 **수치를 붙이지 마라**",
}


def 목록() -> str:
    out = ["검사 꼴 -- **다섯이고 늘지 않는다.** 도메인은 상관없다.", ""]
    for f in FORMS.values():
        out.append(f"  {f.이름:<6} {f.묻는것}")
        out.append(f"         있어야: {' · '.join(f.있어야)}")
        out.append(f"         판정:   {' / '.join(f.판정)}")
        out.append(f"         도는 곳: {f.돌리는것}")
        out.append(f"         **못 하는 것**: {f.못하는것}")
        out.append("")
    out.append("  어떤 꼴로도 안 가는 물음 (관할 밖 -- 실패가 아니다):")
    for k, v in 관할밖.items():
        out.append(f"    {k:<8} {v}")
    return "\n".join(out)
