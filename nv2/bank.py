def cond(cat: str) -> list:
    """**조건.** 그 칸이 실릴 때 늘 같이 간다."""
    return [(n, r) for n, r, tag in CATS[cat] if tag == "조건"]


def eg(cat: str) -> list:
    """**본보기.** 돌려 뽑는 것."""
    return [(n, r) for n, r, tag in CATS[cat] if tag != "조건"]


def draw(cat: str, seed: str, n: int, k: int) -> list:
    """이번 회차에 보여 줄 본보기 k개. 씨앗과 번호로 정해진다 -- 같은 원고는 같다."""
    items = eg(cat)
    if not items or k <= 0:
        return []
    h = hashlib.sha1(f"{seed}|{cat}|{n}".encode("utf-8")).digest()
    order = sorted(range(len(items)), key=lambda i: h[i % len(h)] * 31 + i * 7 + n)
    return [items[i] for i in order[:k]]


def line(pair) -> str:
    return f"    {pair[0]}: {pair[1]}"


def names(cat: str) -> list:
    return [n for n, _, _ in CATS[cat]]


def total() -> int:
    return sum(len(v) for v in CATS.values())
