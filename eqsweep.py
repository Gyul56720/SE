"""**곱셈기 0개 구조가 어디서 지는가** -- 구조 교차 실험.

이 저장소가 잰 것은 여기까지였다: 메모리 없는 비선형은 128칸 표가 되돌리고,
압축 뒤 대역제한이 만든 **짧은** 메모리는 표본 두 개를 색인하는 256칸 표가
되돌린다. 그 창에서 신경망은 곱셈기 값을 못 한다.

**그러면 신경망이 반드시 필요한 자리는 어디인가.** 앞선 판들은 그 자리를 짓지
않은 채 "우리는 그런 경우를 만들지 않았다" 고만 적었다. 이 모듈이 그 자리를 짓는다.

## 처음 세운 셈 -- 맞는 말이지만 **binding 하지 않았다**

표본값 색인 표는 창 `W` 개 표본을 각 `B` 비트로 잘라 색인한다. 칸이 `2^(W·B)` 개다.
보정에 필요한 메모리가 `M` 심볼이면 `W >= M` 이라야 하므로 칸이 **M 에 지수로**
는다(`지수벽()`). 신경망은 같은 창에 파라미터가 `M·H` 로 **선형으로** 는다.
그러므로 M 이 커지면 어디선가 뒤집힐 것이다 -- **셈으로는 맞다.**

**그런데 재 보니 M 은 거의 안 움직였다**(실측 2026-09-16, 25dB · SNR30 · 64만 비트
· 씨 8). 드룹 시상수를 18.8 UI 까지 늘려도 NN/표 가 1.28 -> 1.47 이었다. τ 를
5~150 UI 로 쓸어도 1.21~2.66 사이에서 추세가 없었다.

    바꾼 것                    NN/표 중앙값   NN 이긴 씨
    기준(k=1.0)                    1.28         5/8
    드룹 tau = 18.8 UI              1.47         7/8    <- 노렸던 축. 거의 안 움직인다
    압축 k = 1.3                    2.17         8/8
    압축 k = 1.6                    2.50         8/8
    압축 k = 2.0                    3.40         8/8    <- 실제로 가르는 축
    압축뒤대역 beta = 0.35           0.56         1/8    <- 오히려 표 쪽으로

## 그리고 그 1.28 조차 공정하지 않았다

표 앞에는 FFE 가 있는데, **메모리 없는 압축을 그대로 둔 채 선형 적응기를 돌리고
있었다.** 명제 1 이 "메모리 없는 비선형은 ADC 코드 표가 곱셈 0개로 되돌린다" 인데
정작 비교에서 그 표를 안 깔았다. 깔자 k=2.0 에서 표가 5.9e-2 -> 1.1e-2 로 **5.2배**
좋아졌다. **구조 비교는 약한 쪽의 설정만큼만 믿을 수 있다.**

양쪽에 똑같이 깔고 나면 경계가 이렇게 선다 -- 그리고 이것이 이 모듈의 결론이다.

    k = 1.0   표가 이긴다 (NN/표 0.59, NN 1/8)
    k = 1.3   표가 이긴다 (0.71, 0/8)
    k = 1.6   표가 이긴다 (0.78, 2/8)
    k = 2.0   **망이 이긴다** (1.79, 8/8)

## 규율

- **씨마다 비를 내고 그 비들을 본다**(비의 평균이 아니라). BER 평균은 한 씨가
  지배한다 -- 이 저장소가 이미 한 번 속은 자리다.
- **대조를 같이 돌린다.** 손상이 없는 링크에서도 같은 순서가 나오면 그것은 구조
  차이가 아니라 내 배선이다.
- 여기서 `긴메모리` 라는 이름을 그대로 둔다. **가설의 이름이고, 지지되지 않았다는
  것이 결과다** -- 이름을 지우면 무엇을 재려 했는지가 사라진다.
"""
from __future__ import annotations

import math

import numpy as np

import nneq
import serdes

# 기준 링크. 손상만 갈아 끼우고 나머지는 붙들어 둔다.
밑판 = dict(손실dB=20.0, SNRdB=26.0, ADC비트=7)

# **긴 메모리 비선형**: 드룹(tau=150 표본 = 18.75 심볼) 뒤에 압축.
긴메모리 = dict(누설시상수=150.0, 압축=1.6)
# 대조 하나: 메모리 없는 비선형(압축만). 표가 이겨야 맞는다.
메모리없음 = dict(압축=1.6)
# 대조 둘: 선형 채널. 표도 망도 이길 것이 없어야 맞는다.
선형 = dict()


def _표(창: int, 비트: int) -> dict:
    return {"이름": f"표{창}x{비트}", "칸": 1 << (창 * 비트),
            "꼴": "표", "창": 창, "비트": 비트}


def _mlp(앞뒤: int, 은닉: int) -> dict:
    return {"이름": f"MLP{2 * 앞뒤 + 1}x{은닉}", "꼴": "망", "앞뒤": 앞뒤, "은닉": 은닉}


기본구조 = [
    {"이름": "FFE11", "꼴": "선형"},
    {"이름": "FFE11+역압축", "꼴": "역압축"},
    _표(2, 4), _표(2, 5), _표(3, 4), _표(3, 5),
    _mlp(5, 16), _mlp(10, 16), _mlp(10, 4), _mlp(5, 4),
]


def 한판(구조: dict, 손상: dict, 비트수: int = 200000, 씨: int = 0,
       FFE탭: int = 11, 에폭: int = 12) -> dict:
    """구조 하나를 한 씨로 돌린다. {BER, 오류수, 잰비트, 파라미터수, 곱셈기}."""
    꼴 = 구조["꼴"]
    if 꼴 == "망":
        r = nneq.링크(비트수=비트수, 앞뒤=구조["앞뒤"], 은닉수=구조["은닉"],
                    에폭=에폭, 씨=씨, **밑판, **손상)
        입력 = 2 * 구조["앞뒤"] + 1
        곱셈 = 입력 * 구조["은닉"] + 구조["은닉"]
        return {"BER": r["BER"], "오류수": r["오류수"], "잰비트": r["잰비트"],
                "파라미터수": r["파라미터수"], "곱셈기": 곱셈, "칸": 0}
    인자 = dict(비트수=비트수, FFE탭=FFE탭, 씨=씨, **밑판, **손상)
    if 꼴 == "역압축":
        인자["역압축"] = True
    elif 꼴 == "표":
        인자.update(표본표창=구조["창"], 표본표비트=구조["비트"])
    r = serdes.링크(**인자)
    return {"BER": r["BER"], "오류수": r["오류수"], "잰비트": r["잰비트"],
            "파라미터수": int(r.get("표본표찬칸", 0)) or FFE탭,
            "곱셈기": FFE탭, "칸": 구조.get("칸", 0),
            "찬칸": int(r.get("표본표찬칸", 0))}


def 교차(손상: dict, 구조들=None, 비트수: int = 200000, 씨수: int = 8,
       기준: str = "표2x4", 에폭: int = 12) -> dict:
    """구조들을 여러 씨로 돌리고 **씨마다의 비**로 견준다.

    `기준` 구조 대비 이득 = BER(기준)/BER(구조). 씨마다 내고 중앙값과 이긴 씨 수를
    같이 낸다 -- 평균 BER 의 비는 한 씨에 끌려간다.
    """
    구조들 = list(구조들 if 구조들 is not None else 기본구조)
    잰것 = {}
    for 구 in 구조들:
        판들 = [한판(구, 손상, 비트수, 씨, 에폭=에폭) for 씨 in range(씨수)]
        잰것[구["이름"]] = {
            "BER들": [p["BER"] for p in 판들],
            "오류합": int(sum(p["오류수"] for p in 판들)),
            "비트합": int(sum(p["잰비트"] for p in 판들)),
            "곱셈기": 판들[0]["곱셈기"], "칸": 판들[0]["칸"],
            "파라미터수": 판들[0]["파라미터수"],
            "찬칸": 판들[0].get("찬칸", 0),
        }
    base = 잰것[기준]["BER들"]
    for 이름, v in 잰것.items():
        비 = []
        for b, x in zip(base, v["BER들"]):
            if not (x > 0) or not (b > 0):
                continue                      # 0 오류는 비를 못 낸다
            비.append(b / x)
        v["씨별비"] = 비
        v["비중앙값"] = float(np.median(비)) if 비 else float("nan")
        v["이긴씨"] = int(sum(1 for r in 비 if r > 1.0))
        v["잰씨"] = len(비)
        v["합BER"] = (v["오류합"] / v["비트합"]) if v["비트합"] else float("nan")
    return {"기준": 기준, "손상": dict(손상), "비트수": 비트수, "씨수": 씨수,
            "잰것": 잰것}


def 말로(결과: dict) -> str:
    """사람이 읽을 표 하나. 비는 **씨별 중앙값**이고 괄호는 이긴 씨 수다."""
    줄 = [f"손상 {결과['손상']}  비트 {결과['비트수']}  씨 {결과['씨수']}  "
         f"기준 {결과['기준']}",
         f"{'구조':<14} {'BER(합)':>10} {'기준대비':>9} {'이긴씨':>7} "
         f"{'곱셈기':>7} {'칸':>8} {'찬칸':>7}"]
    for 이름, v in 결과["잰것"].items():
        줄.append(f"{이름:<14} {v['합BER']:10.3e} {v['비중앙값']:9.2f} "
                  f"{v['이긴씨']:>4}/{v['잰씨']:<2} {v['곱셈기']:>7} "
                  f"{v['칸']:>8} {v['찬칸']:>7}")
    return "\n".join(줄)


def 데이터벽(손상: dict, 비트수들=(40000, 160000, 640000), 씨수: int = 8,
         구조들=None, 기준: str = "표2x4") -> dict:
    """**학습 데이터를 늘려 가며** 같은 겨룸을 되풀이한다.

    표는 칸마다 표본이 필요하므로 데이터가 적으면 큰 표가 빈 칸투성이가 된다.
    신경망은 파라미터를 나눠 쓰므로 같은 데이터에서 더 큰 창을 쓴다. **그래서
    누가 이기는지는 손상만으로 정해지지 않는다 -- 학습 길이가 같이 정한다.**
    표준이 프리앰블 길이를 정하므로 이 축은 설계자가 고르는 것이 아니다.
    """
    return {이름: 교차(손상, 구조들=구조들, 비트수=N, 씨수=씨수, 기준=기준)
            for N, 이름 in ((N, N) for N in 비트수들)}


def 버팀(손상: dict, 손잡이: str, 값들, 구조들=None, 비트수: int = 200000,
       씨수: int = 4) -> str:
    """손상 하나를 **세기별로 쓸어** 구조 사이의 순서가 유지되는지 본다.

    누화·전원잡음·지터는 등화기가 지울 수 있는 것이 아니다(각각 딴 데이터·시변
    이득·표본 위치). 그러므로 이것들이 답하는 물음은 "누가 이것을 고치나" 가
    아니라 **"이것이 있어도 아까의 순서가 그대로인가"** 다. 순서가 뒤집히면 앞의
    결론이 손상 없는 실험실에서만 참인 것이다.
    """
    구조들 = list(구조들 if 구조들 is not None else 기본구조)
    이름들 = [구["이름"] for 구 in 구조들]
    줄 = [f"손상 {손상} + {손잡이} 쓸기  비트 {비트수}  씨 {씨수}",
         f"{손잡이:>10} | " + " ".join(f"{n:>13}" for n in 이름들)]
    for v in 값들:
        이 = dict(손상)
        이[손잡이] = v
        칸 = []
        for 구 in 구조들:
            e = b = 0
            for 씨 in range(씨수):
                r = 한판(구, 이, 비트수, 씨)
                e += r["오류수"]; b += r["잰비트"]
            칸.append(e / b if b else float("nan"))
        best = min(x for x in 칸 if x == x)
        줄.append(f"{v:>10} | " + " ".join(
            (f"{x:>12.2e}*" if x == best else f"{x:>12.2e} ") for x in 칸))
    return "\n".join(줄)


def 지수벽(창들=(1, 2, 3, 4, 5, 10, 20), 비트: int = 4, 은닉: int = 16) -> str:
    """표의 칸과 망의 파라미터가 **필요 메모리**에 따라 어떻게 갈리는지 -- 셈만."""
    줄 = [f"{'창(심볼)':>8} {'표 칸수':>14} {'MLP 파라미터':>14}"]
    for W in 창들:
        칸 = 2 ** (W * 비트)
        입력 = 2 * W + 1
        p = 입력 * 은닉 + 은닉 + 은닉 + 1
        줄.append(f"{W:>8} {칸:>14,} {p:>14,}")
    return "\n".join(줄)


if __name__ == "__main__":       # pragma: no cover
    import sys
    N = int(sys.argv[1]) if len(sys.argv) > 1 else 200000
    씨수 = int(sys.argv[2]) if len(sys.argv) > 2 else 8
    print(지수벽(), "\n")
