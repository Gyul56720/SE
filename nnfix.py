"""신경망 등화기의 **고정소수점 기준모델.** RTL 이 이것과 비트까지 같아야 한다.

주제의 5단계(FPGA 구현). 여기가 없으면 합성해서 LC 를 보고하고도 **그것이 맞는 답을
내는지 아무도 안 본다** -- 이 저장소가 내내 쫓은 바로 그 거짓 초록이다. 그래서 순서를
이렇게 둔다.

    활성함수를 BER 로 고른다 -> 고정소수점 기준모델 -> RTL 이 그것과 비트까지 같나
    -> **그 다음에** 면적

## 활성함수는 재서 골랐다 -- 실측 2026-09-16, 200k 비트 · 씨 8개

    곱셈       tanh        hardtanh         pwl3      hardtanh/tanh  이긴 씨
     12     6.322e-03    **5.378e-03**   1.071e-02      0.85배        7/8
     24     5.667e-03      5.559e-03     7.872e-03      0.98배        5/8
     40     4.320e-03      5.483e-03     8.171e-03      1.27배        3/8

**곱셈 12개(이 설계가 쓰는 크기)에서 hardtanh 가 tanh 를 8씨 중 7씨에서 이긴다**
(부호검정 p ~= 0.04). 24개에서는 차이가 없다. 40개에서는 평균이 1.27배 나쁘지만
씨별 비가 [0.93, 2.40] 으로 1 을 가로지르고 이긴 씨가 3/8 이라 **나쁘다고 말할 수
없다(미해결)** -- 한 씨(2.40배)가 평균을 끌었다.

그러니 주장은 여기까지다: **쓰는 크기에서 hardtanh 는 tanh 를 비기거나 이기고,
하드웨어로는 비교 둘이면 끝난다.** 큰 망에서도 그렇다고는 말하지 않는다.

pwl3 는 어느 크기에서나 제일 나쁘다(1.4~1.9배). **tanh 를 더 잘 근사하는데 BER 은
더 나쁘다** -- 망이 주어진 비선형에 맞춰 학습하므로 "더 정확한 근사" 가 "더 좋은
등화기" 가 아니다. 근사 오차를 재서 고르면 여기서 틀린다.

## 자릿수: 갈린 것은 **정수부**다 -- 소수부도 폭도 아니다 (실측 2026-09-16, 씨 6개)

`가중치비트`(부호 포함 전체 폭)와 `프랙비트`를 따로 흔들어 float 대비 BER 배수를 쟀다.

    폭  프랙  정수부   스케일    배     퍼짐
     7    6     0      2    7.86  [5.74,10.84]
     8    6     1      1    1.84  [1.62, 2.05]
    10    8     1      1    1.86  [1.66, 2.10]   <- 폭 10 이어도 정수부 1 이면 같다
     9    6     2      1    0.98  [0.92, 1.08]
     8    5     2      1    0.99  [0.79, 1.36]
     7    4     2      1    1.00  [0.85, 1.24]
    10    6     3      1    0.98  [0.92, 1.08]
    10    4     5      1    1.00  [0.85, 1.24]

**같은 정수부면 전체 폭이 달라도 같은 값이 나온다.** 갈린 것은 소수 해상도가 아니라
가중치가 담기는 **범위**다. 바닥은 정수부 2(가중치 ±4)다.

소수부에도 따로 바닥이 있다: 프랙 3 은 1.21배인데 퍼짐이 [0.60, 2.15] 로 1 을
가로지른다 -- **나쁘다고도 같다고도 말할 수 없다(미해결).** 안전한 바닥으로 4 를 쓴다.

둘을 합치면 **부호 1 + 정수부 2 + 소수부 4 = 7비트(Q2.4)** 이고, 그것이 기본값이다.

    x   Q2.4 7비트 부호  (AGC·ADC 를 지난 표본)
    W1  Q2.4 7비트 부호
    z   누산기           -> 4비트 내림 -> ±16 으로 클립 (hardtanh, ±1)
    h   Q1.4
    W2  Q2.4 7비트 부호
    y   누산기           -> **부호만 쓴다** (0 은 +1, RTL 의 `~y[MSB]` 와 같다)

### 이 자리의 앞 판 진단이 틀렸었다

처음 여기 적은 것은 "Q1.6 8비트가 2.6배 나쁘고, 원인은 W1 이 안 들어가 스케일
`s=8` 로 나눠 담은 것" 이었다. **둘 다 틀렸다.** 8비트에서 `고를스케일` 은 1 을
내놓는다 -- 나누기가 시작되는 것은 7비트부터다. 배수도 2.6 이 아니라 1.84 다.
한 씨로 한 번 돌린 값에 원인까지 붙여 적어 둔 것이었다. **여섯 씨로 축 둘을 따로
흔들기 전에는 무엇이 갈랐는지 알 수 없었다.**

이 오진에는 값이 붙는다. Q3.6 10비트로 지은 회로가 **4,498 LC** 였고, 같은 BER 을
내는 Q2.4 7비트는 **2,368 LC** 다 -- 틀린 진단이 면적을 **1.9배** 물렸다.

## 반올림과 내림은 차이가 없었다

계통 편향이 걱정돼 `반올림` 을 기본으로 두지만 BER 은 같았다. RTL 은 `>>>` 내림이라
비트 일치를 볼 때는 `반올림=False` 로 견준다.

"""
from __future__ import annotations

import numpy as np

import nneq
import serdes

# **재서 고른 바닥이다**(머리말). 정수부 = 기본비트 - 1 - 프랙 = 2.
프랙 = 4            # 소수부 비트. 클립 한계 ±1.0 == ±(1<<프랙)
기본비트 = 7        # 부호 포함 전체 폭. 정수부가 1 로 줄면 1.84배 나빠진다


def 재기(v, 프랙비트: int = 프랙, 비트: int = 기본비트) -> np.ndarray:
    """실수를 Q1.f 정수로. `비트` 폭의 부호 있는 범위로 자른다."""
    큰 = (1 << (int(비트) - 1)) - 1
    q = np.round(np.asarray(v, dtype=float) * (1 << 프랙비트))
    return np.clip(q, -큰 - 1, 큰).astype(np.int64)


def 굳히기(모: dict, 스케일: float = 1.0, 프랙비트: int = 프랙,
        비트: int = 기본비트) -> dict:
    """float 모델을 **정수 가중치**로. `스케일` 은 W1 을 담기 위한 나눗셈."""
    return {"W1": 재기(np.asarray(모["W1"]) / 스케일, 프랙비트, 비트),
            "b1": 재기(np.asarray(모["b1"]) / 스케일, 프랙비트, 비트),
            "W2": 재기(np.asarray(모["W2"]), 프랙비트, 비트),
            "b2": 재기(np.asarray(모["b2"]), 프랙비트, 비트)}


def 고를스케일(모: dict, 프랙비트: int = 프랙, 비트: int = 기본비트) -> float:
    """W1·b1 이 `비트` 폭에 다 들어가게 하는 제일 작은 2의 거듭제곱."""
    큰것 = max(float(np.max(np.abs(모["W1"]))), float(np.max(np.abs(모["b1"]))), 1e-12)
    끝 = (1 << (int(비트) - 1)) - 1
    s = 1.0
    while 큰것 / s * (1 << 프랙비트) > 끝:
        s *= 2.0
    return s


def 누산기(정수모: dict, X정수: np.ndarray, 프랙비트: int = 프랙,
        반올림: bool = True) -> np.ndarray:
    """**RTL 과 같은 순서로** 정수 연산만 해서 마지막 누산기 `y` 를 돌려준다.

    이것이 기준이다. Verilog 가 이 정수값과 하나라도 다르면 RTL 이 틀린 것이다.
    **부호가 아니라 값을 내놓는 까닭**: 부호만 견주면 어긋난 회로도 절반은 맞아
    50% 언저리가 초록처럼 보인다(실측으로 52% · 91% 를 두 번 겪었다).
    """
    return 속내(정수모, X정수, 프랙비트, 반올림)[2]


def 속내(정수모: dict, X정수: np.ndarray, 프랙비트: int = 프랙,
       반올림: bool = True) -> "tuple[np.ndarray, np.ndarray, np.ndarray]":
    """`(z, h, y)` -- 누산기 속을 그대로 내놓는다.

    검사가 **누산기 폭을 재려면 z 를 봐야 한다.** y 는 hardtanh 가 이미 눌러 놓은
    뒤라 아무리 극단을 먹여도 `HW+WW+log2(H+1)` 안에 머문다 -- y 만 보면 z 폭을
    좁혀도 초록이 난다(실측).
    """
    z = X정수 @ 정수모["W1"] + 정수모["b1"] * (1 << 프랙비트)
    # `>>` 는 음수에서 바닥으로 내려가 계통 편향을 만든다. 하드웨어도 더하기 한 번이면
    # 반올림이 되므로 그것을 기본으로 둔다 -- 다만 **재 보니 BER 차이는 없었다**.
    옮긴 = ((z + (1 << (프랙비트 - 1))) >> 프랙비트) if 반올림 else (z >> 프랙비트)
    h = np.clip(옮긴, -(1 << 프랙비트), (1 << 프랙비트))      # hardtanh
    return z, h, np.ravel(h @ 정수모["W2"] + 정수모["b2"] * (1 << 프랙비트))


def 앞먹임(정수모: dict, X정수: np.ndarray, 프랙비트: int = 프랙,
         반올림: bool = True) -> np.ndarray:
    """`누산기` 의 부호. NRZ 판정(±1)이다. **산술은 한 군데에만 있다** -- 검사가
    여기를 안 부르고 같은 식을 다시 쓰면, 기준을 고쳐도 검사가 안 걸린다(실측)."""
    return np.where(누산기(정수모, X정수, 프랙비트, 반올림) >= 0, 1, -1)


def 링크(비트수: int = 200000, 손실dB: float = 25.0, SNRdB: float = 30.0,
       압축: float = 1.0, 앞뒤: int = 2, 은닉수: int = 2, 에폭: int = 10,
       ADC비트: int = 7, 학습비율: float = 0.3, 반사=(),
       프랙비트: int = 프랙, 가중치비트: int = 기본비트, 반올림: bool = True,
       씨: int = 0) -> dict:
    """float 로 학습한 뒤 **정수로 굳혀** 돌린다. float 판정과 나란히 낸다."""
    본 = serdes.링크(비트수=int(비트수), 손실dB=손실dB, SNRdB=SNRdB, sps=8,
                   FFE탭=0, DFE탭=0, 반사=반사, 압축=압축, ADC비트=int(ADC비트),
                   ADC풀스케일시그마=2.5, 학습비율=학습비율, 씨=int(씨))
    x, b = 본["표본"], 본["비트"].astype(float)
    학습끝 = int(np.clip(len(x) * 학습비율, 1, len(x) - 1))
    X = nneq.창만들기(x, int(앞뒤))
    모 = nneq.짓기(X.shape[1], int(은닉수), 씨=int(씨))
    r = nneq.학습(모, X[:학습끝], b[:학습끝], 에폭=int(에폭), 씨=int(씨),
                활성꼴="hardtanh")
    모 = r["모"]

    부동판정 = np.where(nneq.예측(모, X, "hardtanh") >= 0, 1, -1)
    s = 고를스케일(모, 프랙비트, 가중치비트)
    정수모 = 굳히기(모, s, 프랙비트, 가중치비트)
    X정수 = 재기(X, 프랙비트, 가중치비트)
    정수판정 = 앞먹임(정수모, X정수, 프랙비트, 반올림)

    잰것 = slice(학습끝, len(b))
    def 세기(판정):
        틀림 = int(np.sum(판정[잰것] != b[잰것]))
        n = int(잰것.stop - 잰것.start)
        return {"오류수": 틀림, "잰비트": n, "BER": 틀림 / n if n else float("nan")}
    return {"부동": 세기(부동판정), "정수": 세기(정수판정),
            "정수모": 정수모, "스케일": s, "X정수": X정수, "정답": b,
            "학습끝": 학습끝, "수렴": r["수렴"], "학습왜": r["왜"],
            "프랙비트": int(프랙비트), "가중치비트": int(가중치비트),
            "반올림": bool(반올림),
            "같은판정비율": float(np.mean(부동판정 == 정수판정))}
