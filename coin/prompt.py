def 뉴스토막(사건들: list, 최대: int = 25) -> str:
    if not 사건들:
        return "(가) 최근 24시간 뉴스: **없다.** 뉴스 원장이 비었다.\n"
    줄 = ["(가) 최근 24시간 뉴스 (사건으로 뭉친 것 · 최초 보도 시각 기준)"]
    for e in 사건들[:최대]:
        나라 = "+".join(e.get("나라들") or [])
        지연 = e.get("지연", 0)
        늦 = f" · 주류({e.get('주국','?')})는 {지연:+.1f}h" if 지연 else ""
        줄.append(f"  [{e['최초'][:16]}Z] {e['유형']:<10} {e['자산']:<4} "
                  f"나라 {나라:<12} 글{e.get('글수',1)}건{늦}")
        줄.append(f"      {e.get('본보기','')[:100]}")
    if len(사건들) > 최대:
        줄.append(f"  ... 그리고 {len(사건들)-최대}건 더")
    return "\n".join(줄) + "\n"


def 잰것토막(원장: dict, 유형들=None, 최대: int = 40) -> str:
    산것 = LG.쓸만한것(원장)
    if 유형들:
        산것 = [r for r in 산것 if r["유형"] in 유형들] or 산것
    산것.sort(key=lambda r: (not r.get("살아남음"), r.get("p양측", 1)))
    if not 산것:
        return "(나) 과거 사건 연구: **하나도 못 쟀다.** 원장이 비었거나 표본이 다 모자란다.\n"
    시험수 = 산것[0].get("시험수", 0)
    줄 = [f"(나) 과거 사건 연구 -- **이번 실행에서 전부 {시험수}번 쟀다** "
          f"(그중 다중비교 보정을 넘은 것에 * 를 붙였다)",
          "  유형 / 자산 / 지평 | 관측중앙 | 기저율 | 초과 | 표본n | 겹침없는n | 승률 | p"]
    for r in 산것[:최대]:
        별 = "*" if r.get("살아남음") else " "
        줄.append(f"  {r['유형']}/{r['자산']}/D+{r['지평']} | "
                  f"{r['관측중앙']*100:+.2f}% | {r['널중앙']*100:+.2f}% | "
                  f"{r['초과']*100:+.2f}%p | n={r['n']} | {r['유효n']} | "
                  f"{r['승률']*100:.0f}% | p={r['p양측']:.3f}{별} | "
                  f"나라{r.get('나라수',0)} | 해마다 부호 {'같음' if r.get('부호일관') else '갈림'}")
    return "\n".join(줄) + "\n"


def 미검증토막(원장: dict, 최대: int = 15) -> str:
    못 = [r for r in (원장.get("잰것") or []) if r.get("미검증")]
    if not 못:
        return ""
    줄 = ["(다) **못 잰 것** -- 이것들에 대해서는 수를 말하지 마라. 못 쟀다고 적어라"]
    for r in 못[:최대]:
        줄.append(f"  {r['유형']}/{r['자산']}/D+{r['지평']}: {r['왜']}")
    if len(못) > 최대:
        줄.append(f"  ... 그리고 {len(못)-최대}개 더")
    return "\n".join(줄) + "\n"


def 시나리오토막(뭉치들: list) -> str:
    """**확률은 여기서만 온다.** 모델은 이 표를 옮기지 새로 매기지 않는다."""
    if not 뭉치들:
        return ""
    from coin import scenario as SC
    줄 = ["(라) 이미 뽑아 놓은 시나리오 -- **확률은 표본 비율이고 칸은 기저율 분포가 갈랐다**",
          "  * 가 붙은 것만 '기저율과 다르다' 고 말할 수 있다 (오차 구간이 기저율을 안 품는다)"]
    for m in 뭉치들:
        if not m.get("시나리오"):
            continue
        줄.append(f"  [{m['유형']}/{m['자산']}/D+{m['지평']}] 표본 {m['n']}개")
        for s in m["시나리오"]:
            줄.append(SC.줄(s))
    return "\n".join(줄) + "\n" if len(줄) > 2 else ""


def 장세토막(장세: dict, 흐름: dict, 훑음: dict) -> str:
    """**문턱이 없다.** 전부 자기 역사의 몇 % 자리인가."""
    from coin import regime as RG
    from coin import screen as SC2
    줄 = []
    if 장세:
        줄.append("(마-1) 지금 장세 -- 문턱이 아니라 **자기 역사의 자리**다")
        for g in 장세.values():
            줄.append(RG.적기(g))
    if 흐름:
        본 = [f"    {k:<12} {v['날']} 값 {v['값']:.6g} -> 자기 역사의 {v['백분위']*100:.0f}% 자리"
              for k, v in 흐름.items() if v.get("백분위") == v.get("백분위")]
        if 본:
            줄.append("(마-2) 돈 흐름 -- 자금조달률·미결제약정은 **포지션**이고, "
                      "대형이체만 **지갑**이다. 없는 줄은 그 자료를 못 받은 것이다")
            줄 += 본
    if 훑음:
        줄.append("(마-3) 종목 훑기 -- **초과 하나로만 줄을 세웠다.** 종합 점수는 없다")
        줄.append(SC2.적기(훑음, 전부=False))
    return "\n".join(줄) + "\n" if 줄 else ""


def 닮음토막(닮음: dict) -> str:
    """**지금과 가장 닮은 과거.** "~를 바탕으로 미루어 보면" 의 근거가 여기서 온다.

    similar.적기 가 이미 뉴스·시장·흐름을 갈라 낸 브리핑을 만든다. 그것을 그대로
    싣는다 -- 모델이 다시 해석하지 않게, 각 덩이가 고른 과거를 그대로 옮기게.
    """
    if not 닮음 or not 닮음.get("닮은날"):
        return ""
    from coin import similar as SM
    return "(바) 지금과 닮은 과거 -- **여기서 '미루어 보면' 의 근거가 나온다**\n" + SM.적기(닮음)


def 짓기(물음: str, 원장: dict, 사건들: list = None, 되먹임: str = "",
        유형들=None, 시나리오=None, 장세=None, 흐름=None, 훑음=None,
        닮음=None, 물음유형: str = "시장") -> str:
    # **질문 유형이 무엇을 앞세울지 정한다.**
    #   고르기: 훑기(모든 코인 순위)를 앞에 -- "곧 오를 코인"
    #   종목:   그 코인의 닮은 과거·시나리오를 앞에
    #   시장:   장세·지금 뉴스 브리핑을 앞에
    안내 = {
        "고르기": "\n**사용자가 '오를 코인' 을 물었다.** (마-3) 훑기에서 기저율과 갈린 "
                  "것만 고르고, 그중 초과가 양수인 것을 위에 둬라. 갈린 것이 없으면 "
                  "**'지금은 기저율과 갈리는 코인이 없다' 고 그대로 답하라** -- 억지로 "
                  "고르지 마라. 그리고 장세가 아래 칸이면 그것부터 말하라.",
        "종목":   "\n**사용자가 특정 코인을 물었다.** (바) 닮은 과거와 (라) 시나리오를 "
                  "그 코인에 대해 앞세워라. 그 코인의 사건연구가 미검증이면 못 잰다고 하라.",
        "시장":   "\n**사용자가 시장 전체를 물었다.** (마-1) 장세와 (가) 지금 뉴스를 "
                  "앞세워 브리핑하고, (바) 닮은 과거로 '이런 국면 뒤에 무엇이 있었나' 를 대라.",
    }.get(물음유형, "")
    조각 = [머리, 안내, "", f"## 사람이 물은 것\n\n{물음.strip()}", "",
            뉴스토막(사건들 or []), "", 잰것토막(원장, 유형들), "",
            닮음토막(닮음 or {}), "",
            시나리오토막(시나리오 or []), "",
            장세토막(장세 or {}, 흐름 or {}, 훑음), "",
            미검증토막(원장), 꼴]
    if 되먹임:
        조각 += ["", "## 앞 답에서 사실과 어긋난 자리",
                 "", 되먹임,
                 "", "위 자리를 고쳐서 다시 써라. 고칠 수 없으면 그 대목을 **빼라** -- "
                 "지어내서 메우지 마라."]
    return "\n".join(조각)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--물음", required=True)
    ap.add_argument("--원장", default="")
    ap.add_argument("--사건", default="")
    a = ap.parse_args(argv)
    import json
    사건p = Path(a.사건) if a.사건 else Path(__file__).resolve().parent / "corpus/events.json"
    사건 = json.loads(사건p.read_text(encoding="utf-8")).get("사건", []) if 사건p.exists() else []
    print(짓기(a.물음, LG.불러오기(a.원장 or None), 사건[-25:]))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
