"""**프롬프트는 원장에서 짓는다. 여기서 수를 만들지 않는다.**

    python3 coin/prompt.py --물음 "지금 비트코인 어때?"        (호출 0회)

## 모델이 하는 일과 안 하는 일

    한다      원장의 수를 **읽고 · 골라 · 사람 말로 잇는다.** 무엇이 물음에 닿는지 고른다
    안 한다   수를 만든다 · 통계를 낸다 · 어느 것이 유의한지 정한다

`law/METHOD.md` 의 분업 그대로다 -- LLM 은 대조 가능한 일을 하고, 판정은 코드가 한다.
여기서 대조 가능한 일이란 "이 물음에 이 잰 값이 닿는가" 이고, 그 답이 틀리면
`gate.py` 가 잡는다.

## 관문 이름을 프롬프트에 안 싣는다

무엇이 통과하는지 알려 주면 통과하는 답이 나온다. 그러면 관문이 사양서가 되고,
검사받은 것은 **문장의 꼴**이지 내용이 아니게 된다(`law/write.py` · `jaso/write.py`
와 같은 규율). 그래서 여기 적히는 것은 **보고서의 꼴**이지 관문의 목록이 아니다.
`tests/test_coin_loop.py` 가 프롬프트에 `C0\\d\\d` 가 안 들어가는지 붙든다.

## 미검증을 프롬프트에 같이 싣는 까닭

안 실으면 모델은 그 유형에 대해 **아무 말이나** 하게 된다(배경지식으로). 실어 두면
"그건 표본이 모자라 못 쟀다" 고 말할 수 있다. **모른다고 말할 수 있게 하는 것이
프롬프트가 할 수 있는 가장 큰 일이다.**
"""
