def 값물음(물음: str) -> bool:
    """**값을 묻는가.** 그러면 `섬`/`안섬` 이 답이 될 수 없다."""
    q = (물음 or "").strip()
    if not q:
        return False
    if any(w in q for w in 늘값말):
        return True
    return any(w in q for w in 값명사) and not any(w in q for w in 예아니오말)


def 읽기(d) -> 스키마:
    """dict 나 JSON 문자열 -> 스키마. **꼴이 아니면 빈 스키마다.**"""
    if isinstance(d, str):
        try:
            d = json.loads(d)
        except json.JSONDecodeError:
            return 스키마()
    if not isinstance(d, dict):
        return 스키마()
    es = []
    for x in (d.get("요건") or []):
        if not isinstance(x, dict) or not str(x.get("id") or "").strip():
            continue
        역 = str(x.get("역할") or 세움)
        es.append(요건(id=str(x["id"]).strip(), 말=str(x.get("말") or ""),
                      역할=역 if 역 in 역할들 else 세움,
                      무너뜨림=str(x.get("무너뜨림") or ""),
                      출처=str(x.get("출처") or ""),
                      원용필요=bool(x.get("원용필요")),
                      원용됨=bool(x.get("원용됨"))))
    입장 = d.get("입장") if isinstance(d.get("입장"), dict) else {}
    입장 = {k: {kk: bool(vv) for kk, vv in v.items()}
            for k, v in 입장.items() if isinstance(v, dict)}
    return 스키마(물음=str(d.get("물음") or ""),
                 세우는쪽=str(d.get("세우는쪽") or "세우는 쪽"),
                 다투는쪽=str(d.get("다투는쪽") or "다투는 쪽"),
                 요건=es, 입장=입장)


def _되돌이(s: 스키마) -> list:
    """무너뜨림을 따라가다 자기로 돌아오는 사슬. **결론이 안 정해지는 자리다.**"""
    대상 = {e.id: e.무너뜨림 for e in s.요건 if e.무너뜨림}
    돈것 = []
    for start in 대상:
        본, cur = [], start
        while cur and cur not in 본:
            본.append(cur)
            cur = 대상.get(cur, "")
        if cur and cur in 본:
            고리 = 본[본.index(cur):]
            if sorted(고리) not in [sorted(x) for x in 돈것]:
                돈것.append(고리)
    return 돈것


def 검사(s: 스키마) -> list:
    """S001~S005. **스키마가 참인지는 안 본다** -- 성한지만 본다."""
    vs = []
    ids = [e.id for e in s.요건]
    for eid in {i for i in ids if ids.count(i) > 1}:
        vs.append(위반("S001", "hard", eid,
                      f"같은 id 가 {ids.count(eid)}번 있다 -- 어느 것을 가리키는지 모른다"))
    있는 = set(ids)
    for e in s.요건:
        if e.무너뜨림 and e.무너뜨림 not in 있는:
            vs.append(위반("S002", "hard", e.id,
                          f"없는 요건을 무너뜨린다고 한다: {e.무너뜨림!r}"))
    for 고리 in _되돌이(s):
        vs.append(위반("S003", "hard", " -> ".join(고리),
                      "무너뜨림이 되돌이다 -- 서로 무너뜨리면 결론이 안 정해진다"))
    for e in s.요건:
        pos = s.입장.get(e.id, {})
        if len(pos) < 2:
            vs.append(위반("S004", "soft", e.id,
                          f"입장이 {len(pos)}쪽만 적혔다 -- 한쪽 말만 있는 것은 "
                          "다툼이 아니라 설명이다"))
    빈출처 = s.출처없음
    if 빈출처:
        vs.append(위반("S005", "soft", f"{len(빈출처)}개",
                      "출처가 안 적힌 요건이 있다 -- 어디서 온 배경지식인지 모르면 "
                      "**모델이 지어낸 것으로 다뤄야 한다**: "
                      + ", ".join(e.id for e in 빈출처[:6])))

    # S006 -- **헤지는 요건이 아니다.** 늘 참인 말은 늘 서고, 늘 서면 결론이 반드시 섬이다.
    for e in s.요건:
        걸린 = [w for w in 헤지말 if w in e.말]
        if 걸린:
            vs.append(위반("S006", "hard", e.id,
                          f"무너뜨릴 수 없는 말이다({' · '.join(걸린[:3])}) -- "
                          "'5로 알려져 있다' 는 요건이 아니고 '최대 랭크가 5다' 가 "
                          "요건이다. 늘 참인 요건은 늘 서고, 그러면 결론은 도출이 "
                          "아니라 **되풀이**가 된다"))

    # S007 -- **반대가 하나도 없으면 두 정거장이 구조적으로 못 갈린다.**
    # S004 는 '한쪽만 적혔나' 를 보고, 이것은 '둘이 같은 말인가' 를 본다. 다른 구멍이다.
    반대있나 = any(len(s.입장.get(e.id, {})) >= 2
                  and len({bool(v) for v in s.입장[e.id].values()}) > 1
                  for e in s.요건)
    if s.요건 and not 반대있나:
        vs.append(위반("S007", "hard", "입장",
                      "양측이 **반대로** 말한 요건이 하나도 없다 -- 두 정거장이 갈릴 "
                      "수가 없고, 그때 나오는 '섬' 은 판정이 아니라 전제의 되풀이다. "
                      "다투는 쪽이 무엇을 부정하는지 적거나, **이것이 다툼 물음이 "
                      "아니라고 말하고 멈춰라**"))

    # S008 -- **값을 묻는 물음은 여기 것이 아니다.** 결론이 섬/안섬 둘뿐이다.
    if 값물음(s.물음):
        vs.append(위반("S008", "hard", "물음",
                      f"값을 묻는데 여기 결론은 `섬`/`안섬` 둘뿐이다: {s.물음[:40]!r} -- "
                      "둘 중 어느 것도 답이 안 된다. `python3 brain/route.py "
                      "--프롬프트 '<물음>'` 으로 쪼개서 **대조**(원장의 어느 줄과 "
                      "맞는가) 꼴로 보내라. 여기서 억지로 돌리면 값 없는 '섬' 이 나온다"))
    return vs


def hard(vs) -> list:
    return [v for v in vs if v.등급 == "hard"]
