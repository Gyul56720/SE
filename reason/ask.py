"""**스키마를 받아 결론을 끌어낸다.** 데이터도 LLM 호출도 여기서 안 한다.

    python3 reason/ask.py --프롬프트 "<물음>"     # 모델에게 줄 것 (호출 0회)
    python3 reason/ask.py --표 스키마.json        # 검사하고 도출한다
    python3 reason/ask.py --표 - --짧게 < 스키마.json

    끝값 0  냈다   1  스키마에 hard 위반 -- 안 돌렸다   3  못 읽었다

## 결론은 **스키마에 조건부**다 -- 그래서 스키마를 먼저 보여 준다

모든 분야에 원장을 만들 수는 없다. 그러면 스키마가 참인지는 아무도 못 본다 --
외적 정당화이고 늘 관할 밖이었다(`law/METHOD.md` 1-7). 기계가 보는 것은 **그 스키마에서
결론이 따라 나오는가**뿐이다.

조건부인 결론을 낼 때 지켜야 할 것이 하나 있다. **전제를 통째로 같이 보인다.**
결론만 보이고 스키마를 숨기면 검사받지 않은 전제 위에 검사받은 결론이 얹히고, 읽는
사람은 그 둘을 구별할 수 없다 -- 이 저장소가 수에서 막아 온 것과 같은 자리다.

그래서 보고서의 **첫 절이 스키마**다. 결론은 그 다음이다.
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from reason import derive as DR                                    # noqa: E402
from reason import schema as SC                                    # noqa: E402

짧은한도 = 1900          # Discord 한 메시지 2000자


def 프롬프트(물음: str) -> str:
    """**모델에게 줄 것.** 검사 이야기가 한 줄도 없다 -- 스키마만 세우게 한다.

    `law/write.py` 가 생성자에게 관문을 안 알려 주는 것과 같은 규율이다. 무엇이
    통과하는지 알려 주면 통과하는 스키마가 나오고, 그러면 스키마가 사양서가 된다.
    """
    return f"""다음 물음을 **요건표**로 옮겨라. 답을 내지 말고 표만 세운다.

## 물음
{물음.strip()}

## 무엇을 적나

  · **이 표는 다투는 물음에만 쓴다.** 물음이 "얼마인가 · 몇인가 · 하한과 상한이
    무엇인가" 처럼 **값**을 묻는 것이면 여기 것이 아니다. 여기서 나오는 답은
    `섬`/`안섬` 둘뿐이라 값이 될 수 없다. **표를 세우지 말고 그렇다고 말하고 멈춰라.**
  · **세우는 쪽**과 **다투는 쪽**을 정한다. 물음이 무엇을 주장하는지에서 나온다.
    둘은 **반대로 말하는** 두 쪽이다. 같은 말을 하는 두 목소리(예: '수학자'와
    '일반론')는 두 쪽이 아니다.
  · 요건 하나는 **참·거짓을 물을 수 있는 것 하나**다. "좋다" 는 요건이 아니고
    "3년 이상 경력이 있다" 는 요건이다.
  · **무너뜨릴 수 있게 적어라.** "5로 알려져 있다" · "연구가 진행되어 왔다" ·
    "~에 의해 정해진다" 는 늘 참이라 아무도 못 무너뜨린다. 그런 요건만 모으면
    결론은 반드시 `섬` 이 되는데 그것은 도출이 아니라 되풀이다. **값을 아는 것은
    값을 적어라** -- "최대 랭크가 5다" 처럼.
  · 역할은 둘 중 하나다:
      세움      -- **다 서야** 주장이 선다
      무너뜨림  -- **하나만 서도** 주장이 무너진다
  · 어떤 요건이 다른 요건을 되받아치면 `무너뜨림` 에 그 요건의 id 를 적는다.
    받아치기는 여러 겹이어도 된다(주장 <- 반박 <- 재반박 <- 재재반박).
  · **`출처` 를 요건마다 적어라.** 어디서 온 배경지식인가 -- 조문·표준·논문·계약서·
    통념 중 무엇인지. 모르면 비워 두되, **비면 지어낸 것으로 다뤄진다.**
  · `입장` 에 **양쪽이 각각 무엇이라 말하는지** 적는다. 한쪽만 적으면 다툼이 아니라
    설명이 된다. 물음에 안 적힌 쪽은 그 쪽이 **세울 만한 것**을 세워라.
    **양쪽이 반대로 말한 요건이 하나는 있어야 한다.** 전부 `O / O` 면 다투는 쪽이
    없는 것이고, 그러면 이 표는 아무것도 안 가른다.
  · 상대가 꺼내야만 보는 것(먼저 말하지 않으면 안 보는 것)은 `원용필요` 를 true 로.

## 출력 (JSON 하나만. 다른 말은 붙이지 마라)

{{
 "물음": "{물음.strip()[:40]}",
 "세우는쪽": "...", "다투는쪽": "...",
 "요건": [
  {{"id": "짧은id", "말": "참거짓을 물을 수 있는 문장", "역할": "세움",
    "무너뜨림": "", "출처": "어디서 온 것인가", "원용필요": false}}
 ],
 "입장": {{"짧은id": {{"세우는쪽이름": true, "다투는쪽이름": false}}}}
}}"""


def 보고(s: SC.스키마, vs, 짧게: bool = False) -> str:
    st = DR.정거장(s)
    쟁 = DR.도출(s)
    곁 = DR.곁가지(s)
    빈출처 = s.출처없음

    머리 = [f"# {s.물음[:70] or '(물음 없음)'}"]
    if 빈출처:
        머리.append(f"**출처 없는 요건 {len(빈출처)}개** "
                    f"({', '.join(e.id for e in 빈출처[:5])}) -- "
                    "지어낸 것으로 다뤄라")
    if SC.hard(vs):
        # **여기서 도출을 안 돌리는 것이 요점이다.** 돌리면 값 없는 `섬` 이 나오고,
        # 그것은 빈 것이 아니라 **판정받은 옷을 입은 빈 것**이다(실측 2026-09-09).
        머리.append("**스키마에 hard 위반 -- 도출을 안 돌렸다**")
        머리 += [f"  {v}" for v in SC.hard(vs)]
        규칙들 = {v.규칙 for v in SC.hard(vs)}
        if 규칙들 & {"S006", "S007", "S008"}:
            머리.append("")
            머리.append("이 셋은 **표가 성한지**가 아니라 **표가 무엇이라도 말하는지**를 본다.")
            머리.append("그냥 돌리면 결론이 반드시 `섬` 으로 나오는데, 그 `섬` 은 "
                        "전제의 되풀이지 도출이 아니다.")
            if "S008" in 규칙들:
                머리.append("  · 값을 묻는 물음이면 여기가 아니다: "
                            "`python3 brain/route.py --프롬프트 '<물음>'`")
            if "S007" in 규칙들:
                머리.append("  · 다투는 쪽이 없으면 **다툼 물음이 아니라고 말하고 멈춰라.** "
                            "억지로 두 쪽을 지어내지 마라")
            if "S006" in 규칙들:
                머리.append("  · 헤지를 값으로 바꿔라: '5로 알려져 있다' -> '최대 랭크가 5다'")
        return "\n".join(머리)

    # ── 스키마 먼저. **전제를 숨기고 결론만 보이지 않는다** ──────────
    스 = ["", "## 스키마 -- 이 표가 참일 때만 아래 결론이 참이다", ""]
    if not 짧게:
        for e in s.요건:
            표 = "세움" if e.역할 == SC.세움 else "무너뜨림"
            꼬리 = f" <- {e.무너뜨림} 를 무너뜨림" if e.무너뜨림 else ""
            출 = e.출처 or "**출처 없음**"
            pos = s.입장.get(e.id, {})
            말 = " / ".join(f"{k} {'O' if v else 'X'}" for k, v in pos.items()) or "(입장 없음)"
            스.append(f"  [{표}] {e.id}: {e.말}{꼬리}")
            스.append(f"         {말}   · 출처: {출}")
    else:
        스.append(f"  요건 {len(s.요건)}개 "
                  f"(세움 {sum(1 for e in s.요건 if e.역할 == SC.세움)} · "
                  f"무너뜨림 {sum(1 for e in s.요건 if e.역할 == SC.무너뜨림)})"
                  + (f" · **출처 없음 {len(빈출처)}**" if 빈출처 else ""))
    스.append("")

    결 = ["## 두 정거장", "",
          f"  {st['세우는쪽']} 말만으로      **{st['세운쪽결론']}**  ({st['세운쪽왜']})",
          f"  {st['다투는쪽']} 말까지 넣으면 **{st['다툰뒤결론']}**  ({st['다툰뒤왜']})",
          ""]
    결.append("  **갈린다** -- 그 사이에 다툴 거리가 있다." if st["갈림"]
              else "  안 갈린다 -- 상대 주장이 결론을 못 바꾸거나, 애초에 못 세웠다.")
    결.append("")

    쟁절 = ["## 쟁점 -- **뽑은 것이 아니라 계산한 것**", ""]
    if 쟁:
        for i, x in enumerate(쟁, 1):
            쟁절.append(f"  {i}. {x}")
        쟁절.append("")
        쟁절.append("  이것만 답이 갈리면 결론이 갈린다. 나머지는 갈려도 결론이 그대로다.")
    else:
        쟁절.append("  없다. 다투는 것이 없거나, 다투어도 결론을 못 바꾼다.")
    쟁절.append("")
    if 곁:
        쟁절.append(f"  곁가지(다투지만 결론을 못 바꿈): "
                    f"{', '.join(e.id for e in 곁)}")
        쟁절.append("")

    관 = ["## 스키마 검사", ""]
    관.append("  S001~S008: 위반 없음" if not vs
              else "\n".join(f"  {v}" for v in vs))
    관.append("")
    관.append("## 이 도출이 안 보는 것")
    관.append("")
    관.append("  · **스키마가 참인가** -- 요건과 출처가 옳은지는 여기서 판정되지 않는다")
    관.append("  · 어느 쪽이 실제로 이기는가 -- 입장이 참인지는 밖에서 정해진다")
    관.append("  · 무엇이 중요한가 -- 결론에 닿아 있는지만 본다")

    글 = "\n".join(머리 + 스 + 결 + 쟁절 + 관)
    if 짧게 and len(글) > 짧은한도:
        글 = 글[:짧은한도 - 60].rstrip() + "\n  (…길이 때문에 잘렸다. --짧게 를 떼고 전문을 보라)"
    return 글


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description="스키마에서 결론을 끌어낸다 (호출 0회)")
    ap.add_argument("--프롬프트", dest="ask", default="", help="모델에게 줄 것")
    ap.add_argument("--표", dest="path", default="", help="스키마 JSON (`-` 면 표준입력)")
    ap.add_argument("--짧게", dest="short", action="store_true",
                    help="한 메시지에 들어가게 줄인다")
    a = ap.parse_args(argv)

    if a.ask:
        print(프롬프트(a.ask))
        return 0
    if not a.path:
        print("무엇을 할지 안 정해졌다.")
        print("  python3 reason/ask.py --프롬프트 '<물음>'   # 모델에게 줄 것")
        print("  python3 reason/ask.py --표 스키마.json      # 검사하고 도출한다")
        return 3

    try:
        raw = (sys.stdin.read() if a.path == "-"
               else Path(a.path).read_text(encoding="utf-8"))
    except OSError as e:                                          # noqa: BLE001
        print(f"**스키마를 못 열었다**: {e}")
        return 3
    s = SC.읽기(raw)
    if not s.요건:
        print("**스키마를 못 읽었다.** JSON 이 아니거나 `요건` 이 비었다.")
        print("  python3 reason/ask.py --프롬프트 '<물음>' 로 무엇을 받아야 하는지 본다.")
        return 3
    vs = SC.검사(s)
    print(보고(s, vs, a.short))
    return 1 if SC.hard(vs) else 0


if __name__ == "__main__":
    raise SystemExit(main())
