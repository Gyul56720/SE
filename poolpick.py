# -*- coding: utf-8 -*-
"""poolpick -- 후보(키+모델) 순회의 **순서와 멈춤**만 정한다.

왜 따로 있나. 이 판단은 `bot_tools.run_with_fallback_pool` 안에 있었는데, 그 모듈은
langchain 과 discord 를 임포트한다 -- 에이전트 컨테이너에서는 임포트 자체가 안 된다.
그래서 **순회의 규칙을 검사할 길이 없었다.** 규칙이 틀린 것을 사용자가 로그로 알려 주는
것 말고는 알 방법이 없었다는 뜻이다. 여기는 표준 라이브러리만 쓴다.

고치려는 병 (실측 2026-09-21, 사용자 로그):

    [admin-agent] candidate=key-…:gemini-3-flash-preview 일시 장애(503 UNAVAILABLE…),
                  다음 후보로 전환
    … 같은 줄이 끝없이 …

  1. **503 은 아무 데도 안 남았다.** 쿼터는 소진/쿨다운으로, 404·403 은 영구 사망으로
     남는데 일시 장애만 기록이 없었다. 잔량 가득 + 등급 높음 이라 그 조합이 **다음
     요청에서도 또 1순위**가 된다. 과부하가 이어지는 동안 매 메시지가 같은 벽부터
     다시 두드린다 -- 사용자의 물음이 정확히 이것이었다: "변환을 한거를 계속 안쓰고
     왜 처음부터 다시 찾지?"
  2. **쉬는 중인 후보도 그냥 시도했다.** 쿨다운은 정렬을 뒤로 미룰 뿐 건너뛰지 않았다.
     이미 "지금 안 된다" 고 아는 조합에 실제 호출을 넣고 langchain 내부 backoff 로
     수십 초를 문다. 후보가 열이면 한 메시지가 몇 분을 태운다.
  3. **멈추는 자리가 없었다.** 전부 막히면 전부 한 바퀴 돌고, 그동안 맨 앞 것의 쿨다운이
     풀려 다음 메시지가 또 한 바퀴를 돈다. 끝이 없다("도저히 멈추지 않아").

여기서 정하는 것:

    고르기()  -> 지금 **실제로 걸 만한** 후보만, 순서대로. 쉬는 중인 것은 뺀다.
                 다 쉬는 중이면 가장 먼저 풀리는 것과 남은 초를 알려준다.
    기다릴까() -> 그 남은 초를 기다리는 게 나은가(짧으면 기다리는 편이 한 바퀴 도는
                 것보다 싸다), 아니면 포기하고 사용자에게 말할 것인가.

이 파일은 쿼터 장부를 **인자로 받는다**(quota= ). 검사에서 가짜 장부를 물릴 수 있게.
"""
from __future__ import annotations

# 다 쉬는 중일 때 이만큼까지는 기다린다. 한 후보를 실제로 두드려 backoff 를 무는 값이
# 30~50 초였으므로(실측), 그보다 짧게 기다려 풀리는 것을 기다리는 편이 싸다.
기다림상한 = 75.0
# 한 요청이 후보 순회에 쓸 수 있는 벽시계 시간. 넘으면 순회를 멈추고 사실대로 답한다.
# **끝이 있어야 한다** -- 없어서 사용자가 본 것이 "도저히 멈추지 않아" 다.
마감초 = 240.0


def 고르기(labels, pool_id, quota, 등급, 뺄것=()) -> dict:
    """지금 걸 만한 후보를 순서대로.

    labels : 후보 이름들 ("key-abcd1234:gemini-3.5-flash" 꼴)
    quota  : quota_tracker (is_dead / cooling_seconds / remaining / get_pinned)
    등급   : label -> 정렬용 등급 (작을수록 먼저)
    뺄것   : 이번 요청에서 이미 시도한 것 (같은 것을 두 번 두드리지 않는다)

    돌려주는 것:
        순서   실제로 걸 후보 (쉬는 중인 것과 뺄것은 빠져 있다)
        쉼     [(label, 남은초)] 남은초가 짧은 순
        살아있음  영구 사망이 아닌 후보 수
    """
    뺄것 = set(뺄것 or ())
    살아있는 = [l for l in labels if not quota.is_dead(l)]
    if not 살아있는:
        # 다 죽었다고 **기록**돼 있을 뿐이다. 기록이 틀렸을 수 있으니 최후로는 써 본다.
        살아있는 = list(labels)

    쉬는초 = {l: float(quota.cooling_seconds(l)) for l in 살아있는}
    쉼 = sorted(((l, s) for l, s in 쉬는초.items() if s > 0), key=lambda x: x[1])

    def _key(l):
        남 = quota.remaining(l)
        return (남 <= 0, 등급(l), -남)

    순서 = sorted((l for l in 살아있는 if 쉬는초[l] <= 0 and l not in 뺄것), key=_key)

    # 직전에 실제로 답을 준 조합을 맨 앞에 꽂는다. 매번 등급으로 1등을 다시 뽑으면,
    # 등급이 높은데 지금 막힌 조합을 요청마다 처음부터 다시 두드리게 된다.
    핀 = quota.get_pinned(pool_id)
    if 핀 and 핀 in 순서:
        순서 = [핀] + [l for l in 순서 if l != 핀]

    return {"순서": 순서, "쉼": 쉼, "살아있음": len(살아있는)}


def 기다릴까(쉼, 쓴초, 상한=기다림상한, 마감=마감초) -> "tuple[str, float] | None":
    """다 쉬는 중이다. 가장 먼저 풀리는 것을 기다릴 것인가.

    (label, 기다릴초) 또는 None. None 이면 기다리지 말고 사실대로 답한다 --
    **기다리는 척하며 계속 두드리는 것이 제일 나쁘다.**

    실측 2026-09-21, 두 번째: 사용자가 이 답을 받았다.

        모델 후보 40개가 모두 한도/과부하로 쉬는 중입니다.
        가장 먼저 풀리는 것은 gemini-omni-1.1-flash 이고 **약 1초 남았습니다**

    1초를 안 기다리고 사람에게 기다리라고 한 것이다. 까닭은 부르는 쪽이 '한 번만
    기다린다' 는 깃발을 들고 있어서였다 -- 그 한 번을 이미 썼으면 남은 것이 1초여도
    포기했다. 세는 단위가 **횟수**였던 것이 잘못이다. 기다림의 값은 횟수가 아니라
    **벽시계**로 재야 한다. 그래서 부르는 쪽은 이제 쓴 시간만 넘기고, 마감 안쪽이면
    몇 번이든 기다린다. 한없이 도는 일은 없다 -- 기다릴 때마다 쓴초가 늘고, 다시
    실패한 후보는 쉬는 시간이 두 배로 늘기 때문이다(quota_tracker.record_transient).
    """
    if not 쉼:
        return None
    label, 남은 = 쉼[0]
    if 남은 > 상한:
        return None
    if 쓴초 + 남은 >= 마감:
        return None
    # 너무 짧은 잠은 깨어나 보면 아직 안 풀려 있다(시계 알갱이·왕복 지연). 바닥을 둔다.
    return (label, max(1.0, 남은))


def 막힌말(쉼, 살아있음) -> str:
    """전부 막혔을 때 사용자에게 보일 한 줄. 숫자를 지어내지 않는다."""
    if not 쉼:
        return (f"쓸 수 있는 모델 후보 {살아있음}개가 모두 실패했습니다. "
                f"잠시 뒤 다시 물어봐 주세요.")
    label, 남은 = 쉼[0]
    모델 = label.split(":", 1)[-1]
    return (f"모델 후보 {살아있음}개가 모두 한도/과부하로 쉬는 중입니다. "
            f"가장 먼저 풀리는 것은 {모델} 이고 약 {int(남은)}초 남았습니다 -- "
            f"그 뒤에 다시 물어봐 주세요.")


def 막힌답인가(text) -> bool:
    """이 글이 막힌말() 이 낸 '풀 고갈' 안내인가.

    그렇다면 **도구 0회로 벌주거나 되묻지 않는다** -- 모델이 하나도 못 돌았는데 도구를
    안 썼다고 나무라는 것은 틀렸다(실측 2026-09-25 사용자 로그: 다 쉬는 중이라 안내만
    나갔는데 그 뒤에 "[검사] 도구 호출 0회" 가 붙었다). 막힌말() 과 같은 파일에 두어
    문구가 갈라지지 않게 한다."""
    t = text or ""
    return ("다시 물어봐 주세요" in t
            and ("쉬는 중입니다" in t or "모두 실패했습니다" in t))
