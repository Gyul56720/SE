// golden.cpp -- 골든모델(정답) + 자극 생성 + 자기확인.
//
// 이 파일 하나가 세 가지를 한다:
//   1) 알고리즘의 정답을 계산한다            <- 검증의 기준
//   2) 정답 벡터 파일을 낸다 (`./golden vec 개수 씨앗`)
//   3) 스스로를 확인한다     (`./golden self`)
//
// 짓는 법:
//     g++ -O2 -I. -o golden golden.cpp
//
// ── 규칙 셋 ───────────────────────────────────────────────────────────
// 1. **RTL 을 보고 쓰지 않는다.**  스펙만 보고 쓴다.  RTL 에서 뽑은 정답은
//    자기 자신과 비교하는 것이라 아무것도 검증하지 않는다.
// 2. **고정폭 정수만 쓴다** (int32_t 등).  float 이나 파이썬식 큰 정수를
//    쓰면 모델은 넘치지 않고 RTL 만 넘쳐서, 회귀가 "가끔 1 틀림" 으로 나온다.
// 3. **시프트는 시프트로 적는다.**  `/128` 은 0 쪽으로 자르고 `>>7` 은
//    아래로 자른다.  음수에서 둘이 다르다.  RTL 은 시프트를 하므로 모델도.
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <stdint.h>

// ═══ 1. 여기에 스펙의 폭과 상수를 적는다 ═══════════════════════════════
enum {
    IN_W  = 8,        // TODO 입력 비트폭
    OUT_W = 8,        // TODO 출력 비트폭
};

// n비트 부호있는 범위로 포화.  wrap 이 아니라 포화인 이유는 스펙 3절 참고.
static inline int32_t sat(int32_t v, int n) {
    const int32_t hi = (int32_t)((1u << (n - 1)) - 1);
    const int32_t lo = -hi - 1;
    return v > hi ? hi : (v < lo ? lo : v);
}

// 산술 우시프트.  음수 우시프트의 구현정의 동작에 기대지 않는다.
static inline int32_t asr(int32_t v, int n) {
    return (v < 0) ? ~((~v) >> n) : (v >> n);
}

// ═══ 2. 알고리즘 -- 여기가 본체다 ═════════════════════════════════════
// 지금 들어 있는 것은 **돌아가는 최소 예제**다: y = 포화(2x).
// `block.v` 의 기본값과 짝이 맞으므로, 복사하자마자 04~06 단계가 통과한다.
// 여기를 스펙 1절의 수식으로 갈아 끼운다.
//
// 주의: 중간값을 int32_t 로 받는다.  `int8_t y = x + x` 로 적으면
// C 가 int 로 승격했다가 다시 잘라서, **모델과 RTL 이 큰 입력에서 갈라진다.**
static inline int32_t 골든(int32_t x) {
    int32_t y = x + x;        // TODO  (넓은 폭에서 계산하고)
    return sat(y, OUT_W);     //       (마지막에 한 번 포화)
}

// ═══ 3. 자극 -- 경계를 **먼저** 넣는다 ════════════════════════════════
// 무작위만 뽑으면 경계를 거의 안 밟는다.  포화 논리를 통째로 지워도
// 회귀가 초록이 되는 이유가 그것이다.
static const int32_t 경계[] = {
    0,
    (1 << (IN_W - 1)) - 1,        // 최대
    -(1 << (IN_W - 1)),           // 최소
    1, -1,
};
static const int 경계수 = (int)(sizeof(경계) / sizeof(경계[0]));

// xorshift32.  rand() 를 안 쓰는 이유: libc 마다 수열이 달라
// **다른 기계에서 같은 벡터가 안 나온다.**  회귀는 재현돼야 한다.
static uint32_t 씨 = 1u;
static inline uint32_t 다음() {
    씨 ^= 씨 << 13; 씨 ^= 씨 >> 17; 씨 ^= 씨 << 5;
    return 씨;
}

// ═══ 4. 벡터 내기 ═════════════════════════════════════════════════════
static int 벡터내기(int n, unsigned seed) {
    씨 = seed ? seed : 1u;
    for (int i = 0; i < n; i++) {
        int32_t x = (i < 경계수) ? 경계[i]
                                 : (int32_t)(int8_t)(다음() & 0xFFu);  // TODO 폭에 맞게
        printf("%d %d\n", x, 골든(x));      // TODO 열 개수는 스펙에 맞게
    }
    return 0;
}

// ═══ 5. 자기확인 -- **이 모델이 쓸모 있는지** 먼저 본다 ═══════════════
// 관문 둘:
//   (a) 출력이 여러 가지인가 -- 한 가지뿐이면 이 모델로 한 검증은 무의미
//   (b) 경계에서 포화가 실제로 일어나는가 -- 안 일어나면 포화 논리가
//       한 번도 안 돌아, 그것을 지워도 회귀가 통과한다
static int 자기확인() {
    int 다름 = 0, 포화 = 0;
    int32_t 첫값 = 골든(0);
    for (int i = 0; i < 20000; i++) {
        int32_t x = (i < 경계수) ? 경계[i] : (int32_t)(int8_t)(다음() & 0xFFu);
        int32_t y = 골든(x);
        if (y != 첫값) 다름 = 1;
        if (y == (1 << (OUT_W - 1)) - 1 || y == -(1 << (OUT_W - 1))) 포화 = 1;
    }
    printf("출력이 여러 가지인가: %s\n", 다름 ? "예" : "**아니오 -- 이 모델로는 검증이 안 된다**");
    printf("포화가 일어나는가:   %s\n", 포화 ? "예" : "아니오 (스펙상 포화가 없으면 정상)");
    return 다름 ? 0 : 1;
}

int main(int argc, char **argv) {
    if (argc > 1 && strcmp(argv[1], "self") == 0) return 자기확인();
    if (argc > 1 && strcmp(argv[1], "vec") == 0)
        return 벡터내기(argc > 2 ? atoi(argv[2]) : 400,
                        argc > 3 ? (unsigned)atoi(argv[3]) : 1u);
    fprintf(stderr,
        "사용법:\n"
        "  %s self              모델이 쓸모 있는지 확인\n"
        "  %s vec <개수> <씨앗>  정답 벡터를 낸다\n", argv[0], argv[0]);
    return 2;
}
