def kv바이트(층=80, 헤드=8, 헤드차원=128, 길이=100_000, 바이트=2):
    """KV 캐시 한 벌의 바이트. K 와 V 두 벌이라 2 를 곱한다.

    헤드 수는 **KV 헤드**다 -- GQA 에서는 질의 헤드보다 훨씬 적다. 그 차이가
    이 수를 한 자릿수 줄이는 자리다.
    """
    return 2 * 층 * 헤드 * 헤드차원 * 길이 * 바이트


def 산술강도(배치, 층=80, 헤드=8, 헤드차원=128, 길이=8192, 바이트=2, 가중치=70e9):
    """decode 한 걸음의 (연산 / 옮긴 바이트).

    가중치는 배치 전체가 한 번만 읽고 나눠 쓴다. KV 는 **줄마다 따로** 읽는다.
    그래서 배치를 키우면 가중치 쪽은 나눠지고 KV 쪽은 안 나눠진다.
    """
    연산 = 2 * 가중치 * 배치                      # 곱셈+덧셈
    바이트수 = 가중치 * 바이트 + 배치 * kv바이트(층, 헤드, 헤드차원, 길이, 바이트)
    return 연산 / 바이트수


def 기대토큰(알파, 감마):
    """추측 디코딩 한 바퀴가 내는 기대 토큰 수. 닫힌 꼴을 **안 쓰고** 항을 더한다."""
    return sum(알파 ** i for i in range(감마 + 1))


def 닫힌꼴(알파, 감마):
    if 알파 >= 1:
        return 감마 + 1.0
    return (1 - 알파 ** (감마 + 1)) / (1 - 알파)


def 추측표본(p, q, 씨=20260921, 횟수=400_000):
    """추측 표집을 **실제로 돌려** 분포가 p 가 되는지 센다 (정리의 독립 대조).

    p, q 는 같은 길이의 확률 벡터. 돌려주는 것은 경험분포와 수용률.
    """
    r = random.Random(씨)
    n = len(p)
    누적q = []
    s = 0.0
    for x in q:
        s += x
        누적q.append(s)
    # 되살림 분포 (p-q)_+ / beta
    잔 = [max(0.0, a - b) for a, b in zip(p, q)]
    베타 = sum(잔)
    누적잔 = []
    s = 0.0
    for x in 잔:
        s += x
        누적잔.append(s)

    셈 = [0] * n
    수용 = 0
    for _ in range(횟수):
        u = r.random()
        x = next(i for i in range(n) if u <= 누적q[i])
        if r.random() < min(1.0, (p[x] / q[x]) if q[x] > 0 else 1.0):
            셈[x] += 1
            수용 += 1
        else:
            u2 = r.random() * 베타
            y = next(i for i in range(n) if u2 <= 누적잔[i])
            셈[y] += 1
    return [c / 횟수 for c in 셈], 수용 / 횟수


def 총변동(p, q):
    return 0.5 * sum(abs(a - b) for a, b in zip(p, q))


