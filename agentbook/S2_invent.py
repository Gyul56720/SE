def 하이럼확률(동작수, 사용자수, 사용자가건드리는수=30):
    """명세에 없는 동작 하나 이상이 누군가에게 의존될 확률.

    사용자 한 명이 동작 k 개를 건드린다고 보면, 특정 동작이 아무에게도 안 걸릴
    확률은 (1 - k/N)^M. 하나라도 걸릴 확률은 그 여사건을 동작 수만큼.
    """
    p안걸림 = (1 - 사용자가건드리는수 / 동작수) ** 사용자수
    # 적어도 하나의 동작이 걸릴 확률 (독립 근사)
    return 1 - p안걸림 ** 동작수


