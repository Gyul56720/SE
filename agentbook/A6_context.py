def 압축후토큰(원본, 비율):
    return 원본 * 비율


def 정보보존(비율, 손실계수=0.35):
    """압축비 r 에서 남는 '쓸 수 있는 정보' 의 비율 (경험 모형).

    **이것은 가정이고 그렇게 적는다.** 실제 값은 과제마다 재야 한다 --
    이 책의 규율은 가정한 수를 가정이라고 적는 것이지, 가정을 안 하는 것이 아니다.
    """
    import math
    return 1.0 - 손실계수 * (1.0 - 비율) ** 0.5 * math.log1p(1 / max(비율, 1e-6)) / 3.0


def 캐시적중이득(접두사, 전체, 캐시할인=0.9):
    """접두사가 캐시되면 그 몫의 비용이 (1-할인) 로 준다."""
    return (전체 - 접두사 * 캐시할인) / 전체


def 누적(걸음, 시작, 걸음당):
    return 시작 + 걸음 * 걸음당


def 압축시점(창, 시작, 걸음당, 여유=0.25):
    """창의 (1-여유) 를 채우는 걸음 수."""
    목표 = 창 * (1 - 여유)
    n = 0
    while 누적(n, 시작, 걸음당) < 목표:
        n += 1
        if n > 100000:
            break
    return n


