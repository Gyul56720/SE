def 암달(직렬비, 일꾼):
    return 1.0 / (직렬비 + (1 - 직렬비) / 일꾼)


def 팬아웃지연(n, 일꾼, 한작업_s):
    """n 개를 일꾼 W 대로 돌릴 때 벽시계 (완전 병렬, 균등 작업)."""
    import math
    return math.ceil(n / max(일꾼, 1)) * 한작업_s


def 꼬리지연(n, p95배수=3.0, 한작업_s=10.0):
    """**가장 느린 하나가 전체를 정한다.** n 개 중 최대의 기대값 근사."""
    import math
    return 한작업_s * (1 + math.log(max(n, 1)) * (p95배수 - 1) / 3.0)


