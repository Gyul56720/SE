def 유효처리율(작업_s, 체크포인트_s, C, M):
    """체크포인트 비용과 재작업을 다 넣은 실효 진행률.

    Young/Daly 문제의 단순형. C 가 작으면 체크포인트 비용이, 크면 재작업이 먹는다.
    """
    한주기 = C + 체크포인트_s
    손실 = (C / 2.0) * (한주기 / max(M, 1e-9))
    return max(0.0, C / (한주기 + 손실))


def 최적간격(체크포인트_s, M):
    """√(2·C_ckpt·M) -- Young 의 근사."""
    import math
    return math.sqrt(2.0 * 체크포인트_s * M)


