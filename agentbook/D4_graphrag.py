def 요약비용(N, 부채꼴=8, 조각토큰=600, 요약토큰=200):
    """계층 요약의 깊이와 총 토큰. 잎 N 개를 부채꼴 f 로 묶어 올린다."""
    깊이 = math.ceil(math.log(max(N, 2), 부채꼴))
    총입력, 노드 = 0, N
    층 = []
    입력토큰 = 조각토큰
    while 노드 > 1:
        묶음 = math.ceil(노드 / 부채꼴)
        층.append((노드, 묶음))
        총입력 += 묶음 * 부채꼴 * 입력토큰
        노드 = 묶음
        입력토큰 = 요약토큰
    return 깊이, 총입력, 층


def 다중홉확률(k, N, 관련=2):
    """질의와 직접 안 닮은 문서가 우연히 top-k 에 들 확률 (무작위 가정)."""
    if k >= N:
        return 1.0
    p = 1.0
    for i in range(관련):
        p *= (k - i) / (N - i)
    return p


