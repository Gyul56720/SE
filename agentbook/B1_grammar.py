def 반례():
    """지역 마스킹 != 조건화 를 보이는 가장 작은 예.

    어휘 {a, b, $}. 모형 p 는 자유롭게 두고, 언어는 L = {a$, ba$} 로 둔다.
    (a 로 시작하면 바로 끝나고, b 로 시작하면 a 를 하나 더 써야 끝난다.)

    돌려주는 것: (조건부확률, 지역마스킹확률) 두 딕셔너리.
    """
    # p(첫 글자), p(둘째 글자 | 첫 글자)
    p1 = {"a": 0.5, "b": 0.3, "$": 0.2}
    p2 = {"a": {"$": 0.6, "a": 0.4}, "b": {"a": 0.7, "$": 0.3}}
    p3 = {"ba": {"$": 1.0}}

    # 참 결합확률
    p = {"a$": p1["a"] * p2["a"]["$"],
         "ba$": p1["b"] * p2["b"]["a"] * p3["ba"]["$"]}
    pL = sum(p.values())
    조건부 = {k: v / pL for k, v in p.items()}

    # 지역 마스킹: 각 자리에서 '살아남는 이어짓기가 있는' 토큰만 남기고 재정규화
    # 자리 0 에서 허용 = {a, b}  ($ 로 시작하는 말은 L 에 없다)
    Z0 = p1["a"] + p1["b"]
    # 'a' 뒤 허용 = {$}   / 'b' 뒤 허용 = {a}
    Za = p2["a"]["$"]
    Zb = p2["b"]["a"]
    지역 = {"a$": (p1["a"] / Z0) * (p2["a"]["$"] / Za),
          "ba$": (p1["b"] / Z0) * (p2["b"]["a"] / Zb) * 1.0}
    return 조건부, 지역


def 색인비용(어휘=128_000, 상태=350, 평균토큰길이=3.8):
    """정규언어 색인의 선계산 비용과, 그 대가로 사라지는 디코딩 때 비용.

    선계산은 (상태 x 어휘) 를 한 번 훑는다. 디코딩 때는 상태 하나당 비트마스크
    한 줄을 그대로 읽으므로 어휘 크기에 **비례하지 않는다** -- 비트 연산 한 번이다.
    """
    선계산 = 상태 * 어휘
    비트마스크바이트 = 어휘 // 8
    전체마스크바이트 = 상태 * 비트마스크바이트
    return 선계산, 비트마스크바이트, 전체마스크바이트


