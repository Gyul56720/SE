def 소프트맥스(로짓, T):
    if T <= 0:
        m = max(로짓)
        return [1.0 if x == m else 0.0 for x in 로짓]
    e = [math.exp((x - max(로짓)) / T) for x in 로짓]
    s = sum(e)
    return [x / s for x in e]


def 엔트로피(p):
    return -sum(x * math.log2(x) for x in p if x > 0)


def top_p잘라내기(p, top_p):
    """확률 질량 top_p 까지만 남긴다. 남은 후보 수를 돌려준다."""
    줄 = sorted(p, reverse=True)
    s, n = 0.0, 0
    for x in 줄:
        s += x
        n += 1
        if s >= top_p:
            break
    return n


def 다수결정확도(p, k):
    """한 번에 p 로 맞는 것을 k 번 뽑아 다수결하면 (k 홀수, 독립 가정)."""
    from math import comb
    need = k // 2 + 1
    return sum(comb(k, i) * p ** i * (1 - p) ** (k - i) for i in range(need, k + 1))


def 적어도한번(p, k):
    return 1 - (1 - p) ** k


