# ---------------------------------------------------------------------------
# 재는 것 1 -- 자율성이 오르면 무엇이 얼마나 곱해지나
#
# 한 걸음의 성공률이 p 이고 걸음이 n 개면, **사람이 한 번도 안 보는** 연속 성공
# 확률은 p^n 이다. 이것이 에이전트 공학의 첫 수이고, 프레임워크가 존재하는 까닭이다.
# ---------------------------------------------------------------------------
def 끝까지(p, n):
    return p ** n


def 필요한걸음성공률(목표, n):
    """전체를 목표 확률로 끝내려면 한 걸음이 얼마나 정확해야 하나."""
    return 목표 ** (1.0 / n)


def 사람개입기대(p, n):
    """걸음마다 실패하면 사람이 한 번 본다고 할 때, 한 과제당 기대 개입 수."""
    return n * (1.0 - p)


