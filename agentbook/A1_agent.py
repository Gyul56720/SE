def 저장소재기():
    """**인용하지 않는다.** 파일을 세어 낸다."""
    잰것 = {"파이썬파일": 0, "파이썬줄": 0, "검사파일": 0, "기관": 0, "원장줄": 0}
    기관들 = []
    for 뿌리, 디렉, 파일 in os.walk(저장소):
        if any(x in 뿌리 for x in (".git", "__pycache__", "node_modules")):
            continue
        for f in 파일:
            if f.endswith(".py"):
                잰것["파이썬파일"] += 1
                if f.startswith("test_"):
                    잰것["검사파일"] += 1
                try:
                    with open(os.path.join(뿌리, f), encoding="utf-8",
                              errors="replace") as fh:
                        잰것["파이썬줄"] += sum(1 for _ in fh)
                except OSError:
                    pass
            if f == "discord_cmd.py":
                기관들.append(os.path.basename(뿌리))
            if f.endswith("ledger.jsonl"):
                try:
                    with open(os.path.join(뿌리, f), encoding="utf-8",
                              errors="replace") as fh:
                        잰것["원장줄"] += sum(1 for _ in fh)
                except OSError:
                    pass
    잰것["기관"] = len(기관들)
    잰것["기관이름"] = sorted(기관들)
    return 잰것


