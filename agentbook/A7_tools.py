def 도구세기():
    """이 저장소의 고정 명령(= 도구)을 빌드할 때 센다."""
    기관, 총줄 = [], 0
    for 뿌리, _d, 파일 in os.walk(저장소):
        if any(x in 뿌리 for x in (".git", "__pycache__")):
            continue
        if "discord_cmd.py" in 파일:
            p = os.path.join(뿌리, "discord_cmd.py")
            try:
                with open(p, encoding="utf-8", errors="replace") as fh:
                    n = sum(1 for _ in fh)
            except OSError:
                n = 0
            기관.append((os.path.basename(뿌리), n))
            총줄 += n
    return sorted(기관), 총줄


def 선택정확도(도구수, 기본정확도=0.97, 혼동계수=0.012):
    """도구가 많아질수록 고르기가 어려워진다 (경험 모형 -- **가정이다**)."""
    import math
    return max(0.0, 기본정확도 - 혼동계수 * math.log2(max(도구수, 1)))


def 유효호출확률(스키마정확도, 인자수):
    return 스키마정확도 ** 인자수


