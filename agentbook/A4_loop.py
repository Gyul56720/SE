def 기대바퀴(p, 항=400):
    """고침 하나가 확률 p 로 새 문제를 하나 낳을 때 기대 총 바퀴 수.

    분기과정이다. 닫힌 꼴 1/(1-p) 를 쓰지 않고 **항을 더해서** 낸다 -- 아래
    대조가 독립이게. p >= 1 이면 발산한다.
    """
    s, 항값 = 0.0, 1.0
    for _ in range(항):
        s += 항값
        항값 *= p
        if 항값 < 1e-15:
            break
    return s


def 닫힌꼴(p):
    return float("inf") if p >= 1 else 1.0 / (1.0 - p)


def 진전확률로_끝날확률(p_진전, 상한):
    """걸음마다 p 로 '진전' 하고 진전 m 번이면 끝난다고 할 때, 상한 안에 끝날 확률.

    음이항 분포의 누적. m=1 로 두면 기하분포.
    """
    from math import comb
    m = 3
    return sum(comb(k - 1, m - 1) * p_진전 ** m * (1 - p_진전) ** (k - m)
               for k in range(m, 상한 + 1))


