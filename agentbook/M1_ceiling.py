def 천장(문맥성공률, n, 검증자정확도=1.0):
    """문맥 하나를 골라 n 번 뽑고 검증자로 고를 때의 성공률.

    검증자가 완벽하면 1-(1-q)^n. 완벽하지 않으면 통과시킨 것 중 진짜의 비율이
    떨어진다 -- 그것까지 넣는다.
    """
    q = 문맥성공률
    맞는게하나라도 = 1 - (1 - q) ** n
    # 검증자가 틀릴 수 있으면: 진짜를 놓치거나(1-a) 가짜를 통과시킨다
    return 맞는게하나라도 * 검증자정확도


def 문맥쓸기(씨=20260921, 문맥수=40):
    """서로 다른 문맥이 같은 문제에 대해 갖는 성공률을 흩뿌려 본다.

    **이 수는 지어낸 것이 아니라 모형이다** -- 실제 모형에서 문맥마다 성공률이
    다르다는 사실을 베타 분포로 흉내 낸 것이고, 이 장의 논지는 '그 최댓값이
    천장' 이라는 구조이지 특정 수가 아니다.
    """
    r = random.Random(씨)
    return sorted(r.betavariate(2.0, 5.0) for _ in range(문맥수))


