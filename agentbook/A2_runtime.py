# --- 재는 것: 지연 모형 -------------------------------------------------------
def 지연(입력토큰, 출력토큰, TTFT_ms=300.0, prefill_tok_s=20000.0, decode_tok_s=60.0):
    """한 호출의 벽시계 지연.

    **prefill 과 decode 는 물리가 다르다.** prefill 은 입력 전체를 한 번에 미는
    행렬 연산이라 병렬이 잘 되고(토큰/초가 크다), decode 는 한 토큰씩 순차라
    메모리 대역이 목을 잡는다. 그래서 **입력을 두 배로 늘리는 값과 출력을 두 배로
    늘리는 값이 수백 배 다르다** -- 이것이 컨텍스트 설계(A6)의 물리적 근거다.
    """
    return TTFT_ms + 입력토큰 / prefill_tok_s * 1000.0 + 출력토큰 / decode_tok_s * 1000.0


def 루프지연(걸음, 입력토큰, 출력토큰, 도구_ms=150.0, **kw):
    """n 걸음짜리 에이전트의 총 지연. 걸음마다 컨텍스트가 누적된다."""
    총 = 0.0
    누적 = 입력토큰
    for _ in range(걸음):
        총 += 지연(누적, 출력토큰, **kw) + 도구_ms
        누적 += 출력토큰 + 400          # 도구 결과가 창에 쌓인다
    return 총, 누적


def 비용(입력토큰, 출력토큰, 입력달러_M=3.0, 출력달러_M=15.0):
    return 입력토큰 / 1e6 * 입력달러_M + 출력토큰 / 1e6 * 출력달러_M


