# 어디서 무엇을 어떤 꼴로 받아 오는지만 적혀 있다.
#
# ## `확인` 이 비어 있으면 **확인된 적 없는 출처**다
#
# 실측 2026-09-09: 아래 Stooq 세 줄을 **한 번도 안 돌려 보고** 등록했다(그 기계에서
