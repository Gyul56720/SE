#     $ curl -o /dev/null -w '%{http_code}' \
#       'https://stooq.com/q/l/?s=%5Ekospi&f=sd2t2ohlcv&h&e=csv'   -> 404
#
# 그래서 칸을 하나 뒀다. **언제 무엇으로 도는 것을 봤는지 적혀 있지 않으면 미확인**이고,
# 화면이 그렇게 말한다. 고치는 길은 `--탐색` 으로 실제로 받아 본 뒤 그 날짜를 적는 것이다.
SOURCES = {}


def 등록(s: Source) -> Source:
    SOURCES[s.이름] = s
    return s


