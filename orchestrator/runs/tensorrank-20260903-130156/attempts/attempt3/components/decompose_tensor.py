    # 총 27개의 1이 존재하며, 나머지는 모두 0임.
    
    # 23항 분해(Laderman, 1976)를 기반으로 23번째 항을 제거하거나
    # 구조를 수정하여 22항 분해를 시도해야 하나, 수학적으로 23이 최소치인 것으로 
